//          ⇒ **ห้ามมีใครเห็นแล้วแก้กลับ** — จอต้องเขียนกำกับให้คนอ่านรู้ว่าตั้งใจ
//          (นี่คือเหตุผลที่ฟังก์ชันนี้คืน `mismatch` ออกมาด้วย ไม่ได้คืนแค่เดือน)

/** ผลการตัดสินเดือนของไฟล์หนึ่งใบ */
export interface FilingChoice {
  /** เดือนที่ใช้จัดแฟ้มจริง (YYYY-MM) · null = ตัดสินไม่ได้เลยทั้งสองทาง */
  month: string | null
  /** ตัดสินจากอะไร — ต้องบอกได้เสมอ ไม่ใช่คืนแต่เลข */
  from: 'รอบบิลในเอกสาร' | 'ชื่อไฟล์' | 'ไม่รู้'
  /** เดือนที่เขียนอยู่หน้าชื่อไฟล์ (ถ้ามี) — เก็บไว้เทียบ */
  nameMonth: string | null
  /** 🔴 ชื่อไฟล์บอกคนละเดือนกับเอกสาร ⇒ **จอต้องเขียนกำกับ ไม่ใช่เงียบ** */
  mismatch: boolean
}

const MM = /^(\d{4}-\d{2})_REAL_(.+)$/

/** แยกคำนำหน้าเดือนกับชื่อจริงออกจากชื่อไฟล์ในถัง · ไม่ใช่รูปนี้ ⇒ คืน null ทั้งคู่ */
export function splitRealName(name: string): { month: string | null; rest: string | null } {
  const m = MM.exec(String(name ?? ''))
  return m ? { month: m[1], rest: m[2] } : { month: null, rest: null }
}

/**
 * ตัดสินว่าไฟล์ใบนี้ควรอยู่แฟ้มเดือนไหน
 * @param filename ชื่อไฟล์ในถัง (รูป `YYYY-MM_REAL_…`)
 * @param periodInDoc รอบบิลที่อ่านได้จาก **เนื้อในเอกสาร** · null = ยังอ่านไม่ได้/ไม่รู้
 *
 * 🔴 **`null` แปลว่า "ยังไม่รู้" ไม่ใช่ "ไม่มีรอบบิล"** ⇒ ถอยไปใช้ชื่อไฟล์ **ชั่วคราว**
 *    ห้ามถือว่าการถอยครั้งนี้เป็นคำตอบสุดท้าย — พออ่านเอกสารได้เมื่อไหร่ต้องจัดใหม่
 *    (กฎสามสถานะของโปรเจกต์: ไม่รู้ ≠ ไม่มี)
 */
export function filingMonthOf(filename: string, periodInDoc: string | null | undefined): FilingChoice {
  const nameMonth = splitRealName(filename).month
  const doc = typeof periodInDoc === 'string' && /^\d{4}-\d{2}$/.test(periodInDoc) ? periodInDoc : null
  if (doc) {
    return { month: doc, from: 'รอบบิลในเอกสาร', nameMonth, mismatch: !!nameMonth && nameMonth !== doc }
  }
  if (nameMonth) return { month: nameMonth, from: 'ชื่อไฟล์', nameMonth, mismatch: false }
  return { month: null, from: 'ไม่รู้', nameMonth: null, mismatch: false }
}

/** ข้อความกำกับบนจอ/ในรายงาน เมื่อชื่อไฟล์กับเดือนที่จัดไม่ตรงกัน · ตรงกัน ⇒ คืน null */
export function filingNote(c: FilingChoice): string | null {
  if (!c.mismatch || !c.month) return null
  return `ชื่อไฟล์ขึ้นต้นด้วย ${c.nameMonth} แต่รอบบิลในเอกสารคือ ${c.month}`
    + ' — จัดตามรอบบิลในเอกสารโดยตั้งใจ (ชื่อไฟล์เดิมไม่ถูกแก้ เพราะเป็นกุญแจที่ใช้กันซ้ำ)'
}
