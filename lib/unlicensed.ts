/** คำที่บอกว่าหมวดนี้เป็นของทะเบียน — ตัดออกจากหน้านี้ */
export const คำบอกทะเบียน = 'มีทะเบียน'

/** คำนำหน้าของหมวดที่นับเป็น "เลื่อย/บาร์" · เว้นวรรคท้ายสำคัญ (กัน `บาร์โค้ด` ติดมา) */
export const คำนำหน้าเลื่อยบาร์ = ['บาร์ ', 'เลื่อยยนต์ '] as const

/** หมวดนี้เป็นเลื่อย/บาร์ **ที่ไม่มีทะเบียน** หรือไม่ */
export function หมวดไม่มีทะเบียน(ชื่อหมวด: string | null | undefined): boolean {
  const c = String(ชื่อหมวด ?? '').trim()
  if (!c) return false
  if (c.includes(คำบอกทะเบียน)) return false
  return คำนำหน้าเลื่อยบาร์.some((p) => c.startsWith(p))
}

/** แยกว่าหมวดนี้อยู่กลุ่ม "เลื่อย" หรือ "บาร์" — ท่านตั้งชื่อเมนูว่า เลื่อย/บาร์ ⇒ มองสองกลุ่ม
 *  ⚠️ ตัดสินจากชื่อ **หมวด** ไม่ใช่ชื่อสินค้า */
export function กลุ่มของหมวด(ชื่อหมวด: string | null | undefined): 'เลื่อย' | 'บาร์' {
  return String(ชื่อหมวด ?? '').trim().startsWith('บาร์ ') ? 'บาร์' : 'เลื่อย'
}
