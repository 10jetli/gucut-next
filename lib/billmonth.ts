/** รูปเดือนบิลที่รับได้: `YYYY-MM` และเดือนต้องอยู่ในช่วง 01–12 จริง */
export const รูปเดือนบิล = /^\d{4}-(0[1-9]|1[0-2])$/

/** ข้อความบอกเกณฑ์ — **มาจากที่เดียวกับตัวตรวจ** เพื่อไม่ให้แก้เกณฑ์แล้วลืมแก้ข้อความ */
export const เกณฑ์เดือนบิล = 'month ต้องเป็นรูปแบบ YYYY-MM และเดือนต้องอยู่ในช่วง 01–12'

/** true = เดือนนี้รับได้ · ค่าที่ไม่ใช่สตริงถือว่าไม่ผ่าน (ไม่โยน error) */
export function เดือนบิลถูกต้อง(q: unknown): boolean {
  return typeof q === 'string' && รูปเดือนบิล.test(q)
}
