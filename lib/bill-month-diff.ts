import { filingMonthOf } from './bill-filing'
import { เดือนบิลถูกต้อง } from './billmonth'

export type กองส่วนต่าง = 'ไม่เปลี่ยน' | 'ย้ายเดือน' | 'หลุดจากทุกเดือน' | 'แกะรอบไม่ได้'

export interface แถวส่วนต่าง {
  file: string
  วันนี้: string | null
  กติกาใหม่: string | null
  เพราะ: string
}

export interface ตัวสะสมส่วนต่าง {
  ย้ายเดือน: แถวส่วนต่าง[]
  หลุดจากทุกเดือน: แถวส่วนต่าง[]
  แกะรอบไม่ได้: string[]
  ไม่เปลี่ยน: number
}

export const ตัวสะสมใหม่ = (): ตัวสะสมส่วนต่าง =>
  ({ ย้ายเดือน: [], หลุดจากทุกเดือน: [], แกะรอบไม่ได้: [], ไม่เปลี่ยน: 0 })

/** จัดไฟล์หนึ่งใบลงกอง — บริสุทธิ์ ทดสอบตรงได้ ไม่ต้องผ่านเส้น API
 *  @param รอบแกะสด รอบบิลที่ **ตัวแกะรุ่นปัจจุบันให้ในรอบนี้** (ไม่ใช่ค่าเก่าในแคช)
 *    · `null`/`undefined`/`''` = ไม่มีหลักฐาน ⇒ กอง ④
 */
export function จัดกองส่วนต่าง(
  filename: string, รอบแกะสด: string | null | undefined,
): { กอง: กองส่วนต่าง; แถว: แถวส่วนต่าง | null } {
  if (!รอบแกะสด) return { กอง: 'แกะรอบไม่ได้', แถว: null }

  const วันนี้ = filingMonthOf(filename, รอบแกะสด).month
  const กติกาใหม่ = filingMonthOf(filename, เดือนบิลถูกต้อง(รอบแกะสด) ? รอบแกะสด : null).month
  if (วันนี้ === กติกาใหม่) return { กอง: 'ไม่เปลี่ยน', แถว: null }

  /* ③ ก่อน ② — ลำดับนี้สำคัญ: `กติกาใหม่ === null` เป็นกรณีเฉพาะของ "เปลี่ยน"
     ถ้าเช็ค ② ก่อน กองที่หนักที่สุดจะถูกกลืนเข้ากองที่เบากว่า */
  if (กติกาใหม่ === null) {
    return {
      กอง: 'หลุดจากทุกเดือน',
      แถว: {
        file: filename, วันนี้, กติกาใหม่: null,
        เพราะ: `รอบบิลที่แกะได้คือ ${รอบแกะสด} (เดือนนอกช่วง 01–12) และชื่อไฟล์ไม่มีเดือนนำหน้า`
          + ' ⇒ กติกาใหม่ไม่เชื่อรอบบิลนี้ แล้วไม่มีอะไรให้ถอยไปใช้'
          + ' ⇒ **ใบนี้จะหายจากทุกจอที่ไล่เดือน ไม่ใช่ย้ายไปเดือนอื่น**',
      },
    }
  }
  return {
    กอง: 'ย้ายเดือน',
    แถว: {
      file: filename, วันนี้, กติกาใหม่,
      เพราะ: `รอบบิลที่แกะได้คือ ${รอบแกะสด} (เดือนนอกช่วง 01–12)`
        + ` ⇒ กติกาใหม่ไม่เชื่อค่านี้ แล้วถอยไปใช้เดือนจากชื่อไฟล์ (${กติกาใหม่})`,
    },
  }
}

/** เก็บผลลงตัวสะสม — คืนกองที่ไฟล์นั้นเข้า เพื่อให้ผู้เรียกใช้ต่อได้ถ้าต้องการ */
export function เก็บส่วนต่าง(
  acc: ตัวสะสมส่วนต่าง, filename: string, รอบแกะสด: string | null | undefined,
): กองส่วนต่าง {
  const { กอง, แถว } = จัดกองส่วนต่าง(filename, รอบแกะสด)
  if (กอง === 'แกะรอบไม่ได้') acc.แกะรอบไม่ได้.push(filename)
  else if (กอง === 'ไม่เปลี่ยน') acc.ไม่เปลี่ยน++
  else if (กอง === 'หลุดจากทุกเดือน') acc.หลุดจากทุกเดือน.push(แถว!)
  else acc.ย้ายเดือน.push(แถว!)
  return กอง
}

export interface ขอบเขตการอ่าน {
  อ่านรอบนี้: number
  ในถัง: number
  ยังไม่ได้อ่าน: number
}

/** ประกอบคำตอบ — **ความครอบคลุมและขอบเขตต้องไปกับตัวเลขทุกครั้ง**
 *  เลขที่ไม่มีขอบเขตกำกับถูกอ่านเป็นยอดรวมเสมอ (กฎเดิมของโปรเจกต์) */
export function สรุปส่วนต่าง(acc: ตัวสะสมส่วนต่าง, ข: ขอบเขตการอ่าน) {
  const ตัดสินได้ = acc.ไม่เปลี่ยน + acc.ย้ายเดือน.length + acc.หลุดจากทุกเดือน.length
  return {
    ย้ายเดือน: acc.ย้ายเดือน.length,
    รายการย้ายเดือน: acc.ย้ายเดือน,
    /* 🔴 กองที่ CEO สั่งแยกออกมาเอง — "หาไม่เจอเลย" ไม่ใช่ความเสียหายขนาดเดียวกับ "ย้ายเดือน" */
    หลุดจากทุกเดือน: acc.หลุดจากทุกเดือน.length,
    รายการหลุดจากทุกเดือน: acc.หลุดจากทุกเดือน,
    ไม่เปลี่ยน: acc.ไม่เปลี่ยน,
    /* 🔴 กองที่รัดเกณฑ์แล้วไม่ขยับเลย ⇒ ไม่โผล่ในตัวนับใด ๆ แต่เดือนบนจอไม่มีหลักฐานรองรับ */
    แกะรอบไม่ได้: acc.แกะรอบไม่ได้.length,
    รายชื่อที่แกะรอบไม่ได้: acc.แกะรอบไม่ได้,
    ครอบคลุม: `ตัดสินได้ ${ตัดสินได้} ใบ · แกะรอบไม่ได้ ${acc.แกะรอบไม่ได้.length} ใบ`
      + ` · จากไฟล์ที่อ่านรอบนี้ ${ข.อ่านรอบนี้} ใบ · ในถังทั้งหมด ${ข.ในถัง} ใบ`
      + (ข.ยังไม่ได้อ่าน > 0
        ? ` · **ยังไม่ได้อ่านอีก ${ข.ยังไม่ได้อ่าน} ใบ ⇒ ยังสรุปทั้งเจ้าไม่ได้**`
        : ' · อ่านครบทั้งเจ้าแล้ว'),
    /* 🔑 ขอบเขตของคำตอบ — เขียนให้ตรงกับของที่วัดจริง ไม่ใช่เขียนให้ดูรอบคอบ */
    ขอบเขตของคำตอบ: 'เทียบด้วย **ผลแกะสดของรอบนี้** ⇒ ตอบได้ว่า "ถ้ารัดเกณฑ์วันนี้ ใบไหนจะขยับ" · '
      + 'ตอบ **ไม่ได้** ว่า "จอเคยโชว์เดือนอะไรก่อนหน้านี้" เพราะแคชรอบบิลถูกเขียนไปแล้วบางส่วน '
      + 'เมื่อ 30 ก.ย. 2569 (gucut2 ยิงจอบิล 12 ครั้งโดยเข้าใจผิดว่าเส้นนั้นอ่านอย่างเดียว) '
      + '⇒ สภาพก่อนหน้านั้น **วัดย้อนหลังไม่ได้อีกแล้ว** และเลขชุดนี้ไม่ได้อ้างว่าตอบคำถามนั้น',
  }
}
