/* ตัวเทียบ "เส้นนี้อยู่ในรายการที่อนุญาตไหม" — ใช้ร่วมกันทั้ง middleware และเทส
 *
 * 🔴 **ที่มา 28 ก.ย. 2569 (ใบ B08)** — ตอนเพิ่มเส้น `/api/returns-summary` (ท่อสรุปใบคืน
 *    ของ **แอดมิน**) พบว่ารายการของพนักงานมี `'/api/returns'` อยู่ และตัวเทียบเดิมคือ
 *    `pathname.startsWith(p)` เปล่า ๆ (ไม่ดูว่ามี `/` คั่นไหม) ⇒ `/api/returns-summary` **จะกลายเป็นเส้นของพนักงาน
 *    ทันทีโดยไม่มีใครสั่ง** (พนักงานจะเห็นยอดคืน/ยอดเงินทั้งร้าน + ชื่อ-เบอร์-ที่อยู่ลูกค้า)
 *    วัดจริงตอนนั้น: เส้นในรีโป 173 เส้น · หลุดเพราะเหตุนี้ **0 เส้น** ก่อนที่ผมจะเพิ่ม
 *    ⇒ ที่ผ่านมารอดเพราะ **ยังไม่มีใครตั้งชื่อให้ชน** ไม่ใช่เพราะด่านกันไว้
 *
 * 🔑 กติกา: ตรงทั้งเส้น **หรือ** เป็นลูกของเส้นนั้น (ต้องมี `/` คั่น)
 *    `/api/returns` ⇒ อนุญาต `/api/returns` และ `/api/returns/received`
 *                     แต่ **ไม่** อนุญาต `/api/returns-summary`
 */
export function allowedBy(list: readonly string[], pathname: string) {
  return list.some((p) => pathname === p || pathname.startsWith(p.endsWith('/') ? p : `${p}/`))
}
