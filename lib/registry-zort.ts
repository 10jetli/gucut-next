// ท่านประธานสั่ง 10 ต.ค. 2569: "น่าจะเอาหน้านี้มาต่อ /core/registry เชื่อม zort"
// ⚠️ **กลับคำสั่งเดิมของท่านเอง 25 ก.ย. 2569** ที่ว่า "ตัด zort ออกได้เลย zort ไม่เก่ง"
//    ⇒ เหตุของคำสั่งเดิมยังจริงอยู่ (ZORT มีซีเรียลที่ว่ายังมีของ ทั้งที่ทะเบียนบอกขายไปแล้ว)
//    ⇒ จึงไม่ได้เอา ZORT มาเป็น "ความจริง" แค่เอามา **โชว์เทียบ** และให้ท่านกดดันเลขทะเบียนลงไป
//
// 🔑 **ZORT ไม่ส่งช่อง "ติดจอง" มาให้เลย** — เราคิดเอง `คงเหลือ − พร้อมขาย`
//    สูตรนี้วัดแล้วตรง 21/21 (บาร์ 9 · เลื่อย 9 · กลุ่มที่เขียนจริงแล้ว 3) เมื่อ 10 ต.ค. 2569
//    ⇒ ทุกที่ที่โชว์เลขนี้ **ต้องเขียนกำกับว่าเราคิด ไม่ใช่ค่าที่ ZORT บอก**

/** สามสถานะของค่าที่อ่านจาก ZORT — **ห้ามยุบเป็นสองสถานะ**
 *  `ยังไม่อ่าน` ≠ `อ่านไม่ได้` ≠ `มีค่า` · และ **ไม่รู้ห้ามกลายเป็น 0** */
export type สภาพZORT =
  | { สถานะ: 'ยังไม่อ่าน' }
  | { สถานะ: 'อ่านไม่ได้'; เหตุ: string }
  | { สถานะ: 'ไม่มีรหัสนี้' }
  | { สถานะ: 'มีค่า'; คงเหลือ: number; พร้อมขาย: number; ชื่อ: string; ราคา: number | null }

/** ติดจองกี่ชิ้น — `null` เมื่อยังไม่รู้ (ห้ามคืน 0) */
export function จองอยู่(s: สภาพZORT): number | null {
  if (s.สถานะ !== 'มีค่า') return null
  return s.คงเหลือ - s.พร้อมขาย
}

/** พร้อมขายที่จะได้หลังเขียนเลขนี้ — `null` เมื่อยังไม่รู้สภาพปัจจุบัน */
export function คาดพร้อมขาย(จะเขียน: number, s: สภาพZORT): number | null {
  const จ = จองอยู่(s)
  return จ === null ? null : จะเขียน - จ
}

/** ด่านฝั่งท่อจะตีกลับไหม — ท่อตีกลับเมื่อ `จะเขียน − จอง < 0` (commit bc68ffaa)
 *  ⚠️ นี่คือ **การทำนายของจอ** ไม่ใช่คำตอบของท่อ ⇒ จอต้องยังยิงโหมดซ้อมเพื่อฟังคำตอบจริง */
export function จะถูกตีกลับ(จะเขียน: number, s: สภาพZORT): boolean | null {
  const ค = คาดพร้อมขาย(จะเขียน, s)
  return ค === null ? null : ค < 0
}

/** ข้อความเตือนของแถว — คืน `null` เมื่อไม่มีอะไรต้องเตือน
 *  🔑 ข้อความทั้งหมดสร้างจากตัวแปรชุดเดียวกับที่ตัดสิน ห้ามพิมพ์เลขซ้ำด้วยมือ */
export function คำเตือนแถว(จะเขียน: number | null, s: สภาพZORT): string | null {
  if (s.สถานะ === 'ยังไม่อ่าน') return 'ยังไม่ได้อ่านสภาพ ZORT ของรหัสนี้'
  if (s.สถานะ === 'อ่านไม่ได้') return `อ่าน ZORT ไม่ได้: ${s.เหตุ}`
  if (s.สถานะ === 'ไม่มีรหัสนี้') return 'ZORT ไม่รู้จักรหัสนี้ ⇒ เขียนไม่ได้'
  const จ = จองอยู่(s) as number
  if (จะเขียน === null) return จ > 0 ? `ติดใบจอง ${จ} ชิ้น` : null
  const ค = จะเขียน - จ
  if (ค < 0) return `เขียน ${จะเขียน} แล้วพร้อมขายจะเป็น ${ค} ⇒ ด่านจะตีกลับ ต้องเคลียร์ใบจอง ${จ} ชิ้นก่อน`
  if (จ > 0) return `เขียน ${จะเขียน} แล้วแพลตฟอร์มจะเห็นแค่ ${ค} เพราะติดใบจอง ${จ} ชิ้น`
  return null
}

/** กลุ่มนี้ต้องให้คนเลือกรหัสปลายทางเองไหม
 *  🔴 ขนาดเดียวมีหลายรหัสใน ZORT แต่ของมีกองเดียว ⇒ **ห้ามเดาแทน**
 *     (ชีทแท็บ 2566 ไม่ระบุรุ่นเครื่อง ⇒ 24″/28″/30″ บอกไม่ได้ว่าเป็น 7800/8800/9800) */
export function ต้องเลือกรหัสเอง(รหัสสินค้า: string[]): boolean {
  return รหัสสินค้า.length > 1
}

/** `ref` สำหรับการกดหนึ่งครั้ง — ต้องไม่ซ้ำ เพื่อให้ฐานกันกดซ้ำได้
 *  ⚠️ รับเวลาเข้ามา ไม่เรียก `Date.now()` ข้างใน เพื่อให้เทสตรึงค่าได้ */
export function refของการกด(sku: string, เวลา: number): string {
  return `จอทะเบียน-${sku.replace(/\s+/g, '_')}-${เวลา}`
}

