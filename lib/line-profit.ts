/* กำไรของ **บรรทัดขายหนึ่งบรรทัด** — จากสองช่องที่ท่อเปิดให้ 5 ต.ค. 2569 (ใบ t_muu0gaih ข้อ 6)
 *   `unit_cost`   : number | null   ← **ต่อหน่วย ไม่ใช่ต่อบรรทัด**
 *   `cost_source` : 'zort' | 'ใบซื้อ' | 'ตั้งไว้' | null
 *
 * 📐 **สูตร — เขียนไว้เพราะอ่านจากชื่อช่องไม่ออก**
 *   รายได้ของบรรทัด = `amount`            ⇐ เป็นยอดรวมของบรรทัดนั้นแล้ว **ไม่ต้องคูณ qty อีก**
 *   ต้นทุนของบรรทัด = `unit_cost × qty`   ⇐ **ตัวนี้ต้องคูณ**
 *   ⇒ กำไรของบรรทัด = `amount − unit_cost × qty`
 *   🔴 ลืมคูณ `qty` ⇒ กำไรเกินจริงทุกบรรทัดที่ qty > 1 **และดูเหมือนเลขปกติ**
 *      (ฝั่งท่อใส่ด่านบังคับให้สูตรนี้เขียนกำกับในซอร์สเสมอ — บรรทัดนี้คือของฝั่งจอ)
 *
 * 🔴 **ข้อห้ามสองข้อของสัญญา**
 *   ① `unit_cost: null` = บรรทัดนี้ขายก่อนวันที่ระบบเริ่มตรึง ⇒ "ยังไม่รู้ต้นทุน"
 *      **ห้ามแปลงเป็น 0** — กำไรจะกลายเป็น 100% ของราคาขาย และดูเหมือนตัวเลขจริงทุกประการ
 *   ② **ห้ามโชว์ `unit_cost` โดยทิ้ง `cost_source`** — เลขสองตัวหน้าตาเหมือนกัน
 *      แต่เชื่อถือได้ไม่เท่ากัน (กติกาเดิมของเส้น `?cost=1`)
 *      ⇒ ที่นี่จึงคืน `ที่มา` ออกมาด้วยเสมอ และถ้าท่อไม่ส่งมาก็คืน `null` **ไม่ใช่เดาให้**
 *
 * ⚠️ **ไม่มีช่องเลย ≠ null** — ไม่มี `unit_cost` ในแถว = ท่อรุ่นเก่า (คนละข้อความกับ
 *    "แถวนี้ยังไม่ตรึงต้นทุน") ⇒ สองอย่างนี้ต้องขึ้นจอคนละข้อความ ไม่งั้นไล่แก้ผิดฝั่ง
 */

export type แถวที่มีต้นทุน = {
  qty?: number | null
  amount?: number | null
  unit_cost?: number | null
  cost_source?: string | null
}

export type ผลกำไรบรรทัด =
  | { ชนิด: 'ท่อยังไม่ส่งช่อง' }
  | { ชนิด: 'ยังไม่รู้ต้นทุน'; ที่มา: string | null }
  | { ชนิด: 'อ่านตัวเลขไม่ได้'; เหตุ: string }
  | {
    ชนิด: 'คิดได้'
    ต้นทุนบรรทัด: number
    กำไร: number
    /** กำไรขั้นต้น % — `null` เมื่อรายได้เป็น 0 (หารไม่ได้) ⇒ **ห้ามแสดงเป็น 0% หรือ 100%** */
    เปอร์เซ็นต์: number | null
    ที่มา: string | null
  }

const เลข = (x: unknown): number | null => (typeof x === 'number' && Number.isFinite(x) ? x : null)

export function กำไรบรรทัด(row: แถวที่มีต้นทุน | null | undefined): ผลกำไรบรรทัด {
  if (!row || !('unit_cost' in row)) return { ชนิด: 'ท่อยังไม่ส่งช่อง' }

  const ที่มา = typeof row.cost_source === 'string' && row.cost_source !== '' ? row.cost_source : null

  // ① `null` คือ "ยังไม่ตรึง" — ต้องมาก่อนการตรวจ qty/amount
  //    เพราะเหตุที่คิดไม่ได้คือ "ไม่มีต้นทุน" ไม่ใช่ "ตัวเลขอื่นเพี้ยน"
  if (เลข(row.unit_cost) === null) return { ชนิด: 'ยังไม่รู้ต้นทุน', ที่มา }

  const qty = เลข(row.qty)
  const amount = เลข(row.amount)
  if (qty === null) return { ชนิด: 'อ่านตัวเลขไม่ได้', เหตุ: 'ท่อไม่ได้ส่งจำนวนของบรรทัดนี้มา' }
  if (amount === null) return { ชนิด: 'อ่านตัวเลขไม่ได้', เหตุ: 'ท่อไม่ได้ส่งยอดของบรรทัดนี้มา' }

  const ต้นทุนบรรทัด = (row.unit_cost as number) * qty   // ⇐ **คูณ qty** (ข้อที่ลืมแล้วเงียบ)
  const กำไร = amount - ต้นทุนบรรทัด
  return {
    ชนิด: 'คิดได้',
    ต้นทุนบรรทัด,
    กำไร,
    // 🔴 รายได้ 0 ⇒ หารไม่ได้ ⇒ `null` · ของแจกฟรีไม่ใช่ "กำไร 0%" และไม่ใช่ "100%"
    เปอร์เซ็นต์: amount === 0 ? null : (กำไร / amount) * 100,
    ที่มา,
  }
}
