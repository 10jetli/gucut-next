/** รหัสที่คลังเงาบอกว่าติดลบ → จำนวนคงเหลือ (null = ท่อไม่ได้ส่งตัวเลขมา) */
export type NegMap = Map<string, number | null>

export interface StuckSku { sku?: string }

/** รหัสฐานที่รับผิดชอบแถวนี้ — หาไม่ได้ให้คืน null ห้ามเดา */
export function ต้นเหตุของรหัส(sku: string | undefined, neg: NegMap): string | null {
  if (!sku) return null
  if (neg.has(sku)) return sku
  const ฐาน = sku.split('-')[0]
  return ฐาน !== sku && neg.has(ฐาน) ? ฐาน : null
}

export interface ผลจับคู่ {
  /** รหัสฐาน → จำนวนแถวที่จะปลดได้ถ้าแก้ตัวนี้ (เรียงมากไปน้อยแล้ว) */
  ต้นเหตุ: Array<[string, number]>
  /** แถวที่จับคู่ต้นเหตุไม่ได้ — **ต้องพูดออกมา** ไม่ใช่ปัดทิ้ง */
  หาไม่เจอ: number
  /** รหัสในกองดันที่ **ไม่โผล่ในรายการติดลบของจอคลัง** — ตัวเลขที่ทำให้สองจอต่างกัน */
  ไม่โผล่ในจอคลัง: string[]
}

export function จับคู่ต้นเหตุ(rows: StuckSku[], neg: NegMap): ผลจับคู่ {
  const นับ = new Map<string, number>()
  const ไม่โผล่ = new Set<string>()
  let หาไม่เจอ = 0
  for (const r of rows) {
    const b = ต้นเหตุของรหัส(r.sku, neg)
    if (!b) { หาไม่เจอ++; if (r.sku) ไม่โผล่.add(r.sku); continue }
    นับ.set(b, (นับ.get(b) ?? 0) + 1)
    /* รหัสแปรที่ไม่มีแถวของตัวเองในจอคลัง — จอคลังจะไม่มีวันแสดงมัน */
    if (r.sku && r.sku !== b) ไม่โผล่.add(r.sku)
  }
  return {
    ต้นเหตุ: Array.from(นับ.entries()).sort((a, b) => b[1] - a[1]),
    หาไม่เจอ,
    ไม่โผล่ในจอคลัง: Array.from(ไม่โผล่).sort(),
  }
}
