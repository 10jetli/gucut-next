// ที่มาของเลขสต็อกในแถว `?list=stock` — **ตรรกะล้วน ไม่มี JSX** (จอเรียกไปเรนเดอร์)
//
// 🔑 ทำไมแยกจากชิ้นส่วนจอ: ตัวตัดสินที่อยู่ใน JSX ทดสอบได้แค่รูปร่าง ไม่ใช่พฤติกรรม
//    และไฟล์ .tsx ที่คอมไพล์แล้วต้องหา react ⇒ เทสต้องรันในโฟลเดอร์โปรเจกต์ (ทิ้งของค้างได้)
//    ⇒ ย้ายตัวตัดสินมาที่นี่ ⇒ เทสคอมไพล์ไฟล์เดียว ไม่พึ่ง react และคอมไพล์ลงที่ชั่วคราวได้
/** สามช่องที่ท่อเติมให้ทุกแถวของ `?list=stock` (ท่อ gucut-web f924185) */
export interface ที่มาเลขสต็อก {
  /** `licensed` = ทะเบียนใบอนุญาตทับ ZORT โดยตั้งใจ · `mirror` = ภาพถ่ายคลังเงาตามปกติ */
  src?: string | null
  /** ข้อความพร้อมใช้จากท่อ — มีเฉพาะแถว `licensed` · **จอไม่แปลเอง** */
  srcNote?: string | null
  /** เลขที่ทะเบียนใบอนุญาตถืออยู่ (เอาไปวางเทียบกับ available ได้) */
  'ทะเบียนว่า'?: number | null
}

/** แผนที่ป้ายของช่อง `src` — ท่อส่งมา **ที่เดียวในคำตอบ** ไม่ใช่ติดไปทุกแถว (ท่อ 28 ก.ย. 2569)
 *  🔑 ฝั่งจอขอเอง เพราะแถว `mirror` ไม่มีคำอธิบาย ⇒ คนแพ็กของเห็นคำว่า mirror แล้วไม่ได้ความหมาย
 *     และเราตกลงกันว่า **จอไม่แปลเอง** (กันคำแปลสองชุด) ⇒ ท่อเป็นคนส่งคำมา */
export interface แผนที่ป้ายที่มา {
  [src: string]: { 'ป้าย'?: string; 'อธิบาย'?: string } | undefined
}

/** แถวที่มีช่องที่มา = แถวจาก list=stock (ไม่จำเป็นต้องมีครบ) */
export function อ่านที่มา(row: ที่มาเลขสต็อก | null | undefined): ที่มาเลขสต็อก {
  return {
    src: row?.src ?? null,
    srcNote: row?.srcNote ?? null,
    'ทะเบียนว่า': typeof row?.['ทะเบียนว่า'] === 'number' ? row['ทะเบียนว่า'] : null,
  }
}

/** ผลตัดสินว่าจะเขียนอะไรบนจอ — **แยกออกมาเพื่อทดสอบได้โดยไม่ต้องเรนเดอร์**
 *  (จอที่ตัดสินใจอยู่ใน JSX จะทดสอบได้แค่รูปร่าง ไม่ใช่พฤติกรรม) */
export type ผลที่มา =
  | { แบบ: 'ท่อไม่ส่ง' }
  | { แบบ: 'มีคำอธิบายจากท่อ'; src: string; note: string; 'ทะเบียนว่า': number | null }
  | { แบบ: 'ค่าดิบไม่มีคำอธิบาย'; src: string }

export function ตัดสินที่มา(
  row: ที่มาเลขสต็อก | null | undefined,
  ป้าย?: แผนที่ป้ายที่มา | null,
): ผลที่มา {
  const { src, srcNote } = อ่านที่มา(row)
  const ทะเบียน = อ่านที่มา(row)['ทะเบียนว่า'] ?? null
  /* ⚠️ สตริงว่างนับเป็น "ไม่ส่ง" — ท่อส่ง '' มาก็ยังไม่มีข้อมูลที่มา */
  if (!src || !String(src).trim()) return { แบบ: 'ท่อไม่ส่ง' }
  /* ① แผนที่ป้ายที่ท่อส่งมาในคำตอบ มาก่อนเสมอ (ครอบทุกค่า ไม่ใช่แค่ licensed) */
  const ใบ = ป้าย?.[String(src)]
  const คำ = [ใบ?.['ป้าย'], ใบ?.['อธิบาย']].filter((x) => x && String(x).trim()).join(' — ')
  if (คำ) {
    return { แบบ: 'มีคำอธิบายจากท่อ', src: String(src), note: คำ, 'ทะเบียนว่า': ทะเบียน }
  }
  /* ② ไม่มีแผนที่ป้าย (ท่อรุ่นก่อน) ⇒ ตกมาที่ srcNote ที่ติดมากับแถว */
  if (srcNote && String(srcNote).trim()) {
    return { แบบ: 'มีคำอธิบายจากท่อ', src: String(src), note: String(srcNote), 'ทะเบียนว่า': ทะเบียน }
  }
  /* ค่าที่ท่อไม่ได้ส่งคำอธิบายมา (รวม mirror และค่าใหม่ที่ยังไม่รู้จัก) ⇒ โชว์ดิบ ห้ามแปลเอง */
  return { แบบ: 'ค่าดิบไม่มีคำอธิบาย', src: String(src) }
}

