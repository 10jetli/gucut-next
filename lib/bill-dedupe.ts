// 🔑 ลำดับความน่าเชื่อถือของ "เลขที่ใบ": เลขที่อ่านจาก **เนื้อในเอกสาร** > เลขที่เดาจาก **ชื่อไฟล์**
//    ไม่มีทั้งสองอย่าง ⇒ **เก็บไว้ทั้งหมด ห้ามเดาว่าซ้ำ** (บิลหายหนึ่งใบ = เอกสารภาษีขาดหนึ่งใบ)

/* หาเลขที่ใบจากชื่อไฟล์ — ใช้ตัดสินว่าสองไฟล์คือ "ใบเดียวกัน" หรือไม่
   🔴 15 ก.ย. 2569 ท่านประธานทัก: เดือน 8 จอโชว์ 8 ใบ แต่ของจริงมี **4 ใบ**
      เพราะบิลใบเดียวกันเข้าระบบสองทาง แล้วได้ชื่อไฟล์คนละแบบ:
        · THTT202606634060-บริษัท ศีตกาล เทรดดิ้ง จำกัด-Invoice.pdf   (ตัวเก็บอัตโนมัติ)
        · TikTok-Invoice-THTT202606634060.pdf                        (ไฟล์แนบในอีเมล)
      ⇒ นับซ้ำทุกใบ · บัญชีเห็นแล้วนึกว่ามีบิลสองเท่าของจริง

   ⚠️ จับคู่ด้วย **เลขที่ใบเท่านั้น** ห้ามเดาจากขนาดไฟล์หรือวันที่
      ไฟล์คนละใบอาจขนาดเท่ากันเป๊ะได้ (ใบจากระบบเดียวกันมักเท่ากัน)
   ⚠️ ไม่มีเลขที่ใบในชื่อ ⇒ **เก็บไว้ทั้งหมด** ห้ามเดาว่าซ้ำ
      บิลหายหนึ่งใบ = เอกสารภาษีขาดหนึ่งใบ แย่กว่าเห็นซ้ำ */
export function เลขที่ใบจากชื่อไฟล์(filename: string): string | null {
  const m = filename.match(/(THTT\d{6,}|FBADS-[\d-]{6,}|IN-\d{6,}|INV[-_]?\d{6,})/i)
  return m ? m[1].toUpperCase() : null
}

/* 🔴 **แก้ 16 ก.ย. 2569 (ใบ t_mu3g8tq5)** — ท่านประธานจับได้ว่าบิล Adobe ซ้ำ 3–4 ไฟล์ต่อเดือน
   เหตุ: ตัวคัดซ้ำอ่านเลขที่ใบจาก **ชื่อไฟล์** ด้วย regex 4 แบบ ⇒ Adobe ไม่เข้ารูปแบบไหนเลย
         ⇒ `เลขที่ใบ()` คืน null ทุกใบ ⇒ ตกไปกอง "ไม่มีเลข ⇒ เก็บไว้ทั้งหมด" ⇒ ซ้ำหมด
   ⇒ ตอนนี้ใช้ **เลขที่อ่านจากเนื้อใน PDF** ก่อน (ช่อง invoiceNo ที่เก็บตอนสแกน)
     แล้วถอยมาใช้ชื่อไฟล์เฉพาะของเก่าในแคชที่ยังไม่มีช่องนั้น */
export function เลขที่ใบ(f: { filename: string; invoiceNo?: string | null }): string | null {
  const จากเอกสาร = String(f.invoiceNo ?? '').trim()
  if (จากเอกสาร) return จากเอกสาร.toUpperCase()
  return เลขที่ใบจากชื่อไฟล์(f.filename)
}

/* คัดซ้ำออก — ใบเดียวกันเก็บไว้ใบเดียว
   ลำดับความน่าเชื่อถือ: ไฟล์ตัวจริงที่อัปไว้ (_REAL_) > ไฟล์แนบอีเมล > ใบที่ระบบสร้างเอง (GEN) */
export function คัดซ้ำ<T extends { filename: string; attachmentId: string; invoiceNo?: string | null }>(files: T[]): T[] {
  return คัดซ้ำพร้อมรายงาน(files).เก็บไว้
}

/** ไฟล์ที่ถูกซ่อนเพราะเป็นใบเดียวกับอีกไฟล์ — **ต้องบอกคนดู ไม่ใช่ซ่อนเงียบ ๆ** */
export interface ไฟล์ซ้ำ {
  /** ชื่อไฟล์ที่ถูกซ่อน */
  ชื่อไฟล์: string
  /** ชื่อไฟล์ที่เก็บไว้แทน (ใบเดียวกัน) */
  ซ้ำกับ: string
  /** เลขที่ใบที่ใช้ตัดสินว่าเป็นใบเดียวกัน */
  เลขที่ใบ: string
}

/* 🔴 **ซ่อนของแล้วต้องบอกว่าซ่อนอะไรไว้** (เพิ่ม 16 ก.ย. 2569 · ใบ t_mu3g8tq5)
   ของเดิมคัดซ้ำแล้ว **เงียบ** ⇒ ท่านประธานต้องเปิด PDF ทีละใบเองถึงจะรู้ว่าไฟล์ไหนซ้ำ
   ⇒ คืนรายการที่ซ่อนไว้ด้วย เพื่อให้จอเขียนได้ว่า "ซ่อนไฟล์ซ้ำไว้ N ไฟล์" แล้วกดดูได้
   ⚠️ ยังคงกติกาเดิมทุกข้อ: จับคู่ด้วยเลขที่ใบเท่านั้น · ไม่มีเลข = เก็บไว้ทั้งหมด */
export function คัดซ้ำพร้อมรายงาน<T extends { filename: string; attachmentId: string; invoiceNo?: string | null }>(
  files: T[],
): { เก็บไว้: T[]; ซ่อนไว้: ไฟล์ซ้ำ[] } {
  const คะแนน = (f: T) => (f.attachmentId?.startsWith('BLOB:') ? 3 : f.attachmentId === 'GEN' ? 1 : 2)
  /* 🔴 **ต้องเลือกผู้ชนะให้เสร็จก่อน แล้วค่อยเขียนรายงาน**
     รอบแรกผมเขียนแบบรายงานทีละคู่ระหว่างเดิน ⇒ ไฟล์ที่ซ่อนตอนต้นชี้ไปหาไฟล์ที่ยัง
     **ไม่ใช่ผู้ชนะสุดท้าย** (เจอด้วยเทสข้อ ⑦: ชี้ไป mail.pdf ทั้งที่สุดท้ายเก็บ real.pdf)
     ⇒ คนอ่านจะเปิดไฟล์ที่เราบอกแล้วไม่เจอ = รายงานที่ผิดแบบดูน่าเชื่อ */
  const กลุ่ม = new Map<string, T[]>()
  const ไม่มีเลข: T[] = []
  for (const f of files) {
    const no = เลขที่ใบ(f)
    if (!no) { ไม่มีเลข.push(f); continue }
    const เดิม = กลุ่ม.get(no)
    if (เดิม) เดิม.push(f)
    else กลุ่ม.set(no, [f])
  }
  const เก็บไว้: T[] = []
  const ซ่อนไว้: ไฟล์ซ้ำ[] = []
  /* ⚠️ วนด้วย Array.from — tsconfig ของโปรเจกต์ target ต่ำกว่า es2015 จึงวน Map ตรง ๆ ไม่ได้ */
  for (const [no, ชุด] of Array.from(กลุ่ม.entries())) {
    /* คะแนนเท่ากัน ⇒ ตัวแรกชนะ (กติกาเดิมก่อนแยกฟังก์ชันนี้ออกมา) */
    let ผู้ชนะ = ชุด[0]
    for (const f of ชุด) if (คะแนน(f) > คะแนน(ผู้ชนะ)) ผู้ชนะ = f
    เก็บไว้.push(ผู้ชนะ)
    for (const f of ชุด) {
      if (f === ผู้ชนะ) continue
      ซ่อนไว้.push({ ชื่อไฟล์: f.filename, ซ้ำกับ: ผู้ชนะ.filename, เลขที่ใบ: no })
    }
  }
  return { เก็บไว้: เก็บไว้.concat(ไม่มีเลข), ซ่อนไว้ }
}

