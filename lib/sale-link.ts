/* ลิงก์ไปหาใบขายหนึ่งใบบนจอรายการขาย — ใช้ร่วมทุกจอที่ลิงก์เลขที่ใบเข้ามา (17 ก.ย. 2569 · ใบ t_mu2u9mym)
 *
 * 🔴 **ทำไมต้องมีตัวช่วยนี้ ไม่ใช่เขียน `/core/sales?q=<เลขที่ใบ>` ตรง ๆ**
 *    จอรายการขายค้นได้แค่ในช่วงวันของจอ (ค่าเริ่มต้น 90 วัน) — ลิงก์ที่ส่งแค่ `q`
 *    จะขึ้น "ไม่พบ" กับใบที่เก่ากว่านั้น ทั้งที่ใบมีอยู่จริง
 *    วัดจริง: สุ่มใบที่มีสลิป 12 ใบ ⇒ ช่วง 90 วันเจอ **1 ใบ** · เปิดช่วงกว้างเจอ **12 ใบ**
 *
 * 🔑 รู้วันที่ของใบ ⇒ ส่งช่วง **วันก่อน–วันหลัง** (กันขอบวันเพี้ยนระหว่างเวลาไทยกับ UTC)
 *    ไม่รู้วันที่ ⇒ ส่งช่วงกว้างตั้งแต่ปีแรกที่ร้านมีข้อมูล (ช้ากว่า แต่ไม่หลอกว่าไม่มี)
 * ⚠️ เลขที่ใบของสองร้าน **ซ้ำกันได้จริง** ⇒ ลิงก์นี้อาจเจอ 2 ใบ ซึ่งถูกต้อง ให้คนเลือกเอง
 */
const วันแรกที่มีข้อมูล = '2020-01-01'

/* 📏 ผลวัดช่วงวันของ list=orders (CTO 16 ต.ค. 2569 ยิงทีละนัดเว้น 8 วิ) — **ผลวัด ไม่ใช่เพดานที่ท่อประกาศ**
   654 วัน ได้ใน 7.7 วิ · 1,750 วัน ล้ม 500 สองนัดติด · ตัวกรอง customer **ไม่ช่วย** (ชื่อที่ไม่มีจริงก็ 500 เท่ากัน)
   ⇒ ต้นทุนอยู่ที่ช่วงวัน · ระหว่างสองเลขนี้ยังไม่มีใครวัด · ใช้ร่วมกับจอรายการขาย (ข้อความตอนท่อล้ม) */
export const ช่วงยาวที่วัดว่ารอด = 654
export const ช่วงยาวที่วัดว่าล้ม = 1750

const เลื่อนวัน = (iso: string, n: number) => {
  const d = new Date(`${iso}T00:00:00Z`)
  d.setUTCDate(d.getUTCDate() + n)
  return d.toISOString().slice(0, 10)
}

/** ลิงก์ไปรายการขายของลูกค้าคนหนึ่ง "ทุกใบ" (17 ก.ย. 2569) — จอลูกค้ารายคนได้จากท่อแค่ 20 ใบล่าสุด
 *  ⚠️ จอรายการขายค้นชื่อแบบ **มีคำนี้อยู่** แต่จอลูกค้าจับชื่อ **ตรงตัว** ⇒ อาจมีชื่ออื่นที่มีคำเดียวกันปน
 *     และจอรายการขายนับใบยกเลิกด้วย ⇒ จำนวนสองจอต่างกันได้ — คนเรียกต้องเขียนบอกคู่กับลิงก์ */
export function ลิงก์ใบของลูกค้า(ชื่อ: string, วันแรก?: string | null, วันล่าสุด?: string | null): string {
  const qs = new URLSearchParams({ customer: ชื่อ })
  const ช่วง = ช่วงลิงก์ใบของลูกค้า(วันแรก, วันล่าสุด)
  qs.set('from', ช่วง.from)
  if (ช่วง.to) qs.set('to', ช่วง.to)
  return `/core/sales?${qs}`
}

/** ช่วงวันของลิงก์ "ดูครบทุกใบ" — ลูกค้าเก่าหลายปีขอช่วงยาวเกินที่ท่อนับไหว ⇒ ได้ 500 (วัดแล้ว 16 ต.ค. 2569)
 *  🔑 ยาวเกิน ⇒ ตัดเหลือ **ช่วงล่าสุดที่วัดว่ารอด** และคืน `ตัด: true` ให้จอ **เขียนบอกเสมอ**
 *     ว่ามีใบเก่ากว่านั้นที่ลิงก์นี้ไม่แสดง (ห้ามตัดเงียบ — คนจะเชื่อว่าเห็นครบทุกใบ) */
export function ช่วงลิงก์ใบของลูกค้า(วันแรก?: string | null, วันล่าสุด?: string | null): { from: string; to: string; ตัด: boolean } {
  const วัน = (x?: string | null) => (typeof x === 'string' && /^\d{4}-\d{2}-\d{2}/.test(x) ? x.slice(0, 10) : '')
  const to = วัน(วันล่าสุด) ? เลื่อนวัน(วัน(วันล่าสุด), 1) : ''
  const fromเต็ม = วัน(วันแรก) ? เลื่อนวัน(วัน(วันแรก), -1) : วันแรกที่มีข้อมูล
  if (!to) return { from: fromเต็ม, to, ตัด: false }
  const fromต่ำสุด = เลื่อนวัน(to, -(ช่วงยาวที่วัดว่ารอด - 1))
  return fromเต็ม < fromต่ำสุด ? { from: fromต่ำสุด, to, ตัด: true } : { from: fromเต็ม, to, ตัด: false }
}

export function ลิงก์ใบขาย(เลขที่ใบ: string, วันที่ใบ?: string | null): string {
  const qs = new URLSearchParams({ q: เลขที่ใบ })
  const วัน = typeof วันที่ใบ === 'string' && /^\d{4}-\d{2}-\d{2}/.test(วันที่ใบ) ? วันที่ใบ.slice(0, 10) : ''
  if (วัน) {
    qs.set('from', เลื่อนวัน(วัน, -1))
    qs.set('to', เลื่อนวัน(วัน, 1))
  } else {
    qs.set('from', วันแรกที่มีข้อมูล)
  }
  return `/core/sales?${qs}`
}
