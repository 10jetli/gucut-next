/* ลิงก์ไปหาใบขายหนึ่งใบบนจอรายการขาย — ใช้ร่วมทุกจอที่ลิงก์เลขที่ใบเข้ามา (17 ก.ย. 2569 · ใบ t_mu2u9mym)
 *
 * 🔴 **ทำไมต้องมีตัวช่วยนี้ ไม่ใช่เขียน `/core/sales?q=<เลขที่ใบ>` ตรง ๆ**
 *    จอรายการขายค้นได้แค่ในช่วงวันของจอ (ค่าเริ่มต้น 90 วัน) — ลิงก์ที่ส่งแค่ `q`
 *    จะขึ้น "ไม่พบ" กับใบที่เก่ากว่านั้น ทั้งที่ใบมีอยู่จริง
 *    วัดจริง: สุ่มใบที่มีสลิป 12 ใบ ⇒ ช่วง 90 วันเจอ **1 ใบ** · เปิดช่วงกว้างเจอ **12 ใบ**
 *
 * 🔑 รู้วันที่ของใบ ⇒ ส่งช่วง **วันก่อน–วันหลัง** (กันขอบวันเพี้ยนระหว่างเวลาไทยกับ UTC)
 *    ไม่รู้วันที่ ⇒ ส่งช่วงกว้างตั้งแต่ปีแรกที่ร้านมีข้อมูล (ช้ากว่า แต่ไม่หลอกว่าไม่มี)
 * ⚠️ เลขที่ใบของสองร้าน **ซ้ำกันได้จริง** ⇒ ลิงก์นี้อาจเจอ 2 ใบ ซึ่งถูกต้อง ให้คนเลือกเอง
 */
const วันแรกที่มีข้อมูล = '2020-01-01'

const เลื่อนวัน = (iso: string, n: number) => {
  const d = new Date(`${iso}T00:00:00Z`)
  d.setUTCDate(d.getUTCDate() + n)
  return d.toISOString().slice(0, 10)
}

export function ลิงก์ใบขาย(เลขที่ใบ: string, วันที่ใบ?: string | null): string {
  const qs = new URLSearchParams({ q: เลขที่ใบ })
  const วัน = typeof วันที่ใบ === 'string' && /^\d{4}-\d{2}-\d{2}/.test(วันที่ใบ) ? วันที่ใบ.slice(0, 10) : ''
  if (วัน) {
    qs.set('from', เลื่อนวัน(วัน, -1))
    qs.set('to', เลื่อนวัน(วัน, 1))
  } else {
    qs.set('from', วันแรกที่มีข้อมูล)
  }
  return `/core/sales?${qs}`
}
