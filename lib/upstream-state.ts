/** ฝั่งที่เป็นต้นเหตุ — ใช้เลือกถ้อยคำบนจอ */
export type ฝั่งที่ติด =
  | 'สำเร็จ'
  | 'ปลายทางล้ม'
  | 'คำขอเราผิด'
  | 'ยังไม่รู้ฝั่ง'

export interface คำตอบของท่อ {
  upstreamOk?: boolean | null
  retryable?: boolean
  /** ท่อรุ่นเก่าส่งช่องนี้แต่ไม่ส่ง `upstreamOk` ⇒ ใช้เป็นทางสำรองเท่านั้น */
  unknown?: boolean
}

export function ฝั่งที่ติดจาก(d: คำตอบของท่อ | null | undefined): ฝั่งที่ติด {
  if (!d) return 'ยังไม่รู้ฝั่ง'
  if (d.upstreamOk === true) return 'สำเร็จ'
  if (d.upstreamOk === false) return 'ปลายทางล้ม'
  if (d.upstreamOk === null) return 'คำขอเราผิด'
  /* ถึงบรรทัดนี้ = `upstreamOk` เป็น undefined (ท่อรุ่นเก่า)
     ⚠️ ท่อรุ่นเก่าที่ยังส่ง `unknown: true` ⇒ รู้แค่ว่า "ไม่รู้" แต่ **ไม่รู้ว่าฝั่งไหน**
        ⇒ ยังตอบ 'ยังไม่รู้ฝั่ง' ไม่ใช่ 'ปลายทางล้ม' — ห้ามเดาแทนท่อ */
  return 'ยังไม่รู้ฝั่ง'
}

/** ควรเชียร์ให้ลองใหม่ไหม — `null` = ท่อไม่ได้บอก ⇒ **ห้ามแนะนำอะไร** */
export function ควรลองใหม่(d: คำตอบของท่อ | null | undefined): boolean | null {
  if (!d || typeof d.retryable !== 'boolean') return null
  return d.retryable
}
