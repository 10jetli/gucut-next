/** กว้างของ viewBox — ผังทั้งหน้าใช้ค่านี้ */
export const กว้างผัง = 860
/** สูงของผังตอนกล่องผู้เชื่อมมีแถวเดียว */
export const สูงฐาน = 560
/** กล่องต่อแถว · ขนาดกล่อง · ระยะห่าง — เปลี่ยนที่นี่ที่เดียว */
export const ต่อแถว = 4
const กว้างกล่อง = 195
const สูงกล่อง = 46
const ช่องไฟ = 205
const ขอบซ้าย = 30
const บนแถวแรก = 398
/** ระยะห่างระหว่างแถว (ใช้ดันของที่อยู่ใต้กล่องลงมาด้วย) */
export const สูงต่อแถว = 58

export type กล่องผู้เชื่อม = { x: number; y: number; w: number; h: number; แถว: number }

/** วางกล่องผู้เชื่อม n ตัว — คืนพิกัดทุกกล่อง + ขนาดผังที่ต้องใช้ */
export function วางกล่องผู้เชื่อม(จำนวน: number): {
  กล่อง: กล่องผู้เชื่อม[]
  แถวเกิน: number
  สูงผัง: number
} {
  const n = Math.max(0, Math.floor(จำนวน))
  const กล่อง: กล่องผู้เชื่อม[] = []
  for (let i = 0; i < n; i++) {
    const แถว = Math.floor(i / ต่อแถว)
    กล่อง.push({
      x: ขอบซ้าย + (i % ต่อแถว) * ช่องไฟ,
      y: บนแถวแรก + แถว * สูงต่อแถว,
      w: กว้างกล่อง,
      h: สูงกล่อง,
      แถว,
    })
  }
  /* 🔑 แถวเกิน = จำนวนแถวที่มากกว่าแถวแรก — ของที่อยู่ใต้กล่อง (ตู้เซฟสำรอง) เลื่อนลงเท่านี้
     n = 0 ต้องได้ 0 ไม่ใช่ -1 (ceil(0/4)-1 = -1 ⇒ ดันของขึ้นไปทับผังข้างบน) */
  const แถวเกิน = Math.max(0, Math.ceil(n / ต่อแถว) - 1)
  return { กล่อง, แถวเกิน, สูงผัง: สูงฐาน + แถวเกิน * สูงต่อแถว }
}
