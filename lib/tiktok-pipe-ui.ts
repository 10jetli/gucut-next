/** ⏱️ "ตัวดันเงียบไปกี่นาที" — คิดจาก **นาฬิกาเดียวกันทั้งคู่** (ทั้งสองค่ามาจากเซิร์ฟเวอร์)
 *  🔑 เอานาฬิกาเบราว์เซอร์ไปลบเวลาของเซิร์ฟเวอร์ = เครื่องที่ตั้งเวลาเพี้ยนเห็นคำเตือนลวง
 *  อ่านค่าไหนไม่ออก ⇒ null (= ไม่รู้) **ห้ามคืน 0 ซึ่งแปลว่า "เพิ่งรายงาน"** */
export function เงียบไปนาที(ดันเมื่อ: string | null, เวลาเซิร์ฟเวอร์: string | null): number | null {
  if (!ดันเมื่อ || !เวลาเซิร์ฟเวอร์) return null
  const a = Date.parse(ดันเมื่อ), b = Date.parse(เวลาเซิร์ฟเวอร์)
  return Number.isNaN(a) || Number.isNaN(b) ? null : Math.max(0, Math.round((b - a) / 60000))
}

/** ลิงก์ของเพจมาเป็นเส้นทางสัมพัทธ์ (`/reel/<id>/`) ⇒ ต่อโดเมนให้ตอนแสดงเท่านั้น
 *  ⚠️ ค่าที่ไม่ขึ้นต้นด้วย `/` หรือ `https://` = ไม่รู้ว่าคืออะไร ⇒ คืนค่าว่าง ไม่ทำเป็นลิงก์
 *     (เดาโดเมนให้ค่าแปลก ๆ = ส่งคนไปหน้าที่ไม่มีอยู่ · ว่างดีกว่าเดา) */
export function ลิงก์เพจ(v: string): string {
  if (typeof v !== 'string') return ''
  return v.startsWith('https://') ? v : v.startsWith('/') ? `https://www.facebook.com${v}` : ''
}

/** แปลคำตอบของท่อเป็นกล่องเดียวที่จอเอาไปวาด
 *  🔑 **ตัดสินจาก `สถานะข้อมูล` ที่ท่อบอกมา ไม่ใช่จาก "รายการว่างไหม"**
 *     ท่อตั้งใจไม่แนบรายการว่างตอนอ่านไม่ได้ ⇒ จอจึงไม่มีทางเข้าใจผิดว่า "ยังไม่เคยส่ง"
 *  🔴 รูปข้อมูลไม่ตรงสัญญา (200 แต่ไม่มี `สถานะข้อมูล`) ⇒ **'อ่านไม่ได้'**
 *     ห้ามตกไปทางใดทางหนึ่งเงียบ ๆ — ของที่ตอบ 200 ด้วยรูปที่เราไม่รู้จัก คือของที่เราอ่านไม่ได้ */
export function ตีความคำตอบ(ok: boolean, status: number, d: unknown): กล่อง {
  const ก = (d && typeof d === 'object' ? d : null) as Record<string, unknown> | null
  if (!ok || !ก) {
    const เหตุ = String(ก?.error ?? '')
    return { แบบ: 'อ่านไม่ได้', เหตุ: เหตุ ? `HTTP ${status} · ${เหตุ}` : `HTTP ${status} (ท่อไม่ได้บอกเหตุมา)` }
  }
  const ข้อความหรือว่าง = (v: unknown) => (typeof v === 'string' ? v : null)
  if (ก['สถานะข้อมูล'] === 'ยังไม่เคยมีใครดัน') {
    return {
      แบบ: 'ยังไม่เคยดัน',
      เหตุ: String(ก['เหตุ'] ?? 'g1 ยังไม่เคยดันผลขึ้นมาเลย'),
      ขอรอบค้าง: ข้อความหรือว่าง(ก['ขอรอบค้าง']),
    }
  }
  if (ก['สถานะข้อมูล'] !== 'มีข้อมูล' || !Array.isArray(ก['รายการ'])) {
    return {
      แบบ: 'อ่านไม่ได้',
      เหตุ: `ท่อตอบ ${status} แต่รูปข้อมูลไม่ใช่ที่สัญญาไว้ (สถานะข้อมูล=${String(ก['สถานะข้อมูล'])})`,
    }
  }
  return {
    แบบ: 'มีข้อมูล',
    รายการ: ก['รายการ'] as ใบคลิป[],
    เมื่อ: ข้อความหรือว่าง(ก['เมื่อ']),
    ดันเมื่อ: ข้อความหรือว่าง(ก['ดันเมื่อ']),
    เวลาเซิร์ฟเวอร์: ข้อความหรือว่าง(ก['เวลาเซิร์ฟเวอร์']),
    บัญชี: ข้อความหรือว่าง(ก['บัญชี']),
    โหมด: ข้อความหรือว่าง(ก['โหมด']),
    รอบล่าสุด: ข้อความหรือว่าง(ก['รอบล่าสุด']),
    ขอรอบค้าง: ข้อความหรือว่าง(ก['ขอรอบค้าง']),
  }
}
