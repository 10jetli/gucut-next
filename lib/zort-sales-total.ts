export interface แถวใบคืน { status?: string | null; amount?: number | string | null; date?: string | null }

export interface ผลยอดแบบZORT {
  ยอด: number | null
  ขายชำระแล้ว: number | null
  คืนในช่วง: { ใบ: number; บาท: number } | null
  เหตุไม่รู้: string | null
}

const เป็นเลข = (v: unknown): number | null => {
  const n = typeof v === 'number' ? v : typeof v === 'string' && v.trim() !== '' ? Number(v) : NaN
  return Number.isFinite(n) ? n : null
}

/** คิดยอดจากของที่ดึงมาแล้ว — **ไม่รู้ ≠ 0**: ขาดชิ้นไหนคืน null พร้อมเหตุ */
export function ยอดขายแบบZORT(o: {
  ขายชำระแล้ว: unknown
  ใบคืน: แถวใบคืน[] | null
  ตั้งแต่: string
  ถึง: string
}): ผลยอดแบบZORT {
  const ขาย = เป็นเลข(o.ขายชำระแล้ว)
  if (ขาย === null) return { ยอด: null, ขายชำระแล้ว: null, คืนในช่วง: null, เหตุไม่รู้: 'ยังไม่รู้ยอดใบที่ชำระแล้ว' }
  if (!Array.isArray(o.ใบคืน)) return { ยอด: null, ขายชำระแล้ว: ขาย, คืนในช่วง: null, เหตุไม่รู้: 'ดึงใบคืนไม่สำเร็จ' }
  let ใบ = 0, บาท = 0
  for (const r of o.ใบคืน) {
    const d = String(r?.date ?? '').slice(0, 10)
    if (r?.status !== 'Success' || d < o.ตั้งแต่ || d > o.ถึง) continue
    const a = เป็นเลข(r.amount)
    if (a === null) return { ยอด: null, ขายชำระแล้ว: ขาย, คืนในช่วง: null, เหตุไม่รู้: 'มีใบคืนที่ไม่รู้ยอด' }
    ใบ++; บาท += a
  }
  บาท = Math.round(บาท * 100) / 100
  return { ยอด: Math.round((ขาย - บาท) * 100) / 100, ขายชำระแล้ว: ขาย, คืนในช่วง: { ใบ, บาท }, เหตุไม่รู้: null }
}
