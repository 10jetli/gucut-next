/* อ่าน "เหตุผลที่เขียนไม่สำเร็จ" จากคำตอบของท่อ — ใช้ร่วมทุกจอที่ยิงคำสั่งเขียน
 *
 * 🔴 **ที่มา (14 ก.ย. 2569 · ใบ t_mu17qs80)**
 *    ฝั่งท่อเคย "ตอบ ok เสมอ" แม้ตอนอ่านข้อมูลเดิมไม่ได้ ⇒ เขียนความว่างเปล่าทับของจริง
 *    แก้แล้ว (gucut-web 5bce111 · 6428c2d): อ่านไม่ได้ ⇒ **503 + ข้อความไทยที่บอกว่า
 *    "ยังไม่ได้บันทึกอะไร ลองใหม่อีกครั้ง"**
 *    ⇒ แต่จอฝั่งเราหลายจอ **ทิ้งข้อความนั้นแล้วขึ้นคำกลาง ๆ ของตัวเอง** ("ลบไม่สำเร็จ ลองใหม่")
 *
 * ⚠️ **ข้อความกลาง ๆ กลบข้อมูลที่สำคัญที่สุด: "ยังไม่ได้บันทึกอะไร"**
 *    คนอ่าน "ลบไม่สำเร็จ" ไม่รู้ว่าลบไปครึ่งทางหรือเปล่า · กดซ้ำจะซ้ำไหม · ของหายหรือยัง
 *    ส่วนข้อความจากท่อตอบครบทั้งสามคำถามในประโยคเดียว
 *    ⇒ **จอต้องเอาข้อความของท่อขึ้นตรง ๆ** แล้วค่อยเติมบริบทของจอต่อท้าย
 *
 * ⚠️ ห้ามแปลหรือย่อข้อความจากท่อ — ถ้อยคำของท่อคือส่วนที่รู้ว่าเกิดอะไรขึ้นจริง
 *    จอรู้แค่ว่า "คำสั่งไม่ผ่าน" เท่านั้น
 */

/** คำตอบผิดพลาดที่ท่อส่งมา — ทุกเส้นใช้ช่อง `error` เป็นข้อความไทย */
interface ErrorBody { error?: unknown; message?: unknown }

/**
 * คืนเหตุผลที่เขียนไม่สำเร็จเป็นข้อความไทย · คืน `''` ถ้าสำเร็จ
 *
 * @param r คำตอบจาก fetch — ส่ง `null` มาได้ถ้า fetch เองล้ม (ต่อเน็ตไม่ได้)
 */
export async function readWriteError(r: Response | null): Promise<string> {
  /* ต่อไม่ถึงเซิร์ฟเวอร์เลย — **บอกได้เลยว่ายังไม่ได้บันทึกอะไร** เพราะคำขอไม่เคยไปถึง */
  if (!r) return 'ติดต่อเซิร์ฟเวอร์ไม่ได้ — ยังไม่ได้บันทึกอะไร ลองใหม่อีกครั้ง'

  const body = (await r.json().catch(() => null)) as ErrorBody | null
  const said = typeof body?.error === 'string' ? body.error
    : typeof body?.message === 'string' ? body.message : ''

  /* 🔴 **สำเร็จต้องดูทั้ง HTTP และเนื้อใน** — ท่อตอบ 200 พร้อม `{error}` ได้
     (เจอมาแล้วหลายเส้น) ⇒ เช็คอย่างเดียวไม่พอ */
  if (r.ok && !said) return ''
  if (r.ok && said) return said

  /* ท่อพูดเองว่าเกิดอะไร ⇒ ใช้คำของท่อ ไม่แต่งใหม่ */
  if (said) return said

  /* ท่อไม่ได้บอกอะไร ⇒ อย่างน้อยต้องแยกให้ออกว่า "ยังไม่ได้เขียน" หรือ "ไม่รู้"
     503 = ปลายทางบอกเองว่ารับงานไม่ไหวตอนนี้ ⇒ ยังไม่ได้บันทึกแน่นอน
     ส่วนรหัสอื่น ๆ **ห้ามรับประกันว่าไม่ได้บันทึก** เพราะอาจเขียนไปแล้วแต่ตอบกลับไม่ถึงเรา */
  if (r.status === 503) return 'เซิร์ฟเวอร์ยังรับงานนี้ไม่ไหว — ยังไม่ได้บันทึกอะไร ลองใหม่อีกครั้ง'
  return `คำสั่งไม่ผ่าน (HTTP ${r.status}) — ยังไม่ยืนยันว่าบันทึกไปหรือยัง ให้รีเฟรชดูก่อนกดซ้ำ`
}
