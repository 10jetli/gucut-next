const TH_MONTH_SHORT = ['ม.ค.', 'ก.พ.', 'มี.ค.', 'เม.ย.', 'พ.ค.', 'มิ.ย.',
  'ก.ค.', 'ส.ค.', 'ก.ย.', 'ต.ค.', 'พ.ย.', 'ธ.ค.']

export function thaiDate(raw?: string | null): string {
  const s = String(raw ?? '').trim()
  if (!s) return '—'
  /* 🔴 **ค่าที่มีเวลาและโซนติดมาด้วย ต้องแปลงเป็นเวลาไทยก่อน ห้ามตัดเอาแต่ 10 ตัวแรก**
     เจอของจริง 14 ก.ย. 2569 ที่จอใบสั่งผลิต: กำหนดส่งเก็บไว้เป็น `2026-03-19T17:00:00.000Z`
     ซึ่ง **คือเที่ยงคืนวันที่ 20 มี.ค. เวลาไทย** (17:00Z + 7 ชม.)
     ⇒ ตัด 10 ตัวแรกจะได้ "19 มี.ค." — **เลื่อนไปหนึ่งวันโดยไม่มีอะไรฟ้อง**
        และกำหนดส่งที่ผิดไปวันหนึ่งคือเรื่องที่คนเอาไปนัดกับโรงงานจริง
     ⚠️ แต่ค่าที่เป็น "วันที่เปล่า ๆ" (yyyy-MM-dd) **ห้ามเอาไปคิดโซนเวลา**
        เพราะมันไม่ใช่จุดเวลา มันคือวันที่อยู่แล้ว — คิดโซนจะเลื่อนวันในทางกลับกัน
     ⇒ แยกสองกรณีนี้ให้ขาด: มีเวลา+โซน ⇒ แปลง · ไม่มี ⇒ อ่านตรง ๆ */
  const withZone = /^\d{4}-\d{2}-\d{2}T[\d:.]+(Z|[+-]\d{2}:?\d{2})$/.test(s)
  if (withZone) {
    const t = new Date(s)
    if (!Number.isNaN(t.getTime())) {
      const bkk = new Date(t.getTime() + 7 * 3600000)
      return `${bkk.getUTCDate()} ${TH_MONTH_SHORT[bkk.getUTCMonth()]} ${bkk.getUTCFullYear() + 543}`
    }
  }
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(s)
  if (!m) return s
  const year = Number(m[1]), mon = Number(m[2]), day = Number(m[3])
  if (!year || mon < 1 || mon > 12 || !day) return s
  return `${day} ${TH_MONTH_SHORT[mon - 1]} ${year + 543}`
}
