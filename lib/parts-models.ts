/** ⚠️ ของสำรองตอนถามไม่ได้ — **ไม่ใช่ความจริง** · ความจริงอยู่ที่หน้าร้าน */
export const รุ่นสำรอง = ['f250', 'f381', 'f440', 'f660', 'f070', 'f090']

export type แหล่งรุ่น = { รุ่น: string[]; ที่มา: string; ถามได้: boolean }

/** ล้างชื่อรุ่น — ต้องตรงกับ `ล้างรุ่น` ของฝั่งท่อ (`parts-map.mjs`) เป๊ะ */
export const ล้างรุ่น = (v: string | null) =>
  String(v || '').toLowerCase().replace(/[^a-z0-9]/g, '').slice(0, 12)

export async function รุ่นจากหน้าร้าน(
  ฐาน: string,
  ยิง: typeof fetch = fetch,
): Promise<แหล่งรุ่น> {
  try {
    const r = await ยิง(`${ฐาน}/parts/models.json`, { cache: 'no-store' })
    if (!r.ok) throw new Error(`HTTP ${r.status}`)
    const j = (await r.json()) as { รุ่น?: { slug?: string }[] }
    const รุ่น = (j?.รุ่น ?? []).map((m) => ล้างรุ่น(String(m?.slug ?? ''))).filter(Boolean)
    if (!รุ่น.length) throw new Error('อ่านได้แต่ไม่มีรุ่นเลย')
    return { รุ่น, ที่มา: 'หน้าร้าน /parts/models.json', ถามได้: true }
  } catch (e) {
    const เหตุ = String((e as Error)?.message ?? e).slice(0, 60)
    return {
      รุ่น: รุ่นสำรอง,
      ที่มา: `⚠️ ของสำรองในโค้ด (ถามหน้าร้านไม่ได้: ${เหตุ}) — รุ่นที่เพิ่งเพิ่มจะไม่ถูกจับคู่รอบนี้`,
      ถามได้: false,
    }
  }
}

/* ── จับคู่ "รหัสอะไหล่ในคู่มือ" → "รหัสสินค้าในร้าน" ───────────────────────────
 * 🔴 **บั๊กจริงที่เจอ 13 ต.ค. 2569 ตอนยิงรอบซ้อมของจริง** (ไม่ได้อ่านโค้ดเจอ)
 *    รอบซ้อมตอบทุกเล่มว่า `จับคู่ใหม่ = มีอยู่เดิม` และ `ข้ามเพราะมีแล้ว = 0`
 *    (f440: ใหม่ 105 · เดิม 105 · ข้าม 0) ⇒ ตัวเลขชุดนี้เป็นไปไม่ได้ถ้าตัวกันทับทำงาน
 *    เหตุ: ฝั่งร้านเก็บคีย์แบบ **ไม่มีช่องว่าง** (`ล้างรหัส` ใน parts-map.mjs)
 *          แต่ที่นี่เทียบด้วยรหัสจากคู่มือซึ่งมีช่องว่าง (`1123 020 1209`)
 *    ⇒ `เดิม[รหัส]` **ไม่เคยเจอสักตัว** ⇒ ของที่ท่านประธานกรอกเองถูกนับเป็น "ยังว่าง" ทุกใบ
 *    ⇒ ตอนเขียนกลับ `{...เดิม, ...เพิ่ม}` คีย์จะถูกล้างให้เหมือนกันที่ฝั่งร้าน
 *      ⇒ **ค่าที่จับคู่อัตโนมัติทับของที่ท่านกรอกเอง** ทั้งที่หัวไฟล์เขียนว่า "ไม่ทับแม้แต่คู่เดียว"
 * 🔑 คำกล่าวอ้างที่ดังที่สุดในไฟล์ คือคำกล่าวอ้างที่ไม่มีใครไปวัด — ตัวเลขรอบซ้อมเป็นคนบอก
 * ⚠️ ต้องล้างให้ตรงกับฝั่งร้านเป๊ะ (`replace(/\s+/g,"").toUpperCase().slice(0,24)`)
 *    ไม่ตรง = กลับไปเป็นบั๊กเดิมในรูปใหม่ · นี่คือ "สัญญาร่วมข้ามรีโป" ที่ parts-map.mjs ประกาศไว้ */
export const ล้างรหัส = (v: unknown) =>
  String(v ?? '').replace(/\s+/g, '').toUpperCase().slice(0, 24)

/** ถอดทุกอย่างที่ไม่ใช่ตัวเลข — ใช้เทียบกับเลข OEM ในคลัง (คลังเขียนขีด/เว้นวรรคไม่เหมือนกัน) */
export const เลขล้วน = (v: unknown) => String(v ?? '').replace(/\D/g, '')

export type ผลจับคู่ = {
  เพิ่ม: Record<string, string>
  ข้าม: number
  /** เลข OEM เดียวชี้หลาย SKU ⇒ **ไม่เขียน** · รายชื่อไว้ให้ท่านประธานเลือกเอง */
  กำกวม: { รหัส: string; sku: string[] }[]
}

export function จับคู่ที่ยังว่าง(
  แถว: { รหัส?: unknown }[],
  เดิม: Record<string, string>,
  ovrMap: Map<string, string[]>,
): ผลจับคู่ {
  const เพิ่ม: Record<string, string> = {}
  const กำกวม: { รหัส: string; sku: string[] }[] = []
  const เห็นแล้ว = new Set<string>()
  let ข้าม = 0
  for (const r of แถว) {
    const คีย์ = ล้างรหัส(r?.รหัส)
    if (!คีย์) continue
    if (เดิม[คีย์]) { ข้าม++; continue }   // ของคนกรอก — ห้ามแตะ
    const skus = ovrMap.get(เลขล้วน(คีย์))
    if (!skus?.length) continue
    /* 🔴 เลข OEM เดียวชี้ได้หลาย SKU (วัดจริง 13 ต.ค. 2569 ฝั่งท่อ: 28 คู่ใน 174 = 16%
       เช่น 0000 350 0525 → 00587/05749/05795 · 1106 647 9404 → 00155/00185/00563)
       ของเดิมหยิบ `sort()[0]` = **เดาเงียบ ๆ** ⇒ ลูกค้าได้ปุ่ม + ที่ใส่ของผิดชิ้น ไม่มีอะไรแดง
       🔑 คลาสเดียวกับจุดกดบนภาพของ f660: **สัญญาสิ่งที่เราไม่มี**
       ⇒ ไม่เขียน · ปล่อยเป็น "สอบถามร้าน" ซึ่งเป็นความจริง
         แล้วส่งรายชื่อให้ท่านประธานเลือก — "เลขนี้คือสินค้าตัวไหน" เป็นงานของคน ไม่ใช่ของ sort() */
    if (skus.length > 1) {
      if (!เห็นแล้ว.has(คีย์)) { เห็นแล้ว.add(คีย์); กำกวม.push({ รหัส: คีย์, sku: [...skus].sort() }) }
      continue
    }
    เพิ่ม[คีย์] = skus[0]
  }
  return { เพิ่ม, ข้าม, กำกวม }
}
