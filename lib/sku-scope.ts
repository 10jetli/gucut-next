//    เหตุผล: เก็บของที่ไม่มีรหัสต้องเปลี่ยนกุญแจกระจกจาก "รหัสสินค้า" เป็น "id ของ ZORT"
//    ซึ่งกระทบทุกจอที่อ้างสินค้าด้วยรหัส แลกกับของที่ร้านเองยังไม่ได้ตั้งรหัสให้ ⇒ ไม่คุ้ม
//
// **ของจริงที่ทำให้ต้องมีป้ายนี้** (18 ก.ย. 2569)
//    จอ ZORT บอก 2,900 รายการ · ทะเบียนเรามี 2,673 ⇒ ต่างกัน 226
//    กวาดรหัสจากจอ ZORT ทีละหน้าจนครบ 2,900 แถว: มีรหัส 2,674 · **ไม่มีรหัส 226**
//    ⇒ ส่วนต่างคือ "สินค้าที่ยังไม่ได้ตั้งรหัส" ซึ่ง ZORT นับรวม แต่กระจกเราเก็บไม่ได้ (รหัสคือกุญแจ)
//    🔑 **ไม่ใช่ของหาย ไม่ใช่ ZORT ซ่อน ไม่ใช่ตัวซิงก์พัง** — แต่คนที่เห็นเลขสองฝั่งจะเดาแบบนั้น
//       วันนี้คนที่เดาแบบนั้นคือ CTO เอง และเสียเวลาไปสองรอบ ⇒ ป้ายเดียวกันคนรอบหน้าไม่ให้เดินซ้ำ
//
// 🔴 **กฎที่ห้ามละเมิด (CTO กำชับ)**
//    ① **ห้ามเขียนเลข 226 ตายตัวในโค้ด** — ร้านตั้งรหัสเพิ่มเมื่อไหร่ เลขนี้ลดเอง
//       เขียนตายตัว = คำเท็จที่ไม่มีใครรู้ว่ากลายเป็นเท็จตอนไหน (กฎเดียวกับที่ห้ามเขียนจำนวนตัวตรวจในเอกสาร)
//       ⇒ อ่านจากช่อง `noSkuInZort` ที่ท่อส่งมาให้ทุกครั้ง
//    ② **ท่อไม่ส่งเลขมา ⇒ เขียนแค่ว่านับเฉพาะสินค้าที่มีรหัส ห้ามเขียนจำนวน**
//       "ไม่รู้จำนวน" กับ "รู้ว่าเป็นศูนย์" เป็นคนละเรื่อง (กฎสามสถานะของโปรเจกต์)
//    ③ ป้ายต้องอยู่ **ตรงที่คนเห็นพร้อมตัวเลข** ไม่ใช่ต้องเลื่อนจอลงไปหา
//    ④ จอไหนมีปุ่มส่งออก Excel **ต้องมีบรรทัดเดียวกันนี้ในหัวไฟล์ด้วย**
//       เพราะไฟล์ที่ออกไปแล้ว ไม่มีใครตามไปอธิบายให้

/**
 * ประโยคกำกับขอบเขตของตัวเลขสินค้า
 * @param noSku ช่อง `noSkuInZort` จากท่อ — **ส่งค่าที่ได้มาตรง ๆ** อย่าแปลง undefined เป็น 0
 * @returns ประโยคที่เอาไปวางบนจอหรือในหัวไฟล์ได้เลย
 */
export function skuScopeNote(noSku: unknown): string {
  const ฐาน = 'ตัวเลขนี้นับเฉพาะสินค้าที่มีรหัส'
  if (typeof noSku !== 'number' || !Number.isFinite(noSku) || noSku < 0) {
    /* 🔴 ไม่รู้ ⇒ **ห้ามใส่จำนวน** และห้ามเงียบด้วย — ยังต้องบอกว่านับเฉพาะที่มีรหัส */
    return `${ฐาน} (ท่อไม่ได้บอกว่ามีสินค้าที่ยังไม่ได้ตั้งรหัสกี่รายการ)`
  }
  if (noSku === 0) {
    /* รู้ว่าเป็นศูนย์ = ข้อเท็จจริงที่ดี ต้องพูดออกมา ไม่ใช่ซ่อนป้ายทิ้ง
       (วันที่ร้านตั้งรหัสครบ ป้ายนี้จะกลายเป็นคำยืนยันว่าเลขสองฝั่งตรงกันได้แล้ว) */
    return `${ฐาน} — ตอนนี้สินค้าใน ZORT มีรหัสครบทุกตัว`
  }
  return `${ฐาน} — ไม่รวมสินค้าที่ยังไม่ได้ตั้งรหัสอีก ${noSku.toLocaleString('th-TH')} รายการ`
    + ' ซึ่ง ZORT นับรวมไว้ในเลขของเขา'
}
