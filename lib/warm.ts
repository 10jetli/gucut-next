// ปลุกฟังก์ชันฝั่งท่อล่วงหน้า — แก้ "เครื่องเย็น" ซึ่งเป็นตัวถ่วงจริงของหลังร้าน
//
// 📊 **วัดจริง 6 ก.ย. 2569 (ยิงติดกัน 16 ครั้งจากไทย)**
//    4 ครั้งแรก **927 ms** · 12 ครั้งหลัง **426 ms** ⇒ ค่าเครื่องเย็น = **+501 ms**
//
// 📊 **วัดซ้ำแบบแยกแยะได้ (ปล่อยให้เย็นสนิท 3 นาทีก่อนวัดทั้งสองรอบ)**
//    A) เย็น แล้วยิงงานจริงเลย        = **2,134 ms**
//    B) ปลุกก่อน แล้วค่อยยิงงานจริง   = **1,209 ms**
//    ⇒ **ประหยัดจริง 925 ms** มากกว่าตัวเลข 501 ข้างบน เพราะรอบนั้นวัดเส้นที่ไม่แตะฐาน
//    ⇒ ของจริงที่คนใช้เจอ ดีกว่าที่ประเมินไว้เกือบเท่าตัว
//    และค่าเชื่อมต่อถึง Netlify มีแค่ 45 ms ⇒ **เน็ตไม่ได้ช้า ฐานก็ไม่ใช่ตัวหลัก**
//
// 🔴 **ปลุกพร้อมกับคำขอจริง ไม่ช่วยอะไรเลย** — ทั้งคู่เจอเครื่องเย็นรอบเดียวกัน
//    ⇒ ต้องปลุก **ก่อน** คนกด ไม่ใช่ตอนกด นี่คือทั้งหมดของไฟล์นี้
//
// ⚠️ **เจ้าของร้านใช้ iPhone เป็นหลัก — มือถือไม่มีการชี้เมาส์**
//    ⇒ ห้ามผูกกับ onMouseEnter อย่างเดียว ต้องใช้ `pointerdown` (ทำงานทั้งเมาส์และนิ้ว)
//       และปลุกตอน **เปิดแผงเมนู** ด้วย เพราะบนมือถือคนกด ☰ ก่อนเลือกเมนูเสมอ
//
// ⚠️ **ข้อจำกัดที่ต้องรู้ ไม่ใช่ยาวิเศษ** (ฝั่งท่อชี้ไว้)
//    ① เพดานตอนเครื่องอุ่นยังอยู่ที่ ~400 ms — ปลุกล่วงหน้าไม่ทำให้ต่ำกว่านั้น
//    ② ปลุกได้ทีละ **หนึ่งเครื่อง** — จอที่ยิงหลายเส้นพร้อมกันยังเจอเครื่องใหม่ที่เย็นได้
//       (เห็นของจริง 1,330 ms โผล่กลางชุดที่อุ่นแล้ว)
//
// 💰 ค่าใช้จ่าย: การเรียกฟังก์ชันกินเครดิตรวมกัน **4.4%** ของทั้งเดือน
//    (deploy กิน 86.5%) ⇒ ปลุกล่วงหน้าจ่ายไหวสบาย · **แต่ยังต้องไม่ยิงพร่ำเพรื่อ** ดูกติกาข้างล่าง

/** เส้นที่ใช้ปลุก — ต้อง **ไม่แตะฐานข้อมูล** ไม่งั้นจ่ายสองต่อโดยไม่ได้อะไรเพิ่ม
 *  ✅ ฝั่งท่อทำ `?ping=1` ให้แล้ว 6 ก.ย. 2569 — คืน {ok, ping, build}
 *     ไม่แตะฐาน · ไม่แตะที่เก็บข้อมูล · **ไม่โหลดโมดูลเพิ่ม** (เบากว่า zortnoapi ที่เคยใช้ชั่วคราว)
 *  ⚠️ เส้นนี้ **ไม่ต้องใช้รหัส** โดยตั้งใจ ⇒ ปลุกได้แม้ยังไม่ล็อกอิน
 *     และ **ห้ามใส่ข้อมูลอะไรลงไปในคำตอบของมันเพิ่ม** — เส้นที่ไม่มีด่านต้องไม่มีอะไรให้ขโมย */
const WARM_URL = '/api/web/core?ping=1'

/** ถ้าเพิ่งคุยกับท่อไปไม่นาน แปลว่าเครื่องยังอุ่น — **ไม่ต้องปลุก**
 *  ตั้ง 45 วิ เพราะวัดแล้วเครื่องอยู่ได้เกินนั้น และสั้นกว่าช่วงที่คนเปลี่ยนเมนูปกติ */
const WARM_TTL_MS = 45_000

let lastTouch = 0
let inFlight = false

/** บอกว่า "เพิ่งคุยกับท่อไป"
 *
 *  ⚠️ **ของจริงตอนนี้เรียกไม่ครบ และตั้งใจบอกไว้ตรง ๆ** (นับเมื่อ 6 ก.ย. 2569):
 *     จอที่ยิง `/api/web/core` มี **34 ไฟล์ยิงตรง ๆ** ส่วนที่ผ่าน `coreJson` (ซึ่งเรียกตัวนี้ให้)
 *     มีแค่ **4 ไฟล์** ⇒ ตัวปลุกจึงไม่รู้ว่าเครื่องอุ่นอยู่แล้วในกรณีส่วนใหญ่
 *  ผลที่ตามมา: **ยิงปลุกซ้ำโดยไม่จำเป็นได้** (อย่างมากหนึ่งครั้งต่อการกดเมนู)
 *     — เสียนิดเดียวและไม่ทำให้อะไรผิด จึงยังไม่ไล่แก้ทั้ง 34 ไฟล์
 *  🔴 **ห้ามเขียนในนี้ว่า "เรียกจากทุกที่ที่ยิงท่อ"** — เคยเขียนไว้แบบนั้นและมันไม่จริง
 *     คอมเมนต์ที่โม้เกินของจริง ทำให้คนรอบหน้าคำนวณค่าใช้จ่ายผิดโดยไม่มีอะไรฟ้อง */
export function noteCoreCall() {
  lastTouch = Date.now()
}

/** ปลุกเครื่องถ้าน่าจะเย็น — เงียบเสมอ ไม่คืนอะไร ไม่ขวางอะไร
 *  🔴 **ห้ามให้ตัวนี้ทำให้จอช้าลงหรือพังได้เด็ดขาด** — มันเป็นของแถม ไม่ใช่ของจำเป็น
 *     error ทุกชนิดกลืนทิ้ง · ไม่ await ที่ผู้เรียก · ยิงซ้อนกันไม่ได้ */
export function warmCore() {
  if (typeof window === 'undefined') return
  const now = Date.now()
  if (inFlight || now - lastTouch < WARM_TTL_MS) return
  inFlight = true
  lastTouch = now
  // ⚠️ keepalive: ถ้าคนกดเมนูแล้วหน้าเปลี่ยนทันที คำขอนี้ต้องไม่ถูกยกเลิกกลางทาง
  //    ไม่งั้นเครื่องจะไม่ถูกปลุกจริง และเราจ่ายค่าเรียกไปเปล่า ๆ
  fetch(WARM_URL, { keepalive: true, cache: 'no-store' })
    .catch(() => {})
    .finally(() => { inFlight = false })
}
