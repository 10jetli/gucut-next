// คุกกี้ล็อกอิน — **ห้ามเก็บรหัสผ่านลงคุกกี้อีก**
//
// 🔴 ของเดิม (ถึง 6 ก.ย. 2569) เก็บ `gucut_auth = ตัวรหัสผ่านเอง`
//    ผลที่ตามมา 2 ข้อ ซึ่งข้อที่สองอันตรายกว่าที่เห็นตอนแรกมาก:
//    ① ใครอ่านคุกกี้ได้ = ได้รหัสผ่านจริงไปเลย (ไม่ใช่แค่ session ของเครื่องนั้น)
//    ② **middleware เทียบ "คุกกี้ == รหัสผ่าน" ทุกคำขอ** ⇒ คนที่ยิงเดา
//       ไม่จำเป็นต้องผ่านหน้า /api/auth/login เลย ตั้งคุกกี้แล้วขอหน้าไหนก็ได้
//       ⇒ **ตัวกันเดารหัสที่ใส่ไว้เฉพาะหน้าล็อกอิน กันได้แค่ประตูเดียวจากสองประตู**
//
// ⇒ เปลี่ยนเป็นเก็บ **ลายนิ้วมือของรหัส** (SHA-256 + ตัวคั่นประจำระบบ)
//    เดาคุกกี้ให้ตรงต้องเดาเลข 256 บิต ไม่ใช่เดารหัสผ่านของร้าน
//    ⇒ ประตูที่สองปิดด้วยความยาวของเลข ไม่ต้องพึ่งตัวนับครั้ง (ซึ่งใน serverless เชื่อไม่ได้เต็มร้อย)
//
// ⚠️ **ใช้ Web Crypto เท่านั้น ห้าม import node:crypto** — ไฟล์นี้ถูกเรียกจาก middleware
//    ซึ่งรันบน edge runtime · เผลอ import node:crypto = ทั้งเว็บ 500 ตั้งแต่คำขอแรก
//
// ⚠️ ของเดิมกับของใหม่ **ใช้ร่วมกันไม่ได้โดยตั้งใจ** — คุกกี้เก่าทุกใบใช้ไม่ได้ทันทีที่ deploy
//    ⇒ ทุกคน (รวมเจ้าของร้านและพนักงานที่หน้าร้าน) ต้องพิมพ์รหัสใหม่ครั้งเดียว
//    ยอมให้ล็อกอินใหม่ครั้งเดียว ดีกว่ารับคุกกี้เก่าต่อ ซึ่งเท่ากับเปิดรูเดิมค้างไว้

// ✅ **พิสูจน์แล้วด้วยการยิงจริง ไม่ใช่แค่ tsc ผ่าน** (6 ก.ย. 2569 หลัง deploy)
//    บนเว็บจริง — ส่งคุกกี้มั่วเข้าไปที่ /core/sales ⇒ **307 ไม่ใช่ 500**
//    ⇒ แปลว่า crypto.subtle ทำงานจริงบน runtime ของ middleware (ถ้าใช้ไม่ได้จะพัง 500 ทุกหน้า)
//    ⚠️ ยิงตอนไม่มีคุกกี้ **พิสูจน์อะไรไม่ได้เลย** เพราะโค้ดลัดวงจรก่อนถึงการแฮช (ดู middleware)
//       — เกือบสรุปผิดจากการยิงแบบนั้นมาแล้ว ต้องส่งคุกกี้มั่วเข้าไปถึงจะแตะเส้นแฮช
//    ในเครื่อง (build จริง ไม่ใช่ dev) ครบสามทาง:
//      รหัสถูก → 200 + คุกกี้เป็นเลขฐานสิบหก · คุกกี้ปลอมความยาวเท่ากัน → 307
//      **คุกกี้ = ตัวรหัสผ่านดิบ (ท่าเก่า) → 307** ⇒ รูเดิมปิดจริง ไม่ใช่แค่เชื่อว่าปิด
const PREFIX = 'gucut-auth-v1:'

/** ลายนิ้วมือของรหัสผ่าน — ค่าที่เอาไปใส่คุกกี้
 *  ⚠️ ฟังก์ชันนี้ **ไม่ใช่การเก็บรหัสอย่างปลอดภัยสำหรับฐานข้อมูล** (ไม่มี salt รายคน ไม่ถ่วงเวลา)
 *     หน้าที่มันคือ "อย่าให้ตัวรหัสเดินทางไปกับคุกกี้" เท่านั้น — รหัสตัวจริงยังอยู่ใน env */
export async function authToken(password: string): Promise<string> {
  const bytes = new TextEncoder().encode(PREFIX + password)
  const digest = await crypto.subtle.digest('SHA-256', bytes)
  return Array.from(new Uint8Array(digest)).map((b) => b.toString(16).padStart(2, '0')).join('')
}

/** เทียบแบบใช้เวลาเท่ากันเสมอ — ไม่ให้เวลาตอบบอกว่าเดาถูกไปกี่ตัว
 *  ⚠️ ต้อง `!==` สะสมทุกตัว ห้าม return กลางทาง (return เร็ว = บอกความยาวที่ตรง) */
export function sameToken(a: string | undefined, b: string | undefined): boolean {
  if (!a || !b || a.length !== b.length) return false
  let diff = 0
  for (let i = 0; i < a.length; i++) diff |= a.charCodeAt(i) ^ b.charCodeAt(i)
  return diff === 0
}
