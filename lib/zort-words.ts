/** แปลค่าดิบเป็นคำบนจอ — **ไม่รู้จักคืนค่าดิบ ห้ามเดา**
 *  คืน `known: false` ให้จอเลือกได้ว่าจะทำอะไรต่อ (เช่นทำสีเทา หรือขึ้นเครื่องหมายว่ายังไม่แปล)
 *  ⚠️ เดาข้างชำระเงินผิด = จอบอกว่าเก็บเงินแล้วทั้งที่ยังไม่ได้เงิน */
export function zortWord(
  map: Record<string, ZortWord>,
  raw?: string | null,
): { text: string; known: boolean; source?: WordSource } {
  const key = String(raw ?? '').trim()
  if (!key) return { text: '', known: false }
  const hit = map[key]
  return hit ? { text: hit.text, known: true, source: hit.source } : { text: key, known: false }
}

