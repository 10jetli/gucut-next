/** ป้ายเตือน "ชื่อลูกค้าซ้ำกันหลายราย" — แยกออกมาเป็นฟังก์ชันบริสุทธิ์เพื่อ **ทดสอบด้วยการรัน**
 *  (19 ก.ย. 2569 · ฝั่งท่อเพิ่มธง `ชื่อซ้ำกันหลายราย` ให้)
 *
 *  🔑 สามสถานะที่ห้ามยุบ:
 *    `true`      ⇒ ท่อบอกว่าซ้ำ            ⇒ ป้ายแดง "ของที่เห็นอาจเป็นของอีกคน"
 *    `false`     ⇒ ท่อบอกว่าไม่ซ้ำ         ⇒ ไม่ต้องเตือน
 *    `undefined` ⇒ **ท่อรุ่นเก่า ไม่ได้บอก** ⇒ ป้ายเทา "ยังบอกไม่ได้" — **ไม่ใช่ "ไม่ซ้ำ"**
 *
 *  ⚠️ และเตือนเฉพาะตอน **เปิดด้วยชื่อ** — เปิดด้วย id ไม่มีปัญหานี้เลย
 *     คำเตือนที่ขึ้นตอนไม่เกี่ยวข้อง จะถูกเมินจนวันที่มันสำคัญจริง
 */
export type ป้ายชื่อซ้ำ = 'ซ้ำ' | 'ยังบอกไม่ได้' | null

export function ป้ายชื่อซ้ำจาก(เปิดด้วยชื่อ: boolean, ซ้ำ: boolean | undefined, มีคำตอบแล้ว: boolean): ป้ายชื่อซ้ำ {
  if (!มีคำตอบแล้ว) return null        // ยังโหลดอยู่ ⇒ ยังไม่ต้องพูดอะไร
  if (!เปิดด้วยชื่อ) return null        // เปิดด้วย id ⇒ ไม่มีความกำกวมเรื่องชื่อ
  if (ซ้ำ === true) return 'ซ้ำ'
  if (ซ้ำ === undefined) return 'ยังบอกไม่ได้'
  return null                           // ซ้ำ === false ⇒ ท่อยืนยันแล้วว่าไม่ซ้ำ
}
