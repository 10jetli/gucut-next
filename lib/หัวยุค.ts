/** ASCII ที่พิมพ์ได้เท่านั้น — ปลอดภัยกับทุก proxy ไม่ใช่แค่ Latin-1 */
const ปลอดภัย = /^[\x20-\x7E]+$/

export function ค่าหัวที่ปลอดภัย(ค่า: unknown, ยาวสุด = 64): string | null {
  if (typeof ค่า !== 'string') return null
  const t = ค่า.trim()
  if (!t) return null
  if (!ปลอดภัย.test(t)) return null
  return t.slice(0, ยาวสุด)
}
