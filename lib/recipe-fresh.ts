/** รอบซิงก์เป็นภาษาคน — **คิดจากค่าที่ท่อส่งมา ไม่ใช่พิมพ์รอบซ้ำ** */
export function ป้ายรอบซิงก์(everyHours?: number | null): string {
  if (typeof everyHours !== 'number' || !Number.isFinite(everyHours)) return ''
  if (everyHours >= 24 && everyHours % 24 === 0) {
    const วัน = everyHours / 24
    return วัน === 1 ? 'วันละครั้ง' : `ทุก ${วัน} วัน`
  }
  return everyHours === 1 ? 'ทุกชั่วโมง' : `ทุก ${everyHours} ชั่วโมง`
}

