/* อ่านสภาพ "ต้นทุนครอบพอจะคิดกำไรได้ยัง" จากคำตอบของเส้น `?costsince=1`
 *
 * 🔴 **ทำไมเป็นฟังก์ชันบริสุทธิ์แยกไฟล์** — ตัวตัดสินนี้มีกิ่ง 7 ทาง และ 4 ทางเป็นสภาพที่
 *    **ยังไม่เคยเกิดกับร้านนี้** (ยังไม่เริ่มตรึง · ช่วงไม่มีบรรทัดขาย · แปลไม่ได้ · ถึงเกณฑ์)
 *    ⇒ ถ้าเขียนปนในเพจ จะไม่มีทางทดสอบกิ่งพวกนั้นเลยจนกว่าของจริงจะมาถึง
 *    ⇒ แยกออกมา ⇒ ป้อนค่าปลอมทดสอบได้ทุกกิ่ง (ดู `scripts/tests/costsince.test.mjs`)
 *
 * 🔴 **สามข้อห้ามของสัญญานี้ — เขียนไว้ตรงที่โค้ดตัดสินใจ ไม่ใช่ในเอกสารที่ไหน**
 *   ① `ครอบกี่เปอร์เซ็นต์ในช่วง: null` = **ช่วงนั้นไม่มีบรรทัดขายเลย**
 *      ห้ามอ่านเป็น 0 และห้ามอ่านเป็น 100 — "ไม่มีของให้ครอบ" ≠ "ครอบครบ"
 *      และ `ถึงเกณฑ์ยอดรวมไหม: null` = **แปลไม่ได้** ไม่ใช่ **ไม่ผ่าน**
 *   ② `วันแรก: null` = **ยังไม่เริ่มตรึงเลย** ห้ามแปลว่าวันนี้
 *   ③ **ห้ามเทียบเกณฑ์เองที่จอ** — ท่อส่ง `เกณฑ์ครอบยอดรวม` มาเป็นเลขอ้างอิงให้แสดงเท่านั้น
 *      ตัวตัดสินคือ `ถึงเกณฑ์ยอดรวมไหม` ที่ท่อคิดให้ ⇒ ถ้าวันหน้าเปลี่ยนเกณฑ์
 *      สองจอจะไม่บอกคนละอย่าง (ฝั่งท่อมีด่านอ่านซอร์สกันไว้แล้วว่า core.mjs ห้ามมี `>= 95`)
 *
 * ⚠️ **ช่องที่ไม่มีเลย ≠ null** — ไม่มี `ในช่วง` แปลว่า **ท่อรุ่นเก่า** (ยังไม่ขึ้น)
 *    ต่างจาก `ในช่วง` ที่มีแต่ค่าข้างในเป็น null ซึ่งแปลว่าท่อรุ่นใหม่แต่ตอบไม่ได้
 *    ⇒ สองอย่างนี้ต้องขึ้นจอคนละข้อความ ไม่งั้นเราจะไปไล่แก้ผิดฝั่ง
 */

/** รูปคำตอบของ `?costsince=1` — ช่องที่อาจไม่มี ใส่ `?` ไว้ทุกช่อง เพราะท่อรุ่นเก่าไม่ส่ง */
export type CostSinceตอบ = {
  ok?: boolean
  วันแรก?: string | null
  บรรทัดที่มีต้นทุน?: number | null
  บรรทัดขายทั้งหมดในกระจก?: number | null
  ครอบกี่เปอร์เซ็นต์?: number | null
  เกณฑ์ครอบยอดรวม?: number | null
  'โชว์กำไรรายบรรทัดได้'?: boolean | null
  ในช่วง?: {
    จาก?: string | null
    ถึง?: string | null
    บรรทัดขายในช่วง?: number | null
    บรรทัดที่มีต้นทุนในช่วง?: number | null
    ครอบกี่เปอร์เซ็นต์ในช่วง?: number | null
    'ถึงเกณฑ์ยอดรวมไหม'?: boolean | null
  } | null
}

export type สภาพต้นทุน = {
  /** ชนิดของสภาพ — ใช้ตัดสินข้อความและการเปิด/ปิดตัวเลือก */
  ชนิด:
    | 'ท่อรุ่นเก่า'          // ไม่มีช่อง `ในช่วง` เลย ⇒ ท่อยังไม่ขึ้น
    | 'ยังไม่เริ่มตรึง'       // วันแรก = null
    | 'ช่วงนี้ไม่มีบรรทัดขาย' // ครอบกี่เปอร์เซ็นต์ในช่วง = null
    | 'แปลไม่ได้'            // ถึงเกณฑ์ยอดรวมไหม = null (แต่มีบรรทัดขาย)
    | 'ยังไม่ถึงเกณฑ์'
    | 'ถึงเกณฑ์'
  /** เปิดตัวเลือก **ยอดรวม** ได้ไหม — true เฉพาะ 'ถึงเกณฑ์' */
  เปิดยอดรวมได้: boolean
  /** โชว์กำไร **รายบรรทัด** ได้ไหม — `null` = ท่อยังไม่บอก (ห้ามอ่านเป็น false) */
  โชว์รายบรรทัดได้: boolean | null
  /** เหตุที่อ่านแล้วรู้ว่าต้องทำอะไรต่อ — ขึ้นจอได้ตรง ๆ */
  เหตุ: string
  /** เลขอ้างอิงจากคำตอบ (ไม่ใช่จอคิดเอง) — ไม่มี = null */
  ครอบ: number | null
  เกณฑ์: number | null
}

const เลข = (x: unknown): number | null => (typeof x === 'number' && Number.isFinite(x) ? x : null)
const pct = (x: number | null) => (x === null ? '—' : `${x}%`)

export function อ่านสภาพต้นทุน(j: CostSinceตอบ | null | undefined): สภาพต้นทุน {
  const ช = j?.ในช่วง
  const เกณฑ์ = เลข(j?.เกณฑ์ครอบยอดรวม)
  const รายบรรทัด = typeof j?.['โชว์กำไรรายบรรทัดได้'] === 'boolean'
    ? (j['โชว์กำไรรายบรรทัดได้'] as boolean)
    : null

  // ⚠️ ไม่มีช่อง `ในช่วง` **หรือ** ไม่มี `เกณฑ์ครอบยอดรวม` ⇒ ท่อรุ่นเก่า
  //    (เช็คสองช่อง เพราะถ้าเช็คช่องเดียวแล้วท่อส่งมาครึ่งเดียว เราจะอ่านครึ่งที่ขาดเป็น null เงียบ ๆ)
  if (!ช || เกณฑ์ === null) {
    return {
      ชนิด: 'ท่อรุ่นเก่า', เปิดยอดรวมได้: false, โชว์รายบรรทัดได้: รายบรรทัด,
      เหตุ: 'ท่อยังไม่ส่งสภาพต้นทุนของช่วงวันมา (ยังเป็นรุ่นก่อนสัญญา `?costsince=1` รอบใหม่) '
        + '⇒ ยังตัดสินไม่ได้ว่าคิดยอดรวมได้หรือไม่',
      ครอบ: null, เกณฑ์,
    }
  }

  if (j?.วันแรก === null || j?.วันแรก === undefined) {
    return {
      ชนิด: 'ยังไม่เริ่มตรึง', เปิดยอดรวมได้: false, โชว์รายบรรทัดได้: รายบรรทัด,
      เหตุ: 'ยังไม่เริ่มตรึงต้นทุนลงบรรทัดขายเลย ⇒ คิดกำไรไม่ได้ทั้งรายบรรทัดและยอดรวม',
      ครอบ: null, เกณฑ์,
    }
  }

  const ครอบ = เลข(ช.ครอบกี่เปอร์เซ็นต์ในช่วง)
  if (ครอบ === null) {
    return {
      ชนิด: 'ช่วงนี้ไม่มีบรรทัดขาย', เปิดยอดรวมได้: false, โชว์รายบรรทัดได้: รายบรรทัด,
      เหตุ: 'ช่วงวันที่เลือกไม่มีบรรทัดขายเลย ⇒ ไม่มีของให้ครอบ '
        + '(คนละเรื่องกับ "ครอบ 0%" และคนละเรื่องกับ "ครอบครบ")',
      ครอบ: null, เกณฑ์,
    }
  }

  const ถึง = ช['ถึงเกณฑ์ยอดรวมไหม']
  if (typeof ถึง !== 'boolean') {
    return {
      ชนิด: 'แปลไม่ได้', เปิดยอดรวมได้: false, โชว์รายบรรทัดได้: รายบรรทัด,
      เหตุ: `ท่อตอบว่าแปลผลไม่ได้สำหรับช่วงนี้ (ครอบ ${pct(ครอบ)}) `
        + '⇒ "แปลไม่ได้" ไม่ใช่ "ไม่ผ่าน" ⇒ ยังไม่เปิดยอดรวม และไม่ประกาศว่าไม่ถึงเกณฑ์',
      ครอบ, เกณฑ์,
    }
  }

  return ถึง
    ? {
      ชนิด: 'ถึงเกณฑ์', เปิดยอดรวมได้: true, โชว์รายบรรทัดได้: รายบรรทัด,
      เหตุ: `ต้นทุนครอบ ${pct(ครอบ)} ของบรรทัดขายในช่วงนี้ (เกณฑ์ ${pct(เกณฑ์)}) ⇒ คิดยอดรวมได้`,
      ครอบ, เกณฑ์,
    }
    : {
      ชนิด: 'ยังไม่ถึงเกณฑ์', เปิดยอดรวมได้: false, โชว์รายบรรทัดได้: รายบรรทัด,
      /* ⚠️ **ห้ามขึ้นต้นด้วย "ยังคิดยอดรวมไม่ได้"** — จอที่เรียกใช้พูดประโยคนั้นอยู่แล้ว
         ⇒ บนเว็บจริงออกมาเป็น "ยังคิดกำไรรวมไม่ได้ … — ยังคิดยอดรวมไม่ได้ — …" (เจอ 5 ต.ค. 2569
            ด้วยการอ่านข้อความบนเว็บจริง ไม่ใช่จากเทส) ⇒ ช่องนี้ให้ **เหตุ** เท่านั้น ไม่ใช่คำตัดสินซ้ำ */
      เหตุ: `ต้นทุนครอบ ${pct(ครอบ)} ของบรรทัดขายในช่วงนี้ `
        + `ต้องถึง ${pct(เกณฑ์)} · การบวกข้ามบรรทัดที่ขาดต้นทุนทำให้กำไรรวมสูงเกินจริง`,
      ครอบ, เกณฑ์,
    }
}
