/** ขยายช่อง cron หนึ่งช่องเป็นชุดค่าจริง · คืน `null` เมื่อเจอรูปที่ยังไม่รองรับ */
function ขยายช่อง(ช่อง: string, ต่ำสุด: number, สูงสุด: number): number[] | null {
  const out = new Set<number>()
  for (const ส่วน of ช่อง.split(',')) {
    if (ส่วน === '*') {
      for (let i = ต่ำสุด; i <= สูงสุด; i++) out.add(i)
      continue
    }
    const ทุกกี่ = /^\*\/(\d+)$/.exec(ส่วน)
    if (ทุกกี่) {
      const ก้าว = Number(ทุกกี่[1])
      if (!ก้าว) return null
      for (let i = ต่ำสุด; i <= สูงสุด; i += ก้าว) out.add(i)
      continue
    }
    const ช่วง = /^(\d+)-(\d+)$/.exec(ส่วน)
    if (ช่วง) {
      const a = Number(ช่วง[1]); const b = Number(ช่วง[2])
      if (a > b || a < ต่ำสุด || b > สูงสุด) return null
      for (let i = a; i <= b; i++) out.add(i)
      continue
    }
    if (/^\d+$/.test(ส่วน)) {
      const n = Number(ส่วน)
      if (n < ต่ำสุด || n > สูงสุด) return null
      out.add(n)
      continue
    }
    return null   // รูปที่ยังไม่รองรับ ⇒ ตัดสินไม่ได้
  }
  return out.size ? [...Array.from(out)] : null
}

/** จำนวนรอบต่อวันของ cron 5 ช่อง · `null` = ตัดสินไม่ได้ (ไม่ใช่ 0) */
export function รอบต่อวัน(cron?: string | null): number | null {
  if (typeof cron !== 'string') return null
  const ช่อง = cron.trim().split(/\s+/)
  if (ช่อง.length !== 5) return null
  const [นาที, ชั่วโมง, วันที่, เดือน, วันในสัปดาห์] = ช่อง
  /* งานที่ไม่ได้วิ่งทุกวัน ⇒ "รอบต่อวัน" ตอบด้วยเลขเดียวไม่ได้ ⇒ ตัดสินไม่ได้ */
  if (วันที่ !== '*' || เดือน !== '*' || วันในสัปดาห์ !== '*') return null
  const M = ขยายช่อง(นาที, 0, 59)
  const H = ขยายช่อง(ชั่วโมง, 0, 23)
  if (!M || !H) return null
  return M.length * H.length
}

/** ป้ายไทยสั้น ๆ สำหรับตาราง · `—` เมื่อตัดสินไม่ได้ (ห้ามเป็น "0 รอบ/วัน") */
export function ป้ายรอบต่อวัน(cron?: string | null): string {
  const n = รอบต่อวัน(cron)
  return n === null ? '—' : `${n.toLocaleString('th-TH')} รอบ/วัน`
}
