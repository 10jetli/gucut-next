let จำนวน = 0
const ผู้ฟัง = new Set<() => void>()

/** เรียกตอนกล่องแดงโผล่ — คืนฟังก์ชันสำหรับเรียกตอนมันหายไป */
export function นับกล่องแดง(): () => void {
  จำนวน += 1
  ผู้ฟัง.forEach((f) => f())
  let คืนแล้ว = false
  return () => {
    if (คืนแล้ว) return      // กัน unmount ซ้ำไม่ให้ตัวนับติดลบ
    คืนแล้ว = true
    จำนวน = Math.max(0, จำนวน - 1)
    ผู้ฟัง.forEach((f) => f())
  }
}

export const จำนวนกล่องแดง = () => จำนวน

export function ฟังกล่องแดง(f: () => void): () => void {
  ผู้ฟัง.add(f)
  return () => { ผู้ฟัง.delete(f) }
}
