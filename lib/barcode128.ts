const START_B = 104
const STOP = 106

export interface Barcode {
  /** ความกว้างสลับ แท่งดำ-ช่องขาว-… เริ่มที่แท่งดำ (ยังไม่รวมขอบขาว) */
  bars: number[]
  /** ความกว้างรวมเป็นหน่วยโมดูล (ไว้คำนวณ viewBox) */
  modules: number
  /** ตัวอักษรที่เข้ารหัสจริง — เท่ากับ input เสมอ ถ้าไม่มี error */
  text: string
  /** ❗ เข้ารหัสไม่ได้เพราะอะไร — **ถ้ามีค่า ห้ามพิมพ์ฉลากใบนั้น** */
  error?: string
}

/** ขอบขาวสองข้าง — มาตรฐานบังคับอย่างน้อย 10 โมดูล · ขาดขอบ = เครื่องอ่านหาหัวบาร์โค้ดไม่เจอ */
export const QUIET_ZONE = 10

/**
 * เข้ารหัสข้อความเป็น Code 128 ชุด B
 * @param text ตัวอักษร ASCII 32–126 (ช่องว่างได้ · ภาษาไทยไม่ได้)
 */
export function code128b(text: string): Barcode {
  const empty: Barcode = { bars: [], modules: 0, text }
  if (text === '') return { ...empty, error: 'ไม่มีรหัสให้เข้ารหัส (ค่าว่าง)' }

  /* ⚠️ ต้องเช็คทีละตัวเพื่อ **บอกได้ว่าตัวไหนผิด** — บอกแค่ "เข้ารหัสไม่ได้" คนแก้ไม่ถูก */
  /* ⚠️ ใช้ Array.from ไม่ใช่ [...text] — โปรเจกต์นี้ tsc ไม่ได้ตั้ง target ไว้ (เป็น ES5)
     การกระจายสตริงจะ error · และห้ามใช้ split('') เพราะมันฉีกอักษรนอก BMP เป็นครึ่งตัว
     แล้วข้อความเตือนจะบอกอักษรที่ไม่มีจริง */
  const bad = Array.from(text).filter((c) => {
    const n = c.codePointAt(0) ?? 0
    return n < 32 || n > 126
  })
  if (bad.length) {
    return {
      ...empty,
      error: `Code 128 เข้ารหัสได้แค่ ASCII 32–126 · รหัสนี้มีอักษรที่เข้ารหัสไม่ได้: ${
        Array.from(new Set(bad)).map((c) => (c.trim() === '' ? `(ช่องว่างพิเศษ U+${(c.codePointAt(0) ?? 0).toString(16).toUpperCase()})` : c)).join(' ')
      }`,
    }
  }

  const values = Array.from(text).map((c) => (c.codePointAt(0) ?? 0) - 32)
  /* ตัวตรวจทานของ Code 128: (ค่าเริ่ม + Σ ลำดับ×ค่า) mod 103 · ลำดับเริ่มที่ 1 */
  let sum = START_B
  values.forEach((v, i) => { sum += v * (i + 1) })
  const check = sum % 103

  const seq = [START_B, ...values, check, STOP]
  const bars: number[] = []
  for (const v of seq) for (const d of Array.from(CODE128_PATTERNS[v])) bars.push(Number(d))

  return { bars, modules: bars.reduce((a, b) => a + b, 0), text }
}

/**
 * แปลงเป็น SVG พร้อมพิมพ์ — ใช้หน่วยเป็น "โมดูล" ใน viewBox แล้วให้ CSS ยืดตามขนาดฉลาก
 * ⚠️ `shapeRendering: crispEdges` สำคัญ — ถ้าเบราว์เซอร์ลบรอยหยัก ขอบแท่งจะเบลอ
 *    แล้วเครื่องอ่านวัดความกว้างพลาดในฉลากเล็ก
 */
export function code128Svg(b: Barcode, heightModules = 30): string {
  if (b.error || !b.bars.length) return ''
  const w = b.modules + QUIET_ZONE * 2
  let x = QUIET_ZONE
  const rects: string[] = []
  b.bars.forEach((width, i) => {
    if (i % 2 === 0) rects.push(`<rect x="${x}" y="0" width="${width}" height="${heightModules}"/>`)
    x += width
  })
  return `<svg viewBox="0 0 ${w} ${heightModules}" preserveAspectRatio="none" `
    + `width="100%" height="100%" shape-rendering="crispEdges" fill="#000">${rects.join('')}</svg>`
}
