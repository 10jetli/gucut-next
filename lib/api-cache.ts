// ⚠️ ราคาที่ต้องจ่ายคือ "ตัวเลขเก่า" ซึ่ง**อันตรายกว่าช้า** — จอที่โชว์เลขเก่าหน้าตาปกติทุกประการ
//    กติกาข้างล่างจึงไม่ใช่ข้อเสนอแนะ ทุกข้อมีเหตุการณ์รองรับ ห้ามถอดข้อไหนออก

/** อายุสูงสุดที่ยังยอมให้ใช้ของเก่า — เกินนี้ถือว่าไม่มีแคช โหลดใหม่ตามปกติ */
export const CACHE_MAX_AGE = 60_000

interface Entry { at: number; data: unknown }

/** ⚠️ **หน่วยความจำเท่านั้น ห้ามย้ายไป localStorage/sessionStorage เด็ดขาด**
 *  ของในนี้ตายพร้อมการรีเฟรชหน้า ⇒ "กดรีเฟรช = ได้ของสดเสมอ" เป็นทางออกที่คนใช้เดาได้เอง
 *  ถ้าเก็บลงเครื่อง ข้อมูลจะข้ามวัน ข้ามรอบ deploy ข้ามการเปลี่ยนรูปข้อมูลของท่อ
 *  แล้วจะมีจอที่โชว์เลขของเมื่อวานโดยไม่มีใครหาสาเหตุเจอ */
const mem = new Map<string, Entry>()

/** ของเก่าที่ยังใช้ได้ — ไม่มี/เก่าเกินไป คืน null
 *
 *  ⚠️ **คีย์คือ URL เต็มรวมพารามิเตอร์ทุกตัว** (store · from · to · q · status · limit · offset)
 *     ตัดพารามิเตอร์ออกจากคีย์เมื่อไหร่ = สลับตัวกรองแล้วเห็นข้อมูลของตัวกรองก่อนหน้า
 *     **ตัวเลขผิดที่หน้าตาปกติทุกประการ** ⇒ ห้ามทำคีย์แบบ "เอาแค่ชื่อ list" เด็ดขาด */
export function peekApiCache<T = unknown>(
  url: string,
  maxAgeMs: number = CACHE_MAX_AGE,
): { data: T; ageMs: number } | null {
  /* 🔑 **การเรียก peek คือการประกาศว่า "เส้นนี้เป็นการอ่าน"** — ขึ้นทะเบียนตั้งแต่ตรงนี้เลย
     ฝั่งท่อทักมา 5 ก.ย. 2569: ถ้ารอให้ putApiCache ขึ้นทะเบียนให้ (คือหลังคำตอบกลับมา)
     **หลังรีเฟรชหน้าทุกครั้งจะมีช่วงอุ่นเครื่อง** ที่จอแรก ๆ ล้างแคชกันเองไปเรื่อย ๆ
     จนกว่าจะรู้จักครบ — ไม่ผิด แต่แคชแทบไม่ได้ทำงานในช่วงนั้น
     เขาเสนอให้ใส่รายชื่อเส้นเป็นค่าตั้งต้น · ทำแบบนี้ได้ผลเดียวกันโดย**ไม่ต้องมีรายชื่อ**
     เพราะจอเรียก peek ก่อน fetch เสมอ ⇒ พอถึงตอนยิง เส้นนั้นขึ้นทะเบียนแล้ว
     ⚠️ ปลอดภัยเพราะ **มีแต่โค้ดที่ตั้งใจแคชเส้นนั้นเท่านั้นที่เรียก peek**
        ไม่ใช่ค่าที่มาจากผู้ใช้หรือจากท่อ */
  knownReads.add(url)
  const e = mem.get(url)
  if (!e) return null
  const ageMs = Date.now() - e.at
  if (ageMs > maxAgeMs) { mem.delete(url); return null }
  return { data: e.data as T, ageMs }
}

/** เก็บคำตอบไว้ใช้รอบหน้า
 *
 *  ⚠️ **ห้ามเก็บคำตอบที่ผิดพลาด** — ความผิดพลาดชั่วคราวจะค้างบนจอ 60 วินาที
 *     แล้วกดรีเฟรชก็ไม่หาย เพราะรีเฟรชไปเจอของเก่าตัวเดิม
 *     ⇒ ด่านอยู่ตรงนี้ที่เดียว จอเรียกผิดพลาดยังไงก็เก็บของเสียไม่ได้ */
export function putApiCache(url: string, data: unknown): void {
  if (!data || typeof data !== 'object') return
  const d = data as Record<string, unknown>
  if (d.error || d.ok === false || d.skip) return
  knownReads.add(url)
  mem.set(url, { at: Date.now(), data })
}

/** เส้นที่ "รู้แล้วว่าเป็นการอ่านล้วน ๆ" — เส้นที่เคยผ่าน peekApiCache หรือ putApiCache
 *  (peek มาก่อน fetch เสมอ ⇒ **ไม่มีช่วงอุ่นเครื่องหลังรีเฟรชหน้า**)
 *
 *  ⚠️ **ต้องอยู่แยกจาก `mem` และห้ามถูกล้างพร้อมกัน**
 *     `mem` คือของที่ยังใช้ได้ (หมดอายุ/ถูกล้างได้) · ชุดนี้คือ "ความรู้ว่าเส้นไหนไม่เขียนข้อมูล"
 *     ซึ่งไม่หมดอายุ ถ้าล้างพร้อมกันจะกลายเป็นว่าหลังล้างหนึ่งครั้ง ทุกเส้นกลายเป็น
 *     "ไม่รู้จัก" อีกรอบ แล้วล้างกันเองไปมาไม่รู้จบ = แคชไม่เคยรอดข้ามการกดเมนูเลย */
const knownReads = new Set<string>()

/** ล้างทั้งกอง — เรียกหลัง**เขียนข้อมูล**ทุกครั้ง
 *
 *  ⚠️ **ต้องล้างทั้งกอง ไม่ใช่เฉพาะเส้นของจอที่กด** — รับของเข้าใบเดียวกระทบ
 *     จอสต็อก · จอสินค้า · จอหน้าแรก · จอรายงาน พร้อมกัน
 *     ล้างเฉพาะจุดเมื่อไหร่ จะมีจอที่โชว์เลขก่อนบันทึกอยู่อีกนาที แล้วคนกดบันทึกซ้ำ */
export function clearApiCache(): void {
  mem.clear()
}

/* ═══ ล้างแคชอัตโนมัติเมื่อมีการเขียนข้อมูล ═══════════════════════════════
   ⚠️ **ตั้งใจไม่ทำเป็น "ไล่เติม clearApiCache() ทุกจุดที่เขียน"**
      ตอนเขียนไฟล์นี้มีจุดเขียนข้อมูล 20 กว่าจุดใน 15 ไฟล์ ⇒ ไล่เติมมือได้ครบวันนี้
      แต่**คนที่เพิ่มปุ่มบันทึกปุ่มถัดไปจะลืม** แล้วจะได้จอที่โชว์เลขก่อนบันทึกอยู่อีกนาที
      โดยไม่มีอะไรฟ้อง — คนกดจะกดบันทึกซ้ำ

   🔴 **กติกาแรกที่เขียนไว้ ("ไม่ใช่ GET ค่อยล้าง") ใช้ไม่ได้ — ฝั่งท่อจับได้ 5 ก.ย. 2569**
      API ฝั่งท่อมี **10 ตัวที่เขียนข้อมูลแต่สั่งด้วย GET ได้** และไม่เช็ค method เลย:
        init · sync · shopeesync · recon · snapshot · stock · syncbundles · backup · restore · arch
      ⇒ กติกาเดิม**ไม่จับสักตัว** และแย่กว่าไม่มีระบบล้าง เพราะมันดู "มีระบบล้างทำงานอยู่"
      อาการจริงที่จะเจอ: กด "ซิงก์เดี๋ยวนี้" แล้วตัวเลขไม่ขยับนานถึงหนึ่งนาที

   ⇒ **กลับด้านกติกา** (ฝั่งท่อเสนอ): ล้างเมื่อคำขอ **ไม่ใช่เส้นที่เรารู้ว่าเป็นการอ่าน**
      ไม่ใช่ล้างเมื่อ "ไม่ใช่ GET" · GET ที่เขียนกับ GET ที่อ่านหน้าตาเหมือนกันเป๊ะจากฝั่งเบราว์เซอร์
      แต่เส้นที่ **เรา** แคชไว้เรารู้จักหมดอยู่แล้ว ⇒ ที่เหลือทั้งโลกตกไปทาง "ล้าง" เอง
      **ของใหม่ทุกตัวปลอดภัยโดยอัตโนมัติ ไม่ต้องมีใครจำมาเติม**
      หลักการเดียวกับที่ฝั่งท่อใช้กับ `list=` ที่ไม่รู้จัก — **ตัดสินที่บรรทัดท้ายสุด
      ไม่ใช่จากรายชื่อ** ของที่ต้องจำมาเติมเองคือของที่จะถูกลืม

   ⚠️ ล้าง**ทั้งกอง** ไม่ใช่เฉพาะเส้นที่ยิง — รับของเข้าใบเดียวกระทบจอสต็อก · จอสินค้า ·
      จอหน้าแรก · จอรายงาน พร้อมกัน จอไหนกระทบบ้างไม่มีใครรู้ครบ
   ⚠️ ล้าง**ก่อน**ยิง ไม่ใช่หลัง — ยิงแล้วเน็ตหลุดกลางทางก็ยังต้องถือว่าข้อมูลเปลี่ยนแล้ว
      (เซิร์ฟเวอร์อาจบันทึกไปแล้วแต่คำตอบไม่กลับมา) ทิ้งของเก่าดีกว่าเสี่ยงโชว์เลขก่อนบันทึก
   ⚠️ ห่อครั้งเดียว — โมดูลถูก import จากหลายจอ ถ้าห่อซ้ำจะซ้อนกันเป็นชั้น ๆ */
declare global { interface Window { __gucutCacheHooked?: boolean } }

if (typeof window !== 'undefined' && !window.__gucutCacheHooked) {
  window.__gucutCacheHooked = true
  const real = window.fetch.bind(window)
  window.fetch = (input: RequestInfo | URL, init?: RequestInit) => {
    try {
      const method = (init?.method ?? (input instanceof Request ? input.method : 'GET')).toUpperCase()
      const url = String(input instanceof Request ? input.url : input)
      if (url.includes('/api/')) {
        /* ล้าง **เว้นแต่** จะเป็นการอ่านที่เรารู้จักอยู่แล้ว
           - ไม่ใช่ GET/HEAD → ล้างแน่นอน
           - GET ที่ไม่เคยถูกประกาศว่าเป็นการอ่าน → **ถือว่าอาจเขียน** ล้างไว้ก่อน
             (ครอบคลุม sync · snapshot · backup · restore ฯลฯ ที่สั่งด้วย GET ได้)
           ⚠️ จอที่ใช้แคชจะเรียก peek ก่อน fetch เสมอ ⇒ เส้นของมันขึ้นทะเบียนทันตั้งแต่ครั้งแรก
              **ไม่มีช่วงอุ่นเครื่องที่จอล้างแคชกันเอง** (ฝั่งท่อทักจุดนี้ 5 ก.ย. 2569)
              **พลาดไปทางล้างเกิน ไม่ใช่ล้างขาด** — ช้าเกินแก้ได้ ตัวเลขผิดแก้ไม่ได้ */
        const isKnownRead = (method === 'GET' || method === 'HEAD') && knownReads.has(url)
        if (!isKnownRead) clearApiCache()
      }
    } catch {
      /* อ่านคำขอไม่ออก = ล้างไว้ก่อน ปลอดภัยกว่าเก็บของที่อาจเก่า
         ⚠️ ห้ามปล่อยให้ error ตรงนี้ทำให้ fetch พัง — จะพังทั้งเว็บเพราะเรื่องแคช */
      clearApiCache()
    }
    /* ═ ชั้นที่สอง: เซิร์ฟเวอร์บอกเองว่า "คำขอนี้เขียนข้อมูลไปจริง" ═
       ฝั่งท่อติดธง `x-wrote` ที่ชั้น SQL (จุดเดียวกับที่นับ x-d1-count) 5 ก.ย. 2569
       ⇒ ครอบทุก endpoint **ทั้งที่มีตอนนี้และที่จะเพิ่มทีหลัง** โดยไม่มีใครต้องมาบอกจอ

       ทำไมต้องมีทั้งสองชั้นทั้งที่ชั้นแรกจับ 10 ตัวนั้นได้หมดแล้ว:
         ชั้นแรกตัดสินจาก **URL ก่อนยิง** ⇒ ตาบอดกับกรณี "เส้นที่เรานับว่าเป็นการอ่าน
         ดันไปเขียนอะไรบางอย่าง" (เช่นเส้นอ่านที่แอบเติมข้อมูลย้อนหลังให้ตอนถูกเรียก)
         ชั้นนี้ตัดสินจาก **สิ่งที่เกิดขึ้นจริง** จึงจับได้
       ⚠️ ฝั่งท่อส่งหัวนี้เฉพาะตอนเขียนจริง ไม่ส่ง 0 ⇒ **เช็คแค่ว่ามีหัวไหมพอ** ห้ามเทียบค่า
       ⚠️ ห้ามเปลี่ยนคำตอบหรือกลืน error — ห่อด้วย .then ที่คืนตัวเดิมเสมอ
          เรื่องแคชต้องไม่มีวันทำให้คำขอของจอพัง */
    return real(input, init).then((res) => {
      try {
        if (res.headers.has('x-wrote')) {
          /* 🔔 **ถ้าเส้นที่เราขึ้นทะเบียนว่า "อ่านล้วน" ตอบธงนี้กลับมา = เจอรูของกติกาหลัก**
             แปลว่ามีเส้นอ่านที่แอบเขียน ซึ่งกติกากลับด้านมองไม่เห็น (มันดู URL ก่อนยิง)
             ⇒ ล้างให้ปลอดภัยไว้ก่อน **แล้วต้องร้องดัง ๆ ด้วย** ไม่ใช่ล้างเงียบ ๆ
                ล้างเงียบ = อาการหายแต่สาเหตุอยู่ต่อ แล้วไม่มีใครรู้ว่ามีเส้นแบบนี้อยู่
             (ฝั่งท่อเสนอให้ใช้ธงนี้เป็นสัญญาณเตือน 5 ก.ย. 2569 — ถูกกว่าเอาไปตัดสินการล้าง) */
          const url = String(input instanceof Request ? input.url : input)
          if (knownReads.has(url)) {
            console.warn(
              '[แคชในจอ] เส้นที่นับว่า "อ่านอย่างเดียว" ดันเขียนข้อมูล — เอาออกจากรายการที่แคชด่วน:',
              url,
            )
          }
          clearApiCache()
        }
      } catch { /* อ่านหัวไม่ได้ก็ช่างมัน ชั้นแรกยังทำงานอยู่ */ }
      return res
    })
  }
}

/** ข้อความบอกอายุข้อมูลแบบคนอ่านรู้เรื่อง — "12 วินาทีที่แล้ว"
 *  ⚠️ ต้องพูดเป็น "เมื่อกี้" ไม่ใช่เวลานาฬิกา เพราะประเด็นคือ **เก่าแค่ไหน** ไม่ใช่ตอนไหน */
export function ageText(ms: number): string {
  const s = Math.max(0, Math.round(ms / 1000))
  if (s < 5) return 'เมื่อครู่'
  if (s < 60) return `${s} วินาทีที่แล้ว`
  const m = Math.round(s / 60)
  return `${m} นาทีที่แล้ว`
}
