// ทำไมต้องมี: ฝั่งท่อวัดมาแล้ว (5 ก.ย. 2569) เวลาของ /api/core =
//   **1.1 วิคงที่ + 0.27 วิต่อการยิงฐานหนึ่งรอบ** (เส้นตรงเป๊ะ ยิงครั้งละ 5 รอบเอาค่ากลาง)
// 1.1 วินาทีนั้นคือเน็ตจากเครื่องคนดู + ปลุกฟังก์ชัน ⇒ **ต่อให้ API เร็วที่สุดในโลกก็ยังเสีย 1.1 วิ**
// เจ้าของร้านสั่ง "ทำเร็วสุด ๆ" แต่ไม่ย้ายโฮสต์ ⇒ ทางเดียวที่ลงต่ำกว่า 1.1 วิได้คือ **ไม่ยิงเลย**
// นั่นคือหน้าที่ของไฟล์นี้ — กดสลับเมนูไปมาไม่ควรจ่ายราคาเต็มทุกครั้ง
//
// ⚠️ ราคาที่ต้องจ่ายคือ "ตัวเลขเก่า" ซึ่ง**อันตรายกว่าช้า** — จอที่โชว์เลขเก่าหน้าตาปกติทุกประการ
//    กติกาข้างล่างจึงไม่ใช่ข้อเสนอแนะ ทุกข้อมีเหตุการณ์รองรับ ห้ามถอดข้อไหนออก

/** อายุสูงสุดที่ยังยอมให้ใช้ของเก่า — เกินนี้ถือว่าไม่มีแคช โหลดใหม่ตามปกติ */
export const CACHE_MAX_AGE = 60_000

interface Entry { at: number; data: unknown }

/** ⚠️ **หน่วยความจำเท่านั้น ห้ามย้ายไป localStorage/sessionStorage เด็ดขาด**
 *  ของในนี้ตายพร้อมการรีเฟรชหน้า ⇒ "กดรีเฟรช = ได้ของสดเสมอ" เป็นทางออกที่คนใช้เดาได้เอง
 *  ถ้าเก็บลงเครื่อง ข้อมูลจะข้ามวัน ข้ามรอบ deploy ข้ามการเปลี่ยนรูปข้อมูลของท่อ
 *  แล้วจะมีจอที่โชว์เลขของเมื่อวานโดยไม่มีใครหาสาเหตุเจอ */
const mem = new Map<string, Entry>()

/** ของเก่าที่ยังใช้ได้ — ไม่มี/เก่าเกินไป คืน null
 *
 *  ⚠️ **คีย์คือ URL เต็มรวมพารามิเตอร์ทุกตัว** (store · from · to · q · status · limit · offset)
 *     ตัดพารามิเตอร์ออกจากคีย์เมื่อไหร่ = สลับตัวกรองแล้วเห็นข้อมูลของตัวกรองก่อนหน้า
 *     **ตัวเลขผิดที่หน้าตาปกติทุกประการ** ⇒ ห้ามทำคีย์แบบ "เอาแค่ชื่อ list" เด็ดขาด */
export function peekApiCache<T = unknown>(
  url: string,
  maxAgeMs: number = CACHE_MAX_AGE,
): { data: T; ageMs: number } | null {
  const e = mem.get(url)
  if (!e) return null
  const ageMs = Date.now() - e.at
  if (ageMs > maxAgeMs) { mem.delete(url); return null }
  return { data: e.data as T, ageMs }
}

/** เก็บคำตอบไว้ใช้รอบหน้า
 *
 *  ⚠️ **ห้ามเก็บคำตอบที่ผิดพลาด** — ความผิดพลาดชั่วคราวจะค้างบนจอ 60 วินาที
 *     แล้วกดรีเฟรชก็ไม่หาย เพราะรีเฟรชไปเจอของเก่าตัวเดิม
 *     ⇒ ด่านอยู่ตรงนี้ที่เดียว จอเรียกผิดพลาดยังไงก็เก็บของเสียไม่ได้ */
export function putApiCache(url: string, data: unknown): void {
  if (!data || typeof data !== 'object') return
  const d = data as Record<string, unknown>
  if (d.error || d.ok === false || d.skip) return
  mem.set(url, { at: Date.now(), data })
}

/** ล้างทั้งกอง — เรียกหลัง**เขียนข้อมูล**ทุกครั้ง
 *
 *  ⚠️ **ต้องล้างทั้งกอง ไม่ใช่เฉพาะเส้นของจอที่กด** — รับของเข้าใบเดียวกระทบ
 *     จอสต็อก · จอสินค้า · จอหน้าแรก · จอรายงาน พร้อมกัน
 *     ล้างเฉพาะจุดเมื่อไหร่ จะมีจอที่โชว์เลขก่อนบันทึกอยู่อีกนาที แล้วคนกดบันทึกซ้ำ */
export function clearApiCache(): void {
  mem.clear()
}

/* ═══ ล้างแคชอัตโนมัติเมื่อมีการเขียนข้อมูล ═══════════════════════════════
   ⚠️ **ตั้งใจไม่ทำเป็น "ไล่เติม clearApiCache() ทุกจุดที่เขียน"**
      ตอนเขียนไฟล์นี้มีจุดเขียนข้อมูล 20 กว่าจุดใน 15 ไฟล์ ⇒ ไล่เติมมือได้ครบวันนี้
      แต่**คนที่เพิ่มปุ่มบันทึกปุ่มถัดไปจะลืม** แล้วจะได้จอที่โชว์เลขก่อนบันทึกอยู่อีกนาที
      โดยไม่มีอะไรฟ้อง — คนกดจะกดบันทึกซ้ำ

   ⇒ ดักที่ประตูแทน: คำขอที่**ไม่ใช่ GET** ไปที่ `/api/` ล้างแคชทั้งกองเสมอ
      หลักการเดียวกับที่ฝั่งท่อใช้กับ `list=` ที่ไม่รู้จัก — **ตัดสินที่บรรทัดท้ายสุด
      ไม่ใช่จากรายชื่อ** ของที่ต้องจำมาเติมเองคือของที่จะถูกลืม

   ⚠️ ล้าง**ทั้งกอง** ไม่ใช่เฉพาะเส้นที่ยิง — รับของเข้าใบเดียวกระทบจอสต็อก · จอสินค้า ·
      จอหน้าแรก · จอรายงาน พร้อมกัน จอไหนกระทบบ้างไม่มีใครรู้ครบ
   ⚠️ ล้าง**ก่อน**ยิง ไม่ใช่หลัง — ยิงแล้วเน็ตหลุดกลางทางก็ยังต้องถือว่าข้อมูลเปลี่ยนแล้ว
      (เซิร์ฟเวอร์อาจบันทึกไปแล้วแต่คำตอบไม่กลับมา) ทิ้งของเก่าดีกว่าเสี่ยงโชว์เลขก่อนบันทึก
   ⚠️ ห่อครั้งเดียว — โมดูลถูก import จากหลายจอ ถ้าห่อซ้ำจะซ้อนกันเป็นชั้น ๆ */
declare global { interface Window { __gucutCacheHooked?: boolean } }

if (typeof window !== 'undefined' && !window.__gucutCacheHooked) {
  window.__gucutCacheHooked = true
  const real = window.fetch.bind(window)
  window.fetch = (input: RequestInfo | URL, init?: RequestInit) => {
    try {
      const method = (init?.method ?? (input instanceof Request ? input.method : 'GET')).toUpperCase()
      const url = String(input instanceof Request ? input.url : input)
      if (method !== 'GET' && method !== 'HEAD' && url.includes('/api/')) clearApiCache()
    } catch {
      /* อ่านคำขอไม่ออก = ล้างไว้ก่อน ปลอดภัยกว่าเก็บของที่อาจเก่า
         ⚠️ ห้ามปล่อยให้ error ตรงนี้ทำให้ fetch พัง — จะพังทั้งเว็บเพราะเรื่องแคช */
      clearApiCache()
    }
    return real(input, init)
  }
}

/** ข้อความบอกอายุข้อมูลแบบคนอ่านรู้เรื่อง — "12 วินาทีที่แล้ว"
 *  ⚠️ ต้องพูดเป็น "เมื่อกี้" ไม่ใช่เวลานาฬิกา เพราะประเด็นคือ **เก่าแค่ไหน** ไม่ใช่ตอนไหน */
export function ageText(ms: number): string {
  const s = Math.max(0, Math.round(ms / 1000))
  if (s < 5) return 'เมื่อครู่'
  if (s < 60) return `${s} วินาทีที่แล้ว`
  const m = Math.round(s / 60)
  return `${m} นาทีที่แล้ว`
}
