export type ผลช่องทาง = {
  ช่องทาง: string
  /** เวลารอบกวาดล่าสุด (ISO UTC จากท่อ) · null = ท่อไม่ได้จด */
  at: string | null
  /** ผ่านมากี่ชั่วโมง · null = ไม่รู้ */
  ชม: number | null
  /** true = เกินเกณฑ์ · false = ปกติ · null = ตัดสินไม่ได้ */
  หยุด: boolean | null
}

export type ผลดันสต็อก = {
  สถานะ: 'หยุด' | 'ไม่รู้' | 'ปกติ'
  เกณฑ์ชม: number | null
  ราย: ผลช่องทาง[]
  /** เหตุที่สรุปว่าไม่รู้ (ไว้เขียนบนจอ) */
  เหตุไม่รู้?: string
}

export function อ่านสถานะดันสต็อก(j: unknown, nowMs: number = Date.now()): ผลดันสต็อก {
  const o = j as { byChannel?: Record<string, { lastSweep?: { at?: unknown }; autoOn?: unknown; 'มีตัวยิง'?: unknown }>; 'ค้างนานเกณฑ์ชั่วโมง'?: unknown } | null
  if (!o || typeof o !== 'object' || !o.byChannel || typeof o.byChannel !== 'object') {
    return { สถานะ: 'ไม่รู้', เกณฑ์ชม: null, ราย: [], เหตุไม่รู้: 'อ่านสถานะการดันสต็อกไม่ได้' }
  }
  const เกณฑ์ = typeof o['ค้างนานเกณฑ์ชั่วโมง'] === 'number' && o['ค้างนานเกณฑ์ชั่วโมง'] > 0 ? o['ค้างนานเกณฑ์ชั่วโมง'] as number : null
  const ราย: ผลช่องทาง[] = []
  for (const [ช่องทาง, v] of Object.entries(o.byChannel)) {
    if (v?.['มีตัวยิง'] === false || v?.autoOn === false) continue
    const at = typeof v?.lastSweep?.at === 'string' ? v.lastSweep.at : null
    const t = at ? Date.parse(at) : NaN
    const ชม = Number.isFinite(t) ? (nowMs - t) / 3600e3 : null
    const หยุด = ชม === null || เกณฑ์ === null ? null : ชม > เกณฑ์
    ราย.push({ ช่องทาง, at, ชม, หยุด })
  }
  if (ราย.some((r) => r.หยุด === true)) return { สถานะ: 'หยุด', เกณฑ์ชม: เกณฑ์, ราย }
  if (ราย.length === 0) return { สถานะ: 'ไม่รู้', เกณฑ์ชม: เกณฑ์, ราย, เหตุไม่รู้: 'ท่อไม่ได้บอกช่องทางที่ดันสต็อกอัตโนมัติเลย' }
  if (เกณฑ์ === null) return { สถานะ: 'ไม่รู้', เกณฑ์ชม: null, ราย, เหตุไม่รู้: 'ท่อไม่ได้ส่งเกณฑ์ว่ากี่ชั่วโมงถือว่าหยุด' }
  if (ราย.some((r) => r.หยุด === null)) return { สถานะ: 'ไม่รู้', เกณฑ์ชม: เกณฑ์, ราย, เหตุไม่รู้: 'บางช่องทางไม่มีเวลารอบล่าสุด' }
  return { สถานะ: 'ปกติ', เกณฑ์ชม: เกณฑ์, ราย }
}

