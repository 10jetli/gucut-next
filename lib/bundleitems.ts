/* 🧩 อ่านคำตอบ `?list=bundleitems` แบบไม่เดา — ตัวร่วมของ จอรายละเอียดสินค้า (member=) · จอรายละเอียดชุด (sku=)
 *
 * 🔴 `rows: []` ของเส้นนี้มี 4 ความหมายที่แยกจากแถวไม่ได้ (CEO ไล่ของจริง 21 ต.ค. 2569 · ใบ 17:56):
 *    ① โหมดสรุปรวมไม่คืนแถวโดยตั้งใจ ② ชุดมีจริงแต่สูตรว่าง ③ ชุดไม่มีจริง ④ รหัสไม่มีจริง
 *    ⇒ **ห้ามใช้ rows.length ตัดสินว่า "ไม่มี"** — ต้องดู `asked.exists` ก่อน (ท่อ 8fc11160 ถามจากทะเบียนสินค้า ไม่ใช่ตารางสูตร)
 * 🔑 สามสถานะของช่อง: ท่อรุ่นเก่าไม่ส่ง `asked` (ไม่มีคีย์) ≠ ส่งมาเป็น null (โหมดนี้ไม่ได้ถามของชิ้นใด) ≠ true/false
 *    — เช็คด้วย `'asked' in resp` ไม่ใช่ `resp.asked ?? …` (ยุบ "ไม่ส่ง" กับ "ว่าง" รวมกัน) */

export interface BundleItemsAsked {
  kind?: string
  sku?: string
  /** true = ทะเบียนสินค้ารู้จักรหัสนี้ · false = ไม่รู้จัก · null = โหมดนี้ไม่ได้ถามถึงของชิ้นใด */
  exists: boolean | null
  source?: string
}

export type สภาพแถวชุด =
  | { ชนิด: 'มีแถว'; จำนวน: number }
  /** รหัสที่ถามไม่มีในทะเบียนสินค้า — ห้ามเขียนว่า "ไม่มีสินค้าในชุด"/"ไม่อยู่ในชุดไหน" */
  | { ชนิด: 'ไม่รู้จักรหัส'; รหัส: string }
  /** รู้จักรหัส และคืนแถวแล้วแต่ 0 แถว = ว่างจริง */
  | { ชนิด: 'ว่างจริง' }
  /** ท่อรุ่นนี้ยังไม่ส่ง asked ⇒ แยก ว่างจริง / ไม่มีรหัสนี้ ไม่ได้ (ห้ามเดาว่าว่าง) */
  | { ชนิด: 'ยังแยกไม่ได้' }

/** ตัดสินจากคำตอบดิบของท่อ (ไม่ใช่จากแถวที่จอกรองแล้ว) */
export function สภาพแถวชุด(resp: unknown): สภาพแถวชุด {
  const r = (resp && typeof resp === 'object' ? resp : {}) as Record<string, unknown>
  const rows = Array.isArray(r.rows) ? r.rows : []
  if (rows.length > 0) return { ชนิด: 'มีแถว', จำนวน: rows.length }
  if (!('asked' in r)) return { ชนิด: 'ยังแยกไม่ได้' }
  const a = r.asked as BundleItemsAsked | null
  if (a && a.exists === false) return { ชนิด: 'ไม่รู้จักรหัส', รหัส: String(a.sku ?? '') }
  if (a && a.exists === true) return { ชนิด: 'ว่างจริง' }
  return { ชนิด: 'ยังแยกไม่ได้' }
}
