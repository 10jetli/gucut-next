/** รูปแถวเท่าที่ตรรกะนี้ต้องใช้ — จอส่งแถวเต็มมาได้เลย */
export interface แถวงานที่มีผลย่อย {
  'ผลย่อยรอบล่าสุด'?: { 'สำเร็จ'?: number; 'ล้ม'?: number } | null
}

export interface ผลย่อยที่อ่านได้ {
  ok: number
  fail: number
}

/** อ่านผลย่อยแบบสามสถานะ — คืน `null` เมื่อ **ไม่ได้นับชิ้น** (รวมถึงค่าที่ไม่ใช่ตัวเลข)
 *  ⚠️ ห้ามแปลงเป็น 0 ไม่ว่ากรณีใด */
export function อ่านผลย่อย(x: แถวงานที่มีผลย่อย | null | undefined): ผลย่อยที่อ่านได้ | null {
  const v = x?.['ผลย่อยรอบล่าสุด']
  if (!v || typeof v !== 'object') return null
  const ok = Number(v['สำเร็จ'])
  const fail = Number(v['ล้ม'])
  /* ต้องเป็นตัวเลขทั้งคู่ — มาครึ่งเดียวคือรูปคำตอบไม่ใช่อย่างที่ตกลง ⇒ ถือว่ายังไม่รู้ */
  return Number.isFinite(ok) && Number.isFinite(fail) ? { ok, fail } : null
}

/** งานที่ **รอบล่าสุดทำไม่ครบ** — ตัวเลขที่ต้องถูกยกขึ้นหัวจอ
 *  (ตัวเลขที่อยู่แต่ในตารางคือตัวเลขที่ไม่มีใครมอง ซึ่งคือเหตุที่ช่องนี้เงียบมา 8 วัน) */
export function งานที่รอบล่าสุดไม่ครบ<T extends แถวงานที่มีผลย่อย>(rows: T[] | null | undefined): T[] {
  if (!Array.isArray(rows)) return []
  return rows.filter((x) => (อ่านผลย่อย(x)?.fail ?? 0) > 0)
}
