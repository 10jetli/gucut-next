// อ่านก้อน `clamped` ที่ท่อส่งมาเมื่อมันปรับค่าที่จอขอให้อยู่ในขอบ
//
// 🔴 **ที่มา (28 ก.ย. 2569)** — มาจากบั๊กของจอ /import ของเราเอง:
//    ค่าที่ระบบไม่รับ **กลับไปใช้ค่าเดิมเงียบ ๆ** ตอบสำเร็จ และช่องกรอกยังโชว์เลขที่พิมพ์
//    ⇒ คนได้ความเชื่อผิดเรื่องสถานะที่เก็บไว้ · CEO สรุปคลาสนี้ว่า
//      **"ค่าที่ถูกปฏิเสธต้องเดินทางกลับมาหาคนกรอก"** แล้วต่อ `clamped` ให้ 4 เส้น
//    (list=stock · deadstock · stockcard · channel-gaps)
//
// 🔑 **สองอย่างที่ต้องแยกให้ขาด**
//    · `clamped` = ท่อ **ปรับค่าให้อยู่ในขอบ** แล้วเดินต่อ (เกินเพดาน · ต่ำกว่าขั้นต่ำ · อ่านเป็นเลขไม่ได้ · มีเศษ)
//    · **ปฏิเสธ** = ท่อไม่ยอมรับเลย ⇒ ตอบ 400 พร้อมเหตุ ⇒ **ไม่มาอยู่ในก้อนนี้**
//    ⇒ จอห้ามเขียนว่า "ถูกปฏิเสธ" กับสิ่งที่อยู่ในก้อนนี้ เพราะคำขอนั้นสำเร็จ แค่ค่าไม่ใช่ของเรา
//
// ⚠️ **ไม่มีการบีบ = ไม่มีคีย์เลย** (ไม่ใช่คีย์ว่าง) ⇒ เช็ค "มีคีย์ไหม" ได้ตรง ๆ
// ⚠️ **ไม่ได้ส่งมา ≠ ถูกบีบ** — ท่อไม่รายงานช่องที่จอไม่ได้ส่ง (ไม่งั้นทุกคำขอมีบันทึกเต็มจนคนเลิกอ่าน)

/** บันทึกการบีบของหนึ่งช่อง — รูปนี้ฝั่งจอขอเอง: ต้องมี asked · used · why ครบในที่เดียว */
export interface บันทึกการบีบ {
  asked?: unknown
  used?: unknown
  why?: string
}

export interface คำตอบที่อาจถูกบีบ {
  clamped?: Record<string, บันทึกการบีบ> | null
  applied?: Record<string, unknown> | null
}

/** หนึ่งบรรทัดที่จอจะเขียน — `why` เป็น null แปลว่า **ท่อบีบแต่ยังไม่บอกเหตุ** (ท่อรุ่นเก่า) */
export interface บรรทัดการบีบ {
  'ช่อง': string
  'ที่ขอ': string
  'ที่ใช้': string
  'เหตุ': string | null
}

const เป็นข้อความ = (v: unknown) =>
  v === null || v === undefined ? '(ไม่ได้ส่ง)' : typeof v === 'object' ? JSON.stringify(v) : String(v)

/** อ่านจากก้อน `clamped` ที่ท่อส่งมา — ไม่มีก้อน ⇒ คืนรายการว่าง (ไม่ใช่ข้อผิดพลาด) */
export function อ่านการบีบ(resp: คำตอบที่อาจถูกบีบ | null | undefined): บรรทัดการบีบ[] {
  const ก้อน = resp?.clamped
  if (!ก้อน || typeof ก้อน !== 'object') return []
  const out: บรรทัดการบีบ[] = []
  for (const [ช่อง, v] of Object.entries(ก้อน)) {
    if (!v || typeof v !== 'object') continue
    out.push({
      'ช่อง': ช่อง,
      'ที่ขอ': เป็นข้อความ(v.asked),
      'ที่ใช้': เป็นข้อความ(v.used),
      /* เหตุที่เป็นช่องว่างนับเป็น "ไม่บอกเหตุ" — จอต้องไม่แต่งเหตุให้เอง */
      'เหตุ': v.why && String(v.why).trim() ? String(v.why) : null,
    })
  }
  return out
}

/* 🔑 **ทางถอยสำหรับท่อรุ่นที่ยังไม่มี `clamped`**
   `applied` บอกได้แค่ "ค่าที่ท่อใช้" ⇒ จอเทียบกับค่าที่ส่งไปเองได้ว่าต่างไหม
   **แต่จอไม่รู้ว่าทำไม** ⇒ ต้องเขียนว่า "ท่อบีบค่า แต่ยังไม่บอกเหตุ" ห้ามแต่งเหตุ
   (ถ้าจอแต่งเหตุเอง เราจะได้คำอธิบายสองชุดในระบบ — คลาสเดียวกับเรื่องป้ายที่มาของเลขสต็อก) */
export function เทียบขอกับใช้(
  ขอ: Record<string, unknown> | null | undefined,
  resp: คำตอบที่อาจถูกบีบ | null | undefined,
): บรรทัดการบีบ[] {
  if (resp?.clamped) return []           // ท่อรายงานเองแล้ว ⇒ ไม่ต้องเดาซ้ำ
  const applied = resp?.applied
  if (!ขอ || !applied || typeof applied !== 'object') return []
  const out: บรรทัดการบีบ[] = []
  for (const [ช่อง, ค่า] of Object.entries(ขอ)) {
    if (ค่า === null || ค่า === undefined || ค่า === '') continue   // ไม่ได้ส่ง ⇒ ไม่ใช่การบีบ
    if (!(ช่อง in applied)) continue                                // ท่อไม่ได้ประกาศช่องนี้ ⇒ ไม่รู้ ห้ามเดา
    const ใช้ = applied[ช่อง]
    if (ใช้ === null || ใช้ === undefined) continue                  // ท่อบอกว่าไม่ได้กรองด้วยช่องนี้
    if (String(ใช้) === String(ค่า)) continue
    out.push({ 'ช่อง': ช่อง, 'ที่ขอ': เป็นข้อความ(ค่า), 'ที่ใช้': เป็นข้อความ(ใช้), 'เหตุ': null })
  }
  return out
}
