// รู้ให้ได้ว่า "คำตอบที่ได้มา มาจากเส้นที่เราตั้งใจถามจริงไหม"
//
// 🔴 **ปัญหาจริงที่ทำให้ต้องมีไฟล์นี้** (ฝั่งท่อเจอกับตัว 6 ก.ย. 2569)
//    `/api/core` ที่เจอพารามิเตอร์ที่ยังไม่รู้จัก **ไม่ตอบ 404** แต่ตกไปที่ "คำตอบหน้าแรก"
//    พร้อม HTTP 200 ⇒ จอที่เช็คแค่ `res.ok` หรือ `!data.error` จะคิดว่าสำเร็จ
//    แล้วไปอ่านฟิลด์ที่ไม่มี ได้ `undefined` ⇒ **ตีความว่า "ไม่มีข้อมูล"**
//    ซึ่งอ่านบนจอแล้วเหมือน "ตรวจแล้วไม่เจออะไร" ทั้งที่ความจริงคือ **ยังไม่ได้ถามด้วยซ้ำ**
//
// ⚠️ ตัวตรวจของฝั่งท่อขึ้นเขียวจากเส้นที่ยังไม่มีอยู่จริงมาแล้ว —
//    **แย่กว่าไม่มีตัวตรวจ เพราะมันสร้างหลักฐานปลอมว่าตรวจแล้ว**
//
// ⇒ กติกา: **ก่อนตีความเนื้อคำตอบ ต้องพิสูจน์ก่อนว่าคำตอบมาจากเส้นที่ตั้งใจถาม**

/** คำตอบนี้คือ "คำตอบหน้าแรก" ที่ `/api/core` ตกมาเมื่อไม่รู้จักพารามิเตอร์หรือเปล่า
 *
 *  🟢 **ทางที่ถูกต้อง: ธง `fallthrough: true`** — ฝั่งท่อตกลงใส่ให้ตั้งแต่ deploy 6 ก.ย. 2569
 *     เป็น**สัญญาระหว่างสองฝั่ง**: ห้ามลบ ห้ามเปลี่ยนชื่อ และห้ามใส่ในคำตอบของเส้นอื่น
 *
 *  ⚠️ **ยังคงทางเดาจากรูปไว้ด้วยโดยตั้งใจ** จนกว่าธงจะขึ้นเว็บจริง
 *     ถอดก่อน = จอ 4 จุดตาบอดทันทีในช่วงคาบเกี่ยว (ของบนเว็บยังไม่มีธง)
 *     ⇒ **ตัดทางเดาทิ้งได้หลังฝั่งท่อยืนยันว่า deploy ขึ้นแล้วเท่านั้น**
 *     ทางเดาไม่แม่น: คีย์เดียวอาจบังเอิญตรงกับเส้นอื่น จึงต้องเจอ 3 ใน 6 */
export function looksLikeFallThrough(d: unknown): boolean {
  if (!d || typeof d !== 'object') return false
  const o = d as Record<string, unknown>
  // ① ธงจากฝั่งท่อ — แน่นอนที่สุด
  if (o.fallthrough === true) return true
  // ② ทางเดาจากรูป — ของชั่วคราวช่วงคาบเกี่ยว
  const marks = ['ready', 'counts', 'recon', 'channels', 'shopee', 'stock']
  return marks.filter((k) => k in o).length >= 3
}

/** คำตอบนี้ใช้ได้ไหม — ต้องมีคีย์ที่ **เฉพาะเส้นนั้นเท่านั้นที่ส่ง** อย่างน้อยหนึ่งตัว
 *
 *  ⚠️ ห้ามใช้ `ok` เป็นเครื่องพิสูจน์เดี่ยว ๆ — เส้นเกือบทุกเส้นส่ง `ok: true` เหมือนกันหมด
 *     (คำตอบหน้าแรกบังเอิญไม่มี `ok` ในวันนี้ แต่นั่นคือ **ความบังเอิญ ไม่ใช่สัญญา**
 *      วันที่ฝั่งท่อเติม `ok` เข้าไป จอทุกจอที่พึ่ง `ok` จะเชื่อผิดพร้อมกันโดยไม่มีอะไรฟ้อง)
 *
 *  @param required คีย์ที่เป็นลายเซ็นของเส้นนั้นจริง ๆ (ต้องมีอย่างน้อยหนึ่ง)
 */
export function fromExpectedEndpoint(d: unknown, required: string[]): boolean {
  if (!d || typeof d !== 'object') return false
  if (looksLikeFallThrough(d)) return false
  const o = d as Record<string, unknown>
  return required.some((k) => k in o)
}

/* ── ทางที่แน่นที่สุด: หัวข้อมูล `x-core-build` ────────────────────────────
   ฝั่งท่อติดหัวนี้ให้ **ทุกคำตอบ** ของ /api/core ตั้งแต่ 6 ก.ย. 2569
   (ค่าคือเวลาที่ build ท่อรุ่นนั้น) · ท่อกลางส่งต่อหัวที่ขึ้นต้นด้วย x- อยู่แล้ว

   🔴 ทำไมดีกว่าเดาจาก body: **มันมากับทุกคำตอบโดยไม่ต้องมีใครจำ**
      สัญญาที่พึ่งความจำของคน (อย่าลืมใส่คีย์ · อย่าลืมบอกก่อนเปลี่ยนรูป)
      จะพลาดวันที่คนเหนื่อย — หัวข้อมูลไม่ต้องพึ่งใครจำ

   ตัดสินได้ 3 ทางแบบไม่กำกวม:
   · ไม่มีหัว           ⇒ ท่อรุ่นเก่ากว่า 6 ก.ย. (หรือไม่ใช่ท่อเรา) ⇒ **ยังบอกไม่ได้**
   · มีหัว + มีคีย์ที่ขอ ⇒ เส้นนั้นขึ้นแล้วและตอบจริง
   · มีหัว + ไม่มีคีย์   ⇒ ท่อรุ่นใหม่แล้ว **แต่เส้นนั้นไม่มีอยู่จริง** */

export interface CoreResult<T> {
  data: T | null
  /** คำตอบดิบ **เสมอ** แม้รูปไม่ตรงที่ขอ
   *  🔴 ต้องมี เพราะคำตอบที่ล้มเหลวจะไม่มีคีย์ประจำตัวของเส้นนั้น (มีแต่ `error`)
   *     ถ้าคืนแต่ `data` ที่กรองแล้ว จอจะไม่เห็นข้อความ error เลย
   *     แล้วขึ้นว่า "เส้นยังไม่ขึ้นเว็บ" ทั้งที่ความจริงคือ **เส้นขึ้นแล้วแต่ทำงานล้มเหลว**
   *     ⇒ ผิดคนละเรื่องกัน และพาคนไปรอ deploy ที่ไม่ได้แก้อะไร */
  raw: unknown
  /** ท่อรุ่นใหม่พอที่จะตัดสินได้ไหม (มีหัว x-core-build) */
  known: boolean
  /** เส้นที่ขอมีอยู่จริงและตอบมาไหม */
  ok: boolean
  build: string | null
}

export async function coreJson<T>(url: string, required: string[]): Promise<CoreResult<T>> {
  const res = await fetch(url)
  const build = res.headers.get('x-core-build')
  const data = (await res.json().catch(() => null)) as T | null
  const hit = fromExpectedEndpoint(data, required)
  return { data: hit ? data : null, raw: data, known: !!build, ok: hit, build }
}
