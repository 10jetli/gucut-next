/* ขอบเขตของการ "กรองในเบราว์เซอร์" — ครบทั้งชุดหรือไม่ (15 ต.ค. 2569)
 *
 * 🔴 CEO: "เงื่อนไขที่ทำให้โค้ดถูก ถ้าไม่ได้ถูกตรวจทุกครั้ง มันคือสมมติฐาน ไม่ใช่เงื่อนไข"
 *    จอรายการซื้อกรองในเบราว์เซอร์ได้ถูกเพราะ **วันนี้** ร้านมี 33 ใบ ≤ หนึ่งหน้า
 *    วันที่มี 500 ใบ จอจะกรองแค่หน้าแรกเงียบ ๆ แล้วบอกว่า "ไม่มีใบที่ตรง" ทั้งที่ใบตรงอยู่หน้าถัดไป
 *    ⇒ ฟังก์ชันนี้ตัดสิน **ทุกครั้งที่กรอง** และให้ข้อความจากที่เดียว (ข้อความกับตรรกะต้องมาจากที่เดียวกัน)
 *
 * 🔴 รูที่เจอระหว่างย้ายมาที่นี่: เดิมคิด `offset + โหลดมา >= ทั้งหมด` ⇒ อยู่หน้าสุดท้ายแล้วได้ "ครบ"
 *    ทั้งที่ในหน่วยความจำมีแค่แถวของหน้านั้น ⇒ "ครบ" ต้องเริ่มจากแถวแรก (offset 0) เท่านั้น
 *
 * ⚠️ สามสถานะ: ครบ · ไม่ครบ · **ไม่รู้** (ท่อไม่บอกยอดรวม) — ไม่รู้ ห้ามถือว่าครบ
 */
export type ขอบเขต = 'ครบ' | 'ไม่ครบ' | 'ไม่รู้'

export function ขอบเขตกรองในเครื่อง(o: { โหลดมา: number; ทั้งหมด: unknown; offset: number }): {
  ขอบเขต: ขอบเขต
  /** บรรทัดบอกขอบเขต — แสดงทุกครั้งที่มีตัวกรองในเบราว์เซอร์ */
  บรรทัด: string
  /** ข้อความเมื่อกรองแล้วไม่เจอ — ห้ามพูดว่า "ไม่มี" ถ้ายังไม่ได้ดูครบ */
  ไม่เจอ: string
} {
  const น = o.โหลดมา.toLocaleString('th-TH')
  if (typeof o.ทั้งหมด !== 'number' || !Number.isFinite(o.ทั้งหมด)) {
    return {
      ขอบเขต: 'ไม่รู้',
      บรรทัด: `กรองในเบราว์เซอร์จาก ${น} ใบที่โหลดมา · ยังไม่รู้ว่าทั้งชุดมีกี่ใบ (ท่อไม่ได้บอกจำนวน) ⇒ ยืนยันไม่ได้ว่ากรองครบทั้งชุด`,
      ไม่เจอ: `ไม่เจอใน ${น} ใบที่โหลดมา — ยังไม่รู้ว่าทั้งชุดมีกี่ใบ จึงบอกไม่ได้ว่าไม่มีจริง`,
    }
  }
  const ท = o.ทั้งหมด.toLocaleString('th-TH')
  if (o.offset === 0 && o.โหลดมา >= o.ทั้งหมด) {
    return {
      ขอบเขต: 'ครบ',
      บรรทัด: `กรองในเบราว์เซอร์ — โหลดมาครบทั้ง ${ท} ใบแล้ว จึงเท่ากับกรองทั้งชุด`,
      ไม่เจอ: `ทั้งหมด ${ท} ใบ ไม่มีใบไหนตรงเงื่อนไข — กด "ล้างเงื่อนไข" เพื่อดูทั้งหมด`,
    }
  }
  return {
    ขอบเขต: 'ไม่ครบ',
    บรรทัด: `⚠️ กรองในเบราว์เซอร์เฉพาะ ${น} จาก ${ท} ใบที่โหลดมา — ไม่ใช่ทั้งชุด ใบที่ตรงอาจอยู่หน้าอื่น`,
    ไม่เจอ: `ไม่เจอใน ${น} ใบที่โหลดมา (ทั้งชุดมี ${ท} ใบ) — ใบที่ตรงอาจอยู่หน้าอื่น ยังบอกไม่ได้ว่าไม่มี`,
  }
}
