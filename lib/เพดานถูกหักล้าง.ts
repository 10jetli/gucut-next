/* ตัวตัดสิน: **เลขเพดานที่ท่อประกาศ ถูกข้อมูลจริงหักล้างแล้วหรือยัง**
 *
 * 🔴 ที่มา (21 ก.ย. 2569) — จอ `SweepTiming` เขียนเป็นข้อเท็จจริงว่า
 *    *"ฟังก์ชันตามเวลาถูกตัดกลางทางเมื่อเกิน 30 วินาที"* โดยอ้างเลขที่ท่อส่งมา
 *    ⇒ **เป็นเท็จ** — สมุดของเราเองมีรอบ **56,374 ms ที่ทำงานจนจบและเขียนแถวสำเร็จ**
 *    ⇒ ⇒ คนอ่านจอจะเชื่อว่า "ใกล้ถูกตัดแล้ว" แล้วไปลดงาน/ลดความถี่ **ด้วยเส้นที่ไม่มีอยู่จริง**
 *
 * 🔑 กฎที่ยกเป็นกลไก: **ข้อมูลที่ขัดกับค่าคงที่ = ค่าคงที่ผิด ไม่ใช่ข้อมูลผิด**
 *    จอที่ถือ **ทั้งค่าคงที่และข้อมูล** ต้องเป็นคนบอกเองเมื่อสองอย่างขัดกัน
 *    ไม่ใช่รอให้มีคนมานั่งเทียบ (ของจริงรอบนี้กินเวลาสองวันกว่าจะมีคนสังเกต)
 *
 * ⚠️ ตาข่ายเดิมของจอดักไว้แค่กรณี **"ท่อไม่ส่งเพดานมา"** (⇒ ขึ้นคำเตือนค่าสำรอง)
 *    แต่กรณีที่เกิดจริงคือ **"ท่อส่งมา และเลขนั้นไม่ใช่เพดานจริง"** ⇒ ตาข่ายเงียบสนิท
 */

/** คืน ms ที่ยาวที่สุดซึ่ง **เกินเพดานแล้วยังทำงานจนจบ** · `null` = ไม่มีของขัดแย้ง
 *
 * @param msช้าสุดของแต่ละแถว เวลาที่ช้าที่สุดของแต่ละงาน/ช่อง (ms) — แถวที่มีอยู่ในสมุด
 *        ⇒ ทุกแถวในสมุด **คือรอบที่เขียนสำเร็จ** ⇒ การมีอยู่ของมันคือหลักฐานว่าไม่ได้ถูกตัด
 * @param เพดานMs เลขเพดานที่ท่อประกาศ (null/undefined = ไม่มีเลขให้หักล้าง)
 */
export function หาเพดานที่ถูกหักล้าง(
  msช้าสุดของแต่ละแถว: Array<number | null | undefined>,
  เพดานMs: number | null | undefined,
): number | null {
  if (typeof เพดานMs !== 'number' || !Number.isFinite(เพดานMs) || เพดานMs <= 0) return null
  const เกิน = msช้าสุดของแต่ละแถว
    .filter((ms): ms is number => typeof ms === 'number' && Number.isFinite(ms))
    .filter((ms) => ms > เพดานMs)
  return เกิน.length > 0 ? Math.max(...เกิน) : null
}
