// 🔑 **ทำไมต้องผ่านคิวที่ gucut.com ไม่ยิงตรงไป g1**
//    Hermes ไม่มีเส้น HTTP เลย (ฟังแต่ Telegram กับ CLI) — ถ้าจะยิงตรงต้องเปิดพอร์ต
//    ออกอินเทอร์เน็ตที่ g1 = เปิดช่องสั่งรันคำสั่งบนเครื่องที่ถือคีย์ร้านทั้งหมด
//    ⇒ กลับทิศ: ฝากไว้ที่ gucut.com แล้ว **g1 เป็นฝ่ายออกมาหยิบเอง**
//
// 🔑 **ไม่มีคีย์ใหม่** — ใช้ GUCUT_ADMIN_KEY ที่ฝั่งนี้มีอยู่แล้ว (ตัวเดียวกับที่ lib/returns.ts ใช้)
//
// ⚠️ ไม่มีคีย์ = ต้องบอกตรง ๆ ว่าส่งไม่ได้ **ห้ามตอบว่าสำเร็จ** — คนใส่แว่นจะนั่งรอผลที่ไม่มีวันมา

const SITE = 'https://gucut.com'

/** คำที่ใช้ขึ้นต้นเพื่อสั่ง Hermes — เลือกคำที่ตัวถอดเสียงไทยมักได้ถูก
 *  ⚠️ ต้องมีหลายรูป เพราะ **ตัวถอดเสียงสะกดชื่อเฉพาะเพี้ยนเป็นปกติ**
 *     ถ้ารับรูปเดียว ผู้ใช้จะพูดแล้วไม่ติดโดยไม่รู้ว่าเพราะอะไร */
const คำสั่ง = ['เฮอร์มีส', 'เฮอร์เมส', 'เฮอมีส', 'เฮอเมส', 'hermes', 'เฮอร์มิส']

/** ข้อความนี้สั่ง Hermes ไหม — คืนคำสั่งที่ตัดคำนำหน้าออกแล้ว หรือ null ถ้าไม่ใช่ */
export function แยกคำสั่งเฮอร์มีส(text: string): string | null {
  const t = (text || '').trim()
  if (!t) return null
  const low = t.toLowerCase()
  for (const k of คำสั่ง) {
    if (low.startsWith(k.toLowerCase())) {
      // ตัดคำนำหน้า + เครื่องหมายคั่นที่ตามมา (ช่องว่าง จุลภาค ทวิภาค)
      const เหลือ = t.slice(k.length).replace(/^[\s,:：]+/, '').trim()
      return เหลือ || null      // พูดแต่ชื่อเฉย ๆ ไม่นับเป็นคำสั่ง
    }
  }
  return null
}

/** ฝากคำสั่งเข้าคิว — คืนข้อความที่จะให้แว่นพูดกลับ */
export async function ฝากให้เฮอร์มีส(cmd: string): Promise<string> {
  const key = (process.env.GUCUT_ADMIN_KEY || '').trim()
  if (!key) return 'ส่งให้เฮอร์มีสไม่ได้ ยังไม่ได้ตั้งกุญแจฝั่งเซิร์ฟเวอร์'
  try {
    const r = await fetch(`${SITE}/api/core?hermesq=1`, {
      method: 'POST',
      headers: { 'x-admin-key': key, 'content-type': 'application/json' },
      body: JSON.stringify({ cmd, from: 'แว่น' }),
      signal: AbortSignal.timeout(12000),
    })
    const j = (await r.json().catch(() => null)) as
      | { ok?: boolean; id?: string; fallthrough?: boolean }
      | null
    // 🔴 ท่อที่ยังไม่มีช่องนี้จะตอบ "คำตอบหน้าแรก" พร้อม **HTTP 200**
    //    ⇒ ดูแต่รหัสสถานะ = คิดว่าฝากสำเร็จทุกครั้ง ทั้งที่คิวไม่เคยได้รับอะไร
    //    กติกาของท่อ: คำตอบหน้าแรกติดธง fallthrough:true ⇒ เช็คข้อเดียวนี้พอ
    if (j?.fallthrough) return 'ส่งให้เฮอร์มีสไม่ได้ ฝั่งเว็บยังไม่ได้อัปเดต'
    if (!r.ok || !j?.ok) return 'ส่งให้เฮอร์มีสไม่สำเร็จ ลองใหม่อีกครั้ง'
    return 'รับคำสั่งแล้ว ส่งให้เฮอร์มีสทำต่อ ผลจะเข้าเทเลแกรม'
  } catch {
    return 'ส่งให้เฮอร์มีสไม่ได้ ติดต่อเซิร์ฟเวอร์ไม่สำเร็จ'
  }
}
