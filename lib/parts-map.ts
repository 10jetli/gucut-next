/** ล้างรหัสอะไหล่ — ต้องเท่ากับ `ล้างรหัส` ของเซิร์ฟเวอร์: ตัดช่องว่างทุกชนิด · ตัวใหญ่ · ≤24 */
export function ล้างรหัส(v: unknown): string {
  return String(v ?? '').replace(/\s+/g, '').toUpperCase().slice(0, 24)
}

/** ล้างรหัสสินค้าร้าน — ต้องเท่ากับ `ล้างsku` ของเซิร์ฟเวอร์: trim · เหลือ `\w.-` · ≤32 */
export function ล้างsku(v: unknown): string {
  return String(v ?? '').trim().replace(/[^\w.-]/g, '').slice(0, 32)
}

export interface อะไหล่ { เลข: string; รหัส: string; จำนวน: string; ชื่อ: string }
export interface กลุ่มอะไหล่ { id: string; ตัวอักษร: string; ชื่อ: string; อะไหล่?: อะไหล่[] }
export interface ข้อมูลรุ่น { รหัสรุ่น?: string; ชื่อรุ่น?: string; ที่มา?: string; กลุ่ม?: กลุ่มอะไหล่[] }

export interface แถว extends อะไหล่ {
  กลุ่มId: string
  กลุ่มชื่อ: string
  ตัวอักษร: string
  คีย์: string      // รหัสที่ล้างแล้ว — ใช้คุยกับ API
  ลำดับ: number     // ลำดับในหน้า ใช้หาช่องถัดไปตอนกด Enter
}

/** แบนกลุ่ม→แถว เรียงตามที่แสดงบนจอ
 *  ⚠️ **ไม่ตัดแถวที่รหัสซ้ำกันทิ้ง** — ของจริงมีชิ้นเดียวกันโผล่หลายกลุ่ม (เช่นสกรูตัวเดียวกัน)
 *     ตัดทิ้งแล้วท่านจะหาแถวที่เห็นในคู่มือไม่เจอ · แต่ **คีย์เดียวกันจับคู่ครั้งเดียวพอ** */
export function แบนรายการ(ข้อมูล: ข้อมูลรุ่น | null): แถว[] {
  const ออก: แถว[] = []
  for (const g of ข้อมูล?.กลุ่ม ?? []) {
    for (const a of g.อะไหล่ ?? []) {
      ออก.push({
        ...a,
        กลุ่มId: g.id,
        กลุ่มชื่อ: g.ชื่อ,
        ตัวอักษร: g.ตัวอักษร,
        คีย์: ล้างรหัส(a.รหัส),
        ลำดับ: ออก.length,
      })
    }
  }
  return ออก
}

export type สถานะแถว = 'ยังไม่จับคู่' | 'จับคู่แล้ว' | 'กำลังบันทึก' | 'บันทึกไม่สำเร็จ'

/** สถานะของแถวหนึ่ง — **สี่สถานะ ห้ามยุบ**
 *  🔴 `ยังไม่จับคู่` ≠ `บันทึกไม่สำเร็จ` — ถ้ายุบรวม ท่านจะคิดว่ายังไม่ได้กรอก แล้วกรอกซ้ำ
 *     ทั้งที่ของจริงคือเน็ตหลุด/ท่อปฏิเสธ ⇒ กรอกซ้ำก็ไม่สำเร็จเหมือนกัน */
export function สถานะของแถว(คีย์: string, แมป: Record<string, string>,
                            กำลังส่ง: Record<string, boolean>,
                            ล้มเหลว: Record<string, string>): สถานะแถว {
  if (ล้มเหลว[คีย์]) return 'บันทึกไม่สำเร็จ'
  if (กำลังส่ง[คีย์]) return 'กำลังบันทึก'
  return ล้างsku(แมป[คีย์]) ? 'จับคู่แล้ว' : 'ยังไม่จับคู่'
}

/** ความคืบหน้า — นับ **คีย์ที่ไม่ซ้ำ** ไม่ใช่จำนวนแถว
 *  (ถ้านับแถว ชิ้นที่โผล่หลายกลุ่มจะถูกนับหลายครั้ง ⇒ เปอร์เซ็นต์ไม่ถึง 100 ตลอดกาล) */
export function ความคืบหน้า(รายการ: แถว[], แมป: Record<string, string>) {
  const คีย์ทั้งหมด: Record<string, true> = {}
  for (const r of รายการ) คีย์ทั้งหมด[r.คีย์] = true
  const ชื่อคีย์ = Object.keys(คีย์ทั้งหมด)
  let จับคู่แล้ว = 0
  for (const k of ชื่อคีย์) if (ล้างsku(แมป[k])) จับคู่แล้ว++
  return { จับคู่แล้ว, ทั้งหมด: ชื่อคีย์.length, แถว: รายการ.length }
}

/** ช่องถัดไปที่ควรไปต่อเมื่อกด Enter — ข้ามแถวที่จับคู่แล้ว เพื่อให้ไล่กรอกของที่ยังว่างได้เร็ว
 *  คืน `null` เมื่อไม่มีช่องว่างเหลือ (จอต้องบอกว่าครบแล้ว ไม่ใช่เด้งไปแถวแรกเงียบ ๆ) */
export function ช่องถัดไป(รายการ: แถว[], จาก: number, แมป: Record<string, string>): number | null {
  for (let i = จาก + 1; i < รายการ.length; i++) if (!ล้างsku(แมป[รายการ[i].คีย์])) return i
  for (let i = 0; i <= จาก && i < รายการ.length; i++) if (!ล้างsku(แมป[รายการ[i].คีย์])) return i
  return null
}
