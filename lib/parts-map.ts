/** ล้างรหัสอะไหล่ — ต้องเท่ากับ `ล้างรหัส` ของเซิร์ฟเวอร์: ตัดช่องว่างทุกชนิด · ตัวใหญ่ · ≤24 */
export function ล้างรหัส(v: unknown): string {
  return String(v ?? '').replace(/\s+/g, '').toUpperCase().slice(0, 24)
}

/** ล้างรหัสสินค้าร้าน — **ต้องเท่ากับ `ล้างsku` ของเซิร์ฟเวอร์** (`netlify/functions/parts-map.mjs`)
 *
 * 🔴 **กติกาเปลี่ยนแล้ว 12 ต.ค. 2569 (ฝั่งท่อ `75c50ccc`) — ของเดิมทำรหัสจริงเพี้ยน**
 *    เดิม: `replace(/[^\w.-]/g, '')` ⇒ **JS `\w` เป็น ASCII เท่านั้น** ⇒ อักษรไทยถูกตัดทิ้งเงียบ ๆ
 *    ⇒ รหัสจริงอย่าง `บาร์04382` กลายเป็น `04382` ซึ่งอาจเป็นรหัสของสินค้าคนละตัว
 *    ⇒ ใหม่: **ไม่ตัดอักขระทิ้งเลย** — ทำให้เป็นระเบียบแล้ว **รับหรือปฏิเสธ** เท่านั้น
 *
 * ⚠️ **ความยาวนับหลังยุบช่องว่าง ไม่ใช่ก่อน** (ฝั่งท่อย้ำ) ไม่งั้นเคส `A   B` สองฝั่งไม่ตรง
 * ⚠️ เพดาน 32 เป็น **เลขที่วัดมา** ไม่ใช่เลขสวย ๆ — รหัสจริงยาวสุดในคลังคือ 18
 *    ⇒ วันไหนต้องขยับ **ต้องขยับพร้อมกันสองฝั่ง** */
export function ล้างsku(v: unknown): string {
  return ตรวจรหัสร้าน(v).sku
}

/** ทำให้เป็นระเบียบอย่างเดียว — ยังไม่ตัดสินว่ารับหรือไม่ (ตรงกับบรรทัดแรกของฝั่งท่อ) */
function จัดระเบียบsku(v: unknown): string {
  // eslint-disable-next-line no-control-regex -- ตัดอักขระควบคุมตรงกับสเปกเซิร์ฟเวอร์
  return String(v ?? '').replace(/[\u0000-\u001f\u007f]/g, '').replace(/\s+/g, ' ').trim()
}

/** ผลการตรวจรหัสร้านที่คนพิมพ์เข้ามา — **คนละเรื่องกับการล้างค่า**
 *
 * 🔴 **ที่มา 12 ต.ค. 2569 — เจอตอนพิมพ์จริงบนเว็บจริง ไม่ได้เจอจาก tsc หรือด่าน**
 *    พิมพ์ `ทดสอบ-ลบทิ้ง` ⇒ จอขึ้น `-` พร้อมป้ายเขียว **"จับคู่แล้ว"** และตัวนับเดินเป็น 1/336
 *    เหตุ: `[^\w.-]` ของ JS **ไม่นับอักษรไทยเป็น `\w`** ⇒ ตัวไทยถูกตัดทิ้งหมด เหลือแค่ `-`
 *    ⇒ ระบบ "ทำงานถูก" ทุกชั้น (ล้างค่าตรงกับเซิร์ฟเวอร์เป๊ะ · บันทึกสำเร็จจริง)
 *       แต่ **ยืนยันกับคนว่าสำเร็จในสิ่งที่เขาไม่ได้พิมพ์**
 *
 * 🔑 สองข้อที่ต้องแยกออกจากกัน
 *    ① **ล้างค่า** = ทำให้ตรงกับที่เซิร์ฟเวอร์จะเก็บ (ห้ามแก้ ไม่งั้นคีย์เพี้ยนกันสองฝั่ง)
 *    ② **ตรวจค่า** = บอกคนว่าสิ่งที่พิมพ์ถูกเปลี่ยนไปไหม — ของใหม่ ไม่เคยมี
 *    ⇒ แก้ที่ ① ไม่ได้ · ต้องเพิ่ม ② แล้วให้จอพูดต่างกัน
 *
 * ⚠️ `ใช้ไม่ได้` ต้อง **ไม่บันทึก** — ค่าอย่าง `-` หรือ `.` ผ่านตัวล้างได้สบาย
 *    แล้วหน้าร้านจะขึ้น "มีขาย" ให้รหัสที่ไม่มีอยู่จริง
 */
export type สภาพรหัสร้าน = 'ว่าง' | 'ปกติ' | 'จัดระเบียบ' | 'ใช้ไม่ได้'

export function ตรวจรหัสร้าน(ดิบ: unknown): { sku: string; สภาพ: สภาพรหัสร้าน; เหตุ: string } {
  const ต้นฉบับ = String(ดิบ ?? '')
  const จัด = จัดระเบียบsku(ต้นฉบับ)
  if (!จัด) return { sku: '', สภาพ: 'ว่าง', เหตุ: '' }
  /* ⚠️ วัดความยาว **หลัง** ยุบช่องว่างแล้ว ตามที่ฝั่งท่อย้ำ — ไม่งั้น `A   B` สองฝั่งไม่ตรง */
  if (จัด.length > 32) {
    return { sku: '', สภาพ: 'ใช้ไม่ได้',
      เหตุ: `รหัสสินค้ายาวเกิน 32 ตัว (ได้ ${จัด.length}) — รหัสจริงยาวสุดในคลังคือ 18` }
  }
  if (!/[A-Za-z0-9]/.test(จัด)) {
    return { sku: '', สภาพ: 'ใช้ไม่ได้',
      เหตุ: `"${จัด}" ไม่มีตัวอักษรอังกฤษหรือตัวเลขเลย — ไม่ใช่รหัสสินค้า` }
  }
  /* 🔑 เหลือได้แค่สองทาง: **เหมือนที่พิมพ์** หรือ **ถูกจัดระเบียบ** (ยุบช่องว่าง/ตัดหัวท้าย)
     ไม่มีทาง "ตัดอักขระออกแล้วยังรับ" อีกแล้ว — ของเดิมมีทางนั้น และนั่นคือทางที่ทำรหัสเพี้ยน */
  if (จัด !== ต้นฉบับ) {
    return { sku: จัด, สภาพ: 'จัดระเบียบ', เหตุ: `บันทึกเป็น "${จัด}"` }
  }
  return { sku: จัด, สภาพ: 'ปกติ', เหตุ: '' }
}

export interface อะไหล่ { เลข: string; รหัส: string; จำนวน: string; ชื่อ: string }
/** หนึ่งหมวดในผังอะไหล่ (A · Crankcase …)
 *  ⚠️ `ภาพ`/`w`/`h` มีอยู่ในไฟล์ JSON มาตั้งแต่ต้น แต่เคยไม่ได้ประกาศไว้ที่นี่
 *     ⇒ โค้ดที่อยากใช้รูปผังจะ tsc แดง ทั้งที่ข้อมูลมีครบ (เจอ 17 ต.ค. 2569)
 *     เป็นช่องว่างชนิด "ข้อมูลมี แต่ชนิดบอกว่าไม่มี" ซึ่งทำให้ของที่ใช้ได้ดูเหมือนใช้ไม่ได้ */
export interface กลุ่มอะไหล่ {
  id: string
  ตัวอักษร: string
  ชื่อ: string
  /** ชื่อไฟล์ภาพผังของหมวดนี้ (a.webp) — บางหมวดยังไม่มี */
  ภาพ?: string
  /** ขนาดภาพจริง ใส่ให้ <img> กันหน้ากระตุกตอนรูปโหลดเสร็จ */
  w?: number
  h?: number
  อะไหล่?: อะไหล่[]
}
export interface ข้อมูลรุ่น { รหัสรุ่น?: string; ชื่อรุ่น?: string; ที่มา?: string; กลุ่ม?: กลุ่มอะไหล่[] }

export interface แถว extends อะไหล่ {
  กลุ่มId: string
  กลุ่มชื่อ: string
  ตัวอักษร: string
  คีย์: string      // รหัสที่ล้างแล้ว — ใช้คุยกับ API
  ลำดับ: number     // ลำดับในหน้า ใช้หาช่องถัดไปตอนกด Enter
}

/** แบนกลุ่ม→แถว เรียงตามที่แสดงบนจอ
 *  ⚠️ **ไม่ตัดแถวที่รหัสซ้ำกันทิ้ง** — ของจริงมีชิ้นเดียวกันโผล่หลายกลุ่ม (เช่นสกรูตัวเดียวกัน)
 *     ตัดทิ้งแล้วท่านจะหาแถวที่เห็นในคู่มือไม่เจอ · แต่ **คีย์เดียวกันจับคู่ครั้งเดียวพอ** */
export function แบนรายการ(ข้อมูล: ข้อมูลรุ่น | null): แถว[] {
  const ออก: แถว[] = []
  for (const g of ข้อมูล?.กลุ่ม ?? []) {
    for (const a of g.อะไหล่ ?? []) {
      ออก.push({
        ...a,
        กลุ่มId: g.id,
        กลุ่มชื่อ: g.ชื่อ,
        ตัวอักษร: g.ตัวอักษร,
        คีย์: ล้างรหัส(a.รหัส),
        ลำดับ: ออก.length,
      })
    }
  }
  return ออก
}

export type สถานะแถว = 'ยังไม่จับคู่' | 'จับคู่แล้ว' | 'กำลังบันทึก' | 'บันทึกไม่สำเร็จ'

/** สถานะของแถวหนึ่ง — **สี่สถานะ ห้ามยุบ**
 *  🔴 `ยังไม่จับคู่` ≠ `บันทึกไม่สำเร็จ` — ถ้ายุบรวม ท่านจะคิดว่ายังไม่ได้กรอก แล้วกรอกซ้ำ
 *     ทั้งที่ของจริงคือเน็ตหลุด/ท่อปฏิเสธ ⇒ กรอกซ้ำก็ไม่สำเร็จเหมือนกัน */
export function สถานะของแถว(คีย์: string, แมป: Record<string, string>,
                            กำลังส่ง: Record<string, boolean>,
                            ล้มเหลว: Record<string, string>): สถานะแถว {
  if (ล้มเหลว[คีย์]) return 'บันทึกไม่สำเร็จ'
  if (กำลังส่ง[คีย์]) return 'กำลังบันทึก'
  return ล้างsku(แมป[คีย์]) ? 'จับคู่แล้ว' : 'ยังไม่จับคู่'
}

/** ความคืบหน้า — นับ **คีย์ที่ไม่ซ้ำ** ไม่ใช่จำนวนแถว
 *  (ถ้านับแถว ชิ้นที่โผล่หลายกลุ่มจะถูกนับหลายครั้ง ⇒ เปอร์เซ็นต์ไม่ถึง 100 ตลอดกาล) */
export function ความคืบหน้า(รายการ: แถว[], แมป: Record<string, string>) {
  const คีย์ทั้งหมด: Record<string, true> = {}
  for (const r of รายการ) คีย์ทั้งหมด[r.คีย์] = true
  const ชื่อคีย์ = Object.keys(คีย์ทั้งหมด)
  let จับคู่แล้ว = 0
  for (const k of ชื่อคีย์) if (ล้างsku(แมป[k])) จับคู่แล้ว++
  return { จับคู่แล้ว, ทั้งหมด: ชื่อคีย์.length, แถว: รายการ.length }
}

/** ช่องถัดไปที่ควรไปต่อเมื่อกด Enter — ข้ามแถวที่จับคู่แล้ว เพื่อให้ไล่กรอกของที่ยังว่างได้เร็ว
 *  คืน `null` เมื่อไม่มีช่องว่างเหลือ (จอต้องบอกว่าครบแล้ว ไม่ใช่เด้งไปแถวแรกเงียบ ๆ) */
export function ช่องถัดไป(รายการ: แถว[], จาก: number, แมป: Record<string, string>): number | null {
  for (let i = จาก + 1; i < รายการ.length; i++) if (!ล้างsku(แมป[รายการ[i].คีย์])) return i
  for (let i = 0; i <= จาก && i < รายการ.length; i++) if (!ล้างsku(แมป[รายการ[i].คีย์])) return i
  return null
}
