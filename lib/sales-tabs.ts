/** แถวตัวนับที่ท่อส่งมา — ชื่อช่องตามสัญญาของ `list=orders` */
export interface แถวสถานะ { status: string; orders: number }
export interface แถวชำระเงิน { payStatus: string; orders: number
  /** ยอดเงินของกองนี้ — ท่อส่งมาใน `byPayStatus`/`byPayStatusFiltered` (อาจไม่มีในรุ่นเก่า) */
  amount?: number }

export interface แท็บ {
  id: string
  label: string
  /** `undefined` = **ไม่รู้จำนวน** ⇒ ไม่มีวงเล็บ (ห้ามแปลงเป็น 0) */
  count?: number
}

export interface ผลแถบแท็บ {
  tabs: แท็บ[]
  /** แท็บที่ไฮไลต์ · `'—'` = ตัวกรองปัจจุบันไม่ตรงกับแท็บไหน (ห้ามไฮไลต์ "ทั้งหมด" ตอนกรองอยู่) */
  active: string
  ไม่มีแท็บตรง: boolean
  /** เชื่อตัวนับของแท็บฝั่ง `status` ได้ไหม — `false` ⇒ ตัวนับทุกตัวฝั่งนั้นต้องเป็น `undefined` */
  ตัวนับสถานะเชื่อได้: boolean
}

/** ค่าดิบของสถานะชำระเงินที่ ZORT ทำเป็นแท็บไว้ในแถบเดียวกับสถานะใบ (`/Sell/list`) */
export const แท็บชำระเงินของZORT = 'Pending'
/** คำนำหน้า id ของแท็บฝั่งชำระเงิน — กันชนกับค่าดิบฝั่ง `status` ที่สะกดซ้ำกันได้
 *  ⚠️ `Pending` **มีอยู่ในทั้งสองคอลัมน์** และหมายถึงคนละเรื่อง ⇒ ไม่มีคำนำหน้า = กดแท็บผิดมิติเงียบ ๆ */
export const คำนำหน้าแท็บชำระเงิน = 'pay:'

/** ช่องที่ขอจากฝั่งท่อไว้ 14 ต.ค. 2569 — **รายชื่อมีที่เดียว** เพื่อให้ตัววัดฝั่งนอก
 *  (`scripts/วัดสัญญาแท็บชำระเงิน.mjs`) ถามหาช่องเดียวกับที่จอนี้อ่านจริง
 *  🔑 เหตุ: ใบ `เปลี่ยนชื่อค่าในสัญญาร่วมต้องบอกว่าใครอ่านค่านั้น` — ชื่อที่พิมพ์ซ้ำสองที่
 *     จะเพี้ยนกันวันที่ใครเปลี่ยนข้างเดียว แล้ว **ตัววัดจะเขียวฟรีตลอดกาล** */
export const ช่องสัญญาแท็บชำระเงิน = [
  'byPayStatus', 'payStatusesAll', 'tabBase',
  /* 💵 สามช่องเงิน (รอบที่สองของสัญญา · 14 ต.ค. 2569) — ฐาน `w` ชุดเดียวกับ `rows`
     อยู่ในรายการเดียวกันเพราะ **มาใน deploy เดียวกันและพังด้วยกันได้** */
  'byPayStatusFiltered', 'totalPaidAmountByPay', 'totalUnpaidAmountByPay',
  /* ก้อนแยกตาม `status` บนฐาน `w` — ฝั่งท่อประกาศ 14 ต.ค. 2569 เพื่อให้จอ **ตรวจสองช่องเงินเก่าได้เอง**
     🔑 คู่กับ `byPayStatusFiltered` แล้วได้ของแถมฟรี: สองก้อนนี้แบ่ง **แถวชุดเดียวกัน** คนละมิติ
        ⇒ **ผลรวมยอดเงินต้องเท่ากัน** ⇒ ไม่เท่า = คนละฐาน (ตัววัดสัญญาใช้ข้อนี้เป็นตัวตัดสิน) */
  'byStatusFiltered',
] as const
/** คำที่ต้องอยู่ใน `tabBase.excludes` เพื่อให้ตัวนับฝั่งสถานะเชื่อได้ตอนกรองชำระเงิน */
export const คำยกเว้นที่ต้องมี = 'paystatus'

/** ท่อประกาศว่าฐานตัวนับแท็บ **ไม่ผูกกับ `paystatus`** แล้วหรือยัง
 *  ⚠️ **ตัวตัดสินนี้ต้องมีที่เดียว** — ทั้งจอและตัววัดฝั่งนอกเรียกตัวนี้
 *     (ของเดิมเขียน regex ไว้กลางฟังก์ชันสร้างแท็บ ⇒ ตัววัดจะต้องลอกไปอีกชุด) */
export function ฐานตัวนับไม่ผูกกับชำระเงิน(tabBase?: { excludes?: string[] } | null): boolean {
  const ฐาน = Array.isArray(tabBase?.excludes) ? tabBase!.excludes! : null
  return !!ฐาน?.some((x) => new RegExp(คำยกเว้นที่ต้องมี, 'i').test(String(x)))
}

export function สร้างแถบแท็บขาย(o: {
  /** สารบัญสถานะทั้งระบบ (ท่อ: `statusesAll` กรองแค่ร้าน) — ไม่ใช่สถานะที่เจอในผลรอบนี้ */
  รายชื่อสถานะ: string[]
  byStatus?: แถวสถานะ[] | null
  byPayStatus?: แถวชำระเงิน[] | null
  /** ฐานที่ท่อใช้คิดตัวนับแท็บ = รายชื่อตัวกรองที่ท่อ **ไม่** นับรวม · ไม่มี = ท่อรุ่นเก่า */
  tabBase?: { excludes?: string[] } | null
  total?: number | null
  /** ค่าตัวกรองที่จอใช้อยู่ (ค่าดิบ ไม่ใช่คำไทย) */
  status: string
  fPay: string
  ป้ายสถานะ: (ค่าดิบ: string) => string
  ป้ายชำระเงิน: (ค่าดิบ: string) => string
}): ผลแถบแท็บ {
  const ฐานไม่ผูกกับชำระเงิน = ฐานตัวนับไม่ผูกกับชำระเงิน(o.tabBase)

  /* 🔴 ยิงพิสูจน์ 14 ต.ค. 2569: ส่ง `paystatus=Pending` ⇒ `byStatus` เหลือ 2 แถว
     ⇒ แท็บ "ยกเลิก"/"รอส่ง" จะอ่านว่า **(0)** ทั้งที่ระบบมีจริงทั้งคู่
     ⇒ ตอนกรองชำระเงินอยู่ และท่อยังไม่ประกาศว่าฐานตัวนับไม่ผูกกับ `paystatus`
        ตัวนับฝั่ง `status` **ต้องเป็นไม่รู้** */
  /* 🔑 **และข้อนี้บังคับโดยตัวเลือกทีละมิติโดยตรง** (ไม่ใช่แค่เรื่องสารบัญ):
     แถบนี้กดแท็บสถานะแล้ว **ล้างตัวกรองชำระเงิน** ⇒ สิ่งที่ได้หลังกด = ของทั้งชุด (ไม่กรองชำระเงิน)
     ⇒ ถ้าโชว์เลขที่ถูกกรองด้วยชำระเงินไว้ในวงเล็บ **เลขนั้นจะไม่ใช่สิ่งที่ได้ตอนกด**
        = ผิดกฎแท็บข้อ 2 ตรงตัว (เลขในวงเล็บคือคำสัญญาว่ากดแล้วเจอเท่านั้น)
     ⇒ สองเหตุชี้ทางเดียวกัน: ตอนกรองชำระเงินอยู่ ตัวนับฝั่งสถานะต้องเป็น **ไม่รู้** */
  const ตัวนับสถานะเชื่อได้ = o.fPay === '' || ฐานไม่ผูกกับชำระเงิน

  const มีByStatus = Array.isArray(o.byStatus)
  const นับสถานะ = (st: string) => {
    if (!ตัวนับสถานะเชื่อได้ || !มีByStatus) return undefined
    return Number(o.byStatus!.find((r) => r.status === st)?.orders ?? 0)
  }
  const นับชำระเงิน = (v: string) => {
    if (!Array.isArray(o.byPayStatus)) return undefined         // ไม่รู้ ≠ 0
    return Number(o.byPayStatus!.find((r) => r.payStatus === v)?.orders ?? 0)
  }

  /** ตัวนับของแท็บ "ทั้งหมด" — บวกจาก `byStatus` เพราะนั่นคือฐานเดียวกับแท็บอื่น
   *  ⚠️ `total` เป็นตัวสำรอง (ท่อรุ่นที่ไม่ส่ง byStatus) · ไม่รู้ทั้งคู่ ⇒ undefined */
  const นับทั้งหมด = () => {
    if (!ตัวนับสถานะเชื่อได้) return undefined
    if (มีByStatus) {
      const s = o.byStatus!.reduce((n, r) => n + Number(r.orders || 0), 0)
      if (s > 0) return s
    }
    return typeof o.total === 'number' ? o.total : undefined
  }

  const tabs: แท็บ[] = [
    { id: '', label: 'ทั้งหมด', count: นับทั้งหมด() },
    ...o.รายชื่อสถานะ.map((st) => ({ id: st, label: o.ป้ายสถานะ(st), count: นับสถานะ(st) })),
    {
      id: `${คำนำหน้าแท็บชำระเงิน}${แท็บชำระเงินของZORT}`,
      label: o.ป้ายชำระเงิน(แท็บชำระเงินของZORT),
      count: นับชำระเงิน(แท็บชำระเงินของZORT),
    },
  ]

  /* แถบแท็บเลือกได้ทีละมิติ (ผัง ZORT) ⇒ กรองสองมิติพร้อมกันจากแผงค้นหาขั้นสูง = ไม่ตรงแท็บไหน */
  const active = o.fPay === ''
    ? o.status
    : (o.status === '' ? `${คำนำหน้าแท็บชำระเงิน}${o.fPay}` : '—')

  return {
    tabs,
    active,
    ไม่มีแท็บตรง: active !== '' && !tabs.some((t) => t.id === active),
    ตัวนับสถานะเชื่อได้,
  }
}

/* ══ 💵 เงิน "ได้เข้าจริง / ยังไม่เข้า" — ต้องมาจากคอลัมน์ `pay_status` ════════════
   🔴 ที่มา 14 ต.ค. 2569 (ฝั่งท่อเจอเพราะตัวเลขที่จอวัดมา):
      `totalPaidAmount` / `totalUnpaidAmount` ของเดิม **คิดจากคอลัมน์ `status`**
      ⇒ นับเงินของ 23 ใบที่ `status=Pending` แต่ **จ่ายแล้ว** เป็น "ยังไม่จ่าย"
      ⇒ และนับเงินของ 15 ใบที่ `status=Success` แต่ **ยังไม่ได้เงิน** เป็น "ได้เงินแล้ว"
      ⇒ ทิศหลังอันตรายกว่า: ได้เงินแล้วทั้งที่ยังไม่ได้ = **ไม่มีใครไปตามเก็บ** (ข่าวดีปลอม)
   🔑 ท่อส่ง **ก้อนแยกตามสถานะชำระเงินมาด้วย** ไม่ใช่ส่งแต่ยอดรวม — ด้วยเหตุผลของฝั่งท่อเอง:
      ถ้าส่งแต่ตัวเลข **ท่อจะเป็นคนแปลชื่อค่า** ⇒ วันที่ ZORT ส่ง `Partial Payment` มา
      มันจะไม่ถูกนับในทั้งสองช่องและ **ไม่มีอะไรฟ้อง** ⇒ จอจึงต้องเห็นชื่อค่าดิบเอง
   ⇒ ฟังก์ชันนี้ **บอกค่าที่มันยังไม่รู้ว่าจัดกองไหน** ออกมาด้วย (`ค่าที่ยังไม่จัดกอง`)
      จอมีหน้าที่พูดออกมา ไม่ใช่กลืนเงียบ ๆ */
export const ค่าชำระครบ = 'Paid'
export const ค่ารอชำระ = 'Pending'
/** ค่าที่ "ไม่ใช่เงินของร้าน" — ไม่เข้าทั้งสองกอง และ **ไม่ใช่ค่าที่ไม่รู้จัก** */
export const ค่ายกเลิกชำระ = 'Voided'

export interface เงินตามการชำระ {
  /** ค่าที่จอยังจัดกองไม่ได้ **ทั้งฐาน** (จาก `payStatusesAll` · กรองแค่ร้าน ไม่กรองวัน)
   *  🔑 ต่างจาก `ค่าที่ยังไม่จัดกอง` ที่ดูเฉพาะช่วงที่เลือก:
   *     ตัวนี้ตอบว่า **"ขยายช่วงวันแล้วจะเจอไหม"** ⇒ ของจริง 14 ต.ค.: ฐานมี `Partial Payment`
   *     แต่ในช่วงหนึ่งปีไม่มีสักใบ ⇒ ใบพวกนั้นเก่ากว่านั้น
   *  ⚠️ `undefined` = ท่อไม่ส่ง `payStatusesAll` · `[]` = ส่งแล้วไม่มีค่าแปลกเลย (สองอย่างคนละเรื่อง) */
  ค่าที่ยังไม่จัดกองทั้งฐาน?: string[]
  /** `undefined` = ท่อยังไม่ส่ง (ไม่รู้) · `null` = ท่อส่งมาว่าอ่านไม่ได้ — **ห้ามยุบเป็น 0** */
  จ่ายแล้ว?: number | null
  ยังไม่จ่าย?: number | null
  /** `'pay_status'` = ของจริง · `'status'` = ของเก่าที่คิดผิดคอลัมน์ · `null` = ไม่รู้ */
  ที่มา: 'pay_status' | 'status' | null
  /** ค่าดิบในก้อนแยกที่จอยังไม่รู้ว่าควรอยู่กองไหน (เช่น `Partial Payment`) */
  ค่าที่ยังไม่จัดกอง: string[]
  /** ยอดจากก้อนแยกไม่ตรงกับยอดรวมที่ท่อส่ง (เกินค่าปัดเศษ) ⇒ สองแหล่งขัดกัน */
  สองแหล่งไม่ตรง?: string
}

export function อ่านเงินตามการชำระ(o: {
  byPayStatusFiltered?: แถวชำระเงิน[] | null
  /** สารบัญสถานะชำระเงินทั้งฐาน (กรองแค่ร้าน) — ท่อส่งมาตามสัญญา 14 ต.ค. 2569
   *  🔑 **เหตุที่ขอช่องนี้มา เปลี่ยนไปแล้วและผมเขียนไว้ตรง ๆ**: ตอนขอ ผมคิดว่าจะใช้ทำแท็บ
   *     แต่แท็บฝั่งชำระเงินเป็น **ค่าคงที่ตัวเดียว** (ตามแถบของ ZORT) ⇒ ไม่ได้ใช้ทำแท็บ
   *     ⇒ ใช้ตอบคำถามที่มันตอบได้ดีกว่า: **มีสถานะที่จอจัดกองไม่ได้ซ่อนอยู่นอกช่วงที่เลือกไหม** */
  payStatusesAll?: string[] | null
  totalPaidAmountByPay?: number | null
  totalUnpaidAmountByPay?: number | null
  /** ของเก่าที่คิดจากคอลัมน์ `status` — ใช้ได้แต่ **ต้องติดป้ายว่ามาจากกติกาไหน** */
  totalPaidAmount?: number
  totalUnpaidAmount?: number
}): เงินตามการชำระ {
  const ก้อน = Array.isArray(o.byPayStatusFiltered) ? o.byPayStatusFiltered : null
  const ค่าที่ยังไม่จัดกอง = (ก้อน ?? [])
    .map((r) => String(r.payStatus ?? ''))
    .filter((v) => v && v !== ค่าชำระครบ && v !== ค่ารอชำระ && v !== ค่ายกเลิกชำระ)

  /** ค่าที่จัดกองไม่ได้ **ทั้งฐาน** — คนละคำถามกับในช่วงที่เลือก */
  const ทั้งฐาน = Array.isArray(o.payStatusesAll)
    ? o.payStatusesAll
      .map((v) => String(v ?? ''))
      .filter((v) => v && v !== ค่าชำระครบ && v !== ค่ารอชำระ && v !== ค่ายกเลิกชำระ)
    : undefined

  const มีช่องใหม่ = o.totalPaidAmountByPay !== undefined || o.totalUnpaidAmountByPay !== undefined
  if (!มีช่องใหม่ && !ก้อน) {
    /* ท่อรุ่นเก่า — ใช้ของเดิมได้ แต่ **ที่มาต้องติดไปด้วย** เพื่อให้จอเขียนกำกับได้
       (ข้อความกับตรรกะต้องมาจากที่เดียวกัน ⇒ จอห้ามเดาเองว่าเลขนี้มาจากคอลัมน์ไหน) */
    const เก่า = typeof o.totalPaidAmount === 'number' || typeof o.totalUnpaidAmount === 'number'
    return {
      จ่ายแล้ว: o.totalPaidAmount, ยังไม่จ่าย: o.totalUnpaidAmount,
      ที่มา: เก่า ? 'status' : null, ค่าที่ยังไม่จัดกอง: [],
      ค่าที่ยังไม่จัดกองทั้งฐาน: ทั้งฐาน,
    }
  }

  const รวมของ = (v: string) => (ก้อน ?? [])
    .filter((r) => String(r.payStatus) === v)
    .reduce((n, r) => n + Number(r.amount || 0), 0)

  const out: เงินตามการชำระ = {
    จ่ายแล้ว: o.totalPaidAmountByPay,
    ยังไม่จ่าย: o.totalUnpaidAmountByPay,
    ที่มา: 'pay_status',
    ค่าที่ยังไม่จัดกอง,
    ค่าที่ยังไม่จัดกองทั้งฐาน: ทั้งฐาน,
  }
  /* 🔑 **ท่อส่งสองแหล่งมาให้ ⇒ เทียบกันได้ฟรี** — ไม่เทียบคือทิ้งตาข่ายที่มีอยู่แล้ว
     ต่างกันเกิน 1 บาท = มีคนคิดคนละฐาน ⇒ จอต้องพูด ไม่ใช่เลือกเชื่อข้างหนึ่งเงียบ ๆ */
  if (ก้อน) {
    for (const [ชื่อ, ยอด, ค่า] of [
      ['ยังไม่จ่าย', out.ยังไม่จ่าย, ค่ารอชำระ],
      ['จ่ายแล้ว', out.จ่ายแล้ว, ค่าชำระครบ],
    ] as const) {
      if (typeof ยอด !== 'number') continue
      const จากก้อน = รวมของ(ค่า)
      if (Math.abs(จากก้อน - ยอด) > 1) {
        out.สองแหล่งไม่ตรง = `${ชื่อ}: ยอดรวมที่ท่อส่ง ${Math.round(ยอด).toLocaleString('th-TH')}`
          + ` แต่บวกจากก้อนแยกได้ ${Math.round(จากก้อน).toLocaleString('th-TH')}`
        break
      }
    }
  }
  return out
}
