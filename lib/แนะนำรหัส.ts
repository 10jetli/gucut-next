export type ข้อเสนอ = { sku: string; ชื่อ: string; รูป?: string; คะแนน: number }

/** ตัดคำไทยด้วยไลบรารีไม่ได้ (ไม่มีให้ใช้ และไม่อยากเพิ่มของหนัก)
 *  ⇒ ใช้ **ตัวอักษรซ้อน 3 ตัว** แทนการตัดคำ — ภาษาไทยไม่มีช่องว่างระหว่างคำ
 *     วิธีนี้จับ "ลูกปืน" ใน "ลูกปืนเม็ดกลม" ได้โดยไม่ต้องรู้ขอบเขตคำ
 *  ⚠️ ตัดอักขระที่ไม่ใช่ตัวอักษร/ตัวเลขออกก่อน ไม่งั้นช่องว่างกับวงเล็บ
 *     จะกลายเป็นส่วนหนึ่งของลายนิ้วมือ แล้วคะแนนเพี้ยนตามรูปแบบการเว้นวรรค */
function ลายนิ้วมือ(s: string): Set<string> {
  const t = String(s || '').toLowerCase().replace(/[^0-9a-z฀-๿]/g, '')
  const out = new Set<string>()
  for (let i = 0; i + 3 <= t.length; i++) out.add(t.slice(i, i + 3))
  return out
}

/** ตัวเลขในชื่อ (6202 · 15x35x13 · M8) — ตรงกันคือหลักฐานแรงกว่าคำพ้อง
 *  ⚠️ ต้องเป็น "ตรงกันทั้งก้อน" ไม่ใช่ตรงบางหลัก — 6202 กับ 6203 คนละลูกปืน */
function ก้อนเลข(s: string): Set<string> {
  /* ⚠️ แปลง × (U+00D7) เป็น x ก่อนเสมอ — คู่มือใช้ `5x18` ชื่อสินค้าร้านใช้ `5×18`
     ไม่แปลง = ขนาดที่ตรงกันเป๊ะถูกนับว่าไม่ตรง แล้วตัวที่ผิดขนาดขึ้นมาเสมอกัน
     (เจอจริงตอนวัด: `Cylindrical pin 5x18` เสนอ 5×10 คะแนนเท่ากับ 5×18) */
  const t = String(s || '').toLowerCase().replace(/×/g, 'x')
  return new Set((t.match(/\d+(?:x\d+)*/g) || []))
}

/** 🔑 **สัญญาณที่แรงที่สุดในงานนี้ — ค้นพบจากการวัด ไม่ได้เดา**
 *  ร้านเขียน "รหัสตำแหน่งในผัง" ต่อท้ายชื่อสินค้าแทบทุกตัว:
 *      "ข้อเหวี่ยง MS440 **A21**" · "ปะเก็นท่อไอเสีย MS440 **B13**" · "ฝาน้ำมัน MS440 **A34-A35**"
 *  ซึ่งตรงกับ (ตัวอักษรกลุ่ม + เลขในผัง) ของหน้านี้พอดี
 *
 *  วัดกับ 118 แถวที่คนจับคู่ไว้แล้วของ F440: ในกลุ่มที่ชื่อมีรหัสตำแหน่ง
 *  **ตรงพอดี 73 จาก 86 (85%)** · ที่เหลือ 13 ตัวไม่ได้ผิด — เป็นชิ้นเดียวที่ใช้หลายจุด
 *  (สกรู IS-M5x20 อยู่ทั้ง A9 · B11 · F18 ร้านตั้งชื่อตามจุดเดียว)
 *
 *  ⚠️ **ยังเป็นการเดาอยู่ดี** ร้านพิมพ์ชื่อเอง ไม่มีอะไรบังคับรูปแบบ
 *     ⇒ ห้ามเอาไปเติมช่องอัตโนมัติ ต้องให้คนกดรับเสมอ */
function ตำแหน่งในชื่อ(ชื่อ: string): { ตัวอักษร: string; ต้น: number; ปลาย: number }[] {
  const out: { ตัวอักษร: string; ต้น: number; ปลาย: number }[] = []
  for (const m of Array.from(String(ชื่อ || '').toUpperCase()
      .matchAll(/\b([A-Z])\s?(\d{1,3})(?:\s?-\s?[A-Z]?(\d{1,3}))?\b/g))) {
    const ต้น = Number(m[2])
    out.push({ ตัวอักษร: m[1], ต้น, ปลาย: m[3] ? Number(m[3]) : ต้น })
  }
  return out
}

export type ดัชนีสินค้า = {
  สินค้า: สินค้าร้าน[]
  นิ้วมือ: Set<string>[]
  เลข: Set<string>[]
  ตำแหน่ง: { ตัวอักษร: string; ต้น: number; ปลาย: number }[][]
}

export function สร้างดัชนี(สินค้า: สินค้าร้าน[]): ดัชนีสินค้า {
  return {
    สินค้า,
    นิ้วมือ: สินค้า.map((p) => ลายนิ้วมือ(p.ชื่อ)),
    เลข: สินค้า.map((p) => ก้อนเลข(p.ชื่อ)),
    ตำแหน่ง: สินค้า.map((p) => ตำแหน่งในชื่อ(p.ชื่อ)),
  }
}

/** เกณฑ์ขั้นต่ำที่จะยอมเสนอ — **วัดมา ไม่ได้ตั้งตามความรู้สึก**
 *
 *  วัดกับ 118 แถวที่คนจับคู่ไว้แล้วของ F440 (17 ต.ค. 2569) แยกความแม่นตามคะแนน:
 *      0.3–0.5   ถูก  0/30   (0%)      ← เดาล้วน
 *      0.6–0.7   ถูก  4/17   (24%)
 *      0.8–1.1   ถูก  2/5    (40%)
 *      **≥ 1.2   ถูก 58/59   (98%)**   ← ชั้นที่เชื่อได้
 *  ⇒ ตั้งที่ 1.2 · ได้ข้อเสนอราวครึ่งหนึ่งของแถว แต่ที่เสนอออกมาถูกเกือบทั้งหมด
 *
 *  🔑 **เหตุที่ยอมเสนอน้อยลงแลกความแม่น**: คนกรอกหน้านี้ทำงานเร็วและกดรับข้อเสนอ
 *     ที่ดูมั่นใจ ⇒ ข้อเสนอผิด 1 ใน 3 แปลว่าเราเติมข้อมูลผิดให้คลังด้วยมือเขาเอง
 *     ไม่เสนอเลยยังปลอดภัยกว่ามาก เพราะเขาจะไปหาเอง
 *  ⚠️ **แก้เลขนี้ต้องวัดใหม่ทุกครั้ง** (วิธีวัดอยู่ในคอมเมนต์ของ `ตำแหน่งในชื่อ`)
 *     เลขนี้ผูกกับสูตรให้คะแนนด้านล่าง เปลี่ยนน้ำหนักข้อไหนแล้วเลขนี้ใช้ไม่ได้ทันที */
export const เกณฑ์เสนอ = 1.2

/** หารหัสร้านที่น่าจะใช่ จากชื่ออะไหล่ (ไทยที่แปลแล้ว) + ชื่ออังกฤษเดิม
 *  คืนมากสุด `เอากี่ตัว` ตัว เรียงคะแนนมากไปน้อย · ต่ำกว่าเกณฑ์ = ไม่คืน */
export function แนะนำรหัส(
  ดัชนี: ดัชนีสินค้า,
  ชื่อไทย: string,
  ชื่ออังกฤษ: string,
  /** รหัสที่ร้านใช้เรียกรุ่นนี้ (MS440 · 7800 …) จาก `คำค้นร้าน` ใน models.json
   *  🔴 **สำคัญที่สุดของตัวแนะนำ** — ไม่ส่งมา = เสนออะไหล่ข้ามรุ่น
   *     วัดจริง 17 ต.ค. 2569: แถวของ F440 ได้ข้อเสนอเป็นของ MS381/MS180/7800TB
   *     ซึ่ง "หน้าตาถูก" ทุกประการ (ชื่อชิ้นตรงกัน) แต่เป็นคนละรุ่น ⇒ สั่งของผิด */
  คำค้นรุ่น: string,
  /** ตำแหน่งของแถวนี้ในผัง — ตัวอักษรกลุ่ม + เลขที่วงในภาพ (เช่น A, 21)
   *  ดู `ตำแหน่งในชื่อ` ข้างบนว่าทำไมสัญญาณนี้แรงที่สุด */
  ตำแหน่ง: { ตัวอักษร: string; เลข: number } | null,
  เอากี่ตัว = 2,
): ข้อเสนอ[] {
  const ถาม = ลายนิ้วมือ(`${ชื่อไทย} ${ชื่ออังกฤษ}`)
  if (ถาม.size < 3) return []
  const เลขถาม = ก้อนเลข(ชื่ออังกฤษ)
  const รุ่น = String(คำค้นรุ่น || '').toLowerCase().replace(/[^0-9a-z]/g, '')

  const ผล: ข้อเสนอ[] = []
  for (let i = 0; i < ดัชนี.สินค้า.length; i++) {
    const ม = ดัชนี.นิ้วมือ[i]
    if (!ม.size) continue
    /* ⚠️ `for...of` บน Set ใช้ไม่ได้ — tsconfig ของ gucut-next target ต่ำกว่า es2015 (TS2802) */
    let ตรง = 0
    ถาม.forEach((g) => { if (ม.has(g)) ตรง++ })
    if (!ตรง) continue

    /* หารด้วยฝั่งที่สั้นกว่า — ชื่อสินค้าร้านยาวกว่าชื่ออะไหล่มาก
       (เช่น "โซ่เลื่อยยนต์ KINGKONG 3623 (3/8) ขนาดกลาง เกรดA")
       ถ้าหารด้วยยูเนียน ของที่ตรงจริงจะได้คะแนนต่ำเตี้ยทุกตัวจนไม่ผ่านเกณฑ์ */
    let คะแนน = ตรง / Math.min(ถาม.size, ม.size)

    /* ⚠️ เลขตรงกันคือหลักฐานแรง — "Grooved ball bearing 6202" ต้องไม่ไปเจอ 6203
       แต่ **ห้ามบังคับว่าต้องมีเลข** เพราะอะไหล่จำนวนมากไม่มีเลขในชื่อเลย */
    if (เลขถาม.size) {
      let เลขตรง = 0
      เลขถาม.forEach((n) => { if (ดัชนี.เลข[i].has(n)) เลขตรง++ })
      if (เลขตรง) คะแนน += 0.25 * (เลขตรง / เลขถาม.size)
      else คะแนน -= 0.08   // มีเลขแต่ไม่ตรง = น่าสงสัย ไม่ใช่ตัดทิ้ง
    }
    /* 🔑 ชื่อรุ่นในชื่อสินค้าร้าน = หลักฐานแรงที่สุดที่มี
       ร้านเขียนรุ่นไว้ท้ายชื่อแทบทุกตัว ("ซีลใหญ่ (18X29.6X5/3) MS440 A18") */
    const ชื่อสินค้า = ดัชนี.สินค้า[i].ชื่อ.toLowerCase().replace(/[^0-9a-z]/g, '')
    const ตรงรุ่น = !!รุ่น && ชื่อสินค้า.includes(รุ่น)
    if (ตรงรุ่น) คะแนน += 0.30

    /* 🔴 ตำแหน่งในผังตรงกัน = หลักฐานแรงสุด ให้คะแนนทับทุกอย่าง
       ตั้งสูงพอให้ชนะคะแนนข้อความเต็ม ๆ โดยตั้งใจ — ข้อความพ้องกันได้ทั้งคลัง
       แต่ "MS440 A21" ชี้ชิ้นเดียว · ช่วงอย่าง A34-A35 ให้น้อยกว่าเพราะคลุมหลายชิ้น
       ⚠️ **เชื่อรหัสตำแหน่งได้เฉพาะเมื่อรุ่นตรงด้วย** — บทเรียนตอนวัด 17 ต.ค. 2569
          ให้คะแนนตำแหน่งโดยไม่ดูรุ่น แล้วความแม่น **แย่ลง** เพราะ "A1" โผล่ในชื่อ
          สินค้ารุ่นอื่นเต็มไปหมด (เกรดA 1 · C 15) ⇒ ตัวที่คะแนนสูงสุดกลายเป็นคนละรุ่น
       🔑 รูปทั่วไป: **สัญญาณแรงที่ไม่มีบริบทกำกับ ดังกว่าสัญญาณอ่อนที่ถูกต้อง** */
    let ตรงตำแหน่ง = false
    if (ตรงรุ่น && ตำแหน่ง && ตำแหน่ง.ตัวอักษร) {
      const L = ตำแหน่ง.ตัวอักษร.toUpperCase()
      for (const t of ดัชนี.ตำแหน่ง[i]) {
        if (t.ตัวอักษร !== L) continue
        if (t.ต้น === ตำแหน่ง.เลข && t.ปลาย === ตำแหน่ง.เลข) { คะแนน += 0.90; ตรงตำแหน่ง = true; break }
        if (ตำแหน่ง.เลข >= t.ต้น && ตำแหน่ง.เลข <= t.ปลาย) { คะแนน += 0.55; ตรงตำแหน่ง = true }
      }
    }


    /* 🔴 **ชื่อกว้าง ๆ ที่ไม่มีเลขและไม่ตรงรุ่น ⇒ ไม่เสนอเลย**
       "Pin" "Gasket" "Valve" เข้ากับสินค้าได้เป็นสิบตัว ทุกตัวได้คะแนนพอ ๆ กัน
       ⇒ ข้อเสนอที่ออกมาคือ "ตัวไหนก็ได้" ที่ **หน้าตาเหมือนคำตอบ**
       ไม่เสนอดีกว่า — คนกรอกเร็ว ๆ จะกดรับข้อเสนอที่ดูมั่นใจ */
    if (!เลขถาม.size && !ตรงรุ่น && !ตรงตำแหน่ง) continue

    if (คะแนน >= เกณฑ์เสนอ) {
      const p = ดัชนี.สินค้า[i]
      ผล.push({ sku: p.sku, ชื่อ: p.ชื่อ, รูป: p.รูป, คะแนน })
    }
  }
  ผล.sort((a, b) => b.คะแนน - a.คะแนน)
  return ผล.slice(0, เอากี่ตัว)
}
