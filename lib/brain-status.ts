/** ประกาศทุก 10 นาที ⇒ เกิน 45 นาที ถือว่าขาดการติดต่อ (เผื่อพลาดได้ 4 รอบ) */
export const นาทีที่ถือว่าขาดการติดต่อ = 45

export type สถานะหัวสมอง = 'ยังไม่ได้ติดตั้ง' | 'ติดต่อไม่ได้' | 'ปกติ'

export type ประกาศหัวสมอง = {
  ประกาศเมื่อ?: string
  ประกาศเมื่อยูนิกซ์?: number
  ติดตั้งแล้ว?: boolean
  [k: string]: unknown
}

/**
 * @param ประกาศ  เนื้อไฟล์ที่ g1 ประกาศ — `null` = ยังไม่มีไฟล์เลย
 * @param ตอนนี้วินาที  เวลาปัจจุบันเป็นวินาทียูนิกซ์ (รับเข้ามาเพื่อให้ทดสอบได้)
 */
export function ตัดสินสถานะ(
  ประกาศ: ประกาศหัวสมอง | null | undefined,
  ตอนนี้วินาที: number,
): { สถานะ: สถานะหัวสมอง; อายุนาที: number | null; เหตุ: string } {
  /* ไม่มีไฟล์ประกาศเลย = ยังไม่เคยมีใครตั้งหัวสมองขึ้นมา */
  if (!ประกาศ || ประกาศ.ติดตั้งแล้ว !== true) {
    return { สถานะ: 'ยังไม่ได้ติดตั้ง', อายุนาที: null,
      เหตุ: 'ยังไม่มีไฟล์ประกาศสถานะจาก g1 — แปลว่ายังไม่ได้ติดตั้ง ไม่ใช่ติดตั้งแล้วพัง' }
  }

  const เมื่อ = ประกาศ.ประกาศเมื่อยูนิกซ์
  /* 🔴 มีไฟล์แต่ไม่มีเวลา = **ไม่รู้ว่าเก่าแค่ไหน** ⇒ ห้ามอ่านว่าปกติ
     (ไม่รู้ ≠ ปกติ — ช่องที่เว้นว่างคือคำกล่าวอ้าง ไม่ใช่คำยืนยัน) */
  if (typeof เมื่อ !== 'number' || !Number.isFinite(เมื่อ)) {
    return { สถานะ: 'ติดต่อไม่ได้', อายุนาที: null,
      เหตุ: 'ไฟล์ประกาศไม่มีเวลากำกับ ⇒ บอกไม่ได้ว่าเป็นภาพของเมื่อไหร่' }
  }

  const อายุนาที = Math.round((ตอนนี้วินาที - เมื่อ) / 60)
  if (อายุนาที > นาทีที่ถือว่าขาดการติดต่อ) {
    return { สถานะ: 'ติดต่อไม่ได้', อายุนาที,
      เหตุ: `ภาพล่าสุดเก่า ${อายุนาที} นาที (เกิน ${นาทีที่ถือว่าขาดการติดต่อ}) — g1 อาจดับ เน็ตหลุด หรือรอบประกาศหยุด` }
  }
  return { สถานะ: 'ปกติ', อายุนาที, เหตุ: `ภาพล่าสุดอายุ ${Math.max(อายุนาที, 0)} นาที` }
}
