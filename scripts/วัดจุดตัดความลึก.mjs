/* ── ประชากร ① ไฟล์ของสูตรในทะเบียน ──────────────────────────────────────── */
const { สูตร } = await import('./lib/ทะเบียนด่าน.mjs')
const ไฟล์ของสูตร = [...new Set(สูตร.map((f) => f.ไฟล์).filter(Boolean))]

/* ── ประชากร ② ไฟล์ .ts/.tsx ในชั้นจอ/ชั้นของร่วม ─────────────────────────── */
const กวาดไฟล์ = (ที่, ออก = []) => {
  for (const ชื่อ of readdirSync(ที่)) {
    if (ชื่อ === 'node_modules' || ชื่อ.startsWith('.')) continue
    const p = join(ที่, ชื่อ)
    if (statSync(p).isDirectory()) กวาดไฟล์(p, ออก)
    else if (/\.tsx?$/.test(ชื่อ)) ออก.push(relative(ROOT, p))
  }
  return ออก
}
const ไฟล์ทั้งชั้น = ['app', 'lib', 'components'].flatMap((d) => {
  try { return กวาดไฟล์(join(ROOT, d)) } catch { return [] }
})

const ประชากร = [
  ['① ไฟล์ของสูตรในทะเบียนด่าน (ประชากรที่เกณฑ์นี้ถูกใช้จริง)', ไฟล์ของสูตร],
  ['② ไฟล์ .ts/.tsx ทั้ง app/ lib/ components/ (ภาพกว้าง — ไม่ใช่ตัวตัดสิน)', ไฟล์ทั้งชั้น],
]

for (const [ป้าย, ไฟล์] of ประชากร) {
  console.log(`\n═══ ${ป้าย}`)
  console.log(`ประชากร ${ไฟล์.length} ไฟล์`)
  /* 🔴 **อุ่นแคชก่อนจับเวลา** — ไม่อุ่นแล้วรอบแรกจะกินเวลาอ่านไฟล์ของ *ทุก* ความลึก
     ⇒ ตารางจะอ่านว่า "ลึก 1 ช้ากว่าลึก 3 สิบเท่า" ซึ่ง **กลับหัวและเป็นไปไม่ได้**
     (เจอกับตัวเองรอบแรก 1 ต.ค. 2569: 1018 ms vs 17 ms · เลขกลับหัวที่ดูน่าเชื่อ)
     🔑 เลขที่กลับหัวอย่างเห็นได้ชัด ยังดีกว่าเลขที่เพี้ยนเล็กน้อย — แต่ทั้งสองต้องแก้ที่เหตุ */
  for (const f of ไฟล์) เนื้อไฟล์(f)
  console.log(`\nระดับที่แต่ละความลึก (ระดับ 3 = อาจถึงตัวเขียน) · เวลาไม่รวมการอ่านไฟล์ (อุ่นแคชแล้ว)`)
  console.log(`  ลึกสุด │ ระดับ0  ระดับ1  ระดับ2  ระดับ3 │ ระดับ3 แยกตามยืมมากี่ชั้น │ เวลา`)
  for (const ล of ความลึกที่วัด) {
    const t0 = Date.now()
    const { ระดับ, ยืมมา } = นับระดับ(ไฟล์, ล)
    const ms = Date.now() - t0
    const แยก = Object.keys(ยืมมา).sort().map((k) => `${k} ชั้น: ${ยืมมา[k]}`).join(' · ') || '—'
    console.log(`     ${ล}    │  ${String(ระดับ[0]).padStart(4)}    ${String(ระดับ[1]).padStart(4)}`
      + `    ${String(ระดับ[2]).padStart(4)}    ${String(ระดับ[3]).padStart(4)} │ ${แยก.padEnd(34)} │ ${ms} ms`)
  }
  /* 🔑 ตารางไขว้ — ตอบว่า "ไฟล์ไหนขยับ" ไม่ใช่แค่ "ยอดรวมต่างกันเท่าไหร่" */
  for (const [a, b] of [[1, 2], [2, 3]]) {
    const ช่อง = ตารางไขว้(ไฟล์, a, b)
    const แถว = [...ช่อง.entries()].sort().map(([k, n]) => `${k}: ${n}`).join(' · ')
    console.log(`\nตารางไขว้ ลึก ${a} → ลึก ${b}   (รูป "ระดับเดิม→ระดับใหม่")`)
    console.log(`  ${แถว}`)
    console.log(`  ⇒ ไฟล์ที่ **ขยับขึ้น** เมื่อเพิ่มความลึกจาก ${a} เป็น ${b}: ${ขยับขึ้น(ช่อง)} ไฟล์`)
    /* 🔑 **บอกชื่อไฟล์ที่ขยับ ไม่ใช่แค่จำนวน** — จำนวนเท่าเดิมได้ทั้งที่สมาชิกเปลี่ยน
       และคนที่ต้องตัดสินจุดตัดต้องเปิดดูได้ว่า "ของที่เพิ่มมา เป็นของจริงหรือเสียงรบกวน" */
    const ขยับ = ไฟล์.map((f) => ({
      f,
      a: อาจถึงตัวเขียน(f, { ลึกสุด: a }),
      b: อาจถึงตัวเขียน(f, { ลึกสุด: b }),
    })).filter((u) => u.b.ระดับ > u.a.ระดับ)
    for (const u of ขยับ) {
      console.log(`     · ${u.f}  (${u.a.ระดับ}→${u.b.ระดับ} · ยืมมา ${u.b.ยืมมากี่ชั้น} ชั้น)`)
      console.log(`       ${u.b.เพราะ}`)
    }
  }
}

