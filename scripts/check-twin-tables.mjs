#!/usr/bin/env node
/* ค่าชุดเดียวกันที่เขียนไว้สองที่ ต้องตรงกันเสมอ — **ทำให้ build ตก**
 * (19 ก.ย. 2569 · ยกโครงจากฝั่งท่อ `check-twin-tables.mjs`)
 *
 * 🔴 ที่มาฝั่งผม: รายการ "เส้นที่เปิดให้คนไม่มีกุญแจได้โดยชอบธรรม" เขียนไว้ **สองที่**
 *    · `scripts/ยิงเส้นสาธารณะไม่มีกุญแจ.mjs` — ตัวยิงตรวจของจริง
 *    · `scripts/หมุดที่ต้องยิงจริง.mjs` — ตัววัดหมุด `วัดได้ยิงจริง(...)=6`
 *    ผมรู้ตัวว่าเป็นหนี้ตั้งแต่ตอนเขียน และจดไว้ในคอมเมนต์ **แต่ไม่มีอะไรบังคับ**
 *    ⇒ วันนี้ยังตรงกัน — **เพราะโชค ไม่ใช่เพราะมีกลไก**
 *
 * 🔴 ถ้าสองที่นี้เพี้ยนกัน: หมุดจะยังเขียว **แต่เลขในหมุดจะแปลว่าคนละอย่าง**
 *    (ยกเว้นคนละชุด ⇒ นับเส้นที่ปฏิเสธได้คนละจำนวน) ⇒ คำรับรองที่ดูเหมือนกลไก
 *
 * 🔑 **ทิศที่สามสำคัญที่สุด: สกัดไม่ออก ⇒ แดง ไม่ใช่เขียว** (ฝั่งท่อกำชับ)
 *    ถ้าวันหนึ่งมีคนเปลี่ยนชื่อตัวแปรหรือรูปการเขียน ตัวสกัดจะได้ชุดว่าง
 *    ⇒ "ว่างเท่ากับว่าง" = **ผ่านโดยไม่ได้เทียบอะไรเลย** = เขียวตลอดกาล
 */
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const อ่าน = (p) => readFileSync(join(ROOT, p), 'utf8')

/** คู่ที่ต้องตรงกัน — เพิ่มคู่ใหม่ได้ที่อาร์เรย์นี้ที่เดียว */
const คู่ = [
  {
    ชื่อ: 'เส้นที่เปิดให้คนไม่มีกุญแจได้โดยชอบธรรม',
    ทำไมต้องตรง: 'ยกเว้นคนละชุด ⇒ หมุด `วัดได้ยิงจริง(เส้นสาธารณะที่ปฏิเสธคนไม่มีกุญแจ)` จะนับคนละจำนวน โดยยังเขียว',
    ฝั่งA: {
      ไฟล์: 'scripts/ยิงเส้นสาธารณะไม่มีกุญแจ.mjs',
      สกัด: (t) => {
        const m = t.match(/const เปิดได้โดยชอบธรรม = \{([\s\S]*?)\n\}/)
        return m ? [...m[1].matchAll(/'([^']+)':/g)].map((x) => x[1]) : null
      },
    },
    ฝั่งB: {
      ไฟล์: 'scripts/หมุดที่ต้องยิงจริง.mjs',
      สกัด: (t) => {
        const m = t.match(/const ชอบธรรม = \[([^\]]*)\]/)
        return m ? [...m[1].matchAll(/'([^']+)'/g)].map((x) => x[1]) : null
      },
    },
  },
]

/* 🔒 ทะเบียนว่าง = ไม่มีอะไรให้เทียบ ⇒ แดง */
if (คู่.length === 0) {
  console.error('🔴 ทะเบียนคู่ว่าง — ด่านนี้ไม่ได้เทียบอะไรเลย ⇒ ไม่ผ่าน')
  process.exit(1)
}

let ตก = 0
console.log(`ตารางคู่ที่ต้องตรงกัน: ${คู่.length} คู่`)
for (const c of คู่) {
  const a = c.ฝั่งA.สกัด(อ่าน(c.ฝั่งA.ไฟล์))
  const b = c.ฝั่งB.สกัด(อ่าน(c.ฝั่งB.ไฟล์))
  /* 🔑 ทิศที่สาม — สกัดไม่ออกแม้ฝั่งเดียว ⇒ แดง (ไม่ใช่ "ว่างเท่ากับว่าง") */
  if (a === null || b === null || a.length === 0 || b.length === 0) {
    console.error(`🔴 ${c.ชื่อ}: **สกัดรายการไม่ออก** (${c.ฝั่งA.ไฟล์}=${a?.length ?? 'null'} · ${c.ฝั่งB.ไฟล์}=${b?.length ?? 'null'})`)
    console.error('   ⇒ มีคนเปลี่ยนชื่อตัวแปรหรือรูปการเขียน ⇒ **ด่านนี้จะเขียวโดยไม่เทียบอะไรเลย**')
    console.error('   ⇒ แก้ตัวสกัดใน scripts/check-twin-tables.mjs ให้ตรงกับรูปใหม่')
    ตก++
    continue
  }
  const sa = [...a].sort(), sb = [...b].sort()
  const ขาดB = sa.filter((x) => !sb.includes(x))
  const ขาดA = sb.filter((x) => !sa.includes(x))
  if (ขาดA.length || ขาดB.length) {
    console.error(`🔴 ${c.ชื่อ}: สองที่ไม่ตรงกัน`)
    if (ขาดB.length) console.error(`   มีใน ${c.ฝั่งA.ไฟล์} แต่ไม่มีใน ${c.ฝั่งB.ไฟล์}: ${ขาดB.join(' · ')}`)
    if (ขาดA.length) console.error(`   มีใน ${c.ฝั่งB.ไฟล์} แต่ไม่มีใน ${c.ฝั่งA.ไฟล์}: ${ขาดA.join(' · ')}`)
    console.error(`   ⇒ ${c.ทำไมต้องตรง}`)
    ตก++
  } else {
    console.log(`   ✅ ${c.ชื่อ}: ตรงกัน ${sa.length} รายการ`)
  }
}

if (ตก) process.exit(1)
console.log('✅ ตารางคู่ตรงกันทุกคู่')
