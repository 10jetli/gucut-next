#!/bin/bash
# พิสูจน์ว่า `scripts/วัดสัญญาแท็บชำระเงิน.mjs` **ร้องได้จริง และร้องถูกเหตุ**
#
# 🔑 ชี้ตัววัดไปที่ **ท่อปลอม** (โลกที่เราสั่งให้ผิดได้) ⇒ ไม่ต้องทำให้ท่อจริงผิด
#    ใบ: ท่อปลอมใช้เป็นเครื่องปลูกของเสียได้ · และ ตัวเตือนต้องเคยถูกทำให้ร้อง
# 🚫 ไม่อยู่ใน prebuild (เปิดพอร์ต 8191 ชั่วคราว) — รันมือเมื่อแก้ตัววัดหรือแก้สัญญา
#
# ผลที่ต้องได้: ทุกรูปที่ปลูก rc=1 พร้อมเหตุที่ตรงกับรูปนั้น · รูป "ครบ" rc=0
# (จำนวนรูปนับจากลูปเอง — เลขที่พิมพ์ค้างในคอมเมนต์จะเน่าวันที่มีคนเพิ่มรูป)
set -u
cd "$(dirname "$0")/.." || exit 9
FIX=scripts/tests/fixtures-ท่อปลอม-แท็บชำระเงิน.mjs
FAIL=0
N=0
for m in ฐานเปลี่ยนไม่ประกาศ ประกาศแต่ยังผูก ขาดสารบัญ สองช่องฐานเดียวกัน ฐานแท็บผูกกับstatus ครบ; do
  N=$((N+1))
  node "$FIX" "$m" & SRV=$!
  sleep 1
  OUT="$(GUCUT_WEB_BASE=http://127.0.0.1:8191 node scripts/วัดสัญญาแท็บชำระเงิน.mjs 2>&1)"; RC=$?
  kill $SRV 2>/dev/null; wait $SRV 2>/dev/null
  WANT=1; [ "$m" = "ครบ" ] && WANT=0
  if [ "$RC" -eq "$WANT" ]; then printf '   ✅ %-22s rc=%s (ตามที่ต้องการ)\n' "$m" "$RC"
  else printf '   🔴 %-22s rc=%s แต่ต้องได้ %s\n' "$m" "$RC" "$WANT"; FAIL=1; fi
  printf '%s\n' "$OUT" | grep -E '^(🔴|✅|🟡|⏳)|^   ·' | head -3 | sed 's/^/        /'
done
if [ "$FAIL" -ne 0 ]; then echo "🔴 ตัววัดแยกแยะไม่ได้ครบทุกรูป ⇒ อย่าเชื่อผลเขียวของมัน"; exit 1; fi
echo "✅ ตัววัดแยกแยะได้ทั้ง $N รูป — เขียวของมันมีความหมาย"
