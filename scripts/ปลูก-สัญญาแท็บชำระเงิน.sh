#!/bin/bash
# พิสูจน์ว่า `scripts/วัดสัญญาแท็บชำระเงิน.mjs` **ร้องได้จริง และร้องถูกเหตุ**
#
# 🔑 ชี้ตัววัดไปที่ **ท่อปลอม** (โลกที่เราสั่งให้ผิดได้) ⇒ ไม่ต้องทำให้ท่อจริงผิด
#    ใบ: ท่อปลอมใช้เป็นเครื่องปลูกของเสียได้ · และ ตัวเตือนต้องเคยถูกทำให้ร้อง
# 🚫 ไม่อยู่ใน prebuild (เปิดพอร์ต 8191 ชั่วคราว) — รันมือเมื่อแก้ตัววัดหรือแก้สัญญา
#
# ผลที่ต้องได้: ทุกรูปที่ปลูก rc=1 พร้อมเหตุที่ตรงกับรูปนั้น · รูป "ครบ" rc=0
# (จำนวนรูปนับจากลูปเอง — เลขที่พิมพ์ค้างในคอมเมนต์จะเน่าวันที่มีคนเพิ่มรูป)
set -u
cd "$(dirname "$0")/.." || exit 9
FIX=scripts/tests/fixtures-ท่อปลอม-แท็บชำระเงิน.mjs
# 🔴 **จำนวนช่องในสัญญาเป็นคนตัดสินว่า "ครบ" คือครบ** ไม่ใช่มือคนเขียนท่อปลอม
#    เหตุ (14 ต.ค. 2569): สัญญาโตจาก 6 เป็น 7 ช่อง แต่ท่อปลอมโหมด "ครบ" ยังส่ง 6
#    ⇒ มันยังเขียวโดย **ไม่เคยเดินตรรกะช่องใหม่เลย** และชื่อโหมดก็ยืนยันว่าครบ
#    ⇒ ฝั่งท่อตั้งชื่อคลาสนี้ว่า **ตัวควบคุมบวกที่ไม่โตตามสัญญา**
#    ⚠️ ตัวเช็คในท่อปลอม (ตอบ 500 พร้อมชื่อช่องที่ขาด) **ตัดสินแทนไม่ได้**
#       เพราะตัววัดอ่าน 500 ว่า "ยิงไม่ได้ ⇒ ยังไม่ได้วัด (rc=0)" ⇒ ตัวพิสูจน์จะยังเขียว
#       ⇒ ต้องมีด่านที่ **ตัวพิสูจน์** เป็นคนถือ: รอบ "ครบ" ต้องพิมพ์ว่าครบ **เท่าจำนวนช่องจริง**
# 🔴 **ใช้ process.stdout.write ไม่ใช่ console.log** — `console.log(ตัวเลข)` ของ node
#    ใส่สี ANSI มาด้วย (`\x1b[33m7\x1b[39m`) ⇒ ตัวแปรที่ได้ **ไม่ใช่ "7"**
#    ⇒ grep ไม่เจอ แล้วด่านนี้ให้ **แดงลวง** (เจอของจริงตอนเขียนบรรทัดนี้เอง · ใบ ANSI ของทีม)
#    ⇒ ตาเห็นว่าเลขถูก แต่ไบต์ไม่ตรง ⇒ เถียงกับตรรกะก่อนดัมพ์ไบต์ = เสียเวลาฟรี
WANT_FIELDS="$(node --input-type=module -e \
  "import('./lib/sales-tabs.ts').then(m => process.stdout.write(String(m.ช่องสัญญาแท็บชำระเงิน.length)))" 2>/dev/null)"
if [ -z "$WANT_FIELDS" ]; then echo "🔴 อ่านจำนวนช่องในสัญญาไม่ได้ ⇒ ไม่รู้ว่า \"ครบ\" คือเท่าไหร่ ⇒ ไม่พิสูจน์"; exit 1; fi
echo "   สัญญาตอนนี้มี $WANT_FIELDS ช่อง — รอบ \"ครบ\" ต้องพิมพ์ตัวเลขนี้"
FAIL=0
N=0
for m in ฐานเปลี่ยนไม่ประกาศ ประกาศแต่ยังผูก ขาดสารบัญ สองช่องฐานเดียวกัน ฐานแท็บผูกกับstatus สองก้อนคนละฐาน ครบ; do
  N=$((N+1))
  node "$FIX" "$m" & SRV=$!
  sleep 1
  OUT="$(GUCUT_WEB_BASE=http://127.0.0.1:8191 node scripts/วัดสัญญาแท็บชำระเงิน.mjs 2>&1)"; RC=$?
  kill $SRV 2>/dev/null; wait $SRV 2>/dev/null
  WANT=1; [ "$m" = "ครบ" ] && WANT=0
  if [ "$RC" -eq "$WANT" ]; then printf '   ✅ %-22s rc=%s (ตามที่ต้องการ)\n' "$m" "$RC"
  else printf '   🔴 %-22s rc=%s แต่ต้องได้ %s\n' "$m" "$RC" "$WANT"; FAIL=1; fi
  # รอบ "ครบ" ต้องเขียวเพราะ **สัญญาครบจริง** ไม่ใช่เพราะช่องน้อยลง/ยิงไม่ได้
  if [ "$m" = "ครบ" ] && ! printf '%s' "$OUT" | grep -q "ครบสัญญาทั้ง $WANT_FIELDS ช่อง"; then
    printf '   🔴 %-22s เขียวแต่ **ไม่ได้ครบ %s ช่อง** ⇒ ท่อปลอมไม่โตตามสัญญา\n' "$m" "$WANT_FIELDS"
    FAIL=1
  fi
  printf '%s\n' "$OUT" | grep -E '^(🔴|✅|🟡|⏳)|^   ·' | head -3 | sed 's/^/        /'
done
if [ "$FAIL" -ne 0 ]; then echo "🔴 ตัววัดแยกแยะไม่ได้ครบทุกรูป ⇒ อย่าเชื่อผลเขียวของมัน"; exit 1; fi
echo "✅ ตัววัดแยกแยะได้ทั้ง $N รูป — เขียวของมันมีความหมาย"
