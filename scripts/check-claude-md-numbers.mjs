#!/usr/bin/env node
/* ตัวเลขใน CLAUDE.md ต้องวัดซ้ำได้ — **รายงานอย่างเดียว ไม่ทำให้ build ตก**
 * (19 ก.ย. 2569 · ใบ S5)
 *
 * 🔴 ที่มา: ใบ S5 เจอว่า CLAUDE.md เขียนว่า middleware ยกเว้น **3 เส้น**
 *    ของจริงใน `PUBLIC_PATHS` มี **12 รายการ** ⇒ มากกว่าที่คู่มือบอก 9
 *    คนอ่านคู่มือจะเชื่อว่ามีแค่ 3 เส้นที่อยู่นอกกำแพงล็อกอิน ⇒ **ประเมินความเสี่ยงต่ำกว่าจริง**
 *    และ **ไม่มีอะไรฟ้องว่าคู่มือล้าสมัย** — ค้างอยู่อย่างนั้นได้ไม่จำกัดเวลา
 *
 * 🔑 รูปที่ฝั่งท่อสรุปและผมเห็นด้วย: **คู่มือบอกจำนวน · ด่านเป็นคนเฝ้าจำนวนนั้น**
 *    คู่มือที่ไล่ชื่อจะค้างทุกครั้งที่มีของเพิ่ม · คู่มือที่บอก "N รายการ ดูที่ไฟล์ X" ค้างยากกว่ามาก
 *    เพราะมีตัวนับคอยเทียบให้
 *
 * 🚫 **ทำไมไม่ทำให้ build ตก** (ตั้งใจ — และเป็นข้อที่ฝั่งท่อกำชับวันนี้)
 *    CLAUDE.md **ห้ามแก้เอง** (ใบ S5 สั่งไว้ · ต้องให้ CEO/ท่านประธานตัดสิน)
 *    ⇒ ด่านที่ทำ build ตกด้วยเหตุที่คนเจอแก้ไม่ได้ **จะถูกถอดทั้งด่านภายในวันเดียว**
 *    ⇒ ดังนั้นรายงานให้ดัง แล้วเขียนตรง ๆ ว่า **นี่คือหนี้ ไม่ใช่ผ่าน**
 *
 * 🔒 **แต่ตะแกรงพังต้องแดง** — ถ้าหาประโยคที่ลงทะเบียนไว้ใน CLAUDE.md ไม่เจอแล้ว
 *    (มีคนแก้ถ้อยคำ) ⇒ ตัวนับนั้นเงียบไปเฉย ๆ โดยไม่มีใครรู้ ⇒ **นั่นคือเขียวตลอดกาล**
 *    ⇒ กรณีนั้น exit 1 เพราะ **แก้ได้จริงโดยไม่ต้องแตะ CLAUDE.md** (แก้ที่ทะเบียนในไฟล์นี้)
 */
import { readFileSync, readdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const คู่มือ = readFileSync(join(ROOT, 'CLAUDE.md'), 'utf8')

/** ทะเบียนคำกล่าวอ้างที่วัดซ้ำได้
 *  `หา`    = ประโยค/ชิ้นส่วนที่ต้องเจอใน CLAUDE.md (หาไม่เจอ ⇒ แดง เพราะตะแกรงพัง)
 *  `คู่มือว่า` = จำนวนที่คู่มือบอก (อ่านจากประโยคนั้น ไม่ใช่พิมพ์ซ้ำ ถ้าทำได้)
 *  `วัด`   = วัดของจริงในเครื่อง (ห้ามยิงเน็ต — ด่านนี้อยู่ใน prebuild)
 *  `หน่วย` = **นับอะไร** — ต้องพิมพ์ออกมาทุกครั้ง
 *
 * 🔴 **ด่านต้องนับด้วยวิธีที่เอกสารประกาศ ไม่ใช่วิธีที่สะดวกกับภาษาที่เราเขียนด่าน**
 *    (ฝั่งท่อเจอกับตัวเอง 19 ก.ย. 2569: เขานับด้วย `readdirSync().length` ได้ 5824
 *     คู่มือเขียน 5823 เพราะคู่มือประกาศวิธีนับไว้ว่า `ls | wc -l` ซึ่ง **ไม่นับ dotfile**
 *     ⇒ คู่มือถูก · ตัวนับต่างวิธี ⇒ เกือบรายงานว่าคู่มือค้างทั้งที่ไม่ค้าง)
 *    ⚠️ ฝั่งเราเสี่ยงคลาสเดียวกัน: `PUBLIC_PATHS` มี **12 รายการ** แต่กางเป็น **เส้นจริง 15 เส้น**
 *       ⇒ ถ้าด่านนับอย่างหนึ่งแล้วคู่มือเขียนอีกอย่าง จะแดงถาวรทั้งที่ทั้งคู่ถูก
 *       ⇒ **พิมพ์หน่วยที่นับออกมาเสมอ ไม่ใช่รู้กันเอง** */
const ทะเบียน = [
  {
    ชื่อ: 'เส้นที่อยู่นอกกำแพงล็อกอิน',
    หา: 'ล็อกทั้งเว็บด้วย SITE_PASSWORD',
    คู่มือว่า: (t) => {
      /* คู่มือเขียนเป็นรายชื่อในวงเล็บ "(ยกเว้น /login, /api/auth, /api/google)" ⇒ นับชื่อ */
      const m = t.match(/ล็อกทั้งเว็บด้วย SITE_PASSWORD\s*\(ยกเว้น([^)]*)\)/)
      return m ? m[1].split(',').filter((x) => x.trim()).length : null
    },
    วัด: () => {
      const m = readFileSync(join(ROOT, 'middleware.ts'), 'utf8').match(/const PUBLIC_PATHS = \[([\s\S]*?)\]/)
      return m ? [...m[1].matchAll(/'([^']+)'/g)].length : null
    },
    หน่วย: 'รายการใน PUBLIC_PATHS (ไม่ใช่จำนวนเส้นจริง — คำนำหน้าอย่าง /api/rokid กางได้หลายเส้น · วัดจริงวันนี้ได้ 15 เส้น)',
    ทำไมสำคัญ: 'อ่านต่ำกว่าจริง = ประเมินความเสี่ยงของกำแพงล็อกอินต่ำกว่าจริง',
  },
  {
    ชื่อ: 'ชิ้นส่วน UI ที่ใช้ซ้ำ',
    /* 🔑 ผูกกับ **ถ้อยคำที่มีความหมาย** ไม่ใช่กับช่องว่างจัดคอลัมน์ —
       รุ่นแรกผมใส่ช่องว่างตามที่เดา ⇒ หาไม่เจอ ⇒ ด่านแดงตั้งแต่รันครั้งแรก
       (ซึ่งถูกตามที่ออกแบบ: ตะแกรงพังต้องแดง ไม่ใช่เงียบ) */
    หา: 'ชิ้นส่วน UI ใช้ซ้ำ —',
    คู่มือว่า: (t) => {
      const m = t.match(/ชิ้นส่วน UI ใช้ซ้ำ\s*—([^\n]*)/)
      return m ? m[1].split(',').filter((x) => x.trim()).length : null
    },
    วัด: () => readdirSync(join(ROOT, 'components/ui')).filter((f) => f.endsWith('.tsx')).length,
    หน่วย: 'ไฟล์ .tsx ใน components/ui (ไม่นับไฟล์อื่น ไม่นับโฟลเดอร์ย่อย)',
    ทำไมสำคัญ: 'กติกาข้อ 5 สั่งให้ดูรายการนี้ก่อนเขียน markup ใหม่ ⇒ รายการไม่ครบ = เขียนซ้ำของที่มีอยู่',
  },
]

/* 🔒 ทะเบียนว่าง = ไม่มีอะไรให้ตรวจ = **เขียวที่แปลว่ายังไม่เจอ** ⇒ แดง (กฎเดิมของเรา) */
if (ทะเบียน.length === 0) {
  console.error('🔴 ทะเบียนว่าง — ด่านนี้ตรวจอะไรไม่ได้รอบนี้ ⇒ ไม่ผ่าน')
  process.exit(1)
}

let ตะแกรงพัง = 0
let ไม่ตรง = 0
console.log(`ตัวเลขใน CLAUDE.md ที่วัดซ้ำได้: ${ทะเบียน.length} รายการในทะเบียน`)

for (const x of ทะเบียน) {
  /* 🔒 แถวที่ไม่บอกหน่วย = แถวที่คนอ่านตีความเองได้สองแบบ ⇒ ไม่ให้ผ่าน */
  if (!x.หน่วย) {
    console.error(`🔴 ${x.ชื่อ}: ทะเบียนแถวนี้ไม่ได้บอกว่า **นับอะไร** ⇒ เลขที่ได้ตีความได้หลายแบบ`)
    ตะแกรงพัง++
    continue
  }
  if (!คู่มือ.includes(x.หา)) {
    console.error(`🔴 ${x.ชื่อ}: หาประโยคที่ลงทะเบียนไว้ใน CLAUDE.md ไม่เจอ`)
    console.error(`   ที่หา: "${x.หา}"`)
    console.error('   ⇒ **ตะแกรงพัง ไม่ใช่คู่มือถูก** — มีคนแก้ถ้อยคำแล้วตัวนับนี้เงียบไปเฉย ๆ')
    console.error('   ⇒ แก้ `หา` ในทะเบียนของ scripts/check-claude-md-numbers.mjs (ไม่ต้องแตะ CLAUDE.md)')
    ตะแกรงพัง++
    continue
  }
  const บอก = x.คู่มือว่า(คู่มือ)
  const จริง = x.วัด()
  if (บอก === null || จริง === null) {
    console.error(`🔴 ${x.ชื่อ}: อ่านจำนวนไม่ได้ (คู่มือ=${บอก} · วัดได้=${จริง}) ⇒ **ตัดสินไม่ได้ ไม่ใช่ผ่าน**`)
    ตะแกรงพัง++
    continue
  }
  if (บอก !== จริง) {
    console.log(`⚠️  ${x.ชื่อ}: คู่มือบอก **${บอก}** · ของจริง **${จริง}**`)
    console.log(`   นับอะไร: ${x.หน่วย}`)
    console.log(`   ${x.ทำไมสำคัญ}`)
    ไม่ตรง++
  } else {
    console.log(`   ✅ ${x.ชื่อ} = ${จริง} (ตรงกับคู่มือ · นับ: ${x.หน่วย})`)
  }
}

if (ไม่ตรง) {
  console.log(`\n📌 คู่มือค้าง ${ไม่ตรง} จุด — **นี่คือหนี้ ไม่ใช่ผ่าน**`)
  console.log('   🚫 ด่านนี้ไม่ทำให้ build ตกโดยตั้งใจ: CLAUDE.md ห้ามแก้เอง ต้องให้ CEO/ท่านประธานตัดสิน')
  console.log('   ⇒ ถ้าปล่อยให้ตกที่นี่ จะได้ด่านที่คนเจอแก้ไม่ได้ ⇒ ถูกถอดทั้งด่านภายในวันเดียว')
  console.log('   ⇒ เสนอถ้อยคำที่ค้างยากกว่า: **เขียนจำนวน + ชี้ไปที่ไฟล์ แทนการไล่ชื่อ**')
}
if (ตะแกรงพัง) {
  console.error(`\n🔴 ตะแกรงของด่านนี้พัง ${ตะแกรงพัง} จุด ⇒ ไม่ผ่าน (แก้ที่ทะเบียนในไฟล์นี้ได้เลย)`)
  process.exit(1)
}
if (!ไม่ตรง) console.log('✅ ตัวเลขที่ลงทะเบียนไว้ใน CLAUDE.md ตรงกับของจริงทุกตัว')
