#!/usr/bin/env node
/* กฎข้อ 8 ของ CLAUDE.md: *"API route ใหม่วางใต้ `app/api/<ชื่อ>/route.ts` · logic ที่ยาวแยกไป `lib/`
 * — route ทำหน้าที่รับ request/ตอบ response เท่านั้น"*
 *
 * 🔴 **ปัญหาของกฎนี้: มันไม่มีเกณฑ์ตัวเลข** (วัดเจอ 20 ก.ย. 2569 · ใบ S5)
 *    ⇒ ไม่มีวันถูกละเมิดอย่างเป็นทางการ และ **ไม่มีวันถูกตรวจ**
 *    📏 ของจริงตอนวัด: `route.ts` **48 ไฟล์ · ค่ากลาง 64 บรรทัด** · ยาวสุด 299
 *
 * 🔑 **ทำไมไม่ตั้งเพดานเป็นเลขที่ "ควรจะเป็น"** — ฝั่งท่อตัดสินให้ 20 ก.ย. 2569:
 *    *"ผมตั้งเพดานให้คุณไม่ได้ จะเป็นมาตรฐานสองชั้น ⇒ ใช้ท่าเพดานนับถอยหลังแทน
 *      ไม่ต้องตกลงว่าเลขไหนถูก ตกลงแค่ว่า **ไม่แย่ลง**"*
 *    ⇒ เพดานคือ **ของจริงวันที่ตั้ง** ไม่ใช่ความเห็น ⇒ ไม่มีใครต้องอนุมัติเลขนี้
 *
 * 🔴 **และเพดานต้องฟ้องเมื่อ "ต่ำกว่าเพดาน" ด้วย** (ข้อที่ฝั่งท่อเพิ่งโดนกับตัวเอง:
 *    เพดาน 46 ของจริง 45 ⇒ **มีช่องให้แย่ลง 1 จุดโดยไม่มีใครรู้**)
 *    ⇒ เพดานที่ไม่ถูกขันให้แน่นทุกครั้ง จะค่อย ๆ กลายเป็นเพดานที่ไม่ได้กันอะไรเลย
 *
 * ⚠️ **นับบรรทัด ≠ วัดว่า logic อยู่ผิดที่** — ไฟล์ยาวเพราะคอมเมนต์อธิบายเหตุผลก็มี
 *    ⇒ ด่านนี้เป็น **ตัวชี้เป้า** ไม่ใช่ตัวตัดสิน · หน้าที่มันคือ **กันไม่ให้ยาวขึ้นเงียบ ๆ**
 */
import { readdirSync, readFileSync, statSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join, relative } from 'node:path'

const ROOT = fileURLToPath(new URL('..', import.meta.url))

/** 📌 เพดาน = **จำนวนบรรทัดของ route ที่ยาวที่สุด ณ วันที่ตั้ง** (ไม่ใช่เลขที่ใครคิดว่าเหมาะ)
 *  วัดเมื่อ 20 ก.ย. 2569 · ไฟล์ที่ยาวที่สุดคือ `app/api/bills/vendor/route.ts`
 *  ⇒ **ลดได้อย่างเดียว** · ขึ้น = ด่านตก · ลงแล้วไม่แก้เลขนี้ = ด่านตกเหมือนกัน */
const เพดาน = 299

function เดิน(dir, out = []) {
  for (const n of readdirSync(dir)) {
    const p = join(dir, n)
    if (statSync(p).isDirectory()) เดิน(p, out)
    else if (n === 'route.ts') out.push(p)
  }
  return out
}

const ไฟล์ = เดิน(join(ROOT, 'app', 'api'))
/* 🔒 ไม่มีไฟล์ให้กวาด = ตะแกรงพัง ไม่ใช่รีโปสะอาด (กติกาเดิมของทีม) */
if (ไฟล์.length < 10) {
  console.error(`🔴 เจอ route.ts แค่ ${ไฟล์.length} ไฟล์ — **ตัวเดินไฟล์พัง ไม่ใช่ route หาย**`)
  process.exit(1)
}

const วัด = ไฟล์
  .map((p) => ({ ไฟล์: relative(ROOT, p), บรรทัด: readFileSync(p, 'utf8').split('\n').length }))
  .sort((a, b) => b.บรรทัด - a.บรรทัด)
const สูงสุด = วัด[0]
const กลาง = วัด[Math.floor(วัด.length / 2)].บรรทัด

console.log(`กฎข้อ 8 — ขนาด route: **${ไฟล์.length} ไฟล์** · ค่ากลาง ${กลาง} บรรทัด · ยาวสุด ${สูงสุด.บรรทัด} (${สูงสุด.ไฟล์}) · เพดาน ${เพดาน}`)
console.log(`   สามอันดับแรก: ${วัด.slice(0, 3).map((x) => `${x.บรรทัด} (${x.ไฟล์})`).join(' · ')}`)
console.log('   ⚠️ ด่านนี้นับบรรทัด ไม่ได้ตัดสินว่า logic อยู่ผิดที่ — หน้าที่มันคือกันไม่ให้ยาวขึ้นเงียบ ๆ')

if (สูงสุด.บรรทัด > เพดาน) {
  console.error(`\n🔴 route ยาวเกินเพดาน: ${สูงสุด.ไฟล์} มี ${สูงสุด.บรรทัด} บรรทัด (เพดาน ${เพดาน})`)
  console.error('   ⇒ กฎข้อ 8 บอกว่า route ทำหน้าที่รับ request/ตอบ response เท่านั้น')
  console.error('   ⇒ ย้าย logic ไป `lib/` แล้วให้ route เรียก — **ห้ามขยับเพดานขึ้นเพื่อให้ผ่าน**')
  process.exit(1)
}

if (สูงสุด.บรรทัด < เพดาน) {
  console.error(`\n🔴 ของจริงต่ำกว่าเพดานแล้ว (${สูงสุด.บรรทัด} < ${เพดาน}) — **ต้องขันเพดานให้แน่นในคอมมิตเดียวกัน**`)
  console.error(`   แก้ \`const เพดาน = ${เพดาน}\` เป็น \`${สูงสุด.บรรทัด}\` ในไฟล์นี้`)
  console.error('   🔑 เหตุผล: เพดานที่สูงกว่าของจริง = **ช่องให้แย่ลงเงียบ ๆ** โดยไม่มีใครรู้')
  console.error('      (ฝั่งท่อโดนข้อนี้กับตัวเอง 20 ก.ย. 2569: เพดาน 46 ของจริง 45)')
  process.exit(1)
}

console.log('✅ ยาวสุดเท่ากับเพดานพอดี — ไม่มีช่องให้แย่ลงโดยไม่มีใครรู้')
