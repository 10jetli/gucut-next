#!/usr/bin/env node
/* **ไฟล์ไหนถูกเทสเดินผ่านจริง** — วัดจากของที่รันจริง ไม่ใช่จากการค้นชื่อในซอร์ส
 * 🚫 **ไม่อยู่ใน prebuild** (รันเทสทุกตัว · ช้าเป็นนาที) · เรียกตอนอยากรู้
 *
 * 🔴 **ที่มา 29 ก.ย. 2569 (ใบ t_mu8i1pu1) — ผมวัดผิดด้วยมือตัวเอง**
 *    ผมวัด "ไฟล์ที่ยังไม่มีเทสแตะ" ด้วยวิธี *ไม่มีอะไรใน scripts/ เอ่ยชื่อมันเลย*
 *    วันนั้น `lib/emailPdf.ts` (619 บรรทัด · ตัวสร้าง PDF ที่บัญชีเอาไปยื่นภาษี)
 *    หลุดจากรายชื่อ **เพราะเทสของผมเองเอ่ยชื่อมันตอนปลอมมันทิ้ง** ไม่ได้ทดสอบเลยแม้บรรทัดเดียว
 *    ⇒ และตัววัดแบบนั้น **ยิ่งผิดทิศดีขึ้นทุกครั้งที่เขียนเทสเพิ่ม** เพราะเทสที่ปลอมของยิ่งเอ่ยชื่อของมากขึ้น
 *       คือตัววัดที่สวนทางกับสิ่งที่มันควรวัด
 *
 * 🔑 **ท่านี้ฝั่งท่อ (CEO) เสนอ และไล่รูให้สามรอบก่อนผมลงมือ** — เขียนไว้ทั้งสามรอบเพราะ
 *    ทุกรอบเป็นรูที่ "ตัววัดจะให้เลขสวยขึ้นโดยไม่มีอะไรฟ้อง"
 *
 *    รอบ ① วัดด้วย coverage แทนการค้นชื่อ
 *       🔴 วัดแล้ว **ใช้ตรง ๆ ไม่ได้** — coverage บันทึกแต่ `.js` ในที่ชั่วคราว ไม่มี `.ts` เลยแม้อันเดียว
 *          (เทส 39 จาก 67 คอมไพล์ `.ts` ลงที่ชั่วคราวชื่อสุ่มแล้วลบทิ้งใน finally)
 *       ⇒ จึงให้ **คอมไพเลอร์เป็นคนจดแผนที่** ผ่าน shim ของ `npx` ที่เติม `--inlineSourceMap`
 *          (ต้อง shim ที่ `npx` ไม่ใช่ `tsc` เพราะ npx หาใน node_modules/.bin ก่อน PATH)
 *
 *    รอบ ② จับคู่ด้วยชื่อฐานคือเดา และถูกแค่วันนี้
 *       ⇒ อ่านพาธ `.ts` จากแผนที่ที่คอมไพเลอร์เขียน ไม่เดาจากชื่อ
 *       🔑 และธงนั้นปิดรูที่ผมเจอเองด้วย: แผนที่มี **ของที่ถูก import ต่อ** อยู่ในนั้น
 *          (เดิมถ้านับแค่ไฟล์ที่ถูกสั่งคอมไพล์ `lib/bill-filing.ts` จะถูกรายงานว่าไม่ถูกแตะ = ลบลวง)
 *
 *    รอบ ③ **lib ที่ถูกทดสอบเฉพาะโดยเทสที่ไม่ผ่าน tsc จะตกไปกองไม่ถูกแตะ** = ลบลวงคลาสเดิมจากทางอื่น
 *       ⇒ วัดแล้ว: เทส 5 ไฟล์ import `../../lib/x.ts` ตรง ๆ และ Node ลอกชนิดเองได้
 *          ⇒ coverage บันทึกเป็น `.ts` อยู่แล้ว **ไม่ต้องใช้ shim กับกองนั้น**
 *       ⇒ และเลิกจำแนกเทสด้วย grep ทั้งหมด — **รันทุกตัวแล้วให้การวัดเป็นคนตอบ**
 *          (ของเดิมจำแนกได้ 39 + 5 + 2 เหลือ 21 ไฟล์ที่ต้องเปิดอ่านทีละตัว = ที่ซ่อนของรูที่สี่)
 *
 * 🔒 **คำที่ห้ามใช้** (CEO สั่งตรง ๆ 29 ก.ย. 2569): ห้ามพิมพ์ว่า **"ไม่มีใครแตะ"**
 *    เพราะเรารู้แค่ว่า "ไม่พบว่าถูกแตะ **ในขอบเขตที่วัดได้**"
 *    ⇒ และทุกเลขต้องมีป้ายขอบเขตกำกับ ไม่ใช่เลขลอย ๆ
 */
import { execFileSync, spawnSync } from 'node:child_process'
import { readdirSync, readFileSync, writeFileSync, mkdtempSync, rmSync, existsSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, dirname, basename, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
process.chdir(ROOT)
const SHIM = join(ROOT, 'scripts/lib/shim-npx')
const เฉพาะ = process.argv.slice(2).filter((a) => !a.startsWith('-'))

/* หา npx ตัวจริง — **ต้องไม่ใช่ shim ของเราเอง** ไม่งั้นเรียกตัวเองไม่รู้จบ
   (บทเรียนเดิมของทีม: เครื่องมือที่กวาดไฟล์จะเจอตัวเอง) */
const npxจริง = (process.env.PATH ?? '').split(':')
  .filter((d) => d && resolve(d) !== resolve(SHIM))
  .map((d) => join(d, 'npx')).find((p) => existsSync(p))
if (!npxจริง) { console.error('🔴 หา npx ตัวจริงไม่เจอ ⇒ วัดไม่ได้ (ไม่ใช่ "ไม่มีอะไรถูกแตะ")'); process.exit(1) }

const งาน = mkdtempSync(join(tmpdir(), 'แตะจริง-'))
const ทั้งหมด = readdirSync('scripts/tests').filter((f) => f.endsWith('.mjs')).sort()
const เทส = เฉพาะ.length ? ทั้งหมด.filter((f) => เฉพาะ.some((a) => f.includes(a))) : ทั้งหมด

const เดินจริง = new Set()          // พาธจริงของไฟล์ที่ถูกเรียกใช้จริง
const ไม่มีฟังก์ชัน = new Set()      // โหลดแล้วแต่ **ไม่มีฟังก์ชันให้เรียก** (ข้อมูล/ชนิดล้วน)
/* 🔑 **"ไม่ถูกโหลดเลย" กับ "โหลดแล้วไม่มีใครเรียก" คนละเรื่อง และเรื่องแรกคือหัวใจของงานนี้**
   ไฟล์ที่คอมไพเลอร์พ่นให้แต่ **ไม่เคยถูกโหลด** = เทสเปลี่ยนเส้น import ไปที่ตัวปลอม
   ซึ่งคือเคส emailPdf ที่ทำให้ตัววัดเดิมของผมให้เลขดีเกินจริง ⇒ ต้องแยกออกมาให้อ่านเห็น */
const เคยโหลด = new Set()
const แผนที่ = new Map()            // js ที่คอมไพเลอร์พ่น → ts ต้นทาง
const ที่ออก = new Set()            // โฟลเดอร์ที่คอมไพเลอร์พ่นลง
const วัดไม่ได้ = []
const เทสที่ล้ม = []

for (const f of เทส) {
  const cov = join(งาน, 'cov', f)
  const man = join(งาน, `${f}.map.jsonl`)
  const r = spawnSync('node', [join('scripts/tests', f)], {
    env: { ...process.env, PATH: `${SHIM}:${process.env.PATH}`,
      GUCUT_REAL_NPX: npxจริง, GUCUT_TSC_MANIFEST: man, NODE_V8_COVERAGE: cov },
    encoding: 'utf8', timeout: 300_000,
  })
  if (r.status !== 0) เทสที่ล้ม.push(`${f} (exit ${r.status})`)
  if (existsSync(man)) {
    for (const l of readFileSync(man, 'utf8').trim().split('\n').filter(Boolean)) {
      const x = JSON.parse(l)
      if (x.measurable === false) { วัดไม่ได้.push(`${f}: ${x.why}`); continue }
      if (x.js) { ที่ออก.add(dirname(x.js)); if (x.ts) แผนที่.set(x.js, x.ts) }
    }
  }
  if (!existsSync(cov)) continue
  for (const c of readdirSync(cov)) {
    let ก้อน
    try { ก้อน = JSON.parse(readFileSync(join(cov, c), 'utf8')) } catch { continue }
    for (const s of ก้อน.result ?? []) {
      if (!s.url?.startsWith('file://')) continue
      /* 🔑 **"โหลดแล้ว" ไม่เท่ากับ "ถูกเรียก"** — ตัวห่อโมดูลนับ 1 เสมอ
         ⇒ ต้องมีฟังก์ชันที่มีชื่อ และมีช่วงที่ count > 0 อย่างน้อยหนึ่งตัว
         (ถ้าไม่แยกข้อนี้ ไฟล์ที่แค่ถูก import แล้วไม่มีใครเรียก จะนับว่าทดสอบแล้ว) */
      const ที่ = decodeURIComponent(s.url.slice(7))
      เคยโหลด.add(ที่)
      const fn = (s.functions ?? []).filter((x) => x.functionName !== '')
      /* 🔴 **ไฟล์ที่ไม่มีฟังก์ชันที่มีชื่อเลย จะไม่มีวันถูกนับว่า "เดิน"** (เจอ 29 ก.ย. 2569 รอบวัดเต็ม)
         `lib/vendors.ts` มีฟังก์ชัน 0 ตัว (ข้อมูลล้วน) · `lib/types.ts` เป็นชนิดล้วน
         ⇒ เกณฑ์ "ต้องมีฟังก์ชันถูกเรียก" **ตัดสองไฟล์นี้ทิ้งตลอดกาล** ทั้งที่ทุกจอใช้มันอยู่
         ⇒ แยกเป็นสถานะของตัวเอง ไม่งั้นมันจะไปนอนในกอง "ไม่ถูกเรียก" เป็นหนี้ปลอมถาวร */
      if (fn.length === 0) { ไม่มีฟังก์ชัน.add(ที่); continue }
      if (fn.some((x) => x.ranges.some((g) => g.count > 0))) เดินจริง.add(ที่)
    }
  }
}

const pkg = JSON.parse(readFileSync('package.json', 'utf8'))
const ด่านในลูกโซ่ = [...new Set([...(pkg.scripts?.prebuild ?? '').matchAll(/scripts\/[^\s&|]+\.mjs/g)].map((m) => m[0]))]
const ด่านที่รันโค้ด = ด่านในลูกโซ่.filter((x) => x.includes('/tests/'))
const ด่านอ่านซอร์ส = ด่านในลูกโซ่.filter((x) => !x.includes('/tests/'))
const สั้น = (p) => p.replace(ROOT, '').replace(/^\//, '')
const libทั้งหมด = readdirSync('lib').filter((f) => f.endsWith('.ts')).map((f) => join(ROOT, 'lib', f))
const ถูกเดิน = new Set()
for (const p of เดินจริง) {
  if (p.endsWith('.ts')) ถูกเดิน.add(p)                  // Node รัน .ts ตรง ๆ (ลอกชนิดเอง)
  else if (แผนที่.has(p)) ถูกเดิน.add(แผนที่.get(p))      // ผ่านแผนที่ที่คอมไพเลอร์เขียน
}
const พ่นแต่ไม่เดิน = [...new Set([...แผนที่.values()])]
  .filter((ts) => !ถูกเดิน.has(ts) && ![...ไม่มีฟังก์ชัน].some((js) => แผนที่.get(js) === ts))
const ไม่มีฟังก์ชันให้เรียก = libทั้งหมด.filter((ts) => ไม่มีฟังก์ชัน.has(ts)
  || [...ไม่มีฟังก์ชัน].some((js) => แผนที่.get(js) === ts))
const ไม่พบว่าถูกแตะ = libทั้งหมด.filter((ts) => !ถูกเดิน.has(ts)
  && !พ่นแต่ไม่เดิน.includes(ts) && !ไม่มีฟังก์ชันให้เรียก.includes(ts))
const หลักฐานดิบ = [...เดินจริง]
  .filter((p) => ที่ออก.has(dirname(p)) && !แผนที่.has(p))

/* 🔑 **ป้ายขอบเขตขึ้นก่อนตัวเลข** (กติกาของทีม: เลขที่ไม่มีขอบเขตกำกับถูกอ่านเป็นยอดรวมเสมอ) */
const ป้าย = `ครอบเทส ${เทส.length} จาก ${ทั้งหมด.length} ไฟล์`
  + ` · รันสำเร็จ ${เทส.length - เทสที่ล้ม.length} · ล้ม ${เทสที่ล้ม.length}`
console.log(`📐 **ขอบเขตของทุกเลขข้างล่าง: ${ป้าย}**`)
console.log(`   ไฟล์ใน lib/ ที่เอามาถาม ${libทั้งหมด.length} ไฟล์ · วัดจาก **ของที่รันจริง** ไม่ใช่การค้นชื่อในซอร์ส`)
/* 🔴 **จุดตาบอดถาวรของวิธีนี้ — เขียนไว้ก่อนตัวเลข ไม่ใช่เป็นเชิงอรรถ** (29 ก.ย. 2569)
   ลูกโซ่ prebuild มีด่าน ${ด่านในลูกโซ่.length} ตัว แต่มีแค่ ${ด่านที่รันโค้ด.length} ตัวที่อยู่ใน scripts/tests/
   อีก ${ด่านอ่านซอร์ส.length} ตัว **อ่านซอร์สเป็นข้อความ ไม่ได้รันโค้ด** (เช่นตัวที่เฝ้าทะเบียนปุ่มส่งจริง
   อ่าน lib/real-send.ts เป็นข้อความ) ⇒ coverage มองไม่เห็นโดยธรรมชาติ ไม่ใช่เพราะไฟล์ไม่มีตาข่าย
   ⇒ **ช่อง ③ ไม่ได้แปลว่า "ไม่มีตาข่าย"** — เป็นคลาสเดียวกับที่ทีมเคยเจอ
      (ตัวนับที่วัดกลไกเดียว รายงานว่าไม่มีตาข่าย: หนี้ 44 ที่แท้จริง 2) */
console.log(`   🔒 **จุดตาบอด**: ลูกโซ่มีด่าน ${ด่านในลูกโซ่.length} ตัว · ตัวนี้รันได้แค่ ${ด่านที่รันโค้ด.length} ตัวใน scripts/tests/`)
console.log(`      อีก ${ด่านอ่านซอร์ส.length} ตัว **อ่านซอร์สเป็นข้อความ** ⇒ coverage มองไม่เห็น`)
console.log('      ⇒ ช่อง ③ อ่านว่า "coverage ไม่เห็น" **ไม่ใช่** "ไม่มีตาข่าย"')
if (เทสที่ล้ม.length) {
  console.log(`   🔴 เทสที่ล้ม ${เทสที่ล้ม.length} ตัว ⇒ ส่วนที่มันควรครอบ **ยังไม่ได้วัด** ไม่ใช่ "ไม่ถูกแตะ"`)
  for (const x of เทสที่ล้ม) console.log(`      · ${x}`)
}
if (วัดไม่ได้.length) {
  console.log(`   🔴 คอมไพล์ที่หาที่ออกไม่ได้ ${วัดไม่ได้.length} ครั้ง ⇒ ผลของรอบนั้นหายจากการวัด`)
  for (const x of วัดไม่ได้) console.log(`      · ${x}`)
}

console.log(`\n① **ถูกเทสเดินผ่านจริง ${[...ถูกเดิน].filter((p) => p.includes('/lib/')).length} ไฟล์**`)
for (const p of [...ถูกเดิน].filter((x) => x.includes('/lib/')).sort()) console.log(`   ${สั้น(p)}`)

const jsของ = (ts) => [...แผนที่.entries()].filter(([, t]) => t === ts).map(([j]) => j)
const ไม่ถูกโหลดเลย = พ่นแต่ไม่เดิน.filter((ts) => !jsของ(ts).some((j) => เคยโหลด.has(j)))
const โหลดแล้วไม่มีใครเรียก = พ่นแต่ไม่เดิน.filter((ts) => jsของ(ts).some((j) => เคยโหลด.has(j)))
console.log(`\n②ก **คอมไพเลอร์พ่นให้ แต่ไม่ถูกโหลดเลย ${ไม่ถูกโหลดเลย.length} ไฟล์**`)
console.log('   🔑 กองนี้คือหัวใจของงาน — เทส import มันในซอร์ส **แต่เปลี่ยนเส้นไปที่ตัวปลอม**')
console.log('      ⇒ ตัววัดแบบค้นชื่อจะนับว่า "มีเทสแตะ" ทั้งที่ไม่มีบรรทัดไหนถูกรัน')
for (const p of ไม่ถูกโหลดเลย.sort()) console.log(`   ${สั้น(p)}`)
console.log(`\n②ข **โหลดแล้ว แต่ไม่มีฟังก์ชันไหนถูกเรียก ${โหลดแล้วไม่มีใครเรียก.length} ไฟล์**`)
for (const p of โหลดแล้วไม่มีใครเรียก.sort()) console.log(`   ${สั้น(p)}`)

/* 🔒 ห้ามเขียนว่า "ไม่มีใครแตะ" — เรารู้แค่ว่าไม่พบในขอบเขตที่วัดได้ (CEO สั่ง 29 ก.ย. 2569) */
console.log(`\n②ค **โหลดแล้ว แต่ไม่มีฟังก์ชันให้เรียก ${ไม่มีฟังก์ชันให้เรียก.length} ไฟล์**`)
console.log('   (ข้อมูลล้วน/ชนิดล้วน — สถานะนี้ถูกต้องถาวร ไม่ใช่หนี้ที่ต้องไปแก้)')
for (const p of ไม่มีฟังก์ชันให้เรียก.sort()) console.log(`   ${สั้น(p)}`)

console.log(`\n③ **ไม่พบว่าถูกแตะในขอบเขตที่วัดได้ ${ไม่พบว่าถูกแตะ.length} ไฟล์** (${ป้าย})`)
for (const p of ไม่พบว่าถูกแตะ.sort()) console.log(`   ${สั้น(p)}`)

console.log(`\n④ หลักฐานดิบ — เดินจริงในที่ออกของคอมไพเลอร์ แต่คอมไพเลอร์ไม่ได้พ่น ${หลักฐานดิบ.length} ไฟล์`)
console.log('   ⚠️ **หลักฐาน ไม่ใช่คำตัดสิน** — บอกได้แค่ว่าไม่ใช่ผลผลิตของคอมไพเลอร์')
console.log('      ไม่บอกว่ามันแทนไฟล์ไหน เพราะถ้าเดาจากชื่อก็กลับไปวัดร่องรอยอีก')
for (const p of [...new Set(หลักฐานดิบ.map((p) => basename(p)))].sort()) console.log(`   ${p}`)

console.log(`\n📐 ย้ำขอบเขต: ${ป้าย}`)
rmSync(งาน, { recursive: true, force: true })
