const fieldRe = /['"]?([A-Za-z_฀-๿][\w฀-๿]*)['"]?\??\s*:/g

/** เทียบว่า "ชื่อช่องนี้โผล่ในข้อความไหม" แบบที่ **ใช้ได้กับอักษรไทย**
 *  🔴 ห้ามกลับไปใช้ `\b` — มันอิงกับ `\w` ซึ่งไม่รวมอักษรไทย ⇒ `false` เสมอ
 *  ⇒ ใช้ "ขอบเขตด้วยมือ": ข้างหน้า/ข้างหลังต้องไม่ใช่ตัวอักษร เลข ขีดล่าง หรืออักษรไทย */
const ขอบของชื่อ = '[^A-Za-z0-9_\\u0e00-\\u0e7f]'
const หนีอักขระ = (s) => String(s).replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
const มีชื่อช่องในข้อความ = (ช่อง, ข้อความ) =>
  new RegExp(`(^|${ขอบของชื่อ})${หนีอักขระ(ช่อง)}($|${ขอบของชื่อ})`).test(ข้อความ)
const ตัดคอมเมนต์เข้ม = (x) => x.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/\/\/[^\n]*/g, ' ')

let ช่องที่ตรวจ = 0
const พบ = []
/* รายชื่อคีย์ที่ท่อ **ประกาศเอง** ว่าประกอบชื่อตอนรัน (ฝั่งท่อ d814552 · 19 ก.ย. 2569)
   อ่านจากสแนปช็อตสารบัญในเครื่อง — ไม่มี = ท่อรุ่นก่อนหน้านั้น ⇒ ตกไปใช้ทางถอยที่ประกาศตัว */
/* 🔑 **`catch` ที่คืน "ไม่รู้" ต้องแนบเหตุ** (กติการ่วม 20 ก.ย. 2569 · ฝั่งท่อเสนอ ผมรับ)
   🔴 ของเดิม `catch { return [] }` ⇒ **สามเหตุอ่านเหมือนกันหมด**:
      ไม่มีไฟล์สำเนา (ปกติ) · ท่อรุ่นก่อนที่ยังไม่ประกาศ composedKeys (ปกติ) ·
      **สำเนาพัง/รูปข้อมูลเปลี่ยน (ของเราพัง)** ⇒ อย่างที่สามเงียบสนิทและทำให้ด่านอ่อนลงเอง
      (ชุดว่าง = ไม่มีคีย์ที่ประกาศ ⇒ ด่านไปใช้ทางถอย "เดาไว้" ซึ่งหลวมกว่า) */
let เหตุที่ไม่มีคีย์ที่ประกาศ = null
const คีย์ที่ประกาศ = new Set((() => {
  try {
    const snap = JSON.parse(readFileSync(join(ROOT, 'lib/pipe-snapshot.json'), 'utf8'))
    const c = snap?.endpoints?.composedKeys
    if (Array.isArray(c)) return c
    if (c && typeof c === 'object') return Object.values(c).flat()
    เหตุที่ไม่มีคีย์ที่ประกาศ = 'สำเนาอ่านได้ แต่ไม่มีช่อง endpoints.composedKeys ⇒ ท่อรุ่นก่อน 19 ก.ย. 2569'
    return []
  } catch (e) {
    เหตุที่ไม่มีคีย์ที่ประกาศ = e?.code === 'ENOENT'
      ? 'ไม่มีไฟล์ lib/pipe-snapshot.json ⇒ ยังไม่เคยดึงสารบัญท่อในเครื่องนี้'
      : `อ่าน/แปลง lib/pipe-snapshot.json ไม่ได้: ${String(e?.message ?? e).slice(0, 80)}`
        + ' ⇒ **ของเราพัง ไม่ใช่ท่อรุ่นเก่า** (ด่านจะอ่อนลงเองถ้าไม่บอก)'
    return []
  }
})())
if (เหตุที่ไม่มีคีย์ที่ประกาศ) {
  console.log(`   ⚠️ ไม่มีรายชื่อคีย์ที่ท่อประกาศ ⇒ ตกไปใช้ทางถอย "เดาไว้" ซึ่งหลวมกว่า`)
  console.log(`      เหตุ: ${เหตุที่ไม่มีคีย์ที่ประกาศ}`)
}
const เดาไว้ = []
for (const file of walk(join(ROOT, 'app'))) {
  const rel = file.slice(ROOT.length).replace(/^\/+/, '')
  const src = readFileSync(file, 'utf8')
  /* ตรวจเฉพาะจอที่คุยกับท่อจริง ๆ */
  if (!src.includes('/api/web/core') && !src.includes('coreJson')) continue
  for (const [ชื่อ, เนื้อ] of อ่านinterface(src)) {
    for (const [, ช่อง] of ตัดคอมเมนต์เข้ม(เนื้อ).matchAll(fieldRe)) {
      if (ช่อง.length < 4) continue              // ชื่อสั้นมากเสี่ยงชนคำทั่วไป
      ช่องที่ตรวจ++   /* 🔑 ประชากรของด่าน — ต้องพิมพ์คู่กับจำนวนที่ยกเว้นเสมอ
         ⇒ 'ยกเว้น 13 ช่อง' อ่านไม่ออกถ้าไม่รู้ว่าจาก 20 หรือ 2,000 (20 ก.ย. 2569 · ใบ S2) */
      const คีย์ = `${ชื่อ}.${ช่อง}`
      if (ยกเว้น[คีย์]) continue
      if (มีชื่อช่องในข้อความ(ช่อง, ข้อความท่อ)) continue
      /* 🔴 **คีย์ที่ท่อประกอบชื่อตอนรันไม่มีอยู่ในซอร์สเป็นข้อความ** (เจอ 19 ก.ย. 2569)
         ท่อเขียน `[`${prefix}ExpectedEveryHours`]: …` แล้วเรียกด้วย prefix "recipe" กับ "stock"
         ⇒ ค้นหาชื่อเต็มในซอร์สจะ **ไม่เจอตลอดกาล** ⇒ ด่านฟ้องจอที่อ่านคีย์ที่ท่อส่งมาจริง
         🔑 คลาสเดียวกับที่ฝั่งท่อเจอวันเดียวกัน (grep เจอชื่อตัวแปรภายใน ไม่ใช่ชื่อที่วิ่งบนสาย)
            แต่กลับด้าน · ข้อสรุปร่วม: **ซอร์สไม่ใช่สัญญา ⇒ สัญญาต้องประกาศตัวเอง**

         ⇒ ฝั่งท่อแก้ที่ต้นเหตุให้แล้ว: ประกาศรายชื่อไว้ที่ `?endpoints=1 → composedKeys`
            ⇒ **อ่านจากที่เขาประกาศ ดีกว่าเดาจากรูปเทมเพลต** (และดีกว่ายกเว้นทีละชื่อมาก) */
      if (คีย์ที่ประกาศ.has(ช่อง)) continue
      /* ⚠️ ทางถอยระหว่างที่ `composedKeys` ยังไม่ขึ้น — **ประกาศตัวว่ากำลังเดา ไม่เดาเงียบ ๆ**
         เดาจากรูป `${…}Suffix` ที่เจอในซอร์สจริง (ยังต้องเจอเทมเพลต ไม่ใช่ปล่อยผ่านทุกชื่อ) */
      const ส่วนท้าย = ช่อง.match(/^[a-z]+([A-Z]\w+)$/)?.[1]
      if (ส่วนท้าย && new RegExp('\\$\\{[^}]*\\}' + ส่วนท้าย + '\\b').test(ข้อความท่อ)) {
        เดาไว้.push(`${rel}  ${คีย์}`)
        continue
      }
      พบ.push({ ข้อความ: `${rel}  ${คีย์}`, ช่อง })
    }
  }
}

console.log(`ตรวจคีย์ที่จออ่านจากท่อ: **ช่องที่ตรวจ ${ช่องที่ตรวจ} ช่อง** · เทียบกับซอร์ส ../gucut-web · ยกเว้นไว้ ${Object.keys(ยกเว้น).length} ช่อง`
  + ` (${((Object.keys(ยกเว้น).length / (ช่องที่ตรวจ || 1)) * 100).toFixed(1)}% ของประชากร)`
  + (คีย์ที่ประกาศ.size ? ` · ท่อประกาศคีย์ที่ประกอบชื่อไว้ ${คีย์ที่ประกาศ.size} ช่อง` : ''))
if (เดาไว้.length) {
  /* ⚠️ ผ่านเพราะ **เดา** ไม่ใช่เพราะท่อยืนยัน ⇒ ต้องพูดออกมาทุกรอบ ไม่ใช่เงียบแล้วเขียว */
  console.log(`⚠️ ผ่านด้วยการเดาจากรูปเทมเพลต ${เดาไว้.length} ช่อง (ท่อยังไม่ประกาศ \`composedKeys\`):`)
  for (const x of เดาไว้) console.log('   ', x)
  console.log('   ⇒ พอฝั่งท่อ push แล้วรัน scripts/ดึงสารบัญท่อ.mjs ใหม่ บรรทัดนี้จะหายไปเอง')
}
/* 🔴 **"ไม่มีในซอร์สท่อ" กับ "สำเนาท่อในเครื่องเก่ากว่าที่เขา push แล้ว" คนละเรื่องกันคนละทิศ**
   ของจริง 20 ก.ย. 2569: ด่านนี้ฟ้องจอผัง ZORT 15 ช่องว่า "ไม่มีในซอร์สท่อเลย"
   ⇒ ความจริงคือ **สำเนา ../gucut-web ในเครื่องนี้ไม่มีคอมมิตนั้น** ทั้งที่มันเป็น *ยอดของ origin/main*
      (local HEAD ของฝั่งท่อแยกทางจาก origin/main อยู่)
   ⇒ ถ้าไม่แยกสองอย่างนี้ ทางแก้ที่คนจะทำคือ **ใส่ยกเว้นทีละช่อง** ⇒ ตาข่ายหายถาวร
      เพราะเหตุผลที่เขียนในยกเว้นจะเป็น "ตรวจแล้วมีจริง" ซึ่งจริงวันนี้ และไม่มีใครมาถอดวันที่มันเปลี่ยน */
let ข้อความท่อOrigin = ''
let อ่านOriginได้ = false
try {
  const tmp = mkdtempSync(join(tmpdir(), 'pipe-origin-'))
  /* ⚠️ ดึงเฉพาะสามโฟลเดอร์ที่ใช้ — `git archive` ทั้งรีโปของท่อได้ **492 MB**
     (มี out/ กับรูปติดมาด้วย) ⇒ ด่านที่กินดิสก์ครึ่งกิกะไบต์ต่อรอบ คือด่านที่จะถูกถอด */
  for (const base of ['netlify', 'src', 'scripts']) {
    try {
      execSync(`git -C ${JSON.stringify(PIPE)} archive --format=tar origin/main ${base} | tar -x -C ${JSON.stringify(tmp)}`,
        { stdio: ['ignore', 'ignore', 'ignore'] })
    } catch { continue }   // โฟลเดอร์นั้นไม่มีใน origin/main ⇒ ข้าม ไม่ใช่ล้มทั้งด่าน
    const dir = join(tmp, base)
    if (!existsSync(dir)) continue
    /* ⚠️ ใช้ `walk()` ตรง ๆ ไม่ได้ — มันเก็บเฉพาะ `.tsx` (ของฝั่งจอ)
       ถ้าเผลอใช้ จะได้คลังเปล่า **แล้วทุกช่องจะกลายเป็น "ไม่มีบน origin" เงียบ ๆ**
       ⇒ ตัวเดินไฟล์คนละงาน ต้องคนละตัว */
    const เดินท่อ = (d) => {
      for (const name of readdirSync(d)) {
        if (name === 'node_modules') continue
        const p = join(d, name)
        if (statSync(p).isDirectory()) เดินท่อ(p)
        else if (/\.(mjs|js|ts|tsx|json)$/.test(name)) ข้อความท่อOrigin += '\n' + ตัดคอมเมนต์(readFileSync(p, 'utf8'))
      }
    }
    เดินท่อ(dir)
  }
  อ่านOriginได้ = true
  rmSync(tmp, { recursive: true, force: true })
} catch {
  /* ไม่มี git / ไม่มี origin/main ⇒ **ตอบไม่ได้ว่าเก่าหรือไม่มีจริง** ⇒ ต้องพิมพ์ ไม่ใช่เงียบแล้วตัดสิน */
}
const มีบนOrigin = (ช่อง) => อ่านOriginได้ && มีชื่อช่องในข้อความ(ช่อง, ข้อความท่อOrigin)
const เก่ากว่า = พบ.filter((x) => มีบนOrigin(x.ช่อง))
const ไม่มีจริง = พบ.filter((x) => !มีบนOrigin(x.ช่อง))

if (เก่ากว่า.length) {
  console.log(`\n⚠️ ${เก่ากว่า.length} ช่อง **มีอยู่บน origin/main ของท่อแล้ว แต่ยังไม่มีในสำเนาที่เครื่องนี้อ่าน**`)
  for (const x of เก่ากว่า) console.log('   ' + x.ข้อความ)
  console.log('   ⇒ ไม่ใช่ความผิดของจอ และ **ไม่ใช่ของที่ควรใส่ยกเว้น** — สำเนาท่อในเครื่องตามไม่ทันเฉย ๆ')
  console.log('   ⇒ แก้ที่ต้นเหตุ: ฝั่งท่อ `git pull` ให้สำเนาตรงกับ origin/main')
}
if (!อ่านOriginได้ && พบ.length) {
  console.log('\n⚠️ อ่าน origin/main ของท่อไม่ได้ ⇒ **แยกไม่ออก**ว่า "ไม่มีจริง" หรือ "สำเนาเก่า" — ถือว่าไม่มีจริงไว้ก่อน')
}
if (ไม่มีจริง.length) {
  console.error('\n🔴 จออ่านชื่อช่องที่ไม่มีในซอร์สท่อเลย (ทั้งในสำเนาและบน origin/main) — ค่าจะเป็น undefined เงียบ ๆ')
  for (const x of ไม่มีจริง) console.error('   ' + x.ข้อความ)
  console.error('\n   ⚠️ undefined ที่ถูกเขียนว่า `Number(x) || 0` จะกลายเป็น **0 ที่ดูเหมือนค่าจริง**')
  console.error('   วิธีแก้: เทียบชื่อช่องกับที่ท่อส่งจริง หรือถ้าจอสร้างค่าเอง ให้ใส่ใน `ยกเว้น` พร้อมเหตุผลที่ตรวจแล้ว')
  process.exit(1)
}
console.log('✅ ทุกชื่อช่องที่จออ่าน มีอยู่ในซอร์สท่อจริง')
