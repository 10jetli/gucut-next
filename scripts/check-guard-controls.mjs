#!/usr/bin/env node
/* **ด่านที่ไม่เคยถูกพิสูจน์ว่าตะแกรงยังแยกแยะได้ = หนี้** — ตัวนับหนี้แบบเพดานนับถอยหลัง
 *
 * 🔴 **ที่มา 20 ก.ย. 2569** — ฝั่งท่อถามตรง ๆ ว่า "ด่านในสายคุณมีตัวควบคุมฝังในกี่ตัว" (เขา 1 จาก 18)
 *    ฝั่งจอวัดได้ **3 จาก 47** ⇒ สัดส่วนพอ ๆ กัน ⇒ **เป็นหนี้ร่วม ไม่ใช่เรื่องของฝั่งใดฝั่งหนึ่ง**
 *
 * 🔑 **แยกสองแกน อย่ารวมเป็นเลขเดียว** (ฝั่งท่อยืนยันว่าถ้ารวม เขาจะลงแรงผิดแกน):
 *    ① **ตะแกรงแยกแยะได้** — มีเคส *ต้องจับ* และ *ต้องไม่จับ* **อยู่ในโค้ดที่รันจริง**
 *       ⇒ ตอบว่า "ตะแกรงยังเห็นของที่ควรเห็นไหม" ⇒ **นี่คือแกนที่ตัวนับนี้เฝ้า**
 *    ② **พื้นประชากร** — กวาดได้น้อยผิดปกติ ⇒ ประกาศว่าตะแกรงพัง ไม่ใช่ "รีโปสะอาด"
 *       ⇒ ตอบคนละคำถาม ("เรายังส่องของอยู่จริงไหม") ⇒ ไม่นับแทนกัน
 *    ③ `--self-test` ที่เป็น **ขั้นแยกใน `package.json`** — อ่อนกว่าที่เห็น:
 *       **ถอดขั้นนั้นออกเมื่อไหร่ ด่านยังเขียวโดยไม่มีอะไรฟ้อง** ⇒ ไม่นับเป็นข้อ ①
 *
 * 🔴 **และตะแกรงที่ใช้นับ ต้องตัดคอมเมนต์ก่อน** — รอบแรกผมนับเกินไป 1 ตัว
 *    เพราะไฟล์หนึ่งมีแค่ **คอมเมนต์เล่าว่าเคยทำตัวควบคุมด้วยมือ**
 *    (ฝั่งท่อนับเกินเหมือนกันแต่คนละรูป: ของเขาเป็น **สตริงในข้อความ error**)
 *    ⇒ ⇒ **"การเอ่ยถึงตัวควบคุม" กับ "การมีตัวควบคุม" แยกจาก grep เปล่า ๆ ไม่ได้**
 *
 * 📌 **ลำดับที่จะทยอยใช้หนี้ (เกณฑ์เดียวกันสองฝั่ง · ตกลงกัน 20 ก.ย. 2569)**
 *    ① ด่านที่ **ไม่เคยแดงเลย** ⇒ เสี่ยงเป็นเขียวลวงที่สุด
 *    ② ด่านที่ตะแกรงเป็น **regex** ⇒ พังเงียบง่ายที่สุด (สองฝั่งโดนคนละสองรอบในวันเดียว)
 *    ③ ด่านที่คุม **เส้นเงิน/สต็อก** ⇒ ผิดแล้วแพงที่สุด
 *
 * 🔒 **เพดาน = หนี้ของจริงวันที่ตั้ง** ⇒ ลดได้ ห้ามขึ้น · ต่ำกว่าเพดานก็ตก (ต้องขันให้แน่น)
 *    ⇒ ไม่ต้องตกลงว่า "ควรมีตัวควบคุมกี่ตัว" ตกลงแค่ว่า **ไม่แย่ลง**
 */
import { readdirSync, readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'
import { ตัดคอมเมนต์ } from './lib/ตัดคอมเมนต์.mjs'
import { สูตร } from './lib/ทะเบียนด่าน.mjs'

const ROOT = fileURLToPath(new URL('..', import.meta.url))

/** 📌 หนี้ ณ วันที่ตั้ง (20 ก.ย. 2569 · รอบแก้): ด่านในสาย 48 ตัว
 *  ⇒ มีสูตรปลูกในทะเบียน 44 · มีตัวควบคุมฝังในเพิ่มอีก 2 ⇒ **หนี้เหลือ 2** */
const เพดานหนี้ = 2

const คำควบคุม = /(ควรจับ|ต้องไม่จับ|ตะแกรงใช้ได้|ตัวควบคุมลบ|ตัวควบคุมบวก|ควบคุมบวก)/

/** ไฟล์นี้ "มีตัวควบคุมชนิดแยกแยะได้" ไหม — ตัดคอมเมนต์ก่อนเสมอ
 *  🔑 ต้องเห็นทั้ง **คำที่ประกาศเคส** และ **การเทียบผลจริง** (ไม่ใช่แค่เอ่ยถึง) */
export function มีตัวควบคุมแยกแยะ(ซอร์ส) {
  const โค้ด = ตัดคอมเมนต์(String(ซอร์ส ?? ''))
  const บรรทัด = โค้ด.split('\n')
  /* 🔴 **แก้ 20 ก.ย. 2569 รอบสอง — ฝั่งท่อยิงทดสอบคำอวดของผมแล้วพบว่าเป็นรู**
     เกณฑ์เดิมคือ "มีคำควบคุม **และ** ไฟล์นี้มี `process.exit(1)`"
     ⇒ แต่ **ด่านทุกตัวมี `process.exit(1)`** ⇒ เงื่อนไขที่สองแทบไม่ได้กรองอะไรเลย
     ⇒ ⇒ `console.error('ตัวควบคุมลบ: …')` บรรทัดเดียวในไฟล์ไหนก็ได้ **ถูกนับว่ามีตัวควบคุม**
        (ปลูกจริงแล้ว: หนี้ตกจาก 44 เหลือ 43 = **เครดิตลวง**)
     🔑 คำของฝั่งท่อที่เป็นแกนของการแก้นี้:
        **เกณฑ์ต้องผูกกับตัวของมันเอง ไม่ใช่กับอะไรก็ได้ที่อยู่ในไฟล์เดียวกัน**
     ⇒ ตอนนี้บังคับว่า **การเทียบผลต้องอยู่ใกล้คำควบคุม (±4 บรรทัด)** ⇒ คำลอย ๆ ไม่ผ่านอีก */
  /* 🔴 **รอบที่สาม — ท่า "ดูใกล้ ๆ ±4 บรรทัด" ก็ยังเป็นรู** (วัดแล้ว ไม่ได้เดา)
     เพราะในด่านจริง บล็อก `process.exit(1)` อยู่ **ท้ายไฟล์** ซึ่งเป็นที่เดียวกับที่คนจะไปต่อบรรทัดใหม่
     ⇒ ปลูกสตริงลอยท้ายไฟล์ ⇒ มันอยู่ใกล้ exit พอดี ⇒ **ยังได้เครดิตลวงเหมือนเดิม**
     🔑 ⇒ เลิกวัด "ระยะห่าง" เปลี่ยนมาผูกกับ **ตัวเคสเอง**:
        ตัวควบคุมจริงต้องมี **ผลที่คาดไว้** อยู่กับมัน — `[..., true]` / `[..., false]` หรือ `!== ควร…`
        สตริงบอกเล่าไม่มีผลที่คาด ⇒ ไม่ผ่าน · นี่คือข้อที่ฝั่งท่อสรุปไว้:
        **เกณฑ์ต้องผูกกับตัวของมันเอง ไม่ใช่กับอะไรก็ได้ที่อยู่ในไฟล์เดียวกัน** */
  const มีผลที่คาด = /(\b(true|false)\b|!==\s*ควร|===\s*ควร)/
  return บรรทัด.some((l) => คำควบคุม.test(l) && มีผลที่คาด.test(l))
}

/* ── ตัวควบคุมของด่านนี้เอง (รันทุกครั้งก่อนตัดสิน) ── */
/* 🔑 **เคสควบคุมต้องอยู่ในบริบทเดียวกับของจริง** — รอบแรกผมทดสอบเคส "สตริงลอย" บนสคริปต์สั้น
   ที่ไม่มี `process.exit(1)` ⇒ มันผ่าน ⇒ **ผมเลยไม่เห็นรู** ทั้งที่ในไฟล์จริงมี exit อยู่เสมอ
   ⇒ ⇒ เคสที่ 3 ข้างล่างจึงจำลอง **ไฟล์จริง**: สตริงลอยอยู่บรรทัดบน แล้ว exit อยู่ไกลออกไป */
const ไฟล์จำลองที่มีexitอยู่ไกล = [
  "console.error('ตัวควบคุมลบ: ข้อความเฉย ๆ ไม่ได้เทียบอะไร')",
  ...Array.from({ length: 12 }, (_, i) => `const x${i} = ${i}`),
  'if (เจอ.length) process.exit(1)',
].join('\n')

const เคสควบคุม = [
  ['const ควรจับ = true\nif (ได้ !== ควรจับ) ตก++\n', true],
  ['/* เคยทำตัวควบคุมลบด้วยมือแล้ว เล่าไว้เฉย ๆ */\nconsole.log(1)\n', false],
  [ไฟล์จำลองที่มีexitอยู่ไกล, false],
  ['console.log("ไม่เกี่ยวกับการพิสูจน์ตะแกรง")\n', false],
]
let ตกควบคุม = 0
for (const [ข้อความ, ควร] of เคสควบคุม) {
  if (มีตัวควบคุมแยกแยะ(ข้อความ) !== ควร) {
    ตกควบคุม++
    console.error(`   🔴 ตัวควบคุมไม่ผ่าน: ${JSON.stringify(ข้อความ).slice(0, 70)} ⇒ ควรได้ ${ควร}`)
  }
}
if (ตกควบคุม) {
  console.error('🔴 ตะแกรงของด่านนี้ตัดสินตัวควบคุมผิด ⇒ **ตัวเลขหนี้ข้างล่างอ่านไม่ได้**')
  process.exit(1)
}

const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'))
const ด่าน = [...new Set(
  [...(pkg.scripts?.prebuild ?? '').matchAll(/node\s+(scripts\/[^\s&|;]+\.mjs)/g)]
    .map((m) => m[1])
    .filter((p) => !p.includes('/tests/')),
)]

/* 🔒 ประชากรว่าง = อ่านสายไม่ออก ไม่ใช่ "ไม่มีด่าน" */
if (ด่าน.length < 20) {
  console.error(`🔴 อ่านด่านจากสายได้แค่ ${ด่าน.length} ตัว — **ตัวอ่าน prebuild พัง ไม่ใช่สายสั้นลง**`)
  process.exit(1)
}

/* 🔴 **แก้ใหญ่ 20 ก.ย. 2569 รอบสี่ — เลขที่ผมส่งให้ฝั่งท่อรอบก่อน (หนี้ 44) วัดผิดแกน**
   ผมนับเฉพาะ **ตัวควบคุมฝังในไฟล์** ⇒ ได้ 3 ⇒ รายงานว่าหนี้ 44
   แต่ฝั่งจอมี **ทะเบียนสูตรปลูก** (`scripts/lib/ทะเบียนด่าน.mjs`) ที่พิสูจน์ด่านด้วยการปลูกจริง
   และ **ครอบด่านในสายอยู่ 44 จาก 48 ตัว** ⇒ ⇒ ของจริงคือ **หนี้ไม่กี่ตัว ไม่ใช่ 44**
   🔑 บทเรียน: **ตัวนับที่วัดกลไกเดียว จะรายงานว่าไม่มีตาข่าย ทั้งที่ตาข่ายอยู่คนละที่**
      (และเลขที่เกินจริงทำให้อีกฝั่งลงแรงผิดที่ — ข้อที่ฝั่งท่อเตือนไว้เอง)
   ⇒ นับสองทางรวมกัน: **มีสูตรปลูกในทะเบียน** หรือ **มีตัวควบคุมฝังใน** */
/* 🔒 **อ่านทะเบียนไม่ได้ = ตก ไม่ใช่ "ไม่มีสูตร"** (ข้อที่ฝั่งท่อเพิ่มฝั่งเขา 20 ก.ย. 2569 · ผมรับมาใช้)
   ถ้าทะเบียนว่าง/พัง แล้วเราอ่านว่า "ไม่มีสูตรสักตัว" ⇒ ตัวนับจะรายงานหนี้พุ่ง
   ⇒ คนจะไปไล่เขียนตัวควบคุมใหม่ **ทั้งที่ของเดิมยังอยู่ครบ** ⇒ ลงแรงผิดที่ */
if (!Array.isArray(สูตร) || สูตร.length === 0) {
  console.error('🔴 อ่านทะเบียนสูตรปลูกไม่ได้ (ว่างหรือผิดรูป) — **นี่คือตัวอ่านพัง ไม่ใช่ไม่มีสูตร**')
  process.exit(1)
}
const มีสูตรปลูก = new Set(สูตร.map((x) => x.ด่าน))
/* 🔑 **แยกให้เห็นว่ามาจากแหล่งไหน และทับกันกี่ตัว** (ฝั่งท่อเตือน 20 ก.ย. 2569:
   *สองเลขในบรรทัดสรุปทับกันได้* ⇒ ถ้าพิมพ์แต่ยอดรวม คนอ่านจะนึกว่าเป็นกลไกเดียว) */
const มี = [], หนี้ = []
let จากทะเบียน = 0, จากฝังใน = 0, ทับกัน = 0
for (const d of ด่าน) {
  let src = ''
  try { src = readFileSync(join(ROOT, d), 'utf8') } catch { หนี้.push(`${d} (อ่านไฟล์ไม่ได้)`); continue }
  const ก = มีสูตรปลูก.has(d)
  const ข = มีตัวควบคุมแยกแยะ(src)
  if (ก) จากทะเบียน++
  if (ข) จากฝังใน++
  if (ก && ข) ทับกัน++
  ;(ก || ข ? มี : หนี้).push(d)
}

console.log(`หนี้ตัวควบคุม: ด่านในสาย **${ด่าน.length} ตัว** · มีควบคุมชนิดแยกแยะได้ **${มี.length}** · **หนี้ ${หนี้.length}** (เพดาน ${เพดานหนี้})`)
console.log(`   ✅ ตัวควบคุมสี่เคสของด่านนี้ผ่านก่อนตัดสิน ⇒ ตัวเลขข้างบนอ่านได้`)
console.log(`   แยกตามแหล่ง: ทะเบียนสูตรปลูก ${จากทะเบียน} · ตัวควบคุมฝังใน ${จากฝังใน} · **ทับกัน ${ทับกัน}** ⇒ นับไม่ซ้ำ ${มี.length}`)
console.log(`   ยังไม่มีอะไรพิสูจน์: ${หนี้.join(' · ') || '—'}`)

if (หนี้.length > เพดานหนี้) {
  console.error(`\n🔴 หนี้เพิ่มขึ้น (${หนี้.length} > ${เพดานหนี้}) — **มีด่านใหม่ที่ไม่มีตัวควบคุม**`)
  console.error('   ⇒ ด่านใหม่ต้องมีเคส "ต้องจับ" และ "ต้องไม่จับ" อยู่ในโค้ดที่รันจริง')
  console.error('   🔑 มีแต่เคสต้องจับ จะมองไม่เห็นตะแกรงที่กว้างเกิน (ข้อที่ฝั่งท่อยืมไปใช้)')
  process.exit(1)
}
if (หนี้.length < เพดานหนี้) {
  console.error(`\n🔴 ใช้หนี้ไปแล้ว (${หนี้.length} < ${เพดานหนี้}) — **ต้องขันเพดานในคอมมิตเดียวกัน**`)
  console.error(`   แก้ \`const เพดานหนี้ = ${เพดานหนี้}\` เป็น \`${หนี้.length}\``)
  console.error('   🔑 เพดานที่สูงกว่าของจริง = ช่องให้แย่ลงเงียบ ๆ (กฎที่ตกลงกับฝั่งท่อ)')
  process.exit(1)
}
console.log('✅ หนี้เท่าเพดานพอดี — ไม่มีด่านใหม่ที่ไม่มีตัวควบคุม')
