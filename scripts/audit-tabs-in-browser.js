// 🔴 **บทเรียนที่ฝังอยู่ในสคริปต์นี้ (16 ก.ย. 2569 — เสียเวลาไปกับมันมาแล้ว)**
//    ① **อ่านข้อความ "หลังกด" ไม่ใช่ตอนเปิดหน้า** — ข้อความบอกขอบเขต ("กรองแค่หน้านี้")
//       เป็น **ผลของการกรอง** ⇒ ถ้าเก็บ body ตอนโหลดหน้าเสร็จ จะรายงานว่า "จอไม่ได้เขียนกำกับ"
//       ทั้ง ๆ ที่จอเขียนไว้ครบ = **ผลลบปลอม** และเกือบทำให้ไปแก้จอที่ถูกอยู่แล้ว
//    ② **พิมพ์ท่อนข้อความจริงออกมาด้วย ไม่ใช่แค่ true/false** — เห็นข้อความแล้วจับผิดตัวเองได้ทันที
//    ③ **แท็บที่ได้ 0 แถวไม่ใช่บั๊กเสมอไป** — ถ้าจอเขียนเหตุไว้ (ท่อยังไม่รับตัวกรอง ⇒ กรองได้เท่าที่มีในหน้านี้)
//       นั่นคือ "ระบบทำได้เท่านี้ และบอกตรง ๆ" ⇒ สคริปต์จึงเก็บทั้งเลข **และ** เหตุ
//    ④ **แท็บที่ไม่มีเลขในวงเล็บ ไม่ใช่ของลืมใส่เสมอไป** — จอสินค้าถอดเลขออกเพราะเจ้าของร้าน
//       สั่งให้เหมือน ZORT เป๊ะ (3 ก.ย. 2569) ⇒ เจอแล้วให้ไปอ่านคอมเมนต์ในไฟล์จอก่อนตัดสิน
//
// วิธีใช้:
//   await auditTabs()                 // ตรวจจอที่เปิดอยู่
//   await auditTabs({ waitMs: 8000 }) // จอช้าให้รอนานขึ้น
window.auditTabs = async function auditTabs(opts) {
  /* ⚠️ รับเป็น opts แล้วแกะข้างใน (ไม่ destructure ที่พารามิเตอร์) — เผื่อมีคนเรียกด้วย null
     เจอจริงตอนทดสอบผ่าน Playwright: `evaluate(src)` เรียกฟังก์ชันให้เองด้วยค่า null
     ⇒ destructure ที่พารามิเตอร์จะโยน TypeError ทันที ทั้งที่ตัวสคริปต์ไม่ผิด */
  const { waitMs = 6000 } = opts || {}
  const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
  /* ⚠️ คำใบ้ต้องเฉพาะเจาะจง — รอบแรกผมใส่คำกว้าง ๆ ('แสดง' · 'จาก') ลงไปด้วย
     ⇒ มันไปจับ **หัวคอลัมน์ของตาราง** ("# วันที่ รายการ ประเภท จาก ไป สถานะ")
        แล้วรายงานว่านั่นคือเหตุที่จอเขียนไว้ = เสียงรบกวนที่ทำให้คนอ่านไม่เชื่อรายงานทั้งใบ
     ⇒ ใช้วลีเฉพาะ + รูปแบบ "แสดง 1–50 จาก 100 รายการ" ที่มีตัวเลขคร่อมเท่านั้น */
  const CLUE = [
    'กรองในเบราว์เซอร์', 'กรองแค่หน้านี้', 'แถวที่กรองได้มาจากหน้านี้', 'กรองในเครื่อง',
    'ท่อยังไม่รับตัวกรอง', 'ค้นด้วยเลขที่ใบ', 'นับเฉพาะหน้าที่เปิดอยู่',
  ]
  const PAGING = /แสดง\s*[\d,]+\s*[–-]\s*[\d,]+\s*จาก\s*[\d,]+/
  /** นับ "แถวข้อมูลจริง" — แถวข้อความ (EmptyState) มี td เดียว ไม่ใช่ข้อมูล */
  const countRows = () => {
    const tables = [...document.querySelectorAll('table')]
    if (!tables.length) return null
    const t = tables.reduce((a, b) =>
      b.querySelectorAll('tbody tr').length > a.querySelectorAll('tbody tr').length ? b : a)
    return [...t.querySelectorAll('tbody tr')].filter((r) => r.querySelectorAll('td').length > 2).length
  }
  const tabButtons = () => [...document.querySelectorAll('button')]
    .map((b) => ({ el: b, text: (b.innerText || '').replace(/\s+/g, ' ').trim() }))
    .filter((o) => o.text && o.text.length < 40 && /\(\s*[\d,]+\s*\)/.test(o.text))

  const first = tabButtons()
  if (!first.length) {
    console.log('ℹ️ จอนี้ไม่มีแท็บที่มีเลขในวงเล็บ — ถ้าคาดว่าควรมี ให้ไปอ่านคอมเมนต์ในไฟล์จอก่อนสรุปว่าลืมใส่')
    return []
  }
  const out = []
  for (const { text } of first) {
    // ⚠️ หาปุ่มใหม่ทุกครั้ง — React เปลี่ยน DOM หลังกด ปุ่มเก่าอาจไม่อยู่แล้ว
    const btn = tabButtons().find((o) => o.text === text)
    if (!btn) { out.push({ แท็บ: text, ผล: 'หาปุ่มซ้ำไม่เจอหลังกดแท็บก่อนหน้า' }); continue }
    btn.el.click()
    await sleep(waitMs)                        // ① กดก่อน แล้วค่อยอ่าน
    const body = document.body.innerText || ''
    const m = /\(\s*([\d,]+)\s*\)/.exec(text)
    out.push({
      แท็บ: text,
      สัญญา: m ? Number(m[1].replace(/,/g, '')) : null,
      แถวที่ได้: countRows(),
      // ② เก็บท่อนข้อความจริง ไม่ใช่แค่ true/false
      เหตุที่จอเขียนไว้: (body.split('\n').map((s) => s.trim())
        .find((l) => CLUE.some((k) => l.includes(k)) || PAGING.test(l)) || null),
    })
  }
  console.table(out.map((o) => ({ แท็บ: o.แท็บ, สัญญา: o.สัญญา, แถวที่ได้: o.แถวที่ได้ })))
  for (const o of out) {
    if (o.แถวที่ได้ === 0 && o.สัญญา) {
      console.log(o.เหตุที่จอเขียนไว้
        ? `🟡 ${o.แท็บ} ได้ 0 แถว แต่จอเขียนเหตุไว้: ${o.เหตุที่จอเขียนไว้}`
        : `🔴 ${o.แท็บ} ได้ 0 แถว และ **จอไม่ได้เขียนเหตุไว้** ⇒ นี่คือคำสัญญาที่ผิด ต้องแก้`)
    }
  }
  return out
}
