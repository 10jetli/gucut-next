const ไฟล์ = []
const เดิน = (d) => {
  for (const e of readdirSync(d, { withFileTypes: true })) {
    if (e.name === 'node_modules' || e.name.startsWith('.')) continue
    const p = join(d, e.name)
    if (e.isDirectory()) เดิน(p)
    else if (/\.tsx?$/.test(e.name) && statSync(p).isFile()) ไฟล์.push(p)
  }
}
for (const d of ['app', 'components', 'lib']) {
  try { เดิน(join(ROOT, d)) } catch { /* ข้าม */ }
}

const ผิด = []
const ไม่รู้เส้น = []
let ตรวจไป = 0
for (const [ชื่อฟัง, ประตู] of Object.entries(ประตูทั้งหมด)) {
  const พาราม = พารามของฟังก์ชัน(ชื่อฟัง, ep.paramRoutes ?? [])
  if (!พาราม) { ไม่รู้เส้น.push(ชื่อฟัง); continue }
  for (const f of ไฟล์) {
    const src = readFileSync(f, 'utf8')
    if (!new RegExp(`${พาราม}=1`).test(ตัดคอมเมนต์(src))) continue
    ตรวจไป++
    for (const x of ปัญหาของผู้เรียก(src, ประตู)) ผิด.push(`${f.slice(ROOT.length)} [${พาราม}] ${x}`)
  }
}

console.log(`🚪 เทียบประตูของท่อ ${Object.keys(ประตูทั้งหมด).length} เส้น · พบผู้เรียก ${ตรวจไป} จุด`
  + ` (สารบัญดึงเมื่อ ${snap['ดึงเมื่อ'] ?? '?'})`)
