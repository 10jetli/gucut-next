import { readFileSync, readdirSync, statSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { ตัดคอมเมนต์ } from './lib/ตัดคอมเมนต์.mjs'
import { บอกอายุสารบัญ } from './lib/อายุสารบัญ.mjs'

const ROOT = fileURLToPath(new URL('..', import.meta.url))

/** ชื่อฟังก์ชันของท่อ → ชื่อพารามิเตอร์บนเส้น (`zortAddProduct` → `addproduct`)
 *  🔑 **ไม่พิมพ์ตารางแปลงไว้เอง** (นั่นคือสำเนาอีกใบ) — ใช้กติกาการตั้งชื่อ
 *     แล้ว **ยืนยันกับ `paramRoutes` ที่ท่อประกาศ** · ยืนยันไม่ได้ ⇒ บอกว่าไม่รู้ ไม่เดา */
export function พารามของฟังก์ชัน(ชื่อ, paramRoutes = []) {
  const เดา = String(ชื่อ).replace(/^zort/, '').toLowerCase()
  return paramRoutes.includes(เดา) ? เดา : null
}

/** ตัวตัดสินล้วน — รับเนื้อไฟล์ + ประตูของเส้นนั้น คืนรายการปัญหา (ป้อนค่าปลอมได้) */
export function ปัญหาของผู้เรียก(ซอร์ส, ประตู) {
  const โค้ด = ตัดคอมเมนต์(ซอร์ส)
  const มีช่อง = (ช) => new RegExp(`['"\`]?${ช.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}['"\`]?\\s*:`).test(โค้ด)
  const out = []
  for (const ก of ประตู?.['ต้องมี'] ?? []) {
    const ขาด = (ก['ช่อง'] ?? []).filter((ช) => !มีช่อง(ช))
    if (ขาด.length) out.push(`ต้องมี: ขาด ${ขาด.join(' · ')}${ก['ข้อความ'] ? ` — "${ก['ข้อความ']}"` : ''}`)
  }
  for (const ก of ประตู?.['ต้องมีอย่างน้อยหนึ่ง'] ?? []) {
    const ชุด = ก['ช่อง'] ?? []
    /* ชื่อพ้องนับด้วย — ท่อยอมรับทั้งชุด ⇒ ด่านต้องยอมเหมือนกัน ไม่งั้นฟ้องของที่ถูก */
    const พ้อง = (ช) => [ช, ...((ประตู?.['ชื่อพ้อง'] ?? {})[ช] ?? [])]
    if (!ชุด.some((ช) => พ้อง(ช).some(มีช่อง))) {
      out.push(`ต้องมีอย่างน้อยหนึ่งใน ${ชุด.join(' / ')}${ก['ข้อความ'] ? ` — "${ก['ข้อความ']}"` : ''}`)
    }
  }
  for (const ช of ประตู?.['ไม่ส่งต่อแม้รับ'] ?? []) {
    if (มีช่อง(ช)) out.push(`🟡 ส่ง \`${ช}\` ไปด้วย แต่ท่อ **ไม่ส่งต่อ** ⇒ ค่านั้นหายเงียบ`)
  }
  return out
}

