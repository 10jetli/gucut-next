#!/usr/bin/env node
/**
 * 🚧 **ด่านตอนพิมพ์: ไฟล์ที่อ่านอีกรีโปจากดิสก์ ต้องบอกที่มาของของที่มันอ่าน**
 *
 * 🔴 **ของจริงที่ทำให้ด่านนี้เกิด (14 ต.ค. 2569)**
 *    ฝั่งท่อเปลี่ยนรูป API ในรีโปของเขา **ยังไม่ push** แล้วเขียนในคอมมิตว่า
 *    *"ยังไม่ push ⇒ ไม่มีใครพึ่งของเดิม"* — ด่านฝั่งผมอ่านไฟล์นั้นด้วย **พาธบนดิสก์**
 *    ⇒ ด่านผมแดงทันทีที่เขากด Save · เขาไม่รู้ตัว · **และอาการไม่ชี้มาที่เขา**
 *    ⇒ ผมไปรื้อรีโปตัวเองก่อน (เจอบั๊กจริงอีกตัว แต่ **คนละตัวกับตัวจุดชนวน**)
 *
 * 🔑 **ทำไมต้องเป็นด่าน ไม่ใช่บทเรียน** — ผมแก้ประตูที่เจอไปแล้วหนึ่งบาน
 *    แต่ **ไม่ได้ถามว่าประตูทรงเดียวกันมีกี่บาน** (วัดแล้วได้หลายบาน)
 *    ⇒ ของที่พึ่งความจำจะเงียบกับประตูบานที่ 7 ที่เขียนเดือนหน้า
 *
 * ## เกณฑ์ที่ใช้ (และทำไมไม่ใช่เกณฑ์หยาบ)
 * 🚫 เกณฑ์หยาบที่ **ทั้งสองฝั่งเกือบใช้แล้วได้บวกลวง**:
 *    *"ไฟล์เอ่ย `gucut-web` + มี `readFileSync` ที่ไหนก็ได้"*
 *    ⇒ ฝั่งท่อวัดด้วยเกณฑ์นี้ได้ 6 ตัว · เปิดดูทีละไฟล์แล้วของจริงมี **1 ตัว**
 *      อีก 5 เอ่ยชื่อ **ในคอมเมนต์เท่านั้น** ⇒ ⇒ ถ้าด่านใช้เกณฑ์นี้
 *      มันจะบังคับให้ไฟล์ที่ไม่ได้อ่านดิสก์ **import ของที่ไม่ได้ใช้**
 *      (ฝั่งท่อเป็นคนขอข้อนี้เอง · เทสของด่านนี้มีตัวควบคุมลบตามที่เขาขอ)
 * ✅ เกณฑ์ที่ใช้: **ตัดคอมเมนต์ออกก่อน** แล้วหา *พาธไปอีกรีโปที่ยังอยู่ในโค้ดจริง*
 *    ⇒ ไฟล์ที่เอ่ยชื่ออีกรีโปในคอมเมนต์/เอกสารเท่านั้น จะถูกตัดทิ้งก่อนถึงตัวจับ
 *
 * ⚠️ **ขอบเขตที่ด่านนี้ตอบไม่ได้ (ต้องเขียนไว้ ไม่ใช่ปล่อยให้เดา)**
 *    นี่เป็น **ตัวชี้เป้าจากรูปร่างโค้ด** ไม่ใช่การวัดพฤติกรรม ⇒
 *    · ไฟล์ที่ประกอบพาธจาก env ล้วน ๆ โดยไม่เอ่ยชื่อรีโป ⇒ **ด่านนี้มองไม่เห็น**
 *    · วิธีวัดพฤติกรรมจริง (ทำได้ทุกเมื่อ ไม่ต้องแก้โค้ด): แพตช์ `fs` ด้วย `-r` แล้วนับ
 *      การเรียกที่พาธมีชื่ออีกรีโป — ผมใช้ท่านี้ยืนยันรายชื่อตั้งต้นของด่านนี้
 *      ([[แยกไม่ได้จากข้อความให้วัดจากของที่รันจริง]])
 */
import { readdirSync, readFileSync, statSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'
import { ตัดคอมเมนต์ } from './lib/ตัดคอมเมนต์.mjs'

const ROOT = process.env.CROSS_REPO_SCAN_ROOT
  || join(fileURLToPath(new URL('.', import.meta.url)), '..')
/** โมดูลที่ผู้อ่านข้ามรีโปต้องเรียก (แหล่งเดียวของการรายงานที่มา) */
const โมดูล = 'ของนอกรีโป.mjs'
/** ชื่อรีโปอีกฝั่ง — เขียนไว้ที่เดียว เพิ่มได้เมื่อมีรีโปที่สาม */
const รีโปอื่น = (process.env.CROSS_REPO_NAMES || 'gucut-web').split(',').filter(Boolean)

/* 🔴 ยกเว้น **ตัวโมดูลเอง ตัวด่านนี้เอง และเทสของมัน** — ไม่ใช่เพราะ "น่าเบื่อ"
   แต่เพราะด่านที่จับตัวเองจะเรียกตัวเองไม่รู้จบ และเพราะตัวด่าน/เทสต้อง **เอ่ยชื่อรีโป
   เป็นข้อมูล** ไม่ได้อ่านมันจริง ([[เครื่องมือที่กวาดไฟล์จะเจอตัวเอง]]) */
const ยกเว้น = [
  `scripts/lib/${โมดูล}`,
  'scripts/check-ผู้อ่านนอกรีโป.mjs',
  'scripts/tests/ผู้อ่านนอกรีโป.test.mjs',
]

const กวาด = (d, ออก = []) => {
  for (const name of readdirSync(d)) {
    if (name === 'node_modules' || name === '.next' || name.startsWith('.next-')) continue
    const p = join(d, name)
    if (statSync(p).isDirectory()) กวาด(p, ออก)
    else if (/\.(mjs|js|ts|tsx)$/.test(name)) ออก.push(p)
  }
  return ออก
}

/** พาธไปอีกรีโปที่ยังอยู่หลังตัดคอมเมนต์ — คืนบรรทัดตัวอย่างให้คนแก้เห็นว่าที่ไหน */
function พาธข้ามรีโป(โค้ด) {
  for (const ชื่อ of รีโปอื่น) {
    for (const บรรทัด of โค้ด.split('\n')) {
      if (!บรรทัด.includes(ชื่อ)) continue
      /* 🔴 **เกณฑ์นี้ถูกรัดสองรอบ — รอบแรกให้บวกลวง 2 ไฟล์ตรงอย่างที่ฝั่งท่อทายไว้**
         รอบแรกผมถามว่า *"มีสตริงที่ข้างในมีคำว่า gucut-web ไหม"* ⇒ ฟ้องสองไฟล์ที่ไม่ได้อ่านดิสก์:
           · `scripts/tests/prepush-เวลา.test.mjs` — คำนั้นเป็น **ข้อมูลเทส** (บรรทัด log ปลอม)
             `'2026-09-27  gucut-web   ใช้ 240 วินาที …'`
           · `app/sales/page.tsx` — อยู่ในคอมเมนต์ JSX ที่มี backtick ⇒ ตัวตัดคอมเมนต์ปล่อยผ่าน
         ⇒ ถ้าปล่อยไว้ ด่านนี้จะ **บังคับให้ไฟล์ที่ไม่ได้อ่านดิสก์ import ของที่ไม่ได้ใช้**
            (= ความเสียหายที่ฝั่งท่อเตือนล่วงหน้า · เทสมีตัวควบคุมลบคุมข้อนี้ไว้)
         ✅ เกณฑ์ที่ใช้จริง — ต้องเป็น **รูปของพาธ** อย่างใดอย่างหนึ่ง:
           ① มี `/` หรือ `\` ติดหน้าชื่อรีโป  ⇒ `'../gucut-web'` · `/home/jetli/gucut-web/x`
           ② สตริงที่เป็นชื่อรีโป **ทั้งตัวพอดี** และบรรทัดนั้นประกอบพาธ (`join(`/`resolve(`)
              ⇒ `join(ROOT, '..', 'gucut-web', …)` */
      const หนี = ชื่อ.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
      const เป็นพาธ = new RegExp(`[\\/\\\\]${หนี}`).test(บรรทัด)
      const ชิ้นพาธ = new RegExp(`(['"\`])\\s*${หนี}\\s*\\1`).test(บรรทัด)
        && /\b(join|resolve)\s*\(/.test(บรรทัด)
      if (เป็นพาธ || ชิ้นพาธ) return { ชื่อ, บรรทัด: บรรทัด.trim().slice(0, 110) }
    }
  }
  return null
}

const ไฟล์ = ['scripts', 'lib', 'app', 'components']
  .map((d) => join(ROOT, d))
  .filter((d) => { try { return statSync(d).isDirectory() } catch { return false } })
  .flatMap((d) => กวาด(d))

const ผิด = []
let เข้าข่าย = 0
let ตัดเพราะคอมเมนต์ = 0
for (const f of ไฟล์) {
  const ที่ = f.slice(ROOT.length).replace(/^\//, '')
  if (ยกเว้น.includes(ที่)) continue
  const ดิบ = readFileSync(f, 'utf8')
  if (!รีโปอื่น.some((n) => ดิบ.includes(n))) continue
  const โค้ด = ตัดคอมเมนต์(ดิบ)
  const พบ = พาธข้ามรีโป(โค้ด)
  if (!พบ) { ตัดเพราะคอมเมนต์++; continue }   // ← ตัวควบคุมลบของด่านนี้
  เข้าข่าย++
  /* 🔴 **ต้องถามกับโค้ดที่ตัดคอมเมนต์แล้ว ไม่ใช่ซอร์สดิบ** — ตัวปลูกจับผมได้ตรงนี้
     รุ่นแรกถาม `ดิบ.includes(โมดูล)` ⇒ ปลูกถอด `import` ออก **ด่านยังเขียว**
     เพราะไฟล์นั้นมีคอมเมนต์ที่ผมเขียนเองว่า "(`scripts/lib/ของนอกรีโป.mjs`)"
     ⇒ ⇒ คลาสเดิมของทีมเป๊ะ ๆ: **ด่านที่ถามว่า "มีข้อความนี้ไหม" ถูกคอมเมนต์ปลอบได้**
        (เหตุที่ `lib/ตัดคอมเมนต์.mjs` เกิดมา — และผมใช้มันกับการหาพาธ แต่ลืมใช้กับการหา import) */
  if (!โค้ด.includes(โมดูล)) ผิด.push({ ที่, ...พบ })
}

console.log(`📂 ด่านผู้อ่านนอกรีโป: กวาด ${ไฟล์.length} ไฟล์`)
console.log(`   เอ่ยชื่ออีกรีโปแต่**เหลือแค่ในคอมเมนต์** ⇒ ไม่บังคับ: ${ตัดเพราะคอมเมนต์} ไฟล์`)
console.log(`   มีพาธข้ามรีโปในโค้ดจริง ⇒ ต้องรายงานที่มา: ${เข้าข่าย} ไฟล์`)

if (ผิด.length) {
  console.error(`🔴 **ผู้อ่านข้ามรีโป ${ผิด.length} ไฟล์ ไม่รายงานว่าของที่มันอ่านถูกแก้เมื่อไหร่**`)
  for (const x of ผิด) {
    console.error(`   · ${x.ที่}`)
    console.error(`     พาธข้ามรีโป: ${x.บรรทัด}`)
  }
  console.error(`   ⇒ แก้: \`import { บอกไฟล์นอกรีโป } from './lib/${โมดูล}'\``)
  console.error('     แล้วเรียกก่อนเริ่มตัดสิน (กองไฟล์ใช้ `บอกกองนอกรีโป`)')
  console.error('   🔑 เหตุ: อีกฝั่งไม่ต้อง push ของก็ถึงเราแล้ว ⇒ ด่านแดงโดยอาการไม่ชี้ไปที่คนที่เปลี่ยน')
  process.exit(1)
}
console.log(`   ✅ ผู้อ่านข้ามรีโปทั้ง ${เข้าข่าย} ไฟล์ รายงานที่มาของของที่มันอ่าน`)
