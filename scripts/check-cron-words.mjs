/** cron → ทุกกี่นาที (null = รูปที่ยังแปลไม่ได้ ⇒ **ข้าม ไม่ใช่ผ่าน**) */
export function รอบเป็นนาที(cron) {
  const p = String(cron ?? '').trim().split(/\s+/)
  if (p.length !== 5) return null
  const [นาที, ชม, วัน, เดือน, สัปดาห์] = p
  if (เดือน !== '*' || สัปดาห์ !== '*' || วัน !== '*') return null
  const ทุกNนาที = นาที.match(/^\*\/(\d+)$/)
  if (ทุกNนาที && ชม === '*') return Number(ทุกNนาที[1])
  const รายการนาที = นาที.includes(',') ? นาที.split(',').length : (/^\d+$/.test(นาที) ? 1 : null)
  if (!รายการนาที) return null
  if (ชม === '*') return 60 / รายการนาที
  const ทุกNชม = ชม.match(/^\*\/(\d+)$/)
  if (ทุกNชม) return (Number(ทุกNชม[1]) * 60) / รายการนาที
  if (/^\d+$/.test(ชม)) return (24 * 60) / รายการนาที
  return null
}

/** คำบอกรอบใน desc → ทุกกี่นาที (null = ไม่ได้พูดถึงรอบ ⇒ ไม่ตรวจ) */
export function คำบอกรอบ(desc) {
  const t = String(desc ?? '')
  /* ⚠️ ข้ามประโยคที่เล่า **ประวัติ** — ฝั่งท่อกำชับ ไม่งั้นด่านจะร้องใส่บันทึกที่ถูกต้อง
     🔴 รายการคำนี้เคยไม่ครบ แล้วทำให้เกิดธงลวงทันทีในรอบแรก (19 ก.ย. 2569):
        `returns-sync` หัวไฟล์เขียนถูกแล้วว่า "ทุก 3 ชั่วโมง (**ลดจาก**ทุกชั่วโมง 18 ก.ย.)"
        แต่ "ลดจาก" ไม่อยู่ในรายการ ⇒ ด่านอ่านว่าประกาศรอบเป็นทุกชั่วโมง ⇒ ฟ้องของที่ถูก */
  const ตัดประวัติ = t.replace(/(?:เดิม|เคย|ของเก่า|ย้ายจาก|เปลี่ยนจาก|ลดจาก|เพิ่มจาก|จากเดิม)[^·)]*/g, '')

  /* 🔴 **ต้องเอาคำที่มาก่อนในประโยค ไม่ใช่คำที่เราเช็คก่อนในโค้ด** (บั๊กรอบแรกของด่านนี้)
     ของเดิมไล่เช็คทีละแบบตามลำดับที่เขียน ⇒ `ทุกชั่วโมง` ชนะ `ทุก 3 ชั่วโมง` เสมอ
     เพราะสตริง "ทุก 3 ชั่วโมง" ไม่มีคำว่า "ทุกชั่วโมง" ก็จริง แต่ประโยคเดียวกันมักมีทั้งคู่
     ⇒ อ่านตำแหน่งจริงในประโยค แล้วเลือกตัวซ้ายสุด = ตัวที่เป็นคำประกาศของงานนี้ */
  const ผู้สมัคร = []
  const เก็บ = (re, ค่า) => {
    const m = ตัดประวัติ.match(re)
    if (m) ผู้สมัคร.push({ at: m.index, นาที: typeof ค่า === 'function' ? ค่า(m) : ค่า })
  }
  เก็บ(/ทุก\s*(\d+)\s*นาที/, (m) => Number(m[1]))
  เก็บ(/ทุก\s*(\d+)\s*(?:ชั่วโมง|ชม\.)/, (m) => Number(m[1]) * 60)
  เก็บ(/ทุกครึ่งชั่วโมง/, 30)
  เก็บ(/ทุกชั่วโมง/, 60)
  เก็บ(/วันละครั้ง|ทุกคืน|ทุกวัน(?!\s*เวลา)/, 24 * 60)
  if (!ผู้สมัคร.length) return null
  ผู้สมัคร.sort((a, b) => a.at - b.at)
  return ผู้สมัคร[0].นาที
}

function ตรวจ(jobs) {
  const ผิด = []
  for (const j of jobs) {
    const จริง = รอบเป็นนาที(j.cron)
    const พูด = คำบอกรอบ(j.desc)
    if (จริง === null || พูด === null) continue        // แปลไม่ได้/ไม่ได้พูดถึงรอบ ⇒ ไม่ตัดสิน
    if (Math.abs(จริง - พูด) < 0.5) continue
    ผิด.push(`${j.id}  cron \`${j.cron}\` = ทุก ${จริง} นาที · แต่คำในแถวบอก ทุก ${พูด} นาที`)
  }
  return ผิด
}

