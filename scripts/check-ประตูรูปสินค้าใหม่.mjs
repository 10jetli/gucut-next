#!/usr/bin/env node
/* ด่าน: **จอที่สร้างสินค้าใหม่ ต้องส่งช่องประตูรูปไปกับคำขอ**
 *
 * 🔴 ที่มา (12 ต.ค. 2569 · ใบ t_mv4zzcca) — ท่อเพิ่มกติกา "สินค้าใหม่ต้องมีรูป" เมื่อ 28 ก.ย. 2569
 *    `zortAddProduct` ตีกลับทุกใบที่ไม่ส่ง `รูป` หรือ `ไม่มีรูปเพราะ`
 *    ⇒ `/core/stock/new` ไม่เคยส่งทั้งสองช่อง ⇒ **ส่งจริงไม่ได้เลยมา 14 วัน**
 *    และตารางเทียบเมนูยังเขียนว่า "ส่งจริงได้แล้ว 18 ก.ย." ซึ่งกลายเป็นเท็จเมื่อ 28 ก.ย.
 *    📏 ยิงพิสูจน์กับ production: เนื้อที่จอส่งจริง ⇒ **HTTP 400** · ใส่ `ไม่มีรูปเพราะ` ⇒ 200 dryRun
 *
 * 🔑 **คลาสที่ด่านนี้กัน: ประตูถูกเพิ่มที่ท่อ แต่ผู้เรียกไม่ถูกตามไปแก้**
 *    ไม่มีใครรู้เพราะไม่มีอะไรกดปุ่มนั้น — ปุ่มที่ "เปิดแล้ว" กดไม่สำเร็จอย่างเงียบ ๆ
 *
 * ⚠️ **ขอบเขต — อ่านซอร์ส ไม่ได้ยิงท่อ** (ด่าน build ห้ามยิงเน็ต กินเครดิตฟังก์ชัน)
 *    ⇒ พิสูจน์ว่า **ช่องถูกส่งไป** ไม่ได้พิสูจน์ว่าท่อยอมรับ
 *    ⇒ วันที่ท่อเปลี่ยนชื่อช่อง ด่านนี้จะเงียบ — ตัวที่จับได้คือการยิงของจริงหลัง deploy
 */
import { readFileSync, readdirSync, statSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { ตัดคอมเมนต์ } from './lib/ตัดคอมเมนต์.mjs'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const ช่องประตู = ['รูป', 'ไม่มีรูปเพราะ']

/** ตัวตัดสินล้วน — รับเนื้อไฟล์ คืนรายชื่อช่องที่ขาด (ป้อนค่าปลอมได้)
 *
 *  🔴 **ต้องตัดคอมเมนต์ก่อน** — รุ่นแรกของด่านนี้ฟ้อง `lib/excel-rows.ts`
 *     ซึ่ง "มีคำว่า `?addproduct=1`" อยู่ใน **คอมเมนต์หัวไฟล์** ที่ไล่รายชื่อเส้นของท่อ
 *     ⇒ บวกลวงใส่ไฟล์ที่เขียนเอกสารกำกับไว้ดี = คลาสที่ทีมเหยียบ 5 ครั้งในวันเดียว
 *     ⇒ และผมเขียนใบบทเรียนคลาสนี้เองเมื่อหนึ่งชั่วโมงก่อน แล้วสร้างด่านที่ทำซ้ำ
 *     🔑 ⇒ **ตัดคอมเมนต์ต้องเป็นค่าเริ่มต้นของตะแกรง ไม่ใช่สิ่งที่ต้องนึกถึง** */
export function ช่องที่ขาด(ซอร์ส) {
  const โค้ด = ตัดคอมเมนต์(ซอร์ส)
  if (!/addproduct=1/.test(โค้ด)) return null        // ไม่ใช่จอที่สร้างสินค้า ⇒ ไม่เกี่ยว
  return ช่องประตู.filter((ช) => !new RegExp(`['"\`]?${ช}['"\`]?\\s*:`).test(โค้ด))
}

if (process.argv.includes('--self-test')) {
  const เคส = [
    { ควรจับ: false, ชื่อ: 'ต้องไม่จับ: ไฟล์ที่ไม่เกี่ยวกับ addproduct', โค้ด: "fetch('/api/web/core?list=stock')" },
    { ควรจับ: true, ชื่อ: 'ควรจับ: ยิง addproduct แต่ไม่มีช่องประตูเลย',
      โค้ด: "fetch('/api/web/core?addproduct=1',{body:JSON.stringify({sku,name})})" },
    { ควรจับ: true, ชื่อ: 'ควรจับ: มีแค่ช่องเดียว (รูป) ขาดอีกช่อง',
      โค้ด: "fetch('/api/web/core?addproduct=1',{body:JSON.stringify({sku,'รูป':x})})" },
    { ควรจับ: false, ชื่อ: 'ต้องไม่จับ: มีทั้งสองช่อง',
      โค้ด: "fetch('/api/web/core?addproduct=1',{body:JSON.stringify({sku,'รูป':x,'ไม่มีรูปเพราะ':y})})" },
    { ควรจับ: false, ชื่อ: 'ต้องไม่จับ: `addproduct=1` อยู่ในคอมเมนต์ (บวกลวงที่เจอจริง)',
      โค้ด: "/* ขาเข้าจากจอ: product -> ?addproduct=1 {ref, sku, name} */\nexport const x = 1" },
    { ควรจับ: false, ชื่อ: 'ต้องไม่จับ: เขียนช่องแบบไม่มีเครื่องหมายคำพูด',
      โค้ด: "fetch('/api/web/core?addproduct=1',{body:JSON.stringify({รูป: a, ไม่มีรูปเพราะ: b})})" },
  ]
  let ตก = 0
  for (const ก of เคส) {
    const ได้ = (ช่องที่ขาด(ก.โค้ด) || []).length > 0
    const ตรง = ได้ === ก.ควรจับ
    if (!ตรง) ตก++
    console.log(`  ${ตรง ? '✅' : '❌'} ${ก.ชื่อ}`)
  }
  console.log(ตก ? `🛑 self-test ตก ${ตก} เคส` : '🧪 self-test ผ่าน (สองทิศ 5 เคส)')
  process.exit(ตก ? 1 : 0)
}

const ไฟล์ = []
const เดิน = (d) => {
  for (const e of readdirSync(d, { withFileTypes: true })) {
    if (e.name === 'node_modules' || e.name.startsWith('.')) continue
    const p = join(d, e.name)
    if (e.isDirectory()) เดิน(p)
    else if (/\.tsx?$/.test(e.name) && statSync(p).isFile()) ไฟล์.push(p)
  }
}
for (const d of ['app', 'components', 'lib']) {
  try { เดิน(join(ROOT, d)) } catch { /* ไม่มีโฟลเดอร์ก็ข้าม */ }
}

const ผิด = []
let จอที่เกี่ยว = 0
for (const f of ไฟล์) {
  const ขาด = ช่องที่ขาด(readFileSync(f, 'utf8'))
  if (ขาด === null) continue
  จอที่เกี่ยว++
  if (ขาด.length) ผิด.push(`${f.slice(ROOT.length)} — ขาด: ${ขาด.join(' · ')}`)
}

/* 🔑 **ศูนย์จอที่เกี่ยว = ด่านนี้ไม่ได้ตรวจอะไร ห้ามเขียวเงียบ** */
if (!จอที่เกี่ยว) {
  console.log('⚠️ ไม่พบจอที่ยิง `addproduct=1` เลย — ด่านนี้ **ไม่ได้ตรวจอะไรรอบนี้**')
  console.log('   (ถ้าจอยังอยู่ แปลว่าเกณฑ์ค้นเพี้ยน ⇒ ไปดูว่าเส้นเปลี่ยนชื่อหรือยัง)')
  process.exit(0)
}

if (ผิด.length) {
  console.log(`🛑 จอที่สร้างสินค้าใหม่ไม่ส่งช่องประตูรูป ${ผิด.length} จาก ${จอที่เกี่ยว} จอ`)
  ผิด.forEach((x) => console.log(`   🔴 ${x}`))
  console.log('\n   ท่อตีกลับ 400 ทุกใบที่ไม่ส่ง `รูป` หรือ `ไม่มีรูปเพราะ` (กติกา 28 ก.ย. 2569)')
  console.log('   ⇒ ปุ่มจะกดไม่สำเร็จ โดยไม่มีอะไรฟ้องตอน build')
  process.exit(1)
}
console.log(`✅ จอที่สร้างสินค้าใหม่ ${จอที่เกี่ยว} จอ ส่งช่องประตูรูปครบ`)
