#!/usr/bin/env node
/* ด่าน: **ทะเบียน "ปลายเปิด" ของฝั่งท่อ ยังตรงกับโค้ดฝั่งจอไหม**
 *
 * 🔴 ที่มา 14 ต.ค. 2569 — ฝั่งท่อเขียนเองว่า:
 *    *"ของที่กันไว้รอบนี้ไม่ใช่กระบวนการ มันคือการที่ผมเผอิญไปอ่านโค้ดเอง
 *      — ไม่มีด่านไหนอ่านทะเบียนเทียบโค้ดอีกฝั่ง ⇒ ต้องเป็นนิสัยสองด้าน ไม่ใช่โชค"*
 *    ⇒ ด่านนี้คือ **ด้านของผม**: อ่านทะเบียนของเขา แล้วเทียบกับโค้ดในรีโปนี้
 *
 * 🔑 ทะเบียนนั้นเก็บว่าแต่ละช่อง **ใครอ่าน และอ่านเป็นอะไร** ⇒ ตรวจได้สองทิศ:
 *    ① ทะเบียนบอกว่าจอ X อ่าน ⇒ **ไฟล์นั้นต้องมีอยู่และเอ่ยถึงชื่อช่อง**
 *       (ไม่งั้นทะเบียนค้างอยู่กับจอที่เลิกอ่าน/เปลี่ยนชื่อไปแล้ว)
 *    ② ทะเบียนบอกว่า **ไม่มีใครอ่าน** ⇒ ต้องไม่มีไฟล์ใน `app/` เอ่ยถึงชื่อช่องนั้น
 *       (ไม่งั้น = จอเริ่มอ่านแล้วแต่ฝั่งท่อยังคิดว่าไม่มีใครอ่าน ⇒ เขาอาจถอดข้อจำกัดทิ้ง)
 *
 * ⚠️ **เป็นตัวชี้เป้า ไม่ใช่ตัวตัดสิน** — ชื่อช่องอาจโผล่ในคอมเมนต์ และแยก
 *    "อ่านเป็นเลข" กับ "เรนเดอร์เป็นรายชื่อ" ด้วยการ grep ไม่ได้ ⇒ ข้อความบอกให้ไปดูด้วยตา
 * ⚠️ **ข้ามอย่างมีเสียง** เมื่อหาทะเบียนไม่เจอ — ห้ามเงียบแล้วผ่าน
 *    (แยก "ตรวจแล้วไม่เจอ" กับ "ไม่ได้ตรวจ" ให้ขาด)
 * 🚫 **ห้าม import `gen-returned-fields.mjs`** — ไฟล์นั้นยิงท่อ 96 คำขอตอนรัน
 *    ⇒ ต้องเป็นโมดูล **ข้อมูลล้วน** ที่ไม่มีผลข้างเคียง (กฎที่ฝั่งท่อเขียนไว้เองในทะเบียนด่านของผม:
 *      "อย่าให้ตัวรันทะเบียนมีผลข้างเคียงตอนถูก import ⇒ แยกข้อมูลออกจากผลข้างเคียง")
 */
import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
/** ที่ที่ด่านนี้มองหาทะเบียนแบบ **ข้อมูลล้วน** (ขอฝั่งท่อแยกไฟล์ให้ 14 ต.ค. 2569) */
const ที่ทะเบียน = [
  /* 🔑 `OPEN_ENDED_REGISTRY` มีไว้ **ให้ด่านนี้ถูกทดสอบได้** — ไม่ใช่ทางลัดของการใช้งานจริง
     ถ้าไม่มีช่องนี้ ด่านนี้จะทดสอบได้ทางเดียวคือไปเขียนไฟล์ในรีโปของอีกฝั่ง
     ซึ่งผิดกฎ "ต้นไม้ร่วมไม่มีสภาพกลางงาน" ⇒ ทางที่ทดสอบไม่ได้คือทางที่จะไม่ถูกทดสอบ
     (ชื่อเป็น ASCII เพราะชื่อ env ภาษาไทยเรียกจากเชลล์ไม่ได้) */
  ...(process.env.OPEN_ENDED_REGISTRY ? [process.env.OPEN_ENDED_REGISTRY] : []),
  join(ROOT, '..', 'gucut-web', 'scripts', 'lib', 'ทะเบียนปลายเปิด.mjs'),
  join(ROOT, '..', 'gucut-web', 'netlify', 'lib', 'ทะเบียนปลายเปิด.mjs'),
]

const พบ = ที่ทะเบียน.find((p) => existsSync(p))
if (!พบ) {
  console.log('⏭️  ข้ามด่านทะเบียนปลายเปิด: **ยังไม่มีทะเบียนแบบข้อมูลล้วนให้อ่าน**')
  console.log('   ⇒ อ่านว่า **ยังไม่ได้ตรวจ** ไม่ใช่ "ตรวจแล้วตรง"')
  console.log('   ⇒ ที่มองหา: ' + ที่ทะเบียน.map((p) => p.replace(ROOT, '')).join(' · '))
  console.log('   🚫 ตั้งใจไม่อ่าน `gen-returned-fields.mjs` ตรง ๆ — ไฟล์นั้นยิงท่อ 96 คำขอตอนรัน')
  process.exit(0)
}

let ทะเบียน
try {
  ทะเบียน = (await import(พบ)).ปลายเปิด
} catch (e) {
  console.error(`🔴 อ่านทะเบียนไม่ได้ (${String(e?.message ?? e).slice(0, 80)}) ⇒ **ไม่รู้** ไม่ใช่ผ่าน`)
  process.exit(1)
}
if (!ทะเบียน || typeof ทะเบียน !== 'object') {
  console.error('🔴 ทะเบียนไม่มีช่อง `ปลายเปิด` ที่อ่านได้ ⇒ **ไม่รู้** ไม่ใช่ผ่าน')
  process.exit(1)
}

/** ไฟล์ซอร์สทั้งหมดในสายที่เป็น "จอ" */
const ไฟล์จอ = (() => {
  const out = []
  const เดิน = (ที่) => {
    for (const ชื่อ of readdirSync(ที่)) {
      const เต็ม = join(ที่, ชื่อ)
      if (statSync(เต็ม).isDirectory()) เดิน(เต็ม)
      else if (/\.tsx?$/.test(ชื่อ)) out.push(เต็ม)
    }
  }
  for (const ราก of ['app', 'components']) {
    const p = join(ROOT, ราก)
    if (existsSync(p)) เดิน(p)
  }
  return out.map((f) => ({ ที่: f.slice(ROOT.length), เนื้อ: readFileSync(f, 'utf8') }))
})()

const ปัญหา = []
let ตรวจไป = 0
let ข้ามเพราะยังไม่จด = 0

for (const [คีย์, ค่า] of Object.entries(ทะเบียน)) {
  /* ค่าเก่าเป็นสตริงเฉย ๆ (ยังไม่จดว่าใครอ่าน) ⇒ ตรวจไม่ได้ **และต้องนับให้เห็น** */
  if (typeof ค่า === 'string' || !ค่า || typeof ค่า !== 'object' || !('ใครอ่าน' in ค่า)) {
    ข้ามเพราะยังไม่จด++
    continue
  }
  const ชื่อช่อง = String(คีย์).split('.').pop()
  const ใครอ่าน = String(ค่า['ใครอ่าน'] ?? '')
  const เอ่ยถึง = ไฟล์จอ.filter((f) => f.เนื้อ.includes(ชื่อช่อง))
  ตรวจไป++

  const จดว่าไม่มีใครอ่าน = /ไม่มี/.test(ใครอ่าน)
  if (จดว่าไม่มีใครอ่าน) {
    /* ทิศ ②: ทะเบียนบอกว่าไม่มีใครอ่าน แต่จอเริ่มอ่านแล้ว */
    if (เอ่ยถึง.length) {
      ปัญหา.push(`${คีย์}: ทะเบียนจดว่า **${ใครอ่าน}** แต่จอเอ่ยถึงชื่อช่องนี้แล้ว`
        + ` (${เอ่ยถึง.slice(0, 3).map((f) => f.ที่).join(' · ')})`
        + ' ⇒ ถ้าจออ่านจริง ฝั่งท่ออาจถอดข้อจำกัด "รับได้ทุกจำนวน" ทิ้งโดยคิดว่าไม่มีใครใช้')
    }
    continue
  }
  /* ทิศ ①: ทะเบียนบอกว่าจอไหนอ่าน ⇒ ต้องยังเอ่ยถึงอยู่ */
  if (!เอ่ยถึง.length) {
    ปัญหา.push(`${คีย์}: ทะเบียนจดว่า **${ใครอ่าน}** แต่ **ไม่มีไฟล์ใดใน app/ components/ เอ่ยถึง `
      + `\`${ชื่อช่อง}\` แล้ว** ⇒ ทะเบียนค้างอยู่กับจอที่เลิกอ่าน/เปลี่ยนชื่อไปแล้ว`)
  }
}

console.log(`📑 เทียบทะเบียนปลายเปิดกับโค้ดจอ: ตรวจได้ ${ตรวจไป} ช่อง`
  + ` · ยังไม่จดว่าใครอ่าน ${ข้ามเพราะยังไม่จด} ช่อง (ตรวจไม่ได้)`)
console.log(`   ทะเบียน: ${พบ.replace(ROOT, '')}`)
if (ปัญหา.length) {
  console.error(`🔴 **ทะเบียนกับโค้ดไม่ตรงกัน ${ปัญหา.length} ช่อง**`)
  for (const x of ปัญหา) console.error(`   · ${x}`)
  console.error('   ⚠️ ด่านนี้เป็น **ตัวชี้เป้า** — ชื่อช่องอาจโผล่ในคอมเมนต์ ⇒ เปิดดูก่อนแก้ทะเบียน')
  process.exit(1)
}
console.log('   ✅ ทุกช่องที่จดว่าใครอ่าน ยังตรงกับโค้ดจอ (เท่าที่ grep ชื่อช่องบอกได้)')
