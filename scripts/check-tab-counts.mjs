#!/usr/bin/env node
/* กฎแท็บข้อ 1 ของ `CLAUDE.md`: **ตัวนับในแท็บต้องไม่ถูกกรองด้วยแท็บที่กำลังเลือก**
 *
 * 🔴 ที่มาของกฎ (ท่านประธานเจอเอง 2 ก.ย. 2569): กดแท็บแรกแล้วแท็บอื่นเป็นศูนย์หมด
 *    *"แท็บที่บอกไม่ได้ว่าแท็บอื่นมีกี่ใบ ก็ไม่ใช่แท็บ เป็นแค่ปุ่มกรอง"*
 *    และกับดักคู่แฝด: *"ยกเลิก (44)" กดแล้วได้ 0 แถว* ⇒ **ตัวนับกับตัวแถวคนละกติกา**
 *
 * 🔑 ทำไมต้องมีด่าน ทั้งที่วันนี้ทุกจอทำถูก (ตรวจแล้ว 20 ก.ย. 2569 · ใบ S5):
 *    เพราะความถูกต้องตอนนี้ **อยู่ที่คนจำกฎได้** — ไม่มีอะไรบังคับเลย
 *    ⇒ ตรงกับข้อที่ทีมสรุปวันนี้: **คลาสที่รู้แล้วให้แปลงเป็นกลไก ไม่ใช่เพิ่มคำเตือน**
 *    📏 ของจริงตอนเขียน (**เลขของด่านนี้เอง** · นับใหม่ได้ด้วย `node scripts/check-tab-counts.mjs`):
 *       จอที่มีสถานะแท็บ **16** · ในนั้นโชว์ตัวนับคู่กับแท็บ **2** · ผิดกฎ **0**
 *    ⚠️ ตอนสำรวจด้วยมือก่อนเขียนด่าน ผมนับได้ **35 / 9** ซึ่งเป็น **คนละตะแกรง**
 *       (ตะแกรงมือจับคำว่า "tab" ที่ไหนก็ได้ในไฟล์ · ด่านนี้จับเฉพาะ `useState` ที่ชื่อเข้าข่าย)
 *       ⇒ เขียนไว้กันคนเอาสองเลขมาวางคู่กันแล้วคิดว่าด่าน "ครอบไม่ครบ 26 จอ"
 *
 * วิธีจับ: หาตัวแปรที่ **นิยามโดยอ้างสถานะแท็บ** (`const x = ... tab === ...`)
 *          แล้วดูว่ามีตัวไหนถูกเอาไปใช้เป็น **ตัวนับของแท็บ** หรือเปล่า
 *
 * 🚫 ครอบอะไรไม่ได้บ้าง (เขียนไว้ ไม่งั้นเขียวของมันจะถูกอ่านเกินจริง):
 *    · จับเฉพาะรูปที่ตัวนับกับตัวกรองอยู่ **ไฟล์เดียวกัน** — ถ้าตัวนับมาจากท่อ ด่านนี้ไม่รู้
 *      (กรณีนั้นเป็นกฎข้อ 4: "อย่าเอาตัวเลขจากแหล่งหนึ่งไปโชว์คู่กับอีกแหล่ง" — คนละด่าน)
 *    · จับเฉพาะตัวแปรที่นิยามด้วย `const` ในไฟล์นั้น
 */
import { readdirSync, readFileSync, statSync } from 'node:fs'
import { join } from 'node:path'
import { ตัดคอมเมนต์ } from './lib/ตัดคอมเมนต์.mjs'

const ไฟล์ = []
for (const ราก of ['app', 'components']) {
  ;(function เดิน(d) {
    for (const n of readdirSync(d)) {
      if (n === 'node_modules') continue
      const p = join(d, n)
      if (statSync(p).isDirectory()) เดิน(p)
      else if (n.endsWith('.tsx')) ไฟล์.push(p)
    }
  })(ราก)
}

const พบ = []
let จอที่มีแท็บ = 0, จอที่โชว์ตัวนับ = 0

for (const f of ไฟล์) {
  const src = ตัดคอมเมนต์(readFileSync(f, 'utf8'))
  /* ชื่อสถานะแท็บของไฟล์นี้ — รับทั้ง `tab` และชื่อไทย */
  const สถานะ = [...src.matchAll(/const \[(\w+), set\w+\] = useState[^\n]*\n?/g)]
    .map((m) => m[1])
    .filter((n) => /^(tab|activeTab|แท็บ|แถบ|view|mode|มุมมอง)$/i.test(n))
  if (!สถานะ.length) continue
  จอที่มีแท็บ++

  /* ตัวแปรที่นิยามโดยอ้างสถานะแท็บ = "รายการที่ถูกกรองด้วยแท็บแล้ว" */
  const กรองด้วยแท็บ = new Set()
  for (const m of src.matchAll(/const (\w+) = ([^\n]*)/g)) {
    const [, ชื่อ, นิยาม] = m
    if (สถานะ.some((s) => new RegExp(`\\b${s}\\b`).test(นิยาม))) กรองด้วยแท็บ.add(ชื่อ)
  }
  if (!กรองด้วยแท็บ.size) continue

  /* ตัวนับของแท็บ: `count: X.length` หรือ `(${X.length})` */
  const ตัวนับ = [...src.matchAll(/(?:count:\s*|\(\$\{)\s*(\w+)\.length/g)].map((m) => m[1])
  if (!ตัวนับ.length) continue
  จอที่โชว์ตัวนับ++

  for (const ชื่อ of new Set(ตัวนับ)) {
    if (กรองด้วยแท็บ.has(ชื่อ)) {
      พบ.push(`${f}  ตัวนับของแท็บใช้ \`${ชื่อ}\` ซึ่งถูกกรองด้วยสถานะแท็บ (\`${สถานะ.join('/')}\`) แล้ว`)
    }
  }
}

console.log(
  `ตรวจกฎแท็บข้อ 1 (ตัวนับต้องไม่ถูกกรองด้วยแท็บที่เลือก): จอที่มีสถานะแท็บ **${จอที่มีแท็บ}** · ` +
    `ในนั้นโชว์ตัวนับคู่กับแท็บ **${จอที่โชว์ตัวนับ}** · ผิดกฎ **${พบ.length}**`,
)
console.log('   ⚠️ จับเฉพาะกรณีที่ตัวนับกับตัวกรองอยู่ไฟล์เดียวกัน — ตัวนับที่มาจากท่อ ด่านนี้มองไม่เห็น')
if (พบ.length) {
  console.error('\n🔴 แท็บที่ตัวนับถูกกรองด้วยแท็บที่กำลังเลือก')
  for (const x of พบ) console.error('   ' + x)
  console.error('\n   ⚠️ อาการ: กดแท็บแรกแล้ว **แท็บอื่นเป็นศูนย์หมด** ⇒ คนอ่านว่า "ไม่มีของ"')
  console.error('   🔑 แท็บที่บอกไม่ได้ว่าแท็บอื่นมีกี่ใบ **ไม่ใช่แท็บ เป็นแค่ปุ่มกรอง** (ท่านประธาน 2 ก.ย. 2569)')
  console.error('   วิธีแก้: คิดตัวนับจาก **ชุดเต็มก่อนกรอง** แล้วค่อยกรองเฉพาะรายการที่จะแสดง')
  process.exit(1)
}
console.log('✅ ทุกแท็บนับจากชุดเต็ม ไม่ได้นับจากรายการที่กรองด้วยแท็บแล้ว')
