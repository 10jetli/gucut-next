#!/usr/bin/env node
/* ด่าน: **เทสที่ถูกย้ายออกจาก glob ต้องไม่หายเงียบ**
 *
 * 🔴 ที่มา (12 ต.ค. 2569) — ผมทิ้งเทสที่เขียนไม่จบไว้ใน `scripts/tests/` ของรีโปร่วม
 *    ⇒ `npm test` แดง ⇒ **ด่าน push ของอีกฝั่งตีกลับ** และเขาต้องหยุดสืบว่าของใคร
 *    ⇒ ผมเสนอกลไก: เทสที่ยังไม่จบให้ตั้งชื่อ `*.wip.mjs` (นอก glob `*.test.mjs`)
 *
 * 🔑 **แต่ฝั่งท่อชี้ว่าข้อเสนอนั้นเป็นเครื่องมือครึ่งเดียว** และเขาถูก:
 *    *"เทสที่ย้ายออกแล้วไม่มีใครย้ายกลับ = เทสที่ไม่เคยรันเลย และไม่มีอะไรฟ้อง"*
 *    ⇒ กฎนั้นแปลง **ต้นไม้แดง (ดัง ใครก็เห็น)** เป็น **เทสที่หายไปเงียบ ๆ (ไม่มีใครเห็น)**
 *    = คลาสที่เราเขียนกันทั้งวัน: **ย้ายความเสี่ยงไปที่ที่ตัววัดมองไม่เห็น**
 *    ⇒ ⇒ จึงต้องมาเป็น **คู่**: ย้ายออกได้ แต่ต้องมีคนนับและพูดชื่อออกมาทุกรอบ
 *
 * พฤติกรรม
 *   · มี `.wip.mjs` ⇒ **พิมพ์ชื่อ + อายุทุกรอบ** (ไม่เงียบ แม้ยังไม่เกินเพดาน)
 *   · อายุเกิน 48 ชม. ⇒ **ตก** — เทสที่ค้างข้ามวันคือเทสที่ถูกลืม ไม่ใช่เทสที่กำลังเขียน
 *     (48 ไม่ใช่ 24 เพราะงานข้ามคืนมีจริง · ไม่ใช่ 7 วันเพราะนั่นคือลืมแน่นอนแล้ว)
 *   🚫 **ห้ามแก้เพดานเพื่อให้ผ่าน** — เพดานมีไว้บังคับให้เลือก: เขียนให้จบ หรือลบทิ้ง
 */
import { readdirSync, statSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const ที่เทส = join(ROOT, 'scripts/tests')
const เพดานชั่วโมง = 48

/** ตัวตัดสินล้วน — รับรายการ {ชื่อ, อายุชั่วโมง} คืนรายการที่เกินเพดาน
 *  🔑 แยกออกมาเพื่อให้ป้อนค่าปลอมได้ (ตัวที่อ่านดิสก์จริงทดสอบไม่ได้) */
export const เกินเพดาน = (รายการ, เพดาน = เพดานชั่วโมง) =>
  รายการ.filter((x) => x.อายุชั่วโมง > เพดาน)

if (process.argv.includes('--self-test')) {
  const เคส = [
    { ควรจับ: true, ชื่อ: 'ควรจับ: ค้าง 49 ชม. (ข้ามสองวัน = ถูกลืม)', ใน: [{ ชื่อ: 'a.wip.mjs', อายุชั่วโมง: 49 }] },
    { ควรจับ: false, ชื่อ: 'ต้องไม่จับ: เพิ่งสร้าง 1 ชม. (กำลังเขียนอยู่)', ใน: [{ ชื่อ: 'a.wip.mjs', อายุชั่วโมง: 1 }] },
    { ควรจับ: false, ชื่อ: 'ต้องไม่จับ: 48 ชม.พอดี (เพดานใช้ > ไม่ใช่ >=)', ใน: [{ ชื่อ: 'a.wip.mjs', อายุชั่วโมง: 48 }] },
    { ควรจับ: false, ชื่อ: 'ต้องไม่จับ: ไม่มีไฟล์ wip เลย', ใน: [] },
    { ควรจับ: true, ชื่อ: 'ควรจับ: มีหลายไฟล์ ใบใดใบหนึ่งเกิน', ใน: [{ ชื่อ: 'a.wip.mjs', อายุชั่วโมง: 2 }, { ชื่อ: 'b.wip.mjs', อายุชั่วโมง: 100 }] },
  ]
  let ตก = 0
  for (const ก of เคส) {
    const ได้ = เกินเพดาน(ก.ใน).length > 0
    const ตรง = ได้ === ก.ควรจับ
    if (!ตรง) ตก++
    console.log(`  ${ตรง ? '✅' : '❌'} ${ก.ชื่อ}`)
  }
  console.log(ตก ? `🛑 self-test ตก ${ตก} เคส` : '🧪 self-test ผ่าน (สองทิศ 5 เคส)')
  process.exit(ตก ? 1 : 0)
}

let ไฟล์ = []
try {
  ไฟล์ = readdirSync(ที่เทส).filter((f) => f.endsWith('.wip.mjs'))
} catch {
  /* ไม่มีโฟลเดอร์เทส = ไม่มีอะไรต้องนับ */
}

if (!ไฟล์.length) {
  console.log('✅ ไม่มีเทสค้างรูป `*.wip.mjs`')
  process.exit(0)
}

const now = Date.now()
const รายการ = ไฟล์.map((f) => ({
  ชื่อ: f,
  อายุชั่วโมง: (now - statSync(join(ที่เทส, f)).mtimeMs) / 3_600_000,
}))

/* 🔑 **พิมพ์ทุกรอบ แม้ยังไม่เกินเพดาน** — เจตนาทั้งหมดของด่านนี้คือ "ไม่ให้หายเงียบ" */
console.log(`📋 เทสที่ยังเขียนไม่จบ (อยู่นอก glob ⇒ **ไม่ได้ถูกรัน**) ${รายการ.length} ไฟล์`)
for (const x of รายการ) {
  console.log(`   · ${x.ชื่อ} — ค้าง ${x.อายุชั่วโมง.toFixed(1)} ชม.`)
}

const เก่าเกิน = เกินเพดาน(รายการ)
if (เก่าเกิน.length) {
  console.log(`\n🛑 ค้างเกิน ${เพดานชั่วโมง} ชม. ${เก่าเกิน.length} ไฟล์ — **เทสที่ค้างข้ามวันคือเทสที่ถูกลืม**`)
  console.log('   ⇒ เขียนให้จบแล้วเปลี่ยนชื่อเป็น `.test.mjs` · หรือลบทิ้ง')
  console.log('   🚫 ห้ามขยายเพดานเพื่อให้ผ่าน — เพดานมีไว้บังคับให้เลือก')
  process.exit(1)
}
console.log(`\n⚠️ ยังไม่เกินเพดาน ${เพดานชั่วโมง} ชม. — แต่ของพวกนี้ **ยังไม่มีใครรัน** จนย้ายกลับเข้า glob`)
process.exit(0)
