#!/usr/bin/env node
/* ด่านก่อน build: ชื่อเมนูของเราต้องเป็น "คำเดียวกับ ZORT" และอยู่กลุ่มเดียวกัน
 *
 * 🔴 ทำไมต้องมีด่านนี้ — คำสั่งท่านประธาน 15 ก.ย. 2569:
 *    "ใช้ภาษาแบบ zort คือให้เหมือน 100% ลูกน้องผมใช้ จะให้เขารู้สึกว่าไม่ได้ปรับตัวมาก"
 *    วัดด้วยมือเมื่อ 16 ก.ย. 2569 ได้ 36 ชื่อตรงตัวอักษรและอยู่กลุ่มเดียวกันทั้ง 36
 *    ถ้าไม่มีด่าน วันหนึ่งมีคนเปลี่ยนชื่อเมนูให้ "สื่อความหมายกว่า" แล้วความเหมือนจะหายไปเงียบ ๆ
 *
 * ด่านนี้ไม่ได้บังคับให้ทำเมนูครบทุกอันของ ZORT — บังคับแค่ว่า
 *   ① ชื่อที่ ZORT มีและเราก็มี ⇒ ต้องอยู่ **กลุ่มเดียวกับ ZORT**
 *   ② ชื่อของ ZORT ที่เราไม่มี ⇒ ต้องมีเหตุผลเขียนไว้ในไฟล์นี้ (รายการ ยกเว้น ข้างล่าง)
 *      ไม่งั้นแปลว่า "ลืมทำ" แล้วไม่มีใครรู้
 * สแนปช็อตชื่อเมนูของ ZORT: scripts/zort-menu-snapshot.json (เก็บเฉพาะชื่อเมนู ไม่มีข้อมูลร้าน)
 */
import { readFileSync } from 'node:fs'
import { ตัดคอมเมนต์ } from './lib/ตัดคอมเมนต์.mjs'

const snap = JSON.parse(readFileSync(new URL('./zort-menu-snapshot.json', import.meta.url), 'utf8'))
const nav = ตัดคอมเมนต์(readFileSync(new URL('../lib/nav-config.ts', import.meta.url), 'utf8'))

/** ชื่อของ ZORT ที่เราตั้งใจไม่มี หรือตั้งใจใช้คำอื่น — ต้องมีเหตุผลเสมอ */
const ยกเว้น = {
  'สร้างรายการขาย': 'เรามีจอนี้ แต่เจ้าของร้านสั่งให้ใช้ชื่อ POS',
  'คืนสินค้า': 'เราใช้ "คืนสินค้าให้ผู้ขาย" กันสับสนกับ "รับคืนสินค้า" ในกลุ่มขาย',
  'กลุ่มลูกค้า': 'ปิดเรื่องแล้ว — API ทำไม่ได้ และของจริงใน ZORT เป็น 0',
  'ตัวแทนจำหน่าย': 'ปิดเรื่องแล้ว — API ทำไม่ได้ และของจริงใน ZORT เป็น 0',
  'หน้าสั่งซื้อ': 'ปิดเรื่องแล้ว — dropship ของจริงเป็น 0',
  'เพิ่มเซลเพจ': 'ปิดเรื่องแล้ว — เซลเพจทำผ่าน API ไม่ได้',
  'รายการรับเงิน COD': 'ปิดเรื่องแล้ว — ท่อไม่มีเส้นนี้',
  'ไฟล์': 'ยังเป็น soon(files) — จอสลิปรายใบมีแล้ว จอรวมยังไม่ได้ทำ',
  'แพ็คเกจหลัก': 'ค่าบริการที่ร้านจ่ายให้ ZORT ไม่ใช่งานหน้าร้าน',
  'แพ็คเกจเสริม': 'ค่าบริการที่ร้านจ่ายให้ ZORT ไม่ใช่งานหน้าร้าน',
  'ส่วนเสริม': 'ค่าบริการที่ร้านจ่ายให้ ZORT ไม่ใช่งานหน้าร้าน',
  'แพ็คเกจของคุณ': 'ค่าบริการที่ร้านจ่ายให้ ZORT ไม่ใช่งานหน้าร้าน',
  'ประวัติการสั่งซื้อ': 'ประวัติซื้อแพ็คเกจกับ ZORT ไม่ใช่งานหน้าร้าน',
}

/* อ่านเมนูของเราแบบบรรทัดต่อบรรทัด: บรรทัดที่เป็น label เดี่ยว = ชื่อกลุ่ม · บรรทัดที่มี href = เมนูย่อย */
const ของเรา = new Map()
let กลุ่ม = null
for (const ln of nav.split('\n')) {
  const g = ln.match(/^\s*label:\s*'([^']+)',\s*$/)
  if (g && !ln.includes('href')) { กลุ่ม = g[1]; continue }
  const it = ln.match(/href:[^,]+,\s*label:\s*'([^']+)'/)
  if (it && กลุ่ม && !ของเรา.has(it[1])) ของเรา.set(it[1], กลุ่ม)
}

const ผิดกลุ่ม = []
const ไม่มีเหตุผล = []
let ตรงกัน = 0
for (const { กลุ่ม: zg, ชื่อ } of snap['เมนูย่อย']) {
  if (ของเรา.has(ชื่อ)) {
    if (ของเรา.get(ชื่อ) !== zg) ผิดกลุ่ม.push(`${ชื่อ}: ZORT อยู่ [${zg}] แต่ของเราอยู่ [${ของเรา.get(ชื่อ)}]`)
    else ตรงกัน++
  } else if (!ยกเว้น[ชื่อ]) {
    ไม่มีเหตุผล.push(ชื่อ)
  }
}

console.log(`เทียบชื่อเมนูกับ ZORT (สแนปช็อต ${snap['วันที่เก็บ']}): ของ ZORT ${snap['เมนูย่อย'].length} ชื่อ · ตรงกันและอยู่กลุ่มเดียวกัน ${ตรงกัน} · ตั้งใจไม่มี ${Object.keys(ยกเว้น).length}`)

if (ผิดกลุ่ม.length || ไม่มีเหตุผล.length) {
  if (ผิดกลุ่ม.length) {
    console.error('\n🔴 ชื่อเดียวกับ ZORT แต่ไปอยู่คนละกลุ่ม — คนที่ชิน ZORT จะหาไม่เจอ')
    for (const x of ผิดกลุ่ม) console.error('   ' + x)
  }
  if (ไม่มีเหตุผล.length) {
    console.error('\n🔴 ชื่อของ ZORT ที่เมนูเราไม่มี และยังไม่มีเหตุผลกำกับ')
    for (const x of ไม่มีเหตุผล) console.error('   ' + x)
    console.error('   ⇒ ถ้าตั้งใจไม่ทำ ให้ใส่เหตุผลในตัวแปร `ยกเว้น` ของ scripts/check-nav-vs-zort.mjs')
    console.error('   ⇒ ถ้าเปลี่ยนชื่อเอง ให้ถามตัวเองก่อนว่าลูกน้องที่ชิน ZORT จะหาเจอไหม')
  }
  process.exit(1)
}
console.log('✅ ชื่อเมนูยังเป็นคำเดียวกับ ZORT และอยู่กลุ่มเดียวกัน')
