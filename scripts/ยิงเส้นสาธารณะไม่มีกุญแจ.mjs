/* ยิงเส้นที่ข้ามกำแพงล็อกอิน **โดยไม่ใส่กุญแจ** แล้วดูว่ามันปฏิเสธจริงไหม
 * (19 ก.ย. 2569 · งาน S2 — คู่กับ `check-public-paths-have-keys.mjs` ที่อ่านซอร์ส)
 *
 * 🔑 **ทำไมต้องมีทั้งสองตัว**
 *   ตัวอ่านซอร์สตอบว่า "ในไฟล์มีรูปของการตรวจกุญแจและรูปของการปฏิเสธ"
 *   ตัวนี้ตอบว่า "**ยิงจริงแล้วมันปฏิเสธ**" ⇒ เป็นพฤติกรรม ไม่ใช่ร่องรอย
 *   ⇒ วันนี้พิสูจน์แล้วว่าตัวอ่านซอร์สถูกหลอกได้ 4 ชั้น (คอมเมนต์ · กุญแจขาออก ·
 *      สตริงคำแนะนำ · โค้ดในกิ่งที่ไม่มีวันเรนเดอร์) ⇒ ตัวที่ยิงจริงข้ามทั้งสี่ชั้นไปเลย
 *
 * 🚫 **ห้ามใส่ใน prebuild** — มันยิงเน็ตจริง ⇒ กินเวลาฟังก์ชัน = กินเครดิต
 *    และ build รันบ่อยกว่า deploy มาก ⇒ ใช้หลัง deploy หรือเรียกมือ
 *
 * ⚠️ **ยิงด้วย GET เท่านั้น** — ตั้งใจ ไม่ใช่ความมักง่าย
 *    เส้นพวกนี้ส่วนใหญ่เป็น POST ที่ทำงานจริง (ส่งบิล · เขียนไฟล์ · ยิงต่อไปหาคนอื่น)
 *    ยิง POST โดยไม่มีกุญแจ = ถ้าเส้นนั้นเปิดโล่งจริง **เราจะเป็นคนทำให้มันทำงาน**
 *    ⇒ ตัวตรวจต้องไม่ก่อผลข้างเคียงในสิ่งที่มันตรวจ
 *    ⇒ ราคาที่จ่าย: 405 (วิธีไม่ถูก) **ตัดสินไม่ได้** เพราะด่านวิธีมาก่อนด่านกุญแจ
 *       ⇒ ต้องนับแยกให้เห็น ห้ามนับเป็นผ่าน
 *
 * วิธีใช้: node scripts/ยิงเส้นสาธารณะไม่มีกุญแจ.mjs [ฐาน]
 *   ฐานเริ่มต้น https://admin.gucut.com (ตั้ง GUCUT_SCREEN_BASE ทับได้)
 */
import { readFileSync, readdirSync } from 'node:fs'
import { join, relative, sep } from 'node:path'

const ฐาน = process.argv[2] || process.env.GUCUT_SCREEN_BASE || 'https://admin.gucut.com'

/* อ่านจาก middleware.ts ตัวจริง — **ที่เดียวกับที่ของจริงใช้** ไม่ใช่รายการที่ลอกมาไว้ในสคริปต์
   (ลอกไว้ = วันที่ใครเพิ่มเส้นใหม่ ตัวนี้จะไม่รู้ แล้วเงียบอย่างมั่นใจ) */
const mw = readFileSync('middleware.ts', 'utf8')
const m = mw.match(/const PUBLIC_PATHS = \[([\s\S]*?)\]/)
if (!m) { console.error('🔴 อ่าน PUBLIC_PATHS ใน middleware.ts ไม่ออก — ตัวตรวจเองพัง'); process.exit(1) }
const เส้น = [...m[1].matchAll(/'([^']+)'/g)].map((x) => x[1])
if (!เส้น.length) { console.error('🔴 PUBLIC_PATHS ว่าง — ไม่มีของให้ตรวจ ⇒ ถือว่าไม่ผ่าน'); process.exit(1) }

/** เส้นที่ **ตอบ 200 ให้คนไม่มีกุญแจได้โดยชอบธรรม** — ต้องมีเหตุผล ไม่ใช่แค่ชื่อ
 *  (ชุดเดียวกับที่ `check-public-paths-have-keys.mjs` ยกเว้นไว้ — ถ้าแก้ ต้องแก้ให้ตรงกันทั้งสองที่
 *   ⚠️ นี่คือเลขเกณฑ์ที่อยู่สองที่ ซึ่งเรารู้ว่าเพี้ยนกันได้ — ยังไม่รวบเพราะคนละรูป
 *      (ที่โน่นเป็นเส้นทางไฟล์ · ที่นี่เป็นเส้นทาง URL) ⇒ จดไว้เป็นหนี้) */
const เปิดได้โดยชอบธรรม = {
  '/login': 'หน้าล็อกอินเอง',
  '/api/auth': 'ถามสิทธิ์ — คนยังไม่ล็อกอินต้องได้ role: null ไม่ใช่ 401',
  '/api/google': 'เปลี่ยนทาง OAuth + ปลายทางที่ Google ส่งคนกลับมา',
  /* เหตุผลเดียวกับที่ `check-public-paths-have-keys.mjs` ยกเว้นไว้ (ไล่ตรวจ 19 ก.ย. 2569 ใบ t_mu7uzq7a):
     แพลตฟอร์ม Rokid เรียกเส้นนี้ตอนกด "ทดสอบการเชื่อมต่อ" **ก่อน** ใส่กุญแจ
     ⇒ ใส่กุญแจแล้วปุ่มทดสอบพัง · คืนแค่ชื่อโมเดล ไม่มีข้อมูลร้าน */
  '/api/rokid/v1/models': 'แพลตฟอร์มเรียกก่อนใส่กุญแจ — คืนแค่ชื่อโมเดล',
  /* GET ของเส้นนี้เป็น **เส้นเช็คว่ามีชีวิตอยู่** มีคอมเมนต์กำกับในไฟล์ตั้งแต่เขียน
     (POST ซึ่งเป็นตัวที่คุยกับ Anthropic จริง ตรวจ ROKID_BRIDGE_KEY ตามปกติ)
     ⚠️ **แต่ต้องจดว่ามันบอกอะไรกับคนแปลกหน้าจริง ๆ** ไม่ใช่ยกเว้นแบบเหมารวม:
        ชื่อบริการ · ชื่อโมเดล · และ `ready` = ตั้งกุญแจครบหรือยัง (ค่าบูลีน ไม่ใช่ตัวกุญแจ)
     ⇒ `ready` เป็นสัญญาณสำรวจเล็ก ๆ สำหรับคนนอก ⇒ เสนอให้ทบทวนว่าจำเป็นต้องเปิดไหม
        แต่ **ไม่ใช่ของที่ผมจะไปแก้เอง** เพราะเป็นพฤติกรรมที่มีคนตั้งใจทำไว้ */
  '/api/rokid/v1/chat/completions': 'GET = เส้นเช็คว่ามีชีวิตอยู่ (POST ตรวจกุญแจปกติ) · รั่วแค่ชื่อบริการ/โมเดล/ธง ready',
}

/* 🔴 **คำนำหน้า ≠ เส้น** — เจอตอนยิงจริงรอบแรก 19 ก.ย. 2569
   `/api/rokid` กับ `/api/telegram` ตอบ 404 เพราะไม่มี route ที่ path นั้นตรง ๆ
   แต่ middleware ยกเว้นด้วย `startsWith` ⇒ **ลูกทุกตัวใต้คำนำหน้านั้นเปิดหมด**
   ⇒ ยิงแค่คำนำหน้าแล้วได้ 404 **ไม่ได้พิสูจน์อะไรเลย** — มันคือ 307 รุ่นเดียวกับที่ CLAUDE.md เตือนไว้
   ⇒ ต้องกางออกเป็น route จริงจากดิสก์ก่อนยิง */
function เส้นจริงใต้(prefix) {
  const ราก = 'app' + prefix
  const out = []
  const เดิน = (d) => {
    let รายการ
    try { รายการ = readdirSync(d, { withFileTypes: true }) } catch { return }
    for (const e of รายการ) {
      if (e.isDirectory()) เดิน(join(d, e.name))
      else if (/^route\.tsx?$/.test(e.name)) out.push('/' + relative('app', d).split(sep).join('/'))
    }
  }
  เดิน(ราก)
  return out
}
const กาง = []
for (const p of เส้น) {
  const ลูก = เส้นจริงใต้(p)
  if (ลูก.length && !ลูก.includes(p)) กาง.push(...ลูก)
  else กาง.push(p)
}
const เส้นที่ยิง = [...new Set(กาง)]
console.log(`กาง PUBLIC_PATHS ${เส้น.length} รายการ → เส้นจริง ${เส้นที่ยิง.length} เส้น`)

const ผล = []
for (const p of เส้นที่ยิง) {
  const url = ฐาน.replace(/\/+$/, '') + p
  let สถานะ = null, ข้อความ = ''
  try {
    const r = await fetch(url, { method: 'GET', redirect: 'manual' })
    สถานะ = r.status
    ข้อความ = (await r.text().catch(() => '')).slice(0, 80).replace(/\s+/g, ' ')
  } catch (e) { ข้อความ = String(e).slice(0, 60) }
  ผล.push({ p, สถานะ, ข้อความ })
}

const ปฏิเสธ = [], เปิดโล่ง = [], ตัดสินไม่ได้ = [], ยกเว้น = []
for (const r of ผล) {
  const ชอบธรรม = Object.keys(เปิดได้โดยชอบธรรม).find((k) => r.p === k || r.p.startsWith(k + '/'))
  if (ชอบธรรม) { ยกเว้น.push(r); continue }
  if (r.สถานะ === 401 || r.สถานะ === 403) ปฏิเสธ.push(r)
  else if (r.สถานะ !== null && r.สถานะ >= 200 && r.สถานะ < 300) เปิดโล่ง.push(r)
  else ตัดสินไม่ได้.push(r)
}

console.log(`ยิงเส้นสาธารณะโดยไม่ใส่กุญแจ · ฐาน ${ฐาน} · ${เส้นที่ยิง.length} เส้น`)
console.log(`   ✅ ปฏิเสธถูกต้อง (401/403): ${ปฏิเสธ.length}`)
console.log(`   ⏭️  ยกเว้นโดยชอบธรรม: ${ยกเว้น.length} — ${ยกเว้น.map((r) => r.p).join(' ') || '—'}`)
console.log(`   ⚠️ ตัดสินไม่ได้: ${ตัดสินไม่ได้.length} (มักเป็น 405 เพราะเส้นนั้นรับแต่ POST)`)
for (const r of ตัดสินไม่ได้) console.log(`      ${r.p} → HTTP ${r.สถานะ ?? 'ยิงไม่ถึง'}  ${r.ข้อความ}`)
console.log('   🔑 "ตัดสินไม่ได้" ไม่ใช่ "ผ่าน" — เส้นพวกนี้ยัง**ไม่เคยถูกพิสูจน์**ว่าปฏิเสธคนแปลกหน้า')

if (เปิดโล่ง.length) {
  console.error(`\n🔴 เส้นที่ข้ามกำแพงล็อกอิน และ **ตอบ 2xx ให้คนไม่มีกุญแจ**:`)
  for (const r of เปิดโล่ง) console.error(`   ${r.p} → HTTP ${r.สถานะ}  ${r.ข้อความ}`)
  process.exit(1)
}
console.log('\n✅ ไม่มีเส้นไหนตอบ 2xx ให้คนไม่มีกุญแจ (เท่าที่ยิงด้วย GET ตัดสินได้)')
