#!/usr/bin/env node
/* สมอของสูตรปลูก "ตรงฟรี" กี่ตัว — 🚫 ไม่อยู่ใน prebuild (รันด่านทุกตัว · ช้า)
 * (30 ก.ย. 2569 · CEO เสนอตัวควบคุมนี้ · ใบ t_mu8i1pu1)
 *
 * 🔴 ปัญหาที่ไฟล์นี้เกิดมาวัด:
 *    `ต้องเอ่ยถึง` มีไว้กัน "ด่านแดงด้วยเหตุอื่น" ⇒ ผลที่อ้างว่าเกิดจากการปลูก
 *    ต้อง **เอ่ยถึงของที่ปลูก** ด้วย · แต่ถ้าสมอเป็น **ชื่อข้อของเทส**
 *    ชื่อข้อถูกพิมพ์ **ทั้งตอนผ่านและตอนตก** ⇒ สมอ **ตรงฟรีเสมอ** ⇒ ไม่ได้พิสูจน์อะไรเลย
 *    ⇒ สูตรพวกนั้นให้ผล 'ด่านจับได้' ที่อ่อนกว่าที่ตัวเลขความครอบคลุมบอก
 *
 * 🔑 ตัวควบคุมเชิงกล (CEO 30 ก.ย. 2569) — **ไม่ต้องปลูกเลย**
 *      ไม่ปลูก ⇒ สมอโผล่    ⇒ 🔴 สมอ "ตรงฟรี"
 *      ไม่ปลูก ⇒ สมอไม่โผล่ ⇒ ✅ สมอแยกแยะได้จริง
 *    ⇒ ได้รายชื่อทั้งทะเบียนในรอบเดียว **ไม่ต้องไล่ด้วยตา**
 *    🔑 และนี่คือกฎเดิมของเราในรูปที่ใช้กับตัวทดสอบเอง:
 *       **ตัววัดต้องถูกพิสูจน์ว่าเงียบตอนไม่มีของ** — ที่ผ่านมาเราพิสูจน์แต่ว่ามันดังตอนมีของ
 *
 * ⚠️ ขอบเขต: ไฟล์นี้ตรวจ **คุณภาพของสมอ** เท่านั้น
 *    ไม่ได้ตรวจว่า `แก้()` ปลูกลงจริง หรือด่านจับพฤติกรรมได้ (นั่นคือ `ด่านแยกแยะได้ไหม.mjs`)
 * ⚠️ ต้องรันบนต้นไม้ที่สะอาด — ผลของด่านบางตัวเปลี่ยนตามไฟล์ที่ค้างแก้
 *
 * วิธีใช้: node scripts/สมอตรงฟรีไหม.mjs
 */
import { spawnSync } from 'node:child_process'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { สูตร } from './lib/ทะเบียนด่าน.mjs'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
process.chdir(ROOT)

const สกปรก = spawnSync('git', ['status', '--porcelain'], { encoding: 'utf8' }).stdout || ''
/* ไฟล์ที่ build สร้างเอง ไม่นับว่าสกปรก (มันถูกเขียนทุกครั้งที่ build) */
const แถวสกปรก = สกปรก.trim().split('\n').filter((l) => l.trim() && !/lib\/arch-admin\.ts$/.test(l))
if (แถวสกปรก.length) {
  console.error('🔴 ต้นไม้สกปรก ⇒ ผลของด่านอาจเปลี่ยนตามไฟล์ที่ค้าง ⇒ ไม่วัด')
  console.error(แถวสกปรก.join('\n'))
  process.exit(1)
}

/* 🔑 จัดกลุ่มตามคำสั่งด่าน แล้วรัน **คำสั่งละครั้งเดียว**
   144 สูตรใช้ด่านซ้ำกันมาก ⇒ รันทุกสูตรจะเสียเวลาหลายเท่าโดยไม่ได้ข้อมูลเพิ่ม */
const ตามด่าน = new Map()
for (const f of สูตร) {
  const คำสั่ง = Array.isArray(f.ด่าน) ? f.ด่าน.join(' ') : `node ${f.ด่าน}`
  if (!ตามด่าน.has(คำสั่ง)) ตามด่าน.set(คำสั่ง, [])
  ตามด่าน.get(คำสั่ง).push(f)
}
/* ⚠️ บรรทัดนี้เป็น **ความคืบหน้า ไม่ใช่ผล** ⇒ ต้องออก stderr
   ของเดิมออก stdout แล้วโหมด `--ทะเบียน` ที่ redirect stdout ลงไฟล์ **ได้ JSON ที่มีขยะนำหน้า**
   ⇒ ไฟล์ทะเบียน parse ไม่ได้ทั้งที่เครื่องมือ exit 0 (เจอจริง 30 ก.ย. 2569 · เสียหนึ่งรอบ)
   🔑 กติกา: เครื่องมือที่มีโหมดพิมพ์ของที่เครื่องอ่าน ⇒ **stdout มีได้แต่ผล** ที่เหลือไป stderr */
console.error(`ทะเบียน ${สูตร.length} สูตร · ด่านที่ต่างกัน ${ตามด่าน.size} ตัว ⇒ รันด่านละครั้ง\n`)

/* 🔑 **เกณฑ์เรียงคิว: "ไฟล์ที่สูตรนั้นปลูกใส่ เดินไปถึงตัวเขียนไหม"** (CEO ให้ 30 ก.ย. 2569)
 *
 * 🔴 ของเดิมผมเรียงด้วย **พาธ** ซึ่งเป็นการเดาจากชื่อ — และผมมีหลักฐานของตัวเองแล้วว่าชื่อโกหก:
 *    `/api/bills/vendor` ฟังดูอ่านอย่างเดียว แต่มันเรียก Gmail และ **เขียนแคชสองชุด**
 *    (ผมยิงมัน 12 ครั้งโดยเชื่อชื่อ แล้วไปอ่านโค้ดทีหลัง — 30 ก.ย. 2569)
 *
 * ⚠️ **ป้ายต้องเขียนว่า "อาจถึงตัวเขียน" ไม่ใช่ "แตะเงิน"** — เกณฑ์นี้ **ประมาณเกินจริง**
 *    (ไฟล์อาจอิมพอร์ตตัวเขียน แต่กิ่งที่สูตรนั้นแตะไม่ได้เรียกมัน)
 * 🔑 และการประมาณเกินจริงเป็น **ทิศที่ถูกสำหรับคิวลำดับความสำคัญ**
 *    เสียเวลาดูของที่ไม่อันตราย ดีกว่าข้ามของที่อันตราย
 *    🚫 แต่ใช้ **ตัดสิน** ไม่ได้ — เกณฑ์ที่ใช้ตัดสินประมาณเกินจริงไม่ได้ (คนละหน้าที่ อย่ายุบกัน) */
const สัญญาณตัวเขียน = [
  /* แรงสุด — เรียก/อิมพอร์ตตัวเขียนจริง */
  ['เรียกตัวเขียน', 3, /\b(setJSON|getStore|save[A-Z\u0E00-\u0E7F]|uploadBillToBlobs|deleteBillBlob|syncBill|rememberBill|writeFileSync|appendFileSync|zortAddOrder|INSERT\s|UPDATE\s|DELETE\s+FROM)/],
  /* รอง — เส้นนั้นเปิดวิธีที่เปลี่ยนข้อมูล */
  ['เปิด POST/PUT/DELETE', 2, /export\s+async\s+function\s+(POST|PUT|DELETE)\b/],
  /* เสริม — แตะฟิลด์ที่เป็นเงิน/จำนวน **ในข้อมูล** (ไม่ใช่ที่พาธ) */
  ['แตะฟิลด์เงิน/จำนวน', 1, /\b(qty|amount|price|cost|total|sku|stock)\b/],
]
const แคชอ่านไฟล์ = new Map()
const เนื้อไฟล์ = (พาธ) => {
  if (!พาธ) return ''
  if (!แคชอ่านไฟล์.has(พาธ)) {
    try { แคชอ่านไฟล์.set(พาธ, readFileSync(พาธ, 'utf8')) } catch { แคชอ่านไฟล์.set(พาธ, '') }
  }
  return แคชอ่านไฟล์.get(พาธ)
}
/** คืน { ระดับ, เพราะ } — `ระดับ` สูง = น่าจะถึงตัวเขียนมากกว่า · `เพราะ` = **หลักฐานที่อ่านได้** */
const อาจถึงตัวเขียน = (พาธ) => {
  const เนื้อ = เนื้อไฟล์(พาธ)
  const เจอ = สัญญาณตัวเขียน.filter(([, , re]) => re.test(เนื้อ))
  return {
    ระดับ: เจอ.reduce((a, [, n]) => Math.max(a, n), 0),
    เพราะ: เจอ.map(([ชื่อ]) => ชื่อ).join(' · ') || 'ไม่พบสัญญาณตัวเขียนในไฟล์',
  }
}

const อ่อน = [], แข็ง = [], ไม่มีสมอ = [], ด่านแดงอยู่ก่อน = []
let ทำไปแล้ว = 0
for (const [คำสั่ง, กลุ่ม] of ตามด่าน) {
  ทำไปแล้ว++
  const ส่วน = คำสั่ง.split(' ')
  const r = spawnSync(ส่วน[0], ส่วน.slice(1), { encoding: 'utf8' })
  const out = (r.stdout || '') + (r.stderr || '')
  process.stderr.write(`\r  รัน ${ทำไปแล้ว}/${ตามด่าน.size} …`)
  /* 🔴 ด่านที่ **แดงอยู่ก่อนปลูก** ⇒ ผลของสูตรทั้งกลุ่มตีความไม่ได้เลย
     (คลาสที่ฝั่งท่อเจอ 26 ก.ย. 2569 — ปลูกแล้วแดง แต่มันแดงอยู่แล้ว) */
  if (r.status !== 0) {
    ด่านแดงอยู่ก่อน.push({ คำสั่ง, จำนวนสูตร: กลุ่ม.length, exit: r.status })
    continue
  }
  for (const f of กลุ่ม) {
    const ว = อาจถึงตัวเขียน(f.ไฟล์)
    const ใบ = { ด่าน: คำสั่ง, ไฟล์: f.ไฟล์, สมอ: f.ต้องเอ่ยถึง, เล่า: f.เล่า,
      ระดับเขียน: ว.ระดับ, เพราะ: ว.เพราะ }
    if (!f.ต้องเอ่ยถึง) ไม่มีสมอ.push(ใบ)
    else if (out.includes(f.ต้องเอ่ยถึง)) อ่อน.push(ใบ)
    else แข็ง.push(ใบ)
  }
}
process.stderr.write('\r')

const เรียง = (a) => [...a].sort((x, y) =>
  (y.ระดับเขียน - x.ระดับเขียน) || String(x.ไฟล์).localeCompare(String(y.ไฟล์)))
const ป้าย = (n) => (n >= 3 ? '✍️✍️' : n === 2 ? '✍️ ' : n === 1 ? '·  ' : '   ')

/* ── `--ทะเบียน` ⇒ พิมพ์ทะเบียนหนี้เป็น JSON ให้เอาไป commit ────────────────
   🔑 **เครื่องมือพิมพ์ คนเอาไป commit** — ไม่ให้มันเขียนไฟล์ที่ตัวเองตรวจ
      (กฎเดิม: ตัวตรวจห้ามเขียนสิ่งที่มันตรวจ ⇒ ไม่งั้นหนี้จะ "ปิดตัวเอง" ทุกรอบ) */
if (process.argv.includes('--ทะเบียน')) {
  const ทะเบียน = {
    _อ่านก่อนแก้: [
      'ทะเบียน **หนี้** ของสมอที่ตรงฟรี — ไม่ใช่รายการที่ได้รับอนุมัติ',
      'ชื่อในนี้ = สมอที่ยังพิสูจน์ไม่ได้ว่าแยกแยะได้ (โผล่ทั้งที่ไม่ได้ปลูก)',
      'ด่าน scripts/check-anchor-new.mjs ใช้ไฟล์นี้เป็น **ชุดที่ล็อกไว้**:',
      '  สมอตรงฟรีที่ **ไม่อยู่ในชุดนี้** ⇒ แดงทันที (กันตัวที่ 78)',
      '  ชื่อที่ถูกแก้แล้ว ⇒ **ต้องลบออกจากไฟล์นี้** ไม่งั้นทะเบียนโกหกว่ายังมีหนี้',
      'สร้างด้วย: node scripts/สมอตรงฟรีไหม.mjs --ทะเบียน > scripts/lib/สมออ่อน.json',
    ],
    /* 🔴 **เวลาไทย ไม่ใช่ UTC** — เครื่องรัน UTC ⇒ ช่วง 00:00–07:00 ของไทย
       `toISOString()` จะให้ **วันก่อนหน้า** ⇒ แสตมป์ชี้วันผิดโดยไม่มีอะไรฟ้อง
       (เจอจริงกับไฟล์นี้เอง 30 ก.ย. 2569 เวลา 03:09 ไทย ⇒ ได้ 2026-09-29) */
    วันที่วัด: new Date(Date.now() + 7 * 3600e3).toISOString().slice(0, 10),
    เวลาไทยที่วัด: new Date(Date.now() + 7 * 3600e3).toISOString().slice(0, 16).replace('T', ' '),
    ตรงฟรี: เรียง(อ่อน).map((u) => ({ ด่าน: u.ด่าน, สมอ: u.สมอ, ไฟล์: u.ไฟล์,
      อาจถึงตัวเขียน: u.ระดับเขียน, เพราะ: u.เพราะ })),
    ไม่มีสมอ: เรียง(ไม่มีสมอ).map((u) => ({ ด่าน: u.ด่าน, ไฟล์: u.ไฟล์ })),
    /* 🔑 **ต้องจดกองที่ผ่านด้วย ไม่ใช่จดแต่หนี้**
       ด่าน `check-anchor-new.mjs` ถือว่า "คู่ที่ไม่อยู่ในไฟล์นี้" = **ยังไม่มีคำตอบ** ⇒ ต้องรันวัด
       ถ้าจดแต่หนี้ กองที่ผ่าน 69 คู่จะถูกนับว่า "ยังไม่มีคำตอบ" ⇒ ต้องรันด่าน 55 คำสั่งทุก build
       ⇒ เท่ากับเอาตัวกวาดเต็มไปใส่ลูกโซ่ ซึ่งเป็นสิ่งที่เราตั้งใจเลี่ยง (เหยียบมาแล้ว 30 ก.ย. 2569)
       ⚠️ จดแค่ **คีย์** ไม่จดรายละเอียด — ของกองนี้ไม่มีอะไรต้องตามไปแก้ */
    แยกแยะได้: แข็ง.map((u) => `${u.ด่าน}|${u.สมอ}`).sort(),
  }
  process.stdout.write(JSON.stringify(ทะเบียน, null, 2) + '\n')
  process.exit(0)
}


console.log(`ขอบเขต: ตรวจ **คุณภาพของสมอ (ต้องเอ่ยถึง)** เท่านั้น`)
console.log(`   ไม่ได้ตรวจว่า แก้() ปลูกลงจริง หรือด่านจับพฤติกรรมได้ — นั่นคือ ด่านแยกแยะได้ไหม.mjs\n`)
console.log(`✅ สมอที่แยกแยะได้จริง (ไม่โผล่ตอนไม่ปลูก): ${แข็ง.length}`)
console.log(`🔴 สมอที่ **ตรงฟรี** (โผล่ทั้งที่ไม่ได้ปลูก): ${อ่อน.length}`)
console.log(`🟠 สูตรที่ **ไม่มีสมอเลย**: ${ไม่มีสมอ.length}`)
if (ด่านแดงอยู่ก่อน.length) {
  console.log(`\n🔴 ด่านที่ **แดงอยู่ก่อนปลูก** ${ด่านแดงอยู่ก่อน.length} ตัว ⇒ สูตรในกลุ่มนี้ตีความไม่ได้`)
  for (const d of ด่านแดงอยู่ก่อน) console.log(`   · ${d.คำสั่ง} (exit ${d.exit} · ${d.จำนวนสูตร} สูตร)`)
}

if (อ่อน.length) {
  console.log(`\n🔴 รายชื่อสมอที่ตรงฟรี — เรียงด้วย **"อาจถึงตัวเขียนไหม"** (อ่านจากโค้ด ไม่ใช่จากพาธ)`)
  console.log(`   ✍️✍️ = เรียกตัวเขียนจริง · ✍️ = เปิด POST/PUT/DELETE · · = แตะฟิลด์เงิน/จำนวน`)
  console.log(`   ⚠️ ป้ายนี้ **ประมาณเกินจริง** (ไฟล์อาจอิมพอร์ตตัวเขียนแต่กิ่งที่ปลูกไม่เรียก)`)
  console.log(`      ⇒ ใช้ **เรียงคิว** ได้ · ใช้ **ตัดสิน** ไม่ได้`)
  for (const u of เรียง(อ่อน)) {
    console.log(`   ${ป้าย(u.ระดับเขียน)} ${u.ไฟล์}  — ${u.เพราะ}`)
    console.log(`      ด่าน: ${u.ด่าน}`)
    console.log(`      สมอที่ตรงฟรี: ${JSON.stringify(u.สมอ)}`)
  }
}
if (ไม่มีสมอ.length) {
  console.log(`\n🟠 สูตรที่ไม่มีสมอเลย (อ่อนกว่าสมอตรงฟรี เพราะไม่มีอะไรกัน "แดงด้วยเหตุอื่น")`)
  for (const u of เรียง(ไม่มีสมอ)) console.log(`   ${ป้าย(u.ระดับเขียน)} ${u.ไฟล์} — ${u.เล่า}`)
}

console.log(`\n🚫 **ห้ามแก้ทั้งหมดในรอบเดียว** (CEO สั่ง) — ผลงานของรอบนี้คือ **รายชื่อ**`)
console.log(`   แก้ทีละตัวโดยเปลี่ยนสมอเป็น **ข้อความที่พิมพ์เฉพาะตอนตก** แล้วพิสูจน์ซ้ำด้วย`)
console.log(`   ด่านแยกแยะได้ไหม.mjs เฉพาะสูตรนั้น`)
/* 🔑 ไฟล์นี้ **รายงานอย่างเดียว ไม่ทำให้ตก** — ถ้าทำให้ตกตอนนี้ ลูกโซ่จะแดงทันที
   144 ตัว แล้วคนจะปิดมันทิ้ง · ให้เป็นตัววัดที่มีเลขก่อน แล้วค่อยตั้งเพดานเมื่อเลขลงพอ */
console.log(`\n📌 ไฟล์นี้รายงานอย่างเดียว (exit 0 เสมอ) — ยังไม่ตั้งเพดาน`)
console.log(`   เหตุ: ตั้งเพดานวันแรกที่วัด = ลูกโซ่แดงทันที แล้วคนจะปิดตัววัดทิ้ง`)
console.log(`   ⇒ เก็บเลขก่อน · ตั้งเพดานเมื่อเลขลงมาถึงระดับที่ถือได้`)
process.exit(0)
