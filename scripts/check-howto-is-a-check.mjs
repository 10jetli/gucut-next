import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const ไฟล์ทะเบียน = 'app/core/settings-jobs/page.tsx'

/** ชี้ของที่เปิด/ยิงได้ไหม — พาธ · พารามิเตอร์ · ชื่อจอ · ช่องทางที่เด้งหา */
export const ชี้ของที่เปิดได้ = (t) => /\/[a-z][\w/-]*|\?[A-Za-z][\w]*=|จอ|หน้า|Telegram|การ์ด|แถบ|คอลัมน์|กลุ่ม/.test(t)
/** อ้างสถานะการ deploy ของเส้นท่อไหม */
export const อ้างสถานะdeploy = (t) => /ยังไม่ขึ้นเว็บ|ขึ้นเว็บแล้ว|ยังไม่ deploy|ยังไม่ได้ deploy/.test(t)
/** มีคำสั่งที่คนอ่านยิงเองได้ไหม */
export const มีคำสั่งยิง = (t) => /(GET|POST)\s+\/|ยิง\s+GET|\?[A-Za-z][\w]*=/.test(t)

/** ดึงค่า `howToTell` ทุกก้อน (ต่อบรรทัดด้วย `+` ได้) — คืน [{บรรทัด, ข้อความ}] */
export function เก็บช่องวิธีตรวจ(ซอร์ส) {
  const ล = ซอร์ส.split('\n')
  const out = []
  for (let i = 0; i < ล.length; i++) {
    if (!/^\s*howToTell:\s*'/.test(ล[i])) continue
    let ก้อน = ล[i]
    let j = i + 1
    while (j < ล.length && /^\s*\+/.test(ล[j])) { ก้อน += ' ' + ล[j].trim(); j++ }
    out.push({ บรรทัด: i + 1, ข้อความ: ก้อน })
  }
  return out
}

/** ตัดสินก้อนเดียว — คืนชื่อความผิด หรือ null ถ้าผ่าน */
export function ตัดสินช่อง(ข้อความ) {
  if (!ชี้ของที่เปิดได้(ข้อความ)) return 'ไม่ชี้ของที่เปิดหรือยิงได้'
  if (อ้างสถานะdeploy(ข้อความ) && !มีคำสั่งยิง(ข้อความ)) return 'อ้างสถานะ deploy โดยไม่มีคำสั่งตรวจกำกับ'
  return null
}

if (process.argv.includes('--self-test')) {
  /* 🔑 **ปลูกสองทิศ** ตามที่ฝั่งท่อขอ: มีคำสั่งกำกับ ⇒ เขียว · ถอดคำสั่งออก ⇒ แดง
     ถ้าปลูกทิศเดียวเราจะไม่รู้ว่ามันแยกแยะ หรือมันแดงกับทุกอย่าง */
  const เคส = [
    ['ชี้จอ ⇒ ผ่าน', "howToTell: 'จอดันสต็อก — ต้องมีรอบกวาดในชั่วโมงที่ผ่านมา',", null],
    ['ชี้พาธ ⇒ ผ่าน', "howToTell: 'เปิด /bills ดูวันที่บิลล่าสุด',", null],
    ['บอกแค่พฤติกรรม ⇒ แดง', "howToTell: 'ออเดอร์ที่จ่ายแล้วต้องเปลี่ยนสถานะเองภายในครึ่งชั่วโมง',",
      'ไม่ชี้ของที่เปิดหรือยิงได้'],
    ['อ้าง deploy + มีคำสั่งยิง ⇒ ผ่าน',
      "howToTell: 'ยิง GET /api/web/core?mkpfeesum=1 (เส้นขึ้นเว็บแล้ว แต่ยังตอบ 0 จาก 0)',", null],
    ['อ้าง deploy แต่ถอดคำสั่งยิงออก ⇒ แดง',
      "howToTell: 'เส้นนี้ยังไม่ขึ้นเว็บ ให้รอจนกว่าจะ deploy แล้วดูที่จอนี้',",
      'อ้างสถานะ deploy โดยไม่มีคำสั่งตรวจกำกับ'],
  ]
  let ตก = 0
  for (const [ชื่อ, ข้อความ, คาด] of เคส) {
    const ได้ = ตัดสินช่อง(ข้อความ)
    const ผ่าน = ได้ === คาด
    if (!ผ่าน) ตก += 1
    console.log(`  ${ผ่าน ? '✅' : '🔴'} ${ชื่อ} ⇒ ${ได้ ?? 'ผ่าน'}${ผ่าน ? '' : ` (คาด ${คาด ?? 'ผ่าน'})`}`)
  }
  /* ตัวควบคุมของตัวอ่าน: ต้องอ่านก้อนที่ต่อหลายบรรทัดได้ ไม่ใช่เห็นแค่บรรทัดแรก */
  const หลายบรรทัด = เก็บช่องวิธีตรวจ("    howToTell: 'อย่างแรก '\n      + 'ยิง GET /api/web/core?x=1',\n")
  const อ่านต่อได้ = หลายบรรทัด.length === 1 && มีคำสั่งยิง(หลายบรรทัด[0].ข้อความ)
  console.log(`  ${อ่านต่อได้ ? '✅' : '🔴'} อ่านก้อนที่ต่อด้วย + ได้ครบ (ถ้าอ่านแค่บรรทัดแรกจะพลาดคำสั่งยิง)`)
  if (!อ่านต่อได้) ตก += 1
  if (ตก) { console.error(`🔴 self-test ตก ${ตก} เคส ⇒ ห้ามเชื่อผลของด่านนี้`); process.exit(1) }
  console.log('✅ self-test ผ่าน — แยกแยะได้ทั้งสองทิศ (มีคำสั่งกำกับ ⇒ เขียว · ถอดออก ⇒ แดง)')
  process.exit(0)
}

const ซอร์ส = readFileSync(join(ROOT, ไฟล์ทะเบียน), 'utf8')
const ช่อง = เก็บช่องวิธีตรวจ(ซอร์ส)
if (!ช่อง.length) {
  console.error(`🔴 ไม่เจอช่อง howToTell ใน ${ไฟล์ทะเบียน} เลย ⇒ **ตะแกรงพัง ไม่ใช่ผ่าน**`)
  console.error('   (ไฟล์ถูกย้าย/เปลี่ยนรูป ⇒ ด่านนี้จะเขียวตลอดกาลถ้าไม่ร้องตรงนี้)')
  process.exit(1)
}
const ผิด = []
for (const x of ช่อง) {
  const เหตุ = ตัดสินช่อง(x.ข้อความ)
  if (เหตุ) ผิด.push({ ...x, เหตุ })
}
console.log(`ช่อง "วิธีตรวจ" ใน ${ไฟล์ทะเบียน}: ${ช่อง.length} ช่อง`)
if (ผิด.length) {
  console.error(`\n🔴 ${ผิด.length} ช่องไม่ผ่าน`)
  for (const x of ผิด) {
    console.error(`   ${ไฟล์ทะเบียน}:${x.บรรทัด} — ${x.เหตุ}`)
    console.error(`      ${x.ข้อความ.trim().slice(0, 120)}`)
  }
  console.error('\n   ⇒ ช่องนี้มีหน้าที่ตอบว่า "จะรู้ได้ยังไงว่างานนี้ยังวิ่ง"')
  console.error('      ⇒ ต้องชี้ของที่เปิด/ยิงได้ · และถ้าอ้างสถานะ deploy ต้องมีคำสั่งตรวจกำกับ')
  console.error('      (คำยืนยันเรื่องสถานะหมดอายุเงียบ ๆ · คำสั่งตรวจไม่หมดอายุ)')
  process.exit(1)
}
console.log('✅ ทุกช่องชี้ของที่เปิด/ยิงได้ · ไม่มีช่องไหนอ้างสถานะ deploy โดยไม่มีคำสั่งตรวจ')
