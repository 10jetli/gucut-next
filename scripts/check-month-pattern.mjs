const ข้าม = new Set(['node_modules', '.next', '.next-verify', '.git', 'public', 'scripts'])
function ไฟล์ทั้งหมด(ที่, เก็บ = []) {
  for (const ชื่อ of readdirSync(ที่)) {
    if (ข้าม.has(ชื่อ)) continue
    const p = join(ที่, ชื่อ)
    if (statSync(p).isDirectory()) ไฟล์ทั้งหมด(p, เก็บ)
    else if (/\.(ts|tsx|mjs)$/.test(ชื่อ)) เก็บ.push(p)
  }
  return เก็บ
}

export function ตรวจ(รากที่ตรวจ = ROOT) {
  const เจอ = []
  for (const p of ไฟล์ทั้งหมด(รากที่ตรวจ)) {
    const rel = relative(รากที่ตรวจ, p).replace(/\\/g, '/')
    if (rel === แหล่งเดียว) continue
    const บรรทัด = readFileSync(p, 'utf8').split('\n')
    บรรทัด.forEach((l, i) => {
      if (รูปหลวม.test(l)) เจอ.push({ ไฟล์: rel, บรรทัด: i + 1, เนื้อ: l.trim().slice(0, 100) })
    })
  }
  return เจอ
}

