#!/usr/bin/env node
/* กวาดหา "ของปลูก" ที่ค้างอยู่ในรีโป — **ทำให้ build ตก**
 * (19 ก.ย. 2569 · ตามข้อที่ฝั่งท่อกับผมตกลงกันตอนปิดรอบค่ำ)
 *
 * 🔴 ที่มา: บ่ายวันนี้เครื่องมือของผมเองเรียกตัวเองไม่รู้จบ แล้ว **แก้ไฟล์ด่านจริงทับกัน**
 *    ผมกู้ด้วย `git checkout` แล้วมันเขียนทับกลับมาอีก เพราะยังมีลูกวิ่งอยู่
 *    ⇒ ตอนปิดรอบผมกวาดหาของค้างด้วยมือ ⇒ **นั่นคือความตั้งใจ ไม่ใช่กลไก**
 *    ⇒ และบทเรียนทั้งวันคือความตั้งใจไม่รอด
 *
 * 🔑 **`git status` สะอาด ไม่ได้แปลว่าไม่มีของปลูก**
 *    ถ้าเครื่องมือเขียนทับไฟล์แล้วมีคน commit ทับไป ⇒ git บอกสะอาด แต่เนื้อในเป็นของปลูก
 *    ⇒ ต้องกวาดที่ **เนื้อไฟล์** ไม่ใช่ที่สถานะของ git
 *
 * ⚠️ **คำที่ใช้เป็น sentinel ต้องเป็นคำที่ "เกิดเองตามธรรมชาติไม่ได้"** (ฝั่งท่อเจอกับตัวเอง)
 *    เขาใส่คำภาษาคนลงรายการ ⇒ ไปเจอในคอมเมนต์ที่เขียนอธิบายไว้ก่อนหน้า ⇒ **ด่านร้องใส่ของปกติ**
 *    ⇒ และที่แย่กว่านั้น: **ถ้าปลูกด้วยคำภาษาคน ของที่ค้างจะตรวจไม่เจอเลย**
 *    ⇒ กติกา: ปลูกครั้งหน้าใช้รูป `ZZ…ZZ` หรือคำนำหน้า `zz-` เท่านั้น
 *
 * 🔴 **ต้องตัดคอมเมนต์ก่อนกวาด — ด่านนี้ร้องใส่ของถูกตั้งแต่รันครั้งแรก**
 *    มันไปเจอ `ZZNOPEZZ` ใน **คอมเมนต์ของ check-public-paths-have-keys** ที่เขียนเล่าไว้ว่า
 *    "ทำลายตัวจับเป็น /ZZNOPEZZ/ แล้ว self-test ยังเขียว" ⇒ **การเอ่ยถึง ≠ ของปลูกที่ค้าง**
 *    🔑 ผูกกับ **เงื่อนไขที่ทำให้ผิด**: ของปลูกที่ค้างคือ **โค้ดที่ทำงาน** ไม่ใช่ข้อความที่เล่าเรื่อง
 *    ⚠️ และไม่กวาด `.md` เลย — ไฟล์เอกสารเป็นร้อยแก้วทั้งไฟล์ ⇒ ทุกการเอ่ยถึงจะกลายเป็นธงลวง
 */
import { readFileSync, readdirSync, statSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join, relative } from 'node:path'
import { ตัดคอมเมนต์ } from './lib/ตัดคอมเมนต์.mjs'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const ตัวเอง = relative(ROOT, fileURLToPath(import.meta.url))

/** คำที่เครื่องมือปลูกของเรา **ใช้จริง** — ไม่ใช่คำที่นึกเอา
 *  🚫 ห้ามใส่คำภาษาคนลงรายการนี้ (จะร้องใส่คอมเมนต์ปกติ)
 *
 *  🔴 **ย้ายไปเป็นแหล่งเดียวแล้ว 20 ก.ย. 2569** — เดิมรายการนี้พิมพ์ไว้ที่นี่
 *     และถูกพิมพ์ซ้ำอีก **4 ไฟล์** ⇒ **5 ที่ที่เพี้ยนจากกันได้**
 *     ⇒ ⇒ วันเดียวกันนั้นหมุดตัวเดียวทำให้สองฝั่งพลาดคนละทิศ:
 *        ฝั่งจอเจอ **แดงลวง** (ใช้หมุดเป็นตัวควบคุมในเทส) ·
 *        ฝั่งท่อเจอ **เขียวลวง** (ใช้หมุด 6 จุด แต่ชื่อนั้นไม่อยู่ในรายการที่ด่านจับ)
 *     🔑 กฎที่ตกลงกันสองฝั่ง: **รายการหมุดต้องเป็นแหล่งเดียว · ทุกที่ที่ใช้ต้องอ้างจากรายการนั้น** */
import { คำหมุดของปลูก as ของปลูก } from './lib/คำหมุดของปลูก.mjs'

/** ไฟล์ที่ **ได้รับอนุญาตให้เอ่ยถึงคำพวกนี้** เพราะมันคือเครื่องมือที่ใช้คำนั้นเอง */
const เอ่ยได้ = new Set([
  ตัวเอง,
  /* 🔑 **แหล่งเดียวของคำหมุด** (20 ก.ย. 2569) — ไฟล์นี้คือที่เดียวที่ตัวอักษรของหมุดถูกพิมพ์จริง
     ทุกที่อื่น `import` เอาไป ⇒ ⇒ **ยกเว้นหนึ่งที่ ดีกว่ายกเว้นห้าที่**
     และเหตุผลของการยกเว้นอ่านได้จากหัวไฟล์นั้นเอง ไม่ต้องจำ */
  'scripts/lib/คำหมุดของปลูก.mjs',
  'scripts/ตะแกรงของด่านถูกทดสอบไหม.mjs',
  /* ทะเบียนสูตรปลูก — **ต้องมีคำพวกนี้โดยธรรมชาติ** เพราะมันคือของที่มันปลูก
     (ด่านนี้จับไฟล์นี้ได้ตอนเพิ่มเข้ามาใหม่ 19 ก.ย. 2569 ⇒ ด่านถูก รายการยกเว้นไม่ครบ) */
  /* 🔴 **ย้ายมาที่นี่ 20 ก.ย. 2569** — เดิมยกเว้น `scripts/ด่านแยกแยะได้ไหม.mjs`
     แต่ผมย้าย "ทะเบียนสูตร" ออกไปไฟล์ข้อมูลล้วน ⇒ **คำหมุดย้ายตามไปด้วย**
     ⇒ ด่านนี้ร้องทันทีในรอบ build ถัดไป ⇒ **ด่านถูก รายการยกเว้นล้าสมัย**
     🔑 บทเรียน: **ข้อยกเว้นผูกกับ "ไฟล์" ไม่ได้ผูกกับ "เนื้อหา"**
        ⇒ ย้ายโค้ดข้ามไฟล์เมื่อไหร่ ข้อยกเว้นขาดทันที — และคราวนี้มันขาดแบบ **ส่งเสียง** ซึ่งดี
     ✅ `ด่านแยกแยะได้ไหม.mjs` ไม่มีคำหมุดเหลือแล้ว (วัดแล้ว: 0) ⇒ **ถอดออกจากรายการยกเว้น** */
  'scripts/lib/ทะเบียนด่าน.mjs',
  /* เครื่องมือวัดส่วนต่าง — ปลูกคำหมุดเป็น **ตัวควบคุมบวก** ของตัวมันเอง
     🔑 และมันคือตัวที่พิสูจน์ว่า **การยกเว้นมีราคา**: ไฟล์ที่อยู่ในรายการนี้
        จะวัดด้วยตัวควบคุมชนิดคำหมุดไม่ได้อีกต่อไป (ต้องใช้ไวยากรณ์พังแทน) */
  'scripts/คลังตัวอย่างทำด่านสะดุดไหม.mjs',
])
/* 🚫 **คลัง `รูปที่เคยพลาด` จงใจไม่อยู่ในรายการนี้** (19 ก.ย. 2569)
   มันเคยเขียนคำหมุดตรง ๆ ในคำบรรยายรูป ⇒ ด่านนี้จับได้ตอน build ⇒ **ด่านถูก**
   ทางแก้คือ **เลี่ยงคำนั้นในคลัง** ไม่ใช่ยกเว้นคลัง
   เพราะการยกเว้นจะทำให้คลังกลายเป็นไฟล์ที่ **วัดไม่ได้** ด้วยวิธีเดียวกับที่เราใช้วัดไฟล์อื่น */

function เดิน(dir, out = []) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (e.name === 'node_modules' || e.name === '.next' || e.name.startsWith('.')) continue
    const p = join(dir, e.name)
    if (e.isDirectory()) เดิน(p, out)
    else if (/\.(ts|tsx|mjs|js|json)$/.test(e.name)) out.push(p)   // 🚫 ไม่กวาด .md (ร้อยแก้ว)
  }
  return out
}

const ราก = ['app', 'components', 'lib', 'scripts', 'netlify', 'middleware.ts']
let ไฟล์ = []
for (const r of ราก) {
  const เต็ม = join(ROOT, r)
  try { ไฟล์ = ไฟล์.concat(statSync(เต็ม).isDirectory() ? เดิน(เต็ม) : [เต็ม]) } catch { /* ไม่มี = ข้าม */ }
}

/* 🔒 ไม่มีไฟล์ให้กวาด = ตะแกรงพัง ไม่ใช่รีโปสะอาด */
if (ไฟล์.length < 50) {
  console.error(`🔴 กวาดได้แค่ ${ไฟล์.length} ไฟล์ — **ตัวเดินไฟล์พัง ไม่ใช่รีโปสะอาด**`)
  process.exit(1)
}

const เจอ = []
for (const p of ไฟล์) {
  const rel = relative(ROOT, p)
  if (เอ่ยได้.has(rel)) continue
  const ดิบ = readFileSync(p, 'utf8')
  /* JSON ไม่มีคอมเมนต์ ⇒ ตัดไม่ได้และไม่ต้องตัด · ที่เหลือตัดก่อนกวาดเสมอ */
  const t = rel.endsWith('.json') ? ดิบ : ตัดคอมเมนต์(ดิบ)
  for (const คำ of ของปลูก) {
    if (!t.includes(คำ)) continue
    const บรรทัด = t.split('\n').findIndex((l) => l.includes(คำ)) + 1
    เจอ.push(`${rel}:${บรรทัด}  ${คำ}`)
  }
}

console.log(`กวาดของปลูกค้าง: ${ไฟล์.length} ไฟล์ (ตัดคอมเมนต์ก่อนกวาด · ไม่กวาด .md) · คำที่กวาด ${ของปลูก.length} คำ · ยกเว้น ${เอ่ยได้.size} ไฟล์`)
if (เจอ.length) {
  console.error('\n🔴 เจอของปลูกค้างอยู่ในรีโป — **นี่คือโค้ดที่ถูกแก้ไว้ตอนทดสอบแล้วลืมคืน**')
  for (const x of เจอ) console.error('   ' + x)
  console.error('   ⇒ คืนไฟล์ด้วย `git checkout -- <ไฟล์>` แล้วตรวจว่าไม่มีตัวทดสอบวิ่งค้างอยู่ (`ps`)')
  process.exit(1)
}
console.log('✅ ไม่มีของปลูกค้าง')
