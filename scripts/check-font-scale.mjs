#!/usr/bin/env node
/* ด่าน: ขนาดตัวหนังสือต้องอยู่ในชุดที่ตกลงไว้ — ท่านประธานสั่ง 11 ต.ค. 2569 "ทำขนาดตัวหนังสือเท่ากัน"
 *
 * 📏 **ทำไมต้องมีด่าน ไม่ใช่กวาดครั้งเดียว**
 *    ก่อนกวาด: **30 ขนาดต่างกัน · ใช้ 2,920 จุด** ⇒ ไม่มีใครตั้งใจให้เป็นอย่างนั้น
 *    มันโตเพราะทุกคนพิมพ์ `text-[12px]` หรือ `text-[13px]` ตามความรู้สึกตอนนั้น
 *    ⇒ กวาดแล้วไม่มีด่าน = กลับมาเป็น 30 ในเดือนหน้าโดยไม่มีใครรู้
 *
 * 📐 **ที่มาของชุด ไม่ได้เลือกจากความชอบ** — วัด font-size ที่ **เรนเดอร์จริง** บน `/core/registry`
 *    ด้วย Chrome ที่ล็อกอินอยู่ (11 ต.ค. 2569): `12.5px ×239` (เนื้อ) · `12px ×16` (หัวตาราง)
 *    · `13px ×2` (คำโปรย) · `13.5px ×6` (ป้ายสรุป) ⇒ **สี่ขนาดในช่วง 1.5px อยู่ติดกัน**
 *    ⇒ ยุบเข้าหาค่าที่ใช้มากที่สุด เพื่อให้ข้อความส่วนใหญ่ไม่ขยับขนาดเลย
 *
 * ⚠️ ชุดนี้ **ไม่ใช่กฎศักดิ์สิทธิ์** — ต้องการขนาดใหม่จริงให้เติมใน `อนุญาต` **พร้อมเหตุผล**
 *    ด่านนี้กัน "ขนาดที่โผล่มาเพราะพิมพ์ตามความรู้สึก" ไม่ได้กัน "ขนาดที่ตั้งใจเพิ่ม"
 *
 * 🔑 **ตัวควบคุมอยู่ในโค้ดที่รันจริง ไม่ใช่ใน `--self-test`**
 *    ด่าน `check-guard-controls` ของรีโปตีกลับรุ่นแรกของไฟล์นี้ **และมันถูก**:
 *    self-test ที่ต้องสั่งแยกจะไม่เคยถูกเรียกในสายจริง ⇒ ตะแกรงที่กว้างเกินจะไม่มีใครเห็น
 *    ⇒ ต้องมีทั้งเคส *ควรจับ* และ *ต้องไม่จับ* คู่กัน และรันก่อนตัดสินทุกครั้ง
 */
import { readdirSync, readFileSync, statSync } from 'node:fs'
import { join } from 'node:path'

/** ชุดที่อนุญาต · เนื้อหา 3 ขั้น + หัวเรื่อง/เลขเด่นตามที่มีอยู่จริง */
const อนุญาต = new Set([
  '10', '11.5', '12.5',                                 // เนื้อหา: จิ๋ว · เล็ก · หลัก
  '14', '15', '16', '17', '18', '20', '22',             // หัวหมวด · เลขเด่น
  '24', '26', '28', '30', '32', '34', '36', '38', '40', // หัวจอ
])

/** หาขนาดนอกชุดในข้อความหนึ่งก้อน — **ฟังก์ชันเดียวที่ทั้งของจริงและตัวควบคุมใช้**
 *  (ถ้าตัวควบคุมเรียกสำเนาอีกตัว มันจะวัดสำเนาของตัวเอง ไม่ใช่ของที่ใช้จริง) */
export function ขนาดนอกชุด(ข้อความ, ชุด = อนุญาต) {
  const ออก = []
  String(ข้อความ ?? '').split('\n').forEach((l, i) => {
    for (const m of l.matchAll(/text-\[([0-9.]+)px\]/g)) {
      if (!ชุด.has(m[1])) ออก.push({ บรรทัด: i + 1, ขนาด: m[1] })
    }
  })
  return ออก
}

/* ── ตัวควบคุมของด่านนี้เอง · รันทุกครั้งก่อนตัดสิน ──
   🔑 แต่ละเคสประกาศ **ทิศที่คาดไว้เอง** (จำนวนที่ควรจับ) ไม่ใช่เขียนแค่ผ่าน/ไม่ผ่าน */
const เคสควบคุม = [
  ['ขนาดในชุด ⇒ ต้องไม่จับ', '<p className="text-[12.5px]">ก</p>', 0],
  ['สามขั้นเนื้อหาในบรรทัดเดียว ⇒ ต้องไม่จับ', 'text-[10px] text-[11.5px] text-[12.5px]', 0],
  ['หัวจอในชุด ⇒ ต้องไม่จับ', 'className="text-[26px] font-bold"', 0],
  ['ขนาดนอกชุด ⇒ ควรจับ', '<p className="text-[13px]">ก</p>', 1],
  ['ครึ่งพิกเซลที่ยุบไปแล้ว ⇒ ควรจับ', 'text-[13.5px] text-[14.5px]', 2],
  ['ขนาดนอกชุดปนกับในชุด ⇒ จับแค่ตัวนอกชุด', 'text-[12.5px] text-[12px]', 1],
  ['ไม่มีคลาสขนาดเลย ⇒ ต้องไม่จับ', 'className="font-bold text-gray-500"', 0],
  ['คลาสคนละรูป (ไม่ใช่ px) ⇒ ต้องไม่จับ', 'text-sm text-[1.5rem] text-[12em]', 0],
]
let ตกควบคุม = 0
for (const [ชื่อ, ป้อน, ควร] of เคสควบคุม) {
  const ได้ = ขนาดนอกชุด(ป้อน).length
  const ผ่าน = ได้ === ควร
  if (!ผ่าน) { ตกควบคุม++; console.log(`  ❌ ${ชื่อ} — ควรจับ ${ควร} แต่จับได้ ${ได้}`) }
}
/* 🔑 **ตัวควบคุมลบ**: ชุดที่อนุญาตครบ ⇒ ของจริงต้องไม่ถูกจับเพราะตะแกรงกว้างเกิน
   เขียนผลที่คาดไว้ในบรรทัดเดียวกับคำควบคุม เพื่อให้ `check-guard-controls` อ่านได้ */
const ตัวควบคุมลบผ่าน = ขนาดนอกชุด('text-[12.5px] text-[11.5px] text-[10px]').length === 0
if (!ตัวควบคุมลบผ่าน) ตกควบคุม++
console.log(`  ${ตัวควบคุมลบผ่าน ? '✅' : '❌'} ตัวควบคุมลบ: ทุกขนาดอยู่ในชุด ⇒ ต้องไม่จับ false ไม่เกิดขึ้น`)
const นับควรจับ = เคสควบคุม.filter((c) => c[2] > 0).length
const นับต้องไม่จับ = เคสควบคุม.length - นับควรจับ + 1   // +1 = ตัวควบคุมลบที่อยู่นอกอาร์เรย์
if (ตกควบคุม) {
  console.log(`🔴 ตัวควบคุมของด่านนี้ตก ${ตกควบคุม} เคส ⇒ **ตัวเลขข้างล่างอ่านไม่ได้** ⇒ ไม่ตัดสิน`)
  process.exit(1)
}
console.log(`   ✅ ตัวควบคุม ${เคสควบคุม.length + 1} เคสผ่านก่อนตัดสิน `
  + `(ควรจับ ${นับควรจับ} · ต้องไม่จับ ${นับต้องไม่จับ}) ⇒ เลขข้างล่างอ่านได้`)

/* ── ของจริง ── */
const ไฟล์ = []
const เดิน = (d) => {
  for (const e of readdirSync(d)) {
    if (e === 'node_modules' || e.startsWith('.')) continue
    const p = join(d, e)
    if (statSync(p).isDirectory()) เดิน(p)
    else if (/\.(tsx|ts)$/.test(e)) ไฟล์.push(p)
  }
}
for (const d of ['app', 'components']) เดิน(d)

const ผิด = []
for (const f of ไฟล์) for (const x of ขนาดนอกชุด(readFileSync(f, 'utf8'))) ผิด.push({ f, ...x })

if (ผิด.length) {
  console.log(`🔴 เจอขนาดตัวหนังสือนอกชุด ${ผิด.length} จุด`)
  const ตามขนาด = new Map()
  for (const x of ผิด) ตามขนาด.set(x.ขนาด, (ตามขนาด.get(x.ขนาด) || 0) + 1)
  for (const [ข, น] of [...ตามขนาด].sort((a, b) => b[1] - a[1])) console.log(`   text-[${ข}px] × ${น}`)
  console.log('\n   ตัวอย่างที่ต้องแก้:')
  for (const x of ผิด.slice(0, 10)) console.log(`      ${x.f}:${x.บรรทัด}  text-[${x.ขนาด}px]`)
  /* 🔑 เลขที่ใช้ตัดสินคือ `ผิด.length` **ไม่ใช่ความยาวของตัวอย่าง** — เขียนกำกับไว้ให้คนอ่านไม่สับสน */
  if (ผิด.length > 10) console.log(`      … และอีก ${ผิด.length - 10} จุด (ใช้เลขรวมข้างบนตัดสิน ไม่ใช่จำนวนตัวอย่าง)`)
  console.log('\n   ⇒ ใช้ขนาดในชุด: เนื้อหา 10 · 11.5 · 12.5 · หัวหมวด 14 · 15 …')
  console.log('   ⇒ ถ้าต้องการขนาดใหม่จริง ให้เติมใน `อนุญาต` ของไฟล์นี้ **พร้อมเหตุผล**')
  process.exit(1)
}
console.log(`✅ ขนาดตัวหนังสืออยู่ในชุดทั้งหมด (กวาด ${ไฟล์.length} ไฟล์ · ชุดมี ${อนุญาต.size} ขนาด)`)
