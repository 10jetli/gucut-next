#!/usr/bin/env node
/* ด่าน: **ชื่อตัวแปรภาษาไทยในไฟล์เชลล์** — คลาสที่ทีมเหยียบมาแล้ว 7 ครั้ง
 *
 * 🔴 ทำไมคลาสนี้แพง: `bash` ไม่รับชื่อตัวแปรที่ไม่ใช่ `[A-Za-z_][A-Za-z0-9_]*`
 *    แต่มัน **ไม่หยุด** — มันพิมพ์ `command not found` แล้ว **เดินต่อ** จนจบสคริปต์
 *    ⇒ สคริปต์ "วิ่งเสร็จ" และ exit 0 ทั้งที่ของที่ควรทำไม่ได้ทำ
 *    ⇒ และ `bash -n` **จับไม่ได้** (มันตรวจไวยากรณ์ ไม่ได้ตรวจว่าชื่อถูกไหม)
 *    📌 ล่าสุด 14 ต.ค. 2569 ฝั่งท่อเหยียบในไฟล์ที่เพิ่งเขียน **เพื่อแก้เรื่องด่าน**
 *       (คลาส: ไฟล์ที่สร้างมากันความพลาด คือที่ที่เราระวังตัวน้อยที่สุด)
 *
 * 🔑 **ไม่แยก bash กับ python ที่ฝังใน .sh โดยตั้งใจ** (เหตุผลของฝั่งท่อ ผมเห็นด้วย):
 *    คนอ่านไฟล์ `.sh` ก็แยกไม่ออกเหมือนกันว่าบรรทัดไหนเป็นของใคร
 *    ⇒ ด่านที่ดูเข้มเกินจริงในสายตาเรา มักกำลังป้องกัน **คนอ่าน** ไม่ได้ป้องกันเครื่อง
 *    ⇒ อยากใช้ชื่อไทยในบล็อก python ให้ **แยกไฟล์ `.py` ออกไป** (ชัดกับทุกคน)
 *
 * ทางออกเมื่อจำเป็นจริง: เขียน `# ยืนยันแล้ว: <เหตุผล ≥20 อักขระ — มีช่องว่างได้>` บนบรรทัดนั้นหรือบรรทัดก่อนหน้า
 *    (ท่าเดียวกับด่านคำสั่ง bash ของทีม — บังคับให้อธิบาย ไม่ใช่ห้ามแข็ง ๆ แล้วมีคนถอดกฎ)
 */
import { readdirSync, readFileSync, statSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join, relative } from 'node:path'
import { บอกไฟล์นอกรีโป } from './lib/ของนอกรีโป.mjs'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const ข้าม = new Set(['node_modules', '.git', '.next', '.next-verify', 'out', 'public'])

/* ── ใบอนุญาต `# ยืนยันแล้ว:` — **พฤติกรรมถูกตรึงด้วยไฟล์เคสร่วมสองฝั่ง** ────────────
 *
 * 🔴 **ของจริง 14 ต.ค. 2569 — รูปเดิมของไฟล์นี้ตีกลับเหตุผลที่มีช่องว่างทุกอัน**
 *    ผมลอก **ถ้อยคำ** จากด่านทีม (`<เหตุผล ≥20 อักขระ>` คำต่อคำ) แต่ **เขียนรูปขึ้นใหม่เอง**:
 *      ของทีม `#\s*ยืนยันแล้ว:\s*(\S[^\n]{19,})`   ← ตัวแรกไม่ใช่ช่องว่าง แล้วต่อด้วยอะไรก็ได้
 *      ของผม  `#\s*ยืนยันแล้ว:\s*\S{20,}`          ← บังคับ **ไม่มีช่องว่างติดกัน 20 ตัว** 🔴
 *    ⇒ ข้อความเหมือนกันเป๊ะ พฤติกรรมต่างกัน **และต่างในทางที่เข้มกว่า**
 *    ⇒ เหตุผลที่เป็นประโยคปกติ/ภาษาอังกฤษ ถูกตีกลับ **ทั้งที่ทำตามคู่มือแล้ว**
 *    ⇒ ⇒ คนที่เจอจะสรุปว่า "ทางออกนี้ใช้ไม่ได้" แล้ว **ไปแก้โค้ดเลี่ยงด่าน** ซึ่งแย่กว่าไม่มีด่าน
 *    📌 รอดมาได้เพราะ **ภาษาไทยมักไม่มีช่องว่าง** ⇒ ถูกโดยอุบัติเหตุของภาษา
 *
 * 🔑 **ทำไมไม่ลอก regex ของเขามาใส่** (ผมเสนอเองแล้วค้านตัวเอง · ฝั่งท่อตัดสินตาม):
 *    ลอกมา = **สำเนาที่ถูกวันนี้** ⇒ วันที่เขาแก้รูป ของผมไม่ได้รับผล (คลาส "สำเนาไม่ใช่ของร่วม")
 *    และข้อที่หนักกว่า (เหตุของฝั่งท่อ): **regex ตัวเดียวร่วมกัน ⇒ วันที่มันผิด ผิดพร้อมกันสองฝั่ง**
 *    ⇒ ⇒ **เคสร่วมให้ผลตรงข้าม: รูปต่างกันได้ แต่ถ้าฝั่งใดเพี้ยน เคสจะจับฝั่งนั้นฝั่งเดียว**
 *
 * ⚠️ ไฟล์เคสอยู่ **นอกรีโป** ⇒ รายงาน mtime ทุกรอบตามกติกาผู้อ่านข้ามรีโป
 *    อ่านไม่ได้ ⇒ **ตัดสินไม่ได้** ไม่ใช่ "ผ่าน" */
const ไฟล์เคส = process.env.CONFIRM_CASES || '/home/jetli/claude-shared/lib/เคส-ใบอนุญาตยืนยันแล้ว.json'

/** รูปของฝั่งนี้ — เขียนเองโดยเจตนา แล้วให้เคสร่วมเป็นคนตัดสินว่าถูกไหม */
const รูปใบอนุญาต = /#[^\S\n]*ยืนยันแล้ว:[^\S\n]*(\S[^\n]{19,})/
const มีใบอนุญาต = (ท) => รูปใบอนุญาต.test(ท || '')

function รันเคสร่วม() {
  let เคส
  try { เคส = JSON.parse(readFileSync(ไฟล์เคส, 'utf8'))['เคส'] }
  catch (e) {
    console.error(`🔴 อ่านไฟล์เคสร่วมไม่ได้ (${ไฟล์เคส}: ${e?.code || e?.message})`)
    console.error('   ⇒ **ตัดสินไม่ได้** ไม่ใช่ "ผ่าน" — พฤติกรรมของใบอนุญาตไม่ได้ถูกตรึงรอบนี้')
    process.exit(1)
  }
  บอกไฟล์นอกรีโป(ไฟล์เคส, { ป้าย: 'เคสใบอนุญาต (ของร่วมสองฝั่ง):' })
  const ตก = []
  for (const c of เคส) {
    const ได้ = มีใบอนุญาต(c['ข้อความ'])
    if (ได้ !== c['ต้องผ่าน']) {
      ตก.push(`${c['ชื่อ']} — ต้อง${c['ต้องผ่าน'] ? 'ผ่าน' : 'ตก'} แต่ได้${ได้ ? 'ผ่าน' : 'ตก'}`
        + `${c['หมายเหตุ'] ? ` · ${c['หมายเหตุ']}` : ''}`)
    }
  }
  console.log(`   ใบอนุญาต \`# ยืนยันแล้ว:\` ผ่านเคสร่วม **${เคส.length - ตก.length}/${เคส.length}**`)
  if (ตก.length) {
    console.error(`🔴 **รูปของฝั่งนี้ไม่ตรงพฤติกรรมที่ตกลงกัน ${ตก.length} เคส**`)
    for (const x of ตก) console.error(`   · ${x}`)
    console.error('   ⇒ แก้ `รูปใบอนุญาต` ในไฟล์นี้ให้ผ่านเคส **ห้ามแก้ไฟล์เคสให้ตรงรูป**')
    console.error('     (แก้เคสให้ตรงรูป = ย้ายเกณฑ์ไปหาของที่ผิด ⇒ ด่านเขียวตลอดกาล)')
    process.exit(1)
  }
}
รันเคสร่วม()
const ไทย = '฀-๿'

/** รูปที่ **เป็นชื่อตัวแปร** จริง ๆ ไม่ใช่ข้อความไทยทั่วไปในสคริปต์ */
const รูป = [
  { ชื่อ: 'กำหนดค่า', re: new RegExp(`^\\s*(?:local\\s+|export\\s+|declare\\s+[^=]*\\s+)?[A-Za-z0-9_]*[${ไทย}][A-Za-z0-9_${ไทย}]*=`) },
  { ชื่อ: 'เรียกใช้ค่า', re: new RegExp(`\\$\\{?[${ไทย}]`) },
  { ชื่อ: 'ตัวแปรของ for/read', re: new RegExp(`\\b(?:for|read)\\s+[A-Za-z0-9_]*[${ไทย}]`) },
]

const ไฟล์ = []
;(function เดิน(ที่) {
  for (const ชื่อ of readdirSync(ที่)) {
    if (ข้าม.has(ชื่อ)) continue
    const เต็ม = join(ที่, ชื่อ)
    const st = statSync(เต็ม)
    if (st.isDirectory()) เดิน(เต็ม)
    else if (ชื่อ.endsWith('.sh')) ไฟล์.push(เต็ม)
  }
})(ROOT)

const เจอ = []
for (const f of ไฟล์) {
  const บรรทัด = readFileSync(f, 'utf8').split('\n')
  บรรทัด.forEach((บ, i) => {
    if (/^\s*#/.test(บ)) return                    // คอมเมนต์เชลล์ ไม่ใช่โค้ด
    if (มีใบอนุญาต(บ) || มีใบอนุญาต(บรรทัด[i - 1])) return
    /* 🔴 **ตัดเนื้อใน single quote ออกก่อนตรวจ** (แก้ผลบวกลวงที่เจอทันทีรอบแรก)
       ของจริง: `scripts/ปลูก-parts-models.sh:22` มี `${เหตุ}` อยู่ใน `sed 's|…|…|'`
       ซึ่งเป็น **เทมเพลตของไฟล์ TypeScript ที่กำลังถูกแก้** ไม่ใช่ตัวแปรเชลล์
       (ใน single quote ของ bash ไม่มีการขยายค่าใด ๆ ⇒ มันคือข้อความล้วน)
       ⇒ ปล่อยไว้แล้วด่านจะแดงกับของที่ทำงานถูก ⇒ **แดงลวงแพงกว่าเขียวลวง**
          เพราะมีคนไปรื้อของที่ยังดี แล้วสุดท้ายคนจะเลิกเชื่อด่านนี้
       ⚠️ bash ไม่มี escape ใน single quote ⇒ แบ่งด้วย `'` แล้วทิ้งช่วงดัชนีคี่ได้ตรง ๆ */
    const นอกquote = บ.split("'").filter((_, k) => k % 2 === 0).join(' ')
    for (const r of รูป) {
      if (r.re.test(นอกquote)) {
        เจอ.push({ ไฟล์: relative(ROOT, f), บรรทัด: i + 1, รูป: r.ชื่อ, ข้อความ: บ.trim().slice(0, 90) })
        break
      }
    }
  })
}

console.log(`ตรวจชื่อตัวแปรเชลล์: ${ไฟล์.length} ไฟล์ .sh`)
if (เจอ.length === 0) {
  console.log('   ✅ ไม่มีชื่อตัวแปรภาษาไทยในไฟล์เชลล์')
  process.exit(0)
}
console.error(`🔴 **พบชื่อตัวแปรภาษาไทยในไฟล์เชลล์ ${เจอ.length} จุด** — bash จะเดินต่อแล้ว exit 0`)
for (const x of เจอ) {
  console.error(`   · ${x.ไฟล์}:${x.บรรทัด} (${x.รูป})`)
  console.error(`     ${x.ข้อความ}`)
}
console.error('   ⇒ เปลี่ยนเป็นชื่ออังกฤษ · หรือแยกบล็อก python ออกเป็นไฟล์ .py')
console.error('   ⇒ จำเป็นจริง ให้เขียน `# ยืนยันแล้ว: <เหตุผล ≥20 อักขระ — มีช่องว่างได้>` กำกับบรรทัดนั้น')
process.exit(1)
