#!/usr/bin/env node
/* ด่าน: **ชื่อตัวแปรภาษาไทยในไฟล์เชลล์** — คลาสที่ทีมเหยียบมาแล้ว 7 ครั้ง
 *
 * 🔴 ทำไมคลาสนี้แพง: `bash` ไม่รับชื่อตัวแปรที่ไม่ใช่ `[A-Za-z_][A-Za-z0-9_]*`
 *    แต่มัน **ไม่หยุด** — มันพิมพ์ `command not found` แล้ว **เดินต่อ** จนจบสคริปต์
 *    ⇒ สคริปต์ "วิ่งเสร็จ" และ exit 0 ทั้งที่ของที่ควรทำไม่ได้ทำ
 *    ⇒ และ `bash -n` **จับไม่ได้** (มันตรวจไวยากรณ์ ไม่ได้ตรวจว่าชื่อถูกไหม)
 *    📌 ล่าสุด 14 ต.ค. 2569 ฝั่งท่อเหยียบในไฟล์ที่เพิ่งเขียน **เพื่อแก้เรื่องด่าน**
 *       (คลาส: ไฟล์ที่สร้างมากันความพลาด คือที่ที่เราระวังตัวน้อยที่สุด)
 *
 * 🔑 **ไม่แยก bash กับ python ที่ฝังใน .sh โดยตั้งใจ** (เหตุผลของฝั่งท่อ ผมเห็นด้วย):
 *    คนอ่านไฟล์ `.sh` ก็แยกไม่ออกเหมือนกันว่าบรรทัดไหนเป็นของใคร
 *    ⇒ ด่านที่ดูเข้มเกินจริงในสายตาเรา มักกำลังป้องกัน **คนอ่าน** ไม่ได้ป้องกันเครื่อง
 *    ⇒ อยากใช้ชื่อไทยในบล็อก python ให้ **แยกไฟล์ `.py` ออกไป** (ชัดกับทุกคน)
 *
 * ทางออกเมื่อจำเป็นจริง: เขียน `# ยืนยันแล้ว: <เหตุผล ≥20 อักขระ>` บนบรรทัดนั้นหรือบรรทัดก่อนหน้า
 *    (ท่าเดียวกับด่านคำสั่ง bash ของทีม — บังคับให้อธิบาย ไม่ใช่ห้ามแข็ง ๆ แล้วมีคนถอดกฎ)
 */
import { readdirSync, readFileSync, statSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join, relative } from 'node:path'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const ข้าม = new Set(['node_modules', '.git', '.next', '.next-verify', 'out', 'public'])
const ไทย = '฀-๿'

/** รูปที่ **เป็นชื่อตัวแปร** จริง ๆ ไม่ใช่ข้อความไทยทั่วไปในสคริปต์ */
const รูป = [
  { ชื่อ: 'กำหนดค่า', re: new RegExp(`^\\s*(?:local\\s+|export\\s+|declare\\s+[^=]*\\s+)?[A-Za-z0-9_]*[${ไทย}][A-Za-z0-9_${ไทย}]*=`) },
  { ชื่อ: 'เรียกใช้ค่า', re: new RegExp(`\\$\\{?[${ไทย}]`) },
  { ชื่อ: 'ตัวแปรของ for/read', re: new RegExp(`\\b(?:for|read)\\s+[A-Za-z0-9_]*[${ไทย}]`) },
]

const ไฟล์ = []
;(function เดิน(ที่) {
  for (const ชื่อ of readdirSync(ที่)) {
    if (ข้าม.has(ชื่อ)) continue
    const เต็ม = join(ที่, ชื่อ)
    const st = statSync(เต็ม)
    if (st.isDirectory()) เดิน(เต็ม)
    else if (ชื่อ.endsWith('.sh')) ไฟล์.push(เต็ม)
  }
})(ROOT)

const เจอ = []
for (const f of ไฟล์) {
  const บรรทัด = readFileSync(f, 'utf8').split('\n')
  บรรทัด.forEach((บ, i) => {
    if (/^\s*#/.test(บ)) return                    // คอมเมนต์เชลล์ ไม่ใช่โค้ด
    /* ทางออกต้องมีเหตุยาวพอ — ช่องที่รับคำว่า "จำเป็น" ได้ คือช่องที่ทุกคนจะเขียนว่า "จำเป็น" */
    const มีใบอนุญาต = (ท) => /#\s*ยืนยันแล้ว:\s*\S{20,}/.test(ท || '')
    if (มีใบอนุญาต(บ) || มีใบอนุญาต(บรรทัด[i - 1])) return
    /* 🔴 **ตัดเนื้อใน single quote ออกก่อนตรวจ** (แก้ผลบวกลวงที่เจอทันทีรอบแรก)
       ของจริง: `scripts/ปลูก-parts-models.sh:22` มี `${เหตุ}` อยู่ใน `sed 's|…|…|'`
       ซึ่งเป็น **เทมเพลตของไฟล์ TypeScript ที่กำลังถูกแก้** ไม่ใช่ตัวแปรเชลล์
       (ใน single quote ของ bash ไม่มีการขยายค่าใด ๆ ⇒ มันคือข้อความล้วน)
       ⇒ ปล่อยไว้แล้วด่านจะแดงกับของที่ทำงานถูก ⇒ **แดงลวงแพงกว่าเขียวลวง**
          เพราะมีคนไปรื้อของที่ยังดี แล้วสุดท้ายคนจะเลิกเชื่อด่านนี้
       ⚠️ bash ไม่มี escape ใน single quote ⇒ แบ่งด้วย `'` แล้วทิ้งช่วงดัชนีคี่ได้ตรง ๆ */
    const นอกquote = บ.split("'").filter((_, k) => k % 2 === 0).join(' ')
    for (const r of รูป) {
      if (r.re.test(นอกquote)) {
        เจอ.push({ ไฟล์: relative(ROOT, f), บรรทัด: i + 1, รูป: r.ชื่อ, ข้อความ: บ.trim().slice(0, 90) })
        break
      }
    }
  })
}

console.log(`ตรวจชื่อตัวแปรเชลล์: ${ไฟล์.length} ไฟล์ .sh`)
if (เจอ.length === 0) {
  console.log('   ✅ ไม่มีชื่อตัวแปรภาษาไทยในไฟล์เชลล์')
  process.exit(0)
}
console.error(`🔴 **พบชื่อตัวแปรภาษาไทยในไฟล์เชลล์ ${เจอ.length} จุด** — bash จะเดินต่อแล้ว exit 0`)
for (const x of เจอ) {
  console.error(`   · ${x.ไฟล์}:${x.บรรทัด} (${x.รูป})`)
  console.error(`     ${x.ข้อความ}`)
}
console.error('   ⇒ เปลี่ยนเป็นชื่ออังกฤษ · หรือแยกบล็อก python ออกเป็นไฟล์ .py')
console.error('   ⇒ จำเป็นจริง ให้เขียน `# ยืนยันแล้ว: <เหตุผล ≥20 อักขระ>` กำกับบรรทัดนั้น')
process.exit(1)
