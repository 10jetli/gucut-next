#!/usr/bin/env node
/* กัน **สมอตรงฟรีตัวใหม่** ไม่ให้เกิด — ล็อกด้วย **ชุดรายชื่อ** ไม่ใช่ด้วยจำนวน
 * (30 ก.ย. 2569 · CEO สั่ง: *"ห้ามรอให้ 77 ลด — ตัวที่ 78 ต้องแดงตั้งแต่คืนนี้"*)
 *
 * 🔴 ปัญหาที่ด่านนี้แก้: `scripts/สมอตรงฟรีไหม.mjs` วัดได้ครบ **แต่รายงานอย่างเดียว**
 *    ⇒ ลูกโซ่ไม่แดงวันนี้ (ดี) แต่ **คืนนี้จะมีตัวที่ 78 และไม่มีอะไรห้าม** (ไม่ดี)
 *    🔑 ท่าที่ได้ทั้งสองอย่าง: **ล็อกด้วยชุด (ratchet-by-set)**
 *       · สมอตรงฟรีที่อยู่ในชุด `scripts/lib/สมออ่อน.json` = หนี้เดิม ⇒ ผ่าน (ยกเว้น**ทีละชื่อ**)
 *       · สมอตรงฟรีที่ **ไม่อยู่ในชุด** ⇒ 🔴 แดงทันที
 *       · ชื่อในชุดที่ **ไม่มีในทะเบียนสูตรแล้ว** ⇒ 🔴 แดง (ทะเบียนที่โกหกว่ายังมีหนี้ แย่กว่าไม่มี)
 *
 * 🔑 **ทำไมถึงถูกในลูกโซ่ได้ทั้งที่ตัวกวาดเต็มกินเวลา ~15 นาที**
 *    ตัวกวาดเต็มรันด่านทุกคำสั่ง (87 ตัว) · ด่านนี้รันเฉพาะ **คู่ (ด่าน, สมอ) ที่ยังไม่มีคำตอบ**
 *    ⇒ สถานะปกติ (ไม่มีสูตรใหม่) รัน **0 คำสั่ง** · มีสูตรใหม่ 1 ตัว รัน 1 คำสั่ง
 *    ⇒ ราคาจ่ายตอนที่มีของใหม่เท่านั้น ซึ่งเป็นตอนที่เราต้องการคำตอบจริง ๆ
 *
 * ⚠️ **ขอบเขตที่ต้องอ่านให้ตรง** — ด่านนี้จับ **คู่ที่ยังไม่เคยตอบ** เท่านั้น
 *    ถ้าใครแก้ **ข้อความในด่าน** จนสมอที่เคยแยกแยะได้กลายเป็นตรงฟรี **ด่านนี้มองไม่เห็น**
 *    (คีย์คือ ด่าน|สมอ ซึ่งไม่เปลี่ยน) ⇒ ตัวที่ตอบข้อนั้นคือ **ตัวกวาดเต็ม** ที่ต้องรันเป็นรอบ
 *    🔑 เขียนไว้เพราะ "ด่านที่จับได้บางส่วน" ถูกอ่านเป็น "ด่านที่จับได้ทั้งหมด" ทุกครั้งถ้าไม่เขียน
 *
 * วิธีใช้: node scripts/check-anchor-new.mjs [--self-test]
 */
import { spawnSync } from 'node:child_process'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
process.chdir(ROOT)
const ไฟล์ชุด = 'scripts/lib/สมออ่อน.json'
const คีย์ของ = (ด่าน, สมอ) => `${ด่าน}|${สมอ}`

if (process.argv.includes('--self-test')) {
  /* ตัวควบคุมของด่านเอง — ตรรกะตัดสินยกออกมาเป็นฟังก์ชันเพื่อทดสอบตรงได้
     (ของที่ทดสอบผ่านการรันจริงเท่านั้น จะซ่อนบั๊กที่ไม่เปลี่ยน exit code) */
  const ตัดสิน = (คู่, ชุด, ผลกวาด) => {
    const ใหม่ = คู่.filter((c) => ผลกวาด[คีย์ของ(c.ด่าน, c.สมอ)] === 'ตรงฟรี'
      && !ชุด.has(คีย์ของ(c.ด่าน, c.สมอ)))
    const ค้าง = [...ชุด].filter((k) => !คู่.some((c) => คีย์ของ(c.ด่าน, c.สมอ) === k))
    return { ใหม่, ค้าง }
  }
  const คู่ = [{ ด่าน: 'ก', สมอ: 'x' }, { ด่าน: 'ข', สมอ: 'y' }]
  const เคส = [
    ['ตรงฟรีและอยู่ในชุด ⇒ ผ่าน',
      ตัดสิน(คู่, new Set(['ก|x']), { 'ก|x': 'ตรงฟรี' }).ใหม่.length === 0],
    ['ตรงฟรีแต่ไม่อยู่ในชุด ⇒ **ต้องแดง** (นี่คือตัวที่ 78)',
      ตัดสิน(คู่, new Set(), { 'ก|x': 'ตรงฟรี' }).ใหม่.length === 1],
    ['แยกแยะได้และไม่อยู่ในชุด ⇒ ผ่าน (ของดีไม่ต้องขออนุมัติ)',
      ตัดสิน(คู่, new Set(), { 'ก|x': 'แยกแยะได้' }).ใหม่.length === 0],
    ['ชื่อในชุดที่ไม่มีในทะเบียนแล้ว ⇒ ต้องฟ้องให้ลบ',
      ตัดสิน(คู่, new Set(['ไม่มีแล้ว|z']), {}).ค้าง.length === 1],
    /* 🟢 ตัวควบคุมลบของด่านนี้เอง: ชุดตรงกับทะเบียนพอดี ⇒ ต้องไม่ฟ้องอะไรเลย
       ไม่มีข้อนี้ ด่านที่ฟ้องทุกกรณีก็เขียว */
    ['🟢 ชุดตรงกับทะเบียนพอดี ⇒ ไม่ฟ้องอะไร',
      (() => { const r = ตัดสิน(คู่, new Set(['ก|x']), { 'ก|x': 'ตรงฟรี', 'ข|y': 'แยกแยะได้' })
        return r.ใหม่.length === 0 && r.ค้าง.length === 0 })()],
  ]
  let ตก = 0
  for (const [ชื่อ, ผ่าน] of เคส) { if (!ผ่าน) ตก++; console.log(`  ${ผ่าน ? '✅' : '❌'} ${ชื่อ}`) }
  console.log(ตก ? `🔴 self-test ตก ${ตก} เคส` : `🧪 self-test ผ่าน ${เคส.length} เคส (รวมตัวควบคุมลบ 1)`)
  process.exit(ตก ? 1 : 0)
}

const { สูตร } = await import('./lib/ทะเบียนด่าน.mjs')
let ชุดดิบ
try { ชุดดิบ = JSON.parse(readFileSync(ไฟล์ชุด, 'utf8')) } catch (e) {
  console.error(`🔴 อ่าน ${ไฟล์ชุด} ไม่ได้: ${e.message}`)
  console.error(`   ⇒ สร้างด้วย: node scripts/สมอตรงฟรีไหม.mjs --ทะเบียน > ${ไฟล์ชุด}`)
  process.exit(1)
}
const ชุด = new Set((ชุดดิบ['ตรงฟรี'] ?? []).map((r) => คีย์ของ(r.ด่าน, r.สมอ)))
const ไม่มีสมอเดิม = new Set((ชุดดิบ['ไม่มีสมอ'] ?? []).map((r) => r.ด่าน))

const คู่ = สูตร.filter((f) => f.ต้องเอ่ยถึง).map((f) => ({
  ด่าน: Array.isArray(f.ด่าน) ? f.ด่าน.join(' ') : `node ${f.ด่าน}`, สมอ: f.ต้องเอ่ยถึง, ไฟล์: f.ไฟล์,
}))
const ไม่มีสมอ = สูตร.filter((f) => !f.ต้องเอ่ยถึง).map((f) =>
  ({ ด่าน: Array.isArray(f.ด่าน) ? f.ด่าน.join(' ') : `node ${f.ด่าน}`, ไฟล์: f.ไฟล์ }))

/* คู่ที่ไม่อยู่ในชุด ⇒ **ยังไม่มีคำตอบ** ⇒ ต้องวัด (รันด่านของมันหนึ่งครั้ง โดยไม่ปลูก) */
const ยังไม่รู้ = คู่.filter((c) => !ชุด.has(คีย์ของ(c.ด่าน, c.สมอ)))
const ด่านที่ต้องรัน = [...new Set(ยังไม่รู้.map((c) => c.ด่าน))]

console.log(`สมอ: ทะเบียน ${คู่.length} คู่ · ในชุดหนี้ ${ชุด.size} · ยังไม่มีคำตอบ ${ยังไม่รู้.length}`
  + ` ⇒ ต้องรันด่าน ${ด่านที่ต้องรัน.length} คำสั่ง`)

const ผลของด่าน = new Map()
for (const ด of ด่านที่ต้องรัน) {
  const ส่วน = ด.split(' ')
  const r = spawnSync(ส่วน[0], ส่วน.slice(1), { encoding: 'utf8' })
  ผลของด่าน.set(ด, { out: (r.stdout || '') + (r.stderr || ''), exit: r.status })
}

const ตรงฟรีตัวใหม่ = [], ด่านแดงอยู่ก่อน = []
for (const c of ยังไม่รู้) {
  const ผ = ผลของด่าน.get(c.ด่าน)
  /* ด่านที่แดงอยู่ก่อนปลูก ⇒ ตีความผลไม่ได้ ⇒ ต้องฟ้องแยก ไม่ใช่เดาว่าสมอดี */
  if (ผ.exit !== 0) { ด่านแดงอยู่ก่อน.push(c); continue }
  if (ผ.out.includes(c.สมอ)) ตรงฟรีตัวใหม่.push(c)
}
/* ชุดที่โกหกว่ายังมีหนี้ — ชื่อที่หายจากทะเบียนสูตรแล้ว */
const ค้างในชุด = [...ชุด].filter((k) => !คู่.some((c) => คีย์ของ(c.ด่าน, c.สมอ) === k))
/* และกองไม่มีสมอ ก็ต้องไม่โตขึ้น */
const ไม่มีสมอตัวใหม่ = ไม่มีสมอ.filter((c) => !ไม่มีสมอเดิม.has(c.ด่าน))

let ตก = 0
if (ตรงฟรีตัวใหม่.length) {
  ตก++
  console.error(`\n🔴 สมอ **ตรงฟรีตัวใหม่** ${ตรงฟรีตัวใหม่.length} ตัว — โผล่ทั้งที่ไม่ได้ปลูก`)
  for (const c of ตรงฟรีตัวใหม่) {
    console.error(`   · ${c.ไฟล์}`)
    console.error(`     ด่าน: ${c.ด่าน}`)
    console.error(`     สมอ : ${JSON.stringify(c.สมอ)}`)
  }
  console.error(`   ⇒ เปลี่ยนสมอเป็น **ข้อความที่ด่านพิมพ์เฉพาะตอนตก** (ไม่ใช่ชื่อข้อของเทส)`)
  console.error(`   🚫 **ห้ามแก้ด้วยการเพิ่มชื่อลง ${ไฟล์ชุด}** — ชุดนั้นคือหนี้ที่วัดไว้แล้ว ไม่ใช่ที่รับของใหม่`)
}
if (ไม่มีสมอตัวใหม่.length) {
  ตก++
  console.error(`\n🔴 สูตรใหม่ที่ **ไม่มีสมอเลย** ${ไม่มีสมอตัวใหม่.length} ตัว`)
  for (const c of ไม่มีสมอตัวใหม่) console.error(`   · ${c.ไฟล์} — ด่าน ${c.ด่าน}`)
}
if (ค้างในชุด.length) {
  ตก++
  console.error(`\n🔴 ชุดหนี้มีชื่อที่ไม่มีในทะเบียนสูตรแล้ว ${ค้างในชุด.length} รายการ`)
  for (const k of ค้างในชุด) console.error(`   · ${k}`)
  console.error(`   ⇒ ลบออกจาก ${ไฟล์ชุด} — **ทะเบียนที่โกหกว่ายังมีหนี้ แย่กว่าไม่มีทะเบียน**`)
}
if (ด่านแดงอยู่ก่อน.length) {
  console.log(`\n🟠 ${ด่านแดงอยู่ก่อน.length} คู่ตัดสินไม่ได้ เพราะด่านของมันแดงอยู่ก่อนแล้ว`)
  for (const c of ด่านแดงอยู่ก่อน) console.log(`   · ${c.ด่าน} (${c.ไฟล์})`)
  console.log(`   ⇒ ไม่นับเป็นผ่านและไม่นับเป็นตก — แก้ด่านนั้นก่อนแล้วรันซ้ำ`)
}
if (ตก) process.exit(1)
console.log(`✅ ไม่มีสมอตรงฟรีตัวใหม่ · ชุดหนี้ ${ชุด.size} รายการไม่โตขึ้นและไม่มีชื่อค้าง`)
console.log(`   ⚠️ ขอบเขต: จับ **คู่ที่ยังไม่เคยตอบ** เท่านั้น`)
console.log(`      ถ้าข้อความในด่านถูกแก้จนสมอเก่ากลายเป็นตรงฟรี **ด่านนี้มองไม่เห็น**`)
console.log(`      ⇒ ตัวที่ตอบข้อนั้นคือ \`node scripts/สมอตรงฟรีไหม.mjs\` ที่ต้องรันเป็นรอบ`)
