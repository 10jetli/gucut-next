#!/usr/bin/env node
/* ยิงรับของจากท่อตาม **เกณฑ์ที่ตกลงกันไว้ล่วงหน้า** — ไม่ใช่ดูแล้วค่อยตัดสินว่าพอใจไหม
 *
 * 🔴 **ที่มา 19 ก.ย. 2569** — ฝั่งท่อแก้สามเรื่องที่ฝั่งจอรออยู่ แต่ยังไม่ deploy
 *    เราตกลง **เกณฑ์รับของ** กันไว้ก่อน แล้วค่อยยิงเมื่อขึ้น
 *    🔑 เขียนเกณฑ์ก่อนเห็นผล = กันตัวเองไม่ให้ "ปรับเกณฑ์ให้เข้ากับผลที่ได้"
 *       (ซึ่งเป็นสิ่งที่เกิดเองโดยไม่รู้ตัวเมื่ออ่านผลก่อนตั้งเกณฑ์)
 *
 * ⚠️ **ข้อที่ต้องระวังตอนอ่านผล** (ฝั่งท่อกำชับมาก่อนยิง):
 *    · `byStatus` **เท่ากันทุกคำขอ = ถูกต้องแล้ว** เพราะมันคือ "ทั้งร้าน" (ใช้ทำรายชื่อแท็บ)
 *    · ตัวที่ต้อง **ต่างเมื่อ total ต่าง** คือ `byStatusFiltered` (ใช้ทำตัวนับบนแท็บ)
 *    ⇒ เทียบผิดตัวจะสรุปว่าฝั่งท่อทำไม่ครบ ทั้งที่ทำถูก
 *    · `statusesAll` **ไม่มีในเส้นใบคืน และตั้งใจไม่ทำ** (byStatus ทำหน้าที่นั้นอยู่แล้ว
 *      ⇒ เพิ่มชื่อซ้ำ = สองชื่อหนึ่งความหมาย ซึ่งเป็นคลาสที่เราเพิ่งเจอ)
 *
 * ## 📊 ระดับหลักฐานฝั่งท่อ **ก่อน** deploy (ฝั่งท่อบอกมาเอง 19 ก.ย. 2569 · สำคัญตอนอ่านผล)
 *    · 5 ข้อ — ยืนยันด้วยการ **รันฟังก์ชันจริงแล้วอ่านคีย์ในคำตอบ** ⇒ หลักฐานแข็ง
 *    · 1 ข้อ (`list=stock` มี `applied`) — ยืนยันด้วยการ **อ่านโครงสร้างโค้ด** เท่านั้น
 *      (mock ไม่สำเร็จ: เส้นนั้นมี CTE หลายชั้น + ต้องมีภาพถ่ายสต็อกสองวัน ⇒ ตกทาง skip)
 *      ⚠️ **ข้อนี้อ่อนกว่าอีก 5 ข้อ** ⇒ ถ้ามันแดงข้อเดียว **อย่าเพิ่งสรุปว่าฝั่งท่อทำไม่ครบ**
 *         ให้แจ้งฝั่งท่อทันที (เขาขอไว้เอง) — อาจเป็นทาง skip ไม่ใช่ทางหลัก
 * 🔑 จดระดับหลักฐานไว้ **ก่อน**ยิง เพราะหลังเห็นผลแดงแล้ว คนจะตีความไปทาง "อีกฝั่งทำไม่ครบ" เสมอ
 *
 * วิธีใช้: node scripts/รับของท่อ.mjs      (อ่านคีย์จาก .env.local เหมือน ดึงสารบัญท่อ.mjs)
 * 🚫 ไม่อยู่ใน prebuild — ยิงเน็ต และใช้ครั้งเดียวตอนรับของ
 */
import { readFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const key = process.env.GUCUT_WEB_ADMIN_KEY
  || (existsSync(join(ROOT, ".env.local"))
    ? (readFileSync(join(ROOT, ".env.local"), "utf8").match(/^GUCUT_WEB_ADMIN_KEY=(.*)$/m)?.[1] ?? "").trim().replace(/^["']|["']$/g, "")
    : "");
if (!key) { console.error("🛑 ไม่มี GUCUT_WEB_ADMIN_KEY"); process.exit(1); }

const ยิง = async (qs) => {
  const r = await fetch(`https://gucut.com/api/core?${qs}`, { headers: { "x-admin-key": key } });
  const j = await r.json().catch(() => null);
  return { ok: r.ok, build: r.headers.get("x-core-build"), j };
};

let ตก = 0;
const บอก = (ผ่าน, ข้อความ) => { if (!ผ่าน) ตก += 1; console.log(`${ผ่าน ? "✅" : "🔴"} ${ข้อความ}`); };

/* ⚠️ **สถานะที่สามต้องถูกนับ ไม่ใช่แค่พิมพ์แล้วผ่านไป**
   เดิมข้อที่ตัดสินไม่ได้ `console.log` เฉย ๆ ⇒ สรุปท้ายเห็นแต่ `ตก` ⇒ ขึ้น "✅ ผ่านทุกข้อที่ตัดสินได้"
   เท่ากันหมดไม่ว่าจะตัดสินได้ 6 ข้อหรือ 0 ข้อ · บรรทัด ⚠️ เลื่อนพ้นจอไปเมื่อไหร่ก็หายไปเลย
   🔑 กติกาเดียวกับ `scripts/lib/รอจนจอพร้อม.py`: **จำนวนข้อที่ตัดสินไม่ได้วัดคุณภาพของ "เครื่องมือ"**
      ⇒ ต้องโผล่ในบรรทัดสรุป ไม่งั้นเครื่องมือที่ตัดสินไม่ได้สักข้อจะดูเหมือนเครื่องมือที่ผ่านหมด */
let ไม่รู้ = 0;
const ตัดสินไม่ได้ = (ข้อความ) => { ไม่รู้ += 1; console.log(`⚠️ ${ข้อความ} · **ไม่ใช่ว่าผ่าน**`); };

const หัว = await ยิง("list=orders&limit=1");
console.log(`รุ่นท่อที่ตอบตอนนี้: ${หัว.build}\n`);

/* ── ① `applied.q` ใน list=orders และ list=stock ── */
for (const เส้น of ["orders", "stock"]) {
  const { j } = await ยิง(`list=${เส้น}&limit=1&q=zzzzไม่มีคำนี้`);
  const มี = j && typeof j === "object" && "applied" in j;
  /* ⚠️ `stock` เป็นข้อที่หลักฐานก่อน deploy อ่อนกว่าเพื่อน — ติดป้ายไว้ในผลเลย ไม่ให้คนอ่านเดาเอง */
  const ป้าย = เส้น === "stock" ? " [หลักฐานก่อน deploy: อ่านโค้ด ไม่ได้รันจริง]" : "";
  บอก(มี, `① ${เส้น}: มีคีย์ \`applied\`${ป้าย} ${มี ? `· q=${JSON.stringify(j.applied?.q)}` : "— ยังไม่มี (ท่อยังไม่ deploy หรือชื่อไม่ตรง)"}`);
  /* 🔑 มีคีย์อย่างเดียวไม่พอ — ต้องสะท้อนคำที่เราส่งไปจริง ไม่งั้นจอจะเขียนกำกับผิดคำ */
  if (มี) บอก(j.applied?.q === "zzzzไม่มีคำนี้", `①.1 ${เส้น}: \`applied.q\` สะท้อนคำที่ส่งไปตรงตัว`);
}

/* ── ② ?dupsku=1 ── */
{
  const { j } = await ยิง("dupsku=1");
  const เป็นเส้นจริง = j && j.fallthrough !== true;
  บอก(เป็นเส้นจริง, `② dupsku: เส้นมีจริง (ไม่ใช่คำตอบหน้าแรก)`);
  if (เป็นเส้นจริง) {
    const ช่อง = "ที่มีคู่ยาวกว่าขึ้นต้นเหมือนกัน";
    บอก(ช่อง in j, `②.1 dupsku: มีช่อง "${ช่อง}" ${ช่อง in j ? `= ${j[ช่อง]}` : "— ชื่อช่องไม่ตรงกับที่จออ่าน"}`);
  }
}

/* ── ③ mirrorTotals / byStatus / byStatusFiltered ของเส้นใบคืน ── */
{
  const เปล่า = await ยิง("list=returnorders&limit=5");
  /* 🔴 **คำค้นต้องแมตช์ "บางใบ" ไม่ใช่ "ทุกใบ"** — เดิมใช้ `q=CN` ซึ่งแมตช์ **693/693**
     ⇒ รวม Filtered = รวม byStatus = total ทั้งสามเลข **ไม่ว่าท่อจะกรองหรือไม่กรอง**
     ⇒ เคสนั้น **ผ่านเสมอโดยไม่ได้ทดสอบอะไร** (ฝั่งท่อยิงตารางเทียบ 4 คำค้นแล้วชี้ให้)
     🔑 กฎ `test-must-discriminate`: ถามว่า **"ถ้าของจริงตรงข้าม ผลจะเปลี่ยนไหม"**
        `q=CN` ตอบว่า *ไม่เปลี่ยน* ⇒ ไม่ใช่การทดสอบ · `q=CN-1` ⇒ 296/693 ⇒ เปลี่ยน ⇒ ใช้ได้ */
  const ค้น = await ยิง("list=returnorders&limit=5&q=CN-1");
  const ช่วง = await ยิง("list=returnorders&limit=5&from=2026-09-01&to=2026-09-19");
  for (const [ชื่อ, ผล] of [["ไม่กรอง", เปล่า], ["q=CN-1", ค้น], ["ช่วงวัน", ช่วง]]) {
    const mt = ผล.j?.mirrorTotals;
    บอก(!!mt, `③ ${ชื่อ}: มี \`mirrorTotals\``);
    if (mt) บอก("byStatus" in mt, `③.1 ${ชื่อ}: มี \`byStatus\` (ทั้งร้าน — เท่ากันทุกคำขอ = ถูกต้อง)`);
  }
  /* ④.0 ทางที่ถาม ZORT สด (source = zort) ⇒ `byStatusFiltered` ต้องเป็น **null พร้อม note**
     🔑 null ที่นี่แปลว่า **"ทางนี้กรองไม่ได้"** ไม่ใช่ "กรองแล้วไม่มีของ"
        ⇒ ถ้าท่อส่ง [] หรือ 0 มาแทน จอจะอ่านว่า "ไม่มีใบยกเลิกเลย" ซึ่งผิดคนละเรื่อง */
  {
    const src = เปล่า.j?.applied?.source;
    const bf = เปล่า.j?.mirrorTotals?.byStatusFiltered;
    if (src === "zort") {
      บอก(bf === null, `④.0 ไม่กรอง (source=zort): \`byStatusFiltered\` เป็น null ${bf === null ? "" : `— ได้ ${JSON.stringify(bf)}`}`);
      บอก(!!เปล่า.j?.mirrorTotals?.byStatusFilteredNote, "④.0.1 มี `byStatusFilteredNote` บอกเหตุที่กรองไม่ได้");
    } else {
      console.log(`⚠️ ④.0 ตัดสินไม่ได้ — คำขอไม่กรองได้ source=${JSON.stringify(src)} (คาดว่า zort) · **ไม่ใช่ว่าผ่าน**`);
    }
  }

  /* ④ **ผลรวมของ `byStatusFiltered` ต้องเท่ากับ `total` ของคำขอนั้น**
     🔴 เกณฑ์แรกที่ผมเขียน ("ต้องต่างจาก byStatus เมื่อ total ต่าง") **เทียบผิดคู่**
        — ผมเอาคำขอ *ไม่กรอง* (byStatusFiltered = null ตามสัญญา) ไปเทียบ ⇒ ตัดสินไม่ได้ตลอดกาล
     🔴 และมันยังตัดสินผิดได้ด้วย: `q=CN` แมตช์ **ทุกใบ** ⇒ byStatusFiltered เท่ากับ byStatus พอดี
        ตามเกณฑ์เดิมจะอ่านว่า "ไม่ได้กรอง" ทั้งที่กรองแล้วได้ทุกใบจริง ๆ
     ✅ เกณฑ์ที่ถูกคือ **ตัวนับต้องรวมได้เท่ากับจำนวนแถวทั้งชุดของคำขอนั้น**
        = กติกาเดียวกับที่เราใช้กับแท็บทุกจอ: **ตัวนับกับตัวแถวต้องมาจากกติกาเดียวกัน** */
  for (const [ชื่อ, ผล] of [["q=CN-1", ค้น], ["ช่วงวัน", ช่วง]]) {
    const src = ผล.j?.applied?.source;
    const bf = ผล.j?.mirrorTotals?.byStatusFiltered;
    if (src !== "mirror") { ตัดสินไม่ได้(`④ ${ชื่อ}: source=${JSON.stringify(src)} (คาด mirror) ⇒ ตัดสินไม่ได้`); continue; }
    if (!Array.isArray(bf)) { บอก(false, `④ ${ชื่อ}: \`byStatusFiltered\` ไม่ใช่รายการ (ได้ ${JSON.stringify(bf)})`); continue; }
    /* ⚠️ **ด่านกันเคสที่ผ่านโดยไม่ได้ทดสอบ** — ถ้าคำค้นแมตช์ทุกใบในร้าน เลขจะเท่ากันหมด
       ไม่ว่าท่อจะกรองหรือไม่ ⇒ ต้องรายงานว่า "ตัดสินไม่ได้" ไม่ใช่ "ผ่าน"
       (ถ้าไม่มีด่านนี้ วันหนึ่งข้อมูลเปลี่ยนจนคำค้นแมตช์ทุกใบ แล้วสคริปต์จะเขียวลวงเงียบ ๆ) */
    const ทั้งร้าน = (ผล.j?.mirrorTotals?.byStatus ?? []).reduce((a, r) => a + Number(r?.c ?? 0), 0);
    if (ทั้งร้าน && ผล.j?.total === ทั้งร้าน) {
      ตัดสินไม่ได้(`④ ${ชื่อ}: **ตัดสินไม่ได้ — คำค้นนี้แมตช์ทุกใบในร้าน (${ทั้งร้าน})** ⇒ เลขเท่ากันไม่ว่าท่อจะกรองหรือไม่`);
      continue;
    }
    const รวม = bf.reduce((a, r) => a + Number(r?.c ?? 0), 0);
    บอก(รวม === ผล.j?.total, `④ ${ชื่อ}: ผลรวม byStatusFiltered (${รวม}) = total (${ผล.j?.total})`);
  }
}

const หาง = ไม่รู้ ? ` · ⚠️ **ตัดสินไม่ได้ ${ไม่รู้} ข้อ** (ไม่นับเป็นผ่าน — ดูบรรทัด ⚠️ ข้างบน)` : "";
console.log(ตก ? `\n🛑 ไม่ผ่าน ${ตก} ข้อ${หาง}` : `\n✅ ผ่านทุกข้อที่ตัดสินได้${หาง}`);
process.exit(ตก ? 1 : 0);
