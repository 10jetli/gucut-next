#!/bin/bash
# ติดตั้งด่านก่อน push ฝั่งจอ — รัน: bash scripts/install-pre-push.sh
#
# 🔴 **ทำไมต้องมีไฟล์นี้** (19 ก.ย. 2569 · ฝั่งท่อเจอก่อนแล้วบอกมา)
#    ด่านก่อน push อยู่ใน `.git/hooks/` ซึ่ง **git ไม่เก็บ**
#    ⇒ clone ใหม่ · เครื่องใหม่ · บัญชีใหม่ = **ไม่มีด่านเลย และไม่มีอะไรบอกว่ามันหายไป**
#    ⇒ คนที่ clone จะ push ได้อิสระโดยเชื่อว่ามีด่านคุมอยู่ — เงียบสนิท
#    🔑 คลาสเดียวกับที่ทีมไล่ปิดกันทั้งวัน: **"ไม่มี" กับ "ไม่ได้ดู" หน้าตาเหมือนกัน**
#
# 📌 ของเดิมอ้างชื่อไฟล์นี้ไว้ในหัว hook อยู่แล้ว **แต่ไฟล์ไม่เคยมีอยู่จริง**
#    (ฝั่งท่อเจออาการเดียวกันเป๊ะ) ⇒ คำอ้างอิงที่ชี้ไปหาของที่ไม่มี ก็เป็นคำเท็จแบบหนึ่ง
#
# ⚠️ ชื่อตัวแปรใน bash ต้องเป็น ASCII — ภาษาไทยใช้ไม่ได้ (ต่างจาก JS/TS ในรีโปนี้)
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

SRC="scripts/hooks/pre-push"
DST=".git/hooks/pre-push"

[ -f "$SRC" ] || { echo "🛑 ไม่มี $SRC — ติดตั้งไม่ได้"; exit 1; }

if [ -f "$DST" ] && ! cmp -s "$SRC" "$DST"; then
  echo "⚠️  มี $DST อยู่แล้วและ **เนื้อไม่ตรงกับในรีโป**"
  echo "   สำรองไว้ที่ $DST.bak ก่อนทับ — ถ้าของเดิมมีอะไรที่รีโปไม่มี ให้เอากลับมารวมเอง"
  cp "$DST" "$DST.bak"
fi

install -m 755 "$SRC" "$DST"
echo "✅ ติดตั้งด่านก่อน push แล้ว: $DST"
echo "   ตรวจว่าตรงกับในรีโป: cmp $SRC $DST && echo ตรงกัน"
echo "   ⚠️ ด่านนี้ไม่ได้อยู่ใน prebuild ⇒ **build ผ่านไม่ได้แปลว่าด่านติดตั้งอยู่**"
