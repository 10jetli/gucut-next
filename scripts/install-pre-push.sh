#!/bin/bash
# ติดตั้งด่านก่อน push ฝั่งจอ — รัน: bash scripts/install-pre-push.sh
#
# 🔴 **ทำไมต้องมีไฟล์นี้** (19 ก.ย. 2569 · ฝั่งท่อเจอก่อนแล้วบอกมา)
#    ด่านก่อน push อยู่ใน `.git/hooks/` ซึ่ง **git ไม่เก็บ**
#    ⇒ clone ใหม่ · เครื่องใหม่ · บัญชีใหม่ = **ไม่มีด่านเลย และไม่มีอะไรบอกว่ามันหายไป**
#    ⇒ คนที่ clone จะ push ได้อิสระโดยเชื่อว่ามีด่านคุมอยู่ — เงียบสนิท
#    🔑 คลาสเดียวกับที่ทีมไล่ปิดกันทั้งวัน: **"ไม่มี" กับ "ไม่ได้ดู" หน้าตาเหมือนกัน**
#
# 📌 ของเดิมอ้างชื่อไฟล์นี้ไว้ในหัว hook อยู่แล้ว **แต่ไฟล์ไม่เคยมีอยู่จริง**
#    (ฝั่งท่อเจออาการเดียวกันเป๊ะ) ⇒ คำอ้างอิงที่ชี้ไปหาของที่ไม่มี ก็เป็นคำเท็จแบบหนึ่ง
#
# ⚠️ ชื่อตัวแปรใน bash ต้องเป็น ASCII — ภาษาไทยใช้ไม่ได้ (ต่างจาก JS/TS ในรีโปนี้)
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

# 🔴 **ของเดิมติดตั้งแค่ `pre-push` — `pre-commit` ไม่เคยถูกติดตั้งเลย** (เจอ 14 ต.ค. 2569)
#    ⇒ ผมแก้ `scripts/hooks/pre-commit` ไปหลายรอบวันนี้ **แต่ของที่รันจริงเป็นสำเนาเก่า**
#    ⇒ ⇒ และ `check-hook-installed` เทียบแต่ `pre-push` ⇒ **ไม่มีอะไรฟ้องว่าอีกตัวค้าง**
#    🔑 คลาสเดียวกับที่ไฟล์นี้เกิดมาปิด (ด่านอยู่ใน .git ซึ่ง git ไม่เก็บ) —
#       แค่รอบนี้ของที่หายไปคือ **ฮุคตัวที่สอง** ไม่ใช่ทั้งโฟลเดอร์
HOOKS="pre-push pre-commit"
for H in $HOOKS; do
SRC="scripts/hooks/$H"
DST=".git/hooks/$H"

[ -f "$SRC" ] || { echo "🛑 ไม่มี $SRC — ติดตั้งไม่ได้"; exit 1; }

if [ -f "$DST" ] && ! cmp -s "$SRC" "$DST"; then
  echo "⚠️  มี $DST อยู่แล้วและ **เนื้อไม่ตรงกับในรีโป**"
  echo "   สำรองไว้ที่ $DST.bak ก่อนทับ — ถ้าของเดิมมีอะไรที่รีโปไม่มี ให้เอากลับมารวมเอง"
  cp "$DST" "$DST.bak"
fi

# 🔴 **ต้องเขียนไฟล์ใหม่แล้ว `mv` ทับ ห้ามเขียนทับที่เดิม** (12 ต.ค. 2569 · เจอของจริง)
#    `cp`/`install` เขียนทับ **inode เดิม** ⇒ ถ้ามี `git push` วิ่งอยู่ bash จะอ่านสคริปต์ต่อ
#    จากไฟล์ที่เนื้อเปลี่ยนไปแล้ว ณ ตำแหน่งเดิม ⇒ ได้โค้ดครึ่งเก่าครึ่งใหม่ **ที่ไม่เคยมีอยู่จริง**
#    ⇒ ของจริง: ด่านตกด้วย `syntax error` ทั้งที่ `bash -n` ผ่านทั้งก่อนและหลัง
#       🔑 และข้อความนั้น **ไม่ชี้ไปที่เหตุเลย** ⇒ คนจะไปไล่หา syntax error ในไฟล์ที่ไม่มี
#    ⇒ `mv` บนไฟล์ระบบเดียวกันเป็น **rename ที่เปลี่ยนชื่อทีเดียวจบ** ⇒ โปรเซสที่กำลังรัน
#       ยังถือไฟล์เดิมไว้จนจบ · รอบถัดไปค่อยได้ของใหม่ ⇒ ไม่มีช่วงครึ่ง ๆ กลาง ๆ
#    ⚠️ กฎ "อย่าติดตั้งตอนมี push วิ่ง" กันเจตนา · `mv` กันอุบัติเหตุ — ต้องมีทั้งคู่
#    ⚠️ ไฟล์ชั่วคราวต้องอยู่ **โฟลเดอร์เดียวกับปลายทาง** — `mv` ข้ามพาร์ติชันไม่ atomic
#       (กลายเป็น copy+unlink) ⇒ จะได้ `mv` ที่ดูปลอดภัยแต่ไม่ปลอดภัย
#       ซึ่ง **แย่กว่า `cp` ที่เรารู้อยู่แล้วว่าไม่ปลอดภัย**
_tmp="$(dirname "$DST")/.$H.tmp.$$"
install -m 755 "$SRC" "$_tmp"
mv -f "$_tmp" "$DST"
echo "✅ ติดตั้งแล้ว: $DST"
done
echo "   ตรวจว่าตรงกับในรีโป: for h in $HOOKS; do cmp scripts/hooks/\$h .git/hooks/\$h; done"
echo "   ⚠️ ด่านพวกนี้ไม่ได้อยู่ใน prebuild ⇒ **build ผ่านไม่ได้แปลว่าด่านติดตั้งอยู่**"
