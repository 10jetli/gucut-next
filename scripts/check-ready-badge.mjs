#!/usr/bin/env node
/* ด่านก่อน build: จอที่ "ส่งของจริงออกนอกระบบได้" ต้องมีป้ายที่ตั้งใจ ไม่ใช่ป้ายที่ตกทอดมาโดยบังเอิญ
 *
 * 🔴 **ที่มา 18 ก.ย. 2569 (งาน S4/S3)** — เปิดจอจริงบน production แล้วพบว่า
 *    จอที่ `REAL_SEND_ENABLED = true` เหมือนกันทั้งสี่จอ **ติดป้ายคนละแบบ**:
 *      /core/quotations/new · /core/stock/new · /core/purchases/new ⇒ 🟡 "งานเขียนยังทำที่ ZORT"
 *      /core/sales/new                                              ⇒ 🟢 "ความสามารถ: ใช้แทน ZORT ได้เลย"
 *    สาเหตุ: `/core/sales/new` **ไม่มีในทะเบียน** ⇒ `zortReadyOf()` ตัดท้ายไปเจอ `/core/sales`
 *    ซึ่งเป็นจอ "ดูรายการ" (replace) ⇒ จอที่เขียนเอกสารจริงได้ป้ายของจอที่อ่านอย่างเดียว
 *
 * 🔑 **ด่านนี้ไม่ตัดสินว่าป้ายไหนถูก** — นั่นเป็นนโยบายที่ CEO เป็นเจ้าของ
 *    มันบังคับแค่ว่า **ต้องมีคนเลือกป้ายให้จอที่เขียนของจริง** ไม่ใช่ปล่อยให้ตกทอดมาเงียบ ๆ
 *    (ป้ายที่ตกทอดมาโดยบังเอิญ = ไม่มีใครเคยตัดสินใจ แต่ทุกคนอ่านเหมือนมีคนตัดสินแล้ว)
 *
 * 🔴🔴 **ด่านนี้เคยเขียวตลอดกาลอยู่ครึ่งวัน (19 ก.ย. 2569 · ใบ S2)**
 *    ของเดิมหาจอด้วยการ grep `const REAL_SEND_ENABLED = true` ในทุก `page.tsx`
 *    เช้าวันเดียวกันนั้นเราย้ายสถานะไปไว้ที่ทะเบียนเดียว `lib/real-send.ts`
 *    (จอเรียก `ส่งจริงได้('<คีย์>')`) และ `check-real-send-registry.mjs` ก็ **แบนคำนั้น** ด้วย
 *    ⇒ ด่านนี้จึงหาไม่เจอสักจอ แล้วพิมพ์ `ตรวจ 0 จอ ✅` **ผ่านทุกรอบโดยไม่ได้ดูอะไรเลย**
 *    ⇒ ไม่มีอะไรฟ้อง เพราะ "ไม่เจอของผิด" กับ "ไม่ได้มอง" หน้าตาเหมือนกันทุกประการ
 *    🔑 กฎที่ได้: **ด่านที่หาของด้วยรูปคำในซอร์ส จะตายเงียบวันที่รูปคำนั้นเปลี่ยน**
 *       ⇒ ให้หาจาก **ทะเบียน** ที่เป็นแหล่งความจริงเดียว ไม่ใช่จากรูปคำ
 *       ⇒ และต้อง **ยืนยันว่ามีของให้ตรวจ** ทุกรอบ (0 จอที่เปิดส่งจริง = ทะเบียนพัง ไม่ใช่ปลอดภัย)
 *
 * 🧪 พิสูจน์ว่าด่านร้องได้จริง: `node scripts/check-ready-badge.mjs --self-test`
 */
import { readFileSync, readdirSync, statSync } from 'node:fs'
import { join } from 'node:path'
import { ต้องมีของให้ตรวจ } from './lib/ต้องมีของให้ตรวจ.mjs'
import { ตัดคอมเมนต์ } from './lib/ตัดคอมเมนต์.mjs'

const ROOT = new URL('..', import.meta.url).pathname.replace(/\/$/, '')
function walk(d, out = []) {
  let names
  try { names = readdirSync(d) } catch { return out }
  for (const n of names) {
    const p = join(d, n)
    if (statSync(p).isDirectory()) { if (n !== 'node_modules' && n !== '.next') walk(p, out) }
    else if (n === 'page.tsx') out.push(p)
  }
  return out
}

const หน้า = walk(join(ROOT, 'app'))
ต้องมีของให้ตรวจ(หน้า.length, 'check-ready-badge')

let ทะเบียน = ''
/* 🔴 ตัดคอมเมนต์ก่อน (19 ก.ย. 2569 · งาน S2) — ทั้งสองทะเบียนนี้ถูกอ่านแบบ "มีข้อความนี้ไหม"
   ⇒ บรรทัดทะเบียนที่ถูกคอมเมนต์ทิ้ง (`// '/core/sales/new': {…}`) ยังทำให้ด่านผ่าน
   = กลับไปสู่บั๊กเดิมเป๊ะ ๆ ที่ด่านนี้เกิดมาแก้ (ป้ายตกทอดจากเส้นทางแม่) */
try { ทะเบียน = ตัดคอมเมนต์(readFileSync(join(ROOT, 'lib/zort-ready.ts'), 'utf8')) } catch { /* ไม่มีไฟล์ */ }
/* 🔒 อ่านทะเบียนไม่ได้ = ตรวจอะไรไม่ได้ (เหตุผลเดียวกับ ต้องมีของให้ตรวจ) */
if (!ทะเบียน.includes('ZORT_READY')) {
  console.error('🔴 อ่าน lib/zort-ready.ts ไม่ได้ หรือไม่มี ZORT_READY — ด่านนี้ตรวจอะไรไม่ได้ ถือว่าไม่ผ่าน')
  process.exit(1)
}

/* 🔑 **หาจากทะเบียน ไม่ใช่จากรูปคำในซอร์ส** — ดูเหตุผลที่หัวไฟล์
   `ปุ่มส่งจริง` ใน lib/real-send.ts เป็นแหล่งความจริงเดียวของสถานะเปิด-ปิด */
let ทะเบียนส่งจริง = ''
try { ทะเบียนส่งจริง = ตัดคอมเมนต์(readFileSync(join(ROOT, 'lib/real-send.ts'), 'utf8')) } catch { /* ไม่มีไฟล์ */ }
if (!ทะเบียนส่งจริง.includes('ปุ่มส่งจริง')) {
  console.error('🔴 อ่าน lib/real-send.ts ไม่ได้ หรือไม่มี `ปุ่มส่งจริง` — ด่านนี้ตรวจอะไรไม่ได้ ถือว่าไม่ผ่าน')
  process.exit(1)
}

/** คีย์ของจอที่ `เปิด: true` อยู่ตอนนี้ (คีย์ในทะเบียนตัดคำนำหน้า /core/ ไว้แล้ว) */
function จอที่เปิดอยู่(src) {
  const out = []
  /* จับทั้งรูปหลายบรรทัดและรูปบรรทัดเดียว — หยุดที่ `}` ตัวแรกเพื่อไม่ให้ค่าของคีย์ถัดไปไหลมาปน */
  for (const m of src.matchAll(/^\s*'([^']+)':\s*\{([^}]*)\}/gms)) {
    if (/เปิด:\s*true\b/.test(m[2])) out.push(m[1])
  }
  return out
}

function ตรวจ(เปิดอยู่, ป้าย) {
  const ขาด = []
  for (const คีย์ of เปิดอยู่) {
    const path = `/core/${คีย์}`
    /* ต้องมีบรรทัดของตัวเองในทะเบียนป้าย — ตกทอดจากเส้นทางแม่ไม่นับ */
    if (!new RegExp(`'${path.replace(/[/]/g, '\\/').replace(/[[\]]/g, '\\$&')}'\\s*:`).test(ป้าย)) ขาด.push(path)
  }
  return ขาด
}

if (process.argv.includes('--self-test')) {
  /* ปลูกจอที่เปิดส่งจริงแต่ไม่มีบรรทัดป้ายของตัวเอง + ยืนยันว่าของจริงยังไม่ถูกฟ้อง */
  const จริง = ตรวจ(จอที่เปิดอยู่(ทะเบียนส่งจริง), ทะเบียน)
  const ปลูก = ตรวจ(['จอปลอมที่ไม่มีป้าย'], ทะเบียน)
  const เห็นของจริง = จอที่เปิดอยู่(ทะเบียนส่งจริง).length > 0
  const ผ่าน = ปลูก.length === 1 && จริง.length === 0 && เห็นของจริง
  console.log(ผ่าน
    ? `🧪 self-test ผ่าน — จับจอที่ไม่มีป้ายของตัวเองได้ · ไม่ฟ้องของจริง · และเห็นจอที่เปิดอยู่ ${จอที่เปิดอยู่(ทะเบียนส่งจริง).length} จอ (ไม่ใช่ 0)`
    : `🛑 self-test ตก — ปลูก=${JSON.stringify(ปลูก)} จริง=${JSON.stringify(จริง)} เห็นของจริง=${เห็นของจริง}`)
  process.exit(ผ่าน ? 0 : 1)
}

const เปิดอยู่ = จอที่เปิดอยู่(ทะเบียนส่งจริง)
/* 🔴 **0 จอที่เปิดส่งจริง = ทะเบียนพังหรือตัวอ่านพัง ไม่ใช่ "ปลอดภัย"**
   นี่คือกับดักที่ด่านนี้เคยตกมาแล้วเมื่อ 19 ก.ย. 2569 (ดูหัวไฟล์) */
ต้องมีของให้ตรวจ(เปิดอยู่.length, 'check-ready-badge · จอที่เปิดส่งจริง')
const ขาด = ตรวจ(เปิดอยู่, ทะเบียน)
const เขียนได้ = เปิดอยู่.length

console.log(`ตรวจป้ายจอที่เปิดส่งจริงอยู่: ${เขียนได้} จอ (จากทะเบียน lib/real-send.ts) · ไม่มีบรรทัดของตัวเองในทะเบียนป้าย ${ขาด.length} จอ`)
if (ขาด.length) {
  console.error('\n🔴 จอที่เขียนของจริงออกนอกระบบได้ แต่ **ป้ายตกทอดมาจากเส้นทางแม่**')
  for (const p of ขาด) console.error(`   ${p}`)
  console.error('\n   ⇒ คนอ่านป้ายจะเชื่อว่ามีคนตัดสินใจให้จอนี้แล้ว ทั้งที่ไม่มีใครเคยเลือก')
  console.error('   วิธีแก้: เพิ่มบรรทัดของเส้นทางนั้นเองใน lib/zort-ready.ts พร้อมเหตุผลสั้น ๆ')
  process.exit(1)
}
console.log('✅ ทุกจอที่ส่งของจริงได้ มีป้ายที่ถูกเลือกไว้เอง ไม่ได้ตกทอดมา')
