#!/usr/bin/env node
/* ด่านก่อน build: **ทุกเส้นใน `PUBLIC_PATHS` ต้องมีการตรวจกุญแจของตัวเอง**
 *
 * 🔴 ที่มา (19 ก.ย. 2569 · ใบ S5) — เอกสารเขียนว่าเว็บเปิด 3 เส้น ของจริง **12 เส้น**
 *    ทุกเส้นมีกุญแจของตัวเองอยู่แล้ว ⇒ **โค้ดไม่ได้ผิด** แต่ไม่มีอะไรกันวันที่มีคนเพิ่มเส้นที่ 13
 *    และ `middleware.ts` เขียนเตือนเองว่าเคยลืมเพิ่ม `/api/bills/dupcheck` มาก่อน
 *    ⇒ ตอนนั้นอาการคือ "คนมี secret ยิงแล้วได้ 401" = ลืมเพิ่มเข้า PUBLIC_PATHS
 *    ⇒ ด่านนี้กันทิศตรงข้าม: **เพิ่มเข้า PUBLIC_PATHS แล้วลืมตรวจกุญแจ** = เปิดโล่ง
 *
 * 🔑 **ทำไมตรวจ "เงื่อนไข" ไม่ใช่ "จำนวน"** (ฝั่งท่อเสนอ 19 ก.ย. 2569)
 *    เขียนจำนวนลงเอกสารแล้ววันหน้าเพิ่มเส้นที่ 13 เอกสารก็ล้าสมัยอีก
 *    = คลาสเดียวกับ "คำบอกรอบเวลา" ที่ทีมไล่แก้ 3 ตัวในวันเดียว
 *    ⇒ จำนวนเปลี่ยนได้โดยไม่มีใครผิด · **เส้นที่ไม่มีกุญแจต่างหากที่พังจริง**
 *
 * 📏 **วัดก่อนเขียน** (กฎที่ทีมตกลงกัน หลังเคยทำด่านที่ร้อง 55 จุดแล้วเกือบต้องทิ้ง)
 *    ยิงกับของจริงก่อนลงมือ: ฟ้อง **1 จาก 12** และตัวนั้นคือ `/login`
 *    ซึ่งเปิดโดยถูกต้อง (หน้าล็อกอินต้องเข้าได้โดยไม่มีกุญแจ — นั่นคือหน้าที่ของมัน)
 *    ⇒ ยกเว้นตัวเดียวพร้อมเหตุผล ⇒ **เสียงรบกวนเหลือ 0** ⇒ คุ้มที่จะเป็นด่าน
 *
 * ⚠️ **ด่านนี้ไม่ได้พิสูจน์ว่าการตรวจกุญแจนั้นถูกต้อง** — ตรวจได้แค่ว่า "มีการตรวจอยู่"
 *    ของที่มันกันคือ **เส้นที่ไม่มีการตรวจเลย** ซึ่งเป็นคนละคำถามกับ "ตรวจแล้วแน่นพอไหม"
 *    ⇒ เขียนไว้ตรง ๆ ไม่งั้นด่านเขียวจะถูกอ่านว่า "เส้นสาธารณะปลอดภัยแล้ว"
 *
 * 🧪 พิสูจน์ว่าด่านร้องได้จริง: `node scripts/check-public-paths-have-keys.mjs --self-test`
 */
import { readFileSync, existsSync, readdirSync, statSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = new URL('..', import.meta.url).pathname

/** ไฟล์ที่เปิดโดยตั้งใจและ **ไม่ควรมีกุญแจ** — ต้องมีเหตุผล ไม่ใช่แค่ชื่อ
 *  🔑 คีย์เป็น **เส้นทางไฟล์** ไม่ใช่เส้นทาง URL — เพราะเส้นเดียวมีได้หลายไฟล์ (ดูหัวไฟล์) */
const เปิดโดยตั้งใจ = {
  'app/login/page.tsx': 'หน้าล็อกอินเอง — ถ้าต้องมีกุญแจถึงจะเข้าได้ ก็ไม่มีใครล็อกอินได้เลย',
  /* ไล่ตรวจแล้ว 19 ก.ย. 2569 (ใบ t_mu7uzq7a) — คืนเฉพาะชื่อโมเดลที่สะพานใช้ ไม่มีข้อมูลร้าน
     แพลตฟอร์มเรียกเส้นนี้ตอนกด "ทดสอบการเชื่อมต่อ" **ก่อน** ใส่กุญแจ ⇒ ใส่กุญแจแล้วปุ่มทดสอบพัง
     ⚠️ เส้นพี่น้อง `chat/completions` ที่ส่งข้อความจริง **มีกุญแจ** (ROKID_BRIDGE_KEY) */
  'app/api/rokid/v1/models/route.ts': 'คืนแค่ชื่อโมเดล ไม่มีข้อมูลร้าน · เป็นเส้นที่แพลตฟอร์มเรียกก่อนใส่กุญแจ',
  /* ไล่ตรวจแล้ว 19 ก.ย. 2569 — เป็นแค่ตัวเปลี่ยนทางไปหน้ายินยอมของ Google
     `client_id` เป็นของสาธารณะตามการออกแบบ OAuth ⇒ ไม่มีความลับหลุด
     🔑 และที่สำคัญกว่า: `callback` **ไม่ได้เก็บ token ลงที่ไหนเลย** — มันพิมพ์ให้คนคัดลอกเอง
        ⇒ คนนอกที่ทำจนจบจะได้ token **ของบัญชีตัวเอง** · ของเราไม่ถูกเขียนทับ */
  'app/api/google/auth/route.ts': 'เปลี่ยนทางไปหน้ายินยอม Google เท่านั้น · callback ไม่เก็บ token ⇒ คนนอกได้ของตัวเอง',
}

/** ร่องรอยว่าเส้นนั้น "มีการตรวจอะไรสักอย่าง" — ไม่ได้ตัดสินว่าตรวจแน่นพอ */
const ร่องรอยกุญแจ = /SECRET|_KEY|TOKEN|PASSWORD|timingSafeEqual/

function ไฟล์ของเส้น(p) {
  const ฐาน = join(ROOT, 'app', p)
  const out = []
  const เดิน = (d) => {
    for (const ชื่อ of readdirSync(d)) {
      const x = join(d, ชื่อ)
      if (statSync(x).isDirectory()) เดิน(x)
      else if (ชื่อ === 'route.ts' || ชื่อ === 'page.tsx') out.push(x)
    }
  }
  if (existsSync(ฐาน) && statSync(ฐาน).isDirectory()) เดิน(ฐาน)
  for (const ต่อ of ['/route.ts', '/page.tsx']) {
    const x = join(ROOT, 'app', p + ต่อ)
    if (existsSync(x) && !out.includes(x)) out.push(x)
  }
  return out
}

function ตรวจ(รายการ) {
  const ผิด = []
  for (const p of รายการ) {
    const ไฟล์ = ไฟล์ของเส้น(p)
    if (!ไฟล์.length) {
      /* 🔴 **ไม่เจอไฟล์ = ตัดสินไม่ได้ ไม่ใช่ผ่าน** — เส้นสาธารณะที่หาโค้ดไม่เจอ
         อันตรายกว่าเส้นที่เห็นแล้วไม่มีกุญแจ เพราะไม่มีใครรู้ว่ามันทำอะไร */
      ผิด.push(`${p}  🔴 หาไฟล์ route/page ไม่เจอ ⇒ **ตัดสินไม่ได้** (ไม่ใช่ผ่าน)`)
      continue
    }
    /* 🔴🔴 **เดิมรวมทุกไฟล์ใต้เส้นทางแล้วตรวจรวมกัน — ช่องโหว่ที่เจอ 19 ก.ย. 2569**
       `/api/rokid` มีสองไฟล์: `chat/completions` (มีกุญแจ) กับ `v1/models` (ไม่มีเลย)
       ⇒ พอ `join` เข้าด้วยกันแล้วเจอคำว่า KEY จากไฟล์แรก ⇒ **ทั้งเส้นผ่าน**
       ⇒ ไฟล์ที่เปิดโล่งจริงถูกกลบด้วยไฟล์พี่น้องที่ปลอดภัย
       🔑 บทเรียน: **ตรวจเป็นก้อน = ให้ของที่ดีค้ำประกันของที่ยังไม่ได้ตรวจ**
       ⇒ ตรวจทีละไฟล์ · ยกเว้นก็ยกเว้นทีละไฟล์ (คีย์ของ `เปิดโดยตั้งใจ` จึงเป็นเส้นทางไฟล์) */
    for (const x of ไฟล์) {
      const rel = x.slice(ROOT.length).replace(/^\/+/, '')
      if (เปิดโดยตั้งใจ[rel]) continue
      if (!ร่องรอยกุญแจ.test(readFileSync(x, 'utf8'))) {
        ผิด.push(`${p}  🔴 ${rel} — เป็นเส้นสาธารณะแต่ไฟล์นี้ไม่เจอการตรวจกุญแจ`)
      }
    }
  }
  return ผิด
}

/* อ่านรายการจาก middleware.ts — **ไม่พิมพ์ซ้ำในด่าน** ไม่งั้นจะมีสองแหล่งความจริงอีก */
const mw = readFileSync(join(ROOT, 'middleware.ts'), 'utf8')
const ก้อน = mw.slice(mw.indexOf('const PUBLIC_PATHS'))
const รายการ = [...ก้อน.slice(0, ก้อน.indexOf(']')).matchAll(/'([^']+)'/g)].map((m) => m[1])

if (process.argv.includes('--self-test')) {
  /* ปลูกเส้นสาธารณะที่ไม่มีไฟล์ และเส้นที่มีไฟล์แต่ไม่มีกุญแจ */
  const r = ตรวจ(['/api/เส้นปลอมที่ไม่มีอยู่', '/login', ...รายการ])
  const จับได้ = r.some((x) => x.includes('เส้นปลอมที่ไม่มีอยู่'))
  const ไม่ฟ้องlogin = !r.some((x) => x.startsWith('/login'))
  console.log(จับได้ && ไม่ฟ้องlogin
    ? '🧪 self-test ผ่าน — จับเส้นที่ไม่มีโค้ดรองรับได้ และไม่ฟ้อง /login ที่เปิดโดยตั้งใจ'
    : `🛑 self-test ตก — ${JSON.stringify(r)}`)
  process.exit(จับได้ && ไม่ฟ้องlogin ? 0 : 1)
}

if (รายการ.length < 3) {
  console.log(`🛑 อ่าน PUBLIC_PATHS ได้ ${รายการ.length} เส้น — น้อยผิดปกติ ⇒ ตัวอ่านน่าจะพัง (ตรวจ 0 เส้นแล้วเขียวคือสิ่งที่ห้ามเกิด)`)
  process.exit(1)
}
const ผิด = ตรวจ(รายการ)
if (ผิด.length) {
  console.log(`\n🛑 เส้นสาธารณะที่ไม่เจอการตรวจกุญแจ (${ผิด.length} จาก ${รายการ.length})\n`)
  for (const x of ผิด) console.log('  ', x)
  console.log('\n   เส้นใน PUBLIC_PATHS ข้ามด่านล็อกอินทั้งหมด ⇒ ถ้าไม่ตรวจกุญแจเอง = เปิดโล่ง')
  console.log(`   เปิดโดยตั้งใจจริง ⇒ ใส่ใน \`เปิดโดยตั้งใจ\` **พร้อมเหตุผล** ที่ ${'scripts/check-public-paths-have-keys.mjs'}\n`)
  process.exit(1)
}
console.log(`✅ เส้นสาธารณะทั้ง ${รายการ.length} เส้นมีการตรวจกุญแจของตัวเอง`
  + ` (ยกเว้นโดยตั้งใจ ${Object.keys(เปิดโดยตั้งใจ).length}: ${Object.keys(เปิดโดยตั้งใจ).join(' · ')})`
  + '\n   ⚠️ ด่านนี้ตอบแค่ "มีการตรวจอยู่" ไม่ได้ตอบว่า "ตรวจแน่นพอ" — คนละคำถาม')
