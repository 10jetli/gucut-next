  console.log(ผ่านหมด
    ? `🧪 self-test ผ่าน — จับเส้นที่ไม่มีโค้ดรองรับได้ · ไม่ฟ้อง /login · และตัวจับทั้งสองตัวแยกแยะได้ (${กรณีกุญแจ.length + กรณีปฏิเสธ.length} กรณี สองทิศ)`
    : `🛑 self-test ตก — ${JSON.stringify({ จับได้, ไม่ฟ้องlogin, ตก })}`)
  process.exit(ผ่านหมด ? 0 : 1)
