import { execFileSync } from 'node:child_process'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { join } from 'node:path'
import { ตัดคอมเมนต์ } from './lib/ตัดคอมเมนต์.mjs'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const สมุด = 'scripts/lib/เลขค้างบนจอ.json'
const หน่วย = 'ราย|ใบ|รายการ|กลุ่ม|แถว|รหัส|ไฟล์|รอบ|ตัว|ชิ้น|คลัง|เจ้า|บรรทัด|ครั้ง|ร้าน|ช่องทาง'
const รูปหน่วย = new RegExp(`(?<![\\w.,/:#-])(\\d{1,3}(?:,\\d{3})+|\\d+)\\s?(?:${หน่วย})(?![ก-๙])`, 'g')
const รูปจุลภาค = /(?<![\w.])\d{1,3}(?:,\d{3})+(?:\.\d+)?/g

/** คืนรายการจุดที่จับได้ในซอร์สหนึ่งไฟล์ — ฟังก์ชันล้วน (ตรวจตัวเองเรียกตัวเดียวกัน) */
export function จับเลขค้าง(ซอร์ส) {
  const ผล = []
  ตัดคอมเมนต์(ซอร์ส).replace(/\$\{[^}]*\}/g, ' ⟨สด⟩ ').split('\n').forEach((บรรทัด, i) => {
    if (!/[ก-๙]/.test(บรรทัด)) return
    if (/placeholder/.test(บรรทัด)) return
    const ข้อความ = บรรทัด.replace(/อย่างน้อย\s*\d+/g, '')
    const เจอ = [...ข้อความ.matchAll(รูปหน่วย)].map((m) => m[0]).concat([...ข้อความ.matchAll(รูปจุลภาค)].map((m) => m[0]))
    if (เจอ.length) ผล.push({ บรรทัด: i + 1, ข้อความ: บรรทัด.trim(), เลข: [...new Set(เจอ)] })
  })
  return ผล
}

