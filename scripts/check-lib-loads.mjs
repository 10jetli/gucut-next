#!/usr/bin/env node
/* ตัวช่วยใน `scripts/lib/` ต้อง **โหลดได้จริง** และ **โหลดแล้วต้องไม่ลงมือทำอะไร**
 *
 * 🔴 ที่มา ① 20 ก.ย. 2569 — ฝั่งท่อเจอของจริง: แก้ไฟล์ตัวสร้างแล้ว **ลืมใส่ `import`**
 *    ⇒ `ReferenceError` ตอนรัน แต่ **เทส 709 ข้อผ่านหมด** เพราะด่านที่คุมไฟล์นั้น
 *       อ่าน **ข้อความในซอร์ส** ไม่ได้ **รันมัน**
 *    🔑 ⇒ **ด่านรูปแบบกับด่านของจริงจับคนละอย่าง**
 *       `node --check` จับได้แค่ไวยากรณ์ — **ReferenceError เป็นเรื่องตอนรัน มันมองไม่เห็น**
 *    📏 ฝั่งเรา: `scripts/lib/` มี 7 ตัวช่วย · สายรันเรียกใช้จริง 4 ⇒ **3 ตัวไม่เคยถูกรันเลย**
 *       รวม `ปลูกแล้ววัด.mjs` ซึ่งเป็นเครื่องมือที่ **สองรีโปใช้ร่วมกันเพื่อพิสูจน์ว่าด่านจับบั๊กได้**
 *
 * 🔴 ที่มา ② (ฝั่งท่อชี้ให้ 20 ก.ย. 2569) — **ด่านนี้ import ตัวช่วยทุกตัวทุก build**
 *    ⇒ ถ้าวันหนึ่งมีตัวช่วยที่ **ลงมือทำอะไรตอนถูกโหลด** (พิมพ์จอ · เขียนไฟล์ · ยิงเน็ต)
 *       **ด่านนี้จะกลายเป็นตัวสั่งให้มันทำงานทุก build** ⇒ ตัวตรวจกลายเป็นตัวก่อผลข้างเคียง
 *    ⇒ ⇒ เขาเขียนคอมเมนต์เตือนไว้ · **ฝั่งเราทำให้ด่านจับเรื่องนี้เองแทน**
 *       (บทเรียนของวันนี้: คลาสที่รู้แล้วให้แปลงเป็นกลไก ไม่ใช่เพิ่มคำเตือน)
 *    📏 วัดวันที่เขียน: ทั้ง 7 ตัว **ไม่พิมพ์อะไรเลยตอนโหลด** ⇒ ด่านนี้เริ่มจากเขียว
 *
 * 🚫 **ครอบอะไรไม่ได้บ้าง — ต้องเขียนไว้ ไม่งั้นเขียวของมันจะถูกอ่านเกินจริง**
 *    · ครอบ: โหลดโมดูลได้ · โค้ดระดับบนสุดไม่โยน · มี export · ไม่พิมพ์อะไรตอนโหลด
 *    · **ไม่ครอบ: ข้างในตัวฟังก์ชัน** — `ReferenceError` ที่ซ่อนในฟังก์ชันที่ไม่มีใครเรียก ยังหลุดได้
 *      ⇒ ทางแก้ของเรื่องนั้นคือ **เรียกมันจริงในเทส** ไม่ใช่ด่านนี้
 *    · **ไม่ครอบ: ผลข้างเคียงที่เงียบ** (เขียนไฟล์โดยไม่พิมพ์อะไร) — ด่านนี้ดูที่ "เสียงที่มันทำ"
 *      ⇒ จับได้เฉพาะตัวที่พิมพ์ออกจอ · ตัวที่เขียนไฟล์เงียบ ๆ ยังต้องพึ่งการอ่านโค้ด
 */
import { readdirSync, readFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { execFileSync } from 'node:child_process'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { ตัดสินผลโหลด } from './lib/ตัดสินผลโหลด.mjs'

const dir = resolve(process.cwd(), 'scripts/lib')
const ไฟล์ = readdirSync(dir).filter((n) => n.endsWith('.mjs')).sort()
const โหลดไม่ได้ = []
const ลงมือตอนโหลด = []
const ออกก่อนเวลา = []
let ผ่าน = 0

for (const n of ไฟล์) {
  const url = pathToFileURL(join(dir, n)).href
  /* โหลดใน **ลูกกระบวนการ** ไม่ใช่ในตัวเอง — สองเหตุผล:
     ① ตัวช่วยที่เรียก `process.exit()` ตอนโหลด จะฆ่าด่านนี้ทิ้งแล้วดูเหมือน "ผ่าน"
     ② ต้องแยก "เสียง" ของตัวช่วยออกจากเสียงของด่าน ⇒ จับได้ว่าใครพิมพ์ */
  let out = ''
  let ข้อผิดพลาด = null
  /* 🔑 **หมุดยืนยันว่า `import` เดินจบ** (ฝั่งท่อชี้ช่องนี้ให้ 20 ก.ย. 2569)
     ปลูก `process.exit(0)` ตอนโหลด ⇒ ลูกออกด้วย **0 อย่างเงียบ ๆ**
     ⇒ ⇒ **การหยุดกลางทางหน้าตาเหมือนความสำเร็จ** ⇒ ด่านเดิมตอบ "ผ่าน" (ยิงยืนยันฝั่งเราแล้วว่าหลุดจริง)
     ⇒ ลูกกระบวนการแก้เรื่อง "ตัวช่วยฆ่าด่าน" ได้ แต่ **ไม่แก้เรื่อง "ออกก่อนเวลา"** — คนละตาข่าย
     🚫 หมุดต้องเป็น **ไฟล์ ไม่ใช่ข้อความบนจอ** ไม่งั้นด่าน "ต้องเงียบตอนโหลด" จะร้องใส่หมุดของตัวเอง */
  const หมุด = join(tmpdir(), `libload-${process.pid}-${n.replace(/[^\w.-]/g, '_')}.mark`)
  try { rmSync(หมุด, { force: true }) } catch { /* ไม่มีอยู่แล้วก็ดี */ }
  try {
    out = execFileSync(
      process.execPath,
      ['-e', `import(${JSON.stringify(url)}).then(m=>{require("fs").writeFileSync(${JSON.stringify(หมุด)},String(Object.keys(m).length))})`],
      { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 20000 },
    )
  } catch (e) {
    ข้อผิดพลาด = String(e?.stderr || e?.message || e)
  }
  /* อ่านหมุด — ไม่มีหมุด = `import` ไม่เคยเดินจบ ทั้งที่ลูกออกด้วย 0 */
  let หมุดที่ได้ = null
  try { หมุดที่ได้ = readFileSync(หมุด, 'utf8') } catch { /* ไม่มีหมุด */ }
  try { rmSync(หมุด, { force: true }) } catch { /* ลบไม่ได้ก็ไม่เป็นไร */ }

  /* 🔑 **การตัดสินอยู่คนละที่กับการลงมือ** — เกณฑ์ที่ฝั่งท่อสรุป 20 ก.ย. 2569:
     *"แก้อะไรแล้วจำนวนเทสไม่ขยับ ให้ถือว่ายังไม่ได้แก้"*
     ตัวตัดสินเคยฝังอยู่ตรงนี้ ⇒ พิสูจน์ได้ทางเดียวคือปลูกไฟล์จริงทีละทิศ
     ⇒ ยกไป `scripts/lib/ตัดสินผลโหลด.mjs` + เทส 13 ข้อ (รวมข้อที่ปลูกรุ่นกลืนทุกอย่างไว้ในเทสเอง) */
  const ต = ตัดสินผลโหลด({ error: ข้อผิดพลาด, เสียง: out, หมุด: หมุดที่ได้ })
  if (ต.ผล === 'โหลดไม่ได้') { โหลดไม่ได้.push(`${n} — **${ต.ชนิด}** ${ต.เหตุ}`); continue }
  if (ต.ผล === 'ไม่มี export') { โหลดไม่ได้.push(`${n} — ${ต.เหตุ}`); continue }
  if (ต.ผล === 'ลงมือตอนโหลด') { ลงมือตอนโหลด.push(`${n} — ${ต.เหตุ}`); continue }
  if (ต.ผล === 'ออกก่อนเวลา') { ออกก่อนเวลา.push(`${n} — ${ต.เหตุ}`); continue }
  ผ่าน++
}

console.log(`ตรวจว่าตัวช่วยโหลดได้จริงและเงียบตอนโหลด: **${ไฟล์.length} ไฟล์** ใน scripts/lib/ · ผ่าน ${ผ่าน}`)
console.log('   ⚠️ ครอบแค่ระดับบนสุดของโมดูล — ReferenceError ที่ซ่อนในฟังก์ชันที่ไม่มีใครเรียก **ยังหลุดได้**')
console.log('   ⚠️ และจับได้เฉพาะผลข้างเคียงที่ **ส่งเสียง** — ตัวที่เขียนไฟล์เงียบ ๆ ยังต้องอ่านโค้ดเอง')

if (โหลดไม่ได้.length) {
  console.error('\n🔴 ตัวช่วยที่โหลดไม่ได้ (หรือไม่มีของให้ใช้)')
  for (const x of โหลดไม่ได้) console.error('   ' + x)
  console.error('\n   ⚠️ `node --check` ผ่านไม่ได้แปลว่ารันได้ — ไวยากรณ์ถูกกับชื่อมีอยู่จริง คนละเรื่อง')
}
if (ออกก่อนเวลา.length) {
  console.error('\n🔴 ตัวช่วยที่ **ออกกลางทางตอนถูกโหลด** — หน้าตาเหมือนสำเร็จ แต่ `import` ไม่เคยเดินจบ')
  for (const x of ออกก่อนเวลา) console.error('   ' + x)
  console.error('   ⇒ ผู้เรียกจะได้โมดูลไม่ครบโดยไม่มีอะไรฟ้อง · วิธีแก้: ห้ามเรียก process.exit ที่ระดับบนสุดของตัวช่วย')
  console.error('   (สคริปต์ที่ตั้งใจให้รันเดี่ยว ๆ ไม่ควรอยู่ใน scripts/lib/ ตั้งแต่แรก)')
}
if (ลงมือตอนโหลด.length) {
  console.error('\n🔴 ตัวช่วยที่ **ลงมือทำอะไรตอนถูกโหลด** — ด่านนี้ import ทุกตัวทุก build')
  for (const x of ลงมือตอนโหลด) console.error('   ' + x)
  console.error('\n   ⇒ ปล่อยไว้ = **ตัวตรวจกลายเป็นตัวสั่งให้ทำงาน** ทุกครั้งที่ build')
  console.error('   วิธีแก้: ย้ายสิ่งที่มันทำไปไว้ **ในฟังก์ชันที่ผู้เรียกสั่งเอง** แล้ว export ฟังก์ชันนั้นแทน')
}
if (โหลดไม่ได้.length || ลงมือตอนโหลด.length || ออกก่อนเวลา.length) process.exit(1)
console.log('✅ ตัวช่วยทุกตัวโหลดได้ มีของให้ใช้ เงียบตอนโหลด และ import เดินจบจริง')
