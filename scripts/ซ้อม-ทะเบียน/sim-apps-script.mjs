/** ซ้อมตรรกะของ apps-script-ทะเบียน-push.gs ในเครื่อง (Google APIs แทนด้วยชีทจำลองโครงจริง)
 *  โครงตาม ~/claude-shared/วิธีดูชีททะเบียน.md: หัวสองชั้น (รายการรับ/รายการจำหน่าย + หัวย่อย)
 *  หนึ่งแถว = ของหนึ่งชิ้นมีซีเรียล · ฝั่งขวามีชื่อผู้ซื้อ/ลซ.๒/จังหวัด = ขายแล้ว
 *  ตรวจ: ① payload ไม่มีข้อมูลบุคคลหลุด ② ช่องต้องห้ามที่มีของกลายเป็น × ③ endpoint ตอบ 200 สำรวจ
 */

/* ── ชีทจำลอง 3 แท็บ (ย่อจาก 8 แท็บจริง — โครงเดียวกัน) ─────────────── */
const หัวชั้นบน = ['', '', 'รายการรับ', '', '', '', 'รายการจำหน่าย', '', '', '']
const หัวย่อย = ['ลำดับ', 'วัน เดือน ปี', 'ยี่ห้อ', 'ขนาด', 'หมายเลขซีเรียล', 'วัน เดือน ปี', 'ชื่อผู้ซื้อ', 'เลข ลซ.๒', 'จังหวัด', 'หมายเหตุ']
const แถว = (ลำดับ, รับ, ยี่ห้อ, ขนาด, ซีเรียล, ขาย = '', ผู้ซื้อ = '', ลซ = '', จังหวัด = '') =>
  [String(ลำดับ), รับ, ยี่ห้อ, ขนาด, ซีเรียล, ขาย, ผู้ซื้อ, ลซ, จังหวัด, '']
const ชีทจำลอง = [
  { ชื่อ: 'มห00001/2566 (บาร์ NEWWAVE)', แถว: [
    ['บัญชีรับและจำหน่ายอาวุธปืนของร้านค้า'], [], หัวชั้นบน, หัวย่อย,
    แถว(1, '1/3/2566', 'NEWWAVE', '24', '45-7-66-00011'),
    แถว(2, '1/3/2566', 'NEWWAVE', '24', '45-7-66-00012', '7/10/2569', 'นายทดสอบ ซ้อมใหญ่', 'ลซ2-1234', 'เชียงใหม่'),
    แถว(3, '1/3/2566', 'NEWWAVE', '28', '45-7-66-00013'),
  ]},
  { ชื่อ: 'มห00001/2567 (บาร์ Kingkong)', แถว: [
    หัวชั้นบน, หัวย่อย,
    แถว(1, '9/1/2567', 'KINGKONG', '25', '45-7-67-00021'),
    แถว(2, '9/1/2567', 'KINGKONG', '30', '45-7-67-00022', '5/10/2569', 'นางสาวตัวอย่าง ขายแล้ว', 'ลซ2-5678', 'ลำปาง'),
  ]},
  { ชื่อ: 'มห00001/2567 (Series-F)', แถว: [
    หัวชั้นบน, หัวย่อย,
    แถว(1, '2/4/2567', 'NEWWAVE', 'F660', '45-7-67-00031'),
  ]},
]
const ของลับ = ['45-7-66-00011', '45-7-66-00012', '45-7-67-00021', 'นายทดสอบ', 'นางสาวตัวอย่าง', 'ลซ2-1234', 'ลซ2-5678', 'เชียงใหม่', 'ลำปาง']

/* ── ตรรกะเดียวกับ .gs (ลอกคำต่อคำ เปลี่ยนแค่แหล่งข้อมูล) ───────────── */
const อนุญาต = /ลำดับ|ยี่ห้อ|ขนาด|รุ่น|รับ|จำหน่าย|ขาย|วันที่|วัน เดือน ปี/
const ห้าม = /ซีเรียล|หมายเลข|ผู้ซื้อ|ที่อยู่|ใบอนุญาต|เบอร์|ลูกค้า|ลซ|จังหวัด|ชื่อ/
let แท็บ = []
for (const sh of ชีทจำลอง) {
  const ค่า = sh.แถว
  let หัวที่ = -1, คะแนน = 1
  ค่า.slice(0, 15).forEach((r, i) => {
    const k = r.filter((x) => /ซีเรียล|หมายเลข|ยี่ห้อ|ขนาด|รุ่น|จำหน่าย|วันที่|ลำดับ|ใบอนุญาต|ผู้ซื้อ|รับ/.test(String(x))).length
    if (k > คะแนน) { หัวที่ = i; คะแนน = k }
  })
  const โอเค = หัวที่ >= 0
    ? ค่า[หัวที่].map((h) => อนุญาต.test(String(h)) && !ห้าม.test(String(h)))
    : ค่า[0] ? ค่า[0].map(() => false) : []
  const แถวส่ง = ค่า.map((r, i) =>
    i === หัวที่
      ? r.map((x) => String(x).slice(0, 120))
      : r.map((x, c) => (โอเค[c] ? String(x).slice(0, 120) : (String(x) === '' ? '' : '×'))),
  )
  แท็บ.push({ ชื่อ: sh.ชื่อ, แถว: แถวส่ง, _หัวที่: หัวที่ })
}

/* ── ตรวจ ① ② แล้วยิง ③ ─────────────────────────────────────────── */
let ตก = 0
const ok = (ชื่อ, จริง, เหตุ = '') => { console.log(`${จริง ? '✅' : '❌'} ${ชื่อ}${จริง ? '' : ' — ' + เหตุ}`); if (!จริง) ตก++ }

ok('ทุกแท็บเจอแถวหัวย่อย (แถวที่มีคำหัวมากสุด ไม่ใช่ชั้นบน)', แท็บ.every((t) => t._หัวที่ >= 0 && JSON.stringify(ชีทจำลอง[0].แถว[t._หัวที่] ?? []) !== JSON.stringify(หัวชั้นบน)), JSON.stringify(แท็บ.map((t) => t._หัวที่)))
const payload = { key: process.env.REHEARSAL_KEY || 'ซ้อม-g2-rehearsal-key-2210', ชีทแก้ไขล่าสุด: new Date().toISOString(), แท็บ: แท็บ.map(({ _หัวที่, ...t }) => t) }
const ตัวหนังสือ = JSON.stringify(payload)
ok('ไม่มีซีเรียล/ชื่อผู้ซื้อ/ลซ./จังหวัดหลุดใน payload', ของลับ.every((x) => !ตัวหนังสือ.includes(x)), ของลับ.filter((x) => ตัวหนังสือ.includes(x)).join(','))
const t0 = payload.แท็บ[0].แถว
ok('แถวหัวย่อยส่งเต็ม (เพื่อให้ฝั่งรับรู้ตำแหน่งคอลัมน์)', t0[3].includes('หมายเลขซีเรียล') && t0[3].includes('ชื่อผู้ซื้อ'))
ok('แถวขายแล้ว: ช่องผู้ซื้อ = × (มีของ ไม่มีเนื้อหา)', t0[5][6] === '×' && t0[5][7] === '×' && t0[5][8] === '×', JSON.stringify(t0[5]))
ok('แถวยังอยู่: ฝั่งจำหน่ายว่างทุกช่อง', t0[4].slice(5, 9).every((x) => x === ''), JSON.stringify(t0[4]))
ok('วันขาย (วัน เดือน ปี) ส่งเนื้อหาจริง — whitelist ครอบ', t0[5][5] === '7/10/2569', JSON.stringify(t0[5]))
ok('ยี่ห้อ/ขนาดส่งจริง', t0[4][2] === 'NEWWAVE' && t0[4][3] === '24')

const เส้น = process.env.REHEARSAL_URL || 'http://localhost:3002/api/registry-sheet-push'
const res = await fetch(เส้น, { method: 'POST', headers: { 'content-type': 'application/json' }, body: ตัวหนังสือ })
const j = await res.json()
ok('endpoint ตอบ 200 + สถานะสำรวจ', res.status === 200 && j.สถานะ === 'สำรวจ', `${res.status} ${JSON.stringify(j).slice(0, 120)}`)
console.log(ตก === 0 ? '\n✅ ซ้อมตรรกะสคริปต์ผ่านหมด' : `\n❌ ตก ${ตก}`)
process.exit(ตก ? 1 : 0)
