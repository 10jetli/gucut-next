#!/usr/bin/env node
/**
 * 🚧 **พื้นจำนวนด่านในลูกโซ่ — กันลูกโซ่หดเงียบ**
 *
 * บังคับใบ: a-check-is-only-as-alive-as-whatever-triggers-it
 *
 * ## 🔴 ที่มา: รูที่ฝั่งท่อตั้งคำถามแล้วตอบไม่ได้ และผมยิงวัดฝั่งตัวเองแล้ว **มีจริง**
 * เขาเขียนว่า: *"ถ้า `check-plant-formulas` ถูกถอดจากลูกโซ่ ไม่มีอะไรฟ้อง ⇒ รูจริงอยู่ที่นั่น"*
 * ⇒ ผมจำลองในสำเนา (ไม่แตะของจริง) สองทิศ:
 *   ① ถอดด่าน **อื่น** 3 ตัวออกจากสาย `ตรวจ` ⇒ **ฟ้อง** 🔴
 *      เพราะเพดานหนี้ของ `check-ด่านอ้างใบ` สองทาง: `ไม่มีช่องเลย 58 ⇒ 55` ⇒ "ฐานค้างสูงกว่าของจริง"
 *      (ผลข้างเคียงที่ดีของเพดานสองทาง — ผมไม่ได้ออกแบบมาเพื่อข้อนี้)
 *   ② ถอด **ตัวตรวจเอง** ออก ⇒ **เงียบสนิท** · และกวาดแล้ว **ไม่มีไฟล์อื่นเลยที่อ่านสาย `ตรวจ`**
 *      (0 ไฟล์) ⇒ ⇒ **ลูกโซ่หดได้โดยไม่มีใครรู้ ถ้าของที่หายคือตัวที่นับ**
 *
 * 🔑 **กลไกทั่วไป: ตัวนับที่อยู่ในของที่มันนับ หายไปพร้อมกับของที่มันนับ**
 *    ⇒ ของที่จะจับการหดของลูกโซ่ได้ **ต้องอยู่นอกลูกโซ่** ⇒ ด่านนี้ถูกเรียกจาก **ฮุคก่อน push**
 *    (รูปเดียวกับ `check-test-floor` ที่ต้องอยู่นอก prebuild เพราะต้องอ่าน log ของชุดทดสอบ)
 *
 * ⚠️ **ขอบเขตที่ตอบไม่ได้ และต้องเขียนไว้**: ถ้ามีคนถอด **บรรทัดที่เรียกด่านนี้** ออกจากฮุค
 *    ก็เงียบเหมือนกัน — ผมไม่มีชั้นที่สาม · ที่มีคือ `check-hook-installed` ซึ่งเทียบ md5
 *    ของฮุคที่ติดตั้งกับในรีโป ⇒ **จับ "ฮุคไม่ตรงรีโป" ได้ แต่ไม่จับ "รีโปแก้ฮุคให้หลวม"**
 *    ⇒ ⇒ ชั้นสุดท้ายยังเป็นคน ⇒ **เขียนไว้ตรง ๆ ดีกว่าปล่อยให้คนคิดว่าปิดครบ**
 *
 * สามสถานะ (รูปเดียวกับพื้นจำนวนเทส): `ผ่าน | ตก | คุมไม่ได้`
 *   · เท่าพื้น ⇒ ผ่าน · มากกว่าพื้น ⇒ ผ่าน + **ยกพื้นเอง** (ขึ้นเท่านั้น)
 *   · น้อยกว่าพื้น ⇒ **ตก** เว้นมี `เหตุที่ลด` ที่เลขตรงเป๊ะ + เหตุ ≥10 อักขระ
 *   · อ่าน package.json / ไฟล์พื้นไม่ได้ ⇒ **คุมไม่ได้รอบนี้** ไม่ใช่ "ผ่าน"
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'

const ROOT = process.env.CHAIN_FLOOR_ROOT || fileURLToPath(new URL('..', import.meta.url))
const ไฟล์พื้น = process.env.CHAIN_FLOOR_FILE || join(ROOT, 'scripts', 'lib', 'พื้นลูกโซ่.json')

const คุมไม่ได้ = (เหตุ) => {
  console.log(`⬜ **พื้นลูกโซ่: คุมไม่ได้รอบนี้** — ${เหตุ}`)
  console.log('   ⇒ ไม่ใช่ "ผ่าน" · รอบนี้ไม่มีใครยืนยันว่าลูกโซ่ไม่หด')
  process.exit(0)
}

let สาย
try {
  สาย = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')).scripts?.['ตรวจ']
} catch (e) { คุมไม่ได้(`อ่าน package.json ไม่ได้ (${e?.code || e?.message})`) }
if (typeof สาย !== 'string' || !สาย.trim()) คุมไม่ได้('ไม่มีสคริปต์ `ตรวจ` ใน package.json')

/** นับ **ชื่อไม่ซ้ำ** — สายเดียวกันเรียกไฟล์เดิมสองครั้งได้ (`--self-test` แล้วรันจริง) */
const ในสาย = [...new Set([...สาย.matchAll(/node (scripts\/[^\s;&]+)/g)].map((m) => m[1]))]

let พื้นดิบ
try { พื้นดิบ = JSON.parse(readFileSync(ไฟล์พื้น, 'utf8')) }
catch (e) { คุมไม่ได้(`อ่านไฟล์พื้นไม่ได้ (${e?.code || e?.message})`) }
const พื้น = พื้นดิบ['พื้น']
if (typeof พื้น !== 'number') คุมไม่ได้('ช่อง "พื้น" ไม่ใช่ตัวเลข')

console.log(`🔗 พื้นลูกโซ่: ของจริง **${ในสาย.length}** · พื้นที่จด **${พื้น}**`)

/* 🔴 **"ตะแกรงพัง" ต้องแยกจาก "สายหด" — ทางแก้คนละอย่าง** (เคสร่วมของฝั่งท่อ ข้อ ③)
 *    สายหด   ⇒ ไปหาด่านที่ถูกถอดออกจาก `ตรวจ`
 *    ตะแกรงพัง ⇒ ไปหาว่าทำไมตัวจับอ่านสายไม่ออก (เช่นรูปของสายเปลี่ยน · คลาสอักขระไม่ครอบ)
 *    ⇒ ⇒ ถ้าข้อความบอกผิด **คนจะไปไล่หาด่านที่ไม่ได้หายไปไหน**
 * 📏 เลข 5: สายจริงของรีโปนี้มี 153 ตัว ⇒ ต่ำกว่า 5 **ไม่ใช่สภาพที่เกิดจากการถอดด่านทีละตัว**
 *    (ฝั่งท่อเคยมีพื้นเป็น `< 5` เฉย ๆ ซึ่งกันตะแกรงพังได้ แต่ **กันสายหดไม่ได้** ⇒ 25 ⇒ 5 ยังเขียว) */
const ขอบตะแกรงพัง = 5
if (ในสาย.length < ขอบตะแกรงพัง) {
  console.error(`🔴 **ตก: ตะแกรงพัง ไม่ใช่สายหด** — อ่านชื่อด่านได้แค่ ${ในสาย.length} ตัว (< ${ขอบตะแกรงพัง})`)
  console.error('   ⇒ สายจริงมีเป็นร้อย ⇒ เลขระดับนี้แปลว่า **ตัวจับอ่านสายไม่ออก** ไม่ใช่มีคนถอดด่าน')
  console.error('   ⇒ ไปดูรูปของสคริปต์ `ตรวจ` ใน package.json ว่าเปลี่ยนรูปไหม'
    + ' (เช่นเปลี่ยนจาก `node x.mjs` เป็นรูปอื่น) — **อย่าไปไล่หาด่านที่ถูกถอด**')
  process.exit(1)
}
if (ในสาย.length >= พื้น) {
  if (ในสาย.length > พื้น) {
    const ใหม่ = { ...พื้นดิบ, 'พื้น': ในสาย.length, 'จดเมื่อ': new Date().toISOString().slice(0, 10) }
    try {
      writeFileSync(ไฟล์พื้น, JSON.stringify(ใหม่, null, 2) + '\n')
      console.log(`   ✅ ผ่าน · **ยกพื้น ${พื้น} ⇒ ${ในสาย.length}** แล้ว`)
    } catch (e) {
      console.log(`   ✅ ผ่าน · 🔶 ยกพื้นไม่ได้ (${e?.code || e?.message}) ⇒ พื้นค้างต่ำ = ที่ซ่อน`)
    }
  } else console.log('   ✅ ผ่าน · เท่าพื้นพอดี')
  process.exit(0)
}

const ล = พื้นดิบ['เหตุที่ลด'] ?? null
if (ล) {
  const เหตุ = String(ล['เหตุ'] ?? '').trim()
  if (ล['ถึงจำนวน'] !== ในสาย.length) {
    console.error(`🔴 **ตก: ลดโดยตั้งใจ แต่เลขไม่ตรงของจริง** (เหตุบอก ${ล['ถึงจำนวน']} · ของจริง ${ในสาย.length})`)
    process.exit(1)
  }
  if (เหตุ.length < 10) {
    console.error(`🔴 **ตก: เหตุที่ลดสั้นเกิน** (${เหตุ.length} อักขระ · ต้อง ≥10)`)
    process.exit(1)
  }
  console.log(`   ✅ ผ่าน · ลดโดยตั้งใจถึง ${ล['ถึงจำนวน']} — เหตุ: ${เหตุ}`)
  process.exit(0)
}
console.error(`🔴 **ตก: ลูกโซ่หด ${พื้น - ในสาย.length} ตัว** (${ในสาย.length} < ${พื้น})`)
console.error('   ⇒ มีด่านถูกถอดออกจากสคริปต์ `ตรวจ` ใน package.json')
console.error('   ⇒ ถ้าตั้งใจถอด ให้เติม `"เหตุที่ลด": {"ถึงจำนวน": <เลขจริง>, "เหตุ": "<≥10 อักขระ>"}`')
console.error('     ลงใน `scripts/lib/พื้นลูกโซ่.json` — **เลขต้องตรงของจริงเป๊ะ**')
process.exit(1)
