#!/usr/bin/env node
/* รายงาน: **จอแต่ละจออ่านช่องอะไรจากคำตอบของท่อ** และช่องไหน "ประกาศไว้แต่ไม่มีใครใช้"
 *
 * 🔴 **ที่มา 19 ก.ย. 2569** — เจอว่า `byChannel` ถูกประกาศชนิดไว้ในจอรายการขาย
 *    แต่ **ไม่มีที่ไหนเอาไปแสดงเลย** · ฝั่งท่อยืนยันว่าไม่ได้เอาไปคำนวณต่อด้วย
 *    ⇒ ท่อคำนวณให้ทุกคำขอ (1 คำสั่ง D1 ต่อคำขอ) **โดยไม่มีใครดู ทั้งสองฝั่ง**
 *    🔑 คลาสนี้คือ **"ท่อทำให้แล้วจอเลิกใช้ไปตั้งแต่เมื่อไหร่ไม่รู้"** — กลับด้านของ channel-gaps
 *       ไม่มีอะไรพัง ไม่มีอะไรฟ้อง · หาไม่เจอด้วยการอ่านฝั่งเดียว
 *
 * 🎯 ของที่ไฟล์นี้ตอบได้: **ฝั่งจอใช้อะไร** ⇒ เอาไปวางคู่กับ `?endpoints=1` ของท่อ
 *    แล้วจะเทียบได้ **สองทาง**: ท่อมีแต่จอไม่ใช้ · จอใช้แต่ท่อไม่มี
 *
 * ⚠️⚠️ **กองนี้หยาบโดยธรรมชาติ** (อ่านด้วย regex ไม่ได้ parse TypeScript)
 *    · ช่องที่ถูกใช้ผ่านการ destructure หรือส่งต่อทั้งก้อน (`{...data}`) จะถูกนับว่า "ไม่ใช้" ผิด ๆ
 *    · ชื่อช่องที่ซ้ำกับตัวแปรอื่นในไฟล์ จะถูกนับว่า "ใช้" ทั้งที่ไม่ได้ใช้จากคำตอบ
 *    ⇒ **ใช้เป็นรายการที่ต้องไปดูด้วยตา ห้ามถือเป็นข้อสรุป** (ป้ายนี้ต้องติดไปกับผลเสมอ)
 *
 * 🚫 ไม่อยู่ใน prebuild — เป็นรายงาน ไม่ใช่ด่าน (ไม่มีเกณฑ์ตายตัวว่าเท่าไรถึงผิด)
 */
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const ไฟล์ = [];
const เดิน = (d) => {
  for (const name of readdirSync(d)) {
    const p = join(d, name);
    if (statSync(p).isDirectory()) เดิน(p);
    else if (name === "page.tsx") ไฟล์.push(p);
  }
};
เดิน(join(ROOT, "app"));

const รายงาน = [];
for (const p of ไฟล์) {
  const src = readFileSync(p, "utf8");
  /* เส้นที่จอนี้ยิง — ต้องจับ **สองรูป** ไม่ใช่รูปเดียว
     ① เขียนตรง ๆ: `/api/web/core?list=stock&…`
     ② สร้างด้วย URLSearchParams: `new URLSearchParams({ list: 'orders', … })` แล้วต่อเป็น `?${qs}`
     🔴 รุ่นแรกจับแค่รูป ① ⇒ **ข้ามจอรายการขายทั้งจอ** ซึ่งเป็นเคสที่ทำให้เขียนสคริปต์นี้
        (จอสำคัญเกือบทั้งหมดสร้าง query แบบไดนามิก) ⇒ เครื่องมือมองไม่เห็นของที่ต้องดูที่สุด
     ⚠️ จับไม่ได้ทั้งคู่ ⇒ **ไม่ข้ามจอนั้น** แต่เขียนว่า "ไม่รู้ว่ายิงเส้นไหน"
        (ข้ามเงียบ = จอหายจากรายงานโดยไม่มีใครรู้ — คลาสเดียวกับสารบัญที่ตาบอด) */
  const ตรง = [...src.matchAll(/\/api\/web\/core\?([a-zA-Z]+)=([a-zA-Z0-9-]+)/g)]
    .map((m) => (m[1] === "list" ? `list=${m[2]}` : m[1]));
  const ไดนามิก = [...src.matchAll(/URLSearchParams\(\{\s*([a-zA-Z]+)\s*:\s*['"]([a-zA-Z0-9-]+)['"]/g)]
    .map((m) => (m[1] === "list" ? `list=${m[2]}` : m[1]));
  const ยิงท่อ = /\/api\/web\/core/.test(src);
  if (!ยิงท่อ) continue;
  const เส้น = [...new Set([...ตรง, ...ไดนามิก])];
  if (!เส้น.length) เส้น.push("(ไม่รู้ว่ายิงเส้นไหน — สร้าง query แบบที่สคริปต์นี้อ่านไม่ออก)");

  /* ช่องที่ประกาศไว้ใน interface ที่ชื่อลงท้ายด้วย Resp — คือ "ช่องที่จอคาดว่าจะได้" */
  const ประกาศ = new Set();
  /* ⚠️ ปิดบล็อกที่ `}` **ต้นบรรทัด** เท่านั้น — ไม่งั้น regex จะกลืนโค้ดที่อยู่ถัดไป
     (รุ่นก่อนหน้ากลืนชนิดของ props ที่อยู่ใต้ interface ⇒ รายงานชื่ออย่าง label/onChange/width
      ซึ่งไม่ใช่ช่องจากท่อเลย ⇒ **เสียงรบกวนทำให้คนเลิกอ่านรายงานทั้งใบ**) */
for (const m of src.matchAll(/interface\s+\w*Resp\w*\s*\{\n([\s\S]*?)\n\}/g)) {
    /* 🔴 **ต้องจับหลายช่องในบรรทัดเดียวด้วย** — จอรายการขายเขียน
       `rows: Row[]; byChannel: ChannelRow[]; byStatus: StatusRow[]` ไว้บรรทัดเดียว
       รุ่นแรกของสคริปต์นี้จับแค่ช่องแรกของแต่ละบรรทัด ⇒ **มองไม่เห็น `byChannel`
       ซึ่งเป็นเคสที่ทำให้เขียนสคริปต์นี้ขึ้นมาตั้งแต่ต้น**
       🔑 กฎ: เครื่องมือใหม่ต้องชี้ **ตัวอย่างที่รู้ว่ามีจริง** ให้ได้ก่อน จึงเชื่อผลว่างของมันได้ */
    for (const f of m[1].matchAll(/(?:^|[;{]|\*\/)\s*([a-zA-Z_][a-zA-Z0-9_]*)\??\s*:/gm)) ประกาศ.add(f[1]);
  }
  if (!ประกาศ.size) continue;

  /* ใช้จริงไหม — นับการอ้างถึงชื่อนั้นนอกบล็อก interface */
  const นอกinterface = src.replace(/interface\s+\w*Resp\w*\s*\{\n[\s\S]*?\n\}/g, "");
  const ไม่ใช้ = [...ประกาศ].filter((k) => {
    const re = new RegExp(`[.?\\[]\\s*['"]?${k}\\b`);
    return !re.test(นอกinterface);
  });
  รายงาน.push({ จอ: p.slice(ROOT.length), เส้น, ประกาศ: ประกาศ.size, ไม่ใช้ });
}

console.log("📋 จออ่านช่องอะไรจากท่อ — **รายการหยาบ ต้องไปดูด้วยตา ห้ามถือเป็นข้อสรุป**\n");
let รวมไม่ใช้ = 0;
for (const r of รายงาน.sort((a, b) => b.ไม่ใช้.length - a.ไม่ใช้.length)) {
  if (!r.ไม่ใช้.length) continue;
  รวมไม่ใช้ += r.ไม่ใช้.length;
  console.log(`${r.จอ}  [${r.เส้น.join(" · ")}]`);
  console.log(`   ประกาศ ${r.ประกาศ} ช่อง · **ไม่พบการใช้ ${r.ไม่ใช้.length}**: ${r.ไม่ใช้.join(", ")}`);
}
console.log(
  `\nสรุป: ไล่ ${รายงาน.length} จอที่มี interface Resp · ช่องที่ไม่พบการใช้รวม ${รวมไม่ใช้}` +
    `\n⚠️ "ไม่พบการใช้" ≠ "ไม่ได้ใช้" — destructure หรือส่งต่อทั้งก้อนจะถูกนับผิด` +
    `\n⇒ เอารายการนี้ไปวางคู่กับ \`?endpoints=1\` ของท่อ จึงจะเทียบได้สองทาง`
);
