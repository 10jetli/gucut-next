// ไล่ล่า "คำกล่าวอ้างเรื่องความสามารถของ ZORT" ทุกจุดในจอ แล้วบังคับให้มันบอกอายุตัวเอง
//
// ทำไมต้องมี (6 ก.ย. 2569): วันเดียวเจอข้อความที่เคยจริงแล้วกลายเป็นเท็จ **3 จุด**
//   · จอกระเป๋าเงิน "404 ทุกเส้น (Wallet · Payment · Receipt)" → โมดูล Payment มีจริง
//   · จอวางแผนสั่งซื้อ "ไม่ผ่านทุกทาง" → ดึงรายชื่อคลังได้
//   · จอวางแผนสั่งซื้อ (รอบสอง) "ทำไม่ได้" → ที่จริงแค่ "ยังไม่พบทาง"
// ทั้งสามจุดเขียนละเอียดและดูน่าเชื่อถือมาก **นั่นคือสิ่งที่ทำให้มันอันตราย**
//
// 🔴 ข้อแตกต่างที่ทำให้ต้องมีตัวตรวจ: **เลขบนจอมีตัวเทียบ** (ยอดไม่ตรงเดี๋ยวมีคนทัก)
//    ส่วน **คำกล่าวอ้างไม่มีตัวเทียบกับอะไรเลย** มันแค่นั่งอยู่ตรงนั้นและถูกเชื่อ
//    ⇒ ตาข่ายที่พึ่ง "คนตั้งใจกลับมาอ่าน" จะพลาดวันที่คนเหนื่อย ⇒ ให้เครื่องไล่แทน
//
// ⚠️ ตัวนี้ **ไม่ทำให้ build ตก** — มันตัดสินไม่ได้ว่าคำไหนจริง รู้แค่ว่าคำไหน "ไม่ได้บอกวันที่"
//    หน้าที่มันคือทำให้คำกล่าวอ้างทุกอันมีวันที่ติดตัว จะได้ตรวจย้อนได้ว่าเก่าแค่ไหน
// ✅ **พิสูจน์แล้วว่าจับได้จริง 6 ก.ย. 2569** — แทรกคอมเมนต์ "ZORT ไม่เปิด API ตัวนี้ ยิงมาแล้ว 404"
//    ที่ไม่มีวันที่ ⇒ ฟ้องถูกต้อง 1 จุด · ถอดออกแล้วกลับมาเขียว
//    ⚠️ ตัวตรวจที่ไม่เคยถูกป้อนของเสีย ให้ผลเขียวที่แปลว่า "ยังไม่เจอ" ไม่ใช่ "ไม่มี"
// 🔴 **อ่านเลขตัวหน้าด้วย ไม่ใช่ดูแค่ "ไม่ได้บอกวันที่ = 0"** (เจอกับตัวเอง 6 ก.ย. 2569)
//    ผมเติมวันที่ลงกลางวลี `ยิงจริงแล้ว` → กลายเป็น `ยิงจริง 6 ก.ย. 2569 แล้ว`
//    ⇒ วลีที่ใช้จับขาดตอน **บรรทัดนั้นหลุดจากการนับไปเลย** และผลออกมาเป็นเขียวสวย
//    ⇒ จำนวนคำกล่าวอ้างลดจาก 15 เหลือ 14 ทั้งที่ไม่ได้ลบข้อความไหนออกเลยสักคำ
//    **นี่คือการปิดปากตัวตรวจ ไม่ใช่การแก้ของ** — เขียวเพราะมองไม่เห็น ไม่ใช่เพราะไม่มีปัญหา
//    ⇒ กติกา: **เลขรวมลดลงเมื่อไหร่ ต้องอธิบายให้ได้ว่าลบคำกล่าวอ้างไหนออก**
//       ลดโดยไม่ได้ตั้งใจ = มีคนเผลอทำให้ตัวตรวจตาบอด
// รันเอง: node scripts/check-claims.mjs
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs'
import { join } from 'node:path'

/* ⚠️ **ตัวกรองต้องแคบ ไม่งั้นตัวตรวจจะถูกเมิน** (บทเรียนจาก check-nav.mjs วันเดียวกัน)
    รอบแรกจับได้ 86 จุด ซึ่งส่วนใหญ่ไม่ใช่คำกล่าวอ้าง:
    · `status: 404` ในไฟล์ API ของเราเอง (คนละความหมายกับ "ZORT ตอบ 404")
    · สำนวน "ยังไม่ได้ทำ ไม่ใช่ทำไม่ได้" ซึ่งเป็นการประกาศสถานะ **ของเราเอง** ไม่ใช่ของ ZORT
    ⇒ บังคับสองเงื่อนไขพร้อมกัน: พูดถึงปลายทางภายนอก **และ** อ้างว่ามันไม่มีความสามารถ */
const TARGET = /(ZORT|Shopee|Lazada|TikTok|Flash|Netlify|Taobao)/i
const CLAIM = /(ไม่เปิด\s*API|ไม่เปิดเส้น|ไม่เปิดช่องทาง|ไม่มี\s*API|ตอบ\s*404|→\s*404|ยิงมาแล้ว|ยิงจริงแล้ว|ไม่พบภายใต้|ยังไม่พบทาง|404 ทุก)/
// หลักฐานว่าบอกอายุตัวเองแล้ว — วันที่แบบไทย (เช่น "6 ก.ย. 2569") หรือปี พ.ศ.
const DATED = /(25[6-9]\d)|(\d{1,2}\s*(ม\.ค\.|ก\.พ\.|มี\.ค\.|เม\.ย\.|พ\.ค\.|มิ\.ย\.|ก\.ค\.|ส\.ค\.|ก\.ย\.|ต\.ค\.|พ\.ย\.|ธ\.ค\.))/

const files = []
function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) walk(p)
    else if (name.endsWith('.tsx') || name.endsWith('.ts')) files.push(p)
  }
}
walk('app')
walk('components')
// ⚠️ ไฟล์ API ของเราเองมี status 404 เต็มไปหมด — คนละเรื่องกับคำกล่าวอ้างเรื่อง ZORT
const skip = (p) => p.startsWith('app/api/')

let total = 0
const undated = []
for (const f of files) {
  if (skip(f)) continue
  const lines = readFileSync(f, 'utf8').split('\n')
  lines.forEach((line, i) => {
    if (!CLAIM.test(line) || !TARGET.test(line)) return
    total++
    // ดูวันที่ในบรรทัดเดียวกัน หรือ 3 บรรทัดรอบ ๆ (คอมเมนต์อธิบายมักอยู่เหนือ)
    const around = lines.slice(Math.max(0, i - 3), i + 4).join(' ')
    if (!DATED.test(around)) undated.push(`${f}:${i + 1}  ${line.trim().slice(0, 96)}`)
  })
}

console.log(`คำกล่าวอ้างเรื่องความสามารถของ ZORT: ${total} จุด · ไม่ได้บอกวันที่ ${undated.length} จุด`)
if (undated.length) {
  console.log('\n⚠️ ไม่มีวันที่กำกับ — ตรวจย้อนไม่ได้ว่าเก่าแค่ไหน:')
  for (const u of undated) console.log('   ' + u)
  console.log('\n   วิธีแก้: เติมวันที่ที่ยิงตรวจจริง หรือถ้าไม่รู้ ให้ไปยิงใหม่แล้วค่อยเขียน')
} else {
  console.log('✅ ทุกคำกล่าวอ้างมีวันที่กำกับ')
}
/* ── กันคนเผลอทำให้ตัวตรวจตาบอด ────────────────────────────────────────
   เก็บ "จำนวนคำกล่าวอ้างครั้งล่าสุด" ไว้ในไฟล์ที่ commit ตามไปด้วย
   ⇒ วันไหนเลขลดโดยไม่ได้ตั้งใจ (แก้ถ้อยคำจนวลีที่ใช้จับขาดตอน) จะมีคนเห็น
   ⚠️ ไฟล์นี้เขียนทับตัวเองเฉพาะตอนเลข **เท่าเดิมหรือมากขึ้น**
      เลขลดแล้วเขียนทับ = ลบหลักฐานทิ้งด้วยมือตัวเอง ⇒ ต้องให้คนมาแก้ไฟล์เอง
   ⚠️ **เลขนี้ไม่ใช่เป้า** ห้ามไล่เพิ่มให้ถึง — มันเป็นแค่หมุดว่า "เมื่อวานมีเท่านี้" */
const BASE = 'scripts/.claims-count'
let base = null
try { base = Number(readFileSync(BASE, 'utf8').trim()) } catch { /* ยังไม่เคยมี */ }
if (base !== null && Number.isFinite(base) && total < base) {
  console.log(`\n🔴 จำนวนคำกล่าวอ้างลดจาก ${base} เหลือ ${total} — **ต้องอธิบายให้ได้ว่าลบอันไหนออก**`)
  console.log('   ถ้าไม่ได้ตั้งใจลบ แปลว่ามีคนแก้ถ้อยคำจนวลีที่ใช้จับขาดตอน ⇒ ตัวตรวจมองไม่เห็นแล้ว')
  console.log(`   ตั้งใจลบจริง → แก้เลขใน ${BASE} เอง (ห้ามให้สคริปต์แก้ให้)`)
} else if (base === null || total > base) {
  writeFileSync(BASE, String(total) + '\n')
}

console.log('\n📌 มีวันที่ ≠ ยังจริง — ทุกครั้งที่ได้ความรู้ใหม่เรื่อง API ของ ZORT')
console.log('   ต้องกลับมาอ่านรายการนี้ทั้งชุด แล้วเทียบกับผลใหม่ทีละอัน')
