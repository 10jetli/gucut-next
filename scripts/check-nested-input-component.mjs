#!/usr/bin/env node
/* ด่าน: ห้ามประกาศ component ที่มีช่องกรอก **ไว้ในตัว component อื่น**
 *
 * 🔴 **ที่มา 18 ก.ย. 2569 — บั๊กที่ผ่านทุกด่านที่เรามี**
 *    จอ `/core/stock/new` และ `/core/stock/[sku]/edit` (ทั้งคู่เขียนของจริงเข้า ZORT)
 *    ประกาศ `const F = ({...}) => (<input .../>)` ไว้ในตัว component
 *    ⇒ ทุกครั้งที่ state เปลี่ยน React เห็นเป็น **ชนิด component ตัวใหม่**
 *      ⇒ ถอด `<input>` เดิมทิ้งแล้วสร้างใหม่ ⇒ **โฟกัสหลุดไปที่ body**
 *    ⇒ พิมพ์ได้ **ตัวอักษรเดียว** · ตัวที่สองเป็นต้นไปไม่เข้าช่องเลย
 *
 *    🔑 ทำไมต้องมีด่านนี้: build ผ่าน · tsc ผ่าน · ด่านอีก 27 ตัวผ่าน · ตัวกวาดจอผ่าน
 *       เพราะ **ไม่มีด่านไหนพิมพ์ลงช่อง** ⇒ บั๊กนี้มองไม่เห็นด้วยวิธีที่เราใช้อยู่ทั้งหมด
 *       (ดูบทเรียน `form-nobody-ever-typed-into`)
 *
 * 🔴 **รอบแรกของด่านนี้ยังหลวมเกินไป — และตัวที่จับได้คือการพิมพ์จริง ไม่ใช่ด่าน**
 *    เดิมมองหาเฉพาะคอมโพเนนต์ซ้อนที่ **มี `<input>` อยู่ในตัวเอง**
 *    แต่จอเพิ่มผู้ติดต่อใช้ตัวห่อที่รับ `children` (input เป็น **ลูก** ไม่ได้อยู่ในตัวห่อ)
 *    ⇒ ด่านเงียบ · แต่ `scripts/ทดสอบพิมพ์ลงช่อง.py` จับได้ในการรันรอบแรก
 *    ⇒ React ถอด **ทั้งต้นไม้ข้างใน** ทิ้งเมื่อชนิดของตัวห่อเปลี่ยน ⇒ input ที่เป็นลูกก็ถูกสร้างใหม่
 *    🔑 **จึงห้ามประกาศคอมโพเนนต์ซ้อนในที่คืน JSX เลย ไม่ว่าจะมี input หรือไม่**
 *       (React บอกไว้เองว่าห้าม · และ "ไม่มี input ตอนนี้" ไม่ได้แปลว่าพรุ่งนี้ไม่มี)
 *
 * ⚠️ ด่านนี้ตรวจ **รูปแบบ** ไม่ได้ตรวจพฤติกรรม ⇒ มันกันการกลับมาของรูปเดิมเท่านั้น
 *    ไม่ได้แปลว่าฟอร์มใช้ได้ — **จอที่มีช่องกรอก ยังต้องมีคนพิมพ์ทดสอบจริงอยู่ดี**
 */
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { ต้องมีของให้ตรวจ } from "./lib/ต้องมีของให้ตรวจ.mjs";

const ราก = ["app", "components"];
const ไฟล์ = [];
const เดิน = (d) => {
  for (const e of readdirSync(d, { withFileTypes: true })) {
    const p = join(d, e.name);
    if (e.isDirectory()) เดิน(p);
    else if (e.name.endsWith(".tsx")) ไฟล์.push(p);
  }
};
for (const r of ราก) เดิน(r);

const ผิด = [];
for (const p of ไฟล์) {
  const บรรทัด = readFileSync(p, "utf8").split("\n");
  บรรทัด.forEach((ln, i) => {
    /* มีช่องว่างนำหน้า = ประกาศซ้อนอยู่ในบล็อกอื่น (ระดับโมดูลจะไม่มีช่องว่าง) */
    const m = ln.match(/^(\s+)(?:const|let)\s+([A-Z][A-Za-z0-9]*)\s*=\s*(?:\(|function\b)/);
    if (!m) return;
    const บล็อก = บรรทัด.slice(i, i + 20).join("\n");
    /* คืน JSX = เป็นคอมโพเนนต์ · ไม่จำกัดว่าต้องมีช่องกรอกอยู่ในตัวเอง (ดูหมายเหตุหัวไฟล์) */
    if (/<[a-zA-Z]/.test(บล็อก)) ผิด.push(`${p}:${i + 1}  ${m[2]}`);
  });
}

ต้องมีของให้ตรวจ(ไฟล์.length, "ตรวจ component ซ้อนใน", 50);

if (ผิด.length) {
  console.error("🛑 เจอ component ประกาศไว้ในตัว component อื่น (React จะสร้างของข้างในใหม่ทุกครั้งที่ state เปลี่ยน):");
  for (const x of ผิด) console.error("   " + x);
  console.error(
    "\n   ⇒ React จะสร้าง <input> ใหม่ทุกครั้งที่ state เปลี่ยน ⇒ **พิมพ์ได้ตัวเดียวแล้วโฟกัสหลุด**" +
      "\n   ⇒ ย้ายไปประกาศระดับโมดูล แล้วส่ง value/onChange เป็น props"
  );
  process.exit(1);
}
console.log(`ตรวจ component ซ้อนใน: ผ่าน (ไล่ ${ไฟล์.length} ไฟล์)`);
