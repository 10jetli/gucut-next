#!/usr/bin/env node
/* คำกล่าวอ้างเรื่อง "ตัวเก็บบิล" ใน lib/vendors.ts ต้องตรงกับของจริง — **รายงานอย่างเดียว**
 * (19 ก.ย. 2569 · ใบ S4)
 *
 * 🔴 ที่มา — และข้อนี้ไฟล์ `lib/vendors.ts` **เตือนไว้เองตั้งแต่ต้น**:
 *    *"⚠️ แก้สคริปต์/cron เมื่อไหร่ ต้องมาแก้ตรงนี้ด้วย ไม่งั้นจอจะโกหก"*
 *    คำเตือนถูกทุกตัวอักษร **และมันเกิดขึ้นจริงตามที่เตือน** 19 ก.ย. 2569:
 *    LINE กับ Meta เก็บบิลไม่ได้ (`AUTH_REQUIRED` เซสชันหลุด) ตั้งแต่ 01:00 น.
 *    แต่ `collect.ปัญหา` ของทั้งสองเจ้า **ว่างเปล่า** ⇒ จอ `/bills` บอกว่า "ปกติ"
 *
 * 🔑 **ช่องว่างเปล่าคือคำกล่าวอ้างชนิดหนึ่ง** — และเป็นชนิดที่หลอกที่สุด
 *    เพราะไฟล์นิยามไว้ว่า "เว้นว่าง = เก็บได้ปกติ" ⇒ **ความเงียบกลายเป็นคำยืนยัน**
 *    และคำยืนยันนั้น **ไม่มีวันที่ ไม่มีหลักฐาน และไม่มีใครต้องรับผิดชอบ**
 *    ⇒ ต่างจากช่องที่มีข้อความ ซึ่งอย่างน้อยยังมีคนเคยพิมพ์มันลงไป
 *
 * 🚫 **ทำไมไม่ทำให้ build ตก** (เกณฑ์ "คนที่เจอ แก้ได้เองไหม")
 *    คนที่ build อยู่บนเครื่องที่ไม่มี `~/bills-cron.log` **แก้ไม่ได้เลย** ⇒ ดังแต่ไม่ตก
 *    และคนที่แก้ได้จริงคือคนที่ไปล็อกอินบน g1 ซึ่งไม่ใช่คนที่กำลัง build
 *
 * ⚠️ **ปลายทางที่ถูกจริง ๆ คือให้ตัวเก็บบิลจดลงสมุดงานตามเวลา** (`POST /api/core?joblog=1`)
 *    แล้วจออ่านจากสมุด ⇒ เลิกพึ่งช่องที่พิมพ์มือทั้งหมด
 *    ด่านนี้เป็น **ตัวชี้หนี้ ไม่ใช่ทางแก้** — เขียนไว้ตรง ๆ กันมีคนอ่านว่าปิดเรื่องแล้ว
 */
import { readFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'
import { homedir } from 'node:os'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
/* 🔑 พาธล็อกรับจาก env ได้ เพื่อให้ **ป้อนล็อกปลอมเข้ามาทดสอบตัวอ่านได้**
   (28 ก.ย. 2569) ล็อกจริงเป็นของ cron บนเครื่อง g1 ⇒ แตะไม่ได้ และห้ามแตะ
   ⇒ ถ้าไม่มีทางป้อนข้อมูล ทางแก้เดียวคือปลูกลงตัวด่านเอง ซึ่งวัดผิดของ
      (ทะเบียนสูตรปลูกของเราปฏิเสธท่านั้นตรง ๆ และมันถูก) */
const LOG = process.env.BILLS_CRON_LOG || join(homedir(), 'bills-cron.log')

/* ── อ่านคำกล่าวอ้างจากทะเบียน ── */
const src = readFileSync(join(ROOT, 'lib/vendors.ts'), 'utf8')
const เจ้า = []
for (const m of src.matchAll(/\{\s*id:\s*'([^']+)'[\s\S]{0,120}?collect:\s*\{([\s\S]*?)\}/g)) {
  const body = m[2]
  const วิธี = body.match(/วิธี:\s*'([^']+)'/)?.[1] ?? ''
  const รายละเอียด = body.match(/รายละเอียด:\s*'([^']*)'/)?.[1] ?? ''
  const ปัญหา = body.match(/ปัญหา:\s*'([^']*)'/)?.[1] ?? null
  เจ้า.push({ id: m[1], วิธี, สคริปต์: รายละเอียด.match(/([a-z0-9-]+\.py)/)?.[1] ?? null, ปัญหา })
}

/* 🔒 อ่านทะเบียนไม่ได้สักเจ้า = ตะแกรงพัง ไม่ใช่ทะเบียนว่าง */
if (เจ้า.length === 0) {
  console.error('🔴 อ่าน collect จาก lib/vendors.ts ไม่ได้สักเจ้า ⇒ **ตะแกรงพัง** ⇒ ไม่ผ่าน')
  process.exit(1)
}

const บนg1 = เจ้า.filter((v) => v.วิธี === 'สคริปต์บน g1')
console.log(`คำกล่าวอ้างตัวเก็บบิล: ${เจ้า.length} เจ้า · เก็บด้วยสคริปต์บน g1 ${บนg1.length} เจ้า`)

if (!existsSync(LOG)) {
  /* 🔑 ไม่มีล็อก = **ตรวจไม่ได้** ไม่ใช่ "ตรงกัน" — ต้องพิมพ์ทุกครั้ง ไม่ใช่เงียบ */
  console.log(`   ⏭️  ไม่มี ${LOG} บนเครื่องนี้ ⇒ **ยังไม่ได้ตรวจ** (ไม่ใช่ตรวจแล้วผ่าน)`)
  console.log('      ⇒ ตรวจได้เฉพาะบน g1 · ปลายทางที่ถูกคือให้ตัวเก็บบิลจดลงสมุด joblog แล้วจออ่านจากสมุด')
  process.exit(0)
}

/* ── อ่านสถานะล่าสุดจริงของแต่ละตัวเก็บ ──
   🔴 **รุ่นแรกอ่านแต่บรรทัดสรุป `◀ … status=`** ⇒ แถวก่อนบ่ายวันนี้ไม่มีช่องนั้น
      ⇒ ตัดสินไม่ได้ 4 จาก 6 เจ้า **ทั้งที่ค่าอยู่ในล็อกแล้ว**
      บรรทัด JSON ที่ตัวเก็บพิมพ์ (`{"status":"AUTH_REQUIRED",...}`) อยู่เหนือบรรทัดสรุปเสมอ
   🔑 นี่คือคลาส **"วัดได้แล้วทิ้งระหว่างทาง"** ที่ฝั่งท่อตั้งชื่อไว้เมื่อค่ำนี้ — และผมทำเองทันที
      ⇒ ของมีอยู่ ไม่ได้ใช้ · แย่กว่า "วัดไม่ได้" เพราะมันดูเหมือนข้อจำกัด ทั้งที่เป็นการต่อท่อขาด */
const ล่าสุด = new Map()
{
  const lines = readFileSync(LOG, 'utf8').split('\n')
  let jsonล่าสุด = null
  for (const ln of lines) {
    const t = ln.trim()
    if (t.startsWith('{') && t.includes('"status"')) {
      try { jsonล่าสุด = JSON.parse(t)?.status ?? null } catch { jsonล่าสุด = null }
      continue
    }
    const m = ln.match(/^\[([\d-]+ [\d:]+)\]\s*◀\s*([a-z0-9-]+)\s*จบ\s*rc=(\d+)(?:\s*·\s*status=(.+))?$/)
    if (!m) continue
    /* ช่อง status บนบรรทัดสรุปมาก่อน (ชัดเจนกว่า) · ไม่มีก็ใช้ JSON ที่เพิ่งอ่านผ่านมา */
    const st = m[4]?.trim() ?? jsonล่าสุด
    ล่าสุด.set(m[2], { เมื่อ: m[1], rc: m[3], status: st ?? null, จาก: m[4] ? 'บรรทัดสรุป' : (jsonล่าสุด ? 'บรรทัด JSON ของตัวเก็บ' : null) })
    jsonล่าสุด = null
  }
}

/* 🔒 **กฎเดียวกับฝั่งทะเบียนข้างบน แต่ก่อนหน้านี้กันไว้ข้างเดียว** (เพิ่ม 28 ก.ย. 2569)
   ข้างบนเขียนไว้ว่า "อ่าน collect ไม่ได้สักเจ้า = ตะแกรงพัง ไม่ใช่ทะเบียนว่าง" ⇒ exit 1
   แต่ **ฝั่งอ่านล็อกไม่มีข้อนี้เลย** ⇒ ถ้าตัวรันเปลี่ยนรูปบรรทัดสรุป (เช่น เติมช่องก่อน `rc=`)
   regex ข้างบนจะไม่ match สักแถว ⇒ ทุกเจ้ากลายเป็น "ตัดสินไม่ได้" ⇒ **เขียว rc=0 ตลอดกาล**
   ⇒ ต้องแยกสองข้อความให้ชัด (ล้มทุกรอบ ≠ ไม่มีรอบเลย):
     · ล็อกมีบรรทัดสรุป (`◀`) แต่แกะไม่ได้สักแถว = **ตัวอ่านของเราพัง** ⇒ แดง
       (เกณฑ์ของไฟล์นี้คือ "คนที่เจอแก้ได้เองไหม" — อันนี้แก้ได้ เพราะเป็นโค้ดเราเอง)
     · ล็อกยังไม่มีบรรทัดสรุปเลย = **ยังไม่มีรอบเก็บบิล** ⇒ ตรวจไม่ได้ ไม่ใช่ผ่าน */
{
  const ดิบ = readFileSync(LOG, 'utf8')
  const มีบรรทัดสรุป = ดิบ.split('\n').some((ln) => ln.includes('◀'))
  if (ล่าสุด.size === 0) {
    if (มีบรรทัดสรุป) {
      console.error(`🔴 ล็อกมีบรรทัดสรุป (\`◀\`) แต่แกะไม่ได้สักแถว ⇒ **ตัวอ่านล็อกของด่านนี้พัง**`)
      console.error('   (รูปแบบบรรทัดสรุปเปลี่ยน หรือ regex ในไฟล์นี้ตรึงไว้แน่นเกินรูปจริง)')
      console.error('   ⇒ ไม่ใช่ "ตัดสินไม่ได้" — ถ้าปล่อยผ่าน ด่านนี้จะเขียวตลอดกาลโดยไม่ตรวจอะไรเลย')
      process.exit(1)
    }
    console.log('   ⏭️  ล็อกยังไม่มีบรรทัดสรุปของรอบเก็บบิลเลย ⇒ **ยังไม่มีรอบ** (ไม่ใช่ตรวจแล้วผ่าน)')
    process.exit(0)
  }
}

let ไม่ตรง = 0, ตัดสินได้ = 0
for (const v of บนg1) {
  const ชื่อ = v.สคริปต์?.replace(/\.py$/, '')
  const จริง = ชื่อ ? ล่าสุด.get(ชื่อ) : null
  if (!จริง) {
    console.log(`   ⏭️  ${v.id}: ไม่มีแถวของ ${ชื่อ ?? '(ไม่รู้ชื่อสคริปต์)'} ในล็อก ⇒ **ตัดสินไม่ได้**`)
    continue
  }
  /* 🔑 สามสถานะ: status=OK (ปกติ) · status อื่น (มีปัญหา) · ไม่มีช่อง status (ล็อกรุ่นเก่า ⇒ ไม่รู้) */
  const มีปัญหาจริง = จริง.status === null ? null : จริง.status !== 'OK'
  const จอบอกว่ามีปัญหา = !!v.ปัญหา
  if (มีปัญหาจริง === null) {
    console.log(`   ⏭️  ${v.id}: แถวล่าสุด (${จริง.เมื่อ}) **ไม่มีช่อง status** ⇒ ตัดสินไม่ได้ (ล็อกรุ่นเก่ากว่าโค้ดที่อ่าน status)`)
    continue
  }
  ตัดสินได้++
  if (มีปัญหาจริง !== จอบอกว่ามีปัญหา) {
    ไม่ตรง++
    if (มีปัญหาจริง) {
      console.log(`⚠️  ${v.id}: ของจริง **${จริง.status}** เมื่อ ${จริง.เมื่อ} (จาก${จริง.จาก}) · แต่ทะเบียนไม่มีช่อง \`ปัญหา\` ⇒ **จอบอกว่าปกติ**`)
    } else {
      console.log(`⚠️  ${v.id}: ของจริงเก็บได้ปกติเมื่อ ${จริง.เมื่อ} · แต่ทะเบียนยังเขียน \`ปัญหา\` ค้างไว้ ⇒ **จอเตือนทั้งที่หายแล้ว**`)
    }
  } else {
    console.log(`   ✅ ${v.id}: ทะเบียนตรงกับของจริง (${จริง.status} · ${จริง.เมื่อ})`)
  }
}

if (ไม่ตรง) {
  console.log(`\n📌 ทะเบียนกับของจริงไม่ตรงกัน ${ไม่ตรง} เจ้า — **นี่คือหนี้ ไม่ใช่ผ่าน**`)
  console.log('   🔑 ช่อง `ปัญหา` ที่เว้นว่าง = คำกล่าวอ้างว่า "ปกติ" ที่ไม่มีวันที่และไม่มีหลักฐาน')
  console.log('   🚫 ไม่ทำให้ build ตกโดยตั้งใจ — คนที่ build อยู่แก้ไม่ได้ (ต้องไปล็อกอินบน g1)')
  console.log('   ⇒ ทางแก้ถาวร: ให้ตัวเก็บบิลจดลงสมุด `POST /api/core?joblog=1` แล้วจออ่านจากสมุด')
} else {
  console.log(`✅ ทะเบียนตรงกับของจริงทุกเจ้าที่ตัดสินได้`)
}
/* 🔑 **เขียวที่ไม่บอกความครอบคลุม ถูกอ่านเป็นยอดรวมเสมอ** — กฎเดิมของเรา
   ⇒ บอกทุกครั้งว่าตัดสินได้กี่เจ้าจากกี่เจ้า ไม่ใช่เฉพาะตอนไม่ตรง */
console.log(`   📏 ตัดสินได้ ${ตัดสินได้} จาก ${บนg1.length} เจ้าที่เก็บด้วยสคริปต์บน g1`)
if (ตัดสินได้ < บนg1.length) {
  console.log(`      ⚠️ อีก ${บนg1.length - ตัดสินได้} เจ้า **ยังไม่ได้ตรวจ** (ไม่ใช่ตรวจแล้วผ่าน)`)
}
