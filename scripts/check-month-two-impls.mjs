#!/usr/bin/env node
/* เกณฑ์เดือนบิลมีสองสำเนา — ด่านนี้เทียบ **พฤติกรรม** ของทั้งคู่ผ่านตารางร่วม
 * (30 ก.ย. 2569 · CEO สั่งข้อ 5 ของทะเบียนหนี้ · ใบ t_mu8i1pu1)
 *
 * 🔴 ทำไมต้องมีสองสำเนา (และปิดหนี้นี้แบบ "ยอมรับ" ไม่ใช่ "แก้"):
 *    `netlify/functions/*.mjs` อิมพอร์ตได้แค่ `./lib-*.mjs` ข้างตัวเอง
 *    **ไม่มีตัวไหนเคยอิมจาก `lib/` ของรีโปที่เป็น TypeScript** ⇒ แชร์โค้ดกันไม่ได้เชิงโครงสร้าง
 *    ⇒ ตระกูล "สำเนาไม่ใช่ของร่วม" ⇒ ถ้าแกล้งว่าแก้ได้ จะได้ด่านที่โกหก
 *
 * 🔑 **เทียบพฤติกรรม ไม่ใช่เทียบข้อความ** (CEO ย้ำข้อนี้ตรง ๆ)
 *    เทียบข้อความในซอร์สจะ **แดงทุกครั้งที่ใครจัดคอมเมนต์ใหม่** (บวกลวง)
 *    และ **เขียวตอนพฤติกรรมเพี้ยนจริง** ถ้าคนเขียน regex คนละรูปที่ให้ผลต่างกัน (ลบลวง)
 *    ⇒ กลับหัวทั้งสองทาง ซึ่งแย่กว่าไม่มีด่าน
 *
 * 🔒 ตารางร่วมอยู่ที่ `lib/billmonth-cases.json` — **แหล่งเดียวของ "ผลที่ควรได้"**
 *    ⚠️ และด่านนี้บังคับว่า **เคสขอบต้องมีอยู่ในตาราง** เพราะไม่งั้นทางที่ง่ายที่สุด
 *       ตอนด่านแดงคือ **ลบเคสออก** แล้วด่านก็เขียวโดยไม่มีอะไรถูกแก้
 *
 * ⚠️ ขอบเขต: ด่านนี้ตอบว่า **สองสำเนาตัดสินเหมือนกันไหม** และ **ตรงกับตารางไหม**
 *    ไม่ได้ตอบว่าเกณฑ์ในตาราง **ถูกสำหรับธุรกิจ** — อย่างหลังเป็นการตัดสินของคน
 *
 * วิธีใช้: node scripts/check-month-two-impls.mjs [--self-test]
 */
import { readFileSync, rmSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { คอมไพล์เพื่อทดสอบ } from './lib/คอมไพล์เพื่อทดสอบ.mjs'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
process.chdir(ROOT)

const ไฟล์ตาราง = 'lib/billmonth-cases.json'
const ฝั่งTS = 'lib/billmonth.ts'
/* ⚠️ ต้องเป็น URL ที่อ้างจาก **ที่ตั้งของไฟล์นี้** ไม่ใช่พาธสัมพัทธ์กับ cwd
   ESM ไม่ใช้ cwd ในการแก้ specifier ⇒ './netlify/...' จะกลายเป็น 'scripts/netlify/...'
   (จับได้ตอนอ่านทวนก่อนรัน — `process.chdir()` ข้างบนหลอกให้คิดว่าพาธสัมพัทธ์ใช้ได้) */
const ฝั่งMJS = new URL('../netlify/functions/lib-billmonth.mjs', import.meta.url)
const ชื่อฝั่งMJS = 'netlify/functions/lib-billmonth.mjs'

/* ── self-test: ตัวควบคุมของตัวด่านเอง ─────────────────────────────────── */
if (process.argv.includes('--self-test')) {
  const เทียบ = (ตาราง, a, b) => {
    const ต่าง = []
    for (const c of ตาราง) {
      const ผลA = a(c.ค่า), ผลB = b(c.ค่า)
      if (ผลA !== c.รับ || ผลB !== c.รับ || ผลA !== ผลB) ต่าง.push({ ...c, ผลA, ผลB })
    }
    return ต่าง
  }
  const ตาราง = [{ ค่า: '2026-01', รับ: true }, { ค่า: '2026-13', รับ: false }]
  const แน่น = (q) => /^\d{4}-(0[1-9]|1[0-2])$/.test(String(q))
  const หลวม = (q) => /^\d{4}-\d{2}$/.test(String(q))
  const เคส = [
    ['สองฝั่งตรงกันและตรงตาราง ⇒ ไม่มีความต่าง', เทียบ(ตาราง, แน่น, แน่น).length === 0, true],
    ['ฝั่งหนึ่งหลวม ⇒ ต้องจับได้', เทียบ(ตาราง, แน่น, หลวม).length === 1, true],
    ['ทั้งสองฝั่งหลวมเหมือนกัน ⇒ **ยังต้องจับได้** (ตรงกันแต่ผิดตาราง)',
      เทียบ(ตาราง, หลวม, หลวม).length === 1, true],
  ]
  let ตก = 0
  for (const [ชื่อ, ได้, ควร] of เคส) {
    const ผ่าน = ได้ === ควร
    if (!ผ่าน) ตก++
    console.log(`  ${ผ่าน ? '✅' : '❌'} ${ชื่อ}`)
  }
  /* 🔑 เคสที่สามคือหัวใจ: ด่านที่เทียบแค่ "สองฝั่งตรงกันไหม" จะเขียว
     ตอนทั้งคู่ผิดพร้อมกัน ⇒ ต้องเทียบกับ **ตาราง** ด้วย ไม่ใช่เทียบกันเอง */
  console.log(ตก ? `🔴 self-test ตก ${ตก} เคส`
    : `🧪 self-test ผ่าน ${เคส.length} เคส (รวมเคส "ทั้งสองฝั่งผิดพร้อมกัน" ซึ่งด่านที่เทียบกันเองจะพลาด)`)
  process.exit(ตก ? 1 : 0)
}

const ตาราง = JSON.parse(readFileSync(ไฟล์ตาราง, 'utf8'))
const เคส = ตาราง['เคส'] ?? []
const ขอบบังคับ = ตาราง['เคสขอบที่ด่านบังคับให้มี'] ?? []
if (เคส.length === 0) {
  console.error(`🔴 ตาราง ${ไฟล์ตาราง} ว่าง ⇒ ไม่ได้เทียบอะไรเลย`)
  process.exit(1)
}
/* 🔒 กันทางออกที่ง่ายที่สุดตอนด่านแดง: ลบเคสออกจากตาราง */
const ขาดขอบ = ขอบบังคับ.filter((ค) => !เคส.some((c) => c.ค่า === ค))
if (ขาดขอบ.length) {
  console.error(`🔴 ตารางขาดเคสขอบที่บังคับไว้: ${ขาดขอบ.join(' · ')}`)
  console.error('   ⇒ ลบเคสขอบออกแล้วด่านจะเขียวโดยไม่มีอะไรถูกแก้ ⇒ ห้ามลบ')
  process.exit(1)
}

let ที่ออก
try {
  const ผล = คอมไพล์เพื่อทดสอบ({ ไฟล์: [ฝั่งTS], ปลอม: {} })
  ที่ออก = ผล.ที่ออก
  const { เดือนบิลถูกต้อง: ts, เกณฑ์เดือนบิล: ข้อความTS } = await import(ผล.พาธของ(ฝั่งTS))
  const { เดือนบิลถูกต้อง: mjs, เกณฑ์เดือนบิล: ข้อความMJS } = await import(ฝั่งMJS)

  const ต่าง = []
  for (const c of เคส) {
    const ผลTS = ts(c.ค่า), ผลMJS = mjs(c.ค่า)
    if (ผลTS !== c.รับ || ผลMJS !== c.รับ) ต่าง.push({ ...c, ผลTS, ผลMJS })
  }

  console.log(`เกณฑ์เดือนบิล — เทียบ **พฤติกรรม** ของสองสำเนาผ่านตารางร่วม ${เคส.length} เคส`)
  console.log(`   ฝั่ง Next : ${ฝั่งTS}`)
  console.log(`   ฝั่ง netlify: ${ชื่อฝั่งMJS}`)
  console.log(`   ตารางร่วม : ${ไฟล์ตาราง} (เคสขอบที่ห้ามลบ ${ขอบบังคับ.length} เคส · ครบ)`)

  if (ต่าง.length) {
    console.error(`\n🔴 สองสำเนาตัดสินไม่ตรงตาราง ${ต่าง.length} เคส`)
    for (const d of ต่าง) {
      console.error(`   · ${JSON.stringify(d.ค่า)} ⇒ ควรได้ ${d.รับ} · TS ได้ ${d.ผลTS} · netlify ได้ ${d.ผลMJS}`)
      console.error(`     เหตุที่เคสนี้อยู่ในตาราง: ${d.ทำไม}`)
    }
    console.error('\n⇒ แก้ให้ตรงกัน **ทั้งสองไฟล์** · ห้ามแก้ตารางให้เข้ากับโค้ด')
    process.exit(1)
  }

  /* ข้อความเกณฑ์เป็น "ของที่คนเห็น" ⇒ ต่างกันได้โดยไม่ผิดพฤติกรรม แต่ควรรู้
     ⇒ **เตือน ไม่ทำให้ตก** — ไม่งั้นด่านจะแดงเพราะเรื่องถ้อยคำ ซึ่งเป็นการตัดสินของคน */
  if (ข้อความTS !== ข้อความMJS) {
    console.log(`\n🟠 ข้อความเกณฑ์ของสองสำเนาไม่เหมือนกัน (เตือน ไม่ทำให้ตก)`)
    console.log(`   TS      : ${JSON.stringify(ข้อความTS)}`)
    console.log(`   netlify : ${JSON.stringify(ข้อความMJS)}`)
    console.log(`   ⇒ พฤติกรรมตรงกันแล้ว แต่คนที่เห็นข้อความจากสองทางจะได้คำต่างกัน`)
  }
  console.log(`\n✅ สองสำเนาตัดสินเหมือนกัน และตรงกับตารางร่วมทุกเคส`)
  console.log(`   ⚠️ เขียวของด่านนี้ = "สองสำเนาไม่เพี้ยนจากกัน" **ไม่ใช่** "เกณฑ์ถูกสำหรับธุรกิจ"`)
  console.log(`      อย่างหลังเป็นการตัดสินของคน และอยู่ในช่อง "ทำไม" ของแต่ละเคสในตาราง`)
} finally {
  if (ที่ออก) rmSync(ที่ออก, { recursive: true, force: true })
}
