#!/usr/bin/env node
/* ด่านก่อน build: **ตารางงานตามเวลาบนจอ ต้องตรงกับ cron จริงในซอร์สท่อ**
 *
 * 🔴 **ที่มา 18 ก.ย. 2569** — ฝั่งท่อลด `backup-run` จากทุกชั่วโมงเป็นทุก 6 ชั่วโมง
 *    แล้วจอเรายังเขียนว่า "ทุกชั่วโมง (นาทีที่ 40)" และบอกวิธีตรวจว่า
 *    "เวลาสำรองล่าสุดต้องไม่เกิน 1 ชั่วโมง" ⇒ **จอจะบอกว่างานตายทุกวันทั้งที่ปกติ**
 *    แล้วคนจะเลิกอ่านจอสถานะ ซึ่งแย่กว่าไม่มีจอสถานะเลย
 *
 * 🔴 **และตอนกวาดครั้งแรกเจอของที่ใหญ่กว่า**: ท่อมีงานตามเวลา 15 ตัว แต่จอมีแค่ 8 แถว
 *    ที่หายไปรวม **ตัวดันสต็อกขึ้นมาร์เก็ตเพลสทั้งสามตัว** ซึ่งถ้าตายเงียบ = ขายเกินสต็อกจริง
 *    ⇒ จอที่มีไว้ตอบว่า "มีอะไรวิ่งเองบ้าง ถ้าตายจะรู้ได้ยังไง" ตอบไม่ได้ครึ่งหนึ่ง
 *
 * 🔑 ด่านนี้ตรวจสองข้อ
 *    ① ทุกฟังก์ชันที่มี `schedule:` ในซอร์สท่อ ต้องมีแถวในตารางบนจอ
 *    ② ค่า cron ในแถวนั้น ต้องตรงกับซอร์สท่อ **ตัวอักษรต่อตัวอักษร**
 *
 * ⚠️ **ไม่ตรวจข้อความ `when` (เวลาไทย) ให้** — แปลจาก UTC ด้วยมือ เครื่องตรวจแทนไม่ได้
 *    ⇒ แก้ `cron` แล้วต้องแก้ `when` เองเสมอ · ด่านนี้บอกขอบเขตตัวเองไว้ตรงนี้
 * ⚠️ ไม่มี ../gucut-web ⇒ ข้ามแบบมีเสียง (พิมพ์ว่ายังไม่ได้ตรวจ) ไม่ใช่เงียบแล้วผ่าน
 */
import { readdirSync, readFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = new URL('..', import.meta.url).pathname
const PIPE = join(ROOT, '..', 'gucut-web')
const FUNCS = join(PIPE, 'netlify', 'functions')
const จอ = join(ROOT, 'app', 'core', 'settings-jobs', 'page.tsx')

/** งานตามเวลาที่ **ตั้งใจไม่ใส่ในตาราง** — ต้องเขียนเหตุผลทุกบรรทัด */
const ยกเว้น = {
  // ยังไม่มี — ถ้าจะใส่ ต้องบอกว่าใครตัดสินว่าไม่ต้องให้คนเห็น และเพราะอะไร
}

if (!existsSync(FUNCS)) {
  console.log('⏭️  ข้ามด่านตารางงานตามเวลา: ไม่มี ../gucut-web ในเครื่องนี้ ⇒ **ยังไม่ได้ตรวจ** (ไม่ใช่ตรวจแล้วผ่าน)')
  process.exit(0)
}

/* ① อ่าน cron จริงจากซอร์สท่อ */
const ท่อ = new Map()
for (const name of readdirSync(FUNCS)) {
  if (!name.endsWith('.mjs')) continue
  const m = /schedule:\s*"([^"]+)"/.exec(readFileSync(join(FUNCS, name), 'utf8'))
  if (m) ท่อ.set(`netlify/functions/${name}`, m[1])
}

/* ② อ่านแถวจากจอ — จับคู่ `cron:` กับ `src:` ในบล็อกเดียวกัน
   ⚠️ ช่อง `src` ของบางแถวมีข้อความต่อท้าย (เช่น "· netlify/lib/…" หรือ "(repo นี้)")
      ⇒ เทียบด้วย "ขึ้นต้นด้วยชื่อไฟล์" ไม่ใช่เท่ากันเป๊ะ ไม่งั้นจะฟ้องผิดตัวทุกแถวที่มีหมายเหตุ */
const src = readFileSync(จอ, 'utf8')
const แถว = []
for (const m of src.matchAll(/cron:\s*'([^']+)'[\s\S]{0,400}?src:\s*'([^']+)'/g)) {
  แถว.push({ cron: m[1], src: m[2] })
}

const ขาด = []
const ไม่ตรง = []
for (const [ไฟล์, cron] of ท่อ) {
  if (ยกเว้น[ไฟล์]) continue
  const hit = แถว.find((r) => r.src === ไฟล์ || r.src.startsWith(`${ไฟล์} `))
  if (!hit) { ขาด.push(`${ไฟล์}  (cron ${cron})`); continue }
  if (hit.cron !== cron) ไม่ตรง.push(`${ไฟล์}  จอเขียน "${hit.cron}" · ท่อจริง "${cron}"`)
}

console.log(`ตรวจตารางงานตามเวลา: ท่อมี ${ท่อ.size} งาน · จอมี ${แถว.length} แถว`)
if (ขาด.length || ไม่ตรง.length) {
  if (ขาด.length) {
    console.error('\n🔴 งานตามเวลาที่วิ่งอยู่จริง แต่ไม่มีในตารางบนจอ')
    for (const x of ขาด) console.error('   ' + x)
    console.error('   ⚠️ จอนี้คือที่เดียวที่บอกว่า "ถ้ามันตายเงียบจะรู้ได้ยังไง" — ไม่มีแถว = ไม่มีใครรู้ว่าต้องเฝ้า')
  }
  if (ไม่ตรง.length) {
    console.error('\n🔴 ตาราง cron บนจอไม่ตรงกับซอร์สท่อ')
    for (const x of ไม่ตรง) console.error('   ' + x)
    console.error('   ⚠️ อาการ: จอบอกว่างานตายทุกวันทั้งที่ปกติ (หรือแย่กว่า: เงียบทั้งที่ตายจริง)')
    console.error('   ⚠️ แก้ `cron` แล้ว **ต้องแก้ `when` (เวลาไทย) และเกณฑ์เตือนในจอที่เกี่ยวข้องด้วย** — ด่านนี้ตรวจให้ไม่ได้')
  }
  process.exit(1)
}
console.log('✅ ทุกงานตามเวลาในซอร์สท่อ มีแถวบนจอ และ cron ตรงกัน')
