#!/usr/bin/env node
/* ด่านก่อน build: **ตารางงานตามเวลาบนจอ ต้องตรงกับ cron จริงในซอร์สท่อ**
 *
 * 🔴 **ที่มา 18 ก.ย. 2569** — ฝั่งท่อลด `backup-run` จากทุกชั่วโมงเป็นทุก 6 ชั่วโมง
 *    แล้วจอเรายังเขียนว่า "ทุกชั่วโมง (นาทีที่ 40)" และบอกวิธีตรวจว่า
 *    "เวลาสำรองล่าสุดต้องไม่เกิน 1 ชั่วโมง" ⇒ **จอจะบอกว่างานตายทุกวันทั้งที่ปกติ**
 *    แล้วคนจะเลิกอ่านจอสถานะ ซึ่งแย่กว่าไม่มีจอสถานะเลย
 *
 * 🔴 **และตอนกวาดครั้งแรกเจอของที่ใหญ่กว่า**: ท่อมีงานตามเวลา 15 ตัว แต่จอมีแค่ 8 แถว
 *    ที่หายไปรวม **ตัวดันสต็อกขึ้นมาร์เก็ตเพลสทั้งสามตัว** ซึ่งถ้าตายเงียบ = ขายเกินสต็อกจริง
 *    ⇒ จอที่มีไว้ตอบว่า "มีอะไรวิ่งเองบ้าง ถ้าตายจะรู้ได้ยังไง" ตอบไม่ได้ครึ่งหนึ่ง
 *
 * 🔑 ด่านนี้ตรวจสามข้อ (ข้อ ③ เพิ่ม 18 ก.ย. 2569 หลังฝั่งท่อทักว่าตรวจทิศเดียว)
 *    ① ทุกฟังก์ชันที่มี `schedule:` ในซอร์สท่อ ต้องมีแถวในตารางบนจอ
 *    ② ค่า cron ในแถวนั้น ต้องตรงกับซอร์สจริง **ตัวอักษรต่อตัวอักษร**
 *    ③ **ทิศกลับ**: ทุกแถวบนจอต้องมีงานจริงรองรับ — ไม่งั้นจอโฆษณางานที่ไม่มีอยู่
 *       ⚠️ แยกสองกอง: แถวของท่อ เทียบกับ ../gucut-web · แถวที่เขียนว่า "(repo นี้)" เทียบกับ repo นี้
 *          (ถ้าไม่แยก ด่านจะฟ้อง 4 แถวของ repo นี้ทุกครั้ง จนมีคนปิดด่านทิ้ง)
 *
 * ⚠️ **ไม่ตรวจข้อความ `when` (เวลาไทย) ให้** — แปลจาก UTC ด้วยมือ เครื่องตรวจแทนไม่ได้
 *    ⇒ แก้ `cron` แล้วต้องแก้ `when` เองเสมอ · ด่านนี้บอกขอบเขตตัวเองไว้ตรงนี้
 * ⚠️ ไม่มี ../gucut-web ⇒ ข้ามแบบมีเสียง (พิมพ์ว่ายังไม่ได้ตรวจ) ไม่ใช่เงียบแล้วผ่าน
 */
import { readdirSync, readFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = new URL('..', import.meta.url).pathname
const PIPE = join(ROOT, '..', 'gucut-web')
const FUNCS = join(PIPE, 'netlify', 'functions')
const จอ = join(ROOT, 'app', 'core', 'settings-jobs', 'page.tsx')

/** งานตามเวลาที่ **ตั้งใจไม่ใส่ในตาราง** — ต้องเขียนเหตุผลทุกบรรทัด */
const ยกเว้น = {
  // ยังไม่มี — ถ้าจะใส่ ต้องบอกว่าใครตัดสินว่าไม่ต้องให้คนเห็น และเพราะอะไร
}

/* 🔴 **เดิมด่านนี้ข้ามตัวเองเมื่อไม่มี `../gucut-web`** — ซึ่งบนเครื่อง build ของ Netlify
   **ไม่มีเรโปนั้นเสมอ** ⇒ ด่านนี้ไม่เคยวิ่งตอน build จริงเลยสักครั้ง
   มันประกาศว่า "ยังไม่ได้ตรวจ" ซึ่งซื่อสัตย์ **แต่พูดใน log ที่ไม่มีใครอ่าน ⇒ เท่ากับไม่มีด่าน**
   ⇒ ถอยไปใช้ **สำเนาสารบัญ** `lib/pipe-snapshot.json` (สร้างด้วย `scripts/ดึงสารบัญท่อ.mjs`)
   ⚠️ สำเนา **ไม่ใช่แหล่งความจริง** ⇒ ต้องบอกทุกครั้งว่าเทียบกับของวันไหน และเก่าเกินเกณฑ์ต้องเตือน
      (เกณฑ์อยู่ในไฟล์สำเนาเอง ไม่ใช่ในด่าน — เลขเกณฑ์ต้องมีแหล่งเดียว) */
function จากสำเนา() {
  const f = join(ROOT, 'lib', 'pipe-snapshot.json')
  if (!existsSync(f)) return null
  try {
    const j = JSON.parse(readFileSync(f, 'utf8'))
    const jobs = j?.crontable?.jobs
    if (!Array.isArray(jobs) || !jobs.length) return null
    const m = new Map()
    for (const r of jobs) {
      if (typeof r?.file === 'string' && typeof r?.cron === 'string') m.set(r.file.split('/').pop(), r.cron)
    }
    return m.size ? { ตาราง: m, ดึงเมื่อ: j.ดึงเมื่อ, ท่อสร้างเมื่อ: j.ท่อสร้างเมื่อ, เกิน: Number(j.เตือนเมื่อเกินวัน) || 7 } : null
  } catch { return null }
}

let แหล่ง = 'ซอร์สท่อข้างบ้าน (../gucut-web)'
let สำเนา = null
if (!existsSync(FUNCS)) {
  สำเนา = จากสำเนา()
  if (!สำเนา) {
    console.error('🔴 ไม่มีทั้ง ../gucut-web และ lib/pipe-snapshot.json ⇒ **ตรวจไม่ได้** (ไม่ใช่ผ่าน)')
    console.error('   ⇒ รัน `node scripts/ดึงสารบัญท่อ.mjs` บนเครื่องที่มีคีย์ แล้ว commit ไฟล์สำเนา')
    process.exit(1)
  }
  const วัน = (Date.now() - Date.parse(สำเนา.ดึงเมื่อ)) / 86400000
  แหล่ง = `สำเนาสารบัญ (ดึงเมื่อ ${String(สำเนา.ดึงเมื่อ).slice(0, 10)} · ท่อสร้างเมื่อ ${String(สำเนา.ท่อสร้างเมื่อ ?? '-').slice(0, 10)})`
  /* เก่าเกินเกณฑ์ ⇒ **เตือน ไม่ fail** — ด่านที่ fail เพราะสำเนาเก่า จะถูกปิดทิ้งในวันที่คนรีบ */
  if (Number.isFinite(วัน) && วัน > สำเนา.เกิน) {
    console.log(`⚠️ สำเนาสารบัญเก่า ${Math.floor(วัน)} วัน (เกณฑ์ ${สำเนา.เกิน} วัน) ⇒ ของใหม่ฝั่งท่อจะยังไม่ถูกตรวจ`)
    console.log('   ⇒ รัน `node scripts/ดึงสารบัญท่อ.mjs` แล้ว commit — **นี่คือคำเตือน ไม่ใช่ความล้มเหลว**')
  }
}
/* ③ ของ CEO: ห้ามให้สำเนาเป็นหลักฐานว่า "ครบ" — เขียนออกมาทุกครั้งว่าเทียบกับอะไร */
console.log(`ตารางงานตามเวลา: เทียบกับ ${แหล่ง}`)

/** อ่าน `schedule:` จากโฟลเดอร์ฟังก์ชันหนึ่งโฟลเดอร์ ⇒ Map<ชื่อไฟล์, cron> */
function อ่านตาราง(dir) {
  const out = new Map()
  if (!existsSync(dir)) return out
  for (const name of readdirSync(dir)) {
    if (!name.endsWith('.mjs')) continue
    const m = /schedule:\s*"([^"]+)"/.exec(readFileSync(join(dir, name), 'utf8'))
    if (m) out.set(name, m[1])
  }
  return out
}

/* ① cron จริงของ **ท่อ** และของ **repo จอเอง** — สองกองคนละที่ ห้ามปนกัน
   (ฝั่งท่อทักเอง 18 ก.ย. 2569: จอมี 4 แถวที่เป็นงานของ repo จอ ไม่ใช่ของท่อ
    ⇒ ทิศกลับต้องแยกกอง ไม่งั้นด่านจะฟ้อง 4 แถวนี้ทุกครั้งจนมีคนปิดด่านทิ้ง) */
const ท่อดิบ = สำเนา ? สำเนา.ตาราง : อ่านตาราง(FUNCS)
const ท่อ = new Map([...ท่อดิบ].map(([n, c]) => [`netlify/functions/${n}`, c]))
const จอเอง = อ่านตาราง(join(ROOT, 'netlify', 'functions'))

/* ② อ่านแถวจากจอ — จับคู่ `cron:` กับ `src:` ในบล็อกเดียวกัน
   ⚠️ ช่อง `src` ของบางแถวมีข้อความต่อท้าย (เช่น "· netlify/lib/…" หรือ "(repo นี้)")
      ⇒ เทียบด้วย "ขึ้นต้นด้วยชื่อไฟล์" ไม่ใช่เท่ากันเป๊ะ ไม่งั้นจะฟ้องผิดตัวทุกแถวที่มีหมายเหตุ */
const src = readFileSync(จอ, 'utf8')
const แถว = []
for (const m of src.matchAll(/cron:\s*'([^']+)'[\s\S]{0,400}?src:\s*'([^']+)'/g)) {
  แถว.push({ cron: m[1], src: m[2] })
}

/* 🔴 **เขียวเพราะไม่มีข้อมูล ห้ามเกิด** (ฝั่งท่อเพิ่งโดนกับตัวเองวันนี้:
   สกัดชื่อไฟล์ด้วย regex ที่หาคำพูดคู่ แต่จอใช้คำพูดเดี่ยว ⇒ ได้ 0 แถว
   แล้วสคริปต์พิมพ์ว่า "ทุกแถวชี้ไปที่งานที่มีจริง" ซึ่งเป็นเขียวเพราะไม่มีข้อมูล)
   ⇒ ตัวตรวจที่ไม่มีข้อมูล ต้องตอบว่า **ตรวจไม่ได้** ไม่ใช่ตอบว่าผ่าน */
if (ท่อ.size === 0) {
  console.error('🔴 อ่าน schedule จากซอร์สท่อไม่ได้เลยสักตัว — **ตรวจไม่ได้** (ไม่ใช่ผ่าน)')
  console.error('   เช็คว่ารูปแบบ `schedule: "…"` ในท่อเปลี่ยนไปหรือเปล่า')
  process.exit(1)
}

const ขาด = []
const ไม่ตรง = []
const เกิน = []
for (const [ไฟล์, cron] of ท่อ) {
  if (ยกเว้น[ไฟล์]) continue
  const hit = แถว.find((r) => r.src === ไฟล์ || r.src.startsWith(`${ไฟล์} `))
  if (!hit) { ขาด.push(`${ไฟล์}  (cron ${cron})`); continue }
  if (hit.cron !== cron) ไม่ตรง.push(`${ไฟล์}  จอเขียน "${hit.cron}" · ท่อจริง "${cron}"`)
}

/* ③ **ทิศกลับ: แถวบนจอที่ไม่มีงานจริงรองรับ** = จอโฆษณางานที่ไม่มีอยู่
   แยกสองกอง: แถวที่ชี้ไฟล์ของท่อ (เทียบกับ ท่อ) · แถวที่เขียนว่า "(repo นี้)" (เทียบกับ จอเอง) */
for (const r of แถว) {
  /* ⚠️ **ห้ามใช้ `\w` จับชื่อไฟล์** — มันไม่ครอบอักษรไทย
     เจอตอนปลูกบั๊กพิสูจน์ด่านนี้เอง 18 ก.ย. 2569: ตั้งชื่อไฟล์ปลอมเป็นภาษาไทย
     ⇒ สกัดชื่อไม่ได้ ⇒ `continue` ⇒ **ด่านเงียบ** ทั้งที่ควรฟ้อง
     ⇒ คลาสเดียวกับที่ฝั่งท่อโดน (regex หาคำพูดคู่ แต่ของจริงใช้คำพูดเดี่ยว)
     ⇒ จับแบบ "อะไรก็ได้ที่ไม่ใช่ช่องว่าง/คั่น แล้วจบด้วย .mjs" */
  const เต็ม = (/([^\s'"·]+\.mjs)/.exec(r.src) || [])[1]
  /* ⚠️ กองเทียบเก็บ **ชื่อไฟล์ล้วน** ⇒ ต้องตัดโฟลเดอร์ออกก่อน
     (รอบแรกลืมตัด ⇒ ด่านฟ้องผิดตัว 3 แถวที่ถูกต้องอยู่แล้ว — ด่านที่ฟ้องผิดตัวพาคนไปแก้ของที่ไม่ได้พัง) */
  const ชื่อไฟล์ = เต็ม ? เต็ม.split('/').pop() : undefined
  if (!ชื่อไฟล์) continue                 // แถวที่ไม่ได้ชี้ไฟล์ .mjs ⇒ ไม่ตัดสิน
  const เป็นของจอ = /repo นี้/.test(r.src)
  const กอง = เป็นของจอ ? จอเอง : ท่อดิบ
  if (เป็นของจอ && จอเอง.size === 0) continue   // อ่านของ repo จอไม่ได้ ⇒ ไม่ตัดสิน (ห้ามเดา)
  if (!กอง.has(ชื่อไฟล์)) {
    เกิน.push(`${ชื่อไฟล์}  จอเขียน cron "${r.cron}" แต่${เป็นของจอ ? 'ใน repo นี้' : 'ในซอร์สท่อ'}ไม่มีงานตามเวลาชื่อนี้`)
  }
}

console.log(`ตรวจตารางงานตามเวลา: ท่อมี ${ท่อ.size} งาน · repo นี้มี ${จอเอง.size} งาน · จอมี ${แถว.length} แถว`)
if (ขาด.length || ไม่ตรง.length || เกิน.length) {
  if (ขาด.length) {
    console.error('\n🔴 งานตามเวลาที่วิ่งอยู่จริง แต่ไม่มีในตารางบนจอ')
    for (const x of ขาด) console.error('   ' + x)
    console.error('   ⚠️ จอนี้คือที่เดียวที่บอกว่า "ถ้ามันตายเงียบจะรู้ได้ยังไง" — ไม่มีแถว = ไม่มีใครรู้ว่าต้องเฝ้า')
  }
  if (ไม่ตรง.length) {
    console.error('\n🔴 ตาราง cron บนจอไม่ตรงกับซอร์สท่อ')
    for (const x of ไม่ตรง) console.error('   ' + x)
    console.error('   ⚠️ อาการ: จอบอกว่างานตายทุกวันทั้งที่ปกติ (หรือแย่กว่า: เงียบทั้งที่ตายจริง)')
    console.error('   ⚠️ แก้ `cron` แล้ว **ต้องแก้ `when` (เวลาไทย) และเกณฑ์เตือนในจอที่เกี่ยวข้องด้วย** — ด่านนี้ตรวจให้ไม่ได้')
  }
  if (เกิน.length) {
    console.error('\n🔴 แถวบนจอที่ไม่มีงานตามเวลารองรับแล้ว — จอโฆษณางานที่ไม่มีอยู่จริง')
    for (const x of เกิน) console.error('   ' + x)
    console.error('   ⚠️ อาการ: คนอ่านจอเชื่อว่ามีของวิ่งอยู่ แล้วไม่ไปหาสาเหตุตอนของไม่มา')
    console.error('   วิธีแก้: ลบแถวนั้น หรือถ้างานย้ายที่ ให้แก้ช่อง src ให้ตรงของจริง')
  }
  process.exit(1)
}
console.log('✅ ตรงกันสองทาง: ทุกงานในซอร์สมีแถวบนจอ · ทุกแถวบนจอมีงานจริงรองรับ · cron ตรงกัน')
