/* โหลดฟังก์ชันบริสุทธิ์จากไฟล์ `.ts` มาใช้ในเทส `.mjs` โดยไม่ต้องติดตั้ง ts-node/tsx
 * (19 ก.ย. 2569 · รวมสำเนาที่เกิดขึ้นสองที่ — `ชื่อซ้ำ.test.mjs` และ `dupcheck-verdict.test.mjs`)
 *
 * 🔑 ทำไมต้องรวม: บทเรียนของทีม `thirty-copies-of-the-same-helper`
 *    สำเนาที่สองคือจุดที่ต้องรวม ไม่ใช่สำเนาที่สิบ — เพราะตอนสองสำเนายังจำได้ว่ามีที่ไหนบ้าง
 *
 * ⚠️ **ข้อจำกัดที่ต้องรู้ก่อนใช้ (ประกาศจุดบอดของตัวเอง)**
 *    นี่คือการ **ถอดชนิดด้วยข้อความ** ไม่ใช่คอมไพเลอร์ ⇒ ครอบเฉพาะรูปที่ใส่ไว้
 *    ⇒ ใช้ได้กับ **ฟังก์ชันบริสุทธิ์ที่ไม่มี import** เท่านั้น (ไฟล์ที่ import ของอื่นจะพังทันที)
 *    ✅ แต่มันพัง **เสียงดัง** (import โยน SyntaxError) ไม่ใช่พังเงียบ ⇒ ยอมรับได้
 *       ⇒ ถ้าวันหนึ่งมีคนเติมชนิดรูปใหม่เข้าไฟล์ต้นทาง เทสจะตกพร้อมข้อความที่ชี้มาที่นี่
 */
import { readFileSync } from 'node:fs'

/** ถอดชนิดพื้นฐานที่เจอบ่อย — รูปเฉพาะไฟล์ให้ส่งมาทาง `แทนที่` */
const ถอดพื้นฐาน = (s) =>
  s
    .replace(/export type[\s\S]*?(?=\n\n|\nexport |\n\/\*)/g, '')   // ประกาศชนิดทั้งก้อน
    .replace(/export type[^\n]*\n/g, '')                             // ประกาศชนิดบรรทัดเดียว
    .replace(/\)\s*:\s*[^{\n]+\{/g, ') {')                           // ชนิดของค่าที่คืน
    /* ชนิดของตัวแปรในฟังก์ชัน — `const เหตุ: เหตุที่สรุปไม่ได้[] = []`
       (รองรับชื่อภาษาไทย · ถ้ารูปไหนไม่ครอบ ตัวช่วยจะพังเสียงดังพร้อมบอกให้เติม) */
    .replace(/\b(const|let)\s+([\w$\u0E00-\u0E7F]+)\s*:\s*[^=\n]+=/g, '$1 $2 =')

/**
 * @param {URL|string} ที่อยู่ ไฟล์ .ts ต้นทาง
 * @param {[RegExp,string][]} [แทนที่] คู่แทนที่เพิ่มเติมสำหรับชนิดเฉพาะไฟล์นั้น
 * @returns {Promise<any>} โมดูลที่ import ได้แล้ว
 */
export async function โหลดโมดูลจากTS(ที่อยู่, แทนที่ = []) {
  let src = ถอดพื้นฐาน(readFileSync(ที่อยู่, 'utf8'))
  for (const [จาก, เป็น] of แทนที่) src = src.replace(จาก, เป็น)
  if (/^\s*import\s/m.test(src)) {
    throw new Error(`โหลดโมดูลจากTS: ${ที่อยู่} มี import ⇒ ตัวช่วยนี้ใช้ได้เฉพาะไฟล์ที่ไม่มี import`)
  }
  try {
    return await import('data:text/javascript;base64,' + Buffer.from(src).toString('base64'))
  } catch (e) {
    throw new Error(
      `โหลดโมดูลจากTS: แปลง ${ที่อยู่} แล้ว import ไม่ผ่าน — น่าจะมีรูปของชนิดที่ตัวถอดยังไม่รู้จัก\n`
      + `เพิ่มคู่แทนที่ในเทสนั้น หรือเพิ่มรูปพื้นฐานที่ scripts/lib/โหลดโมดูลจากTS.mjs\n`
      + `ต้นเหตุ: ${e?.message ?? e}`
    )
  }
}
