import { readFileSync } from 'node:fs'

export const ความสามารถภายนอก = [
  ['@netlify/blobs', /from\s+['"]@netlify\/blobs['"]/],
  ['node:fs (เขียนไฟล์)', /from\s+['"](node:)?fs['"]/],
  ['ฐานข้อมูล', /from\s+['"](better-sqlite3|@cloudflare\/d1|pg|mysql2)['"]/],
  ['googleapis', /from\s+['"]googleapis?['"]/],
]
/** fetch ที่ไม่ใช่ GET — เรียกออกไปเปลี่ยนของข้างนอก · ชื่อ `fetch` เป็นของ runtime เปลี่ยนไม่ได้ */
export const fetchที่เขียน = /method:\s*['"](POST|PUT|DELETE|PATCH)['"]/
/** ⚠️ ชั้นที่อ่อน — **มาจากชื่อ** ⇒ ป้ายต้องบอกให้รู้ว่าอ่อน */
export const ชื่อที่ฟังดูเขียน = /\b(setJSON|save[A-Z฀-๿]|upsert|put[A-Z]|insert|delete[A-Z]|บันทึก|เขียน)/
export const วิธีที่เขียน = /export\s+async\s+function\s+(POST|PUT|DELETE|PATCH)\b/

const แคชอ่านไฟล์ = new Map()
export const เนื้อไฟล์ = (พาธ) => {
  if (!พาธ) return ''
  if (!แคชอ่านไฟล์.has(พาธ)) {
    try { แคชอ่านไฟล์.set(พาธ, readFileSync(พาธ, 'utf8')) } catch { แคชอ่านไฟล์.set(พาธ, '') }
  }
  return แคชอ่านไฟล์.get(พาธ)
}

/** โมดูลของเราเองที่ไฟล์นี้อิมเข้ามา (รูป `@/lib/x` หรือ `./x`) ⇒ คืนพาธที่เดาว่าเป็นไฟล์นั้น */
export const โมดูลของเราที่อิม = (เนื้อ, ของไฟล์) => {
  const ออก = []
  for (const m of เนื้อ.matchAll(/from\s+['"](@\/[^'"]+|\.[^'"]+)['"]/g)) {
    const ระบุ = m[1]
    const ฐาน = ระบุ.startsWith('@/') ? ระบุ.slice(2)
      : `${(ของไฟล์ ?? '').split('/').slice(0, -1).join('/')}/${ระบุ.replace(/^\.\//, '')}`
    for (const น of ['.ts', '.tsx', '.mjs', '/index.ts']) ออก.push(ฐาน.replace(/\.(ts|tsx|mjs|js)$/, '') + น)
  }
  return ออก
}

const ของภายนอกใน = (เนื้อ) => {
  const เจอ = ความสามารถภายนอก.filter(([, re]) => re.test(เนื้อ)).map(([ชื่อ]) => ชื่อ)
  if (fetchที่เขียน.test(เนื้อ)) เจอ.push('fetch ที่ไม่ใช่ GET')
  return เจอ
}

/** คืน { ระดับ, ยืมมากี่ชั้น, เพราะ, พื้น }
 *  @param {string} พาธ
 *  @param {{ ลึกสุด?: number }} ตัวเลือก `ลึกสุด` = ตามอิมพอร์ตของเราเองได้กี่ชั้น (ค่าเริ่มต้น 1)
 *
 *  ⚠️ `ลึกสุด` เป็น **ตัวเลข** โดยตั้งใจ — ตัววัดจุดตัดเรียกฟังก์ชันเดียวกันนี้ด้วยเลข 1/2/3
 *     ⇒ เลขที่ได้คือเลขของเกณฑ์ที่ใช้จริง ไม่ใช่ของสำเนา
 */
export function อาจถึงตัวเขียน(พาธ, { ลึกสุด = 1 } = {}) {
  const เนื้อ = เนื้อไฟล์(พาธ)
  if (!เนื้อ) {
    return { ระดับ: 0, ยืมมากี่ชั้น: null,
      เพราะ: 'อ่านไฟล์ไม่ได้ ⇒ **ไม่รู้** ไม่ใช่ปลอดภัย', พื้น: 'ไม่รู้' }
  }

  const ตรง = ของภายนอกใน(เนื้อ)
  if (ตรง.length) {
    return { ระดับ: 3, ยืมมากี่ชั้น: 0, เพราะ: `อิมความสามารถ: ${ตรง.join(' · ')}`,
      พื้น: 'ภายนอก (ชื่อไม่ใช่ของเรา)' }
  }

  /* ② ตามอิมพอร์ตของเราเองเป็นชั้น ๆ แบบกว้างก่อน (BFS) ⇒ เจอที่ชั้นไหนคือ `ยืมมากี่ชั้น` นั้น
     🔴 ต้องมี `เคยไป` — ที่ความลึก ≥ 2 วงกลมอิมพอร์ต (A→B→A) มีจริงและจะวนไม่จบ
        รุ่นหนึ่งชั้นไม่เคยเจอปัญหานี้เพราะมันหยุดก่อนถึงชั้นที่สอง */
  const เคยไป = new Set([พาธ])
  let ขอบ = [พาธ]
  for (let ชั้น = 1; ชั้น <= ลึกสุด; ชั้น++) {
    const ขอบถัดไป = []
    for (const ป of ขอบ) {
      for (const ต่อ of โมดูลของเราที่อิม(เนื้อไฟล์(ป), ป)) {
        if (เคยไป.has(ต่อ)) continue
        const เนื้อต่อ = เนื้อไฟล์(ต่อ)
        if (!เนื้อต่อ) continue
        เคยไป.add(ต่อ)
        const ของต่อ = ของภายนอกใน(เนื้อต่อ)
        if (ของต่อ.length) {
          return { ระดับ: 3, ยืมมากี่ชั้น: ชั้น,
            เพราะ: `อิม ${ต่อ.split('/').pop()} ซึ่งอิม: ${ของต่อ.join(' · ')}`,
            พื้น: `ภายนอก ผ่านโมดูลของเรา ${ชั้น} ชั้น` }
        }
        ขอบถัดไป.push(ต่อ)
      }
    }
    ขอบ = ขอบถัดไป
    if (ขอบ.length === 0) break
  }

  if (วิธีที่เขียน.test(เนื้อ)) {
    return { ระดับ: 2, ยืมมากี่ชั้น: 0, เพราะ: 'เส้นนี้เปิด POST/PUT/DELETE/PATCH',
      พื้น: 'วิธี HTTP (ชื่อไม่ใช่ของเรา)' }
  }
  if (ชื่อที่ฟังดูเขียน.test(เนื้อ)) {
    return { ระดับ: 1, ยืมมากี่ชั้น: 0, เพราะ: 'มีชื่อที่ฟังดูเขียน (setJSON/save*/upsert/บันทึก…)',
      พื้น: '⚠️ **ชื่อของเราเอง — เปลี่ยนชื่อแล้วคำตอบเปลี่ยน**' }
  }
  return { ระดับ: 0, ยืมมากี่ชั้น: null, เพราะ: 'ไม่พบความสามารถเขียนที่ตามได้', พื้น: 'ไม่พบ' }
}
