/** ตัดคอมเมนต์ `/* *​/` และ `// …` ออก — คง**จำนวนบรรทัด**ไว้เท่าเดิม
 *  เพื่อให้ด่านที่รายงานเลขบรรทัดยังชี้ตำแหน่งในซอร์สดิบได้ถูก */
export function ตัดคอมเมนต์(ซอร์ส) {
  if (typeof ซอร์ส !== 'string') {
    throw new TypeError(`ตัดคอมเมนต์() ต้องการสตริง แต่ได้ ${typeof ซอร์ส}`)
  }
  /* 🔑 **ตัวเดินอักษร แหล่งเดียว** (20 ก.ย. 2569 · แบบที่ฝั่งท่อแก้แล้วส่งมา · ผมทำตาม)
     เดิมใช้ replace ทีละรูป ⇒ **ไม่รู้จักสตริง** ⇒ `/⟨ดาว⟩` ในสตริงถูกอ่านเป็นคอมเมนต์เปิด
     แล้วกินโค้ดจริงยาว (วัดได้ใน gen-arch: เหลือ 45% ของไฟล์ · โค้ดหาย ~40 บรรทัด)
     ⇒ ตอนนี้เดินทีละตัวอักษรและรู้ว่ากำลังอยู่ในสตริงหรือไม่
     ⚠️ **ยังไม่ใช่ parser เต็ม**: ไม่แยก regex literal ออกจากตัวหาร
        (`/\*` ที่เปิดด้วย `/` แล้วตามด้วย `\` ไม่ถูกนับเป็นคอมเมนต์ ⇒ รอดในทางปฏิบัติ)
     🔑 คงจำนวนบรรทัดเท่าเดิมเสมอ (แทนด้วยช่องว่าง เก็บ \n ไว้) เพราะด่านหลายตัวอ้างเลขบรรทัด */
  const น = ซอร์ส.length
  let out = ''
  let i = 0
  while (i < น) {
    const c = ซอร์ส[i]
    const c2 = ซอร์ส[i + 1]
    /* สตริง — ข้ามทั้งก้อน รวม escape */
    if (c === '"' || c === "'" || c === '`') {
      const ปิด = c
      out += c; i++
      while (i < น) {
        if (ซอร์ส[i] === '\\') { out += ซอร์ส[i] + (ซอร์ส[i + 1] ?? ''); i += 2; continue }
        if (ซอร์ส[i] === ปิด) { out += ซอร์ส[i]; i++; break }
        out += ซอร์ส[i]; i++
      }
      continue
    }
    /* คอมเมนต์บล็อก */
    if (c === '/' && c2 === '*') {
      i += 2
      while (i < น && !(ซอร์ส[i] === '*' && ซอร์ส[i + 1] === '/')) {
        out += ซอร์ส[i] === '\n' ? '\n' : ' '
        i++
      }
      i += 2
      continue
    }
    /* คอมเมนต์ท้ายบรรทัด — เฉพาะที่ต้นบรรทัดหรือหลังช่องว่าง (บัญชีขาวเดิม ยังใช้อยู่) */
    if (c === '/' && c2 === '/') {
      const ก่อน = i === 0 ? '' : ซอร์ส[i - 1]
      if (ก่อน === '' || ก่อน === '\n' || ก่อน === ' ' || ก่อน === '\t') {
        while (i < น && ซอร์ส[i] !== '\n') { out += ' '; i++ }
        continue
      }
    }
    out += c; i++
  }
  return out
}

