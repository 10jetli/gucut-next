import { statSync } from 'node:fs'

/** เกณฑ์ "เพิ่งแก้" — ฝั่งท่อใช้เลขเดียวกันใน `check-unreferenced-endpoints` (e4d9e612) */
export const นาทีที่ถือว่าเพิ่งแก้ = 30

/**
 * อ่านสภาพไฟล์นอกรีโป — **สามสถานะ ไม่ใช่สอง**
 *  · `{มี:true}`            อ่านได้ (มี mtimeMs/size/นาที)
 *  · `{มี:false, เหตุ:…}`   ไม่มีไฟล์ / อ่านไม่ได้ ⇒ **ห้ามกลายเป็น 0 นาที**
 * 🔴 เคยเหยียบ: `catch { return 0 }` ทำให้ "อ่านไม่ได้" เข้าเกณฑ์ "เพิ่งแก้" ทุกครั้ง
 */
export function สภาพไฟล์นอกรีโป(ที่) {
  try {
    const st = statSync(ที่)
    const นาที = Math.round((Date.now() - st.mtimeMs) / 60000)
    return { มี: true, ที่, mtimeMs: st.mtimeMs, size: st.size, นาที, เพิ่งแก้: นาที <= นาทีที่ถือว่าเพิ่งแก้ }
  } catch (e) {
    return { มี: false, ที่, เหตุ: e?.code === 'ENOENT' ? 'ไม่มีไฟล์นี้ในเครื่อง' : `อ่านไม่ได้ (${e?.code || e?.message})`, นาที: null, เพิ่งแก้: null }
  }
}

/** ข้อความบรรทัดเดียว — ใช้ตอนอยากประกอบเอง */
export function บอกสภาพไฟล์นอกรีโป(ที่) {
  const s = สภาพไฟล์นอกรีโป(ที่)
  if (!s.มี) return `🔶 ${s.เหตุ}`
  const อายุ = s.นาที < 60 ? `${s.นาที} นาทีที่แล้ว` : `${Math.round(s.นาที / 60)} ชม.ที่แล้ว`
  return `แก้ล่าสุด ${new Date(s.mtimeMs).toLocaleString('th-TH')} (${อายุ}) · ${s.size} ไบต์`
}

/**
 * 🔑 **ตัวที่ด่านทุกตัวควรเรียก** — พิมพ์ที่มาของของนอกรีโป แล้วคืนสภาพให้ผู้เรียกใช้ต่อ
 * @param {string} ที่ พาธเต็มของไฟล์นอกรีโป
 * @param {{ป้าย?:string, ย่อหน้า?:string}} opt ป้าย = ชื่อที่คนอ่านเข้าใจ (เช่น 'ซอร์สท่อ: core.mjs')
 */
export function บอกไฟล์นอกรีโป(ที่, opt = {}) {
  const s = สภาพไฟล์นอกรีโป(ที่)
  const นำ = opt.ย่อหน้า ?? '   '
  const ป้าย = opt.ป้าย ? `${opt.ป้าย} ` : ''
  console.log(`${นำ}📂 ${ป้าย}ไฟล์นอกรีโป: ${บอกสภาพไฟล์นอกรีโป(ที่)}`)
  if (s.เพิ่งแก้ === true) {
    console.log(`${นำ}   ⚠️ **ของนอกรีโปนี้เพิ่งถูกแก้ ≤${นาทีที่ถือว่าเพิ่งแก้} นาที** ⇒ ถ้าด่านนี้แดง`
      + ` ให้สงสัยของที่เพิ่งเปลี่ยน **ก่อน** รื้อรีโปตัวเอง`)
    console.log(`${นำ}      (อีกฝั่งไม่ต้อง push ของก็ถึงเราแล้ว — เราอ่านจากดิสก์ ไม่ได้อ่านจาก git)`)
  }
  return s
}

/**
 * 🔑 **สำหรับด่านที่อ่าน "กอง" ไฟล์นอกรีโป ไม่ใช่ไฟล์เดียว**
 *    (เช่น `check-pipe-keys` อ่านทั้ง `netlify/functions` + `netlify/lib`)
 *
 * 🔴 **ทำไมต้องรายงานตัวที่ใหม่สุด ไม่ใช่โฟลเดอร์**
 *    mtime ของ**โฟลเดอร์**เปลี่ยนเฉพาะตอนเพิ่ม/ลบไฟล์ — แก้เนื้อในไฟล์ไม่ขยับโฟลเดอร์
 *    ⇒ ⇒ อ่าน mtime ของโฟลเดอร์ = **เมตาดาต้าของภาชนะ ไม่ใช่ข้อมูลข้างใน** (คลาสที่ทีมเคยเหยียบ 3 ครั้งในคืนเดียว)
 *    ⇒ ต้องวัดจาก **ไฟล์ที่ด่านอ่านจริง** แล้วรายงานตัวที่ใหม่สุด
 *
 * @param {string[]} รายชื่อ พาธไฟล์ที่ด่านนี้อ่านจริง
 * @returns สภาพของไฟล์ที่ใหม่สุด (+ `จำนวน`, `อ่านไม่ได้`) · กองว่าง ⇒ `{มี:false}`
 */
export function บอกกองนอกรีโป(รายชื่อ, opt = {}) {
  const นำ = opt.ย่อหน้า ?? '   '
  const ป้าย = opt.ป้าย ? `${opt.ป้าย} ` : ''
  const ทุกตัว = รายชื่อ.map((f) => สภาพไฟล์นอกรีโป(f))
  const อ่านได้ = ทุกตัว.filter((s) => s.มี)
  const อ่านไม่ได้ = ทุกตัว.length - อ่านได้.length
  if (!อ่านได้.length) {
    console.log(`${นำ}📂 ${ป้าย}ไฟล์นอกรีโป: 🔶 อ่านไม่ได้เลย (ส่งมา ${ทุกตัว.length} ชื่อ)`)
    return { มี: false, จำนวน: ทุกตัว.length, อ่านไม่ได้, นาที: null, เพิ่งแก้: null }
  }
  const ใหม่สุด = อ่านได้.reduce((a, b) => (b.mtimeMs > a.mtimeMs ? b : a))
  console.log(`${นำ}📂 ${ป้าย}ของนอกรีโป ${อ่านได้.length} ไฟล์`
    + `${อ่านไม่ได้ ? ` (อ่านไม่ได้ ${อ่านไม่ได้})` : ''}`
    + ` · ใหม่สุด \`${ใหม่สุด.ที่.split('/').slice(-2).join('/')}\` ${บอกสภาพไฟล์นอกรีโป(ใหม่สุด.ที่)}`)
  if (ใหม่สุด.เพิ่งแก้) {
    console.log(`${นำ}   ⚠️ **ของนอกรีโปเพิ่งถูกแก้ ≤${นาทีที่ถือว่าเพิ่งแก้} นาที** ⇒ ถ้าด่านนี้แดง`
      + ` ให้สงสัยของที่เพิ่งเปลี่ยน **ก่อน** รื้อรีโปตัวเอง`)
    console.log(`${นำ}      (อีกฝั่งไม่ต้อง push ของก็ถึงเราแล้ว — เราอ่านจากดิสก์ ไม่ได้อ่านจาก git)`)
  }
  return { ...ใหม่สุด, จำนวน: อ่านได้.length, อ่านไม่ได้ }
}
