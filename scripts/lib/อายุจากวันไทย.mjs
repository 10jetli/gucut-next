export const เดือนไทย = {
  'ม.ค.': 1, 'ก.พ.': 2, 'มี.ค.': 3, 'เม.ย.': 4, 'พ.ค.': 5, 'มิ.ย.': 6,
  'ก.ค.': 7, 'ส.ค.': 8, 'ก.ย.': 9, 'ต.ค.': 10, 'พ.ย.': 11, 'ธ.ค.': 12,
}
const รูปวัน = /(\d{1,2})\s*(ม\.ค\.|ก\.พ\.|มี\.ค\.|เม\.ย\.|พ\.ค\.|มิ\.ย\.|ก\.ค\.|ส\.ค\.|ก\.ย\.|ต\.ค\.|พ\.ย\.|ธ\.ค\.)/g

/** คืนอายุ (วัน) ของวันที่ **ใหม่ที่สุด** ที่เจอในข้อความ · ไม่เจอวันที่เลย ⇒ `null`
 *  🔑 `null` แปลว่า **ไม่รู้** ห้ามอ่านว่า 0 หรือว่า "ใหม่" */
export function อายุจากวันไทย(ข้อความ, วันนี้ = new Date()) {
  const เจอ = [...String(ข้อความ ?? '').matchAll(รูปวัน)]
  if (!เจอ.length) return null
  const วันที่ทั้งหมด = เจอ.map(([, วัน, เดือน]) => {
    let d = new Date(วันนี้.getFullYear(), เดือนไทย[เดือน] - 1, Number(วัน))
    /* คิดแล้วได้อนาคต ⇒ แปลว่าเป็นของปีก่อน (ไม่มีใครเขียนวันที่ล่วงหน้าในคอมเมนต์) */
    if (d > วันนี้) d = new Date(วันนี้.getFullYear() - 1, เดือนไทย[เดือน] - 1, Number(วัน))
    return d
  })
  const ใหม่สุด = วันที่ทั้งหมด.sort((a, b) => b - a)[0]
  return Math.round((วันนี้ - ใหม่สุด) / 86400000)
}
