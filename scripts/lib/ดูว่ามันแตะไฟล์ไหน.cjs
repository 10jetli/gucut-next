/**
 * 🔑 **วัดว่า "ของที่เรากำลังจะรัน" แตะไฟล์ไหน — และบล็อกการเขียนได้**
 *
 * ใช้: `NO_WRITE=1 TOUCH_WHAT=gucut-web node -r ./scripts/lib/ดูว่ามันแตะไฟล์ไหน.cjs <ไฟล์>`
 *   · `TOUCH_WHAT=<คำ>` พิมพ์การเรียก fs ที่พาธมีคำนี้
 *   · `NO_WRITE=1`      🔑 **ทำให้คำว่า "อ่านอย่างเดียว" เป็นจริงโดยโครงสร้าง** — ตัวเขียน throw
 *   · `--ตรวจตัวเอง`     เทสสองทิศของตัวเอง
 *
 * ⚠️ ชื่อธงเป็น ASCII **โดยเจตนา** — ชื่อตัวแปรภาษาไทยใน bash ใช้ไม่ได้
 *    (`ห้ามเขียน=1 node …` ⇒ bash ตอบ command not found แล้ว **เดินต่อ** ⇒ ค่าเป็นว่างเงียบ ๆ)
 *    ของที่ตั้งใจให้เรียกจากเชลล์ จึงต้องใช้ชื่อ ASCII ([[ภาษาไทยเป็นชื่อในเชลล์ไม่ได้]])
 *
 * 🔴 **ที่มา 14 ต.ค. 2569 — ผมเรียกการวัดของตัวเองว่า "อ่านอย่างเดียว" แล้วมันเขียน 528 KB**
 *    ผมอยากรู้ว่าสคริปต์ 6 ตัวตัวไหนอ่านอีกรีโปจากดิสก์จริง ⇒ แพตช์ `fs` แล้ว `node <ไฟล์>` ทั้ง 6
 *    ⇒ ตัวหนึ่ง (`ดึงสารบัญท่อ.mjs`) **มีหน้าที่เขียนไฟล์** ⇒ ทับ `lib/pipe-snapshot.json`
 *      ในต้นไม้ที่ git ติดตาม (diff 6,231 บรรทัด) ⇒ เกือบ commit ติดไปกับงานคนละเรื่อง
 *
 * 🔑 **กลไกที่ต้องจำ: ป้าย "อ่านอย่างเดียว" ของผมพูดถึงสิ่งที่ *เครื่องมือผม* ทำ
 *    ไม่ใช่สิ่งที่ *ของที่ถูกวัด* ทำ** — การรันของคนอื่นเพื่อสังเกตมัน
 *    = ยอมให้ผลข้างเคียงทั้งหมดของมันเกิดขึ้น
 *
 * ⚠️ **ขอบเขตที่ตัวนี้ตอบไม่ได้** (เขียนไว้ ไม่ปล่อยให้เดา):
 *    เห็นแต่ `fs` แบบ sync ที่ผ่านโมดูล `fs` · ไม่เห็น `fs/promises` · `fs.promises`
 *    · ไม่เห็น child process ที่ไปเขียนเอง (`execSync('git …')`) · ไม่เห็น native addon
 *    ⇒ `NO_WRITE=1` คือ **ตะแกรง ไม่ใช่กำแพง** ⇒ ของสำคัญยังต้องรันในสำเนา/worktree
 *    ⇒ และยังต้อง `git status` **ก่อนและหลัง** อยู่ดี (ท่าเดียวกับลายนิ้วมือต้นไม้ของด่าน push)
 */
const fs = require('fs')

const คำ = process.env.TOUCH_WHAT || ''
const ห้ามเขียน = process.env.NO_WRITE === '1'
const เจอ = new Set()
let นับ = 0

/* 🔴🔴 **`writeSync` ต้องไม่อยู่ในรายการนี้ — และผมใส่ไปแล้วเจ็บทันที**
   รุ่นแรกผมใส่ `writeSync` ⇒ `NO_WRITE=1` ทำให้เครื่องมือ **เงียบสนิทและ exit 0**
   เหตุ: `console.log`/`process.stderr.write` เขียนลง fd ผ่าน `fs.writeSync`
   ⇒ ตัวบล็อกไปปิดปากตัวเอง · ข้อผิดพลาดใน exit handler ถูกกลืน ⇒ **ไม่มีเอาต์พุต ไม่มีรหัสผิด**
   ⇒ ⇒ อาการคือ "ดูเหมือนผ่าน" ซึ่งแพงกว่าพังดัง ๆ ([[ข่าวดีปลอมอันตรายกว่าข่าวร้ายปลอม]])
   📌 และ `writeSync(fd, …)` รับ **หมายเลข fd ไม่ใช่พาธ** ⇒ ตะแกรงที่คิดแบบพาธใช้กับมันไม่ได้อยู่แล้ว
   🔑 คลาส: **ของที่ห่อทางออกทั้งหมด ต้องไม่ห่อทางที่มันใช้รายงานตัวเอง**
      (เทส `--ตรวจตัวเอง` จึงบังคับว่า **ต้องมีเอาต์พุต** ไม่ใช่แค่ rc=0) */
const ตัวเขียน = ['writeFileSync', 'appendFileSync', 'rmSync', 'unlinkSync', 'rmdirSync',
  'mkdirSync', 'renameSync', 'copyFileSync', 'truncateSync']
const ตัวอ่าน = ['readFileSync', 'readdirSync', 'statSync', 'existsSync', 'lstatSync',
  'openSync', 'realpathSync']

for (const ชื่อ of [...ตัวอ่าน, ...ตัวเขียน]) {
  const เดิม = fs[ชื่อ]
  if (typeof เดิม !== 'function') continue
  const เป็นตัวเขียน = ตัวเขียน.includes(ชื่อ)
  fs[ชื่อ] = function (p, ...a) {
    const s = (() => { try { return String(p) } catch { return '' } })()
    if (คำ && s.includes(คำ)) { เจอ.add(`${ชื่อ} ${s}`); นับ++ }
    if (เป็นตัวเขียน && ห้ามเขียน) {
      /* 🔴 throw **ก่อน** เรียกของเดิม — ไม่ใช่เตือนแล้วปล่อยผ่าน
         เตือนแล้วปล่อย = ป้ายที่อ้างเกินสิ่งที่มือเราทำ (คลาสเดิมเป๊ะ) */
      const e = new Error(`🔴 NO_WRITE=1 แต่ของที่วัดเรียก fs.${ชื่อ}(${s.slice(0, 160)})`)
      e.code = 'หยุดเพราะจะเขียน'
      throw e
    }
    return เดิม.call(this, p, ...a)
  }
}

process.on('exit', () => {
  const บรรทัด = []
  if (คำ) {
    บรรทัด.push(`[วัดจริง] เรียก fs ด้วยพาธที่มี "${คำ}": ${นับ} ครั้ง · ${เจอ.size} พาธไม่ซ้ำ`)
    for (const x of [...เจอ].slice(0, 3)) บรรทัด.push(`[วัดจริง]   ${x.slice(0, 140)}`)
  }
  บรรทัด.push(`[วัดจริง] NO_WRITE: ${ห้ามเขียน ? 'เปิด' : '🔶 **ปิด** ⇒ ของที่วัดเขียนไฟล์ได้'}`)
  process.stderr.write('\n' + บรรทัด.join('\n') + '\n')
})

/* ── ตรวจตัวเอง ────────────────────────────────────────────────
   🔑 **ต้องมีสองทิศ**: เปิดโหมดแล้วเขียนไม่ได้ · และ **ปิดโหมดแล้วเขียนได้**
      ทิศที่สองคือตัวควบคุมลบ — ไม่มีมัน เทสผ่านได้ด้วยเหตุผลผิด (เช่นพาธใช้ไม่ได้ตั้งแต่ต้น) */
if (process.argv.includes('--ตรวจตัวเอง')) {
  const os = require('os'); const path = require('path')
  const ที่ = path.join(os.tmpdir(), `ตรวจตัวเอง-${process.pid}-${Date.now()}.txt`)
  const ผล = []
  if (ห้ามเขียน) {
    try { fs.writeFileSync(ที่, 'x'); ผล.push('🔴 ตก: เปิด NO_WRITE แต่เขียนลง') }
    catch (e) {
      ผล.push(e.code === 'หยุดเพราะจะเขียน'
        ? '✅ เปิดโหมด ⇒ writeFileSync ถูกบล็อก พร้อมบอกพาธในข้อความ'
        : `🔴 ตก: บล็อกด้วยเหตุผลอื่น (${e.code || e.message})`)
    }
    ผล.push(fs.existsSync(ที่)
      ? '🔴 ตก: ไฟล์ถูกสร้างขึ้นจริงทั้งที่บล็อก (= เตือนแล้วปล่อยผ่าน)'
      : '✅ ไฟล์ไม่ถูกสร้าง (บล็อกก่อนเรียกของเดิม)')
  } else {
    try {
      fs.writeFileSync(ที่, 'x')
      ผล.push('✅ ปิดโหมด ⇒ เขียนได้ตามปกติ (**ตัวควบคุมลบ**: ไม่ได้บล็อกตลอดเวลา)')
      fs.rmSync(ที่)
    } catch (e) { ผล.push(`🔴 ตก: ปิดโหมดแล้วยังเขียนไม่ได้ (${e.message})`) }
  }
  for (const x of ผล) console.log('   ' + x)
  process.exitCode = ผล.some((x) => x.startsWith('🔴')) ? 1 : 0
}
