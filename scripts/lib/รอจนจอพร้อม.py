"""รอจนจอ "พร้อมให้ตัดสิน" แล้วค่อยวัด — ตัวช่วยกลางของสคริปต์ทดสอบที่ใช้เบราว์เซอร์

🔴 **ทำไมต้องมีตัวนี้ แทนที่จะเขียนลูปรอในทุกไฟล์**
คืน 18–19 ก.ย. 2569 กฎ "ดูสัญญาณบวก ไม่ใช่นับเวลา" ถูกเหยียบซ้ำ **สามครั้งในคืนเดียว**
ทั้งที่มันเขียนอยู่ในหัว `scripts/sweep-in-browser.js` มาตั้งแต่ 7 ก.ย.:
  · ตัวกวาดจอมือถือรอ 4.5 วิ ⇒ วัดก่อนตารางขึ้น ⇒ รายงาน "สะอาดทั้ง 78 จอ" ทั้งที่จอขายล้น 79px
  · ฝั่งท่อรอ 2.5 วิแล้ววัดจอ ZORT ⇒ ได้ "แท็บ = []" ⇒ เกือบสรุปว่า ZORT ไม่มีแท็บ
  · ตัวทดสอบรายการโตตั้งเพดานคงที่ 30 วิ ⇒ ที่ 5 เท่าจอมีชิป 95 ตัว ⇒ "ตัดสินไม่ได้" ทั้งที่จอปกติ

🔑 **กฎที่ได้: กฎที่อ่านแล้วไม่ได้ทำให้ผิดยากขึ้น จะถูกเหยียบซ้ำเสมอ**
   ของที่ได้ผลจริงคือ **ตัวช่วยที่ทำให้ท่าถูกง่ายกว่าท่าผิด** ⇒ ไฟล์นี้คือตัวนั้น

⚠️ **สามสถานะ ห้ามยุบเหลือสอง** (กติกาเดียวกับทั้งระบบ)
   ① ยังโหลดอยู่ ⇒ รอต่อ · ② ตัดสินได้ ⇒ วัด · ③ ครบเพดานแล้วยังไม่พร้อม ⇒ **"ตัดสินไม่ได้"**
   🚫 ห้ามแปลง ③ เป็น "ผ่าน" เด็ดขาด — และจำนวน ③ วัดคุณภาพของ **เครื่องมือ** ไม่ใช่ของระบบ
"""
from __future__ import annotations


def รอจนพร้อม(page, เพดานวิ: int = 30, ตัวคูณภาระ: int = 1) -> bool:
    """คืน True เมื่อจอพร้อมให้ตัดสิน · False เมื่อครบเพดานแล้วยังไม่พร้อม (= ตัดสินไม่ได้)

    `ตัวคูณภาระ` — ถ้ากำลังทดสอบด้วยข้อมูลที่ใหญ่กว่าปกติ (เช่นปลูกสมาชิก 5 เท่า)
    ให้ส่งตัวคูณมาด้วย **เพดานเวลาต้องโตตามภาระที่เครื่องมือเองสร้าง**
    ไม่งั้นยิ่งทดสอบหนัก ยิ่งได้ "ตัดสินไม่ได้" ⇒ การทดสอบที่เข้มขึ้นจะให้ผลที่อ่อนลง
    """
    รอบ = max(เพดานวิ, เพดานวิ * max(1, ตัวคูณภาระ) // 2)
    for _ in range(รอบ):
        page.wait_for_timeout(1000)
        try:
            t = page.locator("main").inner_text()
        except Exception:
            continue          # จอกำลังเปลี่ยน — ไม่ใช่คำตอบ ให้รอต่อ
        if "หน้านี้มีปัญหา" in t:
            return True       # พังแน่นอน = ตัดสินได้ (ไม่ต้องรอต่อ)
        # 🔴 **เดิมมองแค่ 160 ตัวอักษรแรก** ⇒ จอที่หัวเรื่องยาว (คำเตือน/แถบความสามารถ)
        #    จะดัน "กำลังโหลด…" ของเนื้อหาจริงพ้นหน้าต่างที่มอง ⇒ ตัวช่วยตอบว่า "พร้อม"
        #    ทั้งที่ของที่เราจะไปวัดยังไม่มา (เจอจริง 19 ก.ย. 2569 ที่ /core/pos —
        #    รายงานไปแล้วว่า "จอค้าง ไม่เรียกท่อเลย" ซึ่ง **ผิด** · ของจริงแค่มาช้า
        #    และ "กำลังโหลดหมวด…" อยู่ตัวที่ ~300)
        # 🔑 กติกาเดิมของไฟล์นี้: ครบเพดานแล้วยังไม่พร้อม ⇒ **ตัดสินไม่ได้** ไม่ใช่ผ่าน
        #    ⇒ มองทั้งจอปลอดภัยกว่า เพราะทางที่ผิดคือ "ตัดสินไม่ได้" ไม่ใช่ "เขียวลวง"
        กำลังโหลด = "กำลังโหลด" in t or "กำลังถาม" in t
        if กำลังโหลด:
            continue
        if len(t) > 220:
            return True
        try:
            if page.locator("main table tbody tr").count() > 0:
                return True   # มีแถวแล้ว = มีของจริงให้ดู แม้ข้อความจะสั้น
        except Exception:
            pass
    return False


def ข้อความตัดสินไม่ได้(path: str, เพดานวิ: int) -> str:
    """ถ้อยคำมาตรฐาน — **ห้ามเขียนว่า "ผ่าน" หรือ "ไม่มีปัญหา"**"""
    return f"{path:30s} ⚠️ ตัดสินไม่ได้ใน {เพดานวิ} วิ (จอยังไม่พร้อม) — **ไม่ใช่ว่าไม่มีปัญหา**"
