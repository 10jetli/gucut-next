/* ตัวตัดสินผลการโหลดตัวช่วย — **แยกออกมาจากลูปที่สั่งลูกกระบวนการ**
 *
 * 🔑 ที่มา 20 ก.ย. 2569 — เกณฑ์ที่ฝั่งท่อสรุปไว้:
 *    **"แก้อะไรแล้วจำนวนเทสไม่ขยับ ให้ถือว่ายังไม่ได้แก้"**
 *    ไม่ใช่เพราะจำนวนเทสสำคัญ แต่เพราะ **การแก้ที่ทดสอบไม่ได้ คือการแก้ที่ยังไม่รู้ว่าถูก**
 *
 *    ของผมเข้าข่ายเป๊ะ: ตัวตัดสินสามกอง (โหลดไม่ได้ · ลงมือตอนโหลด · ออกก่อนเวลา)
 *    **ฝังอยู่ในลูปที่ต้อง spawn ลูกกระบวนการจริงถึงจะเดิน** ⇒ พิสูจน์ได้ทางเดียวคือปลูกไฟล์จริง
 *    ⇒ ⇒ ยก **การตัดสิน** ออกจาก **การลงมือ** ⇒ เทสป้อนค่าตรง ๆ ได้ ไม่ต้องมีไฟล์จริง
 *
 * ⚠️ สิ่งที่ฟังก์ชันนี้ **ไม่ได้** ทำ: มันไม่ได้โหลดอะไรเลย · ไม่รู้จักไฟล์ ·
 *    มันแปลผลที่คนอื่นวัดมาเท่านั้น ⇒ ถ้าตัววัดข้างนอกวัดผิด ตัวนี้ก็ตัดสินผิดตาม
 */

/** ผลที่เป็นไปได้ — **ประกาศเป็นรายชื่อ** เพื่อให้ผู้เรียกตรวจได้ว่าเทียบกับชื่อที่มีจริง
 *  (บทเรียน 20 ก.ย. 2569: เปลี่ยนชื่อค่าในสัญญาร่วมแล้วอีกฝั่งเทียบชื่อเก่า = เงียบแล้วผ่านฟรี) */
export const ผลโหลดทั้งหมด = ['ผ่าน', 'โหลดไม่ได้', 'ลงมือตอนโหลด', 'ออกก่อนเวลา', 'ไม่มี export']

/**
 * @param {object} ข้อมูลที่วัดมา
 * @param {string|null} ข้อมูลที่วัดมา.error  ข้อความ error จากลูกกระบวนการ (null = ลูกจบด้วยรหัส 0)
 * @param {string} ข้อมูลที่วัดมา.เสียง        ทุกอย่างที่ลูกพิมพ์ออกมา
 * @param {string|null} ข้อมูลที่วัดมา.หมุด    เนื้อในไฟล์หมุด (null = ไม่มีหมุด ⇒ import ไม่เดินจบ)
 */
export function ตัดสินผลโหลด({ error = null, เสียง = '', หมุด = null } = {}) {
  /* ลำดับสำคัญ: **error มาก่อนเสมอ** — ลูกที่พังอาจพิมพ์อะไรออกมาด้วย
     ถ้าเรียงสลับ จะรายงานว่า "ลงมือตอนโหลด" ทั้งที่ของจริงคือมันพัง */
  if (error) {
    const ชนิด = /(\w*Error)\b/.exec(String(error))?.[1] ?? 'Error'
    return { ผล: 'โหลดไม่ได้', ชนิด, เหตุ: String(error).replace(/\s+/g, ' ').slice(0, 160) }
  }
  if (String(เสียง).trim()) {
    const ข้อความ = String(เสียง).trim()
    return { ผล: 'ลงมือตอนโหลด', ชนิด: null, เหตุ: `พิมพ์ออกมา ${ข้อความ.length} ตัวอักษรตอนถูกโหลด: "${ข้อความ.slice(0, 80)}"` }
  }
  /* 🔑 ไม่มีหมุด ทั้งที่ลูกจบด้วยรหัส 0 ⇒ **การหยุดกลางทางหน้าตาเหมือนความสำเร็จ** */
  if (หมุด === null) {
    return { ผล: 'ออกก่อนเวลา', ชนิด: null, เหตุ: 'ลูกออกด้วยรหัส 0 แต่ **หมุดไม่ถูกเขียน** ⇒ `import` ไม่เคยเดินจบ (เช่นมี process.exit ตอนโหลด)' }
  }
  if (String(หมุด).trim() === '0') {
    return { ผล: 'ไม่มี export', ชนิด: null, เหตุ: 'โหลดได้แต่ **ไม่มี export เลย** ⇒ ไม่มีใครเอาไปใช้ได้ (ตั้งใจแบบนี้ไหม)' }
  }
  return { ผล: 'ผ่าน', ชนิด: null, เหตุ: '' }
}
