/** ผังหลังร้านที่ `gen-arch.mjs` สร้างทั้งไฟล์ */
export const ผังหลังร้าน = 'lib/arch-admin.ts'

/** ไฟล์ตัวกวาดในเบราว์เซอร์ — `gen-arch.mjs` เขียนทับ **เฉพาะบรรทัด** `window.ALL_ROUTES` */
export const รายชื่อจอของตัวกวาด = 'scripts/sweep-in-browser.js'

export const ทั้งหมด = [ผังหลังร้าน, รายชื่อจอของตัวกวาด]

/** ใช้ในด่านที่ต้องการต้นไม้สะอาด: แถวจาก `git status --porcelain` นี้เป็นผลผลิตของ build ไหม */
export const เป็นผลผลิตของบิลด์ = (แถว) =>
  ทั้งหมด.some((f) => แถว.endsWith(` ${f}`) || แถว.endsWith(`/${f}`) || แถว.trim().endsWith(f))
