/** หมุดทั้งหมดที่ทีมใช้ — เรียงตามที่เกิดก่อน-หลัง */
export const คำหมุดของปลูก = ['ZZPLANTZZ', 'ZZNEVERMATCHZZ', 'ZZBREAKZZ', 'ZZNOPEZZ', 'zz-probe']

/** หมุดมาตรฐานสำหรับ "ปลูกโค้ดที่ต้องถูกจับ" */
export const หมุดปลูก = คำหมุดของปลูก[0]
/** หมุดมาตรฐานสำหรับ "ตะแกรงที่ไม่มีวันตรงกับอะไร" (ใช้ทดสอบว่าด่านแยกแยะได้) */
export const หมุดไม่มีวันตรง = คำหมุดของปลูก[1]

/** มีหมุดตัวไหนอยู่ในข้อความนี้บ้าง — คืนรายชื่อ (ว่าง = ไม่มี) */
export function หมุดที่พบใน(ข้อความ) {
  return คำหมุดของปลูก.filter((c) => String(ข้อความ ?? '').includes(c))
}
