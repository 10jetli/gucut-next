/** รุ่นที่สารบัญ "สำรวจไว้" — ชั้นนอก + รายก้อนที่มีช่องรุ่นของตัวเอง */
export function รุ่นที่สารบัญสำรวจ(snap) {
  const ep = snap?.endpoints ?? {}
  const รายก้อน = []
  for (const [ชื่อ, ก้อน] of Object.entries(ep)) {
    if (!ก้อน || typeof ก้อน !== 'object') continue
    if (!('ดึงเมื่อ' in ก้อน) && !('ท่อสร้างเมื่อ' in ก้อน)) continue
    รายก้อน.push({ ชื่อ, รุ่น: ก้อน['ท่อสร้างเมื่อ'] ?? null })
  }
  return { ชั้นนอก: snap?.['ท่อสร้างเมื่อ'] ?? null, รายก้อน }
}

/** เทียบรุ่นที่จดไว้กับรุ่นที่วิ่งอยู่ — **ตัวตัดสินล้วน** (ป้อนค่าปลอมได้)
 *  คืนรายการ `{ ชื่อ, จด, ตรงกัน }` · `ตรงกัน: null` = **บอกไม่ได้** (ไม่ใช่ตรงกัน) */
export function เทียบรุ่นสารบัญ(snap, รุ่นจริง = null) {
  const r = รุ่นที่สารบัญสำรวจ(snap)
  const ตัดสิน = (จด) => (!จด || !รุ่นจริง ? null : จด === รุ่นจริง)
  return [
    { ชื่อ: '(ชั้นนอก)', จด: r.ชั้นนอก, ตรงกัน: ตัดสิน(r.ชั้นนอก) },
    ...r.รายก้อน.map((x) => ({ ชื่อ: x.ชื่อ, จด: x.รุ่น, ตรงกัน: ตัดสิน(x.รุ่น) })),
  ]
}

/** พิมพ์ผลเทียบรุ่น — **ไม่ทำให้ตก** · ก้อนที่ไม่มีช่องรุ่นต้องพูดออกมา ห้ามเงียบ */
export function บอกรุ่นสารบัญ(snap, รุ่นจริง = process.env.PIPE_BUILD || null) {
  const แถว = เทียบรุ่นสารบัญ(snap, รุ่นจริง)
  if (!รุ่นจริง) {
    console.log('🏷️  รุ่นท่อที่สารบัญสำรวจไว้: '
      + แถว.map((x) => `${x.ชื่อ}=${x.จด ?? 'ไม่ได้จด'}`).join(' · '))
    console.log('   ⇒ **ยังไม่ได้เทียบกับรุ่นที่วิ่งอยู่** ⇒ อายุคือทั้งหมดที่เรารู้'
      + ' (เทียบได้ด้วย `node scripts/เทียบรุ่นท่อ.mjs`)')
    return แถว
  }
  for (const x of แถว) {
    if (x.ตรงกัน === true) continue
    if (x.จด == null) {
      console.log(`   ⚠️ ก้อน \`${x.ชื่อ}\` **ไม่ได้จดรุ่นต้นทาง** ⇒ บอกรุ่นไม่ได้ ⇒ อายุคือทั้งหมดที่เรารู้`)
      continue
    }
    console.log(`   🔴 ก้อน \`${x.ชื่อ}\` สำรวจท่อ **คนละรุ่น** (จด ${x.จด} · วิ่งอยู่ ${รุ่นจริง})`)
    console.log('      ⇒ **อายุบอกอะไรไม่ได้ในกรณีนี้** — เก่าหรือสดก็ผิดได้ ถ้ารุ่นไม่ตรง')
  }
  return แถว
}
