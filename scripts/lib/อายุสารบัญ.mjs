/** ตัวตัดสินล้วน — คืน `{ เก่ากี่วัน, เกิน, เก่าเกิน }` (ป้อนค่าปลอมได้) */
export function อายุของสารบัญ(snap, ตอนนี้ = Date.now()) {
  const ดึงเมื่อ = snap?.['ดึงเมื่อ'] ?? null
  const เกิน = Number(snap?.['เตือนเมื่อเกินวัน']) || 7
  if (!ดึงเมื่อ) return { ดึงเมื่อ: null, เก่ากี่วัน: null, เกิน, เก่าเกิน: false, ไม่รู้: true }
  const ms = ตอนนี้ - Date.parse(ดึงเมื่อ)
  if (!Number.isFinite(ms)) return { ดึงเมื่อ, เก่ากี่วัน: null, เกิน, เก่าเกิน: false, ไม่รู้: true }
  const วัน = ms / 86_400_000
  return { ดึงเมื่อ, เก่ากี่วัน: วัน, เกิน, เก่าเกิน: วัน > เกิน, ไม่รู้: false }
}

/** พิมพ์บรรทัดเดียวทุกครั้งที่รัน — **ไม่ทำให้ตก** (เงื่อนไข ②) */
export function บอกอายุสารบัญ(snap, ตอนนี้ = Date.now()) {
  const a = อายุของสารบัญ(snap, ตอนนี้)
  if (a.ไม่รู้) {
    console.log('📅 สารบัญท่อ: **ไม่รู้ว่าดึงเมื่อไหร่** (ไม่มีช่อง `ดึงเมื่อ` หรืออ่านวันที่ไม่ได้)')
    return a
  }
  const วัน = a.เก่ากี่วัน.toFixed(1)
  console.log(`📅 เทียบกับสารบัญท่อของ ${a.ดึงเมื่อ} (เก่า ${วัน} วัน · เกณฑ์ ${a.เกิน})`
    + (a.เก่าเกิน ? ' ⚠️ **เก่าเกินเกณฑ์ ⇒ ผลของด่านนี้อ่านได้แค่ "ตรงกับของเก่า"**' : ''))
  if (a.เก่าเกิน) console.log('   ⇒ ดึงใหม่: node scripts/ดึงสารบัญท่อ.mjs')
  return a
}
