const ROOT = fileURLToPath(new URL('..', import.meta.url))

export function ความสว่าง(hex) {
  const h = String(hex).replace('#', '')
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16) / 255)
  const f = (v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4)
  return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)
}

export function คอนทราสต์(a, b) {
  const [x, y] = [ความสว่าง(a), ความสว่าง(b)].sort((p, q) => q - p)
  return Math.round(((x + 0.05) / (y + 0.05)) * 100) / 100
}

/** ตัดสินคู่สีของปุ่มสองสภาพพร้อมกัน — คืนเหตุผลเป็นข้อความ ไม่ใช่แค่ boolean
 *  (บทเรียน: รวม boolean ไว้ที่เดียวแต่พิมพ์เหตุด้วยมือ = ย้ายคำโกหกไปช่องข้าง ๆ) */
export function ตัดสินปุ่ม({ ปิดพื้น, ปิดตัวอักษร, เปิดพื้น, เปิดตัวอักษร }) {
  const ปิด = คอนทราสต์(ปิดตัวอักษร, ปิดพื้น)
  const เปิด = คอนทราสต์(เปิดตัวอักษร, เปิดพื้น)
  const ระยะห่าง = Math.round((เปิด - ปิด) * 100) / 100
  const เหตุ = []
  if (ปิด < 4.5) เหตุ.push(`สภาพปิดอ่านไม่ออก ${ปิด}:1 (ต้อง ≥ 4.5)`)
  if (ปิด > เปิด) เหตุ.push(`สภาพปิด (${ปิด}) เด่นกว่าสภาพกดได้ (${เปิด}) ⇒ ตาจะวิ่งไปที่ปุ่มที่กดไม่ได้ก่อน`)
  return { ปิด, เปิด, ระยะห่าง, ผ่าน: เหตุ.length === 0, เหตุ }
}

