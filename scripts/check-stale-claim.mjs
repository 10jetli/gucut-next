import { readdirSync, readFileSync, statSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join, relative } from 'node:path'
import { ตัดคอมเมนต์ } from './lib/ตัดคอมเมนต์.mjs'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const ตัวเอง = relative(ROOT, fileURLToPath(import.meta.url))

function เดิน(dir, out = []) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (e.name === 'node_modules' || e.name === '.next' || e.name.startsWith('.')) continue
    const p = join(dir, e.name)
    if (e.isDirectory()) เดิน(p, out)
    /* 🔴 เดิมรับแค่ `.ts/.tsx` ⇒ ขยายรากไป `scripts/` แล้วก็ยังไม่เห็นอะไร
       เพราะตัวตรวจเป็น `.mjs` ทั้งหมด ⇒ **ขอบเขตมีสองชั้น: ราก และ นามสกุล**
       ⇒ แก้ชั้นเดียวแล้วเชื่อว่าขยายแล้ว = เลขยังเท่าเดิมและดูเหมือนไม่มีของ (20 ก.ย. 2569) */
    else if (/\.(ts|tsx|mjs)$/.test(e.name)) out.push(p)
  }
  return out
}

/* 🔑 **กฎ③ ต้องกวาด `scripts/` ด้วย** — เลขที่วัดรีโปตัวเองส่วนใหญ่อยู่ในตัวตรวจ ไม่ใช่ในจอ
   🔴 รอบแรกรากเป็น app/components/lib ⇒ ด่านเห็นแค่ 1 จุด ทั้งที่วัดมือได้ 8
      ⇒ **เลขของด่านกับเลขที่ผมวัด ขัดกันโดยที่ทั้งคู่ถูกในขอบเขตของตัวเอง**
      ⇒ ถ้าปล่อยไว้ คนอ่านจะเชื่อเลขของด่าน แล้วคิดว่ากองนี้เล็กกว่าจริง 8 เท่า
   ⚠️ กฎ① กับ ② ไม่ต้องการ `scripts/` (มันพูดเรื่องจอ) แต่กวาดรวมไม่เสียหาย
      เพราะทั้งสองกฎผูกกับรูปที่มีเฉพาะในจอ (`!REAL_SEND_ENABLED` · คำอ้างว่ายังไม่ได้ต่อท่อ) */
const ราก = ['app', 'components', 'lib', 'scripts']
let ไฟล์ = []
for (const r of ราก) {
  const เต็ม = join(ROOT, r)
  try { ไฟล์ = ไฟล์.concat(statSync(เต็ม).isDirectory() ? เดิน(เต็ม) : [เต็ม]) } catch { /* ไม่มี = ข้าม */ }
}
/* 🔒 ไม่มีไฟล์ให้ตรวจ = ตะแกรงพัง ไม่ใช่รีโปสะอาด */
if (ไฟล์.length < 50) {
  console.error(`🔴 เดินได้แค่ ${ไฟล์.length} ไฟล์ — **ตัวเดินไฟล์พัง ไม่ใช่ไม่มีของให้ตรวจ**`)
  process.exit(1)
}

/** เรนเดอร์ข้อความในกิ่งปิดไหม — ต้องมีทั้งเงื่อนไขและแท็กข้อความในหน้าต่างเดียวกัน
 *  (แค่ `disabled={… || !REAL_SEND_ENABLED}` ไม่ใช่ข้อความ ⇒ ไม่เข้ากฎข้อ ①) */
const เป็นกิ่งที่พูด = (หน้าต่าง) =>
  /!REAL_SEND_ENABLED/.test(หน้าต่าง) && /<(span|p|b|>)/.test(หน้าต่าง) && !/disabled=/.test(หน้าต่าง)

/** @param {{ปลูกบั๊ก?: false|'พิมพ์เหตุด้วยมือ'|'อ้างว่ายังไม่ต่อทั้งที่ต่อแล้ว'}} */
function ตรวจ({ ปลูกบั๊ก = false } = {}) {
  const ผิด = []
  let กิ่งที่พูด = 0
  let เลขที่วัดเอง = 0
  let ไฟล์ที่อ้างว่าไม่ต่อ = 0
  for (const p of ไฟล์) {
    const rel = relative(ROOT, p)
    /* 🔴 **ข้ามไฟล์ตัวเอง** (20 ก.ย. 2569) — พอขยายขอบเขตมากวาด `scripts/` ด่านนี้จับตัวเองทันที
       เพราะ **ข้อความ error ของมันเอง** มีทั้งคำอ้าง "ยังไม่ได้ต่อท่อ" และคำว่า fetch ติดกัน
       ⇒ คลาส **เครื่องมือที่กวาดไฟล์จะเจอตัวเอง** — เหยียบซ้ำอีกครั้งในวันเดียว
       ⚠️ ยกเว้นเฉพาะไฟล์นี้ไฟล์เดียว และเขียนเหตุไว้ ⇒ ไม่ใช่รายการยกเว้นที่โตได้ */
    if (rel === ตัวเอง) continue
    let ดิบ = readFileSync(p, 'utf8')
    if (ปลูกบั๊ก === 'พิมพ์เหตุด้วยมือ' && rel === 'app/core/stock/cost/page.tsx') {
      ดิบ = ดิบ.replace("{เหตุที่ยังไม่เปิด('stock/cost')}", 'รอท่านประธานอนุมัติจอนี้')
    }
    if (ปลูกบั๊ก === 'เลขวัดเองไม่มีวันที่' && rel === 'app/core/usage/page.tsx') {
      ดิบ = '/* กวาดเจอ 77 จุด ที่ต้องตามไปดู */\n' + ดิบ
    }
    if (ปลูกบั๊ก === 'อ้างว่ายังไม่ต่อทั้งที่ต่อแล้ว' && rel === 'app/core/stock/page.tsx') {
      ดิบ = ดิบ.replace('export default', '/* ยังไม่ได้ต่อท่อกับ ZORT */\nexport default')
    }
    /* 🔑 ตัดคอมเมนต์ก่อน **เฉพาะกฎข้อ ①** — เพราะคอมเมนต์ที่เล่าเรื่องบั๊กนี้มีคำว่า
       "รอท่านประธานอนุมัติ" อยู่ด้วย ⇒ ถ้าไม่ตัด ด่านจะร้องใส่คำอธิบายของตัวเอง
       (เหยียบมาแล้วกับ check-sentinel-leftovers: การเอ่ยถึง ≠ ของจริง) */
    const โค้ด = ตัดคอมเมนต์(ดิบ)
    const บรรทัด = โค้ด.split('\n')

    /* ── กฎ ① ───────────────────────────────────────── */
    for (let i = 0; i < บรรทัด.length; i++) {
      if (!/!REAL_SEND_ENABLED/.test(บรรทัด[i])) continue
      /* 🔴 หน้าต่าง 3 บรรทัดแคบเกินไป (เจอตอนรันครั้งแรก 20 ก.ย. 2569):
         พอตัดคอมเมนต์แล้วคอมเมนต์กลายเป็น **บรรทัดว่าง** (ตัวตัดรักษาจำนวนบรรทัดไว้)
         ⇒ คำอธิบาย 3 บรรทัดที่คั่นอยู่ กินหน้าต่างหมด ⇒ ด่านร้องใส่จอที่แก้ถูกแล้ว
         ⇒ 8 บรรทัดพอสำหรับกิ่ง JSX ที่ยาวที่สุดในรีโปนี้ (วัดแล้ว: quotations/new) */
      const หน้าต่าง = บรรทัด.slice(i, i + 8).join('\n')
      if (!เป็นกิ่งที่พูด(หน้าต่าง)) continue
      กิ่งที่พูด++
      if (!/เหตุที่ยังไม่เปิด\s*\(/.test(หน้าต่าง)) {
        ผิด.push(`${rel}:${i + 1}  🔴 กฎ① พิมพ์เหตุ "ยังไม่เปิด" ด้วยมือในกิ่งที่เดินไม่ถึง`
          + ' ⇒ ใช้ `เหตุที่ยังไม่เปิด(\'<คีย์>\')` จาก lib/real-send.ts')
      }
    }

    /* ── กฎ ③ **เลขที่เกิดจากการวัดรีโปตัวเอง ต้องมีวันที่** ── (20 ก.ย. 2569 · ใบ S4 รอบสอง)
       🔴 ของจริง: คอมเมนต์สองจุดที่ผมเขียนเอง **เมื่อชั่วโมงก่อน** ค้างไปแล้วภายในวันเดียวกัน
          · `check-claude-md-numbers`: เขียน "9 ตะแกรง เดินผ่าน 2" ⇒ ของจริงกลายเป็น 14/9
          · `check-cron-words`: เขียน "12 ตะแกรง เดินผ่าน 3" ⇒ ของจริงกลายเป็น 13/6
          · `lib/format.ts`: เขียน "39 จุดใน 27 ไฟล์" ⇒ วัดซ้ำบ่ายเดียวกันได้ 41/26
          ⇒ **และมันค้างเพราะการแก้ของผมเอง** ไม่ใช่เพราะเวลาผ่านไป
       🔑 เลขพวกนี้ต่างจากเลขอื่นตรงที่ **เราเป็นคนทำให้มันเปลี่ยน** ⇒ ค้างเร็วที่สุดในไฟล์
       ⚠️ **ขอบเขตแคบโดยตั้งใจ**: จับเฉพาะเลขที่มีคำกริยาวัดกำกับ (วัดได้/นับได้/กวาดเจอ/เจอ N)
          **และ** หน่วยเป็นของในโค้ด (จุด · ไฟล์ · ด่าน · ตะแกรง · สูตร …)
          ⇒ วัดประชากรก่อนเขียนกฎ: ตะแกรงหยาบได้ **98 จุด** ซึ่งส่วนใหญ่เป็นข้อความบนจอ/เพดาน
            ⇒ ถ้าใช้ตะแกรงนั้นจะได้ด่านที่ร้องใส่ของถูกจนคนถอด ⇒ **คมลงเหลือ 8 จุด (ไม่มีวันที่ 3)** */
    const กริยาวัด = /(วัดได้|วัดแล้ว|นับได้|กวาดได้|กวาดเจอ|เจอ\s*\*{0,2}\d|ตอนนี้มี|ปัจจุบันมี)/
    const หน่วยโค้ด = /\d{1,5}\s*\**\s*(จุด|ไฟล์|ด่าน|ตะแกรง|สูตร|เส้น|คีย์|ช่อง|แถว|จอ)/
    const มีวันที่ไทย = /(\d{1,2}\s*(ม\.ค\.|ก\.พ\.|มี\.ค\.|เม\.ย\.|พ\.ค\.|มิ\.ย\.|ก\.ค\.|ส\.ค\.|ก\.ย\.|ต\.ค\.|พ\.ย\.|ธ\.ค\.))/
    const บรรทัดทั้งหมด = ดิบ.split('\n')
    for (let i = 0; i < บรรทัดทั้งหมด.length; i++) {
      const l = บรรทัดทั้งหมด[i]
      if (!/^\s*(\/\/|\/\*|\*|\{\/\*)/.test(l)) continue
      if (!กริยาวัด.test(l) || !หน่วยโค้ด.test(l)) continue
      /* 🔴 **ธงลวงจริงรอบแรก**: `check-syntax` เขียนว่า "กวาดได้ 0 ไฟล์ = ตัวเดินไฟล์พัง"
         ⇒ นั่นคือ **ประโยคเกณฑ์** (ถ้าเจอ 0 ให้ถือว่าพัง) ไม่ใช่ผลการวัด ⇒ ไม่มีวันหมดอายุ
         🔑 แยกด้วย **เลข 0 + เครื่องหมายเท่ากับ/ให้ผล** ซึ่งเป็นรูปของการนิยาม ไม่ใช่การรายงาน */
      if (/\b0\s*\**\s*(จุด|ไฟล์|ด่าน|ตะแกรง|สูตร|เส้น|คีย์|ช่อง|แถว|จอ)/.test(l) && /=|⇒/.test(l)) continue
      เลขที่วัดเอง++
      if (มีวันที่ไทย.test(บรรทัดทั้งหมด.slice(Math.max(0, i - 3), i + 2).join('\n'))) continue
      ผิด.push(`${rel}:${i + 1}  🔴 กฎ③ เลขที่ได้จากการวัดรีโปตัวเอง **ไม่มีวันที่กำกับ**`
        + ' ⇒ มันค้างเพราะการแก้ของเราเอง ไม่ใช่เพราะเวลา')
    }

    /* ── กฎ ② ───────────────────────────────────────── */
    /* ดูทั้งไฟล์รวมคอมเมนต์ — เพราะของจริงข้อ ① อยู่ใน **คอมเมนต์หัวไฟล์** */
    const คำอ้าง = /ยังไม่ได้ต่อท่อ|ยังไม่ได้ต่อกับ ZORT/
    if (!คำอ้าง.test(ดิบ)) continue
    ไฟล์ที่อ้างว่าไม่ต่อ++
    /* `fetch(` ในโค้ด (ไม่ใช่ในคอมเมนต์) = ไฟล์นี้ต่อของอยู่จริง */
    if (!/\bfetch\s*\(/.test(โค้ด)) continue
    /* 🔴 **ด่านนี้ร้องใส่คำบรรยายของบั๊กที่ผมเพิ่งแก้ในรอบแรก** (20 ก.ย. 2569)
       ผมเขียนในคอมเมนต์ว่า `เดิมเขียนว่า "…ยังไม่ได้ต่อท่อกับ ZORT เลย"` เพื่อเล่าที่มา
       ⇒ ด่านจับประโยคนั้น ⇒ **การเอ่ยถึง ≠ การกล่าวอ้าง** (กับดักเดียวกับ check-sentinel-leftovers
         และผมเหยียบซ้ำในชั่วโมงเดียวกับที่เขียนด่านนี้)
       🔑 ทางแก้ที่ **ไม่ใช่รายการยกเว้น**: ใช้กติกาที่ใบ S4 สั่งไว้เองเป็นตัวแยก —
          **ของนอกโค้ดต้องเขียนเป็นเหตุการณ์ + วันที่** ⇒ มีวันที่ใกล้ ๆ = ผูกกับเวลาแล้ว ผ่าน
          ไม่มีวันที่ = สภาพลอย ๆ ที่หมดอายุเงียบได้ = ของที่ด่านนี้มีไว้จับ
       ⚠️ ข้อจำกัดที่รู้ตัว: คำกล่าวอ้าง **ที่มีวันที่แต่เป็นเท็จ** ด่านนี้จับไม่ได้
          (จับได้ก็ต้องยิงของจริง ซึ่งไม่ใช่งานของด่าน prebuild) */
    const มีวันที่ = /(\d{1,2}\s*(ม\.ค\.|ก\.พ\.|มี\.ค\.|เม\.ย\.|พ\.ค\.|มิ\.ย\.|ก\.ค\.|ส\.ค\.|ก\.ย\.|ต\.ค\.|พ\.ย\.|ธ\.ค\.))/
    /* 🔑 **เฉพาะคอมเมนต์** — ข้อความบนจอที่อยู่ในกิ่ง (`!zortList ? … : …`) ไม่เข้ากฎนี้
       เพราะเงื่อนไขของกิ่ง **ถูกประเมินใหม่ทุกครั้งที่เรนเดอร์** ⇒ มันแก้ตัวเองได้
       ส่วนคอมเมนต์ **ไม่มีอะไรประเมินมันอีกเลย** ⇒ นั่นคือที่ที่คำกล่าวอ้างหมดอายุเงียบ
       (เจอตอนรันรอบสอง: กฎเดิมร้องใส่ข้อความจอ 4 จุดใน LedgerScreen ซึ่ง **ถูกต้องตามกิ่งของมัน**
        ⇒ กฎกว้างเกิน ไม่ใช่จอผิด) */
    const เป็นคอมเมนต์ = (l) => /^\s*(\/\/|\/\*|\*|\{\/\*)/.test(l)
    const บรรทัดดิบ = ดิบ.split('\n')
    for (let i = 0; i < บรรทัดดิบ.length; i++) {
      if (!คำอ้าง.test(บรรทัดดิบ[i])) continue
      if (!เป็นคอมเมนต์(บรรทัดดิบ[i])) continue
      const แถว = บรรทัดดิบ.slice(Math.max(0, i - 4), i + 3).join('\n')
      if (มีวันที่.test(แถว)) continue
      ผิด.push(`${rel}:${i + 1}  🔴 กฎ② อ้างว่า "ยังไม่ได้ต่อท่อ" แบบไม่มีวันที่ ในไฟล์ที่มี \`fetch(\``
        + ' ⇒ เขียนเป็นเหตุการณ์+วันที่ และผูกกับกิ่งที่ยังไม่ต่อจริง')
    }
  }
  return { ผิด, กิ่งที่พูด, ไฟล์ที่อ้างว่าไม่ต่อ, เลขที่วัดเอง }
}

