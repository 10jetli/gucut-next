#!/usr/bin/env node
/* เทสตัวตัดสินผลการโหลดตัวช่วย
 *
 * 🔑 เกณฑ์ที่ทำให้เทสชุดนี้เกิด (ฝั่งท่อ 20 ก.ย. 2569):
 *    **"แก้อะไรแล้วจำนวนเทสไม่ขยับ ให้ถือว่ายังไม่ได้แก้"**
 *    ก่อนหน้านี้ตัวตัดสินฝังอยู่ในลูปที่ต้อง spawn ลูกกระบวนการจริง ⇒ พิสูจน์ได้แค่ด้วยการปลูกไฟล์
 *    ⇒ ยกออกมาเป็นฟังก์ชัน ⇒ ป้อนค่าตรง ๆ ได้ทุกทิศ รวมทิศที่ปลูกไฟล์จริงยาก
 */
import { ตัดสินผลโหลด, ผลโหลดทั้งหมด } from '../lib/ตัดสินผลโหลด.mjs'

let ตก = 0
const ต้อง = (ชื่อ, ได้, คาด) => {
  const ok = ได้ === คาด
  if (!ok) ตก++
  console.log(`${ok ? '✅' : '🔴'} ${ชื่อ} — คาด "${คาด}" ได้ "${ได้}"`)
}

console.log('── ทิศที่ด่านนี้มีไว้จับ ──')
ต้อง('ลืม import ⇒ ReferenceError', ตัดสินผลโหลด({ error: 'ReferenceError: x is not defined' }).ผล, 'โหลดไม่ได้')
ต้อง('พิมพ์อะไรตอนโหลด', ตัดสินผลโหลด({ เสียง: 'ฉันทำงานตอนถูกโหลด', หมุด: '3' }).ผล, 'ลงมือตอนโหลด')
ต้อง('process.exit ตอนโหลด (ไม่มีหมุด)', ตัดสินผลโหลด({ หมุด: null }).ผล, 'ออกก่อนเวลา')
ต้อง('โหลดได้แต่ไม่มี export', ตัดสินผลโหลด({ หมุด: '0' }).ผล, 'ไม่มี export')
ต้อง('ปกติทุกอย่าง', ตัดสินผลโหลด({ หมุด: '5' }).ผล, 'ผ่าน')

console.log('\n── ลำดับการตัดสิน (ของจริงมาพร้อมกันได้) ──')
/* 🔴 ถ้าเรียงสลับ ลูกที่พังแล้วพิมพ์ error ออก stderr จะถูกรายงานว่า "ลงมือตอนโหลด"
   ⇒ คนอ่านจะไปไล่หาผลข้างเคียงที่ไม่มีอยู่จริง แทนที่จะแก้ของที่พัง */
ต้อง('พังและพิมพ์ด้วย ⇒ ต้องรายงานว่าพัง', ตัดสินผลโหลด({ error: 'SyntaxError: bad', เสียง: 'อะไรสักอย่าง' }).ผล, 'โหลดไม่ได้')
ต้อง('พิมพ์และไม่มีหมุด ⇒ รายงานว่าลงมือก่อน', ตัดสินผลโหลด({ เสียง: 'พิมพ์', หมุด: null }).ผล, 'ลงมือตอนโหลด')

console.log('\n── ชนิดของ error ต้องแยกได้ (คนละทางแก้) ──')
ต้อง('ReferenceError', ตัดสินผลโหลด({ error: 'ReferenceError: a is not defined' }).ชนิด, 'ReferenceError')
ต้อง('SyntaxError', ตัดสินผลโหลด({ error: 'SyntaxError: unexpected token' }).ชนิด, 'SyntaxError')
ต้อง('error ที่ไม่บอกชนิด ⇒ Error', ตัดสินผลโหลด({ error: 'อะไรสักอย่างพัง' }).ชนิด, 'Error')

console.log('\n── ค่าที่ไม่คาดคิด ห้ามกลายเป็น "ผ่าน" ──')
ต้อง('เรียกโดยไม่ส่งอะไรเลย ⇒ ไม่มีหมุด = ออกก่อนเวลา', ตัดสินผลโหลด().ผล, 'ออกก่อนเวลา')
ต้อง('เสียงเป็นช่องว่างล้วน ⇒ ไม่นับว่าส่งเสียง', ตัดสินผลโหลด({ เสียง: '   \n ', หมุด: '2' }).ผล, 'ผ่าน')

console.log('\n── ทุกผลที่คืนต้องอยู่ในรายชื่อที่ประกาศไว้ ──')
/* กันคลาส "เปลี่ยนชื่อค่าในสัญญาร่วมแล้วอีกฝั่งเทียบชื่อเก่า" — ถ้ามีใครเพิ่มผลใหม่โดยไม่เติมรายชื่อ ข้อนี้แดง */
const ทุกกรณี = [{}, { error: 'x' }, { เสียง: 'a', หมุด: '1' }, { หมุด: '0' }, { หมุด: '9' }]
ต้อง('ผลทุกกรณีอยู่ในรายชื่อ', ทุกกรณี.every((c) => ผลโหลดทั้งหมด.includes(ตัดสินผลโหลด(c).ผล)), true)

console.log('\n── ข้อสุดท้าย: ปลูกรุ่นที่ "กลืนทุกอย่าง" ไว้ในเทสเอง ──')
/* 🔑 วันที่เทสชุดนี้เลิกแยกแยะ ข้อนี้จะแดงก่อน (ท่าที่ฝั่งท่อใช้ 20 ก.ย. 2569) */
const รุ่นพัง = () => ({ ผล: 'ผ่าน' })
const ต่างกัน = ['error', 'เสียง', 'หมุดหาย'].some((ทิศ) => {
  const ป้อน = ทิศ === 'error' ? { error: 'ReferenceError: z' } : ทิศ === 'เสียง' ? { เสียง: 'พิมพ์', หมุด: '1' } : { หมุด: null }
  return ตัดสินผลโหลด(ป้อน).ผล !== รุ่นพัง().ผล
})
ต้อง('รุ่นจริงกับรุ่นที่กลืนทุกอย่าง ให้ผลต่างกัน', ต่างกัน, true)

console.log(`\n${ตก ? `🔴 ตก ${ตก} ข้อ` : '✅ ผ่านทุกข้อ'}`)
process.exit(ตก ? 1 : 0)
