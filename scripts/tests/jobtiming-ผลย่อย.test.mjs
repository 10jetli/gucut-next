#!/usr/bin/env node
/* จอเวลางานต้องอ่าน **ผลย่อยของรอบล่าสุด** ที่ท่อส่งมา (`ผลย่อยรอบล่าสุด`)
 * (28 ก.ย. 2569 — ฝั่งท่อถามว่า "จอมีที่ไหนอ่าน checked ของ beam-sweep ไหม" คำตอบคือ **ไม่มีเลย**
 *  ทั้งที่ท่อส่งช่องนี้มาตั้งแต่ 20 ก.ย. ⇒ ช่องที่ถูกส่งแต่ไม่มีใครได้ยิน 8 วัน)
 *
 * 🔴 ทำไมช่องนี้สำคัญกว่า outcome: beam-sweep ตอบ 200 เสมอโดยตั้งใจ ⇒ สมุดจด `ok` ได้
 *    ทั้งที่ถาม ZORT ไม่สำเร็จสักใบ ⇒ ลูกค้าไม่ได้รับแจ้งว่าพัสดุออก โดยไม่มีตัวเลขไหนฟ้อง
 *
 * 🔑 **รุ่นแรกของเทสนี้มีรู และตัวควบคุมลบจับได้** (28 ก.ย. 2569 · จดไว้กันคนถัดไปเขียนซ้ำ):
 *    รุ่นแรกตรวจด้วย "ข้อความนี้มีในไฟล์จอไหม" ⇒ ปลูกสองรูปแล้ว **ยังเขียวทั้งคู่**
 *      · ห่อกล่องเตือนด้วย `{false && (...)}` — ข้อความยังอยู่ในไฟล์ ⇒ ตะแกรงผ่าน
 *      · เปลี่ยนตัวอ่านไปใช้ชื่อช่องผิด — ชื่อเดิมยังอยู่ในบรรทัดประกาศชนิด ⇒ ตะแกรงผ่าน
 *    ⇒ รากเดียวกัน: **ตรวจว่าข้อความมีอยู่ ไม่ได้ตรวจว่าเส้นทางนั้นใช้มัน**
 *    ⇒ ย้ายตรรกะไป `lib/job-subresult.ts` แล้วทดสอบ **พฤติกรรม** · เหลือเฉพาะข้อที่วัดพฤติกรรมไม่ได้
 *      (ว่าจอเรียกใช้ตรรกะนั้นจริง และกล่องเตือนไม่ถูกปิดตาย) จึงยังเป็นการอ่านรูปร่าง
 */
import { execFileSync } from 'node:child_process'
import { mkdtempSync, rmSync, readFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
/* 🔑 ต้องตัดคอมเมนต์ก่อนกวาด — ไม่งั้นตะแกรงจะจับ **คอมเมนต์ของตัวเอง** ว่าเป็นโค้ด
   (เหยียบทันทีตอนเขียนข้อนี้: คอมเมนต์ที่ยกตัวอย่างคำว่า "หมดงบเวลา" ทำให้ข้อนี้แดง) */
import { ตัดคอมเมนต์ } from '../lib/ตัดคอมเมนต์.mjs'

const out = mkdtempSync(join(tmpdir(), `jobsub-${process.pid}-`))
let ตก = 0
const ok = (ชื่อ, เงื่อนไข, เหตุ = '') => {
  console.log(`  ${เงื่อนไข ? '✅' : '❌'} ${ชื่อ}${เงื่อนไข ? '' : ` — ${เหตุ}`}`)
  if (!เงื่อนไข) ตก++
}

try {
  execFileSync('npx', ['tsc', 'lib/job-subresult.ts', '--outDir', out,
    '--module', 'es2022', '--target', 'es2022', '--moduleResolution', 'bundler', '--skipLibCheck'],
    { stdio: 'pipe' })
  const { อ่านผลย่อย, งานที่รอบล่าสุดไม่ครบ } = await import(join(out, 'job-subresult.js'))

  console.log('① สามสถานะ — "ไม่ได้นับชิ้น" ห้ามกลายเป็น 0')
  {
    ok('ท่อไม่ส่งช่องนี้ ⇒ null', อ่านผลย่อย({}) === null)
    ok('ท่อส่ง null ⇒ null', อ่านผลย่อย({ 'ผลย่อยรอบล่าสุด': null }) === null)
    ok('แถวเป็น undefined ⇒ null (ไม่พัง)', อ่านผลย่อย(undefined) === null)
    ok('มาครึ่งเดียว (ขาด "ล้ม") ⇒ null ไม่ใช่เดาเป็น 0',
      อ่านผลย่อย({ 'ผลย่อยรอบล่าสุด': { 'สำเร็จ': 5 } }) === null)
    ok('ค่าที่ไม่ใช่ตัวเลข ⇒ null ไม่ใช่ NaN/0',
      อ่านผลย่อย({ 'ผลย่อยรอบล่าสุด': { 'สำเร็จ': 'ห้า', 'ล้ม': 'ศูนย์' } }) === null)
  }

  console.log('② ค่าที่นับได้จริง ต้องผ่านมาครบ รวมทั้งศูนย์ที่เป็นศูนย์จริง')
  {
    const a = อ่านผลย่อย({ 'ผลย่อยรอบล่าสุด': { 'สำเร็จ': 12, 'ล้ม': 3 } })
    ok('อ่านทั้งสองช่อง', a?.ok === 12 && a?.fail === 3, JSON.stringify(a))
    const b = อ่านผลย่อย({ 'ผลย่อยรอบล่าสุด': { 'สำเร็จ': 0, 'ล้ม': 0 } })
    ok('นับแล้วได้ 0 จริง ⇒ ต้องไม่ใช่ null (ต่างจาก "ไม่ได้นับ")', b?.ok === 0 && b?.fail === 0, JSON.stringify(b))
  }

  console.log('③ คัดงานที่รอบล่าสุดทำไม่ครบ — เกณฑ์คือจำนวนที่ล้ม ไม่ใช่ outcome')
  {
    const rows = [
      { 'งาน': 'ครบ', 'ผลย่อยรอบล่าสุด': { 'สำเร็จ': 10, 'ล้ม': 0 } },
      { 'งาน': 'ไม่ครบ', 'ผลย่อยรอบล่าสุด': { 'สำเร็จ': 2, 'ล้ม': 3 }, 'ล่าสุด': { outcome: 'ok' } },
      { 'งาน': 'ไม่ได้นับชิ้น', 'ผลย่อยรอบล่าสุด': null, 'ล่าสุด': { outcome: 'failed' } },
    ]
    const พบ = งานที่รอบล่าสุดไม่ครบ(rows).map((x) => x['งาน'])
    ok('เจอเฉพาะงานที่มีชิ้นล้ม', JSON.stringify(พบ) === JSON.stringify(['ไม่ครบ']), JSON.stringify(พบ))
    ok('🔑 งานที่สมุดจดว่า ok แต่มีชิ้นล้ม ต้องถูกจับ (นี่คือเคสของ beam-sweep เป๊ะ)',
      พบ.includes('ไม่ครบ'))
    ok('งานที่ไม่ได้นับชิ้นไม่ถูกจับ แม้ outcome จะ failed (คนละคำถาม)', !พบ.includes('ไม่ได้นับชิ้น'))
    ok('ไม่มีแถวเลย ⇒ รายการว่าง ไม่พัง', งานที่รอบล่าสุดไม่ครบ(null).length === 0)
  }

  console.log('④ จอต้องเรียกตรรกะนี้จริง และต้องยกขึ้นหัวจอ (ข้อที่วัดพฤติกรรมไม่ได้ ⇒ อ่านรูปร่าง)')
  {
    const จอดิบ = readFileSync('components/zort/JobTiming.tsx', 'utf8')
    const จอ = จอดิบ            // ข้อที่ดูโครงสร้าง/ข้อความบนจอ ใช้ซอร์สเต็ม
    const จอโค้ด = ตัดคอมเมนต์(จอดิบ)   // ข้อที่ห้ามมีในโค้ดจริง ใช้ฉบับตัดคอมเมนต์
    ok('จอ import ตรรกะจาก lib (ไม่เขียนซ้ำใน JSX)',
      /from '@\/lib\/job-subresult'/.test(จอ) && /งานที่รอบล่าสุดไม่ครบ\(/.test(จอ))
    ok('ไม่มีสำเนาตรรกะเดิมค้างอยู่ในจอ', !/Number\.isFinite\(ok\) && Number\.isFinite\(fail\)/.test(จอ),
      'ตรรกะสองสำเนาจะเพี้ยนจากกันวันหนึ่ง')
    /* 🔑 กล่องเตือนต้องไม่ถูกปิดตาย — รุ่นแรกของเทสนี้จับ `{false && (` ไม่ได้ */
    const กล่อง = จอ.slice(Math.max(0, จอ.indexOf('รอบล่าสุดทำไม่ครบ') - 400), จอ.indexOf('รอบล่าสุดทำไม่ครบ'))
    ok('กล่องเตือนผูกกับผลจริง ไม่ใช่เงื่อนไขตายตัว',
      /รอบล่าสุดไม่ครบ\.length > 0 && \(/.test(กล่อง) && !/\{\s*false\s*&&/.test(กล่อง),
      'เจอเงื่อนไขตายตัวคร่อมกล่องเตือน ⇒ ข้อความยังอยู่ในไฟล์แต่ไม่มีวันขึ้นจอ')
    ok('มีคอลัมน์ในตารางด้วย', /สำเร็จ \/ ล้ม/.test(จอ))
    /* 🔴 รอบที่ **ถูกตัดกลางทางแต่ไม่มีใบไหนล้ม** จะดูสุขภาพดีถ้าโชว์บันทึกเฉพาะตอนล้ม
       ฝั่งท่อใส่เหตุที่รอบจบ (stoppedBecause) ต่อท้าย HTTP status ในบันทึกของรอบ
       ⇒ จอต้องโชว์บันทึกทุกแถว และต้องโชว์ **ข้อความของท่อตรงตัว** ไม่ใช่จับคำมาตัดสินเอง */
    ok('โชว์บันทึกของรอบล่าสุดทุกแถว ไม่ใช่เฉพาะแถวที่ล้ม',
      /\{x\['ล่าสุด'\]\?\.note && \(/.test(จอ), 'รอบที่ถูกตัดกลางทางแต่ไม่มีใบล้ม จะดูปกติทุกประการ')
    ok('ไม่จับคำในบันทึกมาตัดสินเอง (คำของท่อเปลี่ยนได้ทุกเมื่อ)',
      !/note[^\n]*\.includes\(|note[^\n]*match\(|หมดงบเวลา/.test(จอโค้ด),
      'เจอการอ่านคำในบันทึกเพื่อตัดสิน ⇒ จอกำลังเดาถ้อยคำของท่อ')
  }

  console.log('⑤ ทะเบียนงานต้องชี้คนอ่านมาที่ช่องนี้')
  {
    const ทะเบียน = readFileSync('app/core/settings-jobs/page.tsx', 'utf8')
    const แถว = ทะเบียน.slice(ทะเบียน.indexOf('กวาดออเดอร์ Beam ค้างจ่าย'))
    const ช่อง = แถว.slice(0, แถว.indexOf('ifDead'))
    ok('วิธีตรวจของ beam-sweep พูดถึงช่องสำเร็จ/ล้ม', /สำเร็จ\/ล้ม/.test(ช่อง), ช่อง.slice(0, 160))
    ok('ยังมีคำสั่งยิงให้ทำตามได้', /jobtiming=1/.test(ช่อง))
  }
} finally {
  rmSync(out, { recursive: true, force: true })
}

console.log(ตก ? `\n❌ ไม่ผ่าน ${ตก} ข้อ` : '\n✅ ผ่านทุกข้อ')
console.log('⚠️ ขอบเขต: ด่านนี้ตรวจว่า "จออ่านช่องนี้และยกขึ้นหัวจอ" — **ไม่ได้ตรวจว่าเลขบนจอถูก**')
console.log('   ตอนนี้ท่อยังไม่ได้ส่งผลย่อยของ beam-sweep ⇒ ต้องเปิดจอดูอีกครั้งหลังท่อส่งค่ามาจริง')
process.exit(ตก ? 1 : 0)
