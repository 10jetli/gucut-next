#!/usr/bin/env node
/* เส้นสถานะการเก็บบิล (`app/api/bills/status/route.ts`) — จอ /bills อ่านจากเส้นนี้
 * (ใบ t_mu8i1pu1 · 29 ก.ย. 2569 · คิวเรียงตามเกณฑ์ของใบ: แตะเงิน/สต็อก · กอง T2)
 *
 * 🔑 **และเทสนี้เป็นผู้ใช้คนแรกของ `scripts/lib/คอมไพล์เพื่อทดสอบ.mjs`**
 *    ตัวช่วยนั้นถูก commit ไปโดยยังไม่มีใครเรียก = **ทางที่ไม่เคยถูกเดิน**
 *    ⇒ เขียวของมันแปลว่า "ยังไม่มีใครลอง" ไม่ใช่ "ใช้ได้" ⇒ ใช้จริงที่นี่จึงเป็นการพิสูจน์มันด้วย
 *
 * 🔑 ของที่เส้นนี้ตัดสิน และตรึงไว้ทุกข้อ — **ท่านประธานสั่งเองว่าต้องบอกสถานะและเหตุ**
 *    "ไปดึงบิลวันไหนล่าสุด อับเดตด้วย บอกสเตตัส" · "เขียนบอกปัญหาด้วยว่าโหลดไม่ได้เพราะอะไร"
 *    ⇒ ทุกเจ้าที่ไม่ใช่ 'ปกติ' **ต้องมีเหตุที่อ่านรู้เรื่อง** ไม่ใช่คำว่า "ไม่ได้" ลอย ๆ
 *
 * 🔴 สี่สถานะต้องแยกกันจริง ห้ามยุบ "ไม่รู้" กับ "ไม่มี" เข้าด้วยกัน
 *    · อ่านไม่ได้     ⇒ ไม่รู้   (ไม่ใช่ "ไม่มีบิล")
 *    · อัปมือ         ⇒ อัปมือ  (ไม่มีตัวเก็บอัตโนมัติ ⇒ เสี่ยงขาดเงียบ)
 *    · เงียบเกิน 3 วัน ⇒ ควรมาดู (ตัวเก็บน่าจะไม่ทำงาน)
 *    · เพิ่งสแกน      ⇒ ปกติ
 *    ⚠️ และต้องตัดสินด้วย **สแกนล่าสุด** ไม่ใช่ **เจอบิลใหม่ล่าสุด**
 *       เจ้าที่ไม่มีบิลใหม่มานานไม่ได้แปลว่าระบบพัง — บางเจ้าออกบิลไม่ทุกเดือน
 *       (ถ้าสลับสองช่องนี้ จอจะขึ้น "ควรมาดู" ให้เจ้าที่ปกติ ⇒ คนเลิกเชื่อป้ายทั้งจอ)
 */
import { rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { คอมไพล์เพื่อทดสอบ } from '../lib/คอมไพล์เพื่อทดสอบ.mjs'

let ตก = 0
const ok = (ชื่อ, เงื่อนไข, เหตุ = '') => {
  console.log(`  ${เงื่อนไข ? '✅' : '❌'} ${ชื่อ}${เงื่อนไข ? '' : ` — ${เหตุ}`}`)
  /* 🔑 บรรทัดนี้พิมพ์ **เฉพาะตอนตก** ⇒ ใช้เป็นสมอของสูตรปลูกได้
     (ชื่อข้อบรรทัดบนถูกพิมพ์ตอนผ่านด้วย ⇒ เอาเป็นสมอแล้วตรงฟรีเสมอ) */
  if (!เงื่อนไข) { ตก++; console.log(`     🔴 ตกที่ ${ชื่อ}`) }
}
const เส้นTS = 'app/api/bills/status/route.ts'
let งาน

try {
  const ผล = คอมไพล์เพื่อทดสอบ({
    ไฟล์: [เส้นTS],
    ปลอม: {
      'next/server': `
export const NextResponse = {
  json: (ก้อน, init) => ({ status: init?.status ?? 200, async json() { return ก้อน } }),
}
`,
      /* 🔴 **ของที่ export เป็น `const` ต้องอ่านสดทุกครั้งที่ถูกแตะ**
         `export const X = JSON.parse(readFileSync(...))` อ่านครั้งเดียวตอน import ⇒ ค่าถูกตรึง
         ⇒ การป้อนสภาพใหม่ทีหลังไม่มีผลเลย และเทสจะล้ม **เฉพาะข้อที่พึ่ง const**
            ส่วนข้อที่พึ่งฟังก์ชันยังผ่าน (ฟังก์ชันอ่านตอนถูกเรียก)
         🔑 รูปของอาการนี้คือ **ล้มบางข้อแบบดูสมเหตุสมผล** ⇒ ชวนให้ไปแก้โค้ดที่ไม่ได้ผิด
         📌 คลาสนี้ผมเหยียบ 3 ครั้งในวันเดียว (ARCH_ADMIN · ผัง · ทะเบียนเจ้า) ⇒ ใช้ Proxy อ่านสด */
      '@/lib/vendors': `
import { readFileSync } from 'node:fs';
const อ่าน = () => JSON.parse(readFileSync(process.env.ป้อนเจ้า, 'utf8'));
export const BILL_VENDORS = new Proxy([], {
  get: (_t, k) => {
    const a = อ่าน();
    const v = a[k];
    return typeof v === 'function' ? v.bind(a) : v;
  },
  has: (_t, k) => k in อ่าน(),
  ownKeys: () => Reflect.ownKeys(อ่าน()),
  getOwnPropertyDescriptor: (_t, k) => Reflect.getOwnPropertyDescriptor(อ่าน(), k),
});
`,
      '@/lib/billreport': `
import { readFileSync } from 'node:fs';
export async function สรุปทุกเจ้า() {
  return JSON.parse(readFileSync(process.env.ป้อนสรุป, 'utf8'));
}
`,
    },
  })
  งาน = ผล.ที่ออก
  const ไฟล์เจ้า = join(งาน, 'เจ้า.json')
  const ไฟล์สรุป = join(งาน, 'สรุป.json')
  process.env['ป้อนเจ้า'] = ไฟล์เจ้า
  process.env['ป้อนสรุป'] = ไฟล์สรุป
  /* 🔴 ตัวปลอมอ่านไฟล์ **ตอน import** (บนสุดของโมดูล) ⇒ ต้องมีไฟล์อยู่ก่อน
     รอบแรกผมเขียนไฟล์หลัง import ⇒ ENOENT แล้วพังด้วยเหตุที่ไม่เกี่ยวกับสิ่งที่ทดสอบ */
  writeFileSync(ไฟล์เจ้า, '[]', 'utf8')
  writeFileSync(ไฟล์สรุป, '[]', 'utf8')
  const { GET } = await import(ผล.พาธของ(เส้นTS))

  /** ป้อนสภาพแล้วอ่านผลของเจ้าตัวแรก */
  const ยิง = async (เจ้า, สรุป) => {
    writeFileSync(ไฟล์เจ้า, JSON.stringify(เจ้า), 'utf8')
    writeFileSync(ไฟล์สรุป, JSON.stringify(สรุป), 'utf8')
    const r = await GET()
    return (await r.json()).เจ้า[0]
  }
  const เมื่อ = (ชมก่อน) => new Date(Date.now() - ชมก่อน * 3600e3).toISOString()
  const ฐานสรุป = (เพิ่ม = {}) => ({
    id: 'tiktok', ชื่อ: 'TikTok', รวมทุกเดือน: 4,
    เดือน: { '2026-08': { จำนวน: 4, ใบจริงที่อัปไว้: 4, ไฟล์: [] } },
    สแกนล่าสุด: เมื่อ(1), เจอบิลใหม่ล่าสุด: เมื่อ(1), ...เพิ่ม,
  })

  console.log('① ตัวควบคุมลบ — เพิ่งสแกน มีตัวเก็บอัตโนมัติ ⇒ ปกติ และเหตุต้องว่าง')
  {
    const v = await ยิง([{ id: 'tiktok', collect: { วิธี: 'g1' } }], [ฐานสรุป()])
    ok('สถานะ ปกติ', v.สถานะ === 'ปกติ', `${v.สถานะ} · ${v.เหตุ}`)
    ok('เหตุว่าง (ไม่ใส่คำอธิบายตอนไม่มีปัญหา)', v.เหตุ === '', JSON.stringify(v.เหตุ))
    ok('บอกชั่วโมงที่แล้วเป็นตัวเลข', typeof v.ชั่วโมงที่แล้ว === 'number', String(v.ชั่วโมงที่แล้ว))
  }

  console.log('② 🔴 อ่านคลังไม่ได้ ⇒ "ไม่รู้" **ไม่ใช่ "ไม่มีบิล"** และต้องบอกเหตุจริง')
  {
    const v = await ยิง([{ id: 'tiktok', collect: { วิธี: 'g1' } }],
      [ฐานสรุป({ อ่านไม่ได้: 'ถังตอบ 500', รวมทุกเดือน: 0, เดือน: {} })])
    ok('สถานะ ไม่รู้', v.สถานะ === 'ไม่รู้', `${v.สถานะ} ⇒ ยุบเป็น "ปกติ" หรือ "ไม่มีบิล" = จอโกหก`)
    ok('เหตุอ้างข้อความจริงจากคลัง', v.เหตุ.includes('500'), v.เหตุ)
    ok('เหตุบอกว่าอ่านคลังไม่ได้ ไม่ใช่คำว่า "ไม่ได้" ลอย ๆ', /อ่านคลังไม่ได้/.test(v.เหตุ), v.เหตุ)
    ok('ข้อนี้ต้องมาก่อนทุกข้อ — แม้ตัวเก็บมีปัญหาด้วย ก็ยังต้องเป็น ไม่รู้',
      (await ยิง([{ id: 'tiktok', collect: { วิธี: 'g1', ปัญหา: 'เซสชันหลุด' } }],
        [ฐานสรุป({ อ่านไม่ได้: 'ถังตอบ 500' })])).สถานะ === 'ไม่รู้',
      'ถ้าตัวเก็บชนะ เราจะไปแก้เซสชันทั้งที่จริง ๆ อ่านคลังไม่ได้')
  }

  console.log('③ ตัวเก็บมีปัญหา ⇒ ควรมาดู · แต่ถ้าเป็นเจ้าที่อัปมือ ⇒ อัปมือ')
  {
    const อัตโนมัติ = await ยิง([{ id: 'tiktok', collect: { วิธี: 'g1', ปัญหา: 'เซสชันหลุด' } }], [ฐานสรุป()])
    ok('ตัวเก็บอัตโนมัติมีปัญหา ⇒ ควรมาดู', อัตโนมัติ.สถานะ === 'ควรมาดู', อัตโนมัติ.สถานะ)
    ok('เหตุคือข้อความจริงของตัวเก็บ', อัตโนมัติ.เหตุ === 'เซสชันหลุด', อัตโนมัติ.เหตุ)
    const มือ = await ยิง([{ id: 'tiktok', collect: { วิธี: 'อัปมือ', ปัญหา: 'ยังไม่มีใครอัป' } }], [ฐานสรุป()])
    ok('เจ้าที่อัปมือมีปัญหา ⇒ อัปมือ (ไม่ใช่ ควรมาดู)', มือ.สถานะ === 'อัปมือ', มือ.สถานะ)
  }

  console.log('④ ไม่มีตัวเก็บอัตโนมัติ ⇒ อัปมือ พร้อมเหตุที่อ่านรู้เรื่อง')
  {
    const v = await ยิง([{ id: 'tiktok', collect: { วิธี: 'อัปมือ' } }], [ฐานสรุป()])
    ok('สถานะ อัปมือ', v.สถานะ === 'อัปมือ', v.สถานะ)
    ok('เหตุบอกว่าไม่มีตัวเก็บอัตโนมัติ', v.เหตุ === 'ไม่มีตัวเก็บอัตโนมัติ', v.เหตุ)
  }

  console.log('⑤ ยังไม่เคยสแกน ⇒ ไม่รู้ (ไม่ใช่ ปกติ และไม่ใช่ ควรมาดู)')
  {
    const v = await ยิง([{ id: 'tiktok', collect: { วิธี: 'g1' } }], [ฐานสรุป({ สแกนล่าสุด: null })])
    ok('สถานะ ไม่รู้', v.สถานะ === 'ไม่รู้', v.สถานะ)
    ok('เหตุบอกว่ายังไม่เคยสแกน', v.เหตุ === 'ยังไม่เคยสแกน', v.เหตุ)
    ok('ชั่วโมงที่แล้ว = null ไม่ใช่ 0', v.ชั่วโมงที่แล้ว === null,
      `${v.ชั่วโมงที่แล้ว} ⇒ 0 อ่านว่า "เพิ่งสแกนเมื่อกี้" ซึ่งกลับหัวกับความจริง`)
  }

  console.log('⑥ 🔴 เกณฑ์ 3 วัน — และต้องตัดสินด้วย "สแกนล่าสุด" ไม่ใช่ "เจอบิลใหม่ล่าสุด"')
  {
    ok('สแกนมา 71 ชม. ⇒ ยังปกติ', (await ยิง([{ id: 'tiktok', collect: { วิธี: 'g1' } }],
      [ฐานสรุป({ สแกนล่าสุด: เมื่อ(71) })])).สถานะ === 'ปกติ')
    const เกิน = await ยิง([{ id: 'tiktok', collect: { วิธี: 'g1' } }], [ฐานสรุป({ สแกนล่าสุด: เมื่อ(100) })])
    ok('สแกนมา 100 ชม. ⇒ ควรมาดู', เกิน.สถานะ === 'ควรมาดู', เกิน.สถานะ)
    ok('เหตุบอกจำนวนวันจริง', /ไม่ได้สแกนมา 4 วัน/.test(เกิน.เหตุ), เกิน.เหตุ)
    /* 🔴 ข้อที่สำคัญที่สุดของหมวดนี้: เจ้าที่สแกนอยู่ตลอดแต่ไม่มีบิลใหม่มานาน **ต้องปกติ**
       บางเจ้าออกบิลไม่ทุกเดือน ⇒ ถ้าใช้ช่องผิด จอจะขึ้น "ควรมาดู" ให้เจ้าที่ปกติ
       แล้วคนจะเลิกเชื่อป้ายทั้งจอ ซึ่งแพงกว่าการไม่มีป้าย */
    const ไม่มีบิลใหม่นาน = await ยิง([{ id: 'tiktok', collect: { วิธี: 'g1' } }],
      [ฐานสรุป({ สแกนล่าสุด: เมื่อ(1), เจอบิลใหม่ล่าสุด: เมื่อ(24 * 200) })])
    ok('สแกนสม่ำเสมอแต่ไม่มีบิลใหม่ 200 วัน ⇒ ยังปกติ', ไม่มีบิลใหม่นาน.สถานะ === 'ปกติ',
      `${ไม่มีบิลใหม่นาน.สถานะ} ⇒ ใช้ช่อง "เจอบิลใหม่ล่าสุด" ตัดสิน = เตือนผิดตัว`)
  }

  console.log('⑦ ทุกเจ้าที่ไม่ใช่ปกติ ต้องมีเหตุ — ไม่มีเจ้าไหนได้ป้ายแดงแบบไม่บอกสาเหตุ')
  {
    const หลายเจ้า = await (async () => {
      writeFileSync(ไฟล์เจ้า, JSON.stringify([
        { id: 'a', collect: { วิธี: 'g1' } },
        { id: 'b', collect: { วิธี: 'อัปมือ' } },
        { id: 'c', collect: { วิธี: 'g1' } },
      ]), 'utf8')
      writeFileSync(ไฟล์สรุป, JSON.stringify([
        { ...ฐานสรุป(), id: 'a' },
        { ...ฐานสรุป(), id: 'b' },
        { ...ฐานสรุป({ สแกนล่าสุด: เมื่อ(200) }), id: 'c' },
      ]), 'utf8')
      return (await (await GET()).json()).เจ้า
    })()
    const ขาดเหตุ = หลายเจ้า.filter((v) => v.สถานะ !== 'ปกติ' && !v.เหตุ)
    ok('ไม่มีเจ้าไหนสถานะไม่ปกติแล้วเหตุว่าง', ขาดเหตุ.length === 0,
      `ขาดเหตุ: ${ขาดเหตุ.map((v) => v.id).join(' · ')} ⇒ ท่านประธานสั่งเองว่าต้องบอกว่าเพราะอะไร`)
    ok('ได้ครบ 3 เจ้า', หลายเจ้า.length === 3, String(หลายเจ้า.length))
  }
} finally {
  if (งาน) rmSync(งาน, { recursive: true, force: true })
}

console.log(ตก ? `\n❌ ไม่ผ่าน ${ตก} ข้อ` : '\n✅ ผ่านทุกข้อ')
console.log('⚠️ ขอบเขต: ปลอม next/server · ทะเบียนเจ้า · ตัวสรุป — ของจริงคือ **ตรรกะตัดสินสถานะ**'
  + ' (ลำดับความสำคัญของเหตุ · เกณฑ์ 3 วัน · การเลือกช่องที่ใช้ตัดสิน)')
process.exit(ตก ? 1 : 0)
