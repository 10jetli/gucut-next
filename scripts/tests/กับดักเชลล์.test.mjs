/* กับดักเชลล์ที่ผมเหยียบซ้ำ — **ยิงของจริงทุกครั้งที่รันเทส แทนที่จะพึ่งความจำ**
 * (19 ก.ย. 2569 · ฝั่งท่อเสนอท่านี้ · ผมเหยียบสองตัวนี้ในสิบนาทีทั้งที่มีบันทึกถูกต้องอยู่แล้ว)
 *
 * 🔴 ปัญหาที่ไฟล์นี้เกิดมาแก้: **บันทึกที่ถูกต้อง ผูกกับกลไกแล้ว และผมอ่านผ่านตาทุกเซสชัน
 *    ก็ยังไม่กันผมได้** เพราะ **ไม่มีอะไรมาตรวจ** ⇒ ใบที่ถูกต้องกับใบที่ไม่มีอยู่ ให้ผลเท่ากัน
 *    ตอนที่มือกำลังพิมพ์คำสั่ง
 *    ⇒ ไฟล์นี้ไม่ได้กันตอนพิมพ์ (ทำไม่ได้) แต่ทำให้ **พฤติกรรมของเชลล์ถูกยืนยันซ้ำด้วยเครื่อง**
 *      ⇒ วันที่มันเปลี่ยน (เชลล์คนละตัว · locale ต่าง) เราจะรู้ ไม่ใช่เดา
 *
 * 🔑 ทุกเคสมี **ทิศบวก (ท่าผิด ⇒ ต้องพัง)** คู่กับ **ทิศลบ (ท่าถูก ⇒ ต้องรอด)**
 *    มีแต่ทิศเดียวพิสูจน์ไม่ได้ว่าเราเข้าใจสาเหตุถูก
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'

const รัน = (โค้ด) => {
  const r = spawnSync('bash', ['-c', โค้ด], { encoding: 'utf8' })
  return { out: r.stdout ?? '', err: r.stderr ?? '', code: r.status }
}

/* ── กับดัก ①: backtick ในเครื่องหมายคำพูดคู่ — เหยียบ 9 ครั้ง ──
   อาการเปลี่ยนไปเรื่อย ๆ: จดหมายขาดคำ · commit message ขาดคำ · และล่าสุด
   **ตะแกรงคืน 0 จุด ซึ่งอ่านเหมือนข่าวดี** ⇒ รูปเดียวกัน อาการคนละแบบ */
test('① คำพูดคู่ + backtick ⇒ ข้อความหายเงียบ และคำสั่งยัง "สำเร็จ"', () => {
  const r = รัน('echo "ช่อง `ไม่มีคำสั่งชื่อนี้` ถูกใช้"')
  assert.ok(!r.out.includes('ไม่มีคำสั่งชื่อนี้'), '🔴 ถ้าข้อความยังอยู่ แปลว่าเชลล์เปลี่ยนพฤติกรรม — อ่านไฟล์นี้ใหม่ทั้งไฟล์')
  assert.ok(r.out.includes('ช่อง') && r.out.includes('ถูกใช้'), 'ส่วนที่เหลือยังอยู่ ⇒ จึงดูเหมือนข้อความปกติ')
  assert.equal(r.code, 0, '🔑 ที่อันตรายที่สุด: **exit 0** ⇒ ไม่มีอะไรฟ้องว่าข้อความขาด')
})

test('① ทิศลบ: คำพูดเดี่ยว ⇒ ข้อความอยู่ครบ', () => {
  const r = รัน("echo 'ช่อง `ไม่มีคำสั่งชื่อนี้` ถูกใช้'")
  assert.ok(r.out.includes('ไม่มีคำสั่งชื่อนี้'), 'ท่าที่ถูกต้องคงข้อความไว้ครบ')
})

test('① ทิศลบ: heredoc ที่ quote ชื่อคั่น ⇒ ข้อความอยู่ครบ', () => {
  const r = รัน("cat <<'EOF'\nช่อง `ไม่มีคำสั่งชื่อนี้` ถูกใช้\nEOF")
  assert.ok(r.out.includes('ไม่มีคำสั่งชื่อนี้'), 'heredoc ที่ quote แล้วเชลล์ไม่แตะเนื้อข้อความ — ท่าที่ใช้กับ git commit')
})

/* ── กับดัก ②: ชื่อตัวแปรภาษาไทยใน bash — เหยียบ 7 ครั้ง ──
   อาการ: **สคริปต์เดินต่อแล้วพิมพ์ว่าสำเร็จ** ส่วนบรรทัดที่ต้องการค่าจะได้ค่าว่าง
   และ `bash -n` จับไม่ได้ เพราะไวยากรณ์ไม่ผิด — มันตีความเป็น "ชื่อคำสั่ง" */
test('② ชื่อตัวแปรไทย ⇒ ไม่ใช่การกำหนดค่า แต่เป็น "คำสั่งไม่พบ" และสคริปต์เดินต่อ', () => {
  const r = รัน('ผลลัพธ์=40; echo "เดินต่อแล้ว [$ผลลัพธ์]"')
  assert.ok(/not found|command not found/.test(r.err), '🔴 ต้องมีเสียงบ่นใน stderr')
  assert.ok(r.out.includes('เดินต่อแล้ว'), '🔑 สคริปต์ **ไม่หยุด** ⇒ บรรทัดถัดไปทำงานต่อเหมือนไม่มีอะไรเกิดขึ้น')
  assert.ok(!r.out.includes('40'), 'ค่าที่ตั้งใจตั้งไม่เคยไปถึงไหน ⇒ ได้ค่าว่างแทน')
})

test('② ทิศลบ: ชื่อ ASCII ⇒ ได้ค่าจริง และไม่มีเสียงบ่น', () => {
  const r = รัน('n_empty=40; echo "เดินต่อแล้ว [$n_empty]"')
  assert.ok(r.out.includes('[40]'), 'ท่าที่ถูกต้องให้ค่าจริง')
  assert.equal(r.err.trim(), '', 'ไม่มีอะไรใน stderr')
})

test('② `bash -n` จับกับดักนี้ไม่ได้ — จึงต้องรันจริงเท่านั้น', () => {
  const r = spawnSync('bash', ['-n', '-c', 'ผลลัพธ์=40'], { encoding: 'utf8' })
  assert.equal(r.status, 0, '🔑 ตัวตรวจไวยากรณ์ผ่าน ⇒ ด่านที่ใช้ `bash -n` อย่างเดียวจะเงียบตลอดกาล')
})
