/* คลัง "รูปที่เคยพลาด" ต้องเป็นของจริง ไม่ใช่ของที่นึกเอา
 * (19 ก.ย. 2569 — ฝั่งท่อทำคลังแบบเดียวกันแล้ว **เทสจับได้ว่า 3 รูปของเขาเป็นของนึกเอา**
 *  ⇒ ผมจึงเขียนเทสก่อนที่คลังจะโต ไม่ใช่หลังจากมันปนกันแล้ว)
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { รูปที่เคยพลาด, ของจริงเท่านั้น, สรุปคลัง } from '../lib/รูปที่เคยพลาด.mjs'

test('ทุกรูปต้องบอกครบว่า เมื่อไหร่ · ใครพลาด · เล่าว่าอะไร', () => {
  for (const x of รูปที่เคยพลาด) {
    assert.match(x.เมื่อ, /25[6-9]\d/, `${x.ชื่อ}: ไม่มีปีในช่อง เมื่อ`)
    assert.ok(x.ใครพลาด?.length > 3, `${x.ชื่อ}: ไม่ได้บอกว่าใครพลาด`)
    assert.ok(x.เล่า?.length > 20, `${x.ชื่อ}: คำเล่าสั้นเกินกว่าจะใช้ซ้ำได้`)
  }
})

test('🔑 ช่อง `ของจริง` ต้องเป็น boolean เสมอ — ห้ามปล่อยว่างแล้วให้คนเดา', () => {
  for (const x of รูปที่เคยพลาด) {
    assert.equal(typeof x.ของจริง, 'boolean', `${x.ชื่อ}: ไม่ได้ระบุว่าเคยพลาดจริงหรือนึกเอา`)
  }
})

test('🔒 คลังว่าง = ไม่มีตัวควบคุมให้ยืม ⇒ ถือว่าไม่ผ่าน', () => {
  assert.ok(ของจริงเท่านั้น().length > 0, 'ไม่มีรูปที่เคยพลาดจริงเลยสักรูป')
})

test('สรุปคลังต้องแยกจำนวน "จริง" กับ "นึกเอา" ออกจากกัน', () => {
  const s = สรุปคลัง()
  assert.match(s, /เคยพลาดจริง \d+/)
  assert.match(s, /นึกเอา \d+/)
})

test('🔑 ชื่อรูปห้ามซ้ำ — ไม่งั้นคลังจะนับรูปเดียวกันสองครั้ง', () => {
  const ชื่อ = รูปที่เคยพลาด.map((x) => x.ชื่อ)
  assert.equal(new Set(ชื่อ).size, ชื่อ.length)
})
