`,
      '@/lib/billblobs': `
import { readFileSync, appendFileSync } from 'node:fs';
const อ่าน = () => JSON.parse(readFileSync(process.env.ป้อนfix, 'utf8'));
const จด = (o) => appendFileSync(process.env.จดfix, JSON.stringify(o) + '\\n', 'utf8');
