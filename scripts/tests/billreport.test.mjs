#!/usr/bin/env node
/* สรุปสถานะบิลรายเจ้า (`lib/billreport.ts`) — **ที่เดียว** ที่ /api/bills/report กับ /api/bills/status ใช้
 * (ใบ t_mu8i1pu1 · 29 ก.ย. 2569) 108 บรรทัด ไม่มีเทสแตะเลย
 *
 * 🔴 ของจริงสองเคสที่ทำให้ไฟล์นี้เป็นแบบทุกวันนี้:
 *   ① 15 ก.ย. 2569 — ตัวคัดซ้ำรอบแรกเทียบแค่ "ใบจริง vs บิลจากเมล" **ไม่เคยเทียบใบจริงด้วยกันเอง**
 *      ⇒ TikTok ส.ค. ขึ้น 8 ใบ ทั้งที่มี 4 (ใบเดียวกันถูกอัปสองครั้งคนละชื่อ)
 *      🔑 จับได้เพราะ **ยิงของจริงแล้วเลขไม่ตรงกับที่ควรเป็น** ไม่ใช่จากการอ่านโค้ด
 *   ② 18 ก.ย. 2569 — ท่านประธานสั่งว่าเดือนต้องมาจาก **รอบบิลในเอกสาร** ไม่ใช่คำนำหน้าชื่อไฟล์
 *      (และผลที่ตั้งใจให้เป็น: ชื่อไฟล์กับเดือนที่จัด **ไม่ตรงกันได้** — ห้ามใครเห็นแล้วแก้กลับ)
 *
 * 🔑 กฎที่สำคัญไม่แพ้กัน: **"อ่านไม่ได้" ห้ามยุบเป็น 0** — ศูนย์ที่แปลว่าไม่มีบิล
 *    กับศูนย์ที่แปลว่าอ่านถังไม่ได้ พาคนไปคนละทาง ⇒ เทสนี้ตรวจ **สองศูนย์แยกกัน** (ข้อ ④ กับ ⑤)
 *
 * ⚠️ ไฟล์นี้ import ด้วยพาธย่อ `@/lib/...` ⇒ ต้องคอมไพล์ด้วย tsconfig ที่มี `paths`
 *    (ได้ type-check จริงกับ vendors.ts/billblobs.ts ตัวจริง) แล้วค่อย **ชี้ import ที่ออกมาไปตัวปลอม**
 *    ปลอมเฉพาะ **ที่เก็บบิล** — ตรรกะคัดซ้ำ · จัดเดือน · bill-filing.ts เป็นของจริงทุกบรรทัด
 */
import { execFileSync } from 'node:child_process'
import { mkdtempSync, writeFileSync, readFileSync, readdirSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const out = mkdtempSync(join(tmpdir(), `billreport-${process.pid}-`))
let ตก = 0
const ok = (ชื่อ, เงื่อนไข, เหตุ = '') => {
  console.log(`  ${เงื่อนไข ? '✅' : '❌'} ${ชื่อ}${เงื่อนไข ? '' : ` — ${เหตุ}`}`)
  if (!เงื่อนไข) ตก++
}

try {
  /* คอมไพล์ด้วย tsconfig ชั่วคราวที่รู้จัก `@/*` — ไม่งั้น tsc ตอบ TS2307 แล้วเราจะไม่ได้ type-check เลย */
  const tsconfig = join(out, 'tsconfig.json')
  writeFileSync(tsconfig, JSON.stringify({
    compilerOptions: {
      target: 'es2022', module: 'es2022', moduleResolution: 'bundler', skipLibCheck: true,
      strict: true, baseUrl: process.cwd(), paths: { '@/*': ['./*'] },
      /* ⚠️ tsconfig อยู่ใน /tmp ⇒ tsc หา @types เองไม่เจอ (billblobs.ts ใช้ Buffer)
         ไม่ชี้ typeRoots = TS2580 "Cannot find name Buffer" แล้วเราจะไปงงว่าโค้ดผิด */
      typeRoots: [join(process.cwd(), 'node_modules/@types')], types: ['node'],
      rootDir: join(process.cwd(), 'lib'), outDir: out,
    },
    files: [join(process.cwd(), 'lib/billreport.ts')],
  }))
  execFileSync('npx', ['tsc', '-p', tsconfig], { stdio: 'pipe' })
  writeFileSync(join(out, 'package.json'), '{"type":"module"}')

  /* ที่เก็บบิลปลอม — อ่านคำสั่งจากไฟล์ JSON ที่เทสเขียนใหม่ก่อนทุกรอบ
     ⚠️ อ่านใหม่ทุกครั้ง **ห้าม cache** — ของค้างจากรอบก่อนให้ตัวเลขที่น่าเชื่อแต่ผิด */
  writeFileSync(join(out, 'ปลอม-billblobs.js'), `
import { readFileSync } from 'node:fs';
const อ่าน = () => JSON.parse(readFileSync(process.env.ป้อนบิล, 'utf8'));
export async function loadBillIndexBlobs() {
  const p = อ่าน();
  if (p.พังตอนอ่าน) throw new Error(p.พังตอนอ่าน);
  return p.ดัชนี;
}
export async function listVendorBlobNames() { return อ่าน().ชื่อไฟล์; }
export async function loadRealPeriods() { return อ่าน().รอบบิล; }
`)
  writeFileSync(join(out, 'ปลอม-vendors.js'), 'export const BILL_VENDORS = []\n')

  /* ชี้ import ของโค้ดจริงไปตัวปลอม + เติม .js ให้พาธสัมพัทธ์ (tsc ไม่เติมให้) */
  for (const f of readdirSync(out).filter((x) => x.endsWith('.js') && !x.startsWith('ปลอม-'))) {
    const ที่ = join(out, f)
    /* ⚠️ **ลำดับมีผล** — เติม .js ให้พาธสัมพัทธ์ให้เสร็จก่อน แล้วค่อยแทนพาธย่อ
       รอบแรกผมสลับลำดับ ⇒ ตัวปลอมกลายเป็น `ปลอม-vendors.js.js` แล้ว Node ตอบว่าหาไฟล์ไม่เจอ
       (พังด้วยเหตุที่ไม่เกี่ยวกับสิ่งที่ทดสอบ = เสียเวลาไล่ผิดจุด) */
    writeFileSync(ที่, readFileSync(ที่, 'utf8')
      .replace(/(from\s+['"]\.\/[^'"]+?)(?<!\.js)(['"])/g, '$1.js$2')
      .replace(/(['"])@\/lib\/billblobs\1/g, "'./ปลอม-billblobs.js'")
      .replace(/(['"])@\/lib\/vendors\1/g, "'./ปลอม-vendors.js'")
      .replace(/(['"])@\/lib\/bill-filing\1/g, "'./bill-filing.js'"))
  }
  /* 🔑 ยืนยันว่าตัวปลอมถูกต่อจริง — ถ้า replace ไม่โดน (เช่นวันหน้าเปลี่ยนรูป import)
     โค้ดจะ import '@/lib/billblobs' ที่ Node แก้ไม่ได้ ⇒ พังด้วยเหตุที่อ่านว่า "เทสพัง" ไม่ใช่ "โค้ดผิด" */
  const ซอร์สที่คอมไพล์แล้ว = readFileSync(join(out, 'billreport.js'), 'utf8')
  ok('ต่อ import ไปตัวปลอมได้จริง (ไม่เหลือ @/lib/ ค้าง)', !ซอร์สที่คอมไพล์แล้ว.includes('@/lib/'),
    ซอร์สที่คอมไพล์แล้ว.split('\n').filter((l) => l.includes('@/lib/')).join(' · '))

  const ไฟล์ป้อน = join(out, 'ป้อน.json')
  process.env['ป้อนบิล'] = ไฟล์ป้อน
  const ตั้ง = (o) => writeFileSync(ไฟล์ป้อน, JSON.stringify({
    ชื่อไฟล์: [], ดัชนี: { lastScan: null, entries: [] }, รอบบิล: {}, พังตอนอ่าน: null, ...o,
  }), 'utf8')
  const { สรุปบิลรายเจ้า } = await import(join(out, 'billreport.js'))
  const เจ้า = { id: 'tiktok', name: 'TikTok', portal: null, everyMonth: true }

  console.log('① 🔴 ใบเดียวกันที่อัปสองครั้งคนละชื่อ ⇒ ต้องนับเป็นใบเดียว (เคส TikTok ส.ค.)')
  {
    ตั้ง({ ชื่อไฟล์: [
      '2026-08_REAL_THTT202606634060-บริษัท ศีตกาล เทรดดิ้ง จำกัด-Invoice.pdf',  // ตัวเก็บบน g1
      '2026-08_REAL_TikTok-Invoice-THTT202606634060.pdf',                        // ไฟล์แนบในเมล
      '2026-08_REAL_THTT202606634061-อีกใบจริง.pdf',
    ] })
    const r = await สรุปบิลรายเจ้า(เจ้า)
    ok('ส.ค. นับได้ 2 ใบ (ไม่ใช่ 3)', r.เดือน['2026-08']?.จำนวน === 2,
      `ได้ ${r.เดือน['2026-08']?.จำนวน} ⇒ ใบเดียวกันคนละชื่อถูกนับซ้ำ (บั๊กเดิม 8 ทั้งที่มี 4)`)
    ok('รวมทุกเดือนตรงกับผลรวมของเดือน', r.รวมทุกเดือน === 2, String(r.รวมทุกเดือน))
    ok('เก็บชื่อไฟล์ที่เลือกไว้ให้คนตรวจย้อนได้', r.เดือน['2026-08'].ไฟล์.length === 2,
      JSON.stringify(r.เดือน['2026-08'].ไฟล์))
  }

  console.log('② ใบจริงที่ไม่มีเลขที่ในชื่อ ⇒ ห้ามยุบรวมกันเป็นใบเดียว (ไม่มีเลข ≠ เลขเดียวกัน)')
  {
    ตั้ง({ ชื่อไฟล์: ['2026-08_REAL_สแกนจากเครื่องถ่าย-1.pdf', '2026-08_REAL_สแกนจากเครื่องถ่าย-2.pdf'] })
    const r = await สรุปบิลรายเจ้า(เจ้า)
    ok('สองใบที่อ่านเลขที่ไม่ออก ยังเป็น 2 ใบ', r.เดือน['2026-08']?.จำนวน === 2,
      `ได้ ${r.เดือน['2026-08']?.จำนวน} ⇒ เอา "เลขที่ว่าง" มาเป็นกุญแจ = บิลจริงหายจากจอ`)
  }

  console.log('③ ใบที่ระบบสร้างเอง (GEN) ⇒ ตัดทิ้ง **เฉพาะเดือนที่มีใบจริงแล้ว**')
  {
    ตั้ง({
      ชื่อไฟล์: ['2026-08_REAL_THTT202608000111-ใบจริง.pdf'],
      ดัชนี: { lastScan: '2026-09-29', entries: [
        { month: '2026-08', filename: 'GEN-สิงหา.pdf', attachmentId: 'GEN' },
        { month: '2026-07', filename: 'GEN-กรกฎา.pdf', attachmentId: 'GEN' },
      ] },
    })
    const r = await สรุปบิลรายเจ้า(เจ้า)
    ok('ส.ค. มีใบจริงแล้ว ⇒ GEN ถูกตัด เหลือ 1', r.เดือน['2026-08']?.จำนวน === 1,
      JSON.stringify(r.เดือน['2026-08']))
    ok('ก.ค. ไม่มีใบจริง ⇒ GEN ยังอยู่', r.เดือน['2026-07']?.จำนวน === 1,
      'ตัด GEN ทุกเดือน = เดือนที่ยังไม่มีใบจริงกลายเป็นศูนย์ทั้งที่มีของ')
    ok('นับแยกว่าเป็นใบจริงกี่ใบ', r.เดือน['2026-08'].ใบจริงที่อัปไว้ === 1
      && r.เดือน['2026-07'].ใบจริงที่อัปไว้ === 0, JSON.stringify(r.เดือน))
  }

  console.log('④ 🔴 เดือนมาจาก **รอบบิลในเอกสาร** ไม่ใช่คำนำหน้าชื่อไฟล์ (ท่านประธานสั่ง 18 ก.ย.)')
  {
    const ชื่อ = '2026-09_REAL_THTT202609000222-ใบที่ชื่อบอกกันยายน.pdf'
    ตั้ง({ ชื่อไฟล์: [ชื่อ], รอบบิล: { [ชื่อ]: '2026-08' } })
    const r = await สรุปบิลรายเจ้า(เจ้า)
    ok('จัดเข้าเดือน ส.ค. ตามรอบบิลในเอกสาร', r.เดือน['2026-08']?.จำนวน === 1, JSON.stringify(r.เดือน))
    ok('ไม่อยู่ในเดือน ก.ย. ตามชื่อไฟล์', !r.เดือน['2026-09'],
      'ใช้ชื่อไฟล์ ⇒ จอรวมกับจอรายเจ้านับคนละเดือน = ตัวเลขสองที่ไม่ตรงโดยไม่มีใครรู้ว่าทำไม')
  }

  console.log('⑤ ⚠️ ยังไม่เคยอ่านรอบบิล (null) ⇒ ถอยไปใช้ชื่อไฟล์ **ชั่วคราว** (ไม่รู้ ≠ ไม่มี)')
  {
    const ชื่อ = '2026-09_REAL_THTT202609000333-ยังไม่เคยอ่าน.pdf'
    ตั้ง({ ชื่อไฟล์: [ชื่อ], รอบบิล: { [ชื่อ]: null } })
    const r = await สรุปบิลรายเจ้า(เจ้า)
    ok('ยังโชว์ในเดือนตามชื่อไฟล์ (ไม่หายไปเงียบ ๆ)', r.เดือน['2026-09']?.จำนวน === 1,
      `${JSON.stringify(r.เดือน)} ⇒ ทิ้งใบที่ยังอ่านไม่ได้ = บิลจริงหายจากจอโดยไม่มีอะไรฟ้อง`)
  }

  console.log('⑥ 🔴 อ่านถังไม่ได้ ⇒ ต้องบอกว่าอ่านไม่ได้ **ห้ามยุบเป็น 0 เฉย ๆ**')
  {
    ตั้ง({ พังตอนอ่าน: 'ถังตอบ 500' })
    const r = await สรุปบิลรายเจ้า(เจ้า)
    ok('มีช่องบอกว่าอ่านไม่ได้ พร้อมเหตุ', typeof r.อ่านไม่ได้ === 'string' && r.อ่านไม่ได้.includes('500'),
      JSON.stringify(r).slice(0, 140))
    ok('ยังคืนโครงเดิมให้จอใช้ได้ (ไม่พังทั้งก้อน)', r.id === 'tiktok' && r.รวมทุกเดือน === 0
      && r.ต้องมีทุกเดือน === true, JSON.stringify(r).slice(0, 140))
  }

  console.log('⑦ ไม่มีบิลจริง ๆ ⇒ 0 **โดยไม่มีช่องอ่านไม่ได้** (สองศูนย์นี้คนละเรื่อง)')
  {
    ตั้ง({ ดัชนี: { lastScan: '2026-09-29', entries: [] } })
    const r = await สรุปบิลรายเจ้า(เจ้า)
    ok('รวม 0', r.รวมทุกเดือน === 0, String(r.รวมทุกเดือน))
    ok('ไม่มีช่องอ่านไม่ได้', r.อ่านไม่ได้ === undefined,
      'มีช่องนี้ด้วย ⇒ จอขึ้นว่าอ่านถังไม่ได้ทั้งที่แค่ยังไม่มีบิล ⇒ คนไปไล่ปัญหาที่ไม่มีอยู่')
    ok('สแกนล่าสุดส่งต่อมาจากดัชนี', r.สแกนล่าสุด === '2026-09-29', String(r.สแกนล่าสุด))
  }

  console.log('⑧ ดัชนีเป็น null (ยังไม่เคยสแกน) ⇒ ห้ามพัง และห้ามอ้างว่าเคยสแกน')
  {
    ตั้ง({ ดัชนี: null, ชื่อไฟล์: ['2026-08_REAL_THTT202608000444-มีใบจริงแต่ยังไม่เคยสแกนเมล.pdf'] })
    const r = await สรุปบิลรายเจ้า(เจ้า)
    ok('ยังนับใบจริงได้', r.รวมทุกเดือน === 1, String(r.รวมทุกเดือน))
    ok('สแกนล่าสุด = null ไม่ใช่วันนี้', r.สแกนล่าสุด === null, String(r.สแกนล่าสุด))
    ok('ไม่มีช่องอ่านไม่ได้ (null ไม่ใช่ error)', r.อ่านไม่ได้ === undefined, String(r.อ่านไม่ได้))
  }
} finally {
  rmSync(out, { recursive: true, force: true })
}

console.log(ตก ? `\n❌ ไม่ผ่าน ${ตก} ข้อ` : '\n✅ ผ่านทุกข้อ')
console.log('⚠️ ขอบเขต: ปลอมเฉพาะที่เก็บบิล (Netlify Blobs) — ตรรกะคัดซ้ำ/จัดเดือน/bill-filing เป็นของจริง')
process.exit(ตก ? 1 : 0)
