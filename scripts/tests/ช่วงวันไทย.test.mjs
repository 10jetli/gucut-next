/* เทสช่วงวันไทยที่ส่งเข้า ZORT
 *
 * 🔴 เทสชุดนี้เกิดจาก **การวัด ไม่ใช่การคาดเดา** (20 ก.ย. 2569):
 *    ย้อน diff ของคอมมิต `df2229c` (แก้หน้าต่างวันเป็นวันไทย) กลับเป็นรุ่นบั๊ก
 *    ⇒ **สาย 75 ขั้น exit 0 · tsc เขียว** · ฝั่งท่อปลูกบั๊กเดียวกัน ⇒ **เทส 716 ข้อเงียบสนิท**
 *    ⇒ ⇒ ทั้งสองฝั่ง **ไม่มีตาข่าย** สำหรับบั๊กที่ตัดสินว่าจะสั่งของเท่าไหร่/คืนใบไหน
 *
 * 🔑 เขียนตามท่าที่ตกลงกัน: **มีตัวควบคุมที่ปลูกรุ่นพังไว้ในเทสเอง**
 *    ⇒ วันที่เทสชุดนี้เลิกแยกแยะ ข้อควบคุมจะแดงก่อน
 */
import { ช่วงวันย้อนหลัง, จำนวนวันที่ใช้ได้ } from '../../lib/format.ts'

let ตก = 0
const ต้อง = (ชื่อ, ได้, คาด) => {
  const ok = JSON.stringify(ได้) === JSON.stringify(คาด)
  if (!ok) ตก++
  console.log(`${ok ? '✅' : '🔴'} ${ชื่อ}\n     คาด ${JSON.stringify(คาด)}  ได้ ${JSON.stringify(ได้)}`)
}

/* 20 ก.ย. 2569 เวลาไทย 00:30 = 19 ก.ย. 17:30 UTC — จุดที่บั๊ก UTC จะเลื่อนวันกลับ */
const ตีครึ่งไทย = Date.parse('2026-09-19T17:30:00.000Z')
const เที่ยงไทย = Date.parse('2026-09-20T05:00:00.000Z')

console.log('── เคสที่ทำให้เทสชุดนี้เกิด: ตี 0.30 เวลาไทย ──')
ต้อง('ย้อน 0 วัน ⇒ ต้องเป็นวันที่ 20 ทั้งคู่ (รุ่นบั๊กได้ 19)',
  ช่วงวันย้อนหลัง(0, ตีครึ่งไทย), { ตั้งแต่: '2026-09-20', ถึง: '2026-09-20' })
ต้อง('ย้อน 30 วัน จากตี 0.30 ⇒ 21 ส.ค. – 20 ก.ย.',
  ช่วงวันย้อนหลัง(30, ตีครึ่งไทย), { ตั้งแต่: '2026-08-21', ถึง: '2026-09-20' })

console.log('\n── กลางวันไทย: ของที่ถูกอยู่แล้วต้องไม่ขยับ ──')
ต้อง('ย้อน 7 วัน จากเที่ยง ⇒ 13–20 ก.ย.',
  ช่วงวันย้อนหลัง(7, เที่ยงไทย), { ตั้งแต่: '2026-09-13', ถึง: '2026-09-20' })

console.log('\n── ข้ามเดือน/ข้ามปี ──')
ต้อง('ย้อน 1 วัน จาก 1 ม.ค. ตี 0.30 ไทย ⇒ 31 ธ.ค. – 1 ม.ค.',
  ช่วงวันย้อนหลัง(1, Date.parse('2026-12-31T17:30:00.000Z')), { ตั้งแต่: '2026-12-31', ถึง: '2027-01-01' })

console.log('\n── "ไม่รู้" ห้ามกลายเป็นตัวเลข (บทเรียนที่ฝั่งท่อเจอในตัวเดียวกันนี้) ──')
/* 🔴 `Number(null)` = 0 · `Number('')` = 0 ⇒ ถ้าไม่กันชนิดก่อน "ไม่รู้" จะกลายเป็น "วันนี้วันเดียว" */
for (const [ชื่อ, ค่า] of [['null', null], ['undefined', undefined], ['ข้อความว่าง', ''], ['ช่องว่างล้วน', '   '], ['object', {}], ['อาเรย์ว่าง', []], ['true', true], ['ไม่ใช่เลข', 'สามสิบ'], ['ติดลบ', -5], ['NaN', NaN]]) {
  ต้อง(`${ชื่อ} ⇒ null`, จำนวนวันที่ใช้ได้(ค่า), null)
}
ต้อง('ช่วงวันเมื่อจำนวนวันไม่รู้ ⇒ null ทั้งก้อน', ช่วงวันย้อนหลัง(null, เที่ยงไทย), null)
ต้อง('เลขศูนย์จริง ⇒ 0 ไม่ใช่ null', จำนวนวันที่ใช้ได้(0), 0)
ต้อง('ข้อความที่เป็นเลข ⇒ แปลงได้', จำนวนวันที่ใช้ได้('30'), 30)

console.log('\n── ตัวควบคุม: ปลูกรุ่นพังไว้ในเทสเอง ──')
/* รุ่นพัง = ใช้ UTC ตรง ๆ (รูปที่คอมมิต df2229c แก้ไป) */
const รุ่นพัง = (วัน, ms) => ({
  ตั้งแต่: new Date(ms - วัน * 86400000).toISOString().slice(0, 10),
  ถึง: new Date(ms).toISOString().slice(0, 10),
})
const ผลพัง = รุ่นพัง(0, ตีครึ่งไทย)
ต้อง('รุ่นพังให้วันที่ 19 (ยืนยันว่าเคสนี้แยกแยะได้จริง)', ผลพัง.ถึง, '2026-09-19')
ต้อง('รุ่นจริงกับรุ่นพัง ต้องให้ผลต่างกัน',
  JSON.stringify(ช่วงวันย้อนหลัง(0, ตีครึ่งไทย)) !== JSON.stringify(ผลพัง), true)

console.log(`\n${ตก ? `🔴 ตก ${ตก} ข้อ` : '✅ ผ่านทุกข้อ'}`)
process.exit(ตก ? 1 : 0)
