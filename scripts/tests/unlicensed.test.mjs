#!/usr/bin/env node
/* กติกาคัด "เลื่อย/บาร์ ไม่มีทะเบียน" (`lib/unlicensed.ts`)
 * ท่านประธานสั่งทำหน้าใหม่ 9 ต.ค. 2569
 *
 * 🔴 **ทำไมเทสนี้สำคัญกว่าหน้าตาของจอ**
 *    ของทะเบียนกับไม่มีทะเบียน **คนละราคา 100-200฿ และคนละกลุ่มลูกค้า**
 *    ปนกัน = ขายผิดราคาและผิดกฎหมาย (~/claude-shared/กฎ-สองสายขาย-ห้ามรวม.md)
 *    ⇒ ตัวคัดพลาดฝั่งเดียวก็เสียหายจริง ไม่ใช่แค่จอดูแปลก
 *
 * ⚠️ เทสนี้เรียก **ฟังก์ชันตัวจริง** ไม่ลอกเงื่อนไขมาเขียนซ้ำ
 *    (ของจริงวันนี้: ตอนทำเครื่องมืออื่น ผมลอกเงื่อนไขลงเทส แล้วปลูกบั๊กในตัวจริง
 *     เทสยังเขียว เพราะมันวัดสำเนาของตัวเอง ⇒ ห้ามเหยียบซ้ำ)
 *
 * 📏 ชื่อหมวดทั้ง 12 รายการข้างล่าง **คัดลอกจากของจริง** ที่ยิง /api/core?list=categories
 *    เมื่อ 9 ต.ค. 2569 (43 หมวด) ⇒ ไม่ใช่ชื่อที่แต่งขึ้น
 */
import { rmSync } from 'node:fs'
import { คอมไพล์เพื่อทดสอบ } from '../lib/คอมไพล์เพื่อทดสอบ.mjs'

let ตก = 0
const ok = (ชื่อ, เงื่อนไข, เหตุ = '') => {
  console.log(`  ${เงื่อนไข ? '✅' : '❌'} ${ชื่อ}${เงื่อนไข ? '' : ` — ${เหตุ}`}`)
  if (!เงื่อนไข) { ตก++; console.log(`     🔴 ตกที่ ${ชื่อ}`) }
}

const ไฟล์ = 'lib/unlicensed.ts'
let งาน
try {
  const ผล = คอมไพล์เพื่อทดสอบ({ ไฟล์: [ไฟล์], ปลอม: {} })
  งาน = ผล
  const m = await import(ผล.พาธของ(ไฟล์))
  const { หมวดไม่มีทะเบียน, กลุ่มของหมวด } = m

  /* ── หมวดจริงทั้ง 12 ที่มีคำว่า เลื่อย หรือ บาร์ (จาก 43 หมวดของร้าน) ── */
  const เข้าเกณฑ์ = [
    'บาร์ KINGKONG',
    'บาร์ NEWWAVE',
    'เลื่อยยนต์ NEWWAVE',
    'เลื่อยยนต์ Series F',
  ]
  const ต้องคัดออก = [
    /* ของทะเบียน — คนละราคา คนละลูกค้า */
    'บาร์ KINGKONG แบบมีทะเบียน',
    'บาร์ KINGKONG แบบมีทะเบียน (ใน Marketplace)',
    'บาร์ NEWWAVE แบบมีทะเบียน',
    'บาร์ NEWWAVE แบบมีทะเบียน (ใน Marketplace)',
    'เลื่อยยนต์ แบบมีทะเบียน',
    'เลื่อยยนต์ แบบมีทะเบียน (ใน Marketplace)',
    /* มีคำว่า "เลื่อย" แต่ไม่ใช่เลื่อยโซ่ยนต์/บาร์โซ่ — ตัวที่ทำให้กติกาแรกพลาด */
    'น้ำมันเลื่อย',
    'ใบเลื่อยวงเดือน STIHL, OREGON',
  ]

  for (const c of เข้าเกณฑ์) {
    ok(`เก็บหมวดไม่มีทะเบียน: ${c}`, หมวดไม่มีทะเบียน(c) === true, 'ถูกคัดออกผิด')
  }
  for (const c of ต้องคัดออก) {
    ok(`คัดออก: ${c}`, หมวดไม่มีทะเบียน(c) === false, 'หลุดเข้ามา')
  }

  /* ── ตัวควบคุมลบ: จำนวนต้องเป็น 4 พอดีจากชุด 12 หมวดจริง ── */
  const ทั้ง12 = [...เข้าเกณฑ์, ...ต้องคัดออก]
  const ได้ = ทั้ง12.filter(หมวดไม่มีทะเบียน)
  ok('จากหมวดจริง 12 รายการ ต้องเข้าเกณฑ์ 4', ได้.length === 4,
    `ได้ ${ได้.length}: ${ได้.join(' · ')}`)

  /* ── หมวดใหม่ที่ร้านอาจเพิ่มในอนาคต ต้องถูกเก็บเอง (ห้ามฮาร์ดโค้ดรายชื่อ) ── */
  ok('ยี่ห้อใหม่ "บาร์ XYZ" ต้องถูกเก็บเอง', หมวดไม่มีทะเบียน('บาร์ XYZ') === true,
    'กติกาฮาร์ดโค้ดรายชื่อ ⇒ หน้าจะค้างเมื่อร้านเพิ่มหมวด')
  ok('ยี่ห้อใหม่แบบมีทะเบียนต้องถูกคัดออกเอง',
    หมวดไม่มีทะเบียน('บาร์ XYZ แบบมีทะเบียน') === false, 'ของทะเบียนหลุดเข้าหน้าที่ไม่มีทะเบียน')

  /* ── เว้นวรรคท้ายคำนำหน้ามีความหมาย — กันคำที่ขึ้นต้นเหมือนกันแต่ไม่เกี่ยว ── */
  ok('"บาร์โค้ด" ต้องไม่เข้าเกณฑ์ (ไม่มีเว้นวรรค)',
    หมวดไม่มีทะเบียน('บาร์โค้ด') === false, 'คำนำหน้าไม่มีเว้นวรรค ⇒ เก็บของที่ไม่เกี่ยว')

  /* ── ค่าที่อ่านไม่ออกต้องไม่ถูกนับเข้า (ไม่รู้ ≠ เข้าเกณฑ์) ── */
  for (const v of [null, undefined, '', '   ']) {
    ok(`ค่าว่าง/ไม่รู้ (${JSON.stringify(v)}) ต้องไม่เข้าเกณฑ์`,
      หมวดไม่มีทะเบียน(v) === false, 'ค่าที่อ่านไม่ออกถูกนับเข้า')
  }

  /* ── แยกกลุ่มเลื่อย/บาร์ ── */
  ok('บาร์ KINGKONG อยู่กลุ่ม บาร์', กลุ่มของหมวด('บาร์ KINGKONG') === 'บาร์')
  ok('เลื่อยยนต์ Series F อยู่กลุ่ม เลื่อย', กลุ่มของหมวด('เลื่อยยนต์ Series F') === 'เลื่อย')
} catch (e) {
  console.log('  ❌ เทสล้มก่อนเริ่มวัด —', e?.message || e)
  ตก++
} finally {
  if (งาน?.ที่ออก) rmSync(งาน.ที่ออก, { recursive: true, force: true })
}

console.log(ตก ? `\n🔴 ตก ${ตก} ข้อ` : '\n✅ ผ่านทุกข้อ')
process.exit(ตก ? 1 : 0)
