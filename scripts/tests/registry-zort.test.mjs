#!/usr/bin/env node
/* ตรรกะฝั่ง ZORT ของจอ /core/registry (`lib/registry-zort.ts`)
 * ท่านประธานสั่ง 10 ต.ค. 2569: "เอาหน้านี้มาต่อ เชื่อม zort"
 *
 * 🔴 **ทำไมเทสนี้สำคัญกว่าหน้าตาของจอ**
 *    จอนี้มีปุ่มที่ **เขียนจำนวนลง ZORT จริง** ⇒ ถ้าตัวทำนายผิด ท่านจะกดยืนยัน
 *    โดยเชื่อเลขที่จอบอก · เลขทะเบียนเกินจริง = ประกาศขายของที่ปิดทะเบียนแล้ว = ปัญหากฎหมาย
 *
 * ⚠️ เรียก **ฟังก์ชันตัวจริง** ไม่ลอกสูตรมาเขียนซ้ำ (เทสที่วัดสำเนาตัวเองจะเขียวตอนปลูกบั๊ก)
 *
 * 📏 เลขในฟิกซ์เจอร์ **มาจากกรณีจริงที่วัดได้ 10 ต.ค. 2569** ไม่ใช่เลขแต่ง:
 *    `Bar NW 16` คงเหลือ 4 · พร้อมขาย 0 (จอง 4) · `Bar NW 18` 0/0 (จอง 0)
 *    `Bar NW 24-9800` 5/0 จะเขียน 0 ⇒ −5 (เคสที่ด่านของท่อตีกลับจริง)
 *    `Bar NW 22` −1/−1 (จอง 0 แต่ค่าติดลบอยู่แล้ว — ของจริงมี ห้ามถือว่าผิด)
 */
import { rmSync } from 'node:fs'
import { คอมไพล์เพื่อทดสอบ } from '../lib/คอมไพล์เพื่อทดสอบ.mjs'

let ตก = 0
const ok = (ชื่อ, เงื่อนไข, เหตุ = '') => {
  console.log(`  ${เงื่อนไข ? '✅' : '❌'} ${ชื่อ}${เงื่อนไข ? '' : ` — ${เหตุ}`}`)
  if (!เงื่อนไข) { ตก++; console.log(`     🔴 ตกที่ ${ชื่อ}`) }
}

const ไฟล์ = 'lib/registry-zort.ts'
let งาน
try {
  const ผล = คอมไพล์เพื่อทดสอบ({ ไฟล์: [ไฟล์], ปลอม: {} })
  งาน = ผล
  const m = await import(ผล.พาธของ(ไฟล์))
  const { จองอยู่, คาดพร้อมขาย, จะถูกตีกลับ, คำเตือนแถว, ต้องเลือกรหัสเอง, refของการกด, ขาที่ยังไม่มี } = m

  const มีค่า = (คงเหลือ, พร้อมขาย) =>
    ({ สถานะ: 'มีค่า', คงเหลือ, พร้อมขาย, ชื่อ: 'ทดสอบ', ราคา: null })

  console.log('\n── ไม่รู้ ต้องไม่กลายเป็น 0 (สามสถานะ ห้ามยุบ) ──')
  ok('ยังไม่อ่าน ⇒ จองอยู่ = null', จองอยู่({ สถานะ: 'ยังไม่อ่าน' }) === null)
  ok('อ่านไม่ได้ ⇒ จองอยู่ = null',
    จองอยู่({ สถานะ: 'อ่านไม่ได้', เหตุ: 'timeout' }) === null)
  ok('ไม่มีรหัสนี้ ⇒ จองอยู่ = null', จองอยู่({ สถานะ: 'ไม่มีรหัสนี้' }) === null)
  ok('ยังไม่อ่าน ⇒ คาดพร้อมขาย = null', คาดพร้อมขาย(9, { สถานะ: 'ยังไม่อ่าน' }) === null)
  ok('ยังไม่อ่าน ⇒ จะถูกตีกลับ = null (ไม่ใช่ false)',
    จะถูกตีกลับ(9, { สถานะ: 'ยังไม่อ่าน' }) === null)

  console.log('\n── สูตรจอง: คงเหลือ − พร้อมขาย (เลขของจริง 10 ต.ค.) ──')
  ok('Bar NW 16 · 4/0 ⇒ จอง 4', จองอยู่(มีค่า(4, 0)) === 4)
  ok('Bar NW 18 · 0/0 ⇒ จอง 0', จองอยู่(มีค่า(0, 0)) === 0)
  ok('Bar NW 24-9800 · 5/0 ⇒ จอง 5', จองอยู่(มีค่า(5, 0)) === 5)
  ok('Bar NW 22 · −1/−1 ⇒ จอง 0 (ติดลบแต่ไม่มีจอง)', จองอยู่(มีค่า(-1, -1)) === 0)
  ok('Bar NW 24-7800 · 0/−1 ⇒ จอง 1', จองอยู่(มีค่า(0, -1)) === 1)

  console.log('\n── ทำนายผลหลังเขียน ──')
  ok('เขียน 9 ใส่ 4/0 ⇒ พร้อมขาย 5', คาดพร้อมขาย(9, มีค่า(4, 0)) === 5)
  ok('เขียน 9 ใส่ 0/0 ⇒ พร้อมขาย 9', คาดพร้อมขาย(9, มีค่า(0, 0)) === 9)
  ok('เขียน 7 ใส่ −1/−1 ⇒ พร้อมขาย 7', คาดพร้อมขาย(7, มีค่า(-1, -1)) === 7)
  ok('เขียน 0 ใส่ 5/0 ⇒ พร้อมขาย −5 ⇒ ตีกลับ', จะถูกตีกลับ(0, มีค่า(5, 0)) === true)
  ok('เขียน 9 ใส่ 0/0 ⇒ ไม่ตีกลับ', จะถูกตีกลับ(9, มีค่า(0, 0)) === false)
  ok('เขียน 8 ใส่ 0/−1 ⇒ พร้อมขาย 7 ⇒ ไม่ตีกลับ', จะถูกตีกลับ(8, มีค่า(0, -1)) === false)

  console.log('\n── ข้อความเตือนต้องสร้างจากตัวแปรชุดเดียวกับที่ตัดสิน ──')
  /* 🔴 **เทสรุ่นแรกของข้อนี้ผ่านตอนปลูกบั๊ก** — มันเช็คแค่ว่าข้อความมีเลข 0 / -5 / 5
     ซึ่ง **ทั้งสองกิ่งพิมพ์เหมือนกัน** ⇒ ถอดกิ่ง "จะถูกตีกลับ" ออกแล้วยังเขียว
     ⇒ ต้องเช็ค **ความหมายที่ต่างกัน** ไม่ใช่ตัวเลขที่เหมือนกัน (ปลูกบั๊กจับได้ 10 ต.ค. 2569) */
  const ต = คำเตือนแถว(0, มีค่า(5, 0))
  ok('เคสที่ด่านจะตีกลับ: ข้อความต้องบอกว่าจะถูกตีกลับ',
    typeof ต === 'string' && ต.includes('ตีกลับ'), `ได้ ${JSON.stringify(ต)}`)
  ok('เคสที่ด่านจะตีกลับ: ต้องบอกจำนวนจองที่ต้องเคลียร์',
    typeof ต === 'string' && ต.includes('5') && ต.includes('-5'), `ได้ ${JSON.stringify(ต)}`)
  const ต2 = คำเตือนแถว(9, มีค่า(4, 0))
  ok('เคสเขียนได้แต่ไม่เต็ม: ต้องบอกเลขที่แพลตฟอร์มจะเห็น (5)',
    typeof ต2 === 'string' && ต2.includes('5'), `ได้ ${JSON.stringify(ต2)}`)
  ok('สองเคสต้องให้ข้อความต่างกัน (กันกิ่งเดียวตอบทุกเคส)',
    ต !== ต2 && !(ต2 || '').includes('ตีกลับ'), `ตีกลับ=${JSON.stringify(ต)} · ไม่เต็ม=${JSON.stringify(ต2)}`)
  ok('ไม่มีจอง + เขียนได้เต็ม ⇒ ไม่มีคำเตือน', คำเตือนแถว(9, มีค่า(0, 0)) === null)
  ok('ยังไม่อ่าน ⇒ เตือนว่ายังไม่ได้อ่าน (ไม่ใช่ null)',
    typeof คำเตือนแถว(9, { สถานะ: 'ยังไม่อ่าน' }) === 'string')
  ok('ZORT ไม่รู้จักรหัส ⇒ เตือนว่าเขียนไม่ได้',
    (คำเตือนแถว(9, { สถานะ: 'ไม่มีรหัสนี้' }) || '').includes('เขียนไม่ได้'))
  ok('ยังไม่เลือกเลขที่จะเขียน แต่มีจอง ⇒ ยังต้องเตือนเรื่องจอง',
    (คำเตือนแถว(null, มีค่า(4, 0)) || '').includes('4'))

  console.log('\n── ห้ามเดารหัสปลายทางแทนคน ──')
  ok('หนึ่งรหัส ⇒ ไม่ต้องเลือก', ต้องเลือกรหัสเอง(['Bar NW 18']) === false)
  ok('สองรหัส (24″) ⇒ ต้องให้คนเลือก',
    ต้องเลือกรหัสเอง(['Bar NW 24-7800', 'Bar NW 24-9800']) === true)
  ok('สามรหัส (KK 30″) ⇒ ต้องให้คนเลือก',
    ต้องเลือกรหัสเอง(['Bar KK 30-7800', 'Bar KK 30-381', 'Bar KK 30-070']) === true)
  ok('ไม่มีรหัสเลย ⇒ ไม่ต้องเลือก (และกดดันไม่ได้อยู่แล้ว)', ต้องเลือกรหัสเอง([]) === false)

  console.log('\n── ref กันกดซ้ำ ──')
  const r1 = refของการกด('Bar NW 18', 1000)
  const r2 = refของการกด('Bar NW 18', 1001)
  ok('เวลาต่างกัน ⇒ ref ต่างกัน', r1 !== r2)
  ok('ref ไม่มีช่องว่าง (กันพารามิเตอร์เพี้ยน)', !/\s/.test(r1), r1)
  ok('ref มีรหัสอยู่ข้างใน (ตามรอยได้)', r1.includes('Bar_NW_18'), r1)

  console.log('\n── ขาที่ยังไม่มี ต้องประกาศออกมา ไม่ใช่เงียบ ──')
  ok('ข้อความบอกว่าเป็นชีท และบอกเหตุที่อ่านไม่ได้',
    ขาที่ยังไม่มี.includes('ชีท') && ขาที่ยังไม่มี.includes('401'))
} catch (e) {
  ตก++
  console.log('  ❌ เทสล้มทั้งไฟล์:', e?.message || e)
} finally {
  if (งาน?.ที่ออก) rmSync(งาน.ที่ออก, { recursive: true, force: true })
}

console.log(ตก === 0 ? '\n✅ ผ่านหมด' : `\n❌ ตก ${ตก} ข้อ`)
process.exit(ตก === 0 ? 0 : 1)
