#!/usr/bin/env node
/* ป้ายสถานะของเจ้าที่เก็บบิลด้วย **สคริปต์บน g1** (`lib/bills-g1.ts`) — 15 ต.ค. 2569
 *
 * 🔴 ที่มา: /bills ขึ้นว่า 6 เจ้า "ไม่ได้สแกนมา 13 วัน" ทั้งที่คืนก่อน 4 เจ้าทำงานปกติ
 *    (ป้ายอ่าน lastScan ที่มีแต่ทางเมลเขียน) · เกณฑ์ที่ตกลงกับ CEO:
 *    "ป้ายบนจอต้องตรงกับไฟล์สถานะจริงบน g1 ทุกเจ้า ไม่ใช่แค่ไม่แดง"
 *    ⇒ เทสนี้ป้อนรูปเดียวกับที่ ping.gucut.com ส่งจริง (วัด 15 ต.ค. 06:40) แล้วตรึงป้ายรายเจ้า
 *
 * 🔑 สามสถานะ: อ่าน g1 ไม่ได้ / ไม่มีรายงานเจ้านั้น / เวลาอ่านไม่ออก ⇒ "ไม่รู้" — ห้ามเป็น "ปกติ"
 * 🔑 AUTH_REQUIRED ⇒ "ต้องล็อกอิน" แยกจาก "ควรมาดู" (เป็นงานที่ท่านประธานต้องทำเอง ไม่ใช่ระบบพัง)
 */
import { สถานะจากg1, เวลาg1เป็นISO, ชั่วโมงที่ถือว่าเงียบ, เหตุจากรหัสg1 } from '../../lib/bills-g1.ts'

let ตก = 0
const ok = (ชื่อ, เงื่อนไข, เหตุ = '') => {
  console.log(`  ${เงื่อนไข ? '✅' : '❌'} ${ชื่อ}${เงื่อนไข ? '' : ` — ${เหตุ}`}`)
  if (!เงื่อนไข) { ตก++; console.log(`     🔴 ตกที่ ${ชื่อ}`) }
}

/* รูปจริงจาก ping.gucut.com ช่อง "บิล" (ตัด detail ให้สั้น) */
const ตอนนี้ = Date.parse('2026-10-15T07:00:00+07:00')
const g1จริง = {
  ok: true,
  รอบกวาด: { สถานะ: 'เสร็จ', กำลังทำ: null, ทำไปแล้ว: 6, ทั้งหมด: 6, เมื่อ: 1792022000 },
  รายเจ้า: {
    meta:       { status: 'OK', at: '2026-10-15 06:33:05', detail: 'ใหม่ 1 ใบ', ใหม่: 1 },
    tiktok:     { status: 'OK', at: '2026-10-15 06:31:40', detail: 'ไม่มีใบใหม่' },
    adobe:      { status: 'OK', at: '2026-10-15 06:34:10', detail: 'ไม่มีใบใหม่' },
    cloudflare: { status: 'OK', at: '2026-10-15 06:35:00', detail: 'ไม่มีใบใหม่' },
    line:       { status: 'AUTH_REQUIRED', at: '2026-10-15 06:32:20', detail: 'เซสชัน LINE หมดอายุ' },
    netlify:    { status: 'AUTH_REQUIRED', at: '2026-10-15 06:36:00', detail: '' },
  },
}

function ชุดเทส(ตัดสิน, ป้ายชุด) {
  console.log(`\n── ${ป้ายชุด} ──`)
  const คาด = { meta: 'ปกติ', tiktok: 'ปกติ', adobe: 'ปกติ', cloudflare: 'ปกติ', line: 'ต้องล็อกอิน', netlify: 'ต้องล็อกอิน' }
  console.log('① ป้ายตรงกับไฟล์สถานะบน g1 ทุกเจ้า (6/6)')
  for (const [id, ป้าย] of Object.entries(คาด)) {
    const ร = ตัดสิน(id, g1จริง, ตอนนี้)
    ok(`${id} ⇒ ${ป้าย}`, ร.สถานะ === ป้าย, `ได้ ${ร.สถานะ}`)
  }
  ok('ต้องล็อกอินมีเหตุเสมอ แม้ detail ว่าง', ตัดสิน('netlify', g1จริง, ตอนนี้).เหตุ.length > 0)
  ok('สแกนล่าสุดมาจาก g1 (06:33:05 ไทย = 23:33:05Z)', ตัดสิน('meta', g1จริง, ตอนนี้).สแกนล่าสุด === '2026-10-14T23:33:05.000Z',
     String(ตัดสิน('meta', g1จริง, ตอนนี้).สแกนล่าสุด))

  console.log('② ไม่รู้ ≠ ปกติ')
  ok('อ่าน g1 ไม่ได้ ⇒ ไม่รู้', ตัดสิน('meta', { ok: false, เหตุ: 'g1 ตอบ HTTP 403' }, ตอนนี้).สถานะ === 'ไม่รู้')
  ok('เหตุอ้างข้อความจริง', ตัดสิน('meta', { ok: false, เหตุ: 'g1 ตอบ HTTP 403' }, ตอนนี้).เหตุ.includes('403'))
  ok('ไม่มีรายงานเจ้านั้น ⇒ ไม่รู้', ตัดสิน('omise', g1จริง, ตอนนี้).สถานะ === 'ไม่รู้')
  const เวลาเพี้ยน = { ...g1จริง, รายเจ้า: { meta: { status: 'OK', at: 'เมื่อวาน' } } }
  ok('เวลาอ่านไม่ออก ⇒ ไม่รู้ (ไม่เดาว่าเพิ่งสแกน)', ตัดสิน('meta', เวลาเพี้ยน, ตอนนี้).สถานะ === 'ไม่รู้')

  console.log('③ สถานะอื่นที่ไม่ใช่ OK ⇒ ควรมาดู พร้อมเหตุ')
  const พัง = { ...g1จริง, รายเจ้า: { meta: { status: 'ERROR', at: '2026-10-15 06:33:05', detail: 'timeout' } } }
  ok('ERROR ⇒ ควรมาดู', ตัดสิน('meta', พัง, ตอนนี้).สถานะ === 'ควรมาดู')
  ok('เหตุมีทั้งสถานะและ detail', /ERROR.*timeout/.test(ตัดสิน('meta', พัง, ตอนนี้).เหตุ))

  console.log(`④ เงียบเกิน ${ชั่วโมงที่ถือว่าเงียบ} ชม. ⇒ ควรมาดู`)
  const ห่าง = (ชม) => ตัดสิน('meta', g1จริง, Date.parse('2026-10-15T06:33:05+07:00') + ชม * 3600e3).สถานะ
  ok('47 ชม. ⇒ ปกติ', ห่าง(47) === 'ปกติ', ห่าง(47))
  ok('49 ชม. ⇒ ควรมาดู', ห่าง(49) === 'ควรมาดู', ห่าง(49))
}

ชุดเทส(สถานะจากg1, 'ของจริง lib/bills-g1.ts')

/* 🔑 ตัวควบคุม: รุ่นพังที่ปลูกไว้ในเทสเอง — ถ้าชุดเทสเลิกแยกแยะ ข้อนี้จะแดงก่อน
   รุ่นพัง = ยุบ AUTH_REQUIRED เข้า "ควรมาดู" + ถือว่าอ่าน g1 ไม่ได้คือ "ปกติ" (สองบั๊กที่ป้ายเก่าทำอยู่จริง) */
const รุ่นพัง = (id, g1, now) => {
  if (!g1.ok) return { สถานะ: 'ปกติ', เหตุ: '', สแกนล่าสุด: null }
  const r = สถานะจากg1(id, g1, now)
  return r.สถานะ === 'ต้องล็อกอิน' ? { ...r, สถานะ: 'ควรมาดู' } : r
}
const ตกก่อนควบคุม = ตก
ชุดเทส(รุ่นพัง, 'ตัวควบคุม: รุ่นพัง (ต้องแดง)')
const ตกของรุ่นพัง = ตก - ตกก่อนควบคุม
ตก = ตกก่อนควบคุม
console.log(`\nตัวควบคุม: รุ่นพังตก ${ตกของรุ่นพัง} ข้อ (ต้อง ≥ 3: line · netlify · อ่าน g1 ไม่ได้)`)
if (ตกของรุ่นพัง < 3) { ตก++; console.log('🔴 ตกที่ ตัวควบคุม — ชุดเทสแยกรุ่นพังไม่ออก') }

console.log('\n⑤ เวลาg1เป็นISO')
ok('รูปปกติ', เวลาg1เป็นISO('2026-10-15 06:33:05') === '2026-10-14T23:33:05.000Z')
ok('ไม่ใช่สตริง ⇒ null', เวลาg1เป็นISO(1792022000) === null)
ok('ขาดวินาที ⇒ null', เวลาg1เป็นISO('2026-10-15 06:33') === null)

console.log('\n⑥ ไม่มีคีย์ ≠ คีย์ไม่ตรง (CEO ขอให้แยกข้อความ)')
ok('403 ⇒ บอกว่าคีย์ไม่ตรง', เหตุจากรหัสg1(403).includes('ค่าไม่ตรง'))
ok('401 ⇒ บอกว่าคีย์ไม่ตรง', เหตุจากรหัสg1(401).includes('ค่าไม่ตรง'))
ok('500 ⇒ ไม่พูดเรื่องคีย์', !เหตุจากรหัสg1(500).includes('คีย์'))
ok('คีย์ไม่ตรงไม่ใช้คำว่า ไม่มีคีย์', !เหตุจากรหัสg1(403).includes('ไม่มีคีย์'))

console.log(ตก ? `\n🔴 ตก ${ตก} ข้อ` : '\n✅ ผ่านทุกข้อ')
process.exit(ตก ? 1 : 0)
