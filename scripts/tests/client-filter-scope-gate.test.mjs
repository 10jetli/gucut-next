#!/usr/bin/env node
/* ด่าน: จอที่ **แบ่งหน้า** และ **กรองในเบราว์เซอร์** ต้องตัดสินขอบเขตด้วย lib/client-filter-scope.ts
 * (CEO ขอ 15 ต.ค. 2569 — แทนคำเตือน "ถ้าวันหนึ่งใบเสนอราคาได้แบ่งหน้า ต้องย้ายมาใช้ตัวกลาง")
 *
 * 🔑 ทำไมต้องเป็นด่าน: ตัวจุดชนวนเดิมคือ "ถ้ามีคนจำได้" = ไม่เคยเกิด
 *    วันที่จอไหนได้ <PageNav ทั้งที่มี clientFiltered= ของตัวเอง ⇒ เทสนี้แดงเอง ไม่ต้องมีใครจำ
 * 🔑 เหตุที่ต้องใช้ตัวกลาง: ตรรกะ "ครบไหม" ที่เขียนเองเคยผิดจริง — `offset + โหลดมา >= ทั้งหมด`
 *    ทำให้หน้าสุดท้ายได้ "ครบ" ทั้งที่ในเครื่องมีแค่หน้านั้น (จอรายการซื้อ ก่อน bf4f47ca)
 *
 * ⚠️ สัญญาณที่ใช้จับ "กรองในเบราว์เซอร์" = prop `clientFiltered=` ของแผงค้นหาขั้นสูง **ไม่ใช่คำว่า "กรองในเบราว์เซอร์"**
 *    ลองจับด้วยคำแล้ว (15 ต.ค. 2569) ได้บวกลวง 2/2: return-orders เขียน "กรองในเบราว์เซอร์จะกรองได้แค่หน้าที่เห็น จึงไม่ทำ"
 *    และ sales เขียน "จอไม่ได้กรองในเบราว์เซอร์ด้วย" = ประโยคปฏิเสธ
 *    ⇒ ขอบเขตที่ด่านนี้ **ไม่ครอบ**: จอที่กรองแถวในเบราว์เซอร์โดยไม่ผ่านแผงค้นหาขั้นสูง — ยังไม่มีวิธีจับที่ไม่บวกลวง
 */
import { execFileSync } from 'node:child_process'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'

const ROOT = fileURLToPath(new URL('../..', import.meta.url))
let ตก = 0
const ok = (ชื่อ, เงื่อนไข, เหตุ = '') => {
  console.log(`  ${เงื่อนไข ? '✅' : '❌'} ${ชื่อ}${เงื่อนไข ? '' : ` — ${เหตุ}`}`)
  if (!เงื่อนไข) { ตก++; console.log(`     🔴 ตกที่ ${ชื่อ}`) }
}
let ไฟล์ = []
try {
  ไฟล์ = execFileSync('git', ['grep', '-l', 'clientFiltered=', '--', 'app'], { cwd: ROOT, encoding: 'utf8' })
    .split('\n').map((x) => x.trim()).filter(Boolean)
} catch { ไฟล์ = [] }
/* ตัวควบคุม: ต้องเจอจออย่างน้อย 2 จอ (รายการซื้อ · ใบเสนอราคา) — เจอ 0 = ตัวค้นพัง ไม่ใช่ทุกจอผ่าน */
ok(`พบจอที่กรองในเบราว์เซอร์ ${ไฟล์.length} จอ (ต้อง ≥ 2)`, ไฟล์.length >= 2, ไฟล์.join(', '))
let แบ่งหน้า = 0
for (const f of ไฟล์) {
  const s = readFileSync(join(ROOT, f), 'utf8')
  if (!s.includes('<PageNav')) { console.log(`  ⚪ ${f} — ไม่แบ่งหน้า (โหลดครั้งเดียว) ⇒ ยังไม่บังคับ`); continue }
  แบ่งหน้า++
  ok(`${f} แบ่งหน้า ⇒ ต้องใช้ lib/client-filter-scope`, s.includes("from '@/lib/client-filter-scope'"),
    'จอนี้แบ่งหน้าและกรองในเบราว์เซอร์ แต่ตัดสิน "ครบไหม" เอง — ย้ายมาใช้ ขอบเขตกรองในเครื่อง()')
}
ok(`มีจอที่แบ่งหน้าอย่างน้อย 1 จอให้ตรวจจริง (ได้ ${แบ่งหน้า})`, แบ่งหน้า >= 1)
console.log(ตก ? `\n🔴 ตก ${ตก} ข้อ` : '\n✅ ผ่านทุกข้อ')
process.exit(ตก ? 1 : 0)
