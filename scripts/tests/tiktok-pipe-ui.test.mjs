/* ด่าน: ตัวแปลคำตอบของ `/api/web/tiktok-pipe` ให้จอ /web/tiktok (`lib/tiktok-pipe-ui.ts`)
 *
 * 🔴 ความผิดที่แพงที่สุดของจอนี้: **"อ่านไม่ได้" ถูกแสดงเป็น "ยังไม่เคยส่งคลิป"**
 *    ⇒ ท่านประธานจะสั่งส่งซ้ำทั้งที่ของส่งไปแล้ว · หรือเชื่อว่าท่อไม่ทำงานทั้งที่ทำอยู่
 *    ⇒ สามสถานะนี้ต้องแยกกันเสมอ: ไม่รู้ ≠ ไม่มี ≠ มี
 *
 * 🔑 และเคสที่ไม่มีใครเขียนเทสให้: **ท่อตอบ 200 ด้วยรูปที่เราไม่รู้จัก**
 *    (ท่อรุ่นเก่ายังไม่ deploy · ท่อกลางตอบหน้า 404 ของ Next เป็น JSON ฯลฯ)
 *    ของแบบนั้นต้องกลายเป็น 'อ่านไม่ได้' ห้ามตกไปทางใดทางหนึ่งเงียบ ๆ
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { คำอธิบายรหัส, ตีความคำตอบ, ลิงก์เพจ, เงียบไปนาที } from '../../lib/tiktok-pipe-ui.ts'

const ก้อนมีของ = {
  สถานะข้อมูล: 'มีข้อมูล',
  เมื่อ: '2026-10-24T04:45:58.000Z',
  ดันเมื่อ: '2026-10-24T04:46:00.000Z',
  เวลาเซิร์ฟเวอร์: '2026-10-24T04:47:00.000Z',
  บัญชี: 'ajtcut_8', โหมด: 'อัปจริง', เพดานต่อรอบ: 5, รอบล่าสุด: null, ขอรอบค้าง: null,
  รายการ: [{
    fbid: '990005437450571', ชื่อ: 'อ.ธง · 17 ต.ค. 2569',
    publish_id: 'v_inbox_file~v2.770007326788930971',
    สถานะตอนส่ง: 'PROCESSING_UPLOAD', สถานะล่าสุด: 'SEND_TO_USER_INBOX',
    เหตุถามไม่ได้: null, ถามเมื่อ: '2026-10-24T04:45:57.000Z',
    ขึ้นบัญชีแล้ว: null, ทาง: 'กล่องร่าง', ลิงก์fb: '/reel/990005437450571/',
  }],
}

test('สามสถานะต้องแยกกัน — "ยังไม่เคยดัน" ≠ "ส่งแล้ว 0 ใบ" ≠ "อ่านไม่ได้"', () => {
  const ไม่เคยดัน = ตีความคำตอบ(true, 200, {
    สถานะข้อมูล: 'ยังไม่เคยมีใครดัน', เหตุ: 'g1 ยังไม่เคยดันผลขึ้นมาเลย', รายการ: [], ขอรอบค้าง: null,
  })
  assert.equal(ไม่เคยดัน.แบบ, 'ยังไม่เคยดัน')

  const ศูนย์ใบ = ตีความคำตอบ(true, 200, { ...ก้อนมีของ, รายการ: [] })
  assert.equal(ศูนย์ใบ.แบบ, 'มีข้อมูล')
  assert.deepEqual(ศูนย์ใบ.รายการ, [])

  const อ่านไม่ได้ = ตีความคำตอบ(false, 503, { error: 'อ่านคลังไม่ได้: blobs ล่ม', สถานะข้อมูล: 'อ่านคลังไม่ได้' })
  assert.equal(อ่านไม่ได้.แบบ, 'อ่านไม่ได้')
  assert.match(อ่านไม่ได้.เหตุ, /503/)
  assert.match(อ่านไม่ได้.เหตุ, /blobs ล่ม/)

  // 🔴 ทั้งสามต้องเป็นสามค่า — เท่ากันสองอันเมื่อไหร่ แปลว่าจอกลืนความต่างไปแล้ว
  assert.equal(new Set([ไม่เคยดัน.แบบ, ศูนย์ใบ.แบบ, อ่านไม่ได้.แบบ]).size, 3)
})

test('🔴 ท่อตอบ 200 ด้วยรูปที่ไม่รู้จัก ⇒ อ่านไม่ได้ (ห้ามเดาว่าไม่มีของ)', () => {
  for (const ก้อน of [
    {},                                             // ไม่มี สถานะข้อมูล เลย
    { สถานะข้อมูล: 'อะไรไม่รู้' },                     // ค่าที่เราไม่รู้จัก
    { สถานะข้อมูล: 'มีข้อมูล' },                       // บอกว่ามีของแต่ไม่มีอาเรย์
    { สถานะข้อมูล: 'มีข้อมูล', รายการ: 'ไม่ใช่อาเรย์' },
    { pageProps: {}, __N_SSG: true },                // หน้า 404 ของ Next ที่กลายเป็น JSON
  ]) {
    const ผล = ตีความคำตอบ(true, 200, ก้อน)
    assert.equal(ผล.แบบ, 'อ่านไม่ได้', `ก้อน ${JSON.stringify(ก้อน).slice(0, 48)} ต้องเป็น "อ่านไม่ได้"`)
    assert.match(ผล.เหตุ, /ไม่ใช่ที่สัญญาไว้/)
  }
  // body ว่าง/ไม่ใช่ JSON (ท่อกลางคืน null)
  assert.equal(ตีความคำตอบ(true, 200, null).แบบ, 'อ่านไม่ได้')
  assert.equal(ตีความคำตอบ(true, 200, 'ข้อความเปล่า').แบบ, 'อ่านไม่ได้')
})

test('ก้อนมีของ: ส่งทุกช่องต่อให้จอ และคงค่า null ไว้ (ไม่แปลงเป็นค่าว่าง)', () => {
  const ผล = ตีความคำตอบ(true, 200, ก้อนมีของ)
  assert.equal(ผล.แบบ, 'มีข้อมูล')
  assert.equal(ผล.บัญชี, 'ajtcut_8')
  assert.equal(ผล.โหมด, 'อัปจริง')
  assert.equal(ผล.ขอรอบค้าง, null)
  assert.equal(ผล.รายการ.length, 1)
  // 🔑 สองช่องสถานะต้องมาถึงจอครบทั้งคู่ — ยุบรวมกันเมื่อไหร่ จอจะรายงานค่าเก่าเป็นค่าตอนนี้
  assert.equal(ผล.รายการ[0].สถานะตอนส่ง, 'PROCESSING_UPLOAD')
  assert.equal(ผล.รายการ[0].สถานะล่าสุด, 'SEND_TO_USER_INBOX')
})

test('ช่องเวลาที่ไม่ใช่ข้อความ ⇒ null (จออ่านแล้วไม่พัง และไม่คิดเลขจากขยะ)', () => {
  const ผล = ตีความคำตอบ(true, 200, { ...ก้อนมีของ, ดันเมื่อ: 12345, ขอรอบค้าง: { a: 1 } })
  assert.equal(ผล.แบบ, 'มีข้อมูล')
  assert.equal(ผล.ดันเมื่อ, null)
  assert.equal(ผล.ขอรอบค้าง, null)
})

test('🚫 คำอธิบายรหัสห้ามมีคำว่า "สำเร็จ" กับรหัสที่ยังไม่ขึ้นโปรไฟล์', () => {
  assert.match(คำอธิบายรหัส.SEND_TO_USER_INBOX, /กล่องร่าง/)
  assert.doesNotMatch(คำอธิบายรหัส.SEND_TO_USER_INBOX, /สำเร็จ/,
    'SEND_TO_USER_INBOX = ถึงกล่องร่าง ไม่ใช่ขึ้นโปรไฟล์ — เขียนว่า "สำเร็จ" ทำให้เข้าใจว่าคลิปขึ้นแล้ว')
  assert.doesNotMatch(คำอธิบายรหัส.PROCESSING_UPLOAD, /สำเร็จ/)
  // รหัสที่ไม่รู้จักต้องไม่มีคำอธิบาย (จอจะโชว์ค่าดิบเฉย ๆ ห้ามเดาความหมาย)
  assert.equal(คำอธิบายรหัส.SOMETHING_NEW_FROM_TIKTOK, undefined)
})

test('เงียบไปนาที: คิดจากนาฬิกาเซิร์ฟเวอร์สองค่า · อ่านไม่ออก ⇒ null ไม่ใช่ 0', () => {
  assert.equal(เงียบไปนาที('2026-10-24T04:40:00.000Z', '2026-10-24T04:47:00.000Z'), 7)
  assert.equal(เงียบไปนาที('2026-10-24T04:47:00.000Z', '2026-10-24T04:47:00.000Z'), 0)
  // 🔴 null = "ไม่รู้" · 0 = "เพิ่งรายงาน" — คนละเรื่อง ห้ามปนกัน
  assert.equal(เงียบไปนาที(null, '2026-10-24T04:47:00.000Z'), null)
  assert.equal(เงียบไปนาที('2026-10-24T04:40:00.000Z', null), null)
  assert.equal(เงียบไปนาที('เมื่อกี้', '2026-10-24T04:47:00.000Z'), null)
  // นาฬิกา g1 ล้ำหน้าเซิร์ฟเวอร์ ⇒ ไม่คืนค่าลบ (คำเตือน "เงียบ -3 นาที" อ่านไม่รู้เรื่อง)
  assert.equal(เงียบไปนาที('2026-10-24T04:50:00.000Z', '2026-10-24T04:47:00.000Z'), 0)
})

test('ลิงก์เพจ: ต่อโดเมนให้เส้นทางสัมพัทธ์ · ค่าที่ไม่รู้จัก ⇒ ว่าง (ไม่ทำลิงก์ปลอม)', () => {
  assert.equal(ลิงก์เพจ('/reel/990005437450571/'), 'https://www.facebook.com/reel/990005437450571/')
  assert.equal(ลิงก์เพจ('https://www.facebook.com/reel/1/'), 'https://www.facebook.com/reel/1/')
  for (const เสีย of ['', 'reel/1', 'javascript:alert(1)', 'http://x/y']) {
    assert.equal(ลิงก์เพจ(เสีย), '', `"${เสีย}" ต้องไม่ถูกทำเป็นลิงก์`)
  }
})

test('🚫 เพดานต่อรอบ: รับเฉพาะตัวเลขจริง — จอห้ามพิมพ์เลขนี้ไว้เอง และห้ามแปลงค่าให้', () => {
  /* 🔴 ด่าน "เลขค้างบนจอ" จับได้ว่าจอเคยพิมพ์ "เพดาน 5 ใบ/รอบ" ไว้ในข้อความ
     ค่าจริงอยู่ที่ `อัปสูงสุดต่อรอบ` ใน ลงtiktok.py บน g1 ⇒ ใครแก้ที่นั่น ข้อความจะโกหกทันที
     ⇒ ต้องมาจากข้อมูล และ "อ่านไม่ได้" ต้องเป็น null เพื่อให้จอ **ไม่โชว์บรรทัดนั้น** */
  assert.equal(ตีความคำตอบ(true, 200, ก้อนมีของ).เพดานต่อรอบ, 5)
  for (const เสีย of [undefined, null, '5', 'ห้า', {}, NaN, Infinity]) {
    const ผล = ตีความคำตอบ(true, 200, { ...ก้อนมีของ, เพดานต่อรอบ: เสีย })
    assert.equal(ผล.เพดานต่อรอบ, null, `ค่า ${String(เสีย)} ต้องกลายเป็น null ไม่ใช่เลขที่ดูเหมือนวัดมา`)
  }
})
