/* เทสตรึงบั๊กถังเวลาของกราฟรายงาน (20 ก.ย. 2569)
 *
 * 🔑 เคสในไฟล์นี้แบ่งสามกลุ่ม **และไม่ใช่ทุกเคสที่ต้องแยกแยะบั๊ก** (ข้อที่ฝั่งท่อกำชับ)
 *    ① เคสที่ **ตกกับโค้ดรุ่นเก่า** (ใช้ `toISOString()`) ⇒ คือเคสที่พิสูจน์ว่าเทสนี้มีอำนาจ
 *    ② เคสที่ยืนยันสัญญาอื่นของฟังก์ชัน (ป้าย · การเรียง · ช่วงข้ามปี)
 *    ③ เคสที่ตรึง **ข้อจำกัดที่รู้ตัว** (ชนเพดาน) ⇒ วันที่ข้อจำกัดหมดไป เทสนี้จะแดงและบังคับให้แก้เอกสาร
 *
 * ⚠️ รันด้วยโซนเวลาอะไรก็ต้องได้ผลเดิม — ฟังก์ชันอ่านปฏิทินท้องถิ่น ไม่แปลงข้ามโซน
 *    (บั๊กเดิมจะโผล่เฉพาะโซนที่ offset เป็นบวก เช่นไทย ⇒ เทสที่รันแต่ UTC จะเขียวตลอดกาล
 *     ⇒ ไฟล์นี้จึงยืนยัน **คีย์ที่คาดหวังตรง ๆ** ไม่ใช่เทียบกับผลของ toISOString)
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { ถังของช่วง, ถังของวัน, วันตามปฏิทินท้องถิ่น } from '../../lib/report-buckets.ts'

test('① เดือนเดียว: ช่วง 1–30 ก.ย. ต้องได้ถัง ก.ย. ไม่ใช่ ส.ค.', () => {
  const { ถัง, ชนเพดาน } = ถังของช่วง('2026-09-01', '2026-09-30', 'month')
  assert.equal(ชนเพดาน, false)
  assert.deepEqual(ถัง.map((x) => x.key), ['2026-09'])
  /* 🔴 รุ่นเก่าได้ `['2026-08']` — ผิดทั้งถัง ไม่ใช่เกินมาหนึ่งถัง */
  assert.equal(ถัง[0].label, 'ก.ย./2569')
})

test('① รายวัน: ถังแรกต้องเป็นวันแรกของช่วง และถังสุดท้ายเป็นวันสุดท้าย', () => {
  const { ถัง } = ถังของช่วง('2026-09-01', '2026-09-30', 'day')
  assert.equal(ถัง.length, 30)
  assert.equal(ถัง[0].key, '2026-09-01')      // รุ่นเก่าได้ 2026-08-31
  assert.equal(ถัง[29].key, '2026-09-30')     // รุ่นเก่าได้ 2026-09-29
})

test('① ขอบปี: 1 ม.ค. ต้องไม่ทำให้โผล่ปีก่อนหน้า', () => {
  const { ถัง } = ถังของช่วง('2026-01-01', '2026-12-31', 'year')
  assert.deepEqual(ถัง.map((x) => x.key), ['2026'])   // รุ่นเก่าได้ ['2025','2026']
})

test('② วันตามปฏิทินท้องถิ่น อ่านจากปฏิทิน ไม่ใช่เส้นเวลา', () => {
  /* เที่ยงคืนตามปฏิทินท้องถิ่นของวันที่ 1 ⇒ ต้องได้วันที่ 1 ไม่ว่าจะอยู่โซนไหน */
  assert.equal(วันตามปฏิทินท้องถิ่น(new Date(2026, 8, 1, 0, 0, 0)), '2026-09-01')
  assert.equal(วันตามปฏิทินท้องถิ่น(new Date(2026, 8, 1, 23, 59, 59)), '2026-09-01')
  assert.equal(วันตามปฏิทินท้องถิ่น(new Date(2026, 0, 5)), '2026-01-05')
})

test('② ถังสุดท้ายต้องไม่หายเมื่อก้าวเดือนกระโดดข้ามปลายช่วง', () => {
  /* from=15 ม.ค. to=10 ก.พ. · ก้าวเดือนถัดไปคือ 15 ก.พ. ซึ่งเกิน to ⇒ ก.พ. ต้องยังอยู่ */
  const { ถัง } = ถังของช่วง('2026-01-15', '2026-02-10', 'month')
  assert.deepEqual(ถัง.map((x) => x.key), ['2026-01', '2026-02'])
})

test('② ไตรมาสและป้ายปี พ.ศ.', () => {
  assert.deepEqual(ถังของวัน('2026-05-20', 'quarter'), { key: '2026-Q2', label: 'Q2/2569' })
  assert.deepEqual(ถังของวัน('2026-05-20', 'year'), { key: '2026', label: '2569' })
})

test('② ช่วงที่อ่านไม่ออก คืนรายการว่าง และ **ไม่ใช่การชนเพดาน**', () => {
  const r = ถังของช่วง('ไม่ใช่วันที่', '2026-09-30', 'day')
  assert.deepEqual(r.ถัง, [])
  assert.equal(r.ชนเพดาน, false)   // ว่างเพราะอ่านไม่ออก ≠ ว่างเพราะลูปถูกตัด
})

test('③ ข้อจำกัดที่รู้ตัว: เกินเพดานรอบ ⇒ คืนเท่าที่ได้ + บอกว่าชนเพดาน', () => {
  const { ถัง, ชนเพดาน } = ถังของช่วง('2020-01-01', '2026-12-31', 'day', 10)
  assert.equal(ชนเพดาน, true)
  assert.equal(ถัง.length, 10)
  /* 🔑 เคสนี้ตรึง **ข้อจำกัด** ไม่ใช่ความสามารถ — วันที่มีคนทำให้ลูปไม่ต้องมีเพดาน
     เทสนี้จะแดง และนั่นคือสัญญาณให้แก้คอมเมนต์หัวไฟล์ด้วย ไม่ใช่แก้เทสให้ผ่าน */
})
