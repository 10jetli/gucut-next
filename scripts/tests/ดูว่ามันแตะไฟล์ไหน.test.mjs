/* เทสของ `scripts/lib/ดูว่ามันแตะไฟล์ไหน.cjs` — เครื่องมือที่ทำให้คำว่า "อ่านอย่างเดียว"
 * เป็นจริงโดยโครงสร้าง
 *
 * 🔴 **ข้อที่สำคัญที่สุดในไฟล์นี้คือข้อที่บังคับว่า "ต้องมีเอาต์พุต" ไม่ใช่แค่ rc=0**
 *    รุ่นแรกผมใส่ `writeSync` ไว้ในรายการที่บล็อก ⇒ `NO_WRITE=1` ทำให้เครื่องมือ
 *    **เงียบสนิทและ exit 0** เพราะ `console.log` เขียน fd ผ่าน `fs.writeSync`
 *    ⇒ ตัวบล็อกไปปิดปากตัวเอง · ข้อผิดพลาดใน exit handler ถูกกลืน
 *    ⇒ ⇒ อาการคือ **"ดูเหมือนผ่าน"** ซึ่งแพงกว่าพังดัง ๆ
 *    🔑 ถ้าเทสนี้ดูแค่ rc มันจะเขียวให้กับเครื่องมือที่ใช้งานไม่ได้เลย
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const เครื่องมือ = fileURLToPath(new URL('../lib/ดูว่ามันแตะไฟล์ไหน.cjs', import.meta.url))
/* 🔴 ต้องรวม **stdout + stderr** — เครื่องมือรายงานสถานะโหมดทาง stderr
   รุ่นแรกผมใช้ `execFileSync` ซึ่งตอนสำเร็จคืนแต่ stdout ⇒ เทสตกเพราะ **ตัววัดมองไม่ครบ**
   ไม่ใช่เพราะเครื่องมือผิด (ครั้งที่ 4 ของวันนี้ที่บั๊กอยู่ในตัววัด) */
const รัน = (env) => {
  const r = spawnSync('node', [เครื่องมือ, '--ตรวจตัวเอง'],
    { encoding: 'utf8', env: { ...process.env, ...env } })
  return { rc: r.status, out: (r.stdout || '') + (r.stderr || '') }
}

test('เปิด NO_WRITE ⇒ ตัวเขียนถูกบล็อก และไฟล์ไม่ถูกสร้าง', () => {
  const r = รัน({ NO_WRITE: '1' })
  assert.equal(r.rc, 0, `ตรวจตัวเองต้องผ่าน · ได้: ${r.out}`)
  assert.match(r.out, /writeFileSync ถูกบล็อก/)
  assert.match(r.out, /ไฟล์ไม่ถูกสร้าง/,
    'ต้องบล็อก**ก่อน**เรียกของเดิม — เตือนแล้วปล่อยผ่าน = ป้ายที่อ้างเกินสิ่งที่มือเราทำ')
})

test('🔴 เปิด NO_WRITE แล้ว **ยังต้องพิมพ์ออกมาได้** (ห้ามปิดปากตัวเอง)', () => {
  const r = รัน({ NO_WRITE: '1' })
  assert.ok(r.out.trim().length > 0,
    '🔴 **ของจริงเคยเงียบสนิทและ exit 0** เพราะผมบล็อก `fs.writeSync` ซึ่งเป็นทางที่'
    + ' console.log ใช้เขียน fd ⇒ ตัวบล็อกปิดปากตัวเอง ⇒ ดูเหมือนผ่าน'
    + ' ⇒ เทสที่ดูแค่ rc จะเขียวให้เครื่องมือที่ใช้งานไม่ได้เลย')
  assert.match(r.out, /NO_WRITE: เปิด/, 'ต้องรายงานสถานะโหมดทุกรอบ ไม่ใช่เฉพาะตอนบล็อก')
})

test('🔴 ตัวควบคุมลบ: ปิดโหมด ⇒ ต้องเขียนได้ (ไม่ได้บล็อกตลอดเวลา)', () => {
  const r = รัน({ NO_WRITE: '' })
  assert.equal(r.rc, 0, `ปิดโหมดแล้วต้องเขียนได้ · ได้: ${r.out}`)
  assert.match(r.out, /เขียนได้ตามปกติ/,
    'ไม่มีทิศนี้ เทสจะผ่านได้ด้วยเหตุผลผิด (เช่นพาธใช้ไม่ได้ตั้งแต่ต้น)')
  assert.match(r.out, /NO_WRITE: 🔶 \*\*ปิด\*\*/,
    'ปิดโหมดต้องประกาศว่าของที่วัดเขียนไฟล์ได้ — ความเงียบตอนปิดคือข่าวดีปลอม')
})

test('TOUCH_WHAT รายงานจำนวนครั้งที่ fs ถูกเรียกด้วยพาธที่มีคำนั้น', () => {
  const r = รัน({ TOUCH_WHAT: 'ตรวจตัวเอง' })
  assert.match(r.out, /เรียก fs ด้วยพาธที่มี "ตรวจตัวเอง": \d+ ครั้ง · \d+ พาธไม่ซ้ำ/,
    'ต้องมีสองเลข (ครั้ง · พาธไม่ซ้ำ) — เลขเดียวแยก "อ่านไฟล์เดียวหลายรอบ" จาก "อ่านหลายไฟล์" ไม่ได้')
})
