/* เส้นสาธารณะ `/api/build-time` ต้องมี **คีย์เดียว** และต้องไม่รับพารามิเตอร์
 * รัน: node scripts/tests/build-time-public.test.mjs
 *
 * 🔴 **ที่มา 28 ก.ย. 2569** — ฝั่งท่อยืนยัน deploy ด้วยการยิงของที่เสิร์ฟจริง (`x-core-build`)
 *    ฝั่งจอทำแบบนั้นไม่ได้เพราะ middleware ล็อกอินเด้งก่อนถึง routing ⇒ ขอเปิดเส้นเวลาบิลด์
 *    ฝั่งท่ออนุมัติพร้อม **สี่เงื่อนไข** ⇒ ด่านนี้คือตัวบังคับเงื่อนไข ①②③ (④ ต้องยิงเซิร์ฟเวอร์จริง)
 *
 * 🔑 ทำไมต้องมีด่าน ไม่ใช่แค่เขียนคอมเมนต์: เงื่อนไขพวกนี้ "ถูกวันที่เขียน" แล้วเน่าเงียบ
 *    วันที่มีคนเติมช่อง `commit` ลงไปเพราะสะดวก จะไม่มีอะไรบอกว่าข้อตกลงถูกละเมิด
 */
import { readFileSync } from 'node:fs'
import { ตัดคอมเมนต์ } from '../lib/ตัดคอมเมนต์.mjs'

let ตก = 0
const ok = (ชื่อ, เงื่อนไข, เพิ่ม = '') => {
  if (เงื่อนไข) console.log(`  ✅ ${ชื่อ}`)
  else { ตก++; console.log(`  ❌ ${ชื่อ} ${เพิ่ม}`) }
}

const ไฟล์ = 'app/api/build-time/route.ts'
const โค้ด = ตัดคอมเมนต์(readFileSync(ไฟล์, 'utf8'))

/* ── ① คำตอบต้องมีคีย์เดียว ── */
const m = /NextResponse\.json\(\s*\{([\s\S]*?)\}\s*\)/.exec(โค้ด)
ok('อ่านก้อนคำตอบของเส้นนี้ได้ (อ่านไม่ได้ = ตะแกรงพัง ไม่ใช่ผ่าน)', !!m, `หา NextResponse.json({...}) ใน ${ไฟล์} ไม่เจอ`)
const คีย์ = m ? [...m[1].matchAll(/(^|[,{])\s*([A-Za-z_$][\w$]*)\s*:/g)].map((x) => x[2]) : []
console.log(`   📏 คีย์ที่เส้นนี้ส่งออก: ${คีย์.join(', ') || '(ไม่มี)'}`)
ok('🔒 เงื่อนไข ① — คำตอบสาธารณะต้องมี **คีย์เดียว**', คีย์.length === 1,
  `ได้ ${คีย์.length} คีย์: ${คีย์.join(', ')} ⇒ ข้อตกลงกับฝั่งท่อคือช่องเดียว ใครเติมช่องต้องมาคุยกันก่อน`)
ok('คีย์นั้นคือเวลาบิลด์', คีย์[0] === 'buildAtUtc', `ได้ ${คีย์[0]}`)

/* ── ② ห้ามรับพารามิเตอร์ ── */
for (const [ชื่อ, รูป] of [
  ['ไม่อ่าน searchParams', /searchParams/],
  ['ไม่รับ request เข้าฟังก์ชัน', /export async function GET\s*\(\s*[A-Za-z_$]/],
  ['ไม่อ่าน headers ของคำขอ', /req\.headers|request\.headers/],
]) ok(`🔒 เงื่อนไข ② — ${ชื่อ}`, !รูป.test(โค้ด), 'ตอบต่างกันตามสิ่งที่ถูกถาม = เครื่องมือให้คนนอกไล่ดูว่าหน้าไหนมีจริง')

/* ── ③ ต้องอยู่ในรายการที่เทียบเต็มเส้น ไม่ใช่ prefix ── */
const mw = ตัดคอมเมนต์(readFileSync('middleware.ts', 'utf8'))
const exact = /const PUBLIC_EXACT = \[([^\]]*)\]/.exec(mw)
ok('อ่าน PUBLIC_EXACT จาก middleware ได้', !!exact, 'ไม่เจอรายการเทียบเต็มเส้น')
const รายการ = exact ? [...exact[1].matchAll(/'([^']+)'/g)].map((x) => x[1]) : []
ok('🔒 เงื่อนไข ③ — /api/build-time อยู่ในรายการเทียบเต็มเส้น', รายการ.includes('/api/build-time'), `ได้ ${JSON.stringify(รายการ)}`)
const prefixList = /const PUBLIC_PATHS = \[([\s\S]*?)\]/.exec(mw)
const พรีฟิกซ์ = prefixList ? [...prefixList[1].matchAll(/'([^']+)'/g)].map((x) => x[1]) : []
ok('🔴 และต้อง **ไม่** อยู่ในรายการแบบ prefix (จะเปิดลูกที่ยังไม่มีให้ฟรี)',
  !พรีฟิกซ์.includes('/api/build-time'), `PUBLIC_PATHS = ${JSON.stringify(พรีฟิกซ์)}`)
ok('middleware เรียกใช้ PUBLIC_EXACT จริง (ประกาศไว้เฉย ๆ = ไม่มีผล)', /PUBLIC_EXACT\.includes\(/.test(mw))

console.log(ตก ? `\n❌ ไม่ผ่าน ${ตก} ข้อ` : '\n✅ ผ่านทุกข้อ')
console.log('⚠️ เงื่อนไข ④ (ไม่มีคุกกี้กับมีคุกกี้ต้องได้เหมือนกัน) ตรวจที่นี่ไม่ได้ — ต้องยิงเซิร์ฟเวอร์จริง')
/* 🔑 พิมพ์ **วิธีวัดซ้ำ** ไม่ใช่ผลที่วัดไว้ — ผลที่พิมพ์ค้างจะเน่าเงียบ ๆ ส่วนคำสั่งไม่เน่า
   ⚠️ ข้อที่ทำให้รอบแรกให้คำตอบผิด: ถ้ามีเซิร์ฟเวอร์ค้างอยู่ที่พอร์ตนั้นจากบิลด์ก่อน
      `next start` จะผูกพอร์ตไม่ได้ แล้ว curl จะไปโดน **บิลด์เก่า** ⇒ ได้ 401/404
      ที่อ่านเหมือน "โค้ดใหม่พัง" ⇒ ต้องเช็คพอร์ตว่างก่อน และเทียบ BUILD_ID ทุกครั้ง */
console.log(`   วิธีวัดซ้ำ: NEXT_DIST_DIR=.next-verify npm run build
              ⇒ เช็คพอร์ตว่าง (ss -ltn | grep 3111) ⇒ NEXT_DIST_DIR=.next-verify npx next start -p 3111
              ⇒ ยิง GET /api/build-time สามแบบ: ไม่มีคุกกี้ · มีคุกกี้ · ใส่ ?path=... — คำตอบต้องเท่ากันทั้งสาม
              ⇒ และ GET /api/build-time/zz ต้องถูกกำแพงล็อกอินเด้ง (ไม่ใช่ 200)`)
process.exit(ตก ? 1 : 0)
