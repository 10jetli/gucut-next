#!/usr/bin/env node
/* จอต้องอ่าน **เหตุ** ที่ท่อส่งมาคู่กับค่าที่เป็น null — ไม่ใช่เงียบ
 * (28 ก.ย. 2569 · ท่อปิดใบ t_mul8dqjv "คลาสอ่านไม่ได้ตอบเหมือนของว่าง" แล้วเติมคีย์ให้จอ 4 ตัว)
 *
 * 🔴 คลาสที่คีย์เหล่านี้มาแก้: ค่าที่เป็น null ยุบสองเรื่องเป็นคำเดียว
 *    **"ยังไม่เคยทำ"** (งานยังไม่เคยวิ่ง ⇒ รอรอบถัดไป) กับ **"อ่านไม่ได้"** (ของมีแต่พัง ⇒ ต้องไปไล่)
 *    ⇒ จอที่เขียนแค่ "ยังไม่รู้" พาคนไปรอเปล่า ๆ ในกรณีที่สอง
 *
 * 🔒 ข้อความเป็น **คำของท่อ** — จอส่งต่อตรงตัวอักษร ห้ามแต่งเอง (กติกาเดียวกับ srcLabels)
 * ⚠️ ด่านนี้ตรวจ "จออ่านคีย์และเขียนออกจอ" — ส่วนพฤติกรรมของตัวคิดความสดอยู่ใน recipe-fresh.test.mjs
 */
import { readFileSync } from 'node:fs'
import { ตัดคอมเมนต์ } from '../lib/ตัดคอมเมนต์.mjs'

let ตก = 0
const ok = (ชื่อ, เงื่อนไข, เหตุ = '') => {
  console.log(`  ${เงื่อนไข ? '✅' : '❌'} ${ชื่อ}${เงื่อนไข ? '' : ` — ${เหตุ}`}`)
  if (!เงื่อนไข) ตก++
}
const โค้ดของ = (f) => ตัดคอมเมนต์(readFileSync(f, 'utf8'))

console.log('① สี่คีย์ใหม่ต้องมีจออ่านจริง ๆ (ไม่ใช่แค่ประกาศชนิดไว้)')
/* 🔑 วิธีตรวจ: **ตัดบรรทัดประกาศชนิดทิ้งก่อน** แล้วค่อยหาชื่อคีย์
   (รุ่นแรกผมเขียน regex ซ้อน escape จนกลายเป็นตะแกรงที่ไม่ match อะไรเลย ⇒ แดงทั้งที่โค้ดถูก
    ข้อ ② เป็นตัวที่บอกว่าของจริงอ่านอยู่ ⇒ ตะแกรงผิด ไม่ใช่โค้ดผิด) */
const ตัดบรรทัดประกาศ = (โค้ด, คีย์) =>
  โค้ด.split('\n').filter((l) => !new RegExp(`^\\s*${คีย์}\\?:`).test(l.trim() ? l : l)).join('\n')
for (const [คีย์, ไฟล์] of [
  ['recipeCheckedAtWhy', 'app/core/bundles/page.tsx'],
  ['stockSyncedAtWhy', 'app/core/bundles/page.tsx'],
  ['mirrorTotalsError', 'app/core/return-orders/page.tsx'],
  ['resultError', 'app/settings/connections/page.tsx'],
]) {
  const เหลือ = ตัดบรรทัดประกาศ(โค้ดของ(ไฟล์), คีย์)
  ok(`${ไฟล์} อ่าน ${คีย์}`, เหลือ.includes(คีย์),
    'เจอแต่บรรทัดประกาศชนิด = ยังไม่มีใครอ่าน')
}

console.log('② จอต้องไม่แต่งเหตุเอง — ต้องพิมพ์ค่าที่มาจากท่อ')
{
  const ชุด = readFileSync('app/core/bundles/page.tsx', 'utf8')
  ok('จอชุดสินค้าพิมพ์ค่าจากท่อ ไม่ใช่ข้อความคงที่',
    /\{fresh\['เหตุที่ยังไม่รู้'\]\}/.test(ชุด), 'ต้องเรนเดอร์ตัวแปร ไม่ใช่ประโยคที่จอคิดเอง')
  ok('และมีทางเขียนกำกับเมื่อท่อไม่ได้ส่งเหตุมา', /ยังไม่ได้บอกเหตุ/.test(ชุด),
    'ไม่มีเหตุ ⇒ ต้องบอกว่ายังไม่รู้เหตุ ห้ามเงียบ')
  const คืน = readFileSync('app/core/return-orders/page.tsx', 'utf8')
  ok('จอรับคืนพิมพ์เหตุจากท่อ', /\{d\.mirrorTotalsError\}/.test(คืน))
  ok('และบอกว่าไม่ใช่ "ไม่มีกระจก"', /ไม่ใช่ว่าไม่มีกระจก/.test(คืน))
  const เชื่อม = readFileSync('app/settings/connections/page.tsx', 'utf8')
  ok('จอการเชื่อมต่อพิมพ์เหตุจากท่อ', /\{data\.tokenRefresh\.resultError\}/.test(เชื่อม))
  ok('และบอกว่ารอบต่ออายุวิ่งแล้ว (กันคนไปไล่ผิดที่)', /วิ่งแล้ว/.test(เชื่อม))
}

console.log('③ ห้ามแปลงค่าที่ท่อไม่ได้ส่ง ให้กลายเป็นข้อความของจอ')
{
  for (const f of ['app/core/bundles/page.tsx', 'app/core/return-orders/page.tsx',
    'app/settings/connections/page.tsx']) {
    const โค้ด = โค้ดของ(f)
    const ผิด = /(?:Why|Error)\s*(?:\?\?|\|\|)\s*['"`]/.test(โค้ด)
    ok(`${f} ไม่มี fallback เป็นข้อความที่จอคิดเอง`, !ผิด,
      'เจอรูป `...Why ?? "..."` ⇒ ท่อไม่ส่งเหตุ แล้วจอแต่งให้ = คำอธิบายชุดที่สองในระบบ')
  }
}

console.log('④ กิ่งที่เขียนไว้ ต้องไม่ถูกปิดตาย (ข้อความอยู่ในไฟล์ ≠ ขึ้นบนจอ)')
{
  /* 🔑 ตัวควบคุมลบจับได้ว่าเทสรุ่นแรกปล่อยรูปนี้ผ่าน: ห่อกล่องด้วย `{false && (...)}`
     แล้วข้อความยังอยู่ในไฟล์ครบ ⇒ ข้อ ① ②  ผ่านทั้งคู่ทั้งที่จอไม่ขึ้นอะไรเลย
     (คลาสเดียวกับที่เจอตอนเช้าในจอเวลางาน — เหยียบซ้ำในวันเดียวกัน) */
  for (const f of ['app/core/bundles/page.tsx', 'app/core/return-orders/page.tsx',
    'app/settings/connections/page.tsx']) {
    const โค้ด = โค้ดของ(f)
    ok(`${f} ไม่มีกิ่งที่ปิดตายด้วยเงื่อนไขคงที่`, !/\{\s*false\s*&&/.test(โค้ด),
      'เจอ `{false && (...)}` ⇒ ข้อความยังอยู่ในไฟล์แต่ไม่มีวันขึ้นจอ')
  }
}

console.log(ตก ? `\n❌ ไม่ผ่าน ${ตก} ข้อ` : '\n✅ ผ่านทุกข้อ')
process.exit(ตก ? 1 : 0)
