#!/usr/bin/env node
/* การวางกล่องผู้เชื่อมในผังหัวสมอง (`lib/brain-layout.ts`)
 *
 * 🔴 **ทำไมเทสเรื่อง "วางกล่อง" ไม่ใช่เรื่องความสวย**
 *    ของจริง 11 ต.ค. 2569: ต่อแว่นเข้าหัวสมองสำเร็จ แว่นจดชีพจรครบ **แต่ไม่โผล่ในผัง**
 *    เพราะผังเรียงกล่องแถวเดียวบน viewBox กว้าง 860 ⇒ กล่องที่ 6 ขึ้นไปอยู่ที่ x ≥ 840
 *    **หลุดนอกกรอบ หายไปเงียบ ๆ** · และมี `.slice(0,5)` อีกชั้นตัดทิ้งก่อนถึงการวาดด้วย
 *    ⇒ หน้าที่สร้างมาเพื่อบอกว่า "อะไรเชื่อมอยู่จริง" กลับปิดบังของที่เชื่อมอยู่จริง
 *    ⇒ ความผิดคลาสนี้ **ไม่มี error ไม่มี log** ⇒ ด่านต้องเป็นเทส ไม่ใช่การระวัง
 *
 * ⚠️ เทสเรียก **ฟังก์ชันตัวจริง** ไม่ลอกคณิตมาเขียนซ้ำ
 *    (ลอกมาเขียนซ้ำ = วัดสำเนาของตัวเอง ปลูกบั๊กในของจริงแล้วยังเขียว)
 */
import { rmSync } from 'node:fs'
import { คอมไพล์เพื่อทดสอบ } from '../lib/คอมไพล์เพื่อทดสอบ.mjs'

let ตก = 0
const ok = (ชื่อ, เงื่อนไข, เหตุ = '') => {
  console.log(`  ${เงื่อนไข ? '✅' : '❌'} ${ชื่อ}${เงื่อนไข ? '' : ` — ${เหตุ}`}`)
  if (!เงื่อนไข) ตก++
}

const ไฟล์ = 'lib/brain-layout.ts'
let งาน, วางกล่องผู้เชื่อม, กว้างผัง, สูงฐาน, ต่อแถว, สูงต่อแถว
try {
  งาน = คอมไพล์เพื่อทดสอบ({ ไฟล์: [ไฟล์], ปลอม: {} })
  ;({ วางกล่องผู้เชื่อม, กว้างผัง, สูงฐาน, ต่อแถว, สูงต่อแถว } = await import(งาน.พาธของ(ไฟล์)))
} catch (e) {
  console.error(`🔴 คอมไพล์ ${ไฟล์} ไม่ได้:`, e?.message ?? e)
  process.exit(1)
}

console.log('🧪 วางกล่องผู้เชื่อมในผังหัวสมอง')

/* ── ① ด่านหลัก: กล่องทุกใบต้องอยู่ในกรอบ ไม่ว่ามีผู้เชื่อมกี่คน ──
   นี่คือด่านที่ถ้ามีอยู่ตั้งแต่แรก จะจับบั๊กวันที่ 11 ต.ค. ได้ทันที */
for (const n of [1, 4, 5, 8, 9, 12, 20]) {
  const { กล่อง, สูงผัง } = วางกล่องผู้เชื่อม(n)
  ok(`มี ${n} คน → วาดครบ ${n} กล่อง (ห้ามตัดทิ้ง)`, กล่อง.length === n,
    `ได้ ${กล่อง.length} กล่อง`)
  const ล้นขวา = กล่อง.filter((g) => g.x + g.w > กว้างผัง)
  ok(`มี ${n} คน → ไม่มีกล่องหลุดขอบขวา`, ล้นขวา.length === 0,
    `หลุด ${ล้นขวา.length} กล่อง (x+w สูงสุด ${Math.max(...กล่อง.map((g) => g.x + g.w))} > ${กว้างผัง})`)
  const ล้นล่าง = กล่อง.filter((g) => g.y + g.h > สูงผัง)
  ok(`มี ${n} คน → ไม่มีกล่องหลุดขอบล่าง`, ล้นล่าง.length === 0, `หลุด ${ล้นล่าง.length} กล่อง`)
}

/* ── ② กล่องห้ามทับกัน — ทับกัน = อ่านชื่อไม่ออก ซึ่งก็คือ "หาย" ในทางปฏิบัติ ── */
{
  const { กล่อง } = วางกล่องผู้เชื่อม(9)
  let ทับ = 0
  for (let i = 0; i < กล่อง.length; i++)
    for (let j = i + 1; j < กล่อง.length; j++) {
      const a = กล่อง[i], b = กล่อง[j]
      if (a.x < b.x + b.w && b.x < a.x + a.w && a.y < b.y + b.h && b.y < a.y + a.h) ทับ++
    }
  ok('9 คน → ไม่มีกล่องทับกัน', ทับ === 0, `ทับกัน ${ทับ} คู่`)
}

/* ── ③ ผังต้องสูงขึ้นเองเมื่อคนเพิ่ม (ไม่ใช่ยัดคนลงกรอบเดิม) ── */
{
  const ก = วางกล่องผู้เชื่อม(ต่อแถว)
  const ข = วางกล่องผู้เชื่อม(ต่อแถว + 1)
  ok('เกินหนึ่งแถว → ผังสูงขึ้น', ข.สูงผัง === ก.สูงผัง + สูงต่อแถว,
    `${ก.สูงผัง} → ${ข.สูงผัง} (ควรเป็น ${ก.สูงผัง + สูงต่อแถว})`)
  ok('แถวเกินเพิ่มทีละ 1', ข.แถวเกิน === ก.แถวเกิน + 1, `${ก.แถวเกิน} → ${ข.แถวเกิน}`)
}

/* ── ④ ขอบล่าง: 0 คน ต้องไม่ได้แถวเกินติดลบ ──
   ceil(0/4)-1 = -1 ⇒ ของที่อยู่ใต้กล่องจะถูกดันขึ้นไป **ทับผังข้างบน**
   (อ่านสถานะจาก g1 ไม่ได้ ⇒ รายชื่อว่าง ⇒ เคสนี้เกิดจริงได้ ไม่ใช่เคสสมมติ) */
{
  const { กล่อง, แถวเกิน, สูงผัง } = วางกล่องผู้เชื่อม(0)
  ok('0 คน → ไม่มีกล่อง', กล่อง.length === 0)
  ok('0 คน → แถวเกินเป็น 0 ไม่ใช่ -1', แถวเกิน === 0, `ได้ ${แถวเกิน}`)
  ok('0 คน → ผังสูงเท่าฐาน', สูงผัง === สูงฐาน, `ได้ ${สูงผัง}`)
}

/* ── ⑤ 🪤 **ปลูกบั๊กแล้ววัด** — ด่านที่ไม่เคยถูกพิสูจน์ว่าแยกแยะได้ ให้ผลเขียวที่แปลว่า
       "ยังไม่เจอ" ไม่ใช่ "ไม่มี" ⇒ จำลองโค้ดเก่า (เรียงแถวเดียว) แล้วเกณฑ์ข้อ ① ต้องจับได้ */
{
  const แบบเก่า = (n) =>
    Array.from({ length: n }, (_, i) => ({ x: 40 + i * 160, y: 398, w: 150, h: 46 }))
  const จับได้ = แบบเก่า(8).some((g) => g.x + g.w > กว้างผัง)
  ok('🪤 เกณฑ์ข้อ ① จับโค้ดเก่า (เรียงแถวเดียว 8 กล่อง) ได้', จับได้,
    'ปลูกบั๊กแล้วเทสยังเขียว ⇒ เกณฑ์นี้แยกแยะไม่ได้ ห้ามเชื่อผลเขียวของมัน')
}

rmSync(งาน.ที่ออก, { recursive: true, force: true })
console.log(ตก ? `\n🔴 ตก ${ตก} ข้อ` : '\n✅ ผ่านหมด')
process.exit(ตก ? 1 : 0)
