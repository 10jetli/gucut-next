#!/usr/bin/env node
/* กำไรรายบรรทัด — ทดสอบ **ตัวตัดสินของจริง** (คอมไพล์ lib/line-profit.ts ด้วย tsc)
 * (ใบ t_muu0gaih ข้อ 6 · ท่อเปิดสองช่อง `unit_cost` + `cost_source` 5 ต.ค. 2569)
 *
 * 🔒 ข้อที่เทสนี้บังคับ **และมีคู่ตรงข้ามทุกข้อ**
 *   ① `unit_cost` เป็น **ต่อหน่วย** ⇒ ต้นทุนบรรทัด = unit_cost × qty
 *      ⇒ เทสข้อ ① ใช้ **qty = 3** โดยตั้งใจ · ถ้าลืมคูณ ผลจะต่างกันทันที
 *      (ถ้าทดสอบด้วย qty = 1 อย่างเดียว จะเขียวต่อให้ลืมคูณ = ไม่พิสูจน์อะไร)
 *   ② `unit_cost: null` ⇒ "ยังไม่รู้ต้นทุน" **ห้ามเป็น 0** และห้ามคิดกำไรต่อ
 *   ③ **ไม่มีช่องเลย ≠ null** ⇒ คนละชนิด
 *   ④ `cost_source` ต้องรอดออกมาทุกทาง — ห้ามโชว์ต้นทุนโดยทิ้งที่มา
 *   ⑤ รายได้ 0 ⇒ เปอร์เซ็นต์ `null` **ไม่ใช่ 0% และไม่ใช่ 100%**
 */
import { execFileSync } from 'node:child_process'
import { mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const out = mkdtempSync(join(tmpdir(), `line-profit-${process.pid}-`))
let ตก = 0
const ok = (ชื่อ, เงื่อนไข, เหตุ = '') => {
  console.log(`  ${เงื่อนไข ? '✅' : '❌'} ${ชื่อ}${เงื่อนไข ? '' : ` — ${เหตุ}`}`)
  if (!เงื่อนไข) ตก++
}

try {
  execFileSync('npx', ['tsc', 'lib/line-profit.ts', '--outDir', out,
    '--module', 'es2022', '--target', 'es2022', '--moduleResolution', 'bundler', '--skipLibCheck'],
    { stdio: 'pipe' })
  const { กำไรบรรทัด } = await import(join(out, 'line-profit.js'))

  console.log('① 🔴 unit_cost เป็นต่อหน่วย ⇒ ต้องคูณ qty (ทดสอบที่ qty = 3 ไม่ใช่ 1)')
  {
    // ขาย 3 ชิ้น รวม 900 · ต้นทุนชิ้นละ 200 ⇒ ต้นทุนบรรทัด 600 · กำไร 300 (33.33%)
    const r = กำไรบรรทัด({ qty: 3, amount: 900, unit_cost: 200, cost_source: 'ใบซื้อ' })
    ok('ชนิด = คิดได้', r.ชนิด === 'คิดได้', r.ชนิด)
    ok('ต้นทุนบรรทัด = 600 (ไม่ใช่ 200)', r.ต้นทุนบรรทัด === 600, String(r.ต้นทุนบรรทัด))
    ok('กำไร = 300 (ไม่ใช่ 700)', r.กำไร === 300, String(r.กำไร))
    ok('เปอร์เซ็นต์ ≈ 33.33', Math.abs(r.เปอร์เซ็นต์ - 33.333333) < 0.01, String(r.เปอร์เซ็นต์))
    ok('ที่มารอดออกมา', r.ที่มา === 'ใบซื้อ', String(r.ที่มา))
    // ตัวควบคุมตรงข้าม: qty = 1 ⇒ ต้นทุนบรรทัด = unit_cost พอดี
    const หนึ่ง = กำไรบรรทัด({ qty: 1, amount: 300, unit_cost: 200, cost_source: 'zort' })
    ok('ตัวควบคุมตรงข้าม: qty=1 ⇒ ต้นทุน 200', หนึ่ง.ต้นทุนบรรทัด === 200, String(หนึ่ง.ต้นทุนบรรทัด))
  }

  console.log('② 🔴 unit_cost: null ⇒ ยังไม่รู้ต้นทุน ห้ามเป็น 0 และห้ามคิดกำไรต่อ')
  {
    const r = กำไรบรรทัด({ qty: 2, amount: 500, unit_cost: null, cost_source: null })
    ok('ชนิด = ยังไม่รู้ต้นทุน', r.ชนิด === 'ยังไม่รู้ต้นทุน', r.ชนิด)
    ok('ไม่มีช่องกำไรออกมาเลย', !('กำไร' in r), JSON.stringify(r))
    ok('ไม่มีช่องต้นทุนบรรทัดออกมาเลย', !('ต้นทุนบรรทัด' in r), JSON.stringify(r))
    // ตัวควบคุมตรงข้าม: unit_cost = 0 **จริง** ⇒ ต้องคิดได้ และกำไร = ยอดเต็ม
    const ศูนย์จริง = กำไรบรรทัด({ qty: 2, amount: 500, unit_cost: 0, cost_source: 'ตั้งไว้' })
    ok('ตัวควบคุมตรงข้าม: unit_cost=0 จริง ⇒ คิดได้', ศูนย์จริง.ชนิด === 'คิดได้', ศูนย์จริง.ชนิด)
    ok('ต้นทุน 0 จริง ⇒ กำไร 500', ศูนย์จริง.กำไร === 500, String(ศูนย์จริง.กำไร))
  }

  console.log('③ ไม่มีช่องเลย ≠ null ⇒ คนละชนิด (ไม่งั้นไล่แก้ผิดฝั่ง)')
  {
    ok('ไม่มี unit_cost ⇒ ท่อยังไม่ส่งช่อง',
      กำไรบรรทัด({ qty: 1, amount: 100 }).ชนิด === 'ท่อยังไม่ส่งช่อง')
    ok('row เป็น null ⇒ ท่อยังไม่ส่งช่อง', กำไรบรรทัด(null).ชนิด === 'ท่อยังไม่ส่งช่อง')
    ok('มี unit_cost = null ⇒ ยังไม่รู้ต้นทุน (คนละชนิด)',
      กำไรบรรทัด({ qty: 1, amount: 100, unit_cost: null }).ชนิด === 'ยังไม่รู้ต้นทุน')
  }

  console.log('④ cost_source ต้องรอดออกมาทุกทาง — ห้ามโชว์ต้นทุนโดยทิ้งที่มา')
  {
    const ไม่บอกที่มา = กำไรบรรทัด({ qty: 1, amount: 100, unit_cost: 40 })
    ok('ท่อไม่ส่งที่มา ⇒ ที่มา = null (ไม่เดาให้)', ไม่บอกที่มา.ที่มา === null, String(ไม่บอกที่มา.ที่มา))
    ok('แต่ยังคิดได้', ไม่บอกที่มา.ชนิด === 'คิดได้', ไม่บอกที่มา.ชนิด)
    ok('ที่มาว่างเปล่า ⇒ null ไม่ใช่สตริงว่าง',
      กำไรบรรทัด({ qty: 1, amount: 100, unit_cost: 40, cost_source: '' }).ที่มา === null)
    ok('กิ่ง ยังไม่รู้ต้นทุน ก็ยังพาที่มาออกมา',
      กำไรบรรทัด({ qty: 1, amount: 100, unit_cost: null, cost_source: 'zort' }).ที่มา === 'zort')
  }

  console.log('⑤ 🔴 รายได้ 0 ⇒ เปอร์เซ็นต์ null ไม่ใช่ 0% และไม่ใช่ 100%')
  {
    const r = กำไรบรรทัด({ qty: 1, amount: 0, unit_cost: 50, cost_source: 'ใบซื้อ' })
    ok('ชนิด = คิดได้ (ของแจกฟรีก็ยังคิดต้นทุนได้)', r.ชนิด === 'คิดได้', r.ชนิด)
    ok('กำไร = -50 (ขาดทุนจริง)', r.กำไร === -50, String(r.กำไร))
    ok('เปอร์เซ็นต์ = null', r.เปอร์เซ็นต์ === null, String(r.เปอร์เซ็นต์))
    // ตัวควบคุมตรงข้าม: รายได้ไม่ใช่ 0 ⇒ ต้องได้เลข
    ok('ตัวควบคุมตรงข้าม: รายได้ 100 ⇒ ได้เลข',
      typeof กำไรบรรทัด({ qty: 1, amount: 100, unit_cost: 50, cost_source: 'x' }).เปอร์เซ็นต์ === 'number')
  }

  console.log('⑥ ตัวเลขที่ท่อไม่ส่ง ⇒ บอกว่าอ่านไม่ได้ ห้ามเดาเป็น 0')
  {
    const ไม่มีqty = กำไรบรรทัด({ amount: 100, unit_cost: 10 })
    ok('ไม่มี qty ⇒ อ่านตัวเลขไม่ได้', ไม่มีqty.ชนิด === 'อ่านตัวเลขไม่ได้', ไม่มีqty.ชนิด)
    ok('เหตุบอกว่าขาดจำนวน', String(ไม่มีqty.เหตุ).includes('จำนวน'), String(ไม่มีqty.เหตุ))
    const ไม่มีamount = กำไรบรรทัด({ qty: 2, unit_cost: 10 })
    ok('ไม่มี amount ⇒ อ่านตัวเลขไม่ได้', ไม่มีamount.ชนิด === 'อ่านตัวเลขไม่ได้', ไม่มีamount.ชนิด)
    ok('เหตุบอกว่าขาดยอด', String(ไม่มีamount.เหตุ).includes('ยอด'), String(ไม่มีamount.เหตุ))
    // ตัวควบคุมตรงข้าม: qty = 0 **จริง** ⇒ ต้องคิดได้ ไม่ใช่ "อ่านไม่ได้"
    const ศูนย์ชิ้น = กำไรบรรทัด({ qty: 0, amount: 0, unit_cost: 10, cost_source: 'x' })
    ok('ตัวควบคุมตรงข้าม: qty=0 จริง ⇒ คิดได้', ศูนย์ชิ้น.ชนิด === 'คิดได้', ศูนย์ชิ้น.ชนิด)
  }

  console.log(`\nสรุป: ตก ${ตก}`)
  if (ตก) process.exit(1)
} finally {
  rmSync(out, { recursive: true, force: true })
}
