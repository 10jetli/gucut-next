#!/usr/bin/env node
/* ตัวจัดกอง "ถ้ารัดเกณฑ์เดือน ใบไหนจะขยับ" (`lib/bill-month-diff.ts`)
 * (ใบ t_mu8i1pu1 · 30 ก.ย. 2569 · CEO สั่ง แล้วแก้คำถามของตัวเองสองรอบ)
 *
 * ⚠️ เทสนี้ยิง **ของจริงสามชั้น** ไม่มีตัวปลอมเลย:
 *    ① `จัดกองส่วนต่าง` — ตัวจัดกอง
 *    ② `filingMonthOf` — ตัวจัดประเภทเดือนตัวจริง (lib/bill-filing.ts)
 *    ③ `เดือนบิลถูกต้อง` — เกณฑ์เดือนตัวจริง (lib/billmonth.ts)
 *    เหตุที่ต้องเป็นของจริงทั้งสาม: ถ้าปลอมชั้นใดชั้นหนึ่ง เครื่องมือจะวัด
 *    **ตัวจัดประเภทอีกตัวที่ไม่มีใครใช้** แล้วให้เลขที่น่าเชื่อของระบบที่ไม่มีอยู่จริง
 *    (CEO ย้ำข้อนี้ตรง ๆ: import ตัวจริงห้ามลอก)
 *
 * 🔒 สี่กองที่ตรึงไว้ — ลำดับการตัดสินสำคัญ
 *    ③ `หลุดจากทุกเดือน` เป็นกรณีเฉพาะของ "เปลี่ยน" ⇒ ถ้าเช็ค ② ก่อน
 *       กองที่หนักที่สุดจะถูกกลืนเข้ากองที่เบากว่า **แล้วไม่มีอะไรฟ้อง**
 */
import { rmSync } from 'node:fs'
import { คอมไพล์เพื่อทดสอบ } from '../lib/คอมไพล์เพื่อทดสอบ.mjs'

let ตก = 0
const ok = (ชื่อ, เงื่อนไข, เหตุ = '') => {
  console.log(`  ${เงื่อนไข ? '✅' : '❌'} ${ชื่อ}${เงื่อนไข ? '' : ` — ${เหตุ}`}`)
  /* 🔑 บรรทัดนี้พิมพ์ **เฉพาะตอนตก** ⇒ ใช้เป็นสมอของสูตรปลูกได้ */
  if (!เงื่อนไข) { ตก++; console.log(`     🔴 ตกที่ ${ชื่อ}`) }
}
const ไฟล์ = 'lib/bill-month-diff.ts'
let งาน

try {
  const ผล = คอมไพล์เพื่อทดสอบ({ ไฟล์: [ไฟล์], ปลอม: {} })
  งาน = ผล.ที่ออก
  const { จัดกองส่วนต่าง, เก็บส่วนต่าง, ตัวสะสมใหม่, สรุปส่วนต่าง } = await import(ผล.พาธของ(ไฟล์))

  console.log('① สี่กอง — จัดถูกกองทุกรูป')
  {
    const ก1 = จัดกองส่วนต่าง('2026-08_REAL_a.pdf', '2026-08')
    ok('รอบบิลอยู่ในช่วง ⇒ ไม่เปลี่ยน', ก1.กอง === 'ไม่เปลี่ยน' && ก1.แถว === null, JSON.stringify(ก1))

    const ก2 = จัดกองส่วนต่าง('2026-08_REAL_b.pdf', '2026-13')
    ok('รอบบิลนอกช่วง + ชื่อไฟล์มีเดือน ⇒ ย้ายเดือน', ก2.กอง === 'ย้ายเดือน', JSON.stringify(ก2))
    ok('  บอกทั้งวันนี้และกติกาใหม่', ก2.แถว?.วันนี้ === '2026-13' && ก2.แถว?.กติกาใหม่ === '2026-08',
      JSON.stringify(ก2.แถว))

    const ก3 = จัดกองส่วนต่าง('ไม่มีเดือนนำหน้า.pdf', '2026-00')
    ok('รอบบิลนอกช่วง + ชื่อไฟล์ไม่มีเดือน ⇒ **หลุดจากทุกเดือน** ไม่ใช่ ย้ายเดือน',
      ก3.กอง === 'หลุดจากทุกเดือน',
      `${ก3.กอง} ⇒ จัดเป็นย้ายเดือน = คนอ่านคิดว่ายังหาเจอ ทั้งที่มันหายจากทุกจอ`)
    ok('  กติกาใหม่เป็น null และเขียนว่าจะหายจากทุกจอ',
      ก3.แถว?.กติกาใหม่ === null && /หายจากทุกจอ/.test(ก3.แถว?.เพราะ ?? ''), JSON.stringify(ก3.แถว))

    for (const [ชื่อ, ค่า] of [['null', null], ['undefined', undefined], ['ข้อความว่าง', '']]) {
      const ก = จัดกองส่วนต่าง('2026-08_REAL_c.pdf', ค่า)
      ok(`รอบบิลเป็น ${ชื่อ} ⇒ แกะรอบไม่ได้ (ไม่ใช่ ไม่เปลี่ยน)`, ก.กอง === 'แกะรอบไม่ได้',
        `${ก.กอง} ⇒ ยุบเข้า "ไม่เปลี่ยน" = กองที่เดือนบนจอไม่มีหลักฐานรองรับ หายจากรายงาน`)
    }
  }

  console.log('② ลำดับการตัดสิน — กองหนักต้องไม่ถูกกองเบากลืน')
  {
    /* 🔑 ข้อนี้คือเหตุผลที่ต้องเทสตัว lib ตรง ๆ ไม่ใช่เทสผ่านเส้น API เท่านั้น
       เพราะถ้าเช็ค "ย้ายเดือน" ก่อน "หลุดจากทุกเดือน" เส้น API จะยังตอบตัวเลขรวมเท่ากัน
       (สองกองรวมกันได้เลขเดิม) ⇒ ตรึงที่ชั้น lib เท่านั้นที่จับได้ */
    const ทุกรูปที่หลุด = [
      ['ไฟล์ไม่มีเดือนนำหน้าเลย', 'ใบเสร็จ.pdf', '2026-13'],
      ['เดือน 00', 'ใบเสร็จ.pdf', '2026-00'],
      ['เดือน 99', 'ใบเสร็จ.pdf', '2026-99'],
    ]
    for (const [ชื่อ, f, รอบ] of ทุกรูปที่หลุด) {
      const ก = จัดกองส่วนต่าง(f, รอบ)
      ok(`${ชื่อ} ⇒ หลุดจากทุกเดือน`, ก.กอง === 'หลุดจากทุกเดือน', ก.กอง)
    }
    /* 🟢 ตัวควบคุมลบของลำดับ: ชื่อไฟล์มีเดือน ⇒ ต้องเป็น "ย้ายเดือน" ไม่ใช่ "หลุด"
       ไม่มีข้อนี้ โค้ดที่จัดทุกอย่างเป็น "หลุดจากทุกเดือน" ก็เขียว */
    const ก = จัดกองส่วนต่าง('2026-05_REAL_x.pdf', '2026-13')
    ok('🟢 ตัวควบคุมลบ: ชื่อไฟล์มีเดือน ⇒ ย้ายเดือน (ไปเดือนจากชื่อไฟล์)',
      ก.กอง === 'ย้ายเดือน' && ก.แถว?.กติกาใหม่ === '2026-05', JSON.stringify(ก))
  }

  console.log('③ ตัวสะสม + การสรุป')
  {
    const acc = ตัวสะสมใหม่()
    เก็บส่วนต่าง(acc, '2026-08_REAL_a.pdf', '2026-08')
    เก็บส่วนต่าง(acc, '2026-08_REAL_b.pdf', '2026-08')
    เก็บส่วนต่าง(acc, '2026-08_REAL_c.pdf', '2026-13')
    เก็บส่วนต่าง(acc, 'ไม่มีเดือน.pdf', '2026-13')
    เก็บส่วนต่าง(acc, '2026-08_REAL_d.pdf', null)
    ok('นับสี่กองแยกกันถูก', acc.ไม่เปลี่ยน === 2 && acc.ย้ายเดือน.length === 1
      && acc.หลุดจากทุกเดือน.length === 1 && acc.แกะรอบไม่ได้.length === 1,
      JSON.stringify({ ไม่เปลี่ยน: acc.ไม่เปลี่ยน, ย้าย: acc.ย้ายเดือน.length,
        หลุด: acc.หลุดจากทุกเดือน.length, แกะไม่ได้: acc.แกะรอบไม่ได้.length }))

    const ส = สรุปส่วนต่าง(acc, { อ่านรอบนี้: 5, ในถัง: 5, ยังไม่ได้อ่าน: 0 })
    ok('ความครอบคลุมมีตัวหาร และบอกว่าอ่านครบ',
      /ตัดสินได้ 4/.test(ส.ครอบคลุม) && /ในถังทั้งหมด 5/.test(ส.ครอบคลุม)
      && /อ่านครบทั้งเจ้าแล้ว/.test(ส.ครอบคลุม), ส.ครอบคลุม)

    const ยังไม่ครบ = สรุปส่วนต่าง(acc, { อ่านรอบนี้: 5, ในถัง: 40, ยังไม่ได้อ่าน: 35 })
    ok('🔴 อ่านไม่ครบ ⇒ ต้องเขียนตรง ๆ ว่ายังสรุปทั้งเจ้าไม่ได้',
      /ยังไม่ได้อ่านอีก 35 ใบ/.test(ยังไม่ครบ.ครอบคลุม) && /ยังสรุปทั้งเจ้าไม่ได้/.test(ยังไม่ครบ.ครอบคลุม),
      `${ยังไม่ครบ.ครอบคลุม} ⇒ ไม่เขียน = คนอ่านเลข 0 แล้วเชื่อว่าทั้งเจ้าไม่มีปัญหา`)
    ok('รายการไปกับตัวเลขทุกกอง ไม่ใช่มีแต่ตัวเลข',
      ส.รายการย้ายเดือน?.length === 1 && ส.รายการหลุดจากทุกเดือน?.length === 1
      && ส.รายชื่อที่แกะรอบไม่ได้?.length === 1, JSON.stringify(Object.keys(ส)))
    ok('ขอบเขตของคำตอบบอกว่าตอบอะไรไม่ได้', /วัดย้อนหลังไม่ได้/.test(ส.ขอบเขตของคำตอบ),
      ส.ขอบเขตของคำตอบ)

    /* 🟢 ตัวควบคุมลบของตัวสะสม: ไม่เก็บอะไรเลย ⇒ ทุกกองต้องเป็น 0 และไม่พัง */
    const ว่าง = สรุปส่วนต่าง(ตัวสะสมใหม่(), { อ่านรอบนี้: 0, ในถัง: 0, ยังไม่ได้อ่าน: 0 })
    ok('🟢 ตัวควบคุมลบ: ไม่มีไฟล์เลย ⇒ ทุกกอง 0 และยังตอบได้',
      ว่าง.ย้ายเดือน === 0 && ว่าง.หลุดจากทุกเดือน === 0 && ว่าง.แกะรอบไม่ได้ === 0
      && ว่าง.ไม่เปลี่ยน === 0 && /ตัดสินได้ 0/.test(ว่าง.ครอบคลุม), JSON.stringify(ว่าง))
  }
} finally {
  if (งาน) rmSync(งาน, { recursive: true, force: true })
}

console.log(ตก ? `\n❌ ไม่ผ่าน ${ตก} ข้อ` : '\n✅ ผ่านทุกข้อ')
console.log('⚠️ ขอบเขต: **ไม่มีตัวปลอมเลย** — ยิง filingMonthOf และ เดือนบิลถูกต้อง ตัวจริงทั้งคู่')
process.exit(ตก ? 1 : 0)
