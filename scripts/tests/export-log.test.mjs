#!/usr/bin/env node
/* สมุดบันทึกการส่งออกไฟล์ (`lib/export-log.ts`) — **ท่านประธานขอไว้เอง 18 ก.ย. 2569**
 * (ใบ t_mu8i1pu1 · 29 ก.ย. 2569) 105 บรรทัด · ไม่มีอะไรใน scripts/ เอ่ยถึงเลย
 *
 * คำของท่าน ตอนอนุมัติให้ส่งออก Excel ได้ทุกจอ รวมจอผู้ติดต่อที่มีข้อมูลลูกค้า:
 *   "ขอให้จดไว้ด้วยว่าใครกดส่งออกจอไหน เมื่อไหร่ ได้กี่แถว ในที่ที่ผมเปิดดูได้
 *    วันหนึ่งถ้ามีคนถามว่าข้อมูลลูกค้าหลุดจากไหน จะได้ตอบได้"
 *
 * 🔑 สมุดนี้มีหน้าที่ตอบคำถามเดียว: **ใครเอาข้อมูลลูกค้าออกไป**
 *    ⇒ พลาดที่นี่ = วันที่มีคนถาม เราตอบไม่ได้ · และไม่มีวันรู้ว่าพลาดจนถึงวันนั้น
 *    🔴 นี่คือของที่ **ไม่มีใครทดลองใช้จนกว่าจะสายเกินไป** — ตาข่ายจึงเป็นทางเดียวที่พิสูจน์ได้
 *
 * 🔑 สี่กฎที่ไฟล์ประกาศเอง และเทสนี้ตรึงไว้:
 *    ① **ห้ามจดเนื้อข้อมูล** — สมุดที่ไว้สืบเรื่องข้อมูลรั่ว ต้องไม่กลายเป็นที่รั่วเสียเอง
 *       ⇒ ตรวจแบบ **บัญชีขาว** (มีได้เฉพาะ 5 ช่อง) ไม่ใช่บัญชีดำของคำ
 *          บัญชีดำตกยุคทุกครั้งที่มีคนเพิ่มช่องใหม่ · บัญชีขาวฟ้องช่องใหม่ทุกช่อง
 *    ② **ตัวจดห้ามทำให้งานหลักพัง** — ไฟล์ถึงมือผู้ใช้แล้วตอนเรียกตัวนี้
 *       จดไม่ได้ ไม่ใช่เหตุให้บอกว่าส่งออกไม่สำเร็จ ⇒ ห้ามโยน error ออกมา
 *    ③ **หนึ่งครั้ง = หนึ่งคีย์** — สองคนกดพร้อมกันแล้วบันทึกต้องไม่หายเงียบ
 *    ④ **อ่านไม่ได้ (null) ≠ ไม่มีบันทึก ([])** — สองอย่างนี้ตอบคนละคำให้คนที่มาสืบ
 *       "ไม่มีบันทึก" = ไม่มีใครส่งออก · "อ่านไม่ได้" = ยังไม่รู้ ⇒ ต้องไปหาที่อื่นต่อ
 */
import { execFileSync } from 'node:child_process'
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const out = mkdtempSync(join(tmpdir(), `export-log-${process.pid}-`))
let ตก = 0
const ok = (ชื่อ, เงื่อนไข, เหตุ = '') => {
  console.log(`  ${เงื่อนไข ? '✅' : '❌'} ${ชื่อ}${เงื่อนไข ? '' : ` — ${เหตุ}`}`)
  if (!เงื่อนไข) ตก++
}

try {
  execFileSync('npx', ['tsc', 'lib/export-log.ts', '--outDir', out,
    '--module', 'es2022', '--target', 'es2022', '--moduleResolution', 'bundler', '--skipLibCheck'],
    { stdio: 'pipe' })
  writeFileSync(join(out, 'package.json'), '{"type":"module"}')

  /* ที่เก็บปลอม + สวิตช์ทำให้พังได้ — เพราะกฎ ② พูดถึง "ตอนที่ที่เก็บล่ม" โดยเฉพาะ */
  const bl = join(out, 'node_modules', '@netlify', 'blobs')
  mkdirSync(bl, { recursive: true })
  writeFileSync(join(bl, 'package.json'), '{"name":"@netlify/blobs","type":"module","main":"index.js"}')
  writeFileSync(join(bl, 'index.js'), `
export const ถัง = new Map();
export const พัง = { getStore: false, setJSON: false, list: false, get: false };
export function getStore() {
  if (พัง.getStore) throw new Error('ยังไม่ได้ตั้งค่า Blobs');
  return {
    async setJSON(key, v) { if (พัง.setJSON) throw new Error('ถังตอบ 500'); ถัง.set(key, v); },
    async get(key) { if (พัง.get) throw new Error('อ่านไม่ได้'); return ถัง.get(key) ?? null; },
    async list({ prefix } = {}) {
      if (พัง.list) throw new Error('list พัง');
      return { blobs: [...ถัง.keys()].filter((k) => !prefix || k.startsWith(prefix)).map((key) => ({ key, size: 1 })) };
    },
  };
}
`)
  const { ถัง, พัง } = await import(join(out, 'node_modules/@netlify/blobs/index.js'))
  const { logExport, readExportLog } = await import(join(out, 'export-log.js'))
  const ล้าง = () => { ถัง.clear(); for (const k of Object.keys(พัง)) พัง[k] = false }
  const เมื่อ = (วันก่อน) => new Date(Date.now() - วันก่อน * 86400_000).toISOString()

  console.log('① 🔴 ห้ามจดเนื้อข้อมูล — ตรวจแบบบัญชีขาว ช่องใหม่ทุกช่องต้องถูกฟ้อง')
  {
    ล้าง()
    /* ส่งของที่ **ไม่ควรถูกจด** พ่วงมาด้วย — รูปเดียวกับวันที่มีคนเผลอส่ง row ทั้งแถวเข้ามา */
    await logExport({
      at: เมื่อ(0), who: 'สมชาย', screen: 'ผู้ติดต่อ', scope: 'ลูกค้า · ช่วง 01/09–18/09', rows: 42,
      ชื่อลูกค้า: 'คุณมานี ใจดี', เบอร์: '0812345678', ที่อยู่: '99/1 ถนนสุขุมวิท',
      เลขที่เอกสาร: 'IV2609001', แถวตัวอย่าง: [{ name: 'มานี', tel: '081' }],
    })
    const [บันทึก] = [...ถัง.values()]
    const ช่องที่ยอมให้มี = ['at', 'who', 'screen', 'scope', 'rows']
    const ช่องเกิน = Object.keys(บันทึก).filter((k) => !ช่องที่ยอมให้มี.includes(k))
    ok('ในบันทึกมีเฉพาะ 5 ช่องที่ประกาศไว้', ช่องเกิน.length === 0,
      `ช่องเกิน: ${ช่องเกิน.join(' · ')} ⇒ สมุดที่ไว้สืบเรื่องข้อมูลรั่ว กลายเป็นที่รั่วเสียเอง`)
    /* ตรวจซ้ำอีกทางด้วยการหาเนื้อข้อมูลในข้อความ JSON ทั้งก้อน — กันกรณีที่ค่าถูกยัดลงช่องที่ยอมให้มี */
    const ก้อน = JSON.stringify(บันทึก)
    for (const ห้าม of ['0812345678', 'มานี', 'สุขุมวิท', 'IV2609001']) {
      ok(`ไม่มี "${ห้าม}" อยู่ในบันทึก`, !ก้อน.includes(ห้าม), ก้อน.slice(0, 160))
    }
    ok('แต่ยังจดสิ่งที่ท่านขอครบ: คน · จอ · เวลา · จำนวนแถว',
      บันทึก.who === 'สมชาย' && บันทึก.screen === 'ผู้ติดต่อ' && บันทึก.rows === 42 && !!บันทึก.at,
      JSON.stringify(บันทึก))
  }

  console.log('② 🔴 ที่เก็บล่ม ⇒ คืน false **ห้ามโยน error** (ไฟล์ถึงมือผู้ใช้ไปแล้ว)')
  {
    ล้าง(); พัง.setJSON = true
    let โยน = null
    const r = await logExport({ at: เมื่อ(0), who: 'แอดมิน', screen: 'ผู้ติดต่อ', rows: 5 })
      .catch((e) => { โยน = String(e?.message ?? e); return 'โยน' })
    ok('ไม่โยน error ออกมา', โยน === null, `โยน: ${โยน} ⇒ จอจะขึ้นว่าส่งออกไม่สำเร็จ ทั้งที่ไฟล์ออกไปแล้ว`)
    ok('คืน false (บอกตรง ๆ ว่าจดไม่ได้ ไม่ใช่แกล้งว่าจดแล้ว)', r === false, String(r))
    ล้าง(); พัง.getStore = true
    ok('ยังไม่ได้ตั้งค่า Blobs ⇒ false ไม่ใช่ error', (await logExport({ at: เมื่อ(0), who: 'ก', screen: 'ข', rows: 1 })) === false)
  }

  console.log('③ 🔴 หนึ่งครั้ง = หนึ่งคีย์ — สองคนกดพร้อมกันแล้วบันทึกห้ามหาย')
  {
    ล้าง()
    const at = เมื่อ(0)
    await Promise.all([
      logExport({ at, who: 'สมชาย', screen: 'ผู้ติดต่อ', rows: 10 }),
      logExport({ at, who: 'สมหญิง', screen: 'ผู้ติดต่อ', rows: 20 }),
    ])
    ok('ได้ 2 คีย์ (ไม่ทับกันแม้เวลาเท่ากันเป๊ะ)', ถัง.size === 2,
      `${ถัง.size} คีย์ ⇒ คนที่สองหายจากสมุด และไม่มีอะไรฟ้อง`)
    const คน = [...ถัง.values()].map((v) => v.who).sort()
    ok('ทั้งสองคนอยู่ในสมุด', คน.join(',') === 'สมชาย,สมหญิง', คน.join(','))
  }

  console.log('④ 🔴 อ่านไม่ได้ (null) ≠ ไม่มีบันทึก ([]) — ตอบคนละคำให้คนที่มาสืบ')
  {
    ล้าง()
    const ว่าง = await readExportLog()
    ok('ถังว่าง ⇒ [] (ยืนยันได้ว่าไม่มีใครส่งออก)', Array.isArray(ว่าง) && ว่าง.length === 0, JSON.stringify(ว่าง))
    ล้าง(); พัง.list = true
    /* เหตุที่พิมพ์เฉพาะตอนตก — ใช้เป็น **สมอ** ของสูตรปลูก (ชื่อข้อถูกพิมพ์ตอนผ่านด้วย ⇒ ตรงฟรี) */
    ok('อ่านไม่ได้ ⇒ null (ยังไม่รู้ ⇒ ต้องไปหาที่อื่นต่อ)', (await readExportLog()) === null,
      'list พังแล้วไม่คืน null ⇒ ปิดทางสืบต่อ')
    ล้าง(); พัง.getStore = true
    ok('ยังไม่ได้ตั้งค่า ⇒ null ไม่ใช่ []', (await readExportLog()) === null,
      'คืน [] ⇒ คนที่มาสืบจะสรุปว่า "ไม่มีใครส่งออกข้อมูลลูกค้าเลย" ทั้งที่แค่อ่านไม่ได้')
  }

  console.log('⑤ เก็บ 180 วัน — และของที่อ่านวันไม่ออกต้อง **เก็บไว้** ไม่ใช่ทิ้ง')
  {
    ล้าง()
    await logExport({ at: เมื่อ(1), who: 'เพิ่งกด', screen: 'ผู้ติดต่อ', rows: 1 })
    await logExport({ at: เมื่อ(179), who: 'เกือบครบกำหนด', screen: 'ผู้ติดต่อ', rows: 2 })
    await logExport({ at: เมื่อ(181), who: 'เกินกำหนด', screen: 'ผู้ติดต่อ', rows: 3 })
    ถัง.set('e/อ่านวันไม่ออกเลย-zzzzzz', { at: 'มั่ว', who: 'อ่านวันไม่ออก', screen: 'ผู้ติดต่อ', rows: 4 })
    const คน = (await readExportLog()).map((x) => x.who)
    ok('179 วันยังอยู่', คน.includes('เกือบครบกำหนด'), คน.join(' · '))
    ok('181 วันหลุดไปแล้ว', !คน.includes('เกินกำหนด'), คน.join(' · '))
    /* เหตุต้อง **เจาะจงกว่ารายชื่อคน** เพราะสองข้อข้างบนใช้ `คน.join` เป็นเหตุเหมือนกัน
       ⇒ ถ้าเอารายชื่อคนเป็นสมอ มันจะโผล่ตอนข้ออื่นตกด้วย = จับได้ด้วยเหตุผิดข้อ */
    ok('อ่านวันไม่ออก ⇒ เก็บไว้ (ของที่เราอ่านไม่ออกห้ามหายเงียบ)', คน.includes('อ่านวันไม่ออก'),
      `ของที่อ่านวันไม่ออกหายจากสมุดเงียบ ๆ ⇒ ${คน.join(' · ')}`)
  }

  console.log('⑥ เรียงใหม่ก่อน · limit ตัดของเก่าทิ้ง ไม่ใช่ตัดของใหม่')
  {
    ล้าง()
    for (const d of [5, 1, 3]) await logExport({ at: เมื่อ(d), who: `เมื่อ${d}วันก่อน`, screen: 'ก', rows: d })
    const ทั้งหมด = (await readExportLog()).map((x) => x.who)
    ok('ใหม่ก่อน', ทั้งหมด.join(',') === 'เมื่อ1วันก่อน,เมื่อ3วันก่อน,เมื่อ5วันก่อน', ทั้งหมด.join(','))
    const สองแถว = (await readExportLog(2)).map((x) => x.who)
    ok('limit 2 ⇒ ได้สองรายการใหม่สุด', สองแถว.join(',') === 'เมื่อ1วันก่อน,เมื่อ3วันก่อน', สองแถว.join(','))
  }

  console.log('⑦ ชื่อคนที่แยกไม่ได้ ห้ามกลายเป็นชื่อคนใดคนหนึ่ง (รหัสหลักใช้ร่วมกันหลายคน)')
  {
    ล้าง()
    await logExport({ at: เมื่อ(0), who: '', screen: 'ผู้ติดต่อ', rows: 1 })
    const [v] = [...ถัง.values()]
    ok('ไม่รู้ว่าใคร ⇒ ไม่เติมชื่อให้เอง', v.who === '',
      `ได้ "${v.who}" ⇒ สมุดจะชี้นิ้วไปที่คนที่อาจไม่ได้ทำ`)
  }

  console.log('⑧ ⚠️ เพดานข้อความ 120 — **หน่วยเป็นอักขระ ไม่ใช่ไบต์**')
  {
    ล้าง()
    await logExport({ at: เมื่อ(0), who: 'ก'.repeat(300), screen: 'ข'.repeat(300),
      scope: 'ค'.repeat(300), rows: 1 })
    const [v] = [...ถัง.values()]
    ok('ตัดที่ 120 อักขระ', v.who.length === 120 && v.screen.length === 120 && v.scope.length === 120,
      `${v.who.length} · ${v.screen.length} · ${v.scope.length}`)
    const ไบต์ = Buffer.byteLength(v.who, 'utf8')
    ok(`120 อักขระไทย = ${ไบต์} ไบต์ (ราว 3 เท่า) — เขียนไว้ให้เห็น ไม่ให้ใครอ่านเลขนี้เป็นไบต์`,
      ไบต์ === 360, String(ไบต์))
    /* 🔴 รุ่นแรกผมเขียนข้อนี้เป็น `ok('…', (async () => true)() && true)` = **จริงตลอดกาล**
       ตรวจไม่ได้อะไรเลยแต่ขึ้น ✅ ⇒ ข้อทดสอบที่ผ่านฟรีแย่กว่าไม่มีข้อนั้น เพราะนับเข้ายอด */
    ล้าง()
    await logExport({ at: เมื่อ(0), who: 'ก', screen: 'ข', rows: 1 })
    const [ไม่มีขอบเขต] = [...ถัง.values()]
    ok('scope ที่ไม่ส่งมา ⇒ null (ไม่ใช่สตริงว่าง ซึ่งอ่านว่า "ขอบเขตว่าง")',
      ไม่มีขอบเขต.scope === null, JSON.stringify(ไม่มีขอบเขต))
  }

  console.log('⑨ จำนวนแถว — ปัดเศษลง · ลบกลายเป็น 0')
  {
    ล้าง()
    await logExport({ at: เมื่อ(0), who: 'ก', screen: 'ข', rows: 3.7 })
    await logExport({ at: เมื่อ(0), who: 'ข', screen: 'ข', rows: -5 })
    await logExport({ at: เมื่อ(0), who: 'ค', screen: 'ข', rows: NaN })
    const ตาราง = Object.fromEntries([...ถัง.values()].map((v) => [v.who, v.rows]))
    ok('3.7 ⇒ 3', ตาราง['ก'] === 3, String(ตาราง['ก']))
    ok('-5 ⇒ 0', ตาราง['ข'] === 0, String(ตาราง['ข']))
    /* 🟠 **ข้อสังเกตที่ยังไม่แก้ในรอบนี้ และตั้งใจเขียนให้เห็น**
       `rows: NaN` (ไม่รู้ว่ากี่แถว) ถูกเขียนลงสมุดเป็น **0** ซึ่งอ่านว่า "ไม่มีอะไรออกไป"
       ⇒ ในสมุดที่ไว้ตอบคำถาม "ข้อมูลหลุดไปเท่าไหร่" ศูนย์ปลอมคือ **ข่าวดีปลอม**
       🚫 ไม่แก้เองเพราะนี่คือรูปของบันทึกที่ท่านประธานขอ — เปลี่ยนรูปต้องบอกก่อน
       ⇒ เทสตรึง **พฤติกรรมวันนี้** ไว้ พร้อมเขียนกำกับว่าทำไมมันน่าเป็นห่วง
          วันที่มีคนแก้ให้เป็น null ด่านจะแดง แล้วจะได้อ่านข้อนี้ */
    ok('NaN ⇒ 0 (พฤติกรรมวันนี้ · ดูข้อสังเกตในซอร์สของเทส)', ตาราง['ค'] === 0, String(ตาราง['ค']))
    console.log('     🟠 ข้อสังเกต: "ไม่รู้ว่ากี่แถว" ถูกจดเป็น 0 ซึ่งอ่านว่า "ไม่มีอะไรออกไป"')
    console.log('        ⇒ ในสมุดสืบข้อมูลรั่ว ศูนย์ปลอมคือข่าวดีปลอม · เสนอให้เป็น null แต่ยังไม่แก้เอง')
  }
} finally {
  rmSync(out, { recursive: true, force: true })
}

console.log(ตก ? `\n❌ ไม่ผ่าน ${ตก} ข้อ` : '\n✅ ผ่านทุกข้อ')
console.log('⚠️ ขอบเขต: ปลอมที่เก็บ (Netlify Blobs) — กติกาบัญชีขาว · วันหมดอายุ · การไม่โยน error เป็นของจริง')
process.exit(ตก ? 1 : 0)
