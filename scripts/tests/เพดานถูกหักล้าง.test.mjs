#!/usr/bin/env node
/* เทสของ `lib/เพดานถูกหักล้าง.ts`
 *
 * 🔴 ทำไมต้องมี: ตัวตัดสินนี้เกิดเพราะจอเขียน **ประโยคเท็จ** ว่าฟังก์ชันถูกตัดที่ 30 วินาที
 *    ทั้งที่สมุดมีรอบ 56,374 ms ที่จบสำเร็จ ⇒ ถ้าตัวตัดสินนี้เงียบผิด จอจะกลับไปโกหกเหมือนเดิม
 * 🔑 เคสแรกคือ **ของจริงจากสมุด** ไม่ใช่เลขที่แต่งขึ้น
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { หาเพดานที่ถูกหักล้าง } from '../../lib/เพดานถูกหักล้าง.ts'

test('ของจริงจากสมุด 21 ก.ย.: 56,374 ms เกินเพดาน 30,000 ⇒ หักล้าง', () => {
  assert.equal(หาเพดานที่ถูกหักล้าง([15356, 56374, 7381, 3613], 30000), 56374)
})

test('ไม่มีแถวไหนเกิน ⇒ null (ห้ามเตือนลอย ๆ)', () => {
  assert.equal(หาเพดานที่ถูกหักล้าง([15356, 20315, 9994], 30000), null)
})

test('เท่ากับเพดานพอดี ⇒ ยังไม่ถือว่าหักล้าง', () => {
  assert.equal(หาเพดานที่ถูกหักล้าง([30000], 30000), null)
})

test('คืนค่าที่ยาวที่สุดเมื่อมีหลายแถวขัดแย้ง', () => {
  assert.equal(หาเพดานที่ถูกหักล้าง([31000, 56374, 38421], 30000), 56374)
})

test('ท่อไม่ส่งเพดานมา ⇒ null (ไม่มีอะไรให้หักล้าง ไม่ใช่ "ไม่ขัดแย้ง")', () => {
  assert.equal(หาเพดานที่ถูกหักล้าง([99999], null), null)
  assert.equal(หาเพดานที่ถูกหักล้าง([99999], undefined), null)
})

test('ค่าที่ไม่ใช่ตัวเลขในแถว ⇒ ข้าม ไม่โยน', () => {
  assert.equal(หาเพดานที่ถูกหักล้าง([null, undefined, NaN, 40000], 30000), 40000)
})

test('เพดานเป็น 0 หรือติดลบ ⇒ null (ค่าพัง ห้ามอ่านว่าทุกแถวหักล้าง)', () => {
  assert.equal(หาเพดานที่ถูกหักล้าง([1000], 0), null)
  assert.equal(หาเพดานที่ถูกหักล้าง([1000], -5), null)
})

test('ควบคุมลบ: ถ้าไม่กรอง NaN ออก Math.max จะคืน NaN ⇒ เคสนี้กันไว้', () => {
  const ผล = หาเพดานที่ถูกหักล้าง([NaN, NaN], 30000)
  assert.equal(ผล, null)
  assert.ok(!Number.isNaN(ผล))
})
