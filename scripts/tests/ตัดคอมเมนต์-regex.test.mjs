/* ป้อนของเสียใส่ตัวตัดคอมเมนต์ฝั่งจอ — รูปเดียวกับที่ฝั่งท่อเพิ่งเจอ (20 ก.ย. 2569)
   ① regex literal ที่มี backtick  ② regex ที่มี // หรือ /* ข้างใน
   🔑 ถามสองทิศ: (ก) ตัดคอมเมนต์ไม่ออก ⇒ คำในคอมเมนต์กลายเป็นของจริง (บวกลวง)
                 (ข) กินโค้ดจริง ⇒ ด่านมองไม่เห็นโค้ด (เขียวลวง) */
import { ตัดคอมเมนต์ } from '../lib/ตัดคอมเมนต์.mjs'

const เคส = [
  {
    ชื่อ: '① regex มี backtick — คอมเมนต์ข้างล่างต้องถูกตัด',
    โค้ด: "const re = /[`]/\n// ZZคำในคอมเมนต์ZZ\nconst จริง = 1\n",
    ต้องไม่มี: 'ZZคำในคอมเมนต์ZZ',
    ต้องมี: 'const จริง = 1',
  },
  {
    ชื่อ: '② regex มี // ข้างใน — โค้ดจริงข้างหลังต้องอยู่ครบ',
    โค้ด: "const re = /https:\\/\\//\nconst จริง = 2\n",
    ต้องมี: 'const จริง = 2',
  },
  {
    ชื่อ: '③ regex มี /* ข้างใน — โค้ดจริงข้างหลังต้องอยู่ครบ',
    โค้ด: "const re = /\\/\\*/\nconst จริง = 3\n",
    ต้องมี: 'const จริง = 3',
  },
  {
    ชื่อ: '④ สตริงที่มี // ข้างใน — ไม่ใช่คอมเมนต์',
    โค้ด: "const u = 'https://gucut.com'\nconst จริง = 4\n",
    ต้องมี: 'const จริง = 4',
  },
  {
    ชื่อ: '⑤ ตัวควบคุมลบ: คอมเมนต์ปกติต้องถูกตัดจริง',
    โค้ด: "// ZZคำในคอมเมนต์ZZ\nconst จริง = 5\n",
    ต้องไม่มี: 'ZZคำในคอมเมนต์ZZ',
    ต้องมี: 'const จริง = 5',
  },
  {
    ชื่อ: '⑥ regex มี \' เดี่ยว — คอมเมนต์ข้างล่างต้องถูกตัด',
    โค้ด: "const re = /['\"]/\n// ZZคำในคอมเมนต์ZZ\nconst จริง = 6\n",
    ต้องไม่มี: 'ZZคำในคอมเมนต์ZZ',
    ต้องมี: 'const จริง = 6',
  },
  {
    ชื่อ: '⑦ regex มี /* ใน character class — โค้ดจริงข้างหลังต้องอยู่ครบ',
    โค้ด: "const re = /[/*]/\nconst จริง = 7\n",
    ต้องมี: 'const จริง = 7',
  },
]

let ตก = 0
for (const c of เคส) {
  const out = ตัดคอมเมนต์(c.โค้ด)
  const ปัญหา = []
  if (c.ต้องมี && !out.includes(c.ต้องมี)) ปัญหา.push(`โค้ดจริงหาย: ${JSON.stringify(c.ต้องมี)}`)
  if (c.ต้องไม่มี && out.includes(c.ต้องไม่มี)) ปัญหา.push(`คอมเมนต์รอด: ${JSON.stringify(c.ต้องไม่มี)}`)
  if (ปัญหา.length) {
    ตก++
    console.error(`🔴 ${c.ชื่อ}\n   ${ปัญหา.join(' · ')}\n   ได้: ${JSON.stringify(out)}`)
  } else console.log(`✅ ${c.ชื่อ}`)
}
console.log(ตก ? `\n🔴 ตก ${ตก} เคส` : '\n✅ ผ่านทุกเคส')
process.exit(ตก ? 1 : 0)
