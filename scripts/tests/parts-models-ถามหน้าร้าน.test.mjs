#!/usr/bin/env node
/* `lib/parts-models.ts` — รายชื่อรุ่นอะไหล่ต้อง **ถามหน้าร้าน** ไม่ใช่เก็บสำเนาไว้เอง
 * (13 ต.ค. 2569 · ตอนเพิ่ม MS180/361/038/360/880)
 *
 * 🔴 ราคาที่จ่ายเมื่อผิด: รุ่นที่เพิ่งเพิ่มจะ "ไม่มีอยู่จริง" สำหรับรอบจับคู่
 *    ⇒ หน้าอะไหล่เปิดได้ ของครบ แต่ทุกแถวขึ้น "สอบถามร้าน" ทั้งที่ของมีขาย
 *    ⇒ ไม่มี error ไม่มีอะไรแดง — ต้องจับด้วยเทสเท่านั้น
 *
 * 🔑 เคสควบคุมสองทิศ: "ถามได้ต้องใช้ของจริง" คู่กับ "ถามไม่ได้ต้องพูดออกมา"
 *    ด่านที่มีแต่ทิศแรกจะเขียวตลอดแม้ของสำรองถูกใช้เงียบ ๆ ทุกครั้ง
 */
import { execFileSync } from 'node:child_process'
import { mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const out = mkdtempSync(join(tmpdir(), `parts-models-${process.pid}-`))
let ตก = 0
const ok = (ชื่อ, เงื่อนไข, เหตุ = '') => {
  console.log(`  ${เงื่อนไข ? '✅' : '❌'} ${ชื่อ}${เงื่อนไข ? '' : ` — ${เหตุ}`}`)
  if (!เงื่อนไข) { ตก++; console.log(`     🔴 ตกที่ ${ชื่อ}`) }
}

try {
  execFileSync('npx', ['tsc', 'lib/parts-models.ts', '--outDir', out,
    '--module', 'es2022', '--target', 'es2022', '--moduleResolution', 'bundler'], { stdio: 'pipe' })
  const { รุ่นจากหน้าร้าน, รุ่นสำรอง } = await import(join(out, 'parts-models.js'))

  const ตอบ = (body, ok_ = true) => async () => ({ ok: ok_, status: ok_ ? 200 : 503, json: async () => body })

  const ดี = await รุ่นจากหน้าร้าน('https://x', ตอบ({ รุ่น: [{ slug: 'f180' }, { slug: 'f361' }, { slug: 'F 660' }] }))
  ok('ถามได้ ⇒ ใช้รายชื่อของหน้าร้าน', ดี.ถามได้ && ดี.รุ่น.join(',') === 'f180,f361,f660', JSON.stringify(ดี))
  ok('ถามได้ ⇒ ที่มาต้องไม่ติดคำเตือน', !ดี.ที่มา.includes('⚠️'), ดี.ที่มา)

  const ล่ม = await รุ่นจากหน้าร้าน('https://x', async () => { throw new Error('getaddrinfo ENOTFOUND') })
  ok('ถามไม่ได้ ⇒ ใช้ของสำรอง', ล่ม.รุ่น.join(',') === รุ่นสำรอง.join(','), JSON.stringify(ล่ม.รุ่น))
  ok('ถามไม่ได้ ⇒ **ต้องพูดออกมา** (ถามได้=false + มีคำเตือน + บอกเหตุ)',
     ล่ม.ถามได้ === false && ล่ม.ที่มา.includes('⚠️') && ล่ม.ที่มา.includes('ENOTFOUND'), ล่ม.ที่มา)

  const ว่าง = await รุ่นจากหน้าร้าน('https://x', ตอบ({ รุ่น: [] }))
  ok('200 ที่ไม่มีรุ่นเลย = ถามไม่ได้ ไม่ใช่ "ไม่มีรุ่น"',
     ว่าง.ถามได้ === false && ว่าง.รุ่น.length === รุ่นสำรอง.length, JSON.stringify(ว่าง))

  const พัง = await รุ่นจากหน้าร้าน('https://x', ตอบ(null, false))
  ok('HTTP ไม่ ok = ถามไม่ได้ และบอกรหัสสถานะ', พัง.ถามได้ === false && พัง.ที่มา.includes('503'), พัง.ที่มา)
  /* ── ตัวกันทับของที่ท่านประธานกรอกเอง ────────────────────────────────────
     🔴 บั๊กจริง 13 ต.ค. 2569: ร้านเก็บคีย์ไม่มีช่องว่าง · คู่มือมีช่องว่าง
        ⇒ `เดิม[รหัส]` ไม่เคยเจอ ⇒ ของที่ท่านกรอกถูกนับว่า "ยังว่าง" ทุกใบ
        ⇒ เขียนกลับแล้ว **ค่าอัตโนมัติทับของท่าน** ทั้งที่โค้ดเขียนว่าไม่ทับแม้แต่คู่เดียว
     🔑 เคสควบคุมสองทิศ: "ของท่านต้องไม่ถูกแตะ" คู่กับ "ช่องที่ว่างจริงต้องถูกเติม"
        ด่านที่มีแต่ทิศแรกจะเขียวแม้ระบบไม่เติมอะไรเลย */
  const { จับคู่ที่ยังว่าง, ล้างรหัส } = await import(join(out, 'parts-models.js'))
  const คลัง = new Map([['11230201209', ['04382']], ['00003530605', ['09111', '09110']]])
  const แถว = [{ รหัส: '1123 020 1209' }, { รหัส: '0000 353 0605' }]

  const ท่านกรอกไว้ = { '11230201209': '99999' }   // คีย์แบบที่ร้านเก็บจริง (ไม่มีช่องว่าง)
  const ผล = จับคู่ที่ยังว่าง(แถว, ท่านกรอกไว้, คลัง)
  ok('คู่ที่ท่านกรอกเองต้องถูกข้าม ไม่ใช่ถูกทับ',
     ผล.ข้าม === 1 && !('11230201209' in ผล.เพิ่ม), JSON.stringify(ผล))
  /* 🔴 เลขเดียวชี้หลาย SKU = **ห้ามเดา ห้ามเขียน** (ท่อวัดได้ 28 คู่ใน 174 = 16%)
     ของเดิมหยิบ sort()[0] เงียบ ๆ ⇒ ลูกค้าได้ปุ่มใส่ตะกร้าที่ใส่ของผิดชิ้น */
  ok('เลขเดียวชี้หลาย SKU ⇒ ไม่เขียน และต้องมีรายชื่อออกมา',
     !('00003530605' in ผล.เพิ่ม) && ผล.กำกวม.length === 1
       && ผล.กำกวม[0].sku.join(',') === '09110,09111',
     JSON.stringify(ผล))
  const เดี่ยว = จับคู่ที่ยังว่าง([{ รหัส: '0000 353 0605' }], {}, new Map([['00003530605', ['09110']]]))
  ok('เลขที่ชี้ SKU เดียวต้องถูกเติม (ตัวควบคุมบวก — ไม่ใช่ข้ามหมดทุกอัน)',
     เดี่ยว.เพิ่ม['00003530605'] === '09110' && เดี่ยว.กำกวม.length === 0, JSON.stringify(เดี่ยว))
  ok('คีย์ที่เขียนกลับต้องเป็นรูปเดียวกับที่ร้านเก็บ (ไม่มีช่องว่าง)',
     Object.keys(ผล.เพิ่ม).every((k) => !/\s/.test(k)), JSON.stringify(Object.keys(ผล.เพิ่ม)))
  ok('ล้างรหัส ต้องตรงกับฝั่งร้านเป๊ะ (ตัดช่องว่าง · ตัวใหญ่ · ยาวไม่เกิน 24)',
     ล้างรหัส(' 1123 020 1209 ') === '11230201209' && ล้างรหัส('ab cd') === 'ABCD', ล้างรหัส(' 1123 020 1209 '))

  /* ── ดัชนีเลข OEM สองแหล่ง ────────────────────────────────────────────────
     🔴 บั๊กจริง 13 ต.ค. 2569: แหล่ง tags ใช้ `if (!map.has(เลข))` ⇒ เก็บ sku ตัวแรกตัวเดียว
        ⇒ เลขที่สินค้าหลายตัวแปะเหมือนกัน **ดูเหมือนชัดเจน** ⇒ ตัวกันเดาชั้นหลังมองไม่เห็น
        (ท่อวัดกำกวมได้ 28 คู่ · เส้นนี้เห็นแค่ 8 ⇒ ส่วนต่างหายที่ชั้นนี้) */
  const { สร้างดัชนีเลขOEM } = await import(join(out, 'parts-models.js'))
  const เลขจาก = (t) => (String(t).match(/\d{4} \d{3} \d{4}/g) ?? []).map((x) => x.replace(/\D/g, ''))
  const สินค้า = [
    { sku: '00587', tags: ['A20- 0000 350 0525'] },
    { sku: '05749', tags: ['0000 350 0525'] },
    { sku: '05795', tags: ['0000 350 0525'] },
    { sku: '04382', tags: ['1123 020 1209'] },
  ]
  const ดัชนี = สร้างดัชนีเลขOEM({}, สินค้า, เลขจาก)
  ok('เลขเดียวที่สินค้าหลายตัวแปะ ต้องเก็บครบทุก sku (ไม่ใช่ตัวแรกตัวเดียว)',
     (ดัชนี.get('00003500525') ?? []).join(',') === '00587,05749,05795',
     JSON.stringify(ดัชนี.get('00003500525')))
  ok('เลขที่มีสินค้าตัวเดียวต้องยังเป็นตัวเดียว (ตัวควบคุมบวก)',
     (ดัชนี.get('11230201209') ?? []).join(',') === '04382', JSON.stringify(ดัชนี.get('11230201209')))

  /* เจตนาเดิมที่ต้องคงไว้: ของที่ท่านกรอกเองชนะเสมอ — tags ห้ามเติมทับหรือเติมเพิ่ม */
  const มีคนกรอก = สร้างดัชนีเลขOEM({ '09999': '0000 350 0525' }, สินค้า, เลขจาก)
  ok('เลขที่ท่านกรอกเองแล้ว ห้ามให้ tags เติมเพิ่ม',
     (มีคนกรอก.get('00003500525') ?? []).join(',') === '09999', JSON.stringify(มีคนกรอก.get('00003500525')))

} finally {
  rmSync(out, { recursive: true, force: true })
}
console.log(ตก ? `❌ ตก ${ตก} ข้อ` : '✅ ผ่านหมด')
process.exit(ตก ? 1 : 0)
