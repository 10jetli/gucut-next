#!/usr/bin/env node
/* เทสของ `scripts/check-public-paths-have-keys.mjs` — **ตัวที่ ② ในคิว 9 ตัว**
 *
 * 🔑 ทำไมตัวนี้ขึ้นก่อน (เกณฑ์ "ถ้าตัวนี้พังเงียบ จะมีงานอะไรที่ไม่ได้ทำ"):
 *    มันคุม **เส้นใน `PUBLIC_PATHS` ซึ่งข้ามด่านล็อกอินทั้งหมด**
 *    ⇒ พังเงียบ = **เส้นที่เปิดโล่งอยู่ ไม่มีใครรู้** ⇒ คนนอกยิงได้โดยไม่ต้องล็อกอิน
 *
 * 🔴 บั๊กจริงสองใบที่เทสนี้เฝ้า (ทั้งคู่เกิด 19 ก.ย. 2569):
 *    ① ใส่ `// ตรวจ ROKID_BRIDGE_KEY แล้ว` เป็น **คอมเมนต์** ไว้หัวไฟล์ที่เปิดโล่ง ⇒ **ด่านเขียวทันที**
 *       ⇒ แว่นที่ได้: **"ข้อความอยู่ในไฟล์" ≠ "ข้อความนั้นทำงาน"**
 *    ② ทำลายตัวจับกุญแจเป็น `/ZZNOPEZZ/` ⇒ **self-test เดิมยังเขียว**
 *       เพราะมันตรวจแค่ชั้น "หาไฟล์ของเส้นเจอไหม" ⇒ **คำรับรองปลอมสองชั้นซ้อน**
 *
 * 🔑 และเหตุที่ต้องอยู่คนละไฟล์กับด่าน (วัดได้วันนี้):
 *    `--self-test` ที่อยู่ในไฟล์เดียวกัน **ถูกย้อนไปพร้อมโค้ด** ⇒ เป็นตัวตรวจความสอดคล้องภายใน
 *    ไม่ใช่ตัวเฝ้าเจตนา ⇒ ⇒ ทั้งสองให้ผลเขียวเหมือนกัน แยกได้จาก **ที่อยู่ของไฟล์** เท่านั้น
 */
import { ไฟล์นี้ตรวจกุญแจไหม, ไฟล์นี้ปฏิเสธเป็นไหม } from '../check-public-paths-have-keys.mjs'
import { ตัดคอมเมนต์ } from '../lib/ตัดคอมเมนต์.mjs'

let ตก = 0
const ต้อง = (ชื่อ, เงื่อนไข, รายละเอียด = '') => {
  if (เงื่อนไข) console.log(`✅ ${ชื่อ}`)
  else { ตก++; console.error(`🔴 ${ชื่อ}${รายละเอียด ? ' — ' + รายละเอียด : ''}`) }
}

console.log('── ตัวจับ "ไฟล์นี้ตรวจกุญแจไหม" ──')
ต้อง('เทียบกุญแจจริง ⇒ ใช่', ไฟล์นี้ตรวจกุญแจไหม('if (k !== process.env.ROKID_BRIDGE_KEY) return new Response(null, { status: 401 })'))
ต้อง('อ่าน env มาเก็บไว้เทียบ ⇒ ใช่', ไฟล์นี้ตรวจกุญแจไหม('const need = process.env.DRIVESYNC_SECRET'))
ต้อง('ไม่มีอะไรเกี่ยวกับกุญแจ ⇒ ไม่ใช่', !ไฟล์นี้ตรวจกุญแจไหม('export async function GET() { return Response.json({ ok: true }) }'))

console.log('\n── บั๊กจริงใบที่ ①: คอมเมนต์ต้องไม่ทำให้ด่านพอใจ ──')
{
  /* ด่านตัวจริงตัดคอมเมนต์ก่อนเรียกตัวจับ ⇒ เทสต้องเดินทางเดียวกัน ไม่ใช่ป้อนดิบ */
  const ไฟล์ที่เปิดโล่ง = '// ตรวจ ROKID_BRIDGE_KEY แล้ว\nexport async function GET() { return Response.json({ ok: true }) }'
  ต้อง('คอมเมนต์อ้างว่าตรวจแล้ว ⇒ หลังตัดคอมเมนต์ต้องไม่ผ่าน',
    !ไฟล์นี้ตรวจกุญแจไหม(ตัดคอมเมนต์(ไฟล์ที่เปิดโล่ง)))
  ต้อง('ถ้าไม่ตัดคอมเมนต์ก่อน มันจะผ่าน (ยืนยันว่าเคสนี้แยกแยะได้จริง)',
    ไฟล์นี้ตรวจกุญแจไหม(ไฟล์ที่เปิดโล่ง))
}

console.log('\n── ตัวจับ "ไฟล์นี้ปฏิเสธเป็นไหม" (มีทางตอบ 401/403 จริงไหม) ──')
ต้อง('คืน 401 ⇒ ใช่', ไฟล์นี้ปฏิเสธเป็นไหม('return new Response("no", { status: 401 })'))
ต้อง('ไม่มีทางปฏิเสธเลย ⇒ ไม่ใช่', !ไฟล์นี้ปฏิเสธเป็นไหม('return Response.json({ ok: true })'))

console.log('\n── บั๊กจริงใบที่ ②: ตัวจับที่ถูกทำลายต้องให้ผลต่าง ──')
{
  /* รูปที่เคยทำแล้ว self-test เดิมยังเขียว: เปลี่ยนตัวจับเป็นรูปที่ไม่มีวันตรง */
  const ตัวจับพัง = (โค้ด) => /ZZNOPEZZ/.test(โค้ด)
  const โค้ดที่ตรวจกุญแจจริง = 'if (k !== process.env.ROKID_BRIDGE_KEY) return'
  ต้อง('ตัวจับพังตอบ "ไม่ตรวจ" กับโค้ดที่ตรวจจริง', !ตัวจับพัง(โค้ดที่ตรวจกุญแจจริง))
  ต้อง('ตัวจับจริงตอบ "ตรวจ"', ไฟล์นี้ตรวจกุญแจไหม(โค้ดที่ตรวจกุญแจจริง))
  ต้อง('สองตัวให้ผลต่างกัน ⇒ เทสชุดนี้แยกแยะได้', ตัวจับพัง(โค้ดที่ตรวจกุญแจจริง) !== ไฟล์นี้ตรวจกุญแจไหม(โค้ดที่ตรวจกุญแจจริง))
}

console.log(`\n${ตก ? `🔴 ตก ${ตก} ข้อ` : '✅ ผ่านทุกข้อ'}`)
process.exit(ตก ? 1 : 0)
