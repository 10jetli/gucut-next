#!/usr/bin/env node
/* เทสตัวอ่านวันที่ไทยแบบไม่มีปี
 * 🔑 เกณฑ์: **แก้อะไรแล้วจำนวนเทสไม่ขยับ ให้ถือว่ายังไม่ได้แก้** (ฝั่งท่อ 20 ก.ย. 2569)
 *    ⇒ ข้อแรกคือ **เคสที่ทำให้ต้องแก้**: วันที่ข้ามปีเคยได้อายุติดลบ
 */
import { อายุจากวันไทย } from '../lib/อายุจากวันไทย.mjs'

let ตก = 0
const ต้อง = (ชื่อ, ได้, คาด) => {
  const ok = ได้ === คาด
  if (!ok) ตก++
  console.log(`${ok ? '✅' : '🔴'} ${ชื่อ} — คาด ${คาด} ได้ ${ได้}`)
}
const วันนี้ = new Date(2026, 8, 20)   // 20 ก.ย. 2569

console.log('── เคสที่ทำให้ต้องแก้: วันที่ข้ามปี ห้ามได้อายุติดลบ ──')
ต้อง('"15 ธ.ค." ⇒ ของปีก่อน ไม่ใช่อนาคต', อายุจากวันไทย('เขียนไว้ 15 ธ.ค.', วันนี้), 279)
ต้อง('"3 พ.ย." ⇒ ของปีก่อน', อายุจากวันไทย('3 พ.ย.', วันนี้), 321)
ต้อง('ไม่มีวันไหนได้ค่าติดลบ', [...Array(12)].every((_, i) => {
  const เดือน = ['ม.ค.', 'ก.พ.', 'มี.ค.', 'เม.ย.', 'พ.ค.', 'มิ.ย.', 'ก.ค.', 'ส.ค.', 'ก.ย.', 'ต.ค.', 'พ.ย.', 'ธ.ค.'][i]
  return (อายุจากวันไทย(`1 ${เดือน}`, วันนี้) ?? 0) >= 0
}), true)

console.log('\n── กรณีปกติ ──')
ต้อง('"16 ก.ย." (ไม่มีปี) ⇒ 4 วัน', อายุจากวันไทย('อ่านแล้ว 16 ก.ย.', วันนี้), 4)
ต้อง('"16 ก.ย. 2569" (มีปี) ⇒ 4 วันเท่ากัน', อายุจากวันไทย('อ่านแล้ว 16 ก.ย. 2569', วันนี้), 4)
ต้อง('วันนี้เอง ⇒ 0', อายุจากวันไทย('20 ก.ย. 2569', วันนี้), 0)

console.log('\n── หลายวันที่ในข้อความเดียว ⇒ เอาวันที่ใหม่ที่สุด ──')
/* 🔑 เพราะคอมเมนต์มักเล่าประวัติ: "เขียน 6 ก.ย. · แก้ 18 ก.ย." ⇒ อายุที่ใช้ตัดสินคือครั้งล่าสุด */
ต้อง('"6 ก.ย. · แก้ 18 ก.ย." ⇒ 2 วัน', อายุจากวันไทย('เขียน 6 ก.ย. · แก้ 18 ก.ย.', วันนี้), 2)

console.log('\n── ไม่มีวันที่ ⇒ null ไม่ใช่ 0 ──')
/* 🔴 ถ้าคืน 0 จะแปลว่า "เขียนวันนี้" ⇒ ของที่ไม่มีวันที่จะกลายเป็นของใหม่ที่สุดทั้งกอง */
ต้อง('ข้อความเปล่า', อายุจากวันไทย('ไม่มีวันที่ในนี้', วันนี้), null)
ต้อง('undefined', อายุจากวันไทย(undefined, วันนี้), null)
ต้อง('เลขที่ไม่ใช่วันที่', อายุจากวันไทย('มี 15 จุด และ 18 ไฟล์', วันนี้), null)

console.log('\n── ปลูกรุ่นที่พังไว้ในเทสเอง ──')
/* รุ่นเก่า = เดาปีปัจจุบันเสมอ ⇒ ต้องให้ผลต่างจากรุ่นที่แก้แล้ว ไม่งั้นแปลว่าเทสนี้ไม่ได้ทดสอบอะไร */
const รุ่นเก่า = (s, n) => {
  const m = /(\d{1,2})\s*(ธ\.ค\.)/.exec(s)
  return m ? Math.round((n - new Date(n.getFullYear(), 11, Number(m[1]))) / 86400000) : null
}
ต้อง('รุ่นเก่าให้ค่าติดลบ (ยืนยันว่าเทสนี้แยกแยะได้จริง)', รุ่นเก่า('15 ธ.ค.', วันนี้) < 0, true)
ต้อง('รุ่นใหม่ไม่ติดลบ', อายุจากวันไทย('15 ธ.ค.', วันนี้) > 0, true)

console.log(`\n${ตก ? `🔴 ตก ${ตก} ข้อ` : '✅ ผ่านทุกข้อ'}`)
process.exit(ตก ? 1 : 0)
