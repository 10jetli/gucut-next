/* ตัวช่วย "ปลูกแล้ววัด" ต้องแยก **สามผลลัพธ์ที่หน้าตาเหมือนกัน** ออกจากกันได้จริง
 * (19 ก.ย. 2569 — ฝั่งจอเหยียบ "ปลูกไม่ลง แล้วอ่านว่าด่านพัง" 4 ครั้งในวันเดียว)
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { ปลูกแล้ววัด } from '../lib/ปลูกแล้ววัด.mjs'
import { execFileSync } from 'node:child_process'

const เป้า = 'netlify/functions/bills-watch.mjs'   // ไฟล์จริง · ไม่มีเทสไหน import
const ด่าน = ['node', 'scripts/check-syntax.mjs']

test('🔑 ปลูกไม่ลง (ข้อความไม่มีในไฟล์) ⇒ บอกว่า "ปลูกไม่ลง" ไม่ใช่ "ด่านจับไม่ได้"', () => {
  const r = ปลูกแล้ววัด({ ไฟล์: เป้า, แก้: (s) => s.replace('ZZไม่มีข้อความนี้ZZ', 'x'), ด่าน })
  assert.equal(r.ผล, 'ปลูกไม่ลง')
})

test('ปลูกลงแต่ไม่ทำให้พังจริง ⇒ "ปลูกไม่ลง" (ตัวยืนยันไม่ล้ม)', () => {
  const r = ปลูกแล้ววัด({
    ไฟล์: เป้า,
    แก้: (s) => s + '\n// ZZเติมคอมเมนต์เฉย ๆZZ\n',
    ยืนยันปลูกลง: ['node', '--check', เป้า],
    ด่าน,
  })
  assert.equal(r.ผล, 'ปลูกไม่ลง')
})

test('ปลูกลงจริง + ด่านจับได้ + เอ่ยถึงไฟล์ ⇒ "ด่านจับได้"', () => {
  const r = ปลูกแล้ววัด({
    ไฟล์: เป้า,
    /* รูปเดียวกับบั๊กจริง: ข้อความหลายบรรทัดต่อท้ายบรรทัด `//` */
    แก้: (s) => {
      const l = s.split('\n')
      const i = l.findIndex((x) => x.trim().startsWith('//'))
      l[i] = l[i] + 'export default async function zz(a) {\n  const x = ('
      return l.join('\n')
    },
    ยืนยันปลูกลง: ['node', '--check', เป้า],
    ด่าน,
    ต้องเอ่ยถึง: 'bills-watch',
  })
  assert.equal(r.ผล, 'ด่านจับได้')
})

/* 🔴 **ข้อที่หกเพิ่ม 26 ก.ย. 2569 — ตัวควบคุมลบของตัวเครื่องมือเอง**
   ของจริงวันนั้น: สูตรของ `check-dep-direction` เขียนข้อความบั๊กเป็นสตริงไว้ในทะเบียน
   ซึ่งอยู่ใต้ `scripts/` = ขอบเขตที่ด่านนั้นกวาด ⇒ **ด่านแดงอยู่ก่อนปลูก**
   ⇒ ปลูกแล้วก็แดง · `ต้องเอ่ยถึง` ก็ตรง (ไฟล์ที่ปลูกโผล่ในผลด้วย) ⇒ ได้ 'ด่านจับได้' ที่ว่างเปล่า
   🔑 เคสนี้จำลองด้วยด่านที่ **แดงเสมอไม่ว่าจะปลูกหรือไม่** ⇒ ต้องไม่ได้ 'ด่านจับได้' */
test('ด่านแดงอยู่ก่อนปลูก ⇒ ตัวควบคุมลบต้องปฏิเสธ ไม่ใช่นับเป็น "ด่านจับได้"', () => {
  const r = ปลูกแล้ววัด({
    ไฟล์: เป้า,
    แก้: (s) => s + '\n// ZZปลูกอะไรก็ได้ZZ\n',
    ด่าน: ['node', '-e', 'process.stdout.write("bills-watch พัง"); process.exit(1)'],
    ต้องมีในไฟล์: '// ZZปลูกอะไรก็ได้ZZ',
    ต้องเอ่ยถึง: 'bills-watch',
  })
  assert.equal(r.ผล, 'ด่านให้ผลเดิมตอนไม่ได้ปลูก (ตัวควบคุมลบไม่ผ่าน)')
  assert.match(r.รายละเอียด, /exit 1|ยังมีคำว่า/)
})

test('🔒 คืนไฟล์ครบทุกกรณี — ไฟล์ต้องสะอาดใน git หลังรันทุกเทสข้างบน', () => {

  /* 🔴 **ข้ามแบบมีเสียงเมื่อไม่มี git** (เพิ่ม 26 ก.ย. 2569 ตอนเอาเทสนี้เข้าสาย prebuild)
     เทสนี้ยืนยันว่า `ปลูกแล้ววัด` คืนไฟล์ครบ ⇒ ต้องถาม git
     ⚠️ แต่สายนี้รันบน Netlify ด้วย ซึ่ง **ยังไม่ยืนยันว่ามี .git ให้ถาม**
        ⇒ ถ้า execFileSync โยน เทสจะตก ⇒ **build ของทุกคนพังเพราะเครื่องมือวัด ไม่ใช่เพราะของพัง**
     ⇒ จึงข้ามแบบ **พิมพ์บอก** (ไม่ใช่เงียบ) — "ยังไม่ได้ตรวจ" ต้องไม่ถูกอ่านว่า "ตรวจแล้วผ่าน"
     (คลาสเดียวกับที่ `check-dev-running` ข้ามเมื่อไม่มีคำสั่ง `ss`) */
  let out
  try {
    out = execFileSync('git', ['status', '--porcelain', '--', เป้า], { encoding: 'utf8' })
  } catch (e) {
    console.log(`⏭️  ข้ามข้อ "คืนไฟล์ครบ": ถาม git ไม่ได้ (${e.code ?? e.message}) ⇒ **ยังไม่ได้ตรวจ**`)
    return
  }
  assert.equal(out.trim(), '', `ไฟล์ค้างสภาพปลูก: ${out}`)
})
