#!/usr/bin/env node
/* เทสของ `scripts/lib/ตัดคอมเมนต์.mjs` — **อยู่คนละไฟล์กับของที่มันตรวจโดยตั้งใจ**
 *
 * 🔴 เหตุผลที่ต้องแยกไฟล์ (เจอวันนี้ 20 ก.ย. 2569 ตอนวัดด้วยวิธีปลูกจากประวัติ git):
 *    ตัวช่วยนี้มี `--self-test` อยู่ **ในไฟล์เดียวกับตัวมันเอง**
 *    ⇒ พอผมย้อนไฟล์กลับเป็นรุ่นก่อนแก้ (`46e325d^`) เพื่อทดสอบ
 *      **self-test ก็ถูกย้อนกลับไปเป็นของรุ่นเก่าด้วย** ⇒ มันผ่านฉลุย
 *    ⇒ ⇒ 🔑 **เทสที่อยู่ในไฟล์เดียวกับของที่มันตรวจ จะถูกย้อนไปพร้อมกัน**
 *         ⇒ มันตอบได้แค่ *"รุ่นนี้ตรงกับความคาดหวังของรุ่นนี้ไหม"*
 *           **ไม่ได้ตอบว่า "รุ่นนี้ยังทำสิ่งที่เราต้องการอยู่ไหม"**
 *
 * 🔴 และเหตุผลที่สอง (ฝั่งท่อชี้ 20 ก.ย. 2569):
 *    ฝั่งท่อมีตรรกะเดียวกันคนละสำเนา ⇒ เขาเขียนเทสฝั่งเขาแล้ว **แต่ไม่ครอบสำเนาของเรา**
 *    ⇒ เกณฑ์: *"ถ้าฝั่งหนึ่งแก้ อีกฝั่งได้รับผลเองไหม"* ⇒ ไม่ ⇒ **เป็นสำเนา นับเป็นสองงาน**
 *    ⇒ ⇒ ถ้าเราขีดฆ่าทั้งรายการเพราะฝั่งเขาปิดแล้ว **ช่องฝั่งเราจะเปิดอยู่โดยคิดว่าปิดแล้ว**
 *
 * 📏 บั๊กจริงที่เทสนี้เฝ้า (commit `4804688`): ตัวถอดไม่รู้จักสตริง ⇒ ทับ-ดาว ที่อยู่ในเครื่องหมายคำพูด
 *    ถูกอ่านเป็น "คอมเมนต์เปิด" ⇒ **กินโค้ดจริงไปจนเจอตัวปิดถัดไป**
 *    ของจริงตอนนั้น: `gen-arch.mjs` เหลือ 45% ของไฟล์ · โค้ดถูกล้าง 4 ช่วง ~40 บรรทัด
 */
import { ตัดคอมเมนต์ } from '../lib/ตัดคอมเมนต์.mjs'

let ตก = 0
const ต้อง = (ชื่อ, เงื่อนไข, รายละเอียด = '') => {
  if (เงื่อนไข) console.log(`✅ ${ชื่อ}`)
  else { ตก++; console.error(`🔴 ${ชื่อ}${รายละเอียด ? ' — ' + รายละเอียด : ''}`) }
}

/* สร้างอักขระด้วยโค้ด ไม่พิมพ์ตรง ๆ — ถ้าพิมพ์ ทับ-ดาว ลงในคอมเมนต์ของไฟล์นี้เอง
   มันจะปิดคอมเมนต์ก่อนเวลา (ผมเหยียบมาแล้ววันนี้ตอนเขียนคำอธิบายบั๊กนี้) */
const เปิดคอมเมนต์ = '/' + '*'
const ปิดคอมเมนต์ = '*' + '/'

console.log('── เคสที่ทำให้เทสนี้เกิด: ทับ-ดาว อยู่ในสตริง ──')
{
  const โค้ด = [
    `const แบบ = 'app${เปิดคอมเมนต์}route.ts'`,
    'const สำคัญ = 42',
    `${เปิดคอมเมนต์} คอมเมนต์จริง ${ปิดคอมเมนต์}`,
    'export { สำคัญ }',
  ].join('\n')
  const ผล = ตัดคอมเมนต์(โค้ด)
  ต้อง('โค้ดจริงหลังสตริงต้องไม่ถูกกิน', ผล.includes('สำคัญ = 42'), `ได้: ${JSON.stringify(ผล).slice(0, 120)}`)
  ต้อง('บรรทัด export ต้องยังอยู่', ผล.includes('export { สำคัญ }'))
  ต้อง('คอมเมนต์จริงต้องถูกตัดออก', !ผล.includes('คอมเมนต์จริง'))
}

console.log('\n── ต้องยังตัดคอมเมนต์จริงได้ (ไม่ใช่แค่ไม่กินโค้ด) ──')
{
  const โค้ด = ['const a = 1', '// คอมเมนต์ท้ายบรรทัด', `${เปิดคอมเมนต์} หลายบรรทัด`, 'ยังอยู่ในคอมเมนต์', `${ปิดคอมเมนต์}`, 'const b = 2'].join('\n')
  const ผล = ตัดคอมเมนต์(โค้ด)
  ต้อง('คอมเมนต์ท้ายบรรทัดถูกตัด', !ผล.includes('คอมเมนต์ท้ายบรรทัด'))
  ต้อง('คอมเมนต์บล็อกถูกตัด', !ผล.includes('ยังอยู่ในคอมเมนต์'))
  ต้อง('โค้ดทั้งสองบรรทัดยังอยู่', ผล.includes('const a = 1') && ผล.includes('const b = 2'))
  ต้อง('จำนวนบรรทัดต้องเท่าเดิม (ด่านอื่นใช้เลขบรรทัดอ้างอิง)',
    ผล.split('\n').length === โค้ด.split('\n').length,
    `เดิม ${โค้ด.split('\n').length} ได้ ${ผล.split('\n').length}`)
}

console.log('\n── URL ในสตริงต้องไม่ถูกตัด (สแลชคู่ไม่ใช่คอมเมนต์เสมอไป) ──')
{
  const ผล = ตัดคอมเมนต์(`const u = 'https://x.com/a'`)
  ต้อง('https ในสตริงรอด', ผล.includes('https://x.com/a'), `ได้: ${ผล}`)
}

console.log('\n── ตัวควบคุม: รุ่นที่ไม่รู้จักสตริง (รูปก่อนแก้) ต้องให้ผลต่าง ──')
{
  /* รุ่นเก่าแบบย่อ: ตัดบล็อกด้วย regex โดยไม่สนสตริง — รูปเดียวกับที่ commit 46e325d แก้ไป */
  const รุ่นเก่า = (s) => s.replace(new RegExp(`\\${เปิดคอมเมนต์}[\\s\\S]*?\\${ปิดคอมเมนต์}`, 'g'), '')
  const โค้ด = [`const แบบ = 'app${เปิดคอมเมนต์}route.ts'`, 'const สำคัญ = 42', `${เปิดคอมเมนต์} จริง ${ปิดคอมเมนต์}`].join('\n')
  ต้อง('รุ่นเก่ากินโค้ดจริง (ยืนยันว่าเคสนี้แยกแยะได้)', !รุ่นเก่า(โค้ด).includes('สำคัญ = 42'))
  ต้อง('รุ่นวันนี้ไม่กิน', ตัดคอมเมนต์(โค้ด).includes('สำคัญ = 42'))
}

console.log(`\n${ตก ? `🔴 ตก ${ตก} ข้อ` : '✅ ผ่านทุกข้อ'}`)
process.exit(ตก ? 1 : 0)
