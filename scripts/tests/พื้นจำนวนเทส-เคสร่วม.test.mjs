/* เทสที่รัน **ไฟล์เคสร่วมสองฝั่ง** กับด่านพื้นจำนวนเทสของฝั่งนี้
 *
 * 🔑 **แชร์ "เคส" ไม่ใช่ "โค้ด"** (เหตุของฝั่งท่อ · คำในไฟล์เคสเอง):
 *    ก๊อปโค้ดข้ามรีโป = ฝาแฝดที่ถูกแก้คนละวัน
 *    regex/ตรรกะร่วมตัวเดียว = **วันที่มันผิด ผิดพร้อมกันสองฝั่ง**
 *    ⇒ ⇒ เคสร่วมให้ผลตรงข้าม: รูปต่างกันได้ แต่ **ฝั่งใดเพี้ยน เคสจับฝั่งนั้นฝั่งเดียว**
 *
 * ⚠️ ไฟล์เคสอยู่ **นอกรีโป** ⇒ รายงาน mtime ทุกรอบ · อ่านไม่ได้ ⇒ **ตัดสินไม่ได้ ไม่ใช่ผ่าน**
 *
 * 🔴 และข้อที่ฝั่งท่อเจอตอนเขียนเทสของเขา (ผมจึงไม่ต้องเจอเอง):
 *    ถ้าด่านไม่มีทาง **ฉีดไฟล์พื้น** เข้ามา เคสร่วมจะเขียนทับไฟล์พื้นจริง
 *    ⇒ **เทสทำลายของที่มันตรวจ** · ฝั่งผมฉีดด้วย env `TEST_FLOOR_FILE`
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { mkdtempSync, writeFileSync, rmSync, readFileSync, existsSync, statSync } from 'node:fs'
import { tmpdir, homedir } from 'node:os'
import { join } from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const ด่าน = fileURLToPath(new URL('../check-test-floor.mjs', import.meta.url))
/* 🔴 **ห้ามฝังพาธของเครื่องใดเครื่องหนึ่ง** — ของเดิมเขียน `/home/jetli/...` ตายตัว
   ⇒ เทสนี้ **ตกเสมอบนเครื่องอื่น** (เครื่อง Mac ของทีม) ⇒ ด่านก่อน push แดงค้าง
   ⇒ คนที่ทำงานเครื่องนั้น push งานของตัวเองไม่ได้เลย ทั้งที่งานไม่เกี่ยวกับเทสนี้
   (เจอจริง 17 ต.ค. 2569 · คลาสเดียวกับกฎ "ห้ามฝัง IP วงแลน")
   ⇒ ใช้บ้านของผู้ใช้เป็นฐาน · ยังเคารพ TEST_FLOOR_CASES เหมือนเดิมถ้าตั้งไว้ */
const ไฟล์เคส = process.env.TEST_FLOOR_CASES
  || join(homedir(), 'claude-shared', 'lib', 'เคส-พื้นจำนวนเทส.json')

/** ยิงด่านด้วย (จำนวนเทส, พื้น, เหตุที่ลด) แล้วแปลผลเป็นสามสถานะตามสัญญา */
function ยิง({ จำนวนเทส, พื้น, เหตุที่ลด }) {
  const d = mkdtempSync(join(tmpdir(), 'พื้นเทส-'))
  const log = join(d, 't.log')
  /* `จำนวนเทส: null` = log ไม่มีบรรทัดนั้น (runner เปลี่ยนรูปผลลัพธ์) */
  writeFileSync(log, จำนวนเทส === null
    ? 'ok 1 - อะไรบางอย่าง\n'
    : `# tests ${จำนวนเทส}\n# pass ${จำนวนเทส}\n# fail 0\n`)
  const ไฟล์พื้น = join(d, 'พื้น.json')
  writeFileSync(ไฟล์พื้น, JSON.stringify({ 'พื้น': พื้น, ...(เหตุที่ลด ? { 'เหตุที่ลด': เหตุที่ลด } : {}) }))
  const r = spawnSync('node', [ด่าน, log], {
    encoding: 'utf8', env: { ...process.env, TEST_FLOOR_FILE: ไฟล์พื้น },
  })
  const out = (r.stdout || '') + (r.stderr || '')
  const สถานะ = /คุมไม่ได้รอบนี้/.test(out) ? 'คุมไม่ได้' : r.status === 0 ? 'ผ่าน' : 'ตก'
  const พื้นหลัง = (() => { try { return JSON.parse(readFileSync(ไฟล์พื้น, 'utf8'))['พื้น'] } catch { return null } })()
  rmSync(d, { recursive: true, force: true })
  return { สถานะ, out, พื้นหลัง }
}

test('ด่านพื้นจำนวนเทสผ่าน **ทุกเคสในไฟล์ร่วม**', () => {
  if (!existsSync(ไฟล์เคส)) {
    assert.fail(`🔴 ไม่มีไฟล์เคสร่วม (${ไฟล์เคส}) ⇒ **ตัดสินไม่ได้ ไม่ใช่ผ่าน**`
      + ' — พฤติกรรมของด่านนี้ไม่ได้ถูกตรึงรอบนี้')
  }
  const st = statSync(ไฟล์เคส)
  console.log(`   📂 ไฟล์เคสร่วม (นอกรีโป): แก้ล่าสุด ${new Date(st.mtimeMs).toLocaleString('th-TH')}`
    + ` · ${st.size} ไบต์`)
  const เคส = JSON.parse(readFileSync(ไฟล์เคส, 'utf8'))['เคส']
  const ตก = []
  for (const c of เคส) {
    const r = ยิง({ จำนวนเทส: c['จำนวนเทส'], พื้น: c['พื้น'], เหตุที่ลด: c['เหตุที่ลด'] })
    if (r.สถานะ !== c['คาดหวัง']) {
      ตก.push(`${c['ชื่อ']} — ต้อง "${c['คาดหวัง']}" ได้ "${r.สถานะ}"`
        + `${c['_เหตุ'] ? ` · เหตุของเคส: ${c['_เหตุ']}` : ''}`)
    }
  }
  console.log(`   ผ่านเคสร่วม **${เคส.length - ตก.length}/${เคส.length}**`)
  assert.deepEqual(ตก, [],
    '🔴 **รูปของฝั่งนี้ไม่ตรงพฤติกรรมที่ตกลงกัน** ⇒ แก้ด่านให้ผ่านเคส'
    + ' **ห้ามแก้ไฟล์เคสให้ตรงด่าน** (แก้เคส = ย้ายเกณฑ์ไปหาของที่ผิด ⇒ เขียวตลอดกาล)')
})

test('🔑 เคส "เพิ่มขึ้น" ต้อง **ยกพื้นลงไฟล์จริง** ไม่ใช่แค่พิมพ์ว่าผ่าน', () => {
  const r = ยิง({ จำนวนเทส: 1600, พื้น: 1589, เหตุที่ลด: null })
  assert.equal(r.สถานะ, 'ผ่าน')
  assert.equal(r.พื้นหลัง, 1600,
    'ถ้าไม่ยกพื้น พื้นจะค้างต่ำกว่าของจริง = **ที่ซ่อน** ⇒ เทสหายได้ฟรีเท่ากับส่วนต่าง')
  assert.match(r.out, /ยกพื้น 1589 ⇒ 1600/, 'การยกพื้นต้องถูกพิมพ์ ไม่ใช่เกิดเงียบ ๆ')
})

test('🔴 ห้ามยกพื้น**ลง**อัตโนมัติ — ตัวตรวจที่เขียนไฟล์ที่มันตรวจ ต้องเขียนทิศเดียว', () => {
  const r = ยิง({ จำนวนเทส: 1200, พื้น: 1589, เหตุที่ลด: null })
  assert.equal(r.สถานะ, 'ตก')
  assert.equal(r.พื้นหลัง, 1589,
    '🔴 ถ้าด่านลดพื้นให้เองตอนเทสหด มันจะ **กลืนคำตัดสินของตัวเอง** ⇒ เขียวตลอดกาล')
})
