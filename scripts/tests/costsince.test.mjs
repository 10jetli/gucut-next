#!/usr/bin/env node
/* สภาพต้นทุนจากเส้น `?costsince=1` — ทดสอบ **ตัวตัดสินของจริง** (คอมไพล์ lib/costsince.ts ด้วย tsc)
 * (ใบ t_muu0gaih · ท่านประธานสั่ง 4 ต.ค. 2569 23:46 · สัญญาจากฝั่งท่อ 23:53)
 *
 * 🔒 สามข้อห้ามของสัญญา เทสนี้บังคับทั้งสาม **และมีคู่ตรงข้ามทุกข้อ**
 *    ① `ครอบกี่เปอร์เซ็นต์ในช่วง: null` = ไม่มีบรรทัดขายเลย ⇒ ห้ามอ่านเป็น 0 **และห้ามอ่านเป็น 100**
 *       `ถึงเกณฑ์ยอดรวมไหม: null` = แปลไม่ได้ ⇒ **ห้ามอ่านว่าไม่ผ่าน**
 *    ② `วันแรก: null` = ยังไม่เริ่มตรึง ⇒ ห้ามแปลว่าวันนี้
 *    ③ **จอห้ามเทียบเกณฑ์เอง** ⇒ เทสข้อ ⑥ ป้อนคู่ที่ "ครอบสูงกว่าเกณฑ์แต่ท่อบอกไม่ถึง"
 *       ถ้าจอแอบเทียบเอง ข้อนั้นจะพลิกทันที
 *
 * 🔑 **ทดสอบที่ขอบเกณฑ์ ไม่ใช่แค่ค่ากลาง** — ป้อน 100% กับ 10% อย่างเดียวจะเขียวต่อให้
 *    โค้ดเทียบอะไรก็ได้ ⇒ ไม่พิสูจน์ว่าใช้ธงของท่อจริง
 */
import { execFileSync } from 'node:child_process'
import { mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const out = mkdtempSync(join(tmpdir(), `costsince-${process.pid}-`))
let ตก = 0
const ok = (ชื่อ, เงื่อนไข, เหตุ = '') => {
  console.log(`  ${เงื่อนไข ? '✅' : '❌'} ${ชื่อ}${เงื่อนไข ? '' : ` — ${เหตุ}`}`)
  if (!เงื่อนไข) ตก++
}

try {
  execFileSync('npx', ['tsc', 'lib/costsince.ts', '--outDir', out,
    '--module', 'es2022', '--target', 'es2022', '--moduleResolution', 'bundler', '--skipLibCheck'],
    { stdio: 'pipe' })
  const { อ่านสภาพต้นทุน } = await import(join(out, 'costsince.js'))

  const เต็ม = (o = {}) => ({
    ok: true, วันแรก: '2026-10-04', เกณฑ์ครอบยอดรวม: 95, 'โชว์กำไรรายบรรทัดได้': true,
    ในช่วง: { จาก: '2026-10-01', ถึง: '2026-10-05', บรรทัดขายในช่วง: 100,
      บรรทัดที่มีต้นทุนในช่วง: 98, ครอบกี่เปอร์เซ็นต์ในช่วง: 98, 'ถึงเกณฑ์ยอดรวมไหม': true, ...(o.ในช่วง ?? {}) },
    ...Object.fromEntries(Object.entries(o).filter(([k]) => k !== 'ในช่วง')),
  })

  console.log('① ท่อรุ่นเก่า (ไม่มีช่อง `ในช่วง`) ⇒ ต้องบอกว่าท่อรุ่นเก่า ห้ามอ่านว่าไม่ถึงเกณฑ์')
  {
    const เก่า = อ่านสภาพต้นทุน({ ok: true, วันแรก: '2026-10-04', 'ครอบกี่เปอร์เซ็นต์': 0.3 })
    ok('ชนิด = ท่อรุ่นเก่า', เก่า.ชนิด === 'ท่อรุ่นเก่า', เก่า.ชนิด)
    ok('ไม่เปิดยอดรวม', เก่า.เปิดยอดรวมได้ === false)
    ok('ครอบ = null ไม่ใช่ 0 (ไม่หยิบเลขทั้งกระจกมาใช้แทน)', เก่า.ครอบ === null, String(เก่า.ครอบ))
    ok('null ทั้งก้อนก็ต้องเป็นท่อรุ่นเก่า', อ่านสภาพต้นทุน(null).ชนิด === 'ท่อรุ่นเก่า')
    // 🔴 ส่งมาครึ่งเดียว (มี ในช่วง แต่ไม่มีเกณฑ์) ⇒ ยังต้องเป็นท่อรุ่นเก่า ไม่ใช่เดาเกณฑ์เอง
    const ครึ่ง = อ่านสภาพต้นทุน({ วันแรก: '2026-10-04', ในช่วง: { ครอบกี่เปอร์เซ็นต์ในช่วง: 99, 'ถึงเกณฑ์ยอดรวมไหม': true } })
    ok('มี ในช่วง แต่ไม่มีเกณฑ์ ⇒ ท่อรุ่นเก่า', ครึ่ง.ชนิด === 'ท่อรุ่นเก่า', ครึ่ง.ชนิด)
    // ตัวควบคุมตรงข้าม: ครบทั้งสองช่อง ⇒ ต้องไม่ใช่ท่อรุ่นเก่า
    ok('ตัวควบคุมตรงข้าม: ครบสองช่อง ⇒ ไม่ใช่ท่อรุ่นเก่า', อ่านสภาพต้นทุน(เต็ม()).ชนิด !== 'ท่อรุ่นเก่า')
  }

  console.log('② `วันแรก: null` = ยังไม่เริ่มตรึง ⇒ ห้ามแปลว่าวันนี้ และห้ามเปิดยอดรวม')
  {
    const r = อ่านสภาพต้นทุน(เต็ม({ วันแรก: null }))
    ok('ชนิด = ยังไม่เริ่มตรึง', r.ชนิด === 'ยังไม่เริ่มตรึง', r.ชนิด)
    ok('ไม่เปิดยอดรวม ทั้งที่ ถึงเกณฑ์ยอดรวมไหม = true', r.เปิดยอดรวมได้ === false)
    ok('เหตุไม่มีคำว่าวันนี้', !r.เหตุ.includes('วันนี้'), r.เหตุ)
  }

  console.log('③ `ครอบกี่เปอร์เซ็นต์ในช่วง: null` = ไม่มีบรรทัดขาย ⇒ ห้ามเป็น 0 และห้ามเป็น 100')
  {
    const r = อ่านสภาพต้นทุน(เต็ม({ ในช่วง: { ครอบกี่เปอร์เซ็นต์ในช่วง: null, บรรทัดขายในช่วง: 0, 'ถึงเกณฑ์ยอดรวมไหม': null } }))
    ok('ชนิด = ช่วงนี้ไม่มีบรรทัดขาย', r.ชนิด === 'ช่วงนี้ไม่มีบรรทัดขาย', r.ชนิด)
    ok('ครอบ = null', r.ครอบ === null, String(r.ครอบ))
    ok('เหตุไม่พูดว่า 0%', !r.เหตุ.includes('ครอบ 0%') || r.เหตุ.includes('คนละเรื่อง'), r.เหตุ)
    ok('เหตุบอกว่าคนละเรื่องกับครอบครบ', r.เหตุ.includes('ครอบครบ'), r.เหตุ)
    // ตัวควบคุมตรงข้าม: ครอบ 0 (มีบรรทัดขายแต่ไม่มีต้นทุนเลย) ⇒ ต้องเป็น "ยังไม่ถึงเกณฑ์" ไม่ใช่ "ไม่มีบรรทัดขาย"
    const ศูนย์ = อ่านสภาพต้นทุน(เต็ม({ ในช่วง: { ครอบกี่เปอร์เซ็นต์ในช่วง: 0, บรรทัดขายในช่วง: 40, 'ถึงเกณฑ์ยอดรวมไหม': false } }))
    ok('ตัวควบคุมตรงข้าม: ครอบ 0 ≠ ไม่มีบรรทัดขาย', ศูนย์.ชนิด === 'ยังไม่ถึงเกณฑ์', ศูนย์.ชนิด)
    ok('ครอบ 0 ต้องยังเป็นเลข 0 ไม่ใช่ null', ศูนย์.ครอบ === 0, String(ศูนย์.ครอบ))
  }

  console.log('④ `ถึงเกณฑ์ยอดรวมไหม: null` = แปลไม่ได้ ⇒ ห้ามอ่านว่าไม่ผ่าน')
  {
    const r = อ่านสภาพต้นทุน(เต็ม({ ในช่วง: { ครอบกี่เปอร์เซ็นต์ในช่วง: 60, 'ถึงเกณฑ์ยอดรวมไหม': null } }))
    ok('ชนิด = แปลไม่ได้', r.ชนิด === 'แปลไม่ได้', r.ชนิด)
    ok('ไม่เปิดยอดรวม', r.เปิดยอดรวมได้ === false)
    ok('เหตุแยก แปลไม่ได้ ออกจาก ไม่ผ่าน', r.เหตุ.includes('ไม่ใช่ "ไม่ผ่าน"'), r.เหตุ)
    ok('ยังรายงานเลขครอบที่ท่อให้มา', r.ครอบ === 60, String(r.ครอบ))
  }

  console.log('⑤ ขอบเกณฑ์ — ตัดสินจากธงของท่อ ไม่ใช่จากเลข')
  {
    const ถึงพอดี = อ่านสภาพต้นทุน(เต็ม({ ในช่วง: { ครอบกี่เปอร์เซ็นต์ในช่วง: 95, 'ถึงเกณฑ์ยอดรวมไหม': true } }))
    ok('ครอบ 95 + ท่อบอกถึง ⇒ เปิด', ถึงพอดี.เปิดยอดรวมได้ === true, ถึงพอดี.ชนิด)
    const ต่ำกว่าหนึ่งขั้น = อ่านสภาพต้นทุน(เต็ม({ ในช่วง: { ครอบกี่เปอร์เซ็นต์ในช่วง: 94.9, 'ถึงเกณฑ์ยอดรวมไหม': false } }))
    ok('ครอบ 94.9 + ท่อบอกไม่ถึง ⇒ ไม่เปิด', ต่ำกว่าหนึ่งขั้น.เปิดยอดรวมได้ === false, ต่ำกว่าหนึ่งขั้น.ชนิด)
  }

  console.log('⑥ 🔴 จอห้ามเทียบเกณฑ์เอง — ป้อนคู่ที่เลขขัดกับธง')
  {
    // ครอบ 99 (สูงกว่าเกณฑ์ 95) แต่ท่อบอก **ไม่ถึง** ⇒ จอต้องเชื่อธง ไม่ใช่เชื่อเลข
    const ขัด1 = อ่านสภาพต้นทุน(เต็ม({ ในช่วง: { ครอบกี่เปอร์เซ็นต์ในช่วง: 99, 'ถึงเกณฑ์ยอดรวมไหม': false } }))
    ok('ครอบ 99 แต่ท่อบอกไม่ถึง ⇒ ไม่เปิด', ขัด1.เปิดยอดรวมได้ === false, ขัด1.ชนิด)
    // ครอบ 10 (ต่ำกว่าเกณฑ์) แต่ท่อบอก **ถึง** ⇒ ก็ต้องเชื่อธง
    const ขัด2 = อ่านสภาพต้นทุน(เต็ม({ ในช่วง: { ครอบกี่เปอร์เซ็นต์ในช่วง: 10, 'ถึงเกณฑ์ยอดรวมไหม': true } }))
    ok('ครอบ 10 แต่ท่อบอกถึง ⇒ เปิด', ขัด2.เปิดยอดรวมได้ === true, ขัด2.ชนิด)
    ok('เกณฑ์ที่โชว์มาจากคำตอบ ไม่ใช่ค่าคงที่ในจอ',
      อ่านสภาพต้นทุน(เต็ม({ เกณฑ์ครอบยอดรวม: 80 })).เกณฑ์ === 80)
  }

  console.log('⑦ สองธงตอบคนละคำถาม ⇒ ห้ามยุบรวม')
  {
    // ยอดรวมยังไม่ถึงเกณฑ์ แต่กำไรรายบรรทัดโชว์ได้ ⇒ ต้องแยกกัน
    const r = อ่านสภาพต้นทุน(เต็ม({ 'โชว์กำไรรายบรรทัดได้': true, ในช่วง: { ครอบกี่เปอร์เซ็นต์ในช่วง: 20, 'ถึงเกณฑ์ยอดรวมไหม': false } }))
    ok('ยอดรวมปิด', r.เปิดยอดรวมได้ === false)
    ok('รายบรรทัดยังเปิด', r.โชว์รายบรรทัดได้ === true)
    // ท่อไม่บอกธงรายบรรทัด ⇒ null ห้ามเป็น false
    const ไม่บอก = อ่านสภาพต้นทุน(เต็ม({ 'โชว์กำไรรายบรรทัดได้': undefined }))
    ok('ท่อไม่บอก ⇒ null ไม่ใช่ false', ไม่บอก.โชว์รายบรรทัดได้ === null, String(ไม่บอก.โชว์รายบรรทัดได้))
    // ตัวควบคุมตรงข้าม: ท่อบอก false ⇒ ต้องเป็น false จริง ไม่ใช่ null
    const บอกปิด = อ่านสภาพต้นทุน(เต็ม({ 'โชว์กำไรรายบรรทัดได้': false }))
    ok('ท่อบอก false ⇒ false ไม่ใช่ null', บอกปิด.โชว์รายบรรทัดได้ === false, String(บอกปิด.โชว์รายบรรทัดได้))
  }

  console.log(`\nสรุป: ตก ${ตก}`)
  if (ตก) process.exit(1)
} finally {
  rmSync(out, { recursive: true, force: true })
}
