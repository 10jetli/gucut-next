#!/usr/bin/env node
/* ตรรกะหน้าจับคู่รหัสอะไหล่ (`lib/parts-map.ts`)
 * ท่านประธานสั่ง 11 ต.ค. 2569 "รหัสผมจะลงจับคู่เองด้วยมือ ขอให้คุณทำช่องให้ผมใส่ง่ายๆ"
 *
 * 🔴 **ทำไมเทสนี้สำคัญกว่าหน้าตาของจอ**
 *    ท่านจะนั่งกรอกเป็นร้อยตัว (F440 = 368 ชิ้น · F070 = 377) ด้วยมือ
 *    ถ้าตัวล้างรหัสของจอไม่ตรงกับเซิร์ฟเวอร์ **จอจะขึ้นว่า "ยังไม่จับคู่" ทั้งที่บันทึกสำเร็จ**
 *    ⇒ ท่านจะกรอกซ้ำทั้งหน้า และไม่มีอะไรฟ้องว่าผิดที่ไหน
 *
 * 📏 **เทสนี้ตรึงสเปกของเซิร์ฟเวอร์ ไม่ใช่ตรึงพฤติกรรมของตัวเอง**
 *    ลอกจาก `gucut-web/netlify/functions/parts-map.mjs` (origin/main) บรรทัด 40-42:
 *      ล้างรหัส = String(v||"").replace(/\s+/g,"").toUpperCase().slice(0,24)
 *      ล้างsku  = String(v||"").trim().replace(/[^\w.-]/g,"").slice(0,32)
 *    ⚠️ วันที่เซิร์ฟเวอร์เปลี่ยนสเปก เทสนี้จะยังเขียว **เพราะมันเทียบกับสำเนาที่เขียนไว้ที่นี่**
 *       ⇒ เขียนกำกับไว้ให้คนรอบหน้ารู้ว่าต้องไปดูของจริงด้วย (ข้ามรีโป import ไม่ได้)
 *
 * 📦 ฟิกซ์เจอร์ใช้ **รหัสจริงจาก f440.json** ไม่ใช่รหัสแต่ง
 */
import { rmSync } from 'node:fs'
import { คอมไพล์เพื่อทดสอบ } from '../lib/คอมไพล์เพื่อทดสอบ.mjs'

let ตก = 0
const ok = (ชื่อ, เงื่อนไข, เหตุ = '') => {
  console.log(`  ${เงื่อนไข ? '✅' : '❌'} ${ชื่อ}${เงื่อนไข ? '' : ` — ${เหตุ}`}`)
  if (!เงื่อนไข) { ตก++; console.log(`     🔴 ตกที่ ${ชื่อ}`) }
}

const ไฟล์ = 'lib/parts-map.ts'
let งาน
try {
  const ผล = คอมไพล์เพื่อทดสอบ({ ไฟล์: [ไฟล์], ปลอม: {} })
  งาน = ผล
  const m = await import(ผล.พาธของ(ไฟล์))
  const { ล้างรหัส, ล้างsku, แบนรายการ, สถานะของแถว, ความคืบหน้า, ช่องถัดไป } = m

  console.log('\n── ล้างรหัส ต้องเท่ากับสเปกเซิร์ฟเวอร์ ──')
  /* 🔑 เคสเหล่านี้คือ **ตัวควบคุมสองทิศ**: ควรเปลี่ยน / ต้องไม่เปลี่ยน */
  const เคสรหัส = [
    ['รหัสจริงมีช่องว่าง', '1128 020 2122', '11280202122'],
    ['รหัสจริงอีกตัว', '0000 988 5211', '00009885211'],
    ['ตัวเล็กต้องเป็นตัวใหญ่', '1128 020 2122a', '11280202122A'],
    ['แท็บและช่องว่างซ้อน', '1128\t020  2122', '11280202122'],
    ['ไม่มีช่องว่างอยู่แล้ว ⇒ ต้องไม่เปลี่ยน', '11280202122', '11280202122'],
    ['ค่าว่าง ⇒ ว่าง', '', ''],
    ['null ⇒ ว่าง (ไม่ใช่ "null")', null, ''],
  ]
  for (const [ชื่อ, ป้อน, ควร] of เคสรหัส) ok(ชื่อ, ล้างรหัส(ป้อน) === ควร, `ได้ ${JSON.stringify(ล้างรหัส(ป้อน))}`)
  ok('ยาวเกิน 24 ⇒ ตัดที่ 24', ล้างรหัส('A'.repeat(40)).length === 24)

  console.log('\n── ล้าง sku ต้องเท่ากับสเปกเซิร์ฟเวอร์ ──')
  const เคสsku = [
    ['รหัสร้านปกติ ⇒ ไม่เปลี่ยน', '04382', '04382'],
    ['มีขีดกับจุด ⇒ เก็บไว้', 'Bar-NW.16', 'Bar-NW.16'],
    ['ช่องว่างหัวท้าย ⇒ ตัด', '  04382  ', '04382'],
    ['🔴 ช่องว่างกลาง ⇒ หาย (เซิร์ฟเวอร์ทำแบบนี้)', 'Bar NW 16', 'BarNW16'],
    ['อักขระพิเศษ ⇒ ตัดทิ้ง', '04382!@#', '04382'],
  ]
  for (const [ชื่อ, ป้อน, ควร] of เคสsku) ok(ชื่อ, ล้างsku(ป้อน) === ควร, `ได้ ${JSON.stringify(ล้างsku(ป้อน))}`)

  console.log('\n── แบนรายการ: ไม่ตัดแถวซ้ำ แต่คีย์ซ้ำนับครั้งเดียว ──')
  const ข้อมูล = {
    ชื่อรุ่น: 'F 440',
    กลุ่ม: [
      { id: 'a', ตัวอักษร: 'A', ชื่อ: 'Crankcase', อะไหล่: [
        { เลข: '1', รหัส: '1128 020 2122', จำนวน: '1', ชื่อ: 'Crankcase' },
        { เลข: '3', รหัส: '9371 470 2610', จำนวน: '2', ชื่อ: 'Cylindrical pin 5x18' } ] },
      { id: 'b', ตัวอักษร: 'B', ชื่อ: 'Cylinder', อะไหล่: [
        { เลข: '5', รหัส: '9371 470 2610', จำนวน: '2', ชื่อ: 'Cylindrical pin 5x18' } ] },
      { id: 'c', ตัวอักษร: 'C', ชื่อ: 'ไม่มีอะไหล่' },
    ],
  }
  const รายการ = แบนรายการ(ข้อมูล)
  ok('ได้ 3 แถว (ไม่ตัดแถวซ้ำทิ้ง)', รายการ.length === 3, รายการ.length)
  ok('กลุ่มที่ไม่มีอะไหล่ ⇒ ไม่พัง', true)
  ok('คีย์ถูกล้างแล้ว', รายการ[0].คีย์ === '11280202122', รายการ[0].คีย์)
  ok('ลำดับไล่ต่อเนื่อง', รายการ.map((r) => r.ลำดับ).join() === '0,1,2')
  ok('แถวพาชื่อกลุ่มมาด้วย', รายการ[2].กลุ่มชื่อ === 'Cylinder')
  ok('ข้อมูล null ⇒ ได้อาร์เรย์ว่าง ไม่ใช่พัง', แบนรายการ(null).length === 0)

  const คืบ = ความคืบหน้า(รายการ, {})
  ok('ความคืบหน้านับคีย์ไม่ซ้ำ (2) ไม่ใช่จำนวนแถว (3)',
    คืบ.ทั้งหมด === 2 && คืบ.แถว === 3, JSON.stringify(คืบ))
  /* คีย์ตัวนี้คือ '9371 470 2610' หลังล้างแล้ว — เขียนตรงตัวเพื่อให้เห็นว่าเทียบกับอะไร */
  const คืบ2 = ความคืบหน้า(รายการ, { '93714702610': '04382' })
  ok('จับคู่คีย์ที่ซ้ำสองกลุ่ม ⇒ นับ 1 ครั้ง', คืบ2.จับคู่แล้ว === 1, JSON.stringify(คืบ2))
  ok('sku ที่เป็นช่องว่าง ⇒ ไม่นับว่าจับคู่',
    ความคืบหน้า(รายการ, { '11280202122': '   ' }).จับคู่แล้ว === 0)

  console.log('\n── สี่สถานะ ห้ามยุบ ──')
  ok('ไม่มีในแมป ⇒ ยังไม่จับคู่', สถานะของแถว('X', {}, {}, {}) === 'ยังไม่จับคู่')
  ok('มีในแมป ⇒ จับคู่แล้ว', สถานะของแถว('X', { X: '04382' }, {}, {}) === 'จับคู่แล้ว')
  ok('กำลังส่ง ⇒ กำลังบันทึก', สถานะของแถว('X', {}, { X: true }, {}) === 'กำลังบันทึก')
  ok('ล้มเหลว ⇒ บันทึกไม่สำเร็จ (ไม่ใช่ ยังไม่จับคู่)',
    สถานะของแถว('X', {}, {}, { X: 'เน็ตหลุด' }) === 'บันทึกไม่สำเร็จ')
  ok('🔑 ล้มเหลวต้องชนะ "จับคู่แล้ว" — ค่าเก่ายังอยู่แต่ของใหม่ยังไม่ลง',
    สถานะของแถว('X', { X: '04382' }, {}, { X: 'พัง' }) === 'บันทึกไม่สำเร็จ')
  ok('sku ว่างในแมป ⇒ ยังไม่จับคู่ (ไม่ใช่จับคู่แล้ว)',
    สถานะของแถว('X', { X: '' }, {}, {}) === 'ยังไม่จับคู่')

  console.log('\n── Enter ไปช่องถัดไปที่ยังว่าง ──')
  const ร3 = แบนรายการ({ กลุ่ม: [{ id: 'a', ตัวอักษร: 'A', ชื่อ: 'ก', อะไหล่: [
    { เลข: '1', รหัส: 'AAA', จำนวน: '1', ชื่อ: 'ก' },
    { เลข: '2', รหัส: 'BBB', จำนวน: '1', ชื่อ: 'ข' },
    { เลข: '3', รหัส: 'CCC', จำนวน: '1', ชื่อ: 'ค' } ] }] })
  ok('ว่างทั้งหมด ⇒ จาก 0 ไป 1', ช่องถัดไป(ร3, 0, {}) === 1)
  ok('ข้ามแถวที่จับคู่แล้ว', ช่องถัดไป(ร3, 0, { BBB: '04382' }) === 2)
  ok('ถึงท้ายแล้ววนกลับหาช่องว่างข้างหน้า', ช่องถัดไป(ร3, 2, { CCC: '1' }) === 0)
  ok('ครบทุกช่อง ⇒ คืน null (จอต้องบอกว่าครบ ไม่ใช่เด้งเงียบ)',
    ช่องถัดไป(ร3, 0, { AAA: '1', BBB: '2', CCC: '3' }) === null)
} catch (e) {
  ตก++
  console.log('  ❌ เทสล้มทั้งไฟล์:', e?.message || e)
} finally {
  if (งาน?.ที่ออก) rmSync(งาน.ที่ออก, { recursive: true, force: true })
}

console.log(ตก === 0 ? '\n✅ ผ่านหมด' : `\n❌ ตก ${ตก} ข้อ`)
process.exit(ตก === 0 ? 0 : 1)
