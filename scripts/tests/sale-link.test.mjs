#!/usr/bin/env node
/* ลิงก์ไปหาใบขาย (`lib/sale-link.ts`) — 41 บรรทัดที่ตัดสินว่าคนกดแล้ว **เจอใบ** หรือเห็นคำว่า "ไม่พบ"
 * (ใบ t_mu8i1pu1 · 29 ก.ย. 2569) ตัววัดใหม่ยืนยันว่าอยู่ในกองที่ไม่พบว่าถูกแตะ
 *
 * 🔴 **ที่มา (17 ก.ย. 2569 · ใบ t_mu2u9mym)** — จอรายการขายค้นได้แค่ในช่วงวันของจอ (ค่าเริ่มต้น 90 วัน)
 *    ลิงก์ที่ส่งแค่ `q=<เลขที่ใบ>` จะขึ้น **"ไม่พบ" กับใบที่เก่ากว่านั้น ทั้งที่ใบมีอยู่จริง**
 *    📏 วัดจริง: สุ่มใบที่มีสลิป 12 ใบ ⇒ ช่วง 90 วันเจอ **1 ใบ** · เปิดช่วงกว้างเจอ **12 ใบ**
 *    🔑 "ไม่พบ" คือคำตอบที่คนเชื่อแล้วเลิกหา ⇒ ผิดทางนี้ทำให้คนสรุปว่าเอกสารไม่มีอยู่
 *
 * 🔑 กฎที่ตรึงไว้:
 *    ① รู้วันที่ใบ ⇒ ส่งช่วง **วันก่อน–วันหลัง** (กันขอบวันเพี้ยนระหว่างเวลาไทยกับ UTC)
 *    ② ไม่รู้วันที่ ⇒ ส่งช่วงกว้างตั้งแต่ปีแรกที่มีข้อมูล (ช้ากว่า **แต่ไม่หลอกว่าไม่มี**)
 *    ③ วันที่รูปแบบใช้ไม่ได้ ⇒ ต้องถอยไปช่วงกว้าง **ห้ามส่งค่าเสียเข้าไปในลิงก์**
 *    ④ ค่าที่ไปอยู่ใน URL ต้องถูก encode (เลขที่ใบมี `/` ได้จริง)
 */
import { execFileSync } from 'node:child_process'
import { mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const out = mkdtempSync(join(tmpdir(), `sale-link-${process.pid}-`))
let ตก = 0
const ok = (ชื่อ, เงื่อนไข, เหตุ = '') => {
  console.log(`  ${เงื่อนไข ? '✅' : '❌'} ${ชื่อ}${เงื่อนไข ? '' : ` — ${เหตุ}`}`)
  if (!เงื่อนไข) ตก++
}

try {
  execFileSync('npx', ['tsc', 'lib/sale-link.ts', '--outDir', out,
    '--module', 'es2022', '--target', 'es2022', '--moduleResolution', 'bundler', '--skipLibCheck'],
    { stdio: 'pipe' })
  const { ลิงก์ใบขาย, ลิงก์ใบของลูกค้า } = await import(join(out, 'sale-link.js'))
  const พารา = (url) => new URLSearchParams(url.split('?')[1] ?? '')

  console.log('① 🔴 รู้วันที่ใบ ⇒ ช่วงต้องคลุมวันก่อนและวันหลัง (กันขอบวันไทย/UTC)')
  {
    const p = พารา(ลิงก์ใบขาย('SO-2026-0001', '2026-09-15'))
    ok('from = วันก่อนหนึ่งวัน', p.get('from') === '2026-09-14', String(p.get('from')))
    ok('to = วันหลังหนึ่งวัน', p.get('to') === '2026-09-16', String(p.get('to')))
    ok('ส่งเลขที่ใบไปด้วย', p.get('q') === 'SO-2026-0001', String(p.get('q')))
    /* 🔑 ถ้าส่งวันเดียวกันทั้ง from และ to ใบที่ลงเวลาใกล้เที่ยงคืนจะหลุดช่วง
       เพราะเวลาของท่อเป็น UTC แต่คนอ่านเป็นเวลาไทย (+7) */
    ok('from ต้องไม่เท่ากับ to (ไม่ใช่ช่วงวันเดียว)', p.get('from') !== p.get('to'),
      'ช่วงวันเดียว ⇒ ใบที่ลงเวลาใกล้เที่ยงคืนหลุดช่วงเพราะท่อเป็น UTC')
  }

  console.log('② 🔴 ข้ามเดือน/ข้ามปี — การเลื่อนวันต้องถูก ไม่ใช่ลบเลขวันตรง ๆ')
  {
    const ต้นเดือน = พารา(ลิงก์ใบขาย('A', '2026-03-01'))
    ok('1 มี.ค. ⇒ from = 28 ก.พ.', ต้นเดือน.get('from') === '2026-02-28', String(ต้นเดือน.get('from')))
    const ปีใหม่ = พารา(ลิงก์ใบขาย('A', '2026-01-01'))
    ok('1 ม.ค. ⇒ from = 31 ธ.ค. ปีก่อน', ปีใหม่.get('from') === '2025-12-31', String(ปีใหม่.get('from')))
    const สิ้นปี = พารา(ลิงก์ใบขาย('A', '2026-12-31'))
    ok('31 ธ.ค. ⇒ to = 1 ม.ค. ปีหน้า', สิ้นปี.get('to') === '2027-01-01', String(สิ้นปี.get('to')))
    /* ปีอธิกสุรทิน — 2024 มี 29 ก.พ. */
    const อธิก = พารา(ลิงก์ใบขาย('A', '2024-03-01'))
    ok('ปีอธิกสุรทิน: 1 มี.ค. 2024 ⇒ from = 29 ก.พ.', อธิก.get('from') === '2024-02-29', String(อธิก.get('from')))
  }

  console.log('③ 🔴 ไม่รู้วันที่ ⇒ ช่วงกว้าง **ห้ามปล่อยให้จอใช้ค่าเริ่มต้น 90 วัน**')
  {
    for (const ว่าง of [undefined, null, '', 'ไม่ใช่วันที่', '15/09/2026', '2026-9-5', 20260915]) {
      const p = พารา(ลิงก์ใบขาย('SO-เก่า', ว่าง))
      ok(`วันที่ใช้ไม่ได้ (${JSON.stringify(ว่าง)}) ⇒ from = ปีแรกที่มีข้อมูล`,
        p.get('from') === '2020-01-01',
        `${p.get('from')} ⇒ ถ้าไม่ส่ง from จอจะใช้ 90 วัน แล้วขึ้น "ไม่พบ" กับใบเก่า`)
      ok(`  และไม่ส่ง to (ไม่จำกัดปลายช่วง)`, !p.has('to'), String(p.get('to')))
    }
  }

  console.log('④ วันที่ที่มีเวลาต่อท้าย ⇒ ตัดเอาแค่วัน ไม่ใช่ทิ้งทั้งค่า')
  {
    const p = พารา(ลิงก์ใบขาย('A', '2026-09-15T13:45:00Z'))
    ok('ยังคิดช่วงจากวันนั้น', p.get('from') === '2026-09-14' && p.get('to') === '2026-09-16',
      `${p.get('from')} .. ${p.get('to')} ⇒ ทิ้งทั้งค่า = เสียความแม่นของช่วงไปฟรี ๆ`)
  }

  console.log('⑤ ค่าที่ไปอยู่ใน URL ต้อง encode — เลขที่ใบมี / และ & ได้จริง')
  {
    const url = ลิงก์ใบขาย('INV/2026/09&x=1', '2026-09-15')
    ok('อ่านค่ากลับมาได้ตรงตัว', พารา(url).get('q') === 'INV/2026/09&x=1', String(พารา(url).get('q')))
    ok('ไม่มี & ดิบสร้างพารามิเตอร์ใหม่', [...พารา(url).keys()].length === 3,
      `${url} ⇒ ได้ ${[...พารา(url).keys()].join(',')}`)
    ok('ขึ้นต้นด้วยเส้นทางจอรายการขาย', url.startsWith('/core/sales?'), url)
  }

  console.log('⑥ ลิงก์ใบของลูกค้า — ชื่อลูกค้ากับช่วงวัน')
  {
    const ไม่รู้วัน = พารา(ลิงก์ใบของลูกค้า('บริษัท ก&ข จำกัด'))
    ok('ส่งชื่อลูกค้าและอ่านกลับได้ตรงตัว', ไม่รู้วัน.get('customer') === 'บริษัท ก&ข จำกัด',
      String(ไม่รู้วัน.get('customer')))
    ok('ไม่รู้วัน ⇒ from = ปีแรกที่มีข้อมูล', ไม่รู้วัน.get('from') === '2020-01-01', String(ไม่รู้วัน.get('from')))
    ok('ไม่รู้วันล่าสุด ⇒ ไม่ส่ง to', !ไม่รู้วัน.has('to'))
    const รู้วัน = พารา(ลิงก์ใบของลูกค้า('ก', '2026-05-10', '2026-09-20'))
    ok('รู้วันแรก ⇒ ถอยหนึ่งวัน', รู้วัน.get('from') === '2026-05-09', String(รู้วัน.get('from')))
    ok('รู้วันล่าสุด ⇒ เดินหน้าหนึ่งวัน', รู้วัน.get('to') === '2026-09-21', String(รู้วัน.get('to')))
    const วันแรกเสีย = พารา(ลิงก์ใบของลูกค้า('ก', 'มั่ว', '2026-09-20'))
    ok('วันแรกใช้ไม่ได้ ⇒ ถอยไปช่วงกว้าง แต่ยังใช้วันล่าสุดที่ถูก',
      วันแรกเสีย.get('from') === '2020-01-01' && วันแรกเสีย.get('to') === '2026-09-21',
      `${วันแรกเสีย.get('from')} .. ${วันแรกเสีย.get('to')}`)
  }
} finally {
  rmSync(out, { recursive: true, force: true })
}

console.log(ตก ? `\n❌ ไม่ผ่าน ${ตก} ข้อ` : '\n✅ ผ่านทุกข้อ')
console.log('⚠️ ขอบเขต: ตรวจ **ลิงก์ที่ประกอบออกมา** ไม่ได้ตรวจว่าจอปลายทางตีความช่วงวันตามนั้นจริง'
  + ' (อย่างหลังต้องยิงของจริง — เคยยิงแล้ว 17 ก.ย. 2569: 12 ใบเจอครบเมื่อเปิดช่วงกว้าง)')
process.exit(ตก ? 1 : 0)
