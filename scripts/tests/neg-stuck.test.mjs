#!/usr/bin/env node
/* `lib/neg-stuck.ts` — กติกาที่ **สองจอใช้ร่วมกัน** (StuckPushList · NegVsPush)
 * (ใบ t_mu8i1pu1 · 28 ก.ย. 2569) วัดแล้วว่าไฟล์นี้ไม่มีเทสและไม่มีด่านเอ่ยถึงเลย
 *
 * 🔴 ไฟล์นี้เกิดมาแก้ปัญหา "เลขสองแหล่งที่ไม่มีใครบอกว่าต่างกัน":
 *    จอคลังบอกติดลบ 22 รหัส · กองดันไม่ขึ้นบอก 29 รหัส · ซ้อนกันแค่ 5
 *    ⇒ คนที่ถูกสั่งให้ "ไปแก้ของติดลบ" แก้ครบตามจอคลังแล้ว ยังเหลือตัวขวางการดันอีก 24 โดยไม่มีอะไรบอก
 *
 * 🔒 กฎที่ไฟล์ประกาศเอง และเทสนี้บังคับ:
 *    ① ห้ามเดากติกาการตั้งรหัส — ตัดที่ขีดกลางแล้วเชื่อเลยไม่ได้
 *       ยอมรับรหัสฐานได้ **ต่อเมื่อฐานนั้นอยู่ในรายการติดลบจริงจากท่อ**
 *    ② แถวที่จับคู่ไม่ได้ **ต้องพูดออกมา** ไม่ใช่ปัดทิ้งเงียบ ๆ
 *    ③ ต้องบอกได้ว่ารหัสไหน "ไม่โผล่ในจอคลัง" — นั่นคือตัวเลขที่ทำให้สองจอต่างกัน
 *    ④ ติดลบที่ท่อไม่ได้ส่งตัวเลขมา (null) **ยังนับว่าอยู่ในรายการ** — ไม่รู้จำนวน ≠ ไม่ติดลบ
 */
import { execFileSync } from 'node:child_process'
import { mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const out = mkdtempSync(join(tmpdir(), `neg-stuck-${process.pid}-`))
let ตก = 0
const ok = (ชื่อ, เงื่อนไข, เหตุ = '') => {
  console.log(`  ${เงื่อนไข ? '✅' : '❌'} ${ชื่อ}${เงื่อนไข ? '' : ` — ${เหตุ}`}`)
  if (!เงื่อนไข) ตก++
}

try {
  execFileSync('npx', ['tsc', 'lib/neg-stuck.ts', '--outDir', out,
    '--module', 'es2022', '--target', 'es2022', '--moduleResolution', 'bundler', '--skipLibCheck'],
    { stdio: 'pipe' })
  const { ต้นเหตุของรหัส, จับคู่ต้นเหตุ } = await import(join(out, 'neg-stuck.js'))

  console.log('① จับคู่ตรงตัวได้ก่อนเสมอ')
  {
    const neg = new Map([['00747', -3]])
    ok('รหัสที่อยู่ในรายการติดลบ คือต้นเหตุของตัวเอง', ต้นเหตุของรหัส('00747', neg) === '00747')
  }

  console.log('② รหัสแปร (มีขีดกลาง) — ยอมรับฐานได้ต่อเมื่อฐานอยู่ในรายการติดลบจริง')
  {
    const มีฐาน = new Map([['00747', -3]])
    ok('ฐานอยู่ในรายการ ⇒ ชี้ไปที่ฐาน', ต้นเหตุของรหัส('00747-L', มีฐาน) === '00747')
    const ไม่มีฐาน = new Map([['99999', -1]])
    ok('🔒 ฐานไม่อยู่ในรายการ ⇒ ต้องคืน null **ห้ามเดาจากขีดกลาง**',
      ต้นเหตุของรหัส('00747-L', ไม่มีฐาน) === null,
      'เดาเอง = สร้างกติกาการตั้งรหัสของร้านขึ้นมาเอง')
    ok('ไม่มีรหัสเลย ⇒ null', ต้นเหตุของรหัส(undefined, มีฐาน) === null)
    ok('รหัสว่าง ⇒ null', ต้นเหตุของรหัส('', มีฐาน) === null)
  }

  console.log('③ ท่อไม่ได้ส่งจำนวนมา (null) ⇒ ยังนับว่าติดลบอยู่ในรายการ (ไม่รู้จำนวน ≠ ไม่ติดลบ)')
  {
    const neg = new Map([['00747', null]])
    ok('รหัสตรงตัวยังจับคู่ได้', ต้นเหตุของรหัส('00747', neg) === '00747')
    ok('รหัสแปรยังชี้ไปที่ฐานได้', ต้นเหตุของรหัส('00747-XL', neg) === '00747')
  }

  console.log('④ สรุปรวม — ต้องบอกทั้งต้นเหตุ · แถวที่จับคู่ไม่ได้ · รหัสที่จอคลังจะไม่แสดง')
  {
    const neg = new Map([['00747', -3], ['00900', null]])
    const rows = [
      { sku: '00747' }, { sku: '00747-L' }, { sku: '00747-XL' },
      { sku: '00900' },
      { sku: 'ZZ001' },
      { sku: undefined },
    ]
    const ผล = จับคู่ต้นเหตุ(rows, neg)
    ok('เรียงต้นเหตุจากมากไปน้อย', JSON.stringify(ผล.ต้นเหตุ) === JSON.stringify([['00747', 3], ['00900', 1]]),
      JSON.stringify(ผล.ต้นเหตุ))
    ok('นับแถวที่จับคู่ไม่ได้ (ห้ามปัดทิ้งเงียบ ๆ)', ผล.หาไม่เจอ === 2, `หาไม่เจอ=${ผล.หาไม่เจอ}`)
    ok('รหัสแปรที่จอคลังไม่แสดง ต้องถูกชี้ออกมา',
      ผล.ไม่โผล่ในจอคลัง.includes('00747-L') && ผล.ไม่โผล่ในจอคลัง.includes('00747-XL'),
      JSON.stringify(ผล.ไม่โผล่ในจอคลัง))
    ok('รหัสที่จับคู่ไม่ได้ก็ไม่โผล่ในจอคลังเหมือนกัน', ผล.ไม่โผล่ในจอคลัง.includes('ZZ001'),
      JSON.stringify(ผล.ไม่โผล่ในจอคลัง))
    ok('รหัสที่ตรงตัวกับจอคลัง ไม่ถูกนับว่าไม่โผล่', !ผล.ไม่โผล่ในจอคลัง.includes('00747'),
      JSON.stringify(ผล.ไม่โผล่ในจอคลัง))
    ok('แถวที่ไม่มีรหัสเลย ไม่ไปโผล่ในรายชื่อ (ไม่มีชื่อให้ชี้)',
      !ผล.ไม่โผล่ในจอคลัง.some((x) => !x), JSON.stringify(ผล.ไม่โผล่ในจอคลัง))
  }

  console.log('⑤ ไม่มีแถวติดลบเลย ⇒ ทุกอย่างต้องเป็นศูนย์/ว่าง ไม่ใช่พัง')
  {
    const ผล = จับคู่ต้นเหตุ([], new Map())
    ok('ต้นเหตุว่าง', ผล.ต้นเหตุ.length === 0)
    ok('หาไม่เจอ = 0', ผล.หาไม่เจอ === 0)
    ok('รายชื่อว่าง', ผล.ไม่โผล่ในจอคลัง.length === 0)
    const ผล2 = จับคู่ต้นเหตุ([{ sku: 'AAA' }, { sku: 'BBB' }], new Map())
    ok('มีแถวแต่ไม่มีรายการติดลบ ⇒ จับคู่ไม่ได้ทั้งหมด และต้องพูดออกมา',
      ผล2.หาไม่เจอ === 2 && ผล2.ต้นเหตุ.length === 0, JSON.stringify(ผล2))
  }
} finally {
  rmSync(out, { recursive: true, force: true })
}

console.log(ตก ? `\n❌ ไม่ผ่าน ${ตก} ข้อ` : '\n✅ ผ่านทุกข้อ')
process.exit(ตก ? 1 : 0)
