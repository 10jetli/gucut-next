#!/usr/bin/env node
/* กติกาตัดสินสถานะหัวสมอง (`lib/brain-status.ts`) — ท่านประธานสั่งหน้า /core/brain 9 ต.ค. 2569
 *
 * 🔴 **ทำไมเทสนี้ไม่ใช่เรื่องความสวยของจอ**
 *    ท่านย้ำเองว่า "ห้ามวาดผังสวย ๆ แล้วทำเหมือนทุกอย่างทำงานอยู่"
 *    สถานะที่อ่านผิด **สั่งให้คนไปทำผิดเรื่อง**:
 *      · "ปกติ" ทั้งที่เครื่องดับ  ⇒ ไม่มีใครไปปลุก ความจำค้างอยู่อย่างนั้นเป็นวัน
 *      · "ยังไม่ติดตั้ง" ทั้งที่ติดตั้งแล้วแค่เน็ตสะดุด ⇒ มีคนไปตั้งใหม่ทับของเดิม
 *    ⇒ สามสถานะนี้จึงห้ามยุบรวม และห้ามเดาเมื่อไม่รู้
 *
 * ⚠️ เทสเรียก **ฟังก์ชันตัวจริง** ไม่ลอกเงื่อนไขมาเขียนซ้ำ
 *    (ลอกมาเขียนซ้ำ = วัดสำเนาของตัวเอง ปลูกบั๊กในของจริงแล้วยังเขียว)
 */
import { rmSync } from 'node:fs'
import { คอมไพล์เพื่อทดสอบ } from '../lib/คอมไพล์เพื่อทดสอบ.mjs'

let ตก = 0
const ok = (ชื่อ, เงื่อนไข, เหตุ = '') => {
  console.log(`  ${เงื่อนไข ? '✅' : '❌'} ${ชื่อ}${เงื่อนไข ? '' : ` — ${เหตุ}`}`)
  if (!เงื่อนไข) ตก++
}

const ไฟล์ = 'lib/brain-status.ts'
let งาน
try {
  งาน = คอมไพล์เพื่อทดสอบ({ ไฟล์: [ไฟล์], ปลอม: {} })
  const { ตัดสินสถานะ, นาทีที่ถือว่าขาดการติดต่อ } = await import(งาน.พาธของ(ไฟล์))

  const ตอนนี้ = 1_791_500_000
  const นาที = (n) => ตอนนี้ - n * 60

  /* ── ① ยังไม่มีไฟล์ประกาศเลย = ยังไม่ได้ติดตั้ง ── */
  for (const ของ of [null, undefined, {}, { ติดตั้งแล้ว: false }]) {
    const r = ตัดสินสถานะ(ของ, ตอนนี้)
    ok(`ไม่มีประกาศ (${JSON.stringify(ของ)}) ⇒ ยังไม่ได้ติดตั้ง`,
      r.สถานะ === 'ยังไม่ได้ติดตั้ง', `ได้ ${r.สถานะ}`)
  }

  /* ── ② ประกาศสดใหม่ = ปกติ ── */
  const สด = ตัดสินสถานะ({ ติดตั้งแล้ว: true, ประกาศเมื่อยูนิกซ์: นาที(3) }, ตอนนี้)
  ok('ประกาศเมื่อ 3 นาทีก่อน ⇒ ปกติ', สด.สถานะ === 'ปกติ', `ได้ ${สด.สถานะ}`)
  ok('บอกอายุเป็นนาทีได้', สด.อายุนาที === 3, `ได้ ${สด.อายุนาที}`)

  /* ── ③ ประกาศเก่าเกินเกณฑ์ = ติดต่อไม่ได้ (ไม่ใช่ "ยังไม่ติดตั้ง") ── */
  const เก่า = ตัดสินสถานะ({ ติดตั้งแล้ว: true, ประกาศเมื่อยูนิกซ์: นาที(นาทีที่ถือว่าขาดการติดต่อ + 5) }, ตอนนี้)
  ok('ประกาศเก่าเกินเกณฑ์ ⇒ ติดต่อไม่ได้', เก่า.สถานะ === 'ติดต่อไม่ได้', `ได้ ${เก่า.สถานะ}`)
  ok('เก่าแล้วต้องไม่กลายเป็น "ยังไม่ได้ติดตั้ง"', เก่า.สถานะ !== 'ยังไม่ได้ติดตั้ง',
    'ติดตั้งแล้วแต่เงียบ กับ ไม่เคยติดตั้ง เป็นคนละเรื่อง')

  /* ── ④ ค่าปลายสองข้างของเกณฑ์ — ชื่อช่องบอกทิศไม่ได้ ต้องยิงทั้งสองข้าง ── */
  const พอดี = ตัดสินสถานะ({ ติดตั้งแล้ว: true, ประกาศเมื่อยูนิกซ์: นาที(นาทีที่ถือว่าขาดการติดต่อ) }, ตอนนี้)
  ok(`อายุ ${นาทีที่ถือว่าขาดการติดต่อ} นาทีพอดี ⇒ ยังปกติ`, พอดี.สถานะ === 'ปกติ', `ได้ ${พอดี.สถานะ}`)
  const เกินหนึ่ง = ตัดสินสถานะ({ ติดตั้งแล้ว: true, ประกาศเมื่อยูนิกซ์: นาที(นาทีที่ถือว่าขาดการติดต่อ + 1) }, ตอนนี้)
  ok(`อายุ ${นาทีที่ถือว่าขาดการติดต่อ + 1} นาที ⇒ ติดต่อไม่ได้`,
    เกินหนึ่ง.สถานะ === 'ติดต่อไม่ได้', `ได้ ${เกินหนึ่ง.สถานะ}`)

  /* ── ⑤ มีไฟล์แต่ไม่มีเวลากำกับ = ไม่รู้ว่าเก่าแค่ไหน ⇒ ห้ามอ่านว่าปกติ ── */
  for (const ร้าย of [{ ติดตั้งแล้ว: true },
                      { ติดตั้งแล้ว: true, ประกาศเมื่อยูนิกซ์: null },
                      { ติดตั้งแล้ว: true, ประกาศเมื่อยูนิกซ์: 'เมื่อกี้' },
                      { ติดตั้งแล้ว: true, ประกาศเมื่อยูนิกซ์: NaN }]) {
    const r = ตัดสินสถานะ(ร้าย, ตอนนี้)
    ok(`ประกาศไม่มีเวลาที่อ่านได้ (${JSON.stringify(ร้าย.ประกาศเมื่อยูนิกซ์)}) ⇒ ต้องไม่ใช่ "ปกติ"`,
      r.สถานะ === 'ติดต่อไม่ได้', `ได้ ${r.สถานะ} — ไม่รู้ ไม่ใช่ ปกติ`)
  }

  /* ── ⑥ นาฬิกาเครื่องอ่านเพี้ยนไปข้างหน้า (ประกาศ "อนาคต") ต้องไม่กลายเป็นติดต่อไม่ได้ ── */
  const อนาคต = ตัดสินสถานะ({ ติดตั้งแล้ว: true, ประกาศเมื่อยูนิกซ์: ตอนนี้ + 120 }, ตอนนี้)
  ok('ประกาศเวลาล้ำหน้าเล็กน้อย ⇒ ยังปกติ', อนาคต.สถานะ === 'ปกติ', `ได้ ${อนาคต.สถานะ}`)

  /* ── ⑦ **ทุกกิ่ง** ต้องมีเหตุเป็นข้อความให้คนอ่าน — สถานะเปล่า ๆ บอกไม่ได้ว่าต้องทำอะไรต่อ
     🔑 รอบแรกข้อนี้ครอบแค่ 4 กิ่ง **ไม่ครอบกิ่ง "ยังไม่ได้ติดตั้ง"**
        ⇒ ปลูกบั๊กลบเหตุผลของกิ่งนั้นแล้วเทสยังเขียว (จับได้ตอนปลูก 9 ต.ค. 2569)
        ⇒ กิ่งที่เทสเดินไม่ถึง คือกิ่งที่คำกล่าวอ้างเน่าได้โดยไม่มีใครรู้ */
  const ทุกกิ่ง = {
    'ยังไม่ได้ติดตั้ง': ตัดสินสถานะ(null, ตอนนี้),
    'ปกติ': สด,
    'เก่าเกินเกณฑ์': เก่า,
    'ล้ำหน้า': อนาคต,
    'พอดีเกณฑ์': พอดี,
    'ไม่มีเวลากำกับ': ตัดสินสถานะ({ ติดตั้งแล้ว: true }, ตอนนี้),
  }
  for (const [ชื่อ, r] of Object.entries(ทุกกิ่ง)) {
    ok(`กิ่ง "${ชื่อ}" มีเหตุผลเป็นข้อความ`,
      typeof r.เหตุ === 'string' && r.เหตุ.trim().length > 10,
      `เหตุ = ${JSON.stringify(r.เหตุ)} — สถานะเปล่า ๆ บอกไม่ได้ว่าต้องทำอะไรต่อ`)
  }
} catch (e) {
  console.log('  ❌ เทสล้มก่อนเริ่มวัด —', e?.message || e)
  ตก++
} finally {
  if (งาน?.ที่ออก) rmSync(งาน.ที่ออก, { recursive: true, force: true })
}

console.log(ตก ? `\n🔴 ตก ${ตก} ข้อ` : '\n✅ ผ่านทุกข้อ')
process.exit(ตก ? 1 : 0)
