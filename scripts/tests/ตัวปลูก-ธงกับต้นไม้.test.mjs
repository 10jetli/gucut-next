/* เทสสองพฤติกรรมของ `scripts/ด่านแยกแยะได้ไหม.mjs` ที่ฝั่งท่อขอ 14 ต.ค. 2569
 *
 * 🔴 **ของจริงที่ทำให้เทสนี้เกิด** — ผมพิมพ์ `--เฉพาะ <พาธ>` (เว้นวรรค) แทน `--เฉพาะ=<พาธ>`
 *    ⇒ ตัวกรองหายไปเงียบ ๆ ⇒ ตัวปลูกรัน **161 สูตร** ปลูกบั๊กลงไฟล์จริง
 *    ⇒ ฆ่ากลางทาง ⇒ `lib/route-allow.ts` ค้างในรูปหลวม = ช่องโหว่พาธในต้นไม้
 *
 * 🔑 สองข้อนี้ **ต้องมีตัวควบคุมลบ** ไม่ใช่แค่ "เขียนโค้ดแล้ว":
 *    ① ธงที่ parse ไม่ได้ ⇒ **ไม่รัน** (exit 1) ไม่ใช่ **ไม่กรอง**
 *    ② สภาพต้นไม้ต้องถูกพิมพ์ **ทุกทางออก** และแยก "ค้างมาก่อน" จาก "ตัวปลูกทิ้งไว้"
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const ตัวปลูก = fileURLToPath(new URL('../ด่านแยกแยะได้ไหม.mjs', import.meta.url))
const ราก = fileURLToPath(new URL('../..', import.meta.url))

function รัน(args) {
  try {
    const out = execFileSync('node', [ตัวปลูก, ...args], { cwd: ราก, encoding: 'utf8' })
    return { rc: 0, out }
  } catch (e) { return { rc: e.status, out: (e.stdout || '') + (e.stderr || '') } }
}

test('🔴 ธงเว้นวรรค (`--เฉพาะ xxx`) ⇒ ไม่รัน ไม่ใช่ไม่กรอง', () => {
  const r = รัน(['--เฉพาะ', 'xxx'])
  assert.equal(r.rc, 1,
    '🔴 **นี่คือตัวควบคุมลบที่ฝั่งท่อขอโดยตรง** — ของจริงเคยเข้าทางเดินเริ่มต้น'
    + ' แล้วปลูกบั๊กลงไฟล์จริงทั้งทะเบียน ⇒ ธงที่ parse ไม่ได้ต้องตีกลับ')
  assert.match(r.out, /อาร์กิวเมนต์ที่ไม่รู้จัก/)
  assert.match(r.out, /ไม่ใช่ "รันแบบไม่กรอง"/, 'ข้อความต้องบอกว่าต่างจาก "ไม่กรอง" ตรงไหน')
  assert.doesNotMatch(r.out, /พิสูจน์ว่าด่านแยกแยะได้/,
    '🔴 ห้ามเริ่มพิสูจน์เลย — เริ่มแล้วคือเริ่มแก้ไฟล์จริง')
})

test('ธงที่ไม่รู้จักตัวอื่นก็ต้องตีกลับ (ไม่ใช่กันเฉพาะรูปที่เคยพลาด)', () => {
  const r = รัน(['--ธงที่ไม่มีจริง=1'])
  assert.equal(r.rc, 1, 'กันเฉพาะ `--เฉพาะ` ที่พิมพ์ผิด = กันรูปเดียวที่เคยเจ็บ ไม่ใช่กลไก')
  assert.match(r.out, /--ธงที่ไม่มีจริง=1/, 'ต้องบอกว่าธงตัวไหนที่ไม่รู้จัก')
})

test('ตัวกรองที่ถูกรูปแต่ไม่ตรงสูตรไหน ⇒ ตก (ไม่ใช่ "ผ่านเพราะไม่มีอะไรทำ")', () => {
  const r = รัน(['--เฉพาะ=ไม่มีสูตรชื่อนี้แน่นอน-zzz'])
  assert.equal(r.rc, 1)
  assert.match(r.out, /ไม่ได้พิสูจน์อะไร/, 'รอบที่ไม่ได้พิสูจน์อะไร ห้ามอ่านเหมือนผ่าน')
})

test('🌳 สภาพต้นไม้ถูกพิมพ์ทุกทางออก และแยก "ค้างมาก่อน" ออกจาก "ตัวปลูกทิ้งไว้"', () => {
  for (const args of [['--เฉพาะ', 'xxx'], ['--เฉพาะ=ไม่มีสูตรชื่อนี้แน่นอน-zzz']]) {
    const r = รัน(args)
    assert.match(r.out, /สภาพต้นไม้หลังตัวปลูกจบ/,
      `ทางออกนี้ไม่พิมพ์สภาพต้นไม้ (${args.join(' ')}) `
      + '⇒ 🔴 ทางออกที่เงียบคือทางที่ของค้างจะไม่มีใครเห็น')
    assert.match(r.out, /ค้างอยู่ก่อนเริ่ม \d+ · ตอนนี้ \d+/,
      'ต้องมีสองเลข — เลขเดียวทำให้ของที่ค้างมาก่อนถูกอ่านว่าตัวปลูกทำ (โทษผิดตัว)')
    assert.match(r.out, /วัดด้วย git status ไม่ใช่คำหมุด/,
      'ต้องเขียนว่าวัดด้วยอะไร: คำหมุดจับสูตรที่ไม่ใส่หมุดไม่ได้ (ของจริงรอบนั้นคือ route-allow.ts)')
  }
})
