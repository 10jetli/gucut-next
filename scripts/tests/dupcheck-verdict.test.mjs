/* "อ่านคลังไฟล์ไม่ได้" ห้ามอ่านว่า "ไม่มีใบซ้ำ" — เดินทางนั้นให้จริง
 * (19 ก.ย. 2569 · เจอจากการกวาดคลาส `.catch(() => ว่าง)` ที่ฝั่งท่อชี้)
 *
 * 🔑 เคสที่ ① คือรูปของบั๊กจริงเป๊ะ ๆ: คลังล้ม ⇒ `files = []` ⇒ ทุกตัวเลขเป็น 0
 *    ⇒ เงื่อนไขเดิมสามข้อ **เป็นจริงทั้งสามข้อ** ⇒ `สรุปได้: true` พร้อม `ใบซ้ำ: []`
 *    ⇒ ตัวเลขที่อ่านเหมือน "ตรวจครบแล้วสะอาด" ทั้งที่ไม่ได้อ่านอะไรเลย
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { โหลดโมดูลจากTS } from '../lib/โหลดโมดูลจากTS.mjs'

const { เหตุที่ยังสรุปไม่ได้, สรุปได้จาก } = await โหลดโมดูลจากTS(
  new URL('../../lib/dupcheck-verdict.ts', import.meta.url),
  [
    [/: *string \| null/g, ''],
    [/: *number/g, ''],
    [/export function เหตุที่ยังสรุปไม่ได้\(x: \{[\s\S]*?\}\) *\{/, 'export function เหตุที่ยังสรุปไม่ได้(x) {'],
    [/export const สรุปได้จาก = \(x: [^)]*\) =>/, 'export const สรุปได้จาก = (x) =>'],
  ],
)

const ปกติ = { อ่านคลังไฟล์ไม่ได้: null, อ่านได้: 12, ไฟล์ในช่วง: 12, ตัดสินไม่ได้: 0, ไฟล์ในถัง: 12, skip: 0, limit: 60 }

test('① รูปของบั๊กจริง: อ่านคลังไม่ได้ ⇒ ทุกตัวเลขเป็น 0 ⇒ ต้องสรุปไม่ได้', () => {
  const ล้ม = { อ่านคลังไฟล์ไม่ได้: 'blobs: connection refused', อ่านได้: 0, ไฟล์ในช่วง: 0, ตัดสินไม่ได้: 0, ไฟล์ในถัง: 0, skip: 0, limit: 60 }
  assert.equal(สรุปได้จาก(ล้ม), false, '🔴 อ่านไม่ได้แล้วตอบว่าสรุปได้ = ตอบว่า "สะอาด" ทั้งที่ไม่ได้อ่าน')
  assert.deepEqual(เหตุที่ยังสรุปไม่ได้(ล้ม), ['อ่านคลังไฟล์ไม่ได้'])
})

test('② ตัวควบคุมลบ: ทุกอย่างปกติ ⇒ สรุปได้ และไม่มีเหตุค้าง', () => {
  assert.equal(สรุปได้จาก(ปกติ), true)
  assert.deepEqual(เหตุที่ยังสรุปไม่ได้(ปกติ), [])
})

test('③ ถังว่างจริง (อ่านได้ แต่ไม่มีไฟล์) ⇒ สรุปได้ — ต้องต่างจากเคส ①', () => {
  const ว่างจริง = { อ่านคลังไฟล์ไม่ได้: null, อ่านได้: 0, ไฟล์ในช่วง: 0, ตัดสินไม่ได้: 0, ไฟล์ในถัง: 0, skip: 0, limit: 60 }
  assert.equal(สรุปได้จาก(ว่างจริง), true, '"ไม่มีบิล" กับ "อ่านไม่ได้" ต้องให้คำตอบคนละแบบ')
})

test('④ เหตุค้างอื่นยังทำงานครบ และรายงานพร้อมกันได้หลายข้อ', () => {
  const หลายข้อ = { อ่านคลังไฟล์ไม่ได้: 'x', อ่านได้: 3, ไฟล์ในช่วง: 5, ตัดสินไม่ได้: 2, ไฟล์ในถัง: 500, skip: 0, limit: 60 }
  assert.deepEqual(เหตุที่ยังสรุปไม่ได้(หลายข้อ), [
    'อ่านคลังไฟล์ไม่ได้', 'อ่านไฟล์ในช่วงไม่ครบ', 'มีใบที่ตัดสินไม่ได้', 'ยังมีไฟล์ที่ยังไม่ได้อ่าน',
  ])
})
