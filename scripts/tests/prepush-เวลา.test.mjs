#!/usr/bin/env node
/* ตัวจับเวลาของด่านก่อน push — ตรวจสองชิ้นที่ "คิดเลข" (ส่วนที่พังแล้วเตือนผิดได้เงียบ ๆ)
 * (28 ก.ย. 2569 · หลังวัดของจริง: ยิง push 21:37 อยู่ในหน้าต่าง แต่ด่านใช้ 1 ชม. 22 นาที
 *  ⇒ ของขึ้นเว็บ 22:59 นอกหน้าต่าง · หน้าต่างถูกบังคับตอน "พิมพ์คำสั่ง" ที่เดียว)
 *
 * 🔑 ทำไมต้องมีเทส ทั้งที่มันเป็นแค่ข้อความเตือน:
 *    ตัวเตือนนี้ตัดสินจาก **ตัวเลขที่มันคำนวณเอง** (ขอบหน้าต่าง + เวลานานสุดที่เคยใช้)
 *    คิดผิด = เตือนผิด · และตัวเตือนที่เตือนผิดจะถูกคนเลิกอ่านถาวร (noise-filters-eat-real-cases)
 *
 * 🔴 จุดที่อันตรายที่สุดและเทสนี้เกิดมาเพื่อมัน: **สมุดเป็นไฟล์กลางที่สองรีโปเขียนร่วมกัน**
 *    ด่านของสองฝั่งใช้เวลาต่างกันมาก ⇒ ถ้าอ่านแถวรวมกันแล้วคาดเวลา จะเตือนผิดทั้งสองฝั่ง
 *    (กฎเดิม: เทียบเลขต้องวัดรุ่นเดียวกัน)
 */
import { execFileSync } from 'node:child_process'
import { mkdtempSync, writeFileSync, rmSync, readFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const ที่ = mkdtempSync(join(tmpdir(), `prepush-${process.pid}-`))
let ตก = 0
const ok = (ชื่อ, เงื่อนไข, เหตุ = '') => {
  console.log(`  ${เงื่อนไข ? '✅' : '❌'} ${ชื่อ}${เงื่อนไข ? '' : ` — ${เหตุ}`}`)
  if (!เงื่อนไข) ตก++
}
const sh = (cmd) => execFileSync('bash', ['-c', cmd], { encoding: 'utf8' }).trim()

const hook = readFileSync('scripts/hooks/pre-push', 'utf8')

try {
  console.log('① ตัวหาค่านานสุด ต้องนับเฉพาะแถวของรีโปตัวเอง')
  {
    const log = join(ที่, 'เวลา.log')
    writeFileSync(log, [
      '2026-09-27  gucut-web   ใช้ 240 วินาที  เริ่ม 20:40 เสร็จ 20:44  ปกติ',
      '2026-09-27  gucut-next  ใช้ 1200 วินาที เริ่ม 20:35 เสร็จ 20:55  ปกติ',
      '2026-09-28  gucut-web   ใช้ 9000 วินาที เริ่ม 21:00 เสร็จ 23:30  เริ่มในหน้าต่าง แต่เสร็จนอกหน้าต่าง',
      /* 🔴 แถวที่ฝั่งท่อยิงวัดแล้วจับรูของผมได้: ชื่อรีโปที่ **ขึ้นต้นเหมือนกัน** แต่คนละตัว
         รุ่นแรกผมกรองด้วย `$0 ~ repo` (substring) ⇒ แถวนี้ถูกนับเข้าไปด้วยตอนหา gucut-web
         ⇒ ได้ 9600 แทนที่จะเป็น 9000 · คลาสเดียวกับรู prefix ของ middleware เมื่อเช้า */
      '2026-09-28  gucut-web-สำรอง  ใช้ 9600 วินาที เริ่ม 01:00 เสร็จ 03:40  ปกติ',
      '',
    ].join('\n'), 'utf8')
    /* 🔑 ใช้สูตรเดียวกับในด่านเป๊ะ — เทียบ **เต็มช่อง** ไม่ใช่ "มีคำนั้นอยู่ในบรรทัด" */
    const หา = (repo) => sh(`awk -v repo='${repo}' '$2 == repo { for (i=1;i<=NF;i++)`
      + ` if ($i == "ใช้") { s = $(i+1)+0; if (s>m) m=s } } END { print m+0 }' '${log}'`)
    ok('รีโปจอได้ 1200 (ไม่ใช่ 9000 ของอีกฝั่ง)', หา('gucut-next') === '1200', หา('gucut-next'))
    ok('🔴 รีโปท่อได้ 9000 — **ไม่ใช่ 9600 ของ gucut-web-สำรอง**', หา('gucut-web') === '9000',
      `${หา('gucut-web')} ⇒ กรองแบบ substring จะกินแถวของรีโปที่ชื่อขึ้นต้นเหมือนกัน`)
    ok('และรีโปสำรองได้ของตัวเอง 9600', หา('gucut-web-สำรอง') === '9600', หา('gucut-web-สำรอง'))
    ok('รีโปที่ไม่มีในสมุด ⇒ 0 (แปลว่า "ยังไม่มีประวัติ" ไม่ใช่ "เร็วมาก")',
      หา('gucut-อื่น') === '0', หา('gucut-อื่น'))
  }

  console.log('② ตัวอ่านขอบหน้าต่าง ต้องอ่านจากด่านกลางได้จริง (ไม่พิมพ์เลขซ้ำในสองไฟล์)')
  {
    const gate = join(ที่, 'ด่าน.py')
    writeFileSync(gate, 'PUSH_WINDOW = ((20, 30), (22, 0))          # 20:30-22:00\n', 'utf8')
    const win = sh(`grep -m1 '^PUSH_WINDOW' '${gate}' | grep -oE '[0-9]+' | tr '\\n' ' '`
      + ` | awk '{ if (NF>=4) printf "%d %d", $1*60+$2, $3*60+$4 }'`)
    ok('แปลง 20:30-22:00 เป็นนาที ⇒ "1230 1320"', win === '1230 1320', win)
    const ว่าง = join(ที่, 'ไม่มีขอบ.py')
    writeFileSync(ว่าง, '# ไฟล์นี้ไม่มีบรรทัด PUSH_WINDOW\n', 'utf8')
    const win2 = sh(`grep -m1 '^PUSH_WINDOW' '${ว่าง}' 2>/dev/null | grep -oE '[0-9]+' | tr '\\n' ' '`
      + ` | awk '{ if (NF>=4) printf "%d %d", $1*60+$2, $3*60+$4 }' || true`)
    ok('อ่านขอบไม่ได้ ⇒ ค่าว่าง (ให้ด่านเงียบเรื่องหน้าต่าง ไม่ใช่เดาว่าอยู่ในรอบ)', win2 === '', `ได้ "${win2}"`)
  }

  console.log('③ ด่านต้องอ่านขอบจากไฟล์กลาง และต้องไม่พิมพ์เลขหน้าต่างเองซ้ำ')
  {
    ok('ชี้ไปไฟล์ด่านกลาง', /PREPUSH_GATE=.*ด่านคำสั่ง-bash\.py/.test(hook))
    const มีเลขซ้ำ = /PREPUSH_(LO|HI)=\s*\d/.test(hook) || /\b1230\b|\b1320\b/.test(hook)
    ok('ไม่มีเลขขอบหน้าต่างพิมพ์ค้างในด่าน', !มีเลขซ้ำ,
      'เลขเกณฑ์สองที่จะเพี้ยนกันวันหนึ่ง — ต้องอ่านจากแหล่งเดียว')
    ok('อ่านค่านานสุดแบบกรองด้วยชื่อรีโป', /awk -v repo="\$PREPUSH_REPO"/.test(hook),
      'ไม่กรอง = เอาเวลาของอีกรีโปมาคาดเวลาของเรา')
    ok('🔴 และกรองแบบ **เทียบเต็มช่อง** ไม่ใช่ substring', /\$2 == repo/.test(hook),
      'เจอ `$0 ~ repo` ⇒ ชื่อรีโปที่ขึ้นต้นเหมือนกันจะถูกนับรวม (ฝั่งท่อยิงวัดจับได้ 28 ก.ย.)')
  }

  console.log('④ ต้องจดของจริงเสมอ และต้องไม่ตีกลับเมื่อหน้าต่างปิดระหว่างทาง')
  {
    /* ⚠️ อย่าผูกเกณฑ์กับ "บรรทัดเดียว" — คำสั่ง printf ในด่านเขียนแบบต่อบรรทัดด้วย \\
       เทสรุ่นแรกของข้อนี้แดงทั้งที่โค้ดถูก เพราะ regex เดินไม่ข้ามบรรทัด
       (คลาสเดิมที่เหยียบมาแล้ววันนี้: ตะแกรงที่อ่านทีละบรรทัดกับโค้ดที่เขียนหลายบรรทัด) */
    const บล็อกจด = hook.slice(hook.indexOf('PREPUSH_ELAPSED=$(( $(date +%s)'))
    ok('มีการเขียนลงสมุด', /printf[\s\S]{0,400}>> "\$PREPUSH_LOG"/.test(บล็อกจด),
      'ไม่เจอคำสั่งเขียนสมุดในบล็อกจดเวลา')
    ok('จดชื่อรีโปลงไปด้วย (ไม่งั้นกรองไม่ได้)', /"\$PREPUSH_REPO"/.test(hook))
    /* 🚫 ตัดสินใจร่วมกับฝั่งท่อ 28 ก.ย.: ตีกลับตอนท้ายไม่ประหยัดเครดิต (ยังเป็น deploy รอบเดียว)
       และผลักคนไปใช้ทางฉุกเฉิน ⇒ ได้ deploy เพิ่ม = ตรงข้ามกับเจตนาของกฎ */
    const กิ่งปิดหน้าต่าง = hook.slice(hook.indexOf('PREPUSH_NOTE="เริ่มในหน้าต่าง'))
    ok('กิ่ง "ปิดหน้าต่างระหว่างทาง" ไม่มี exit 1',
      !/exit 1/.test(กิ่งปิดหน้าต่าง.slice(0, 700)), 'ตีกลับตอนท้าย = ทิ้งแรงฟรีโดยไม่ประหยัดเครดิต')
    ok('และต้องพูดออกมาว่าของจะขึ้นนอกรอบ', /ของจะขึ้นเว็บนอกรอบ/.test(hook))
  }

  console.log('⑤ ไวยากรณ์ของด่านต้องยังผ่าน (ด่านที่พังคือด่านที่ไม่มีใครผ่าน)')
  {
    let ผ่าน = true
    try { execFileSync('bash', ['-n', 'scripts/hooks/pre-push']) } catch { ผ่าน = false }
    ok('bash -n ผ่าน', ผ่าน)
  }
} finally {
  rmSync(ที่, { recursive: true, force: true })
}

console.log(ตก ? `\n❌ ไม่ผ่าน ${ตก} ข้อ` : '\n✅ ผ่านทุกข้อ')
console.log('⚠️ ขอบเขต: ตรวจการคิดเลขและรูปของด่าน — **ไม่ได้รันด่านจริง** (มันรันเทส+build ทั้งชุด)')
process.exit(ตก ? 1 : 0)
