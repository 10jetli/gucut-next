#!/usr/bin/env node
/* เทสตัวอ่านล็อกของ `check-bill-collector-claims.mjs` — **ป้อนล็อกปลอมสามรูป แล้ววัด rc**
 * (28 ก.ย. 2569 · มาจากบทเรียนที่ฝั่งท่อส่งมา: ด่านที่ตรึงทางออกทั้งก้อนจะแดงลวงตอนมีคนเพิ่มช่อง
 *  ⇒ ผมกวาดฝั่งจอหารูปเดียวกัน แล้วเจอ **ทิศตรงข้าม** ในด่านนั้น)
 *
 * 🔴 ของจริงที่เจอ: ด่านนั้นกันเคส "ตะแกรงพัง ≠ ทะเบียนว่าง" ไว้**ฝั่งทะเบียน** (exit 1 ถ้าแกะ
 *    lib/vendors.ts ไม่ได้สักเจ้า) แต่ **ฝั่งอ่านล็อกไม่ได้กันเลย** ⇒ ถ้ารูปบรรทัดสรุปเปลี่ยน
 *    regex จะไม่ match สักแถว ⇒ ทุกเจ้ากลายเป็น "ตัดสินไม่ได้" ⇒ **เขียว rc=0 ตลอดกาล**
 *    = ผู้เขียนคนเดียวกัน (ผม) ใช้กฎกับตัวเองข้างเดียว
 *
 * 🔑 ทำไมเป็นเทสไม่ใช่สูตรปลูก: สิ่งที่ต้องทำให้ผิดคือ **ข้อมูลที่ด่านอ่าน** ไม่ใช่ตัวด่าน
 *    ล็อกจริงเป็นของ cron บน g1 ⇒ แตะไม่ได้ ⇒ จึงให้ด่านรับ `BILLS_CRON_LOG` แล้วป้อนของปลอม
 *    (ถ้าปลูกลงตัวด่านเอง ตัวที่ถูกวัดจะกลายเป็น regex ของเรา ไม่ใช่พฤติกรรมตอนข้อมูลเปลี่ยนรูป)
 *
 * ⚠️ ทุกรอบสร้างโฟลเดอร์ใหม่ที่มี pid — ห้ามล้างแล้วใช้ซ้ำ (ของค้างให้ผลที่น่าเชื่อแต่ผิด)
 */
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('../..', import.meta.url))
const ด่าน = join(ROOT, 'scripts/check-bill-collector-claims.mjs')
const ที่ทำงาน = mkdtempSync(join(tmpdir(), `bcclog-${process.pid}-`))

let ตก = 0
const ok = (ชื่อ, เงื่อนไข, เหตุ = '') => {
  console.log(`  ${เงื่อนไข ? '✅' : '❌'} ${ชื่อ}${เงื่อนไข ? '' : ` — ${เหตุ}`}`)
  if (!เงื่อนไข) ตก++
}

/** ยิงด่านด้วยล็อกที่เราแต่ง — คืน {rc, out} */
function ยิง(ชื่อไฟล์, เนื้อ) {
  const p = join(ที่ทำงาน, ชื่อไฟล์)
  writeFileSync(p, เนื้อ, 'utf8')
  const r = spawnSync(process.execPath, [ด่าน], {
    cwd: ROOT, encoding: 'utf8', env: { ...process.env, BILLS_CRON_LOG: p },
  })
  return { rc: r.status, out: `${r.stdout ?? ''}${r.stderr ?? ''}` }
}

/* รูปบรรทัดสรุปจริงที่ ~/bin/รันงานบิล.sh พิมพ์ */
/* ⚠️ ชื่อในล็อกคือ **ชื่อสคริปต์ตัดนามสกุล** ที่ทะเบียน lib/vendors.ts ประกาศไว้
   (เช่น `tiktok-bills.py` ⇒ `tiktok-bills`) — ใช้ชื่อเจ้าเฉย ๆ จะแกะแถวได้แต่จับคู่ไม่ติด
   ผมเขียนผิดเป็น 'tiktok' รอบแรก แล้วเทสจับได้ว่า "ตัดสินได้ 0 จาก 6" ⇒ เก็บกฎนี้ไว้ในคอมเมนต์ */
const แถวปกติ = [
  '[2026-09-28 11:37:00] ▶ tiktok-bills เริ่ม',
  '[2026-09-28 11:37:20] ◀ tiktok-bills จบ rc=0 · status=OK',
  '[2026-09-28 11:38:00] ◀ meta-bills จบ rc=0 · status=OK',
].join('\n')

console.log('① ล็อกรูปปกติ ⇒ ต้องแกะได้และรายงานความครอบคลุม')
{
  const { rc, out } = ยิง('ปกติ.log', แถวปกติ + '\n')
  ok('ไม่แดง', rc === 0, `rc=${rc}`)
  ok('บอกว่าตัดสินได้กี่เจ้าจากกี่เจ้า', /ตัดสินได้ \d+ จาก \d+/.test(out), out.slice(-200))
  ok('แกะแถวได้จริง (ตัดสินได้ ≥ 1)', /ตัดสินได้ [1-9]\d* จาก/.test(out), out.slice(-200))
}

console.log('② ล็อกเปลี่ยนรูป (ตัวคั่นไม่ใช่ ◀ แล้ว) ⇒ ต้อง **แดง** ไม่ใช่ "ตัดสินไม่ได้"')
{
  const { rc, out } = ยิง('เปลี่ยนรูป.log', แถวปกติ.replace(/◀/g, '◁') + '\n[2026-09-28 11:39:00] ◀\n')
  ok('แดง (rc=1)', rc === 1, `rc=${rc} ⇒ ด่านจะเขียวตลอดกาลโดยไม่ตรวจอะไรเลย`)
  ok('บอกสาเหตุว่าตัวอ่านพัง ไม่ใช่ข้อมูลไม่มี', /ตัวอ่านล็อกของด่านนี้พัง/.test(out), out.slice(-300))
}

console.log('③ ล็อกที่ยังไม่มีรอบสรุปเลย ⇒ ต้องข้าม และเขียนว่า "ยังไม่มีรอบ" ไม่ใช่ผ่าน')
{
  const { rc, out } = ยิง('ยังไม่มีรอบ.log', '[2026-09-28 11:37:00] ▶ tiktok เริ่ม\n')
  ok('ไม่แดง', rc === 0, `rc=${rc}`)
  ok('เขียนว่ายังไม่มีรอบ (ไม่ใช่ตรวจแล้วผ่าน)', /ยังไม่มีรอบ/.test(out), out.slice(-300))
  ok('ไม่อ้างว่าทะเบียนตรงกับของจริง', !/ตรงกับของจริงทุกเจ้า/.test(out), out.slice(-300))
}

rmSync(ที่ทำงาน, { recursive: true, force: true })
console.log(ตก ? `\n❌ ไม่ผ่าน ${ตก} ข้อ` : '\n✅ ผ่านทุกข้อ — ตัวอ่านล็อกแยก "ข้อมูลไม่มี" กับ "ตัวอ่านพัง" ออกจากกันได้')
process.exit(ตก ? 1 : 0)
