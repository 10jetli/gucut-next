/* ด่าน: สมุด "AI แนะนำร้านเราไหม" (`data/ai-แนะนำร้านเรา.json`)
 *
 * 🔴 ที่มา (ข้อ ③ ของงานจอ `/web/seo` · 14 ต.ค. 2569)
 *    จอนั้นมี "บอต AI มาเก็บข้อมูล" + "คะแนน GEO" อยู่แล้ว ⇒ อ่านรวมกันชวนให้สรุปว่า
 *    **AI ทำงานให้ร้านเราอยู่** ทั้งที่ทั้งสองอย่างไม่ได้ตอบคำถามนั้น
 *    ⇒ ของที่เพิ่มคือ **ชุดคำถามคงที่ + สมุดบันทึก** ไม่ใช่ตัวเลขที่เดาขึ้นมา
 *
 * 🔑 ด่านนี้เฝ้าของที่พังเงียบได้สองทาง:
 *    ① ชุดคำถามหาย/ว่าง ⇒ จอยังเขียนว่า "ชุดคำถามคงที่" แต่ไม่มีคำถามให้ถาม
 *    ② บันทึกผลที่กรอกไม่ครบ (ไม่มีวันที่ · ไม่มีคำตอบ) ⇒ **ช่องว่างกลายเป็นคำยืนยัน**
 *       ("ไม่เอ่ยร้านใด" ต้องพิมพ์ออกมา ห้ามปล่อยว่างแล้วให้คนอ่านเดา)
 *    ③ คำถามในบันทึกไม่ตรงกับชุด ⇒ เทียบข้ามรอบไม่ได้ (วัดคนละคำถามแล้วเอามาวางคู่กัน)
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'

const ROOT = fileURLToPath(new URL('../..', import.meta.url))
const ด = JSON.parse(readFileSync(join(ROOT, 'data/ai-แนะนำร้านเรา.json'), 'utf8'))

test('ชุดคำถามต้องมีจริงและครบช่อง — จอเขียนว่า "ชุดคำถามคงที่" ไว้แล้ว', () => {
  const ชุด = ด['ชุดคำถาม']
  assert.ok(Array.isArray(ชุด) && ชุด.length > 0,
    'ชุดคำถามว่าง = จอสัญญาว่ามีชุดคำถามแต่ไม่มีอะไรให้ถาม')
  for (const q of ชุด) {
    assert.ok(q.id && q.คำถาม && q['เหตุที่เลือก'],
      `คำถาม ${JSON.stringify(q).slice(0, 60)} ขาดช่อง — เหตุที่เลือกคือสิ่งที่กันคนเปลี่ยนคำถามทิ้งโดยไม่รู้ว่าทำไมมันอยู่ตรงนี้`)
  }
  const ids = ชุด.map((q) => q.id)
  assert.equal(new Set(ids).size, ids.length, 'id ซ้ำ = เทียบผลข้ามรอบไม่ได้')
})

test('🔴 บันทึกผลทุกแถวต้องมี เมื่อ/ผู้ช่วย/โดย/คำถาม/คำตอบ ครบ — ช่องว่างห้ามเป็นคำตอบ', () => {
  const บ = ด['บันทึกผล']
  assert.ok(Array.isArray(บ), 'บันทึกผลต้องเป็นอาร์เรย์ (ว่างได้ = ยังไม่เคยถาม)')
  for (const r of บ) {
    for (const ช of ['เมื่อ', 'ผู้ช่วย', 'โดย', 'คำถาม', 'คำตอบ']) {
      assert.ok(typeof r[ช] === 'string' && r[ช].trim() !== '',
        `บันทึกขาดช่อง ${ช} — "ไม่เอ่ยร้านใด" ต้องพิมพ์ออกมา ห้ามปล่อยว่างให้คนอ่านเดา`)
    }
  }
})

test('คำถามในบันทึกต้องเป็นคำถามจากชุด — ไม่งั้นเทียบข้ามรอบไม่ได้', () => {
  const ถาม = new Set((ด['ชุดคำถาม'] || []).map((q) => q.คำถาม))
  for (const r of (ด['บันทึกผล'] || [])) {
    assert.ok(ถาม.has(r.คำถาม),
      `บันทึกใช้คำถามที่ไม่อยู่ในชุด: ${String(r.คำถาม).slice(0, 40)} ⇒ วัดคนละคำถามแล้วเอามาวางคู่กัน`)
  }
})

test('ไฟล์ต้องอธิบายตัวเองว่าทำไมยังวัดอัตโนมัติไม่ได้ — เหตุที่หายไปจะกลายเป็น "ขี้เกียจทำ"', () => {
  const เหตุ = ด['ทำไมยังวัดอัตโนมัติไม่ได้']
  assert.ok(Array.isArray(เหตุ) && เหตุ.length >= 2 && เหตุ.every((x) => String(x).length >= 30),
    'เหตุต้องยาวพอที่จะเป็นเหตุ — ช่องที่รับคำว่า "จำเป็น" ได้ คือช่องที่ทุกคนจะเขียนว่า "จำเป็น"')
})
