/* ด่าน: `scripts/check-ทะเบียนปลายเปิด.mjs` ต้องจับความไม่ตรงกัน **ทั้งสองทิศ**
 *
 * 🔴 ที่มา 14 ต.ค. 2569 — ฝั่งท่อเขียนเองว่า:
 *    *"ของที่กันไว้รอบนี้ไม่ใช่กระบวนการ มันคือการที่ผมเผอิญไปอ่านโค้ดเอง
 *      — ไม่มีด่านไหนอ่านทะเบียนเทียบโค้ดอีกฝั่ง ⇒ ต้องเป็นนิสัยสองด้าน ไม่ใช่โชค"*
 *    ⇒ ด่านนั้นคือด้านของผม · **เทสนี้คือสิ่งที่ทำให้มันไม่ใช่โชคอีกต่อไป**
 *
 * 🔑 ใช้ทะเบียนตัวอย่างในรีโปนี้ (ไม่เขียนไฟล์ลงรีโปของอีกฝั่ง —
 *    "ต้นไม้ร่วมไม่มีสภาพกลางงาน") ⇒ ด่านรับพาธผ่าน `OPEN_ENDED_REGISTRY`
 *    ⚠️ ช่องนั้นมีไว้ **เพื่อให้ทดสอบได้** — ทางที่ทดสอบไม่ได้ คือทางที่จะไม่ถูกทดสอบ
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'

const ROOT = fileURLToPath(new URL('../..', import.meta.url))
const ด่าน = join(ROOT, 'scripts', 'check-ทะเบียนปลายเปิด.mjs')
const ทะเบียน = join(ROOT, 'scripts', 'tests', 'fixtures', 'ทะเบียนปลายเปิด-ตัวอย่าง.mjs')

const รัน = (โหมด, เพิ่ม = {}) => spawnSync(process.execPath, [ด่าน], {
  encoding: 'utf8',
  env: { ...process.env, OPEN_ENDED_REGISTRY: ทะเบียน, REGISTRY_MODE: โหมด, ...เพิ่ม },
})

test('ทะเบียนตรงกับโค้ด ⇒ เขียว (rc=0) และไม่พิมพ์คำว่าไม่ตรงกัน', () => {
  const r = รัน('ตรง')
  assert.equal(r.status, 0, r.stdout + r.stderr)
  assert.ok(!/ไม่ตรงกัน/.test(r.stdout + r.stderr), 'ด่านที่ร้องทุกครั้งแยกไม่ออกจากด่านที่ร้องเพราะมีปัญหาจริง')
})

test('🔴 ทิศ ①: ทะเบียนจดว่าจออ่าน แต่โค้ดไม่เอ่ยถึงแล้ว ⇒ แดงพร้อมชื่อช่อง', () => {
  const r = รัน('ทิศ1')
  /* 🔑 **ข้อความต้องอยู่ที่ assert ตัวแรกที่บั๊กปลูกจะสะดุด** — node:test หยุดที่ตัวแรกที่ล้ม
     ⇒ ข้อความของ assert ถัดไปไม่มีวันถูกพิมพ์ (เหยียบมาแล้วเช้านี้ครั้งหนึ่ง) */
  assert.equal(r.status, 1,
    'ด่านต้องแดงเมื่อทะเบียนค้างอยู่กับจอที่เลิกอ่าน — เงียบแล้วทะเบียนจะผิดตลอดกาล')
  assert.ok(/ทะเบียนค้างอยู่กับจอที่เลิกอ่าน/.test(r.stderr),
    'ต้องบอกว่าทะเบียนค้าง ไม่ใช่บอกแค่ว่า "ไม่ตรง"')
})

test('🔴 ทิศ ②: ทะเบียนจดว่าไม่มีใครอ่าน แต่จออ่านแล้ว ⇒ แดงพร้อมเหตุที่อันตราย', () => {
  const r = รัน('ทิศ2')
  assert.equal(r.status, 1,
    'ด่านต้องแดงเมื่อจออ่านช่องที่ทะเบียนจดว่าไม่มีใครอ่าน'
    + ' — เงียบแล้วฝั่งท่ออาจถอดข้อจำกัด "รับได้ทุกจำนวน" ทิ้งเพราะคิดว่าไม่มีใครใช้')
  assert.ok(/ถอดข้อจำกัด/.test(r.stderr),
    'ต้องบอกผลที่ตามมา (ฝั่งท่ออาจถอดข้อจำกัดเพราะคิดว่าไม่มีใครใช้) ไม่ใช่แค่ว่าไม่ตรง')
})

test('ไม่มีทะเบียนให้อ่าน ⇒ **ข้ามอย่างมีเสียง** (rc=0 แต่ต้องบอกว่ายังไม่ได้ตรวจ)', () => {
  const r = spawnSync(process.execPath, [ด่าน], {
    encoding: 'utf8',
    env: { ...process.env, OPEN_ENDED_REGISTRY: join(ROOT, 'ไม่มีไฟล์นี้.mjs') },
  })
  assert.equal(r.status, 0)
  assert.ok(/ยังไม่ได้ตรวจ/.test(r.stdout),
    'เงียบแล้วผ่าน = แยก "ตรวจแล้วไม่เจอ" กับ "ไม่ได้ตรวจ" ไม่ออก')
})

/* ══ 🆕 กิ่งของ **ชนิดผู้อ่าน** (ฝั่งท่อแยกเป็นฟิลด์ 14 ต.ค. 2569) ═══════════════
   มีชนิดแล้วด่านเลือกเกณฑ์ได้ ⇒ เลิกเดาจากการ grep ว่าเจอที่ไหน
   ⚠️ สามกิ่งนี้เป็น **ทางที่ไม่เคยถูกเดิน** ถ้าไม่เขียนเทส ⇒ เขียนไว้ตั้งแต่วันที่เพิ่มกิ่ง */

test('🔴 ชนิด "ด่าน/ตัววัด" แต่จอก็อ่านด้วย ⇒ **ชนิดต่ำกว่าความจริง** (ความเสี่ยง UI ไม่ถูกจด)', () => {
  const r = รัน('ชนิดต่ำกว่าจริง')
  assert.equal(r.status, 1,
    'ด่านต้องแดง — ชนิดต่ำกว่าจริงทำให้ความเสี่ยงเรื่องสมาชิกโตไม่ถูกจดไว้เลย')
  assert.ok(/ชนิดต่ำกว่าความจริง/.test(r.stderr))
})

test('🔴 ชนิด "ด่าน/ตัววัด" แต่ไม่มีไฟล์ไหนอ่าน ⇒ ทะเบียนค้างกับด่านที่เลิกอ่าน', () => {
  const r = รัน('ด่านเลิกอ่าน')
  assert.equal(r.status, 1, 'ด่านต้องแดงเมื่อไม่มีผู้อ่านตามชนิดที่จดไว้')
  assert.ok(/ค้างกับด่านที่เลิกอ่าน/.test(r.stderr))
})

test('🔴 ชนิด "lib ที่จอเรียก" แต่ไม่มีใน lib/ ⇒ ชนิดไม่ตรงกับโค้ด', () => {
  const r = รัน('libไม่ตรง')
  assert.equal(r.status, 1, 'ด่านต้องแดงเมื่อชนิดกับที่อยู่จริงไม่ตรงกัน')
  assert.ok(/ชนิดไม่ตรงกับโค้ด/.test(r.stderr))
})

/* ══ 🔴 **ขอบคำ: ชื่อสั้นห้ามกินชื่อยาว** (ฝั่งท่อยิงตรวจแล้วส่งมาเตือน 14 ต.ค. 2569) ═══
   วัดได้: `byStatusFiltered`.includes(`byStatus`) = true ⇒ ถ้าด่านใช้ `includes`
   ไฟล์ที่เอ่ยเฉพาะ `byStatusFiltered` จะถูกนับว่าเอ่ย `byStatus` ⇒ **แดงลวง**
   🔑 และเขาขอให้ **ปลูกไฟล์จริงพิสูจน์ ไม่ใช่เชื่อว่า regex ถูกเพราะอ่านแล้วดูถูก**
      ⇒ ปลูกในไดเรกทอรีที่เทสคุมเอง (`OPEN_ENDED_SCAN_ROOT`) ไม่ใช่ในต้นไม้จริง */
test('🔴 ไฟล์ที่เอ่ยเฉพาะ `byStatusFiltered` **ต้องไม่ถูกนับว่าเอ่ย** `byStatus`', () => {
  const ราก = mkdtempSync(join(tmpdir(), 'กวาดจอ-'))
  mkdirSync(join(ราก, 'app'), { recursive: true })
  mkdirSync(join(ราก, 'components'), { recursive: true })
  writeFileSync(join(ราก, 'app', 'จอปลูก.tsx'),
    'export const x = (d) => d.byStatusFiltered?.length ?? 0\n')
  /* ⚠️ ช่องที่ทะเบียนตัวอย่าง "มีทุกโหมด" ต้องมีผู้อ่านในรากที่กวาดด้วย
     ไม่งั้นเทสนี้จะล้มด้วย **เหตุอื่น** แล้วเราจะอ่านว่าขอบคำพัง (ของจริงเกิดกับผมรอบแรก) */
  writeFileSync(join(ราก, 'components', 'จออื่น.tsx'),
    'export const y = (d) => d.statusesAll ?? []\n')
  try {
    const r = รัน('ขอบคำ', { OPEN_ENDED_SCAN_ROOT: ราก })
    assert.equal(r.status, 0,
      'เอ่ยแต่ `byStatusFiltered` แล้วด่านฟ้อง `byStatus` = **แดงลวง** ⇒ คนจะถอดด่านทิ้ง\n'
      + r.stdout + r.stderr)
  } finally { rmSync(ราก, { recursive: true, force: true }) }
})

test('🔴 ทะเบียนขัดกันเอง (ใครอ่าน=ไม่มี แต่ระบุชนิดผู้อ่าน) ⇒ แดง พร้อมบอกว่าให้แก้ทะเบียน', () => {
  const r = รัน('ขัดกันเอง')
  assert.equal(r.status, 1, 'สองช่องที่เป็นไปไม่ได้พร้อมกัน ต้องถูกฟ้อง')
  assert.ok(/ขัดกันในตัวเอง/.test(r.stderr),
    'ข้อความต้องบอกว่าทะเบียนขัดกันเอง ไม่ใช่ "ค้างกับด่านที่เลิกอ่าน" — คนละที่ที่ต้องไปแก้')
})
