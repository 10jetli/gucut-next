#!/usr/bin/env node
/* 🔒 **ตรึงตัวเลขผังที่วัดมาจาก ZORT ไว้ไม่ให้หายเงียบ ๆ** (15 ต.ค. 2569)
 *
 * 🔴 ที่มา: คืนนี้แก้ผังจอขาย/จอคลังหลายรอบ **ทุกตัวเลขมาจากการวัดของจริง**
 *    (แถบเมนู 200 · เนื้อหาเริ่ม x=230 · ช่องว่างเซลล์ 8px · ปุ่มใต้หัวจอเฉพาะจอขาย)
 *    ถ้าไม่มีอะไรยืนขวาง วันหนึ่งมีคน refactor แล้วค่าเหล่านี้หายไป **โดยไม่มีใครรู้**
 *    ⇒ แล้วเราต้องไปวัดใหม่ทั้งชุดเพื่อตอบคำถามที่เทสตัวเดียวตอบได้ทุกครั้งที่ build
 *
 * ⚠️ **นี่คือด่านที่ตรึง "รูปร่างของโค้ด" ไม่ใช่ "พฤติกรรมบนจอ"** — ต้องเขียนไว้ตรง ๆ
 *    เหตุที่วัดพฤติกรรมจริงไม่ได้ในด่านนี้: ต้องเปิดเซิร์ฟเวอร์ + ล็อกอิน + เบราว์เซอร์จริง
 *    ซึ่งแพงเกินกว่าจะรันทุก build ⇒ ⇒ **ด่านนี้จับได้แค่ "ใครลบของทิ้ง"**
 *    มันจับไม่ได้ว่าจอยังเรนเดอร์ออกมาตรงเดิมไหม ⇒ **ยังต้องวัดด้วยเบราว์เซอร์เป็นระยะ**
 *    (วิธีวัดซ้ำทั้งชุดอยู่ใน `เทียบ-zort.md` — ไฟล์เดียวกับที่เก็บเลขก่อน/หลัง)
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'

const ROOT = fileURLToPath(new URL('../..', import.meta.url))
const อ่าน = (p) => readFileSync(join(ROOT, p), 'utf8')

/* ค่าที่วัดมาจาก ZORT — เปลี่ยนตัวเลขพวกนี้ได้ **ก็ต่อเมื่อวัดใหม่แล้วเท่านั้น** */
const ที่วัดมา = {
  แถบเมนู: 'md:w-[200px]',     // รายการในเมนู ZORT: x=0 กว้าง 200 (วัด 2 จอ)
  ขอบเนื้อหา: 'md:ml-[206px]', // 200 + 6 + padding เพจ 24 = เนื้อหาเริ่ม x=230 เท่า ZORT
  ช่องว่างเซลล์: 'px-2',       // ZORT paddingLeft/Right = 8px (วัด 3 จอ: Contact · Bundle · Warehouse)
}

test('แถบเมนูกว้าง 200 และเนื้อหาเริ่มที่ x=230 (วัดจาก ZORT)', () => {
  const s = อ่าน('components/layout/AppShell.tsx')
  assert.ok(s.includes(ที่วัดมา.แถบเมนู),
    `AppShell ต้องมี ${ที่วัดมา.แถบเมนู} — ZORT กว้าง 200 (วัด 15 ต.ค. 2569)`)
  assert.ok(s.includes(ที่วัดมา.ขอบเนื้อหา),
    `AppShell ต้องมี ${ที่วัดมา.ขอบเนื้อหา} — 200 + 6 + padding เพจ 24 = 230 เท่า ZORT`)
  /* 🔴 ค่าเก่าที่ผิดเพราะลืมหาร devicePixelRatio (165 × 1.25 ≈ 206 ≈ 200) ห้ามกลับมา */
  assert.ok(!s.includes('md:w-[165px]'), 'ค่า 165 มาจากการวัดภาพโดยไม่หาร dpr — ห้ามกลับมาใช้')
})

test('ช่องว่างซ้าย/ขวาของเซลล์ตาราง = 8px (px-2) ตาม ZORT', () => {
  const s = อ่าน('components/zort/index.tsx')
  for (const ชื่อ of ['TH', 'THR', 'TD', 'TDR']) {
    const m = s.match(new RegExp(`export const ${ชื่อ} = '([^']+)'`))
    assert.ok(m, `หา ${ชื่อ} ใน components/zort/index.tsx ไม่เจอ`)
    assert.ok(m[1].includes(ที่วัดมา.ช่องว่างเซลล์),
      `${ชื่อ} ต้องใช้ ${ที่วัดมา.ช่องว่างเซลล์} (ZORT 8px · วัด 3 จอ) — ได้ '${m[1]}'`)
    assert.ok(!m[1].includes('px-3'), `${ชื่อ} ยังมี px-3 (12px) ซึ่งกว้างกว่า ZORT`)
  }
})

/* 📋 **ตารางจับคู่จอ = คำตอบของคำถามที่ใช้เวลาทั้งคืนหามา** (จอไหนคู่กับจอไหน · ผังอะไร · วัดเมื่อไหร่)
   เทสอ่านจากไฟล์นั้น ⇒ เพิ่มจอใหม่ต้องไปเพิ่มในตารางพร้อมหลักฐาน **ไม่ใช่แก้เทส** */
const ตาราง = JSON.parse(อ่าน('scripts/lib/จับคู่จอ-zort.json'))

test('ทุกจอในตารางจับคู่ ตั้งผังหัวจอตรงกับที่วัดมาจาก ZORT', () => {
  assert.ok(ตาราง['คู่จอ'].length > 0, 'ตารางจับคู่ว่าง — ไม่มีอะไรให้ตรึง')
  for (const แถว of ตาราง['คู่จอ']) {
    const src = อ่าน(แถว['จอเรา'])
    const ใช้ปุ่มใต้หัวจอ = /<PageHead[\s\S]{0,200}?ปุ่มใต้หัวจอ/.test(src)
    const ควรใช้ = แถว['ผังหัวจอ'] === 'ใต้หัวจอ'
    assert.equal(ใช้ปุ่มใต้หัวจอ, ควรใช้,
      `${แถว['จอเรา']} ต้องเป็นผัง "${แถว['ผังหัวจอ']}" ตาม ${แถว['จอZORT']} ` +
      `(หลักฐาน: ${แถว['หลักฐาน']} · วัด ${แถว['วัดเมื่อ']})`)
    assert.ok(แถว['หลักฐาน'] && แถว['วัดเมื่อ'],
      `แถว ${แถว['จอเรา']} ต้องมีหลักฐานและวันที่วัด — ตารางที่ไม่มีหลักฐานคือความเห็น ไม่ใช่ผลวัด`)
  }
})

test('จอที่ **ไม่อยู่ในตาราง** ต้องใช้ผังค่าเริ่มต้น (ห้ามลอกผังโดยไม่วัด)', () => {
  const ในตาราง = new Set(ตาราง['คู่จอ'].filter((r) => r['ผังหัวจอ'] === 'ใต้หัวจอ').map((r) => r['จอเรา']))
  const เปิดอยู่ = ไฟล์ที่เปิดปุ่มใต้หัวจอ()
  const เกิน = เปิดอยู่.filter((f) => !ในตาราง.has(f))
  assert.deepEqual(เกิน, [],
    `จอที่เปิด "ปุ่มใต้หัวจอ" โดยไม่มีแถวในตารางจับคู่: ${เกิน.join(' · ')}\n` +
    '   ⇒ ไปวัดจอนั้นของ ZORT ก่อน แล้วเพิ่มแถวพร้อมหลักฐาน (ไม่ใช่แก้เทส)')
  const หัวจอ = อ่าน('components/zort/index.tsx')
  assert.ok(หัวจอ.includes('ปุ่มใต้หัวจอ = false'),
    'PageHead ต้องตั้งต้นเป็น false — ZORT วางปุ่มชิดขวา 4 ใน 6 จอที่วัด')
})

/** ไฟล์ในเพจที่เปิด `ปุ่มใต้หัวจอ` — ใช้ git grep เพื่อไม่ต้องเดินต้นไม้เอง */
function ไฟล์ที่เปิดปุ่มใต้หัวจอ() {
  try {
    const out = execFileSync('git', ['grep', '-l', 'ปุ่มใต้หัวจอ', '--', 'app'],
      { cwd: ROOT, encoding: 'utf8' })
    return out.split('\n').map((x) => x.trim()).filter(Boolean)
  } catch {
    return []   // git grep คืน 1 เมื่อไม่เจอ = ไม่มีจอไหนเปิด
  }
}
