#!/usr/bin/env node
/* สถานะรายขาของผังสต็อก (`lib/flow-status.ts`) — ใบสั่ง 22 ต.ค. 13:30 "ออโต้ทั้งผัง"
 * 🔴 จุดที่พลาดแล้วเงียบ: ของผิดรูปถูกเก็บ ⇒ จอขึ้นค่าแปลกแทนที่จะแดง · ขาที่หยุดส่งหายจากจอ ·
 *    ขาที่ตายแต่ตัวส่งยังวิ่ง ⇒ ต้องแดงจากเวลาที่ตัวงานจด ไม่ใช่เวลาอัปโหลด */
import { rmSync } from 'node:fs'
import { คอมไพล์เพื่อทดสอบ } from '../lib/คอมไพล์เพื่อทดสอบ.mjs'

let ตก = 0
const ok = (ชื่อ, เงื่อนไข, เหตุ = '') => {
  console.log(`  ${เงื่อนไข ? '✅' : '❌'} ${ชื่อ}${เงื่อนไข ? '' : ` — ${เหตุ}`}`)
  if (!เงื่อนไข) { ตก++; console.log(`     🔴 ตกที่ ${ชื่อ}`) }
}

const ปลอมBlobs = `
const ของ = globalThis.__ถังflow ??= new Map()
export function getStore() {
  return {
    async get(k, o) { if (!ของ.has(k)) return null; const v = ของ.get(k); return o?.type === 'json' ? JSON.parse(v) : v },
    async setJSON(k, v) { ของ.set(k, JSON.stringify(v)) },
  }
}`

const ไฟล์ = 'lib/flow-status.ts'
let งาน
try {
  งาน = คอมไพล์เพื่อทดสอบ({ ไฟล์: [ไฟล์], ปลอม: { '@netlify/blobs': ปลอมBlobs } })
  const { ตรวจรูป, เงียบเกิน, เก็บ, อ่าน } = await import(งาน.พาธของ(ไฟล์))
  const ดี = (เมื่อ) => ({ เมื่อ, ผล: 'ok', รายละเอียด: 'x', รอบนาที: 10 })

  console.log('\n── ตรวจรูป: ของผิดรูปต้องไม่ผ่าน (ไม่งั้นจอขึ้นค่าแปลกแทนที่จะแดง) ──')
  ok('ก้อนดีผ่าน', ตรวจรูป({ ขา: { 'ทะเบียน-ZORT': ดี('2026-10-22T06:00:00Z') } }).ok === true)
  ok('ไม่มีช่อง ขา ⇒ ไม่ผ่าน', ตรวจรูป({}).ok === false)
  ok('เวลาอ่านไม่ได้ ⇒ ไม่ผ่าน', ตรวจรูป({ ขา: { a: { ...ดี(''), เมื่อ: 'เมื่อวาน' } } }).ok === false)
  ok('ผล นอกชุด ⇒ ไม่ผ่าน', ตรวจรูป({ ขา: { a: { ...ดี('2026-10-22T06:00:00Z'), ผล: 'green' } } }).ok === false)
  ok('รอบนาที 0 ⇒ ไม่ผ่าน (2×0 = แดงไม่มีวันถึง)', ตรวจรูป({ ขา: { a: { ...ดี('2026-10-22T06:00:00Z'), รอบนาที: 0 } } }).ok === false)
  ok('ชื่อขาแปลก ⇒ ไม่ผ่าน', ตรวจรูป({ ขา: { 'a<script>': ดี('2026-10-22T06:00:00Z') } }).ok === false)
  ok('ชื่อขาไทยผ่าน', ตรวจรูป({ ขา: { 'ดึงเป้าทะเบียน': ดี('2026-10-22T06:00:00Z') } }).ok === true)

  console.log('\n── เงียบเกิน: 2 เท่าของรอบตัวเอง ──')
  const t0 = Date.parse('2026-10-22T06:00:00Z')
  ok('ผ่านไป 19 นาที (รอบ 10) ⇒ ยังไม่เงียบ', เงียบเกิน(ดี('2026-10-22T06:00:00Z'), t0 + 19 * 60e3) === false)
  ok('ผ่านไป 21 นาที (รอบ 10) ⇒ เงียบ', เงียบเกิน(ดี('2026-10-22T06:00:00Z'), t0 + 21 * 60e3) === true)

  console.log('\n── เก็บ: รวมกับของเดิม — ขาที่รอบนี้ไม่ส่ง ต้องไม่หายเงียบ ──')
  await เก็บ({ a: ดี('2026-10-22T05:00:00Z'), b: ดี('2026-10-22T05:00:00Z') })
  await เก็บ({ a: ดี('2026-10-22T06:00:00Z') })
  const ก = await อ่าน()
  ok('ขา b ยังอยู่ (จะเก่าเองจนแดง ไม่ใช่หาย)', !!ก.ขา.b && ก.ขา.a.เมื่อ === '2026-10-22T06:00:00Z', JSON.stringify(ก))
} catch (e) {
  ตก++
  console.log('  ❌ เทสล้มทั้งไฟล์:', e?.stack || e)
} finally {
  if (งาน?.ที่ออก) rmSync(งาน.ที่ออก, { recursive: true, force: true })
}

console.log(ตก === 0 ? '\n✅ ผ่านหมด' : `\n❌ ตก ${ตก} ข้อ`)
process.exit(ตก === 0 ? 0 : 1)
