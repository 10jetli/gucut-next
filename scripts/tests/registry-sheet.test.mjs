#!/usr/bin/env node
/* ขาชีททะเบียน (`lib/registry-sheet.ts`) — ท่านประธานสั่ง 22 ต.ค. 2569 "ทำให้มันออโต้สิ"
 *
 * 🔴 ทำไมเทสนี้สำคัญ: ออโต้ที่ผิดจะผิด **ทุกช่องทางพร้อมกัน** (ใบสั่ง-สต็อกออโต้.md ข้อ ③)
 *    ⇒ ทุกตาข่ายต้อง **เคยถูกป้อนของเสียแล้วร้อง** ไม่ใช่แค่ผ่านตอนของดี
 * ⚠️ เรียกฟังก์ชันตัวจริงทั้งหมด · ขาเข้าคือก้อนที่ Apps Script POST มา (ท่า ads-push — เปลี่ยน 22 ต.ค. 13:39)
 */
import { rmSync } from 'node:fs'
import { คอมไพล์เพื่อทดสอบ } from '../lib/คอมไพล์เพื่อทดสอบ.mjs'

let ตก = 0
const ok = (ชื่อ, เงื่อนไข, เหตุ = '') => {
  console.log(`  ${เงื่อนไข ? '✅' : '❌'} ${ชื่อ}${เงื่อนไข ? '' : ` — ${เหตุ}`}`)
  if (!เงื่อนไข) { ตก++; console.log(`     🔴 ตกที่ ${ชื่อ}`) }
}

const ปลอมBlobs = `
const ของ = globalThis.__ถังทดสอบ ??= new Map()
export function getStore() {
  return {
    async get(k, o) { if (!ของ.has(k)) return null; const v = ของ.get(k); return o?.type === 'json' ? JSON.parse(v) : v },
    async set(k, v) { ของ.set(k, String(v)) },
    async setJSON(k, v) { ของ.set(k, JSON.stringify(v)) },
  }
}`

const ไฟล์ = 'lib/registry-sheet.ts'
let งาน
try {
  งาน = คอมไพล์เพื่อทดสอบ({ ไฟล์: [ไฟล์], ปลอม: { '@netlify/blobs': ปลอมBlobs } })
  const m = await import(งาน.พาธของ(ไฟล์))
  const { ตรวจรูปแท็บ, กุญแจตรง, สำรวจ, ลายนิ้วมือ, ลดฮวบ, รับชีท, อ่านสถานะ } = m
  const ถัง = globalThis.__ถังทดสอบ

  /* หัวคอลัมน์สมมติเพื่อทดสอบ pipeline — 🔴 ไม่ใช่หัวของชีทจริง (ยังไม่มีใครส่งมา) */
  const หัว = ['ลำดับ', 'หมายเลขซีเรียล', 'ยี่ห้อ', 'ขนาด', 'วันที่จำหน่าย', 'ผู้ซื้อ']
  const เล่ม = [
    { ชื่อ: '2566', แถว: [['บัญชีรับและจำหน่าย'], [], หัว, ['1', '', 'KINGKONG', '30', '', ''], ['2', '', 'KINGKONG', '30', '1/10/2569', '']] },
    { ชื่อ: '2567 & ใหม่', แถว: [หัว, ['1', '', 'NEWWAVE', '16', '', '']] },
  ]

  console.log('\n── ตรวจรูปก้อนที่สคริปต์ส่งมา — ของผิดรูปห้ามเข้า pipeline ──')
  ok('ก้อนดีผ่าน', ตรวจรูปแท็บ({ แท็บ: เล่ม, ชีทแก้ไขล่าสุด: '2026-10-05T13:38:44Z' }).ok === true)
  ok('ไม่มีแท็บ ⇒ ไม่ผ่าน', ตรวจรูปแท็บ({ แท็บ: [] }).ok === false)
  ok('แท็บไม่มีชื่อ ⇒ ไม่ผ่าน', ตรวจรูปแท็บ({ แท็บ: [{ แถว: [] }] }).ok === false)
  ok('แถวไม่ใช่อาร์เรย์ ⇒ ไม่ผ่าน', ตรวจรูปแท็บ({ แท็บ: [{ ชื่อ: 'x', แถว: ['abc'] }] }).ok === false)
  const ใหญ่ = ตรวจรูปแท็บ({ แท็บ: [{ ชื่อ: 'x', แถว: [['ย'.repeat(500)]] }] })
  ok('เซลล์ยาวถูกตัดที่ 120', ใหญ่.ok === true && ใหญ่.แท็บ[0].แถว[0][0].length === 120)
  const วแ = ตรวจรูปแท็บ({ แท็บ: เล่ม, ชีทแก้ไขล่าสุด: 'เมื่อวาน' })
  ok('วันที่แก้ล่าสุดอ่านไม่ได้ ⇒ ถูกทิ้ง (ไม่พัง)', วแ.ok === true && วแ.ชีทแก้ไขล่าสุด === undefined)

  console.log('\n── กุญแจเวลาคงที่ (ท่า ads-push) ──')
  ok('กุญแจตรง ⇒ true', กุญแจตรง('abc123', 'abc123') === true)
  ok('กุญแจผิด ⇒ false', กุญแจตรง('abc124', 'abc123') === false)
  ok('ว่างทั้งคู่ ⇒ false (ไม่ตั้งกุญแจ = ปิด ไม่ใช่เปิด)', กุญแจตรง('', '') === false)
  ok('ไม่ใช่สตริง ⇒ false', กุญแจตรง(undefined, 'abc') === false)

  console.log('\n── สำรวจ: เก็บแค่แถวหัว ห้ามเก็บแถวข้อมูล ──')
  const ส = สำรวจ(เล่ม)
  ok('เจอแถวหัวที่แถว 3 ของแท็บแรก', ส[0].แถวหัว === 3, JSON.stringify(ส[0]))
  ok('นับแถวมีของหลังหัว 2', ส[0].แถวมีของหลังหัว === 2, JSON.stringify(ส[0]))
  ok('ผลสำรวจไม่มีค่าจากแถวข้อมูล', !JSON.stringify(ส).includes('KINGKONG'), JSON.stringify(ส))
  const เล่ม2 = [{ ...เล่ม[0], แถว: [เล่ม[0].แถว[0], [], [...หัว.slice(0, 3), 'ความยาว', ...หัว.slice(4)], ...เล่ม[0].แถว.slice(3)] }, เล่ม[1]]
  ok('หัวเปลี่ยนหนึ่งคำ ⇒ ลายนิ้วมือเปลี่ยน', ลายนิ้วมือ(ส) !== ลายนิ้วมือ(สำรวจ(เล่ม2)))

  console.log('\n── ตาข่าย: ลดฮวบ ──')
  ok('รอบแรก (ไม่มีของเดิม) ⇒ ไม่ร้อง', ลดฮวบ(null, { a: 1 }).length === 0)
  ok('9 → 8 ⇒ ไม่ร้อง (ขายจริงทีละชิ้น)', ลดฮวบ({ a: 9 }, { a: 8 }).length === 0)
  ok('8 → 0 ⇒ ร้อง', ลดฮวบ({ a: 8 }, { a: 0 }).length === 1)
  ok('14 → 6 ⇒ ร้อง (ลดเกินครึ่ง)', ลดฮวบ({ a: 14 }, { a: 6 }).length === 1)
  ok('รหัสหายจากผลนับ ⇒ ร้อง (ไม่รู้ ≠ ไม่มี)', ลดฮวบ({ a: 3 }, {}).length === 1)
  ok('1 → 0 ⇒ ร้อง (เหลือ 0 ทั้งที่รอบก่อนมี)', ลดฮวบ({ a: 1 }, { a: 0 }).length === 1)

  console.log('\n── รับชีท: pipeline จริงกับถังปลอม ──')
  let r = await รับชีท(เล่ม, '2026-10-05T13:38:44Z')
  ok('ยังไม่มีกติกานับ ⇒ สำรวจ · ไม่ผลิตเป้า', r.สถานะ === 'สำรวจ' && !r.stocks && !ถัง.has('latest'), JSON.stringify(r).slice(0, 200))
  ok('รอบสำรวจจดหัวคอลัมน์ไว้ให้คนดู', r.สำรวจ?.[0]?.หัว?.includes('หมายเลขซีเรียล'), JSON.stringify(r.สำรวจ))
  ok('รอบสำรวจไม่ล็อก layout (ล็อกเฉพาะตอนผลิตเป้า)', !ถัง.has('layout'))
  r = await รับชีท(เล่ม2)
  ok('หัวเปลี่ยนแต่ยังไม่เคยล็อก ⇒ ยังเป็นสำรวจ (ไม่ใช่หยุด)', r.สถานะ === 'สำรวจ', JSON.stringify(r).slice(0, 150))
  const สถ = await อ่านสถานะ()
  ok('ทุกรอบถูกจด ใหม่สุดก่อน · ไม่มี latest', สถ.log.length === 2 && สถ.log[0].สถานะ === 'สำรวจ' && สถ.latest === null, JSON.stringify(สถ.log.map((x) => x.สถานะ)))
} catch (e) {
  ตก++
  console.log('  ❌ เทสล้มทั้งไฟล์:', e?.stack || e)
} finally {
  if (งาน?.ที่ออก) rmSync(งาน.ที่ออก, { recursive: true, force: true })
}

console.log(ตก === 0 ? '\n✅ ผ่านหมด' : `\n❌ ตก ${ตก} ข้อ`)
process.exit(ตก === 0 ? 0 : 1)
