#!/usr/bin/env node
/* ที่มาของเลขสต็อกบนจอ — ทดสอบ **ตัวตัดสิน** ของจริง (คอมไพล์ components/ui/StockSource.tsx ด้วย tsc)
 * (ใบ t_mul363qv · 28 ก.ย. 2569 · ฝั่งท่อเติมสามช่องให้ทุกแถวของ ?list=stock)
 *
 * 🔒 สามข้อที่ฝั่งท่อกำกับมา เทสนี้บังคับทั้งสามข้อ
 *    ① ใช้ `srcNote` ของท่อ **ห้ามจอแปลเอง** ⇒ ผลลัพธ์ต้องคืนข้อความของท่อตรงตัวอักษร
 *       และค่าที่ท่อไม่ได้ส่งคำอธิบาย (mirror) ต้องออกมาเป็น **ค่าดิบ** ไม่ใช่คำไทยที่เราคิดขึ้น
 *    ② ช่องนี้บอกแหล่งของตัวเลข ไม่ได้บอกว่าเลขถูกหรือผิด ⇒ ห้ามมีคำตัดสินความถูกต้องในผล
 *    ③ เพิ่มช่องอย่างเดียว ⇒ แถวจากท่อรุ่นเก่า (ไม่มีสามช่องนี้) ต้องได้สถานะ "ท่อไม่ส่ง"
 *       **ไม่ใช่เงียบ และไม่ใช่เดาว่าเป็น mirror** — ความเงียบจะถูกอ่านว่า "มาจากทางปกติ"
 *
 * 🔑 ตัวตัดสินถูกแยกออกจาก JSX เพื่อให้ทดสอบ **พฤติกรรม** ได้ ไม่ใช่ตรึงรูปร่างโค้ด
 */
import { execFileSync } from 'node:child_process'
import { mkdtempSync, rmSync, readFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const out = mkdtempSync(join(tmpdir(), `stock-source-${process.pid}-`))
let ตก = 0
const ok = (ชื่อ, เงื่อนไข, เหตุ = '') => {
  console.log(`  ${เงื่อนไข ? '✅' : '❌'} ${ชื่อ}${เงื่อนไข ? '' : ` — ${เหตุ}`}`)
  if (!เงื่อนไข) ตก++
}

try {
  /* คอมไพล์ **ไฟล์ตรรกะล้วน** ⇒ ไม่ต้องหา react ⇒ คอมไพล์ลงที่ชั่วคราวนอกโปรเจกต์ได้
     (ถ้าคอมไพล์ .tsx จะต้องวางผลลัพธ์ในโปรเจกต์เพื่อให้หา react เจอ = ทิ้งของค้างไว้ในรีโป) */
  execFileSync('npx', ['tsc', 'lib/stock-source.ts', '--outDir', out,
    '--module', 'es2022', '--target', 'es2022', '--moduleResolution', 'bundler', '--skipLibCheck'],
    { stdio: 'pipe' })
  const { ตัดสินที่มา, อ่านที่มา } = await import(join(out, 'stock-source.js'))

  console.log('① แถวจากท่อรุ่นเก่า (ไม่มีช่อง) ⇒ ต้องบอกว่าท่อไม่ส่ง ห้ามเดาว่าเป็นทางปกติ')
  {
    ok('ไม่มีช่องเลย', ตัดสินที่มา({ sku: 'X', available: 3 }).แบบ === 'ท่อไม่ส่ง',
      JSON.stringify(ตัดสินที่มา({ sku: 'X' })))
    ok('row เป็น null', ตัดสินที่มา(null).แบบ === 'ท่อไม่ส่ง')
    ok('src เป็นสตริงว่าง', ตัดสินที่มา({ src: '' }).แบบ === 'ท่อไม่ส่ง')
    ok('ไม่เดาว่าเป็น mirror', ตัดสินที่มา(null).src === undefined, 'เติมค่า src ให้เองไม่ได้')
  }

  console.log('② แถว licensed ⇒ ใช้ข้อความของท่อตรงตัวอักษร + เลขที่ทะเบียนถืออยู่')
  {
    const note = 'ทะเบียนใบอนุญาตทับ ZORT โดยตั้งใจ — เลื่อย/บาร์นับเป็นเลขซีเรียล'
    const ผล = ตัดสินที่มา({ src: 'licensed', srcNote: note, 'ทะเบียนว่า': 7 })
    ok('รู้ว่ามีคำอธิบายจากท่อ', ผล.แบบ === 'มีคำอธิบายจากท่อ', ผล.แบบ)
    ok('ข้อความตรงตัวอักษร ไม่ถูกจอเขียนใหม่', ผล.note === note, ผล.note)
    ok('ส่งเลขทะเบียนต่อให้จอ', ผล['ทะเบียนว่า'] === 7, String(ผล['ทะเบียนว่า']))
  }

  console.log('③ แถว mirror (ท่อไม่ส่งคำอธิบาย) ⇒ ต้องเป็นค่าดิบ ห้ามมีคำแปลของจอ')
  {
    const ผล = ตัดสินที่มา({ src: 'mirror' })
    ok('เป็นค่าดิบ', ผล.แบบ === 'ค่าดิบไม่มีคำอธิบาย', ผล.แบบ)
    ok('คืนค่าดิบตามที่ท่อส่ง', ผล.src === 'mirror', ผล.src)
  }

  console.log('④ ค่าที่ยังไม่รู้จัก (ท่อเพิ่มชนิดใหม่ในอนาคต) ⇒ ต้องโชว์ดิบ ไม่ใช่ตกลงถังผิด')
  {
    const ผล = ตัดสินที่มา({ src: 'คลังใหม่ที่ยังไม่มีใครรู้จัก' })
    ok('ไม่กลายเป็น "ท่อไม่ส่ง"', ผล.แบบ === 'ค่าดิบไม่มีคำอธิบาย', ผล.แบบ)
    ok('ค่าดิบมาครบ', ผล.src === 'คลังใหม่ที่ยังไม่มีใครรู้จัก', ผล.src)
  }

  console.log('⑤ ทะเบียนว่า: ไม่ใช่ตัวเลข ⇒ ต้องเป็น null (ไม่รู้) ไม่ใช่ 0')
  {
    ok('undefined ⇒ null', อ่านที่มา({ src: 'licensed' })['ทะเบียนว่า'] === null)
    ok('สตริง ⇒ null ไม่ใช่ NaN/0', อ่านที่มา({ src: 'licensed', 'ทะเบียนว่า': 'เจ็ด' })['ทะเบียนว่า'] === null)
    ok('0 ยังเป็น 0 (ของหมดจริง ≠ ไม่รู้)', อ่านที่มา({ src: 'licensed', 'ทะเบียนว่า': 0 })['ทะเบียนว่า'] === 0)
  }

  console.log('⑧ แผนที่ป้ายจากท่อ (srcLabels) ⇒ mirror ต้องมีคำไทยแล้ว และต้องเป็นคำของท่อ')
  {
    const ป้าย = {
      mirror: { 'ป้าย': 'จากกระจก ZORT', 'อธิบาย': 'มาจากภาพถ่ายคลังเงาที่คัดจาก ZORT' },
      licensed: { 'ป้าย': 'จากทะเบียนใบอนุญาต', 'อธิบาย': 'ทับ ZORT โดยตั้งใจ' },
    }
    const ผล = ตัดสินที่มา({ src: 'mirror' }, ป้าย)
    ok('mirror เลิกเป็นค่าดิบเมื่อมีแผนที่ป้าย', ผล.แบบ === 'มีคำอธิบายจากท่อ', ผล.แบบ)
    ok('ใช้คำของท่อทั้งป้ายและคำอธิบาย',
      ผล.note.includes('จากกระจก ZORT') && ผล.note.includes('ภาพถ่ายคลังเงา'), ผล.note)
  }

  console.log('⑨ แผนที่ป้ายมาก่อน srcNote ของแถว (กันคำอธิบายสองชุดในระบบ)')
  {
    const ป้าย = { licensed: { 'ป้าย': 'จากทะเบียนใบอนุญาต', 'อธิบาย': 'คำของท่อรุ่นใหม่' } }
    const ผล = ตัดสินที่มา({ src: 'licensed', srcNote: 'คำเก่าที่ติดมากับแถว' }, ป้าย)
    ok('ใช้คำจากแผนที่ป้าย', ผล.note.includes('คำของท่อรุ่นใหม่'), ผล.note)
    ok('ไม่ใช้คำเก่าที่ติดมากับแถว', !ผล.note.includes('คำเก่าที่ติดมากับแถว'), ผล.note)
  }

  console.log('⑩ ค่าที่ไม่มีในแผนที่ป้าย ⇒ ตกไปใช้ srcNote · ไม่มีทั้งคู่ ⇒ ค่าดิบ ห้ามแปลเอง')
  {
    const ป้าย = { mirror: { 'ป้าย': 'จากกระจก ZORT' } }
    const ก = ตัดสินที่มา({ src: 'คลังใหม่', srcNote: 'ท่ออธิบายมากับแถว' }, ป้าย)
    ok('ตกไปใช้ srcNote', ก.แบบ === 'มีคำอธิบายจากท่อ' && ก.note === 'ท่ออธิบายมากับแถว', JSON.stringify(ก))
    const ข = ตัดสินที่มา({ src: 'คลังใหม่' }, ป้าย)
    ok('ไม่มีทั้งคู่ ⇒ ค่าดิบ', ข.แบบ === 'ค่าดิบไม่มีคำอธิบาย' && ข.src === 'คลังใหม่', JSON.stringify(ข))
    const ค = ตัดสินที่มา({ src: 'mirror' }, { mirror: { 'ป้าย': '   ' } })
    ok('ป้ายที่เป็นช่องว่าง ไม่นับว่ามีคำอธิบาย', ค.แบบ === 'ค่าดิบไม่มีคำอธิบาย', JSON.stringify(ค))
  }

  console.log('⑥ ห้ามมีคำตัดสินว่าเลขไหนถูก/ผิด ในข้อความที่จอเขียนเอง')
  {
    /* ⚠️ ข้อนี้ตรวจ **ข้อความที่จอเขียนเอง** ในไฟล์ชิ้นส่วน — พฤติกรรมวัดไม่ได้เพราะเป็นตัวหนังสือคงที่
       (คำที่มาจากท่อไม่นับ เพราะท่อเป็นคนเขียนและเป็นเจ้าของความหมาย) */
    const ซอร์ส = readFileSync('components/ui/StockSource.tsx', 'utf8')
      + readFileSync('lib/stock-source.ts', 'utf8')
    const เนื้อที่จอเขียน = ซอร์ส.split('\n').filter((l) => !l.trim().startsWith('//') && !l.trim().startsWith('*')
      && !l.trim().startsWith('/*')).join('\n')
    const คำตัดสิน = ['เลขนี้ถูก', 'เลขนี้ผิด', 'ค่าที่ถูกต้องคือ', 'เชื่อเลขนี้', 'ห้ามเชื่อ']
    const เจอ = คำตัดสิน.filter((c) => เนื้อที่จอเขียน.includes(c))
    ok('ไม่มีคำตัดสินความถูกต้องของตัวเลข', เจอ.length === 0, เจอ.join(' · '))
  }

  console.log('⑦ ทั้งสองจอต้องเรียกชิ้นส่วนนี้จริง (ชิ้นส่วนที่ไม่มีใครเรียก = ไม่มีอยู่บนจอ)')
  {
    for (const จอ of ['app/core/stock/[sku]/page.tsx', 'app/core/stock-stuck/page.tsx']) {
      const t = readFileSync(จอ, 'utf8')
      ok(`${จอ} เรียก <StockSource`, /<StockSource[\s/>]/.test(t) && t.includes("@/components/ui/StockSource"))
    }
  }
} finally {
  rmSync(out, { recursive: true, force: true })
}

console.log(ตก ? `\n❌ ไม่ผ่าน ${ตก} ข้อ` : '\n✅ ผ่านทุกข้อ')
process.exit(ตก ? 1 : 0)
