#!/usr/bin/env node
/* ขอบเขตการกรองในเบราว์เซอร์ (`lib/client-filter-scope.ts`) — 15 ต.ค. 2569
 * 🔑 CEO ขอ: เทสต้อง **ปลูก ยอดรวม > ที่โหลด** แล้วยืนยันว่าจอลดเกียรติตัวเองอย่างซื่อสัตย์
 *    เทสแบบ "กรองถูกเมื่อโหลดครบ" จะเขียวตลอดไปจนวันที่ของจริงพัง ⇒ ไม่นับเป็นตาข่าย */
import { ขอบเขตกรองในเครื่อง } from '../../lib/client-filter-scope.ts'

let ตก = 0
const ok = (ชื่อ, เงื่อนไข, เหตุ = '') => {
  console.log(`  ${เงื่อนไข ? '✅' : '❌'} ${ชื่อ}${เงื่อนไข ? '' : ` — ${เหตุ}`}`)
  if (!เงื่อนไข) { ตก++; console.log(`     🔴 ตกที่ ${ชื่อ}`) }
}
const ก = (โหลดมา, ทั้งหมด, offset = 0) => ขอบเขตกรองในเครื่อง({ โหลดมา, ทั้งหมด, offset })

console.log('① วันนี้: 33 ใบ โหลดครบ ⇒ ครบ')
ok('33/33 ⇒ ครบ', ก(33, 33).ขอบเขต === 'ครบ')
ok('ไม่เจอ ⇒ พูดว่าทั้งชุดไม่มี (ได้ เพราะดูครบแล้ว)', ก(33, 33).ไม่เจอ.includes('ไม่มีใบไหนตรง'))

console.log('② 🔴 ปีหน้า: 500 ใบ โหลดหน้าแรก 50 ⇒ ต้องลดเกียรติตัวเอง')
const ปีหน้า = ก(50, 500)
ok('50/500 ⇒ ไม่ครบ', ปีหน้า.ขอบเขต === 'ไม่ครบ', ปีหน้า.ขอบเขต)
ok('บรรทัดบอกทั้งสองเลข', ปีหน้า.บรรทัด.includes('50') && ปีหน้า.บรรทัด.includes('500'), ปีหน้า.บรรทัด)
ok('ไม่เจอ ⇒ ห้ามพูดว่าไม่มี', !ปีหน้า.ไม่เจอ.includes('ไม่มีใบไหนตรง') && ปีหน้า.ไม่เจอ.includes('ยังบอกไม่ได้ว่าไม่มี'), ปีหน้า.ไม่เจอ)

console.log('③ 🔴 หน้าสุดท้าย: offset 450 โหลด 50 จาก 500 ⇒ ไม่ครบ (รูเดิม: offset+โหลด ≥ ทั้งหมด ⇒ ครบ)')
ok('offset 450 · 50/500 ⇒ ไม่ครบ', ก(50, 500, 450).ขอบเขต === 'ไม่ครบ', ก(50, 500, 450).ขอบเขต)

console.log('⑤ ตัวควบคุมบวกด้วยเลขจริง: ผู้ติดต่อ 28,479 แถว หน้าละ 50 ⇒ ต้อง ไม่ครบ ทุกหน้า')
for (const off of [0, 50, 28450]) ok(`ผู้ติดต่อ offset ${off} ⇒ ไม่ครบ`, ก(off === 28450 ? 29 : 50, 28479, off).ขอบเขต === 'ไม่ครบ')

console.log('④ ท่อไม่บอกยอดรวม ⇒ ไม่รู้ (ห้ามถือว่าครบ)')
for (const [ป, ค่า] of [['undefined', undefined], ['null', null], ['สตริง', '33'], ['NaN', NaN]]) {
  ok(`ทั้งหมด = ${ป} ⇒ ไม่รู้`, ก(33, ค่า).ขอบเขต === 'ไม่รู้', ก(33, ค่า).ขอบเขต)
}
ok('ไม่รู้ ⇒ ไม่เจอห้ามพูดว่าไม่มี', ก(33, null).ไม่เจอ.includes('บอกไม่ได้ว่าไม่มีจริง'))

console.log(ตก ? `\n🔴 ตก ${ตก} ข้อ` : '\n✅ ผ่านทุกข้อ')
process.exit(ตก ? 1 : 0)
