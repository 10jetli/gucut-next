/* ด่าน: สารบัญท่อมี **สองอายุ** — ชั้นนอกกับก้อนข้างใน และก้อนข้างในเก่ากว่าได้
 *
 * 🔴 ของจริง 14 ต.ค. 2569: `lib/pipe-snapshot.json`
 *      ชั้นนอก `ดึงเมื่อ` = 12 ต.ค. (1.8 วัน · สดตามเกณฑ์ 7)
 *      └ `endpoints.returnedFields.ดึงเมื่อ` = 18 ก.ย. (**25.3 วัน** · เกินเกณฑ์)
 *    ตัวบอกอายุเดิมอ่านชั้นนอกตัวเดียว ⇒ พิมพ์ว่า "สด" ทั้งที่ก้อนที่จะเอาไปใช้เก่ากว่า 23 วัน
 *    🔑 คลาส: **เมตาดาต้าของภาชนะ ไม่ใช่ข้อมูลข้างใน**
 *    📌 วันที่เจอมันยังไม่กัด (ไม่มีด่านไหนตัดสินจากก้อนนั้น) ⇒ ปิดก่อนมีคนเหยียบ
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'
import { อายุรายก้อน, อายุของสารบัญ, เทียบรุ่นสารบัญ } from '../lib/อายุสารบัญ.mjs'

const ROOT = fileURLToPath(new URL('../..', import.meta.url))
const วัน = (n) => new Date(Date.now() - n * 86_400_000).toISOString()

test('ก้อนที่เก่ากว่าเกณฑ์ต้องถูกฟ้อง แม้ชั้นนอกจะสด', () => {
  const snap = {
    'ดึงเมื่อ': วัน(1), 'เตือนเมื่อเกินวัน': 7,
    endpoints: { สด: { 'ดึงเมื่อ': วัน(2) }, เก่า: { 'ดึงเมื่อ': วัน(26) } },
  }
  assert.equal(อายุของสารบัญ(snap).เก่าเกิน, false, 'ชั้นนอกสด — นี่คือเหตุที่ของเดิมเงียบ')
  const เกิน = อายุรายก้อน(snap).filter((x) => x.เก่าเกิน).map((x) => x.ชื่อ)
  assert.deepEqual(เกิน, ['เก่า'], 'ก้อนที่เก่าเกินเกณฑ์ต้องโผล่ และก้อนที่สดต้องไม่โผล่ (เสียงหอนทำให้คนเลิกอ่าน)')
})

test('ก้อนที่ไม่มี `ดึงเมื่อ` ของตัวเอง = ไม่ต้องตรวจ (มันใช้วันของชั้นนอก)', () => {
  const snap = { 'ดึงเมื่อ': วัน(1), endpoints: { ปกติ: { a: 1 }, ว่าง: null, ข้อความ: 'x' } }
  assert.deepEqual(อายุรายก้อน(snap), [], 'ไม่มีวันของตัวเอง ⇒ ไม่ใช่สองอายุ ⇒ ไม่ต้องพูด')
})

test('วันที่อ่านไม่ได้ ⇒ **ไม่รู้** ห้ามเงียบและห้ามนับว่าสด', () => {
  const snap = { 'ดึงเมื่อ': วัน(1), endpoints: { พัง: { 'ดึงเมื่อ': 'เมื่อวานนี้' } } }
  const r = อายุรายก้อน(snap)
  assert.equal(r.length, 1)
  assert.equal(r[0].ไม่รู้, true, 'อ่านวันที่ไม่ได้ ≠ สด')
})

test('🔴 ของจริงในรีโปตอนนี้: ก้อน `returnedFields` ต้องถูกฟ้องว่าเก่ากว่าตัวไฟล์', () => {
  /* ⚠️ เทสนี้ผูกกับ **สภาพจริงของไฟล์** โดยตั้งใจ — วันที่ฝั่งท่อดึงสารบัญใหม่
     มันจะเลิกฟ้องเอง และนั่นคือสิ่งที่ถูก (ด่านที่เงียบตอนของถูกแก้ให้ถูก = ด่านที่ดี)
     ⇒ ถ้าวันหนึ่งไม่มีก้อนไหนเกินเกณฑ์เลย เทสนี้ต้องยังผ่าน จึงเขียนเป็น "ถ้ามีก้อนเกิน ต้องมีข้อมูลครบ" */
  const snap = JSON.parse(readFileSync(join(ROOT, 'lib/pipe-snapshot.json'), 'utf8'))
  const เกิน = อายุรายก้อน(snap).filter((x) => x.เก่าเกิน || x.ไม่รู้)
  for (const x of เกิน) {
    assert.ok(x.ชื่อ && x.ดึงเมื่อ, 'ก้อนที่ฟ้องต้องบอกชื่อและวันของตัวเอง ไม่งั้นคนไปแก้ไม่ถูกจุด')
  }
  const ชั้นนอกสด = อายุของสารบัญ(snap).เก่าเกิน === false
  if (ชั้นนอกสด && เกิน.length > 0) {
    assert.ok(เกิน.some((x) => x.ชื่อ === 'returnedFields'),
      'ชั้นนอกสดแต่มีก้อนเก่า ⇒ ต้องมี returnedFields อยู่ในรายการ (ของจริงที่เจอ 14 ต.ค.)')
  }
})

/* ══ 🔑 **อายุเป็นตัวแทน · รุ่นเป็นของจริง** (ฝั่งท่อชี้ 14 ต.ค. 2569) ═══════════════
   ตัวแทนผิดสองทิศ: เก่าแต่ท่อไม่เคยเปลี่ยน = ยังถูก (แดงลวง) ·
   ดึงมานาทีเดียวแล้วท่อ deploy = ชั้นนอกสดแต่เนื้อผิด (เขียวลวง)
   📏 ของจริงบนไฟล์เราเอง: ชั้นนอก "สด 1.8 วัน" แต่สำรวจท่อคนละรุ่นกับที่วิ่งอยู่ */

test('ไม่ส่งรุ่นที่วิ่งอยู่มา ⇒ ทุกก้อนต้องเป็น **บอกไม่ได้ (null)** ห้ามเป็น true', () => {
  const snap = { 'ท่อสร้างเมื่อ': 'A', endpoints: { ก: { 'ดึงเมื่อ': 'x', 'ท่อสร้างเมื่อ': 'A' } } }
  for (const x of เทียบรุ่นสารบัญ(snap, null)) {
    assert.equal(x.ตรงกัน, null, 'ไม่มีของมาเทียบ = ไม่รู้ · ถ้าตกเป็น true คือเขียวลวงทั้งด่าน')
  }
})

test('รุ่นตรงกัน ⇒ true · รุ่นต่างกัน ⇒ false (แยกกันให้ขาด)', () => {
  const snap = { 'ท่อสร้างเมื่อ': 'A', endpoints: { เก่า: { 'ดึงเมื่อ': 'x', 'ท่อสร้างเมื่อ': 'B' } } }
  const ได้ = Object.fromEntries(เทียบรุ่นสารบัญ(snap, 'A').map((x) => [x.ชื่อ, x.ตรงกัน]))
  assert.equal(ได้['(ชั้นนอก)'], true)
  assert.equal(ได้['เก่า'], false, 'ก้อนที่สำรวจคนละรุ่นต้องถูกฟ้อง แม้ชั้นนอกจะตรง')
})

test('🔴 ก้อนที่ **ไม่ได้จดรุ่น** ⇒ บอกไม่ได้ (null) ห้ามนับว่าตรง', () => {
  const snap = { 'ท่อสร้างเมื่อ': 'A', endpoints: { ไม่จด: { 'ดึงเมื่อ': 'x' } } }
  const ได้ = Object.fromEntries(เทียบรุ่นสารบัญ(snap, 'A').map((x) => [x.ชื่อ, x.ตรงกัน]))
  assert.equal(ได้['ไม่จด'], null,
    'ไม่มีช่องรุ่น = อายุคือทั้งหมดที่เรารู้ ⇒ ต้องพูดออกมา ไม่ใช่เงียบแล้วให้คนอ่านว่าตรง')
})

test('ของจริงในรีโป: ชั้นนอกจดรุ่นไว้เป็นข้อความ (ถ้าไม่จด ด่านจะบอกรุ่นไม่ได้เลย)', () => {
  const snap = JSON.parse(readFileSync(join(ROOT, 'lib/pipe-snapshot.json'), 'utf8'))
  const ชั้นนอก = เทียบรุ่นสารบัญ(snap, 'ของปลอม').find((x) => x.ชื่อ === '(ชั้นนอก)')
  assert.equal(typeof ชั้นนอก.จด, 'string', 'ตัวดึงสารบัญต้องจด `ท่อสร้างเมื่อ` ไว้เสมอ')
  assert.equal(ชั้นนอก.ตรงกัน, false, 'เทียบกับรุ่นปลอมต้องได้ false — พิสูจน์ว่าตัวเทียบทำงาน ไม่ใช่คืน null ตลอด')
})
