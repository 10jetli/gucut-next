/* 🔎 **ตัวชี้เป้า ไม่ใช่ด่านบังคับ** — ประตูที่คุมของซึ่งอาจไม่ได้มาจากเส้นเดียวกับมัน
 *
 * ⚠️ **จงใจไม่ต่อเข้าสาย prebuild** (ตัดสิน 18 ก.ย. 2569) เหตุผลตรง ๆ:
 *    ตัวนี้แยกไม่ออกระหว่าง "การ์ดที่คำนวณจากข้อมูลชุดเดียวกัน" กับ "การ์ดที่มาจากคนละเส้น"
 *    ⇒ ของจริงในโปรเจกต์ตอนนี้ร้อง 13 จุด ซึ่งส่วนใหญ่เป็นของปกติ
 *    ⇒ ถ้าเอาไปบังคับ build จะถูกปิดทิ้งภายในวันเดียว แล้ววันที่มีเคสจริงก็จะไม่มีใครฟัง
 *    (กติกาของบ้านนี้: ด่านที่ร้องใส่ของปกติ = ด่านที่จะถูกปิด · ด่านที่เขียวเสมอ = แย่กว่าไม่มี)
 *  ⇒ ใช้เป็น **รายการให้คนไล่ดู** เวลาสงสัยว่าของบนจอหายโดยไม่มีสาเหตุ
 *    `node scripts/check-gate-source.mjs`
 *
 * เดิมตั้งใจทำเป็นด่าน: **ประตูที่คุมของซึ่งไม่ได้มาจากเส้นเดียวกับมัน**
 *
 * 🔴 **คลาสนี้เจอ 3 รอบใน 2 วัน** (17–18 ก.ย. 2569) ⇒ CEO เสนอให้ทำเป็นด่าน:
 *   ① จอมาร์เก็ตเพลส: ทั้งใบคุมด้วย `itemsWithStock` ตัวเดียว ⇒ กองอื่นหายทั้งที่มีข้อมูล
 *   ② จอ /core/usage: การ์ดเครดิตถูกคุมด้วยผลของเส้น `usage=1` ซึ่งใช้ **คีย์คนละใบ**
 *      ⇒ คีย์ตัวนั้นยังไม่ได้ตั้ง การ์ดเลยหายทั้งที่อ่านเครดิตได้ปกติ
 *   ③ จอสินค้า: ป้าย "กรองหมวด" ขึ้น แต่คำขอไม่มีหมวด (คนละอาการ แต่รากเดียวกัน:
 *      สิ่งที่คนเห็น กับสิ่งที่ตัดสินจริง มาคนละที่)
 *
 * 🔑 **รูปที่ด่านนี้จับ**: `{X && ( …เนื้อหาที่ไม่เคยพูดถึง X เลย… )}`
 *    ถ้าเนื้อหาข้างในไม่เคยใช้ `X` แปลว่า X ไม่ได้เป็นเจ้าของข้อมูลในนั้น
 *    ⇒ วันที่ X หายไปด้วยเหตุของมันเอง ของข้างในจะหายตามโดยไม่มีใครตั้งใจ
 *
 * ⚠️ **ไม่ใช่ทุกกรณีคือบั๊ก** — บางประตูตั้งใจคุมด้วย "โหลดเสร็จหรือยัง"
 *    ⇒ ของแบบนั้นใส่ `ยกเว้น` พร้อมเหตุผล **ที่ตรวจแล้ว** ห้ามใส่เพราะอยากให้ด่านเขียว
 * ⚠️ ด่านนี้ดูเฉพาะรูปแบบ `{ชื่อ && (` ที่ขึ้นบรรทัดใหม่ · รูปอื่นยังต้องกวาดด้วยมือ
 */
import { readdirSync, readFileSync, statSync } from 'node:fs'
import { join } from 'node:path'
import { ต้องมีของให้ตรวจ } from './lib/ต้องมีของให้ตรวจ.mjs'

const ROOT = new URL('..', import.meta.url).pathname

/** ประตูที่ตรวจแล้วว่าตั้งใจ — คีย์คือ `ไฟล์:ชื่อตัวแปรประตู` */
/* 🔴 **ห้ามใส่ข้อยกเว้นเพราะอยากให้ด่านเขียว** — ผมทำพลาดแบบนั้นตอนเขียนไฟล์นี้:
   ใส่ `app/core/usage/page.tsx:d` ไว้ แล้วพอ**ปลูกบั๊กเดิมกลับเข้าไปทดสอบ ด่านก็ไม่จับ**
   เพราะข้อยกเว้นของผมเองกลืนเคสที่ด่านนี้มีไว้จับพอดี
   ⇒ ข้อยกเว้นต้องระบุให้แคบที่สุด และต้องทดสอบซ้ำหลังใส่ทุกครั้ง */
const ยกเว้น = {}

/** ตัวแปรที่เป็น "สถานะจอ" ไม่ใช่ก้อนข้อมูล ⇒ ประตูแบบนี้ปกติ */
const สถานะจอ = new Set([
  'loading', 'error', 'open', 'show', 'showScript', 'busy', 'saving', 'sending',
  'copied', 'edit', 'editing', 'picked', 'sel', 'menu', 'expanded', 'collapsed',
  'notDeployed', 'ok', 'done', 'ready', 'canAdv', 'isAdmin', 'canWrite',
])

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    const st = statSync(p)
    if (st.isDirectory()) { if (name !== 'node_modules' && name !== '.next') walk(p, out) }
    else if (name.endsWith('.tsx')) out.push(p)
  }
  return out
}

/** หาช่วงของบล็อกด้วยการนับวงเล็บ — ห้ามใช้ regex หาตัวปิด (บทเรียน 18 ก.ย. 2569) */
function ช่วงบล็อก(src, เริ่ม) {
  let i = src.indexOf('(', เริ่ม)
  if (i < 0) return null
  let ลึก = 0
  for (; i < src.length; i++) {
    if (src[i] === '(') ลึก++
    else if (src[i] === ')') { ลึก--; if (ลึก === 0) return [เริ่ม, i] }
  }
  return null
}

const พบ = []
/* 🔒 ไม่มีไฟล์ให้ตรวจ = ไม่ผ่าน (งาน S2 · 18 ก.ย. 2569) */
const ไฟล์ที่ตรวจ = walk(join(ROOT, 'app')).concat(walk(join(ROOT, 'components')))
ต้องมีของให้ตรวจ(ไฟล์ที่ตรวจ.length, 'check-gate-source')
for (const file of ไฟล์ที่ตรวจ) {
  const rel = file.slice(ROOT.length).replace(/^\/+/, '')
  const src = readFileSync(file, 'utf8')
  /* จับเฉพาะรูป `{ชื่อ && (` และ `{ชื่อ?.ช่อง && (` ที่ตามด้วยบล็อกหลายบรรทัด */
  for (const m of src.matchAll(/\{\s*([^{}()\n]{1,120}?)\s*&&\s*\(/g)) {
    const ข้อความประตู = m[1]
    /* 🔑 **จับเฉพาะประตูที่เป็น "ก้อนข้อมูล" ไม่ใช่ธงบูลีน** (แก้หลังวัดอัตราจับผิด 18 ก.ย. 2569)
       รุ่นแรกจับทุกชื่อ ⇒ ได้ 16 จุด ซึ่ง **ส่วนใหญ่เป็นธงที่คำนวณมาจากข้อมูลชุดเดียวกัน**
       (`truncated` · `hasZero` · `notFound` · `showForm`) — ธงพวกนี้ไม่ถูกอ้างข้างในเป็นเรื่องปกติ
       ⇒ ด่านที่ร้องใส่ของปกติ 16 จุด จะถูกปิดทิ้งภายในวันเดียว แล้วเคสจริงจะรอดไปด้วย
       ⇒ เงื่อนไขใหม่: ประตูต้องมีการ **อ่านช่องของก้อน** (`x.y` หรือ `x?.y`) ถึงจะนับว่าเป็นก้อนข้อมูล */
    /* ⚠️ **ข้าม `.length`** — ประตูแบบ `rows.length === 0 && (…จอว่าง…)` เป็นการเช็คจำนวน
       ไม่ใช่การคุมด้วยก้อนข้อมูลคนละเส้น · วัดจริง 18 ก.ย. 2569: รูปนี้เป็นผลบวกลวง 3 ใน 6 จุด */
    const รากในประตู = [...ข้อความประตู.matchAll(/\b([A-Za-z_$][\w$]*)\??\.([A-Za-z_$][\w$]*)/g)]
      .filter((x) => x[2] !== 'length')
      .map((x) => x[1])
    /* 🔴 **ห้ามคัดชื่อสั้นทิ้ง** — ของจริงในโปรเจกต์นี้ตั้งชื่อก้อนข้อมูลว่า `d` · `j` · `s`
       ตัวกรอง "ยาวอย่างน้อย 2 ตัว" ที่ผมใส่ไว้กันเสียงรบกวน **คัดเคสจริงทิ้งพอดี**
       (รู้ตอนปลูกบั๊กแล้วด่านเงียบ — ไล่ทีละชั้นถึงเจอ 18 ก.ย. 2569) */
    const ชื่อ = รากในประตู.find((x) => !สถานะจอ.has(x))
    if (!ชื่อ) continue
    if (ยกเว้น[`${rel}:${ชื่อ}`]) continue
    const ช่วง = ช่วงบล็อก(src, m.index)
    if (!ช่วง) continue
    const เนื้อ = src.slice(ช่วง[0] + m[0].length, ช่วง[1])
    if (เนื้อ.split('\n').length < 6) continue          // บล็อกสั้น ๆ ไม่ใช่เป้าของด่านนี้
    /* 🔑 **ต้องมองที่ "การ์ดซ้อนในประตู" ไม่ใช่ทั้งบล็อก** (แก้ 18 ก.ย. 2569 หลังปลูกบั๊กแล้วด่านไม่จับ)
       ของจริงที่เจอ: ประตู `d && !d.skip` คุมทั้งหน้า และ**ข้างในมีทั้งของที่ใช้ `d` จริง ๆ
       กับการ์ดเครดิตที่ใช้ `cred` ล้วน ๆ** ⇒ กฎ "ทั้งบล็อกไม่เคยใช้ประตู" จับไม่ได้เลย
       ⇒ เปลี่ยนมาไล่ประตูซ้อนข้างใน: ถ้าการ์ดซ้อนคุมด้วยก้อน `R2` และ**ทั้งการ์ดนั้นไม่เคยแตะ `R`**
         แปลว่าการ์ดนั้นไม่ได้เป็นของเส้นเดียวกับประตูชั้นนอก แต่ถูกประตูชั้นนอกคุมชีวิตอยู่ */
    for (const ใน of เนื้อ.matchAll(/\{\s*([^{}()\n]{1,120}?)\s*&&\s*\(/g)) {
      const รากใน = [...ใน[1].matchAll(/\b([A-Za-z_$][\w$]*)\??\.([A-Za-z_$][\w$]*)/g)]
        .filter((x) => x[2] !== 'length')
        .map((x) => x[1])
      /* การ์ดมักคุมด้วยชื่อเปล่า ๆ เช่น `{cred && (` ⇒ ต้องรับรูปนี้ด้วย
         (ตอนทดสอบด้วยการปลูกบั๊กจริง ด่านไม่จับ เพราะกฎเดิมรับเฉพาะประตูที่อ่านช่อง) */
      const เปล่า = /^([A-Za-z_$][\w$]*)$/.exec(ใน[1].trim())
      const ชื่อใน = รากใน.find((x) => !สถานะจอ.has(x) && x.length >= 2 && x !== ชื่อ)
        ?? (เปล่า && !สถานะจอ.has(เปล่า[1]) && เปล่า[1].length >= 2 && เปล่า[1] !== ชื่อ ? เปล่า[1] : undefined)
      if (!ชื่อใน) continue
      const ช่วงใน = ช่วงบล็อก(เนื้อ, ใน.index)
      if (!ช่วงใน) continue
      const เนื้อใน = เนื้อ.slice(ช่วงใน[0], ช่วงใน[1])
      if (เนื้อใน.split('\n').length < 5) continue
      if (new RegExp(`\\b${ชื่อ}\\b`).test(เนื้อใน)) continue   // การ์ดนั้นใช้ของจากประตูชั้นนอกด้วย ⇒ ปกติ
      const บรรทัดใน = src.slice(0, ช่วง[0] + m[0].length + ใน.index).split('\n').length
      พบ.push(`${rel}:${บรรทัดใน}  การ์ดที่ใช้ "${ชื่อใน}" ถูกคุมด้วยประตูชั้นนอก "${ชื่อ}" ซึ่งการ์ดนี้ไม่เคยแตะเลย`)
    }
  }
}

console.log(`ตรวจประตูที่คุมของคนละเส้น: .tsx ในสาย app/ components/ · ยกเว้นไว้ ${Object.keys(ยกเว้น).length} จุด`)
if (พบ.length) {
  console.error('\n🔴 เจอประตูที่คุมของซึ่งไม่ได้มาจากเส้นเดียวกับมัน')
  for (const x of พบ) console.error('   ' + x)
  console.error('\n   ⚠️ อาการ: วันที่ของฝั่งประตูหายไปด้วยเหตุของมันเอง **ของข้างในจะหายตามโดยไม่มีใครตั้งใจ**')
  console.error('      และจอจะ "ดูปกติทุกประการ" เพราะไม่มี error — แค่ของหายไปเฉย ๆ')
  console.error('   วิธีแก้: แยกประตูให้ตรงกับแหล่งข้อมูลของแต่ละกอง')
  console.error('\n   🔎 **นี่คือรายการให้ไล่ดู ไม่ใช่คำตัดสิน** — การ์ดที่คำนวณจากข้อมูลชุดเดียวกันจะติดมาด้วย')
  console.error('      เกณฑ์ตัดสินด้วยตา: ถ้าเงื่อนไขที่ครอบการ์ด **ไม่ได้มาจากคำขอเดียวกับข้อมูลในการ์ด** ⇒ นั่นคือของจริง')
  process.exit(0)
}
console.log('✅ ทุกประตูคุมของที่มาจากเส้นเดียวกับมัน')
