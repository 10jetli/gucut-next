#!/usr/bin/env node
/**
 * 🚧 **พื้นจำนวนเทส — กันชุดทดสอบหดเงียบ**
 *
 * บังคับใบ: a-check-is-only-as-alive-as-whatever-triggers-it
 *
 * ## ที่มา (14 ต.ค. 2569)
 * กฎที่ผมเสนอ: **ด่านที่เขียนขึ้นเพื่อคุมคนหนึ่ง จะถูกทดสอบเฉพาะทิศที่คนนั้นจะโกง
 * และทิศที่ไม่มีใครได้ประโยชน์จากการโกง คือทิศที่ตัวด่านเองพัง**
 * ⇒ ฝั่งท่อเอาไปส่องด่าน push ของเขาทันที แล้วเจอว่า **ไม่มีพื้นจำนวนเทส**
 * ⇒ ผมส่องของผมตามใน 2 นาที — **รูเดียวกันเป๊ะ** (`scripts/hooks/pre-push`):
 *     ตัดสินจาก exit code ของ `node --test` เท่านั้น ·
 *     บรรทัด `# tests/pass/fail` เป็นแค่การ **พิมพ์** ไม่มีใครเทียบกับอะไร
 * 🔑 ⇒ กฎนี้ **ทำนายได้ ไม่ใช่ย้อนอธิบาย** — ชี้ล่วงหน้าว่าทิศไหนยังไม่มีใครตรวจ
 *
 * ## สี่ทิศที่ต้องแยกออกจากกัน (ท่าของฝั่งท่อ ผมทำตาม)
 *   ① เท่าพื้น            ⇒ ผ่าน
 *   ② ต่ำกว่าพื้น          ⇒ **ตก** (ชุดทดสอบหด)
 *   ③ **0 ตัว**            ⇒ **ตก** — ของเดิมพิมพ์ว่าผ่านในกรณีนี้
 *   ④ อ่านไฟล์พื้น/log ไม่ได้ ⇒ **"คุมไม่ได้รอบนี้"** ไม่ใช่ "ผ่าน" (พิมพ์เสียงดัง · rc 0)
 *
 * 🔑 และ **พื้นสองทาง** (รูปเดียวกับเพดานหนี้ของ `check-ด่านอ้างใบ`):
 *   ของจริง **มากกว่า** พื้น ⇒ ตกด้วย ⇒ บังคับให้ยกพื้นตามจริง
 *   เพราะพื้นที่ค้างต่ำคือ **ที่ซ่อน**: เทสหาย 30 ตัวยังผ่านได้ถ้าพื้นต่ำกว่าของจริง 30
 *   ⇒ เพดานที่ขยับได้ทางเดียว = ที่ซ่อนที่โตเองตามความขี้เกียจของเรา
 *
 * ใช้: `node scripts/check-test-floor.mjs <ไฟล์ log ของ node --test>`
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'

const ROOT = process.env.TEST_FLOOR_ROOT || fileURLToPath(new URL('..', import.meta.url))
const ไฟล์พื้น = process.env.TEST_FLOOR_FILE || join(ROOT, 'scripts', 'lib', 'พื้นจำนวนเทส.json')
const ไฟล์log = process.argv[2]

const คุมไม่ได้ = (เหตุ) => {
  console.log(`⬜ **พื้นจำนวนเทส: คุมไม่ได้รอบนี้** — ${เหตุ}`)
  console.log('   ⇒ นี่ไม่ใช่ "ผ่าน" · แปลว่ารอบนี้ไม่มีใครยืนยันว่าชุดทดสอบไม่หด')
  process.exit(0)
}

if (!ไฟล์log) คุมไม่ได้('ไม่ได้ส่งพาธ log มา')

let พื้นดิบ
try { พื้นดิบ = JSON.parse(readFileSync(ไฟล์พื้น, 'utf8')) }
catch (e) { คุมไม่ได้(`อ่านไฟล์พื้นไม่ได้ (${e?.code || e?.message})`) }
const พื้น = พื้นดิบ['พื้น']
if (typeof พื้น !== 'number') คุมไม่ได้('ช่อง "พื้น" ไม่ใช่ตัวเลข ⇒ ตัดสินไม่ได้')

let เนื้อ
try { เนื้อ = readFileSync(ไฟล์log, 'utf8') }
catch (e) { คุมไม่ได้(`อ่าน log ไม่ได้ (${e?.code || e?.message})`) }

/* 🔴 ต้องอ่านบรรทัด **สุดท้าย** ที่ขึ้นต้น `# tests` — node --test พิมพ์สรุปของแต่ละไฟล์ด้วย
   ⇒ หยิบบรรทัดแรกจะได้ของไฟล์แรกไฟล์เดียว ⇒ ตัวเลขต่ำกว่าจริงเสมอ ⇒ ด่านแดงลวงทุกรอบ */
const ทั้งหมด = [...เนื้อ.matchAll(/^# tests (\d+)$/gm)].map((m) => Number(m[1]))
if (!ทั้งหมด.length) คุมไม่ได้('ใน log ไม่มีบรรทัด `# tests N` เลย (รูป log เปลี่ยน?)')
const จำนวน = ทั้งหมด[ทั้งหมด.length - 1]

console.log(`📏 พื้นจำนวนเทส: ของจริง **${จำนวน}** · พื้นที่จด **${พื้น}**`)

/* ── สามสถานะตาม **สัญญาในไฟล์เคสร่วม** `~/claude-shared/lib/เคส-พื้นจำนวนเทส.json` ──
 * `ผ่าน | ตก | คุมไม่ได้` — ห้ามมีสถานะที่สี่ · และ "คุมไม่ได้" ห้ามนับเป็น "ผ่าน"
 *
 * 🔴 **รุ่นแรกของผมผิดสัญญาข้อหนึ่ง และมันจะเจ็บทุกวัน**
 *    ผมให้ `จำนวน > พื้น` ⇒ **ตก** (บังคับให้คนยกพื้นด้วยมือ)
 *    ⇒ ⇒ แปลว่า **ทุก push ที่เพิ่มเทสจะแดง** ⇒ คนจะเลิกเพิ่มเทส หรือเลิกเชื่อด่าน
 *    = ด่านที่ **ลงโทษพฤติกรรมที่เราอยากได้** (คลาสเดียวกับที่ฝั่งท่อชี้เรื่องกอง 🔶)
 *    ✅ สัญญาร่วมถูกกว่า: โตขึ้น ⇒ **ผ่าน + ยกพื้นเอง + พิมพ์ว่ายกแล้ว**
 *    ⚠️ แต่ยกได้ **ทางขึ้นเท่านั้น** — ตัวตรวจที่เขียนไฟล์ที่มันตรวจต้องเขียนได้ทิศเดียว
 *       ([[ตัวตรวจห้ามเขียนสิ่งที่มันตรวจ]]) ⇒ ลดพื้นต้องเป็นมือคนพร้อมเหตุเท่านั้น
 */
const เหตุที่ลด = พื้นดิบ['เหตุที่ลด'] ?? null
if (จำนวน === 0) {
  console.error('🔴 **ตก: เทส 0 ตัว** — ทิศที่ของเดิมพิมพ์ว่า "ผ่าน" (`# fail 0` จริง ๆ)')
  console.error('   ⇒ glob ไม่จับไฟล์ไหนเลย / เทสถูกย้าย / ไฟล์ไม่ประกาศ test()')
  process.exit(1)
}
if (จำนวน >= พื้น) {
  if (จำนวน > พื้น) {
    /* ยกพื้นตามจริง — **ขึ้นเท่านั้น** */
    const ใหม่ = { ...พื้นดิบ, 'พื้น': จำนวน, 'จดเมื่อ': new Date().toISOString().slice(0, 10) }
    try {
      writeFileSync(ไฟล์พื้น, JSON.stringify(ใหม่, null, 2) + '\n')
      console.log(`   ✅ ผ่าน · **ยกพื้น ${พื้น} ⇒ ${จำนวน}** แล้ว (เขียนลง ${ไฟล์พื้น.slice(ROOT.length)})`)
    } catch (e) {
      console.log(`   ✅ ผ่าน · 🔶 แต่ **ยกพื้นไม่ได้** (${e?.code || e?.message})`)
      console.log('      ⇒ พื้นจะค้างต่ำกว่าของจริง = ที่ซ่อน ⇒ ต้องยกด้วยมือ')
    }
  } else {
    console.log('   ✅ ผ่าน · เท่าพื้นพอดี')
  }
  process.exit(0)
}

/* จำนวน < พื้น ⇒ ผ่านได้เฉพาะเมื่อ **ลดโดยตั้งใจ** และครบสองเงื่อนไข */
if (เหตุที่ลด) {
  const ถึง = เหตุที่ลด['ถึงจำนวน']
  const เหตุ = String(เหตุที่ลด['เหตุ'] ?? '').trim()
  /* 🔑 เลขต้อง **ตรงเป๊ะ** — ยอมผ่านเพราะ "มีเหตุ" เท่ากับเปิดประตูให้ลดไม่จำกัดด้วยเหตุใบเดียว */
  if (ถึง !== จำนวน) {
    console.error(`🔴 **ตก: ลดโดยตั้งใจ แต่เลขไม่ตรงของจริง** (เหตุบอก ${ถึง} · ของจริง ${จำนวน})`)
    console.error('   ⇒ เหตุใบเดียวต้องครอบได้เลขเดียว ไม่ใช่ครอบทุกเลขที่ต่ำกว่าพื้น')
    process.exit(1)
  }
  /* 🔑 เหตุที่สั้นกว่า 10 อักขระไม่ใช่เหตุ — มันคือช่องที่ถูกกรอกให้ผ่าน */
  if (เหตุ.length < 10) {
    console.error(`🔴 **ตก: เหตุที่ลดสั้นเกิน** (${เหตุ.length} อักขระ · ต้อง ≥10)`)
    process.exit(1)
  }
  console.log(`   ✅ ผ่าน · ลดโดยตั้งใจถึง ${ถึง} — เหตุ: ${เหตุ}`)
  process.exit(0)
}

console.error(`🔴 **ตก: ชุดทดสอบหด ${พื้น - จำนวน} ตัว** (${จำนวน} < ${พื้น})`)
console.error('   ⇒ ถ้าตั้งใจลด ให้เติม `"เหตุที่ลด": {"ถึงจำนวน": <เลขจริง>, "เหตุ": "<≥10 อักขระ>", "วันที่": "…"}`')
console.error('     ลงใน `scripts/lib/พื้นจำนวนเทส.json` — **เลขต้องตรงของจริงเป๊ะ**')
process.exit(1)
