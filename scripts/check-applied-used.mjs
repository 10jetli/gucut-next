#!/usr/bin/env node
/* ด่านก่อน build: จอที่รู้จักช่อง `applied` **ต้องเอามาเทียบจริง** ไม่ใช่ประกาศไว้เฉย ๆ
 *
 * 🔑 `applied` คือช่องที่ท่อบอกว่า "เงื่อนไขที่ฉันใช้จริงคืออะไร"
 *    มีไว้ให้จอตรวจว่า **ที่ขอไป** กับ **ที่ได้มา** ตรงกันไหม
 *    ⇒ กฎประจำโปรเจกต์: **ตอบ 200 ไม่ได้แปลว่าทำให้** (เจอมาแล้วหลายรอบ:
 *       `list=purchases&status=` ถูกเมินเงียบ ๆ · `offset` ถูกเมินที่เส้นเอกสารบัญชี ฯลฯ)
 *
 * 🔴 ที่มาของด่านนี้ (17 ก.ย. 2569): จอลูกค้า **ประกาศ `applied` ไว้ตั้งแต่ 15 ก.ย.**
 *    และเทียบแค่สองสวิตช์ · ส่วน **คำค้น (`q`) ไม่เคยถูกเทียบเลย**
 *    ⇒ ถ้าท่อเมินคำค้น จอจะโชว์รายชื่อทั้งกองให้คนที่เพิ่งพิมพ์ค้นหา โดยไม่มีอะไรฟ้อง
 *    ⇒ ด่านนี้กันไม่ให้ "ประกาศแล้วลืมใช้" เกิดอีก
 *
 * วิธีตรวจ: ไฟล์ `app/**\/page.tsx` ที่ประกาศ `applied?:` ในชนิดข้อมูล
 *   ต้องมีการ **อ่านค่ามาเทียบ** (`applied.` หรือ `applied?.`) อย่างน้อยหนึ่งจุดนอกบรรทัดที่ประกาศ
 * ⚠️ ตรวจได้แค่ "มีการเทียบ" ไม่ได้ตรวจว่าเทียบครบทุกช่อง — ยังต้องดูด้วยตา
 *    (แต่จับกรณี "ประกาศแล้วไม่ใช้เลย" ซึ่งเป็นกรณีที่เกิดจริง)
 */
import { readdirSync, readFileSync, statSync } from 'node:fs'
import { join } from 'node:path'
import { ต้องมีของให้ตรวจ } from './lib/ต้องมีของให้ตรวจ.mjs'
import { ตัดคอมเมนต์ } from './lib/ตัดคอมเมนต์.mjs'

const ROOT = new URL('..', import.meta.url).pathname

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    const st = statSync(p)
    if (st.isDirectory()) { if (name !== 'node_modules' && name !== '.next') walk(p, out) }
    else if (name === 'page.tsx') out.push(p)
  }
  return out
}

const ปัญหา = []
const ไม่ได้เทียบ = []
/* 🔒 ไม่มีไฟล์ให้ตรวจ = ไม่ผ่าน (ดู scripts/lib/ต้องมีของให้ตรวจ.mjs) */
const ไฟล์ที่ตรวจ = walk(join(ROOT, 'app'))
ต้องมีของให้ตรวจ(ไฟล์ที่ตรวจ.length, 'check-applied-used')
for (const file of ไฟล์ที่ตรวจ) {
  const src = ตัดคอมเมนต์(readFileSync(file, 'utf8'))
  if (!/\bapplied\?\s*:/.test(src)) continue          // จอนี้ไม่รู้จัก applied ⇒ ไม่เกี่ยว
  /* ต้องมีการอ่านค่าไปใช้จริง — นับเฉพาะบรรทัดที่ **ไม่ใช่** บรรทัดประกาศชนิดข้อมูล */
  const ใช้จริง = src.split('\n').some((line) =>
    /\bapplied\s*(\?\.|\.)/.test(line) && !/\bapplied\?\s*:/.test(line))
  if (!ใช้จริง) { ปัญหา.push(file.replace(ROOT, '')); continue }

  /* 🔴 **ชั้นที่สอง (19 ก.ย. 2569 · งาน S2): "อ่านอย่างน้อยหนึ่งครั้ง" ไม่ใช่คำถามที่ถูก**
     จอ transfers ประกาศ `applied` ไว้ 5 ช่อง · ส่ง q/from/to/status ไปจริง
     · แต่เทียบแค่ `applied.status` ⇒ **ผ่านด่านชั้นแรกสบาย ๆ**
     ⇒ วันที่ท่อเมินคำค้น จอจะโชว์ของทั้งกองให้คนที่เพิ่งพิมพ์ค้นหา โดยไม่มีอะไรฟ้อง
     🔑 คลาส "ของดีค้ำประกันของที่ยังไม่ได้ตรวจ" ระดับบรรทัด — ตัวกรองหนึ่งตัวที่เทียบแล้ว
        ทำให้ทั้งจอดูเหมือนมีตาข่าย

     ⚠️ **เทียบเฉพาะช่องที่จอประกาศเองว่าท่อคืนมา** (จากชนิด `applied?: {...}`)
        ถ้าท่อไม่คืนช่องนั้น จอเทียบไม่ได้ ⇒ นั่นเป็นหนี้ฝั่งท่อ ไม่ใช่ฝั่งจอ
        ⇒ ด่านนี้ต้องไม่เรียกร้องสิ่งที่เป็นไปไม่ได้ ไม่งั้นจะถูกปิดทิ้งทั้งด่าน
     ⚠️ และ **ไม่นับบรรทัดที่เป็นลิงก์ไปจออื่น** (`href=` · `router.push` · `<Link`)
        ⇒ ผมนับผิดรอบแรกเพราะ `?customer=…` ในลิงก์ ถูกนับเป็นตัวกรอง ⇒ ได้เลขเกินจริงเท่าตัว */
  const ชนิด = src.match(/applied\?\s*:\s*\{([^}]*)\}/)
  const ท่อคืน = new Set(ชนิด ? [...ชนิด[1].matchAll(/(\w+)\??\s*:/g)].map((m) => m[1].toLowerCase()) : [])
  const ส่ง = new Set()
  for (const line of src.split('\n')) {
    if (/href=|router\.push|<Link/.test(line)) continue
    for (const m of line.matchAll(/\.set\(\s*['"]([a-zA-Z][\w-]*)['"]/g)) ส่ง.add(m[1].toLowerCase())
  }
  for (const x of ['list', 'store', 'limit', 'page', 'offset', 'secret']) ส่ง.delete(x)
  /* 🔴 **รุ่นแรกนับการ "เอาไปแสดงผล" ว่าเป็นการ "เทียบ"** (แก้ทันทีวันเดียวกัน)
     รู้เพราะปลูก: ถอดเงื่อนไข `withEmail !== !!data.applied.withEmail` ออก ⇒ ด่านยังเขียว
     เพราะอีกบรรทัดหนึ่งเขียน `{data.applied.withEmail ? 'ใช่' : 'ไม่'}` เพื่อ**โชว์**ค่า
     ⇒ โชว์ค่าที่ท่อใช้ ≠ เทียบว่าตรงกับที่จอส่งไป · อย่างแรกไม่มีวันเตือนใครได้
     ⇒ บังคับว่าบรรทัดนั้นต้องมีตัวดำเนินการเปรียบเทียบอยู่ด้วย
     ⚠️ ยังเป็นรูปข้อความ (เทียบข้ามบรรทัดจะมองไม่เห็น) — ยกราคาของการปลอม ไม่ได้ตัดขาด */
  const เทียบแล้ว = new Set()
  for (const line of src.split('\n')) {
    if (!/[!=]==?|[<>]/.test(line)) continue
    for (const m of line.matchAll(/applied[?.]*\.(\w+)/g)) เทียบแล้ว.add(m[1].toLowerCase())
  }
  const ขาด = [...ส่ง].filter((x) => ท่อคืน.has(x) && !เทียบแล้ว.has(x)).sort()
  if (ขาด.length) ไม่ได้เทียบ.push({ ไฟล์: file.replace(ROOT, ''), ขาด })
}

if (ปัญหา.length) {
  console.error('🔴 จอที่ประกาศช่อง `applied` ไว้ แต่ไม่ได้เอามาเทียบ:\n')
  for (const f of ปัญหา) console.error(`  ${f}`)
  console.error('\n⇒ `applied` คือคำตอบของท่อว่า "ใช้เงื่อนไขอะไรจริง ๆ"')
  console.error('   จอต้องเทียบกับสิ่งที่ส่งไป แล้วขึ้นคำเตือนเมื่อไม่ตรง (ตอบ 200 ไม่ได้แปลว่าทำให้)')
  process.exit(1)
}
console.log('✅ จอที่รู้จัก `applied` เอามาเทียบครบแล้ว')

/* ── หมุดกัน "ตัวกรองที่ส่งแล้วไม่เทียบ" โตขึ้น ──
   ⚠️ **เลข 15 คือสภาพวันที่ตั้ง ไม่ใช่ระดับที่ยอมรับได้** — เป็นหนี้ที่ค้างอยู่
   🚫 สคริปต์ไม่เขียนเลขนี้เอง — ลดได้เมื่อไหร่ต้องมีคนมาแก้ (ให้มันเขียนเอง =
      วันที่เลขพุ่งขึ้นมันจะเลื่อนเพดานตามแล้วเงียบ) */
/* 📌 15 → 18 เมื่อ 19 ก.ย. 2569 — **เลขขึ้นเพราะด่านคมขึ้น ไม่ใช่เพราะโค้ดแย่ลง**
   (3 ตัวที่เพิ่มมาเคยถูกนับว่า "เทียบแล้ว" ทั้งที่เป็นการเอาค่าไปแสดงผลเฉย ๆ)
   ⇒ เวลาเลขหมุดขยับ **ต้องเขียนว่าขยับเพราะอะไร** ไม่งั้นคนรอบหน้าอ่านว่าเราถอยหลัง */
const เพดานไม่ได้เทียบ = 18
const รวมขาด = ไม่ได้เทียบ.reduce((n, x) => n + x.ขาด.length, 0)
console.log(`\nตัวกรองที่จอส่งไป · ท่อคืนค่ามาให้เทียบ · แต่จอไม่ได้เทียบ: ${รวมขาด} ตัว ใน ${ไม่ได้เทียบ.length} จอ`)
for (const x of ไม่ได้เทียบ) console.log(`   ${x.ไฟล์}  →  ${x.ขาด.join(' ')}`)
console.log('   ⇒ ท่อเมินตัวกรองเมื่อไหร่ จอจะโชว์ของทั้งกองให้คนที่เพิ่งกดกรอง โดยไม่มีอะไรฟ้อง')
if (รวมขาด > เพดานไม่ได้เทียบ) {
  console.error(`\n🔴 เพิ่มจาก ${เพดานไม่ได้เทียบ} เป็น ${รวมขาด} — ตัวกรองใหม่ต้องเทียบ \`applied\` ด้วย`)
  process.exit(1)
} else if (รวมขาด < เพดานไม่ได้เทียบ) {
  console.log(`   🎉 ลดเหลือ ${รวมขาด} ⇒ **แก้เลขเพดานในสคริปต์ลงด้วยมือ** ไม่งั้นที่ลดได้จะไหลกลับเงียบ ๆ`)
}
