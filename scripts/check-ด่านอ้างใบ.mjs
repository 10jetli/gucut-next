import { readFileSync, existsSync, readdirSync, realpathSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'

/* 🔑 ราก/คลัง/ไฟล์ฐาน เปิดให้แทนที่ด้วย env **เพื่อให้เทสเดินทางที่ผู้ใช้จริงเดิน**
   ไม่ใช่เพื่อความสะดวก — ด่านที่ทดสอบได้แค่ "กับรีโปจริงตอนนี้" จะมีกิ่งที่ไม่มีใครเดินถึง
   ([[ทางที่ไม่เคยถูกเดินคือทางที่ยังไม่รู้ว่าใช้ได้ไหม]]) */
const ROOT = process.env.GATE_CARDS_ROOT || fileURLToPath(new URL('..', import.meta.url))
/** คลังทีม — อ้างได้ที่เดียวโดยคำตัดสิน (ฝั่งท่อ 14 ต.ค. 2569) */
const คลังทีม = process.env.TEAM_LESSONS || '/home/jetli/claude-shared/en/lessons'
/** ฐานหนี้ "ไม่มีช่องเลย" — เลขเดียว ที่เดียว ([[เลขเกณฑ์ต้องมีที่เดียว]]) */
const ไฟล์ฐาน = process.env.GATE_CARDS_BASE || join(ROOT, 'scripts', 'lib', 'หนี้ด่านอ้างใบ.json')

/* 🔑 **ทำไมเป็นเพดานหนี้ ไม่ใช่ "ต้องมีครบทุกตัว"**
   วันแรกมีด่าน 58 ตัวและ **ไม่มีตัวไหนมีช่องเลย** ⇒ ถ้าบังคับให้ครบ prebuild แดงทั้งสาย
   ⇒ คนที่เจอจะปิดด่านทิ้ง หรือกรอกช่องมั่วให้ผ่าน (= เปลี่ยนงานวัดเป็นงานกรอก)
   🔴 แต่ถ้าแค่ "พิมพ์เลขแล้วผ่านทุกครั้ง" มันคือ **รายงาน ไม่ใช่ด่าน** — และรายงานไม่กันอะไรเลย
   ✅ ท่าที่เป็นด่านได้ตั้งแต่วันแรก: **หนี้ห้ามโต** — ตก เมื่อ C มากกว่าฐานที่จดไว้
      ⇒ ด่านใหม่ทุกตัวต้องมีช่อง (ไม่งั้น C โต ⇒ แดง) · ของเก่าทยอยปิดได้ตามจังหวะ
      ⇒ และฐานต้อง **ลดได้เท่านั้น** — ตก เมื่อฐานถูกแก้ให้ใหญ่กว่า C จริง (กันการเลื่อนเพดาน) */

const อ่านฐาน = () => {
  try { return JSON.parse(readFileSync(ไฟล์ฐาน, 'utf8')) }
  catch { return null }   // ← null = ไม่มีฐาน ห้ามตกเป็น 0 (0 จะทำให้ด่านแดงทั้งสายวันแรก)
}

/** ชื่อใบในคลังทีม — เซ็ตของชื่อไฟล์ไม่รวม .md */
const ใบในคลังทีม = () => {
  try { return new Set(readdirSync(คลังทีม).filter((f) => f.endsWith('.md') && f !== 'MEMORY.md')
    .map((f) => f.replace(/\.md$/, ''))) }
  catch { return null }
}

/** รายชื่อสคริปต์ในสาย prebuild — อ่านจาก package.json ไม่ใช่จากการกวาดโฟลเดอร์
    🔑 เหตุ: ของที่ **อยู่ในสาย** คือของที่ถูกรันจริง · ไฟล์ที่กวาดเจอแต่ไม่มีใครเรียก ไม่ใช่ด่าน
       ([[ด่านที่ไม่มีใครเรียกกับสายที่ไม่มีใครเดิน]]) */
const ในสาย = () => {
  const สาย = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')).scripts['ตรวจ'] || ''
  return [...new Set([...สาย.matchAll(/node (scripts\/[^\s;&]+)/g)].map((m) => m[1]))]
}

const ไฟล์ทั้งสาย = ในสาย()
const เทสที่กันออก = ไฟล์ทั้งสาย.filter((f) => f.startsWith('scripts/tests/'))
const ต้องมีช่อง = ไฟล์ทั้งสาย.filter((f) => !f.startsWith('scripts/tests/'))

/* ใบอนุญาต "ไม่อ้างใบ" — ใช้รูป **เดียวกับด่านทีม** (`\S[^\n]{19,}`) โดยเจตนา
   🔴 ห้ามใช้ `\S{20,}` ซึ่งเป็นรูปที่ผมเขียนเองใน check-ชื่อตัวแปรเชลล์.mjs แล้วพบว่า
      **ตีกลับเหตุผลที่มีช่องว่างทุกอัน** (รวมภาษาอังกฤษทั้งหมด) ⇒ ทางออกที่เดินไม่ได้ */
/* 🔴 **รูปแรกของผมรับคอมเมนต์ได้แค่บางสไตล์ — เทสจับทันทีข้อแรก**
   รุ่นแรกยอมรับนำหน้าเฉพาะ `*` · `//` · `#` ⇒ บรรทัดสไตล์คอมเมนต์บรรทัดเดียว (เปิด-ปิดในบรรทัดเดียวกัน) **ไม่ถูกนับ**
   ⇒ ⇒ ด่านที่ **จดช่องแล้ว** จะถูกนับเป็น "ไม่มีช่องเลย" ⇒ ตัวเลขหนี้ผิดในทิศที่มองไม่เห็น
      (หนี้ดูเยอะกว่าจริง ⇒ วันหนึ่งคนจะเลื่อนฐานขึ้นเพื่อให้ผ่าน = เปิดที่ซ่อนด้วยมือตัวเอง)
   📌 ไฟล์จริงของผมใช้สไตล์ ` * บังคับใบ:` (บล็อกคอมเมนต์) ⇒ **มันผ่านเพราะสไตล์ที่ผมเผอิญใช้**
      = ถูกโดยอุบัติเหตุ ซึ่งเป็นคลาสเดียวกับรูป `\S{20,}` ที่รอดเพราะภาษาไทยไม่มีช่องว่าง
   ✅ จึงรับนำหน้าทุกสไตล์ที่ใช้จริง และ **ตัดหางปิดคอมเมนต์** ออกจากค่าที่อ่านได้
   ⚠️ และคอมเมนต์ก้อนนี้เองเคยพัง เพราะผมเขียนตัวอย่างที่มีเครื่องหมายปิดคอมเมนต์อยู่ข้างใน
      ⇒ ปิดบล็อกกลางทาง ⇒ `SyntaxError` ⇒ **ห้ามเขียนเครื่องหมายปิดคอมเมนต์ในคอมเมนต์** */
const นำหน้าคอมเมนต์ = '(?:\\/\\*|\\*\\/|\\*|\\/\\/|#)?'
const รูปไม่อ้าง = new RegExp(`(?:^|\n)[^\\S\n]*${นำหน้าคอมเมนต์}[^\\S\n]*ไม่อ้างใบ:[^\\S\n]*(\\S[^\n]{19,})`)
const รูปบังคับ = new RegExp(`(?:^|\n)[^\\S\n]*${นำหน้าคอมเมนต์}[^\\S\n]*บังคับใบ:[^\\S\n]*([^\n]+)`, 'g')
/** ตัดเครื่องหมายปิดคอมเมนต์ที่ติดมาท้ายบรรทัดออก ไม่ให้กลายเป็นส่วนของชื่อใบ */
const ล้างหาง = (t) => t.replace(/\s*(?:\*\/|-->)\s*$/, '').trim()

const ใบ = ใบในคลังทีม()
const ฐาน = อ่านฐาน()
const ปัญหา = []
let อ้างใบ = 0, ไม่อ้างใบ = 0, ไม่มีช่อง = 0
const ใบที่ถูกอ้าง = new Set()

for (const f of ต้องมีช่อง) {
  const ที่ = join(ROOT, f)
  if (!existsSync(ที่)) { ปัญหา.push(`${f} — อยู่ในสาย prebuild แต่ไม่มีไฟล์`); continue }
  const s = readFileSync(ที่, 'utf8')
  const ชื่อใบ = [...s.matchAll(รูปบังคับ)]
    .flatMap((m) => ล้างหาง(m[1]).split('·').map((x) => x.trim()).filter(Boolean))
  if (ชื่อใบ.length) {
    อ้างใบ++
    for (const n of ชื่อใบ) {
      ใบที่ถูกอ้าง.add(n)
      /* 🔑 ข้อที่ฝั่งท่อเพิ่ม: **ชื่อใบที่ด่านอ้าง ต้องมีไฟล์จริง**
         คลาสเดียวกับคู่มือที่ชี้ไปไฟล์ที่ไม่มี ([[ของที่พังแล้วคนโทษตัวเองคือของที่ไม่มีใครรายงาน]]) */
      if (ใบ && !ใบ.has(n)) ปัญหา.push(`${f} — อ้างใบ "${n}" แต่ไม่มีไฟล์นี้ในคลังทีม`)
    }
    continue
  }
  const ม = รูปไม่อ้าง.exec(s)
  if (ม) { ไม่อ้างใบ++; continue }
  if (/ไม่อ้างใบ:/.test(s)) {
    ปัญหา.push(`${f} — มีช่อง "ไม่อ้างใบ:" แต่เหตุสั้นกว่า 20 ตัวอักษร`)
    continue
  }
  ไม่มีช่อง++
}

console.log('📑 ด่านอ้างใบไหน (ทิศ ด่าน→ใบ · คำตัดสินฝั่งท่อ 14 ต.ค. 2569)')
console.log(`   ด่านที่ต้องมีช่อง ${ต้องมีช่อง.length} · อ้างใบ ${อ้างใบ} · ไม่อ้างใบ ${ไม่อ้างใบ}`
  + ` · **ไม่มีช่องเลย ${ไม่มีช่อง}**`)
console.log(`   🔸 **เทสที่ถูกกันออกรอบนี้ ${เทสที่กันออก.length} ตัว** — หนี้นี้ไม่หาย`)
console.log('      (เทสที่ล้ม = โค้ดทำผิดจากที่เขียนไว้ · ด่านที่ล้ม = คนทำผิดกติกาที่ทีมตั้ง)')
console.log('      ⚠️ มีเทสที่เป็นด่านจริงอยู่ในกองนี้ ⇒ ย้าย**ทีละตัว** ห้ามย้ายทั้งกอง')
if (ใบ === null) {
  console.log(`   🔶 **อ่านคลังทีมไม่ได้** (${คลังทีม}) ⇒ ตรวจชื่อใบไม่ได้รอบนี้ (ไม่ใช่ "ชื่อถูกทุกใบ")`)
} else {
  console.log(`   ใบที่มีด่านอ้างถึง: **${ใบที่ถูกอ้าง.size}/${ใบ.size}** ในคลังทีม`)
  console.log(`      📍 คลังทีม = ${realpathSync(คลังทีม)}`)
  console.log('      ⚠️ **เลขนี้เทียบกับฝั่งท่อตรง ๆ ไม่ได้** — คลังทีมเป็น symlink ไปคลังความจำของเขา')
  console.log('         ⇒ ใบของเขาอยู่ในคลังร่วมตั้งแต่เขียน · ใบของผมต้องยกขึ้นมา')
  console.log('         ⇒ ความต่างนี้เป็น **ของโครงสร้าง ไม่ใช่ของคน** — ต้องอ่านอย่างนั้น')
}

if (ฐาน === null) {
  console.error(`🔴 ไม่มีไฟล์ฐานหนี้ (${ไฟล์ฐาน}) ⇒ **ตัดสินไม่ได้** (ไม่ใช่ผ่าน)`)
  console.error(`   ⇒ สร้างด้วย: {"ไม่มีช่องเลย": ${ไม่มีช่อง}, "จดเมื่อ": "<วันนี้>"}`)
  process.exit(1)
}
if (ไม่มีช่อง > ฐาน['ไม่มีช่องเลย']) {
  ปัญหา.push(`หนี้โต: ไม่มีช่องเลย ${ไม่มีช่อง} > ฐาน ${ฐาน['ไม่มีช่องเลย']}`
    + ' ⇒ ด่านใหม่ต้องมีช่อง `บังคับใบ:` หรือ `ไม่อ้างใบ: <เหตุ>`')
}
if (ฐาน['ไม่มีช่องเลย'] > ไม่มีช่อง) {
  /* 🔑 ฐานต้องตามของจริงลงมา ไม่ใช่ค้างสูงไว้เป็นที่ซ่อน
     ([[เกณฑ์คัดกรองที่ดีสร้างที่ซ่อนให้ของที่ผ่านเกณฑ์]]) */
  ปัญหา.push(`ฐานค้างสูงกว่าของจริง (${ฐาน['ไม่มีช่องเลย']} > ${ไม่มีช่อง})`
    + ` ⇒ ลดฐานใน ${ไฟล์ฐาน.slice(ROOT.length)} เป็น ${ไม่มีช่อง}`)
}

if (ปัญหา.length) {
  console.error(`🔴 **ด่านอ้างใบ: ${ปัญหา.length} ข้อ**`)
  for (const x of ปัญหา) console.error(`   · ${x}`)
  process.exit(1)
}
console.log(`   ✅ ไม่มีด่านไหนอ้างใบที่ไม่มีจริง · หนี้ไม่โตเกินฐาน ${ฐาน['ไม่มีช่องเลย']}`)
