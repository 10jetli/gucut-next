if (ฐาน['ไม่มีช่องเลย'] > ไม่มีช่อง) {
  /* 🔑 ฐานต้องตามของจริงลงมา ไม่ใช่ค้างสูงไว้เป็นที่ซ่อน
     ([[เกณฑ์คัดกรองที่ดีสร้างที่ซ่อนให้ของที่ผ่านเกณฑ์]]) */
  ปัญหา.push(`ฐานค้างสูงกว่าของจริง (${ฐาน['ไม่มีช่องเลย']} > ${ไม่มีช่อง})`
    + ` ⇒ ลดฐานใน ${ไฟล์ฐาน.slice(ROOT.length)} เป็น ${ไม่มีช่อง}`)
}

if (ปัญหา.length) {
  console.error(`🔴 **ด่านอ้างใบ: ${ปัญหา.length} ข้อ**`)
  for (const x of ปัญหา) console.error(`   · ${x}`)
  process.exit(1)
}
