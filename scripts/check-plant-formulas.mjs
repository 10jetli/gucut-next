#!/usr/bin/env node
/* ด่านก่อน build: **สูตรปลูกบั๊กในทะเบียน ยัง "ปลูกลง" อยู่ไหม**
 * (20 ก.ย. 2569 · ฝั่งท่อทำก่อน ผมทำตาม)
 *
 * 🔴 ที่มา — ของจริงวันนี้: ผมเขียน `scripts/lib/ตัดคอมเมนต์.mjs` ใหม่ทั้งไฟล์
 *    ⇒ ข้อความที่สูตรของมันจะแทน **หายไปจากไฟล์** ⇒ สูตรนั้น **ปลูกไม่ลงอีกแล้ว**
 *    ⇒ แต่ไม่มีอะไรฟ้อง เพราะทะเบียนจริงช้าและ **ไม่อยู่ในลูกโซ่ build**
 *    ⇒ ⇒ **การแก้โค้ดทำให้ "หลักฐานการพิสูจน์" หมดอายุเงียบ ๆ ได้**
 *
 * 🔑 ด่านนี้ตรวจ **ข้อเดียวที่ถูกที่สุดและถูกที่สุด (ราคา)**: `แก้()` ยังเปลี่ยนเนื้อไฟล์ไหม
 *    · **ไม่เขียนไฟล์ใด ๆ** (อ่านอย่างเดียว) ⇒ เอาเข้า prebuild ได้โดยไม่มีผลข้างเคียง
 *    · **เร็ว** เพราะไม่รันด่านจริงสักตัว
 *
 * 🚫 **เขียวที่นี่ ไม่ได้แปลว่า "ด่านจับบั๊กได้"** — มันแปลแค่ว่า *สูตรยังใช้งานได้*
 *    การพิสูจน์จริงยังต้องรัน `node scripts/ด่านแยกแยะได้ไหม.mjs` ซึ่งช้าและแก้ไฟล์ชั่วคราว
 *    ⇒ เขียนไว้ตรงนี้กันคนอ่านผลว่าเป็นอย่างหลัง
 */
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'
import { สูตร } from './lib/ทะเบียนด่าน.mjs'

const ROOT = fileURLToPath(new URL('..', import.meta.url))

if (!Array.isArray(สูตร) || สูตร.length === 0) {
  console.error('🔴 ทะเบียนสูตรว่างหรืออ่านไม่ได้ ⇒ **ตะแกรงพัง ไม่ใช่ไม่มีสูตร**')
  process.exit(1)
}

const ตก = []
for (const x of สูตร) {
  let เดิม
  try {
    เดิม = readFileSync(join(ROOT, x.ไฟล์), 'utf8')
  } catch (e) {
    ตก.push(`${x.ด่าน}: อ่านไฟล์เป้า ${x.ไฟล์} ไม่ได้ (${String(e?.message ?? e).slice(0, 60)})`)
    continue
  }
  let ใหม่
  try {
    ใหม่ = x.แก้(เดิม)
  } catch (e) {
    ตก.push(`${x.ด่าน}: \`แก้()\` โยน error (${String(e?.message ?? e).slice(0, 60)})`)
    continue
  }
  if (ใหม่ === เดิม) {
    ตก.push(`${x.ด่าน}: **ปลูกไม่ลง** — \`แก้()\` คืนเนื้อเดิม ⇒ ข้อความที่จะแทนไม่มีใน ${x.ไฟล์} แล้ว`)
    continue
  }
  /* ถ้าสูตรประกาศร่องรอยไว้ ต้องเจอร่องรอยนั้นในผลด้วย — ไม่งั้น "เปลี่ยนแล้ว" อาจเปลี่ยนผิดที่ */
  if (x.ต้องมีในไฟล์ && !ใหม่.includes(x.ต้องมีในไฟล์)) {
    ตก.push(`${x.ด่าน}: แก้แล้วแต่ไม่พบ "${x.ต้องมีในไฟล์}" ⇒ ของที่ปลูกไม่ได้อยู่ในรูปที่ตั้งใจ`)
  }
}

/* 🔑 **นับ "ขาดเงื่อนไขเป้า" แยกจาก "ปลูกไม่ลง"** (20 ก.ย. 2569 · ฝั่งท่อชี้ว่าเขายัดสองเหตุ
   ไว้ป้ายเดียวในรอบแรก ⇒ คนอ่านจะไปไล่หาว่าข้อความที่สูตรมองหาหายไปไหน
   **ทั้งที่ของจริงคือยังไม่ได้เขียนเอกสาร**) ⇒ สองเหตุที่ **แก้คนละแบบ** ห้ามใช้ป้ายเดียวกัน
   📌 **รายงานอย่างเดียวก่อน ไม่ทำให้ตก** — เพราะสูตรเดิม 31 ตัวเขียนเงื่อนไขไว้ใน *คอมเมนต์*
      ซึ่งเครื่องอ่านไม่ได้ ⇒ ถ้าให้ตกทันทีจะกลายเป็นด่านที่บังคับงานกวาดครั้งใหญ่ในรอบเดียว
      ⇒ ฝั่งท่อชี้ข้อที่ถูก: **ฟิลด์อ่านได้ตอนรัน ⇒ ด่านตรวจได้ · คอมเมนต์อ่านได้แต่ตอนคนเปิดไฟล์** */
const ขาดเงื่อนไข = สูตร.filter((x) => !x['เงื่อนไขเป้า']).map((x) => x.ด่าน)

console.log(`ตรวจสูตรปลูกในทะเบียน: ${สูตร.length} สูตร · ปลูกลง ${สูตร.length - ตก.length} · **ไม่เขียนไฟล์ใด ๆ**`)
console.log(`   📏 สูตรที่มีช่อง \`เงื่อนไขเป้า\` แบบเครื่องอ่านได้: ${สูตร.length - ขาดเงื่อนไข.length} จาก ${สูตร.length}`)
if (ขาดเงื่อนไข.length) {
  console.log(`   ⚠️ **ขาดเงื่อนไขเป้า ${ขาดเงื่อนไข.length} สูตร** — คนละเหตุกับ "ปลูกไม่ลง" และแก้คนละแบบ`)
  console.log('      (เขียนไว้ในคอมเมนต์อาจมีแล้ว แต่เครื่องอ่านไม่ได้ ⇒ ยังไม่นับ) · **รายงานอย่างเดียว ไม่ทำให้ตก**')
}
console.log('   ⚠️ เขียวที่นี่แปลว่า **สูตรยังใช้ได้** ไม่ใช่ **ด่านจับบั๊กได้** — อย่างหลังต้องรัน ด่านแยกแยะได้ไหม.mjs')

if (ตก.length) {
  console.error(`\n🔴 สูตรที่ใช้ไม่ได้แล้ว ${ตก.length} สูตร:`)
  for (const t of ตก) console.error('   ' + t)
  console.error('\n   ⇒ แก้สูตรให้ตรงกับโค้ดรุ่นปัจจุบัน แล้วรันทะเบียนจริงซ้ำเพื่อยืนยันว่าด่านยังแดง')
  process.exit(1)
}
