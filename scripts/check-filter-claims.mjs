const รับแน่ = (เส้น) => {
  const ช่อง = ตาราง[เส้น]?.กรองจริง
  if (!ช่อง || !ช่อง.มีคีย์) return undefined        // ท่อยังไม่ส่ง supportedFilters ของเส้นนี้
  if (ช่อง.ค่า === null) return null                  // ท่อบอกไม่ได้
  return new Set(ช่อง.ค่า.map((x) => String(x).toLowerCase()))
}
