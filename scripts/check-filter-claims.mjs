      if (ผล.some(([, s]) => s === null)) {
        ข้ามเพราะnull++
        ผล.filter(([, s]) => s === null).forEach(([e]) => เส้นที่ข้ามnull.add(e))
        continue
      }
      const รับหมด = ผล.every(([, s]) => s && s.has(พารา.toLowerCase()))
      /* 🔑 ถ้ามีเส้นที่ **ตัดสินไม่ได้** ปนอยู่ ⇒ ผูกคำกล่าวอ้างกับเส้นไหนไม่ได้ ⇒ ข้าม
         แต่ต้องนับ ไม่งั้นด่านจะดู "ครอบคลุม" กว่าความจริงมาก
         (ของจริง: จอ transfers เรียก transfers + warehouses ⇒ เส้นหลังท่อยังไม่ส่ง supportedFilters) */
