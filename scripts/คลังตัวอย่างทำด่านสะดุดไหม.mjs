#!/usr/bin/env node
/* ไฟล์ที่ **เก็บรูปของบั๊กไว้เป็นตัวอย่าง** ทำให้ด่านของเราเองสะดุดหรือไม่
 * 🚫 ไม่อยู่ใน prebuild (แก้ไฟล์ชั่วคราว · รันด่านทั้งชุด 3 รอบ)
 * (19 ก.ย. 2569 · หนี้ที่ฝั่งท่อจดไว้ · ฝั่งจอทำก่อน)
 *
 * 🔴 ปัญหา: คลัง `รูปที่เคยพลาด` เก็บ **รูปที่เคยทำตะแกรงพัง** ไว้เป็นข้อความ
 *    แล้วตัวมันเองก็เป็น **ไฟล์ที่ถูกด่านกวาด** ⇒ เนื้อในคลังอาจ
 *    ① ทำให้ด่านแดงลวง (คลังถูกอ่านเป็นของจริง) หรือ
 *    ② **ทำให้ด่านเขียวลวง** (คลังมีคำที่ด่านมองหา ⇒ ด่านถูกทำให้พอใจด้วยเอกสาร)
 *    ⇒ ทิศ ② คือคลาสที่ฝั่งท่อเจอมาแล้ว (ด่านที่อ่านซอร์สต้องถอดคอมเมนต์ก่อนตรวจ)
 *
 * 🔑 วิธีที่ใช้ — **วัดส่วนต่าง ไม่ใช่อ่านโค้ดเดา**
 *    รันด่านทั้งชุด 2 รอบ: มีเนื้อในคลัง / ถอดเนื้อออกเหลือโครง ⇒ ผลต่างกันตรงไหน
 *    ⇒ จับได้ทั้งสองทิศพร้อมกัน เพราะถ้าคลังค้ำด่านอยู่ พอถอดออกด่านจะเปลี่ยนผล
 *
 * ⚠️ **ข้อที่ทำให้การวัดนี้เชื่อได้** — ต้องมี **ตัวควบคุมบวก** รอบที่สาม
 *    ปลูกของที่ *รู้ว่าด่านต้องจับ* ลงในคลัง แล้ววิธีวัดต้องรายงานว่า "ต่าง"
 *    ⇒ ไม่มีรอบนี้ ผล "ไม่ต่าง" แปลได้สองอย่างแยกไม่ออก:
 *       คลังไม่มีผล **หรือ** วิธีวัดของเราจับความต่างไม่ได้เลย
 *    (ฝั่งท่อชี้ข้อนี้กับผมตรง ๆ 19 ก.ย. 2569: ผลเขียวของการทดสอบที่ไม่มีพลังแยกแยะ
 *     แปลว่า "ไม่มีความเสี่ยงให้วัด" ไม่ใช่ "วัดแล้วปลอดภัย")
 *
 * วิธีใช้: node scripts/คลังตัวอย่างทำด่านสะดุดไหม.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
process.chdir(ROOT)

/** ไฟล์ที่เก็บ "รูปของบั๊ก" ไว้เป็นข้อความ · `โครง` ต้อง import ได้เหมือนเดิม */
const คลัง = [
  {
    ไฟล์: 'scripts/lib/รูปที่เคยพลาด.mjs',
    โครง: [
      'export const รูปที่เคยพลาด = []',
      'export const ของจริงเท่านั้น = () => รูปที่เคยพลาด.filter((x) => x.ของจริง)',
      'export const สรุปคลัง = () => `คลังรูปที่เคยพลาด: 0 รูป`',
      '',
    ].join('\n'),
  },
  {
    ไฟล์: 'scripts/ด่านแยกแยะได้ไหม.mjs',
    โครง: 'console.log("โครงเปล่าสำหรับวัดส่วนต่าง")\n',
    /* 🔑 ไฟล์นี้ **อยู่ใน whitelist ของ check-sentinel-leftovers** โดยชอบธรรม
       (มันต้องเอ่ยชื่อ sentinel เพราะมันเป็นคนปลูก) ⇒ ปลูก ZZPLANTZZ ลงไปแล้ว
       **ไม่มีด่านไหนเห็น** ⇒ ตัวควบคุมมาตรฐานใช้กับไฟล์นี้ไม่ได้
       ⇒ เครื่องมือรุ่นแรกจึงตอบ "คุม 0/1" ซึ่ง **ถูกแล้ว** — และนั่นคือเหตุผลที่ต้องมีรอบคุม
       🔑 บทเรียนย่อย: **ข้อยกเว้นที่เราให้ไฟล์หนึ่ง ทำให้ไฟล์นั้นวัดด้วยวิธีเดิมไม่ได้ด้วย**
          ⇒ ไฟล์ที่ถูกยกเว้นต้องมีตัวควบคุมของตัวเอง ไม่ใช่ใช้ของกลาง */
    ควบคุม: '\nconst zzวงเล็บไม่ปิด = (\n',
    ควบคุมเล่า: 'ไวยากรณ์พัง ⇒ check-syntax ต้องเห็น (ไฟล์นี้ถูกยกเว้นจากด่าน sentinel)',
    /* ความต่างที่ **เข้าใจแล้วและถูกต้อง** — ต้องมีเหตุผลกำกับเสมอ ไม่ใช่รายชื่อเปล่า
       ⚠️ ถ้าไม่มีช่องนี้ เครื่องมือจะแดงถาวรด้วยเหตุผลที่ถูก ⇒ สุดท้ายถูกถอดทั้งตัว */
    คาดว่าเปลี่ยน: {
      'scripts/เส้นที่ไม่มีใครเรียก.mjs':
        'ทะเบียนนี้เอ่ยพาธของเส้นจริงเส้นหนึ่งเป็นเป้าปลูก (ดูในทะเบียน — ไม่เขียนซ้ำตรงนี้ ' +
        'เพราะข้อความในไฟล์นี้ก็ถูกด่านนั้นกวาดเหมือนกัน) ⇒ ถอดออกแล้วเส้นนั้นย้ายกลุ่ม · ' +
        'ด่านนั้นถูกแก้ให้แยกกลุ่ม "อ้างถึงโดยตัวตรวจเท่านั้น" แล้ว 19 ก.ย. 2569 ⇒ ความต่างนี้คือของที่ควรเกิด',
    },
  },
]

/** ของที่ **รู้ว่าด่านต้องจับ** — ใช้เป็นตัวควบคุมบวกของวิธีวัดเอง
 *  (ของปลูกค้างในรูปโค้ดที่ทำงาน ⇒ check-sentinel-leftovers ต้องเห็น) */
const ตัวควบคุมกลาง = '\nconst ZZPLANTZZ = 1\nexport const zzควบคุม = ZZPLANTZZ\n'

const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'))
const ด่าน = [...new Set([...(pkg.scripts?.prebuild ?? '').matchAll(/scripts\/[^\s&|]+\.mjs/g)].map((m) => m[0]))]
  .filter((p) => !p.includes('/tests/'))
if (ด่าน.length === 0) {
  console.error('🔴 อ่านรายชื่อด่านจาก prebuild ไม่ได้ ⇒ ไม่ใช่ "ไม่มีด่าน" ⇒ ตก')
  process.exit(1)
}

const รันทั้งชุด = () =>
  ด่าน.map((g) => {
    const r = spawnSync('node', [g], { encoding: 'utf8' })
    return { g, out: (r.stdout || '') + (r.stderr || ''), code: r.status }
  })
const ต่างกัน = (a, b) => a.filter((x, i) => x.out !== b[i].out || x.code !== b[i].code).map((x) => x.g)

let ตก = false
for (const { ไฟล์, โครง, ควบคุม, ควบคุมเล่า, คาดว่าเปลี่ยน } of คลัง) {
  const ของคุม = ควบคุม ?? ตัวควบคุมกลาง
  const ร่องรอยคุม = ควบคุม ? 'zzวงเล็บไม่ปิด' : 'ZZPLANTZZ'
  const สกปรก = spawnSync('git', ['status', '--porcelain', '--', ไฟล์], { encoding: 'utf8' })
  if ((สกปรก.stdout || '').trim()) {
    console.error(`🔴 ${ไฟล์} มีของแก้ค้างใน git ⇒ ไม่แตะ (ต้องมีตาข่ายรับก่อน)`)
    ตก = true
    continue
  }
  const เดิม = readFileSync(ไฟล์, 'utf8')
  const คืน = () => { try { writeFileSync(ไฟล์, เดิม) } catch { /* สุดทางแล้ว */ } }
  const สัญญาณ = ['SIGINT', 'SIGTERM', 'SIGHUP']
  const ดัก = () => { คืน(); process.exit(130) }
  for (const s of สัญญาณ) process.on(s, ดัก)
  try {
    console.log(`\n📂 ${ไฟล์} — ด่านที่วัด ${ด่าน.length} ตัว`)
    const มีเนื้อ = รันทั้งชุด()

    writeFileSync(ไฟล์, โครง)
    const ถอดเนื้อ = รันทั้งชุด()

    /* ตัวควบคุมบวก — ต้องทำ **ก่อน**ตีความผลข้างบน ไม่ใช่หลัง */
    writeFileSync(ไฟล์, เดิม + ของคุม)
    if (!readFileSync(ไฟล์, 'utf8').includes(ร่องรอยคุม)) {
      console.error('   🔴 ปลูกตัวควบคุมไม่ลง ⇒ ตัดสินไม่ได้')
      ตก = true
      continue
    }
    const คุม = ต่างกัน(มีเนื้อ, รันทั้งชุด())
    if (คุม.length === 0) {
      console.error(`   🔴 คุม 0/1 — ปลูก "${ร่องรอยคุม}" (${ควบคุมเล่า ?? 'ของปลูกค้างในรูปโค้ดที่ทำงาน'}) แล้ววิธีวัดยังบอกว่า "ไม่ต่าง"`)
      console.error('      ⇒ วิธีวัดไม่มีพลังแยกแยะ ⇒ **ห้ามอ่านผลด้านล่างว่าปลอดภัย**')
      ตก = true
      continue
    }
    console.log(`   ✅ คุม 1/1 ผ่าน (${คุม.join(' · ')} เห็นของที่ปลูก) ⇒ ผลด้านล่างเชื่อได้`)

    const เปลี่ยน = ต่างกัน(มีเนื้อ, ถอดเนื้อ)
    const รู้แล้ว = คาดว่าเปลี่ยน ?? {}
    const ใหม่ = เปลี่ยน.filter((g) => !รู้แล้ว[g])
    for (const g of เปลี่ยน.filter((g) => รู้แล้ว[g])) {
      console.log(`   📎 เปลี่ยนตามที่คาดไว้: ${g}`)
      console.log(`      เหตุผล: ${รู้แล้ว[g]}`)
    }
    /* รายชื่อที่คาดไว้แล้วไม่เกิดจริง = คำอธิบายที่หมดอายุ ⇒ ต้องรู้ ไม่ใช่ปล่อยเงียบ */
    for (const g of Object.keys(รู้แล้ว)) {
      if (!เปลี่ยน.includes(g)) {
        console.error(`   🔴 คาดว่า ${g} จะเปลี่ยน แต่ไม่เปลี่ยน ⇒ เหตุผลที่จดไว้หมดอายุแล้ว ต้องลบหรือแก้`)
        ตก = true
      }
    }
    if (ใหม่.length === 0) {
      console.log(`   ✅ ถอดเนื้อในคลังออก ⇒ ด่าน ${ด่าน.length} ตัว ไม่มีตัวไหนเปลี่ยนผลนอกเหนือจากที่อธิบายไว้`)
    } else {
      console.error(`   🔴 ด่านที่ผลเปลี่ยนโดยไม่มีคำอธิบาย ${ใหม่.length} ตัว: ${ใหม่.join(' · ')}`)
      console.error('      ⇒ ด่านพวกนี้ตัดสินจาก **ข้อความตัวอย่างในคลัง** ไม่ใช่จากโค้ดจริง')
      console.error('      ⇒ เปิดอ่านก่อนตัดสิน — อาจเป็นของที่ควรเกิด (แล้วจดลง คาดว่าเปลี่ยน พร้อมเหตุผล)')
      ตก = true
    }
  } finally {
    คืน()
    for (const s of สัญญาณ) process.off(s, ดัก)
  }
}

console.log(`\n📏 ขอบเขต: ด่านใน prebuild ${ด่าน.length} ตัว · คลังที่ตรวจ ${คลัง.length} ไฟล์ · วัดที่เนื้อไฟล์ ณ วันนี้`)
console.log('   ⚠️ เพิ่มรูปใหม่เข้าคลังเมื่อไหร่ ให้รันตัวนี้ซ้ำ — ผลเก่าไม่ครอบเนื้อใหม่')
process.exit(ตก ? 1 : 0)
