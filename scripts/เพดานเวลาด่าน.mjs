#!/usr/bin/env node
/* เพดานเวลาของด่านตอน build — ท่านประธานสั่ง 12 ต.ค. 2569
 * "หาวิธีป้องกันแก้ไขเหตุการณ์นี้ อัตโนมัติ"
 *
 * 🔴 **เหตุการณ์ที่ต้องกัน**: ด่านตอน build โตจากไม่กี่ตัวเป็น **165 ตัว** โดยไม่มีใครรู้ตัว
 *    จนรันครั้งละ 6 นาที (เคยถึง 1 ชม. 22 นาที) ⇒ ทีมติดทุกครั้ง ⇒ เริ่มมีคนข้ามด่าน
 *    ⇒ ด่านทั้งหมดไร้ค่าพร้อมกัน
 *
 * 🔑 **ทำไมกฎที่เขียนไว้เฉย ๆ ไม่พอ** (เหตุผลที่ต้องมีไฟล์นี้)
 *    สาเหตุจริงไม่ใช่ "คนไม่รู้ว่าด่านเยอะไม่ดี" — ทุกคนรู้
 *    สาเหตุคือ **ไม่มีใครถือหน้าที่ดูเวลา** ⇒ ด้านความถูกต้องโตได้ฟรี ไม่มีแรงต้าน
 *    ⇒ แก้ด้วยการ **ให้เวลามีเจ้าของเป็นตัวเลข** แล้วให้ตัวเลขนั้นทักเอง
 *
 * 🔑 **ทำไมไม่ทำให้มันตีกลับ**: บทเรียนของวันเดียวกัน — ด่านที่ขวางทางจนคนข้าม = ไร้ค่า
 *    ⇒ เกินเพดาน ⇒ **เปิดใบงานบนกระดานอัตโนมัติ** ไม่บล็อกใคร
 *       แต่ก็ไม่ปล่อยให้เงียบ เพราะใบงานมีคนเห็นแน่นอน
 *
 * ใช้:  node scripts/เพดานเวลาด่าน.mjs เริ่ม     ← วางเป็นด่านแรกของ prebuild
 *       node scripts/เพดานเวลาด่าน.mjs จบ        ← วางเป็นด่านสุดท้าย
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

/* เพดาน 60 วินาที — ตอนตั้ง (12 ต.ค. 2569) ของจริงอยู่ที่ 12 วิ ⇒ มีที่ให้โตอีก 5 เท่า
   ⚠️ **ห้ามขยายเพดานเพื่อให้ผ่าน** — เพดานมีไว้บังคับให้เลือก ไม่ได้มีไว้ให้ปรับตาม
      จะขยายต้องมีเหตุผลที่ไม่ใช่ "ของเราเกินแล้ว" (เช่น เครื่อง build ช้าลงจริง) */
const เพดานวินาที = Number(process.env.GATE_BUDGET_SEC || 60)
const ที่จด = join(tmpdir(), `gate-timer-${process.env.npm_package_name || 'repo'}.txt`)
const คำสั่ง = process.argv[2]

if (คำสั่ง === 'เริ่ม') {
  writeFileSync(ที่จด, String(Date.now()))
  process.exit(0)
}

if (คำสั่ง !== 'จบ') {
  console.error('ใช้: เพดานเวลาด่าน.mjs เริ่ม|จบ')
  process.exit(2)
}

if (!existsSync(ที่จด)) {
  /* 🔑 ไม่มีหมุดเริ่ม = วัดไม่ได้ ⇒ **บอกว่าวัดไม่ได้ ห้ามเงียบ**
     (เงียบ = เพดานนี้ตายเองโดยไม่มีใครรู้ ซึ่งคือคลาสเดียวกับที่เรากำลังกัน) */
  console.log('⏱️  เพดานเวลาด่าน: วัดไม่ได้ (ไม่เจอหมุดเริ่ม) — ไม่ใช่ว่าผ่าน')
  process.exit(0)
}

const วินาที = (Date.now() - Number(readFileSync(ที่จด, 'utf8'))) / 1000
const เกิน = วินาที > เพดานวินาที
console.log(`⏱️  ด่านตอน build ใช้ ${วินาที.toFixed(1)} วิ (เพดาน ${เพดานวินาที})` +
            (เกิน ? ' ❌ เกิน' : ' ✓'))

if (!เกิน) process.exit(0)

console.log('   ⚠️ ด่านโตเกินเพดาน — ให้ย้ายตัวที่ไม่ได้กันเงิน/ข้อมูลหาย ไปที่ `npm run ตรวจ`')
console.log('   🚫 ห้ามแก้ด้วยการขยายเพดาน')

/* เปิดใบงานอัตโนมัติ — ไม่บล็อก build แต่ไม่ปล่อยให้เงียบ
   ⚠️ ยิงไม่ถึงก็ไม่ล้ม build (เพดานนี้ไม่ใช่ของที่ควรทำให้ deploy พัง) */
const คีย์ = process.env.GUCUT_WEB_ADMIN_KEY
if (คีย์) {
  try {
    await fetch('https://gucut.com/api/office', {
      method: 'POST',
      headers: { 'content-type': 'application/json', 'x-admin-key': คีย์ },
      body: JSON.stringify({
        taskAdd: `⏱️ ด่านตอน build โตเกินเพดาน (${วินาที.toFixed(0)} วิ > ${เพดานวินาที}) — ย้ายตัวที่ไม่ได้กันเงิน/ข้อมูลไป npm run ตรวจ`,
      }),
      signal: AbortSignal.timeout(8000),
    })
    console.log('   📋 เปิดใบงานบนกระดานให้แล้ว')
  } catch {
    console.log('   (เปิดใบงานไม่สำเร็จ — ยังเห็นคำเตือนนี้ในล็อก build)')
  }
}
process.exit(0)
