#!/usr/bin/env node
/* ข้อทดสอบที่ **เขียนไว้แล้วไม่ได้รัน** — `fail 0` จะยังสวยอยู่ทุกครั้ง
 *
 * 🔴 ที่มา 20 ก.ย. 2569 (ฝั่งท่อเจอของจริง): เขียนเทส 6 ข้อ ⇒ รายงาน **`pass 1 · fail 0`**
 *    เพราะ `process.exit` ในโค้ดที่ถูกทดสอบ **ฆ่าโปรเซสตั้งแต่ข้อแรก** ⇒ อีก 5 ข้อไม่เคยรัน
 * 🔑 คำของเขาที่เป็นแกนของด่านนี้:
 *    **`fail 0` คือสิ่งที่เราอยากเห็น — สิ่งที่ควรสะดุดคือ `pass` น้อยกว่าที่เขียน**
 *    ⇒ ⇒ ตัวเลขที่เราจ้องมาตลอด (`fail`) **มองไม่เห็นคลาสนี้เลยโดยธรรมชาติ**
 *
 * 📏 วัดฝั่งเราตอนเขียน: **0 ไฟล์** ที่ `# tests` ไม่ตรงกับจำนวน `test(` ที่เขียนไว้
 *    ⚠️ และรอบแรกผมวัดด้วยการนับบรรทัด ✅ ⇒ **ได้ผลผิดทั้งสองทิศ**
 *       (ไฟล์ที่ใช้ `node:test` ไม่พิมพ์ ✅ · ไฟล์ที่ใช้ลูปพิมพ์ ✅ มากกว่าจำนวนที่เขียน)
 *       ⇒ จึงเทียบกับ **`# tests` ที่ node:test รายงานเอง** ไม่ใช่กับสิ่งที่เราเดาจากข้อความ
 *
 * 🚫 ขอบเขต (เขียนไว้ ไม่งั้นเขียวของมันจะถูกอ่านเกินจริง):
 *    · ครอบเฉพาะไฟล์ที่ใช้ **`node:test`** — ไฟล์ที่เขียนเองด้วยตัวนับมือ **ด่านนี้ไม่รู้**
 *      (นับข้อของมันเชื่อถือไม่ได้ เพราะลูปหนึ่งบรรทัดสร้างได้หลายข้อ)
 *    · บอกได้ว่า "ข้อหาย" — **บอกไม่ได้ว่าข้อที่รันนั้นตรวจถูกหรือเปล่า**
 */
import { readdirSync, readFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { join } from 'node:path'

const dir = 'scripts/tests'
const ไฟล์ = readdirSync(dir).filter((n) => n.endsWith('.mjs')).sort()
const ผิด = []
let ตรวจได้ = 0, ข้ามเพราะนับมือ = 0

for (const n of ไฟล์) {
  const src = readFileSync(join(dir, n), 'utf8')
  /* ใช้ node:test ไหม — ดูที่ import จริง ไม่ใช่แค่คำว่า test โผล่ในไฟล์ */
  if (!/from ['"]node:test['"]/.test(src)) { ข้ามเพราะนับมือ++; continue }
  /* นับเฉพาะ `test(` ที่ขึ้นต้นบรรทัด (การเรียกจริง) — กันคำในคอมเมนต์/สตริง */
  const เขียน = (src.match(/^\s*test\s*\(/gm) ?? []).length
  let out = ''
  try {
    out = execFileSync(process.execPath, [join(dir, n)], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 120000 })
  } catch (e) {
    out = String(e?.stdout ?? '') + String(e?.stderr ?? '')
  }
  const รายงาน = Number((out.match(/# tests (\d+)/) ?? [])[1] ?? NaN)
  ตรวจได้++
  if (!Number.isFinite(รายงาน)) {
    ผิด.push(`${n} — ใช้ node:test แต่ **ไม่มีบรรทัด \`# tests\`** ⇒ โปรเซสน่าจะตายก่อนสรุปผล`)
  } else if (รายงาน !== เขียน) {
    ผิด.push(`${n} — เขียนไว้ **${เขียน}** ข้อ แต่รันจริง **${รายงาน}** ข้อ ⇒ **${เขียน - รายงาน} ข้อไม่ได้รัน**`)
  }
}

console.log(`ตรวจว่าข้อทดสอบได้รันครบไหม: ไฟล์ใน ${dir} **${ไฟล์.length}** · ใช้ node:test **${ตรวจได้}** · ข้ามเพราะนับเอง **${ข้ามเพราะนับมือ}**`)
console.log('   ⚠️ ด่านนี้บอกได้ว่า "ข้อหาย" — **บอกไม่ได้ว่าข้อที่รันตรวจถูกหรือเปล่า**')
if (ผิด.length) {
  console.error('\n🔴 มีข้อทดสอบที่เขียนไว้แล้วไม่ได้รัน')
  for (const x of ผิด) console.error('   ' + x)
  console.error('\n   ⚠️ `fail 0` จะยังสวยอยู่ทุกครั้ง ⇒ **ตัวเลขที่ต้องจ้องคือ `pass` เทียบกับที่เขียน**')
  console.error('   เหตุที่พบบ่อย: โค้ดที่ถูกทดสอบเรียก `process.exit` ⇒ ฆ่าโปรเซสตั้งแต่ข้อแรก')
  process.exit(1)
}
console.log('✅ ทุกไฟล์ที่ใช้ node:test รันครบทุกข้อที่เขียนไว้')
