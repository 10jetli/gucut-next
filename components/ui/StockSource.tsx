//    และมีของกลุ่มหนึ่งที่ **ทะเบียนใบอนุญาตทับ ZORT โดยตั้งใจ** (เจ้าของร้านสั่ง 25 ก.ย. 2569)
//    ⇒ คนเปิดจอเห็นเลขไม่ตรง ZORT แล้วสรุปว่า "ระบบเพี้ยน" ทั้งที่ตั้งใจให้ต่าง
//
// 🔒 **สามข้อที่ฝั่งท่อกำกับมา และชิ้นนี้ทำตามทั้งหมด**
//    ① ใช้ `srcNote` ที่ท่อส่งมา **ห้ามเขียนคำแปลเองที่จอ** ไม่งั้นมีคำแปลสองชุดในระบบ
//       ⇒ ค่าที่ท่อไม่ได้ส่งคำอธิบายมาให้ จอ **โชว์ค่าดิบ** แล้วบอกว่ายังไม่มีคำอธิบาย
//    ② ช่องนี้บอก **แหล่งของตัวเลข** ไม่ได้บอกว่าเลขถูกหรือผิด ⇒ ห้ามเขียนว่าเลขไหนถูก
//    ③ เพิ่มช่องอย่างเดียว ⇒ จอต้องทำงานได้เหมือนเดิมตอนท่อยังไม่ส่งช่องนี้
//
// 🔑 ตรรกะการตัดสินอยู่ที่ `lib/stock-source.ts` (ทดสอบได้โดยไม่ต้องเรนเดอร์)
//
// ⚠️ **ไม่มีช่อง ≠ ไม่มีที่มา** — ท่อรุ่นก่อน 28 ก.ย. 2569 ไม่ส่งสามช่องนี้
//    (และช่วง deploy เหลื่อมจะมีทั้งสองรุ่นอยู่พร้อมกัน) ⇒ ต้องเขียนบนจอว่า "ท่อรุ่นนี้ยังไม่ส่ง"
//    ห้ามเงียบ เพราะความเงียบจะถูกอ่านว่า "เลขนี้มาจากทางปกติ" ซึ่งเรายังไม่รู้

import { ตัดสินที่มา, type ที่มาเลขสต็อก, type แผนที่ป้ายที่มา } from '@/lib/stock-source'

export default function StockSource(
  { row, ป้าย, สั้น = false }: {
    row: ที่มาเลขสต็อก | null | undefined
    /** แผนที่ป้ายจากคำตอบของท่อ (`srcLabels`) — ส่งมาได้ก็ส่ง ไม่มีก็ตกไปใช้ srcNote ของแถว */
    ป้าย?: แผนที่ป้ายที่มา | null
    สั้น?: boolean
  },
) {
  const ผล = ตัดสินที่มา(row, ป้าย)

  /* ① ท่อยังไม่ส่งช่องนี้ — ต่างจาก "มาจากทางปกติ" ⇒ ต้องเขียนออกมา ไม่ใช่เงียบ */
  if (ผล.แบบ === 'ท่อไม่ส่ง') {
    return (
      <div className="text-[11px] text-gray-400">
        ที่มาของเลข: <b>ท่อรุ่นนี้ยังไม่ส่งช่องนี้</b>
        {!สั้น && ' — ไม่ใช่ว่าเลขนี้ไม่มีที่มา'}
      </div>
    )
  }

  /* ② มีคำอธิบายจากท่อ ⇒ ใช้ข้อความของท่อตรง ๆ */
  if (ผล.แบบ === 'มีคำอธิบายจากท่อ') {
    return (
      <div className="text-[11px] leading-relaxed text-amber-800 bg-amber-50 border border-amber-200 rounded px-2 py-1">
        ที่มาของเลข: <code className="text-[10px]">{ผล.src}</code>
        <div>{ผล.note}</div>
        {ผล['ทะเบียนว่า'] !== null && (
          <div>
            ทะเบียนว่า <b>{ผล['ทะเบียนว่า']}</b>
            {!สั้น && ' · เลขบนการ์ดมาจากกระจก ⇒ สองเลขต่างกันได้โดยตั้งใจ (ช่องนี้บอกแหล่ง ไม่ได้บอกว่าเลขไหนถูก)'}
          </div>
        )}
      </div>
    )
  }

  /* ③ ค่าดิบที่ท่อไม่ได้ส่งคำอธิบายมา */
  return (
    <div className="text-[11px] text-gray-500">
      ที่มาของเลข: <code className="text-[10px]">{ผล.src}</code>
      {!สั้น && <span className="text-gray-400"> · ท่อไม่ได้ส่งคำอธิบายของที่มานี้ (จอไม่แปลเอง)</span>}
    </div>
  )
}
