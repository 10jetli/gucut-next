'use client'
import type { ReactNode } from 'react'

/** ปุ่ม "ส่งจริงเข้า ZORT" — ปุ่มที่ยิงของจริง จึงมีสองสภาพที่ต้องอ่านออกทั้งคู่
 *
 * 🔴 **ที่มา 12 ต.ค. 2569 — ท่านประธานแจ้งเองว่า "ฟอนต์ขาวอ่านไม่ได้"**
 *    ของเดิม: ตัวหนังสือ **ขาว** บนพื้น `#9aa0a6` = **2.64:1** (เกณฑ์ 4.5:1)
 *    และยังมี `disabled:opacity-40` ทับอีกชั้น ⇒ **ของที่ตาเห็นจริงคือ 1.43:1**
 *    (ผสม 40% ลงบนพื้นหน้าเว็บ: ตัวหนังสือกลายเป็น #fafafb บนพื้น #d1d4d8)
 *    ⚠️ ⇒ **ตัวกวาดคอนทราสต์ที่ไม่คิดชั้น opacity จะรายงานเลขที่ดีกว่าความจริง**
 *       จุดที่แย่ที่สุดจึงดูเหมือนจุดกลาง ๆ — ของเราบอก 2.64 ทั้งที่ของจริง 1.43
 *    ⇒ กวาด 77 จอบน 1.gucut.com แล้วจุดนี้เป็นจุดที่แย่ที่สุด · `grep 9aa0a6` ได้ **12 ไฟล์**
 *       (ตัวกวาดเห็นแค่ 3 เพราะอีก 9 เป็นจอลูกที่ไม่อยู่ในเมนู — ตัวกวาดเดินไม่ถึง ไม่ใช่ไม่มี)
 *
 * 🔑 **ปุ่มที่กดไม่ได้ ไม่ควรเป็นปุ่มที่อ่านไม่ได้**
 *    สภาพปิดมีหน้าที่บอกว่า "ปุ่มนี้คืออะไร และทำไมยังกดไม่ได้"
 *    ถ้าอ่านไม่ออก คนจะไม่รู้ว่าติดอะไรอยู่ แล้วเดาเอาเอง
 *    ⇒ สภาพปิดจึงใช้ **ตัวหนังสือเข้มบนพื้นเทาอ่อน** ไม่ใช่ขาวบนเทา และ **ไม่ลด opacity**
 *       สัญญาณว่า "ปิดอยู่" มาจาก **สีที่หายไป** (ไม่ใช่สีแบรนด์แดง) + `cursor-not-allowed`
 *       ไม่ได้มาจากการทำให้มองไม่เห็น
 *
 * 🔑 **เกณฑ์มีสองข้อ ไม่ใช่ข้อเดียว** (ฝั่งท่อชี้ 12 ต.ค. 2569 — ร่างแรกของผมตกข้อสอง)
 *    ① สภาพปิดต้องอ่านออก: **≥ 4.5:1**
 *    ② สภาพปิดต้อง **ไม่เด่นกว่า** สภาพกดได้: `คอนทราสต์(ปิด) ≤ คอนทราสต์(กดได้)`
 *    ร่างแรกใช้ #374151 ได้ 8.33:1 ซึ่งผ่านข้อ ① สวยงาม **แต่ตกข้อ ②** (กดได้ 5.44)
 *    ⇒ ตาจะวิ่งไปที่ปุ่มที่กดไม่ได้ก่อน = แก้อาการเดิมแล้วสร้างอาการใหม่กลับหัว
 *    ⇒ เลือก #596273 = 4.96:1 · ผ่านทั้งสองข้อโดย **ไม่ต้องแตะสีแบรนด์** (ซึ่งเป็นของจานสีกลาง)
 *    ⚠️ ระยะห่าง 4.96 กับ 5.44 **บางมาก** ⇒ ใครแก้สีใดสีหนึ่ง ต้องคิดใหม่ทั้งคู่ ไม่ใช่ทีละตัว
 *
 * ⚠️ เหตุที่ต้องเป็น component ไม่ใช่แก้ทีละไฟล์: รูปเดิมถูกลอกต่อกันมา 12 จอ
 *    แก้ทีละที่ = รอบหน้ามีคนลอกจอที่ยังไม่ได้แก้ไปอีก (กฎข้อ 5 ของ CLAUDE.md)
 */
export default function PillSend({
  พร้อมส่งจริง,
  กำลังส่ง = false,
  onClick,
  children = 'ส่งจริงเข้า ZORT',
  title,
  เล็ก = false,
}: {
  /** เงื่อนไขครบจริงไหม (ทดลองส่งผ่านแล้ว · เปิดส่งจริง · ไม่ใช่โหมดที่ปิดไว้) */
  พร้อมส่งจริง: boolean
  กำลังส่ง?: boolean
  /** ปุ่มที่ปิดถาวร (เช่นจอนำเข้า) ไม่มีตัวสั่งงาน ⇒ optional */
  onClick?: () => void
  children?: ReactNode
  /** เหตุที่ยังกดไม่ได้ — ขึ้นตอนชี้ค้าง · จอยังต้องเขียนเหตุเป็นข้อความข้าง ๆ ด้วย */
  title?: string
  /** 3 จอจาก 11 ใช้ 12.5px อยู่เดิม — ให้คงขนาดเดิมไว้ ไม่ใช่ยุบทุกจอให้เท่ากันในรอบนี้
   *  (งาน "ยุบ body เหลือขนาดเดียว" เป็นอีกใบ · รวมสองเรื่องเข้าด้วยกันแล้วถ้าจอเพี้ยน
   *   จะแยกไม่ออกว่าเพี้ยนเพราะสีหรือเพราะขนาด) */
  เล็ก?: boolean
}) {
  const ปิดอยู่ = !พร้อมส่งจริง || กำลังส่ง
  return (
    <button
      type="button"
      onClick={onClick}
      disabled={ปิดอยู่}
      title={title}
      className={`${เล็ก ? 'text-[12.5px] px-5' : 'text-[14px] px-6'} font-semibold rounded-full py-2 min-h-[40px] ${
        ปิดอยู่ ? 'cursor-not-allowed' : ''
      }`}
      style={
        ปิดอยู่
          ? { background: '#e5e7eb', color: '#596273' }  // วัดได้ 4.96:1 — อ่านออก แต่ไม่แย่งสายตาปุ่มที่กดได้
          : { background: '#c0392b', color: '#ffffff' }  // วัดได้ 5.44:1 — สีแบรนด์เดิม ไม่แตะจานสีกลาง
      }
    >
      {/* ⚠️ ไม่สลับข้อความตอนกำลังส่ง **โดยตั้งใจ** — ใบนี้แก้เรื่องอ่านออก ไม่ใช่เรื่องถ้อยคำ
          รวมสองเรื่องเข้าด้วยกันแล้วถ้าจอเพี้ยน จะแยกไม่ออกว่าเพี้ยนเพราะอะไร */}
      {children}
    </button>
  )
}
