// กล่องบอกว่า "ค่าที่จอขอ ไม่ใช่ค่าที่ท่อใช้" — ใช้ได้กับทุกจอที่ยิงเส้นซึ่งรายงาน `clamped`
//
// 🔑 หัวข้อความต้อง **ไม่บอกว่าล้มเหลว** เพราะคำขอสำเร็จ · แต่ต้องไม่เงียบ เพราะเลขบนจอ
//    ไม่ได้มาจากค่าที่คนกรอก (คลาส "ระบบทำงานถูก แต่สื่อสารผิด")
// ⚠️ ห้ามเขียนว่า "ถูกปฏิเสธ" — บีบ ≠ ปฏิเสธ (ปฏิเสธคือ 400 ซึ่งไม่มาอยู่ในก้อนนี้)
import { อ่านการบีบ, เทียบขอกับใช้, type คำตอบที่อาจถูกบีบ } from '@/lib/clamped'

export default function ClampedNote(
  { resp, ขอ }: {
    resp: คำตอบที่อาจถูกบีบ | null | undefined
    /** ค่าที่จอส่งไป — ใช้เป็นทางถอยตอนท่อยังไม่มีก้อน `clamped` */
    ขอ?: Record<string, unknown> | null
  },
) {
  const จากท่อ = อ่านการบีบ(resp)
  const เดาจากapplied = จากท่อ.length ? [] : เทียบขอกับใช้(ขอ, resp)
  const บรรทัด = [...จากท่อ, ...เดาจากapplied]
  if (!บรรทัด.length) return null

  return (
    <div className="mt-2 rounded-lg border border-sky-300 bg-sky-50 px-2.5 py-2 text-[11px] leading-relaxed text-sky-900">
      <b>ค่าที่ท่อใช้จริงไม่ตรงกับที่จอขอ {บรรทัด.length} ช่อง</b> — เลขบนจอเป็นผลของค่าที่ท่อใช้
      <ul className="mt-1 list-disc pl-4">
        {บรรทัด.map((b) => (
          <li key={b['ช่อง']}>
            <b>{b['ช่อง']}</b>: ขอ {b['ที่ขอ']} · ใช้จริง <b>{b['ที่ใช้']}</b>
            {b['เหตุ'] ? ` — ${b['เหตุ']}` : ' — ท่อรุ่นนี้ยังไม่บอกเหตุ (จอไม่เดาเหตุให้)'}
          </li>
        ))}
      </ul>
    </div>
  )
}
