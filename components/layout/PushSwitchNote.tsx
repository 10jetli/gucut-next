'use client'
// คำเตือน "สต็อกบนช่องทางไหนยังไม่ถูกดันกลับ" — ต่อท้ายแถบป้ายเฉพาะจอที่เอกสารทำให้สต็อกขยับ
//
// 🔴 **ที่มา 18 ก.ย. 2569** — CEO ชี้ว่าใบขายที่เปิดจากจอเรา **ลดสต็อก**
//    แต่สวิตช์ดันสต็อก Shopee/TikTok **ยังปิดอยู่** (รอท่านประธาน)
//    ⇒ เปิดใบที่จอเราตอนนี้ สต็อกบนสองเจ้านั้นไม่ขยับเลย ⇒ **ขายเกินสต็อกได้จริง**
//    ⇒ ไม่ใช่ "ยังไม่ครบกระบวนการ" แบบทฤษฎี มันขาดอยู่ตอนนี้จริง ๆ
//
// ⚠️ **คิดจาก `autoOn` ที่ท่อส่งมา ห้ามเขียนชื่อเจ้าที่ปิดฝังไว้**
//    วันที่ท่านประธานสั่งเปิดสวิตช์ ข้อความนี้ต้อง**หายเอง** ไม่ต้องรอใครมาถอด
//    (กฎเดียวกับที่ใช้กับป้ายทั้งแผง — คำเตือนหมดอายุคือโรคที่ไล่กันมาทั้งวัน)
// ⚠️ ถามไม่ได้ ⇒ **เงียบ** ไม่ใช่เดาว่าปิดหรือเปิด (ถามไม่ได้ ≠ ปิดอยู่)
// ⚠️ ขึ้นเฉพาะเส้นทางที่อยู่ใน `กระทบสต็อก` — จอที่ไม่ขยับสต็อกเตือนไปก็เป็นเสียงรบกวน
import { useEffect, useState } from 'react'

const ชื่อเจ้า: Record<string, string> = { shopee: 'Shopee', lazada: 'Lazada', tiktok: 'TikTok' }

export default function PushSwitchNote() {
  const [ปิดอยู่, setปิดอยู่] = useState<string[] | null>(null)

  useEffect(() => {
    let ทิ้งแล้ว = false
    ;(async () => {
      try {
        const res = await fetch('/api/web/core?pushstate=1')
        const d = await res.json()
        if (ทิ้งแล้ว || !res.ok || d?.error || !d?.byChannel) return
        const off = Object.entries(d.byChannel as Record<string, { autoOn?: boolean; 'มีตัวยิง'?: boolean }>)
          /* มีตัวยิงแต่สวิตช์ปิด = เรื่องที่ต้องเตือน · ไม่มีตัวยิงเลยเป็นอีกเรื่อง (จอดันสต็อกบอกอยู่แล้ว) */
          .filter(([, v]) => v?.['มีตัวยิง'] === true && v?.autoOn === false)
          .map(([k]) => ชื่อเจ้า[k] ?? k)
        setปิดอยู่(off)
      } catch { /* เงียบโดยตั้งใจ — ถามไม่ได้ ≠ ปิดอยู่ */ }
    })()
    return () => { ทิ้งแล้ว = true }
  }, [])

  if (!ปิดอยู่ || ปิดอยู่.length === 0) return null
  /* 🔴 **เขียนกลไก ไม่ใช่ผลที่ทำนาย** (CEO แก้ให้ 18 ก.ย. 2569 ก่อนขึ้นจอจริง)
     ฉบับแรกผมเขียนว่า "ของบนสองช่องทางนั้นยังขายต่อได้ทั้งที่ของหมด" — **แข็งเกินหลักฐาน**
     จอนี้ไม่รู้ว่าเลขที่ตั้งไว้บนแพลตฟอร์มเป็นเท่าไร ⇒ อาจไม่มีของค้างสักตัวก็ได้
     ⇒ กลไก ("ใบนี้จะไม่ไปลดสต็อก") เป็นจริงทุกกรณี · ผลขึ้นกับเลขที่เราไม่เห็นจากจอนี้
     🔑 คำว่า "อาจ" ไม่ได้ทำให้คำเตือนอ่อนลง — มันทำให้คนเชื่อคำเตือนอื่นของเราต่อไป
     (ตระกูลเดียวกับที่ไล่กันมาทั้งวัน: note เรื่องคลัง KLD · ฟิลด์ denied · ป้าย 🟢) */
  return (
    <span className="block">
      🔴 ใบที่เปิดที่นี่จะ<b>ไม่ไปลดสต็อกบน {ปิดอยู่.join(' · ')}</b> จนกว่าสวิตช์ดันสต็อกจะเปิด
      {' '}(ปิดอยู่ รอคำสั่งท่านประธาน) ⇒ ถ้าเลขบนช่องทางนั้นสูงกว่าของจริง <b>ลูกค้าอาจสั่งของที่เราไม่มี</b>
    </span>
  )
}
