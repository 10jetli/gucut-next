'use client'
/* ประตูของตัวเลือก "กำไร" — ถามท่อว่าช่วงวันที่จอกำลังโชว์ มีต้นทุนครอบพอจะคิดยอดรวมได้ยัง
 *
 * 🔑 **ทำไมเป็นของร่วม** — จอภาพรวมกับจอยอดขายมีตัวเลือกกำไรทั้งคู่
 *    ถ้าเขียนแยก สองจอจะบอกคนละอย่างในวันที่เกณฑ์เปลี่ยน (เคยเจอคลาสนี้มาแล้วหลายรอบ)
 *
 * 🔴 **สามสภาพที่อ่านเหมือนกันถ้าไม่แยก — ที่นี่แยก**
 *    ① `กำลังถาม`     ⇒ ยังไม่รู้ · ห้ามเขียนว่าไม่ถึงเกณฑ์
 *    ② `ถามไม่สำเร็จ` ⇒ **ท่อตอบไม่ได้** คนละเรื่องกับ "ท่อตอบว่าไม่ถึงเกณฑ์"
 *       (ถ้ายุบรวม วันที่ท่อล่ม จอจะประกาศว่าต้นทุนไม่พอ ซึ่งเป็นคำกล่าวอ้างที่เราไม่ได้วัด)
 *    ③ สภาพจาก `lib/costsince.ts` ⇒ ท่อตอบแล้ว · ตัวตัดสินอยู่ที่นั่น มีเทส 26 ข้อคุม
 */
import { useCallback, useEffect, useState } from 'react'
import { อ่านสภาพต้นทุน, type CostSinceตอบ, type สภาพต้นทุน } from '@/lib/costsince'

export type ประตูกำไร =
  | { ชนิด: 'กำลังถาม' }
  | { ชนิด: 'ถามไม่สำเร็จ'; เหตุ: string }
  | { ชนิด: 'ตอบแล้ว'; สภาพ: สภาพต้นทุน }

/** เปิดตัวเลือก **ยอดรวม** ได้ไหม — ค่าเริ่มต้นคือ "ไม่" ทุกสภาพที่ไม่ใช่ "ตอบแล้วว่าถึงเกณฑ์"
 *  🔑 ค่าตั้งต้นที่น่าเชื่อถือที่สุด คือที่ที่ความผิดพลาดแพงที่สุด —
 *     ที่นี่ความผิดพลาดคือ "โชว์กำไรรวมที่สูงเกินจริง" ⇒ ตั้งต้นว่าปิด */
export const เปิดยอดรวมได้ = (ป: ประตูกำไร) => ป.ชนิด === 'ตอบแล้ว' && ป.สภาพ.เปิดยอดรวมได้

/** ข้อความสั้นสำหรับต่อท้ายป้ายตัวเลือก (คนเห็นตอนกางรายการ) */
export function ป้ายสั้น(ป: ประตูกำไร): string {
  if (ป.ชนิด === 'กำลังถาม') return 'กำลังถามท่อว่าคิดได้ยัง'
  if (ป.ชนิด === 'ถามไม่สำเร็จ') return 'ถามท่อไม่สำเร็จ — ยังไม่รู้ว่าคิดได้ยัง'
  const ส = ป.สภาพ
  switch (ส.ชนิด) {
    case 'ท่อรุ่นเก่า': return 'ท่อยังไม่ส่งสภาพต้นทุนของช่วงวันมา'
    case 'ยังไม่เริ่มตรึง': return 'ยังไม่เริ่มตรึงต้นทุนลงบรรทัดขาย'
    case 'ช่วงนี้ไม่มีบรรทัดขาย': return 'ช่วงนี้ไม่มีบรรทัดขาย'
    case 'แปลไม่ได้': return 'ท่อยังแปลผลช่วงนี้ไม่ได้'
    case 'ยังไม่ถึงเกณฑ์':
      return `ครอบ ${ส.ครอบ ?? '—'}% ต้องถึง ${ส.เกณฑ์ ?? '—'}%`
    case 'ถึงเกณฑ์': return ''
  }
}

/** เหตุเต็มสำหรับ `title` และกล่องข้อความ */
export const เหตุเต็ม = (ป: ประตูกำไร): string =>
  ป.ชนิด === 'กำลังถาม' ? 'กำลังถามท่อ — ยังไม่รู้ว่าคิดยอดรวมได้หรือไม่'
    : ป.ชนิด === 'ถามไม่สำเร็จ'
      ? `ถามท่อไม่สำเร็จ: ${ป.เหตุ} ⇒ **ยังไม่รู้** ไม่ใช่ว่าต้นทุนไม่พอ`
      : ป.สภาพ.เหตุ

/** ถามท่อ · ส่ง from/to เสมอถ้าจอมี (สัญญากำกับไว้: ไม่ส่ง = ได้แต่เลขทั้งกระจกซึ่งตัดสินใจไม่ได้) */
export function useประตูกำไร(from?: string | null, to?: string | null): ประตูกำไร {
  const [ป, setป] = useState<ประตูกำไร>({ ชนิด: 'กำลังถาม' })
  const ถาม = useCallback(async () => {
    setป({ ชนิด: 'กำลังถาม' })
    try {
      const q = new URLSearchParams({ costsince: '1' })
      if (from) q.set('from', from)
      if (to) q.set('to', to)
      const r = await fetch(`/api/web/core?${q.toString()}`)
      const j = (await r.json()) as CostSinceตอบ & { error?: string }
      if (!r.ok || j?.error) throw new Error(j?.error ?? `HTTP ${r.status}`)
      setป({ ชนิด: 'ตอบแล้ว', สภาพ: อ่านสภาพต้นทุน(j) })
    } catch (e) {
      setป({ ชนิด: 'ถามไม่สำเร็จ', เหตุ: e instanceof Error ? e.message : String(e) })
    }
  }, [from, to])
  useEffect(() => { void ถาม() }, [ถาม])
  return ป
}

/** บรรทัดเดียวใต้ตัวเลือก — **มองเห็น ไม่ใช่ `title`**
 *  ⚠️ **ชื่อคอมโพเนนต์เป็น ASCII โดยตั้งใจ** — ตัวแปร/prop ภาษาไทยในรีโปนี้เดินมาแล้วนับไม่ถ้วน
 *     แต่ **แท็ก JSX ชื่อไทยยังไม่เคยถูกเดินเลยสักจุด** (กวาด app/ components/ 5 ต.ค. 2569:
 *     40 จุดที่ตะแกรงจับได้เป็นคอมเมนต์กับ generic ทั้งหมด ไม่มี JSX จริง)
 *     ⇒ กฎการแยก "แท็กคือ element หรือ component" ขึ้นกับตัวแปลง (SWC/Babel) ซึ่งเราไม่ได้ทดสอบ
 *     ⇒ ไม่เอาของที่ต้องใช้จริงไปวางบนทางที่ยังไม่รู้ว่าเดินได้
 *  เหตุ: ตัวเลือกที่ปิดไว้ hover ยากและบนมือถือ hover ไม่ได้เลย
 *  ⇒ ถ้าเหตุอยู่แต่ใน `title` คนจะอ่านว่า "ระบบเราทำกำไรไม่ได้" ซึ่งไม่จริง */
export default function CostStateNote({ ประตู, ช่วง }: { ประตู: ประตูกำไร; ช่วง?: string }) {
  if (เปิดยอดรวมได้(ประตู)) return null
  const เตือน = ประตู.ชนิด === 'ถามไม่สำเร็จ'
  return (
    <p className={`text-[11.5px] mt-1 ${เตือน ? 'text-amber-800' : 'text-gray-500'}`}>
      {เตือน ? '⚠️ ' : ''}<b>ยังคิดกำไรรวมไม่ได้</b>{ช่วง ? ` (${ช่วง})` : ''} — {เหตุเต็ม(ประตู)}
      {ประตู.ชนิด === 'ตอบแล้ว' && ประตู.สภาพ.โชว์รายบรรทัดได้ === true && (
        <> · <span className="text-gray-600">กำไร<b>รายบรรทัด</b>ของบรรทัดที่ตรึงต้นทุนแล้ว อ่านได้ตามปกติ
          — ความจริงรายบรรทัดไม่ขึ้นกับว่าบรรทัดอื่นมีข้อมูลไหม</span></>
      )}
    </p>
  )
}
