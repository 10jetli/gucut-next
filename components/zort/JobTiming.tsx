'use client'
/* เวลาที่ **งานตามเวลาทุกตัว** ใช้จริง — คู่กับ `SweepTiming` ที่ดูเฉพาะตัวกวาดดันสต็อก
 * (19 ก.ย. 2569 · ใบ S1 — เขียนรอไว้ **ก่อน** ท่อปล่อยของ ตามสัญญาช่องที่ฝั่งท่อส่งมาล่วงหน้า)
 *
 * 🔑 ทำไมต้องมี: ผมรายงานไปว่า "ตัวกวาดใช้ 26.25 นาที/วัน" โดยไม่ได้เขียนขอบเขต
 *    ของจริงคือ **ครอบแค่ 288 จาก 497 รอบ/วัน = 58%** ⇒ อีก 42% ไม่มีสมุดเวลาเลย
 *    ⇒ ตัวเลขที่ถูก แต่ไม่มีขอบเขตกำกับ **ถูกอ่านเป็นยอดรวมเสมอ**
 *
 * ⚠️ สามข้อที่ฝั่งท่อกำชับ — เขียนไว้ตรงนี้เพราะถ้าลืมจะขึ้นแดงลวง:
 *  ① **`ผล.ไม่ได้ตัดสิน` เป็นเลขใหญ่โดยตั้งใจ** — ห้านตัวที่ครอบข้างนอกตอบ 200 ได้แม้ข้างในมี error
 *     ⇒ ท่อไม่เดาว่า 200 = สำเร็จ ⇒ **จอห้ามนับเป็นความล้ม และห้ามนับเป็นสำเร็จ**
 *  ② **`ครอบคลุม` หารด้วย `ชั่วโมงที่สมุดเปิดรับจริง` ไม่ใช่ `ชั่วโมงย้อนหลัง`**
 *     (สมุดที่เพิ่งเริ่มจด 25 นาทีจะขึ้น 0.04 = ดูเหมือนจดได้น้อยกว่าตาราง 96% — ฝั่งท่อเจอเองแล้วแก้)
 *     ⇒ `< 1` = จดได้น้อยกว่าที่ตารางบอก · `> 1` ได้ ถ้ามีคนสั่งมือเพิ่ม **ไม่ใช่ความผิด**
 *     🔴 **และ `< 1` ยังไม่ใช่คำตัดสินว่า "รอบหาย"** (ฝั่งท่อชี้ 20 ก.ย. 2569)
 *        ตัวเศษ = แถวที่ **ท่อที่ปล่อยอยู่** จด · ตัวหาร = cron ที่สแกนจาก **ซอร์สตอน build**
 *        ⇒ สองข้างมาจากโค้ดคนละชุดได้ ⇒ เพี้ยนโดยไม่มีอะไรฟ้อง — คลาสเดียวกับ `x-core-build`
 *        ⇒ จอจึงเขียนว่า "จดได้น้อยกว่าที่ตารางบอก" (สิ่งที่วัดได้) ไม่ใช่ "มีรอบที่ไม่ได้ถูกจดเลย" (คำตัดสิน)
 *  ③ **`ms` ไม่รวม cold start** ⇒ ต่ำกว่าที่ถูกคิดเงินเสมอ ⇒ ห้ามเอาไปเทียบตรง ๆ กับบิล
 *
 * 🚫 **ท่อยังไม่ส่งช่องพวกนี้ (ยังไม่ push)** ⇒ การ์ดนี้ต้อง **ไม่แสดงอะไรเลย** ไม่ใช่ขึ้น 0
 *    เช็ค `'งานที่จดเวลาแล้ว' in d` ⇒ ไม่มีคีย์ = **ท่อรุ่นเก่า** (คนละเรื่องกับ "ไม่มีข้อมูล")
 *    และเช็ค `inconclusive` **ก่อน** `ok` เสมอ (ตอนอ่านสมุดไม่ได้ จะไม่มีคีย์ `ok` เลย)
 */
import { useCallback, useEffect, useState } from 'react'
import { อ่านผลย่อย, งานที่รอบล่าสุดไม่ครบ } from '@/lib/job-subresult'

type งาน = {
  /* 🔴 **ท่อส่งชื่องานมาในช่อง `งาน` ไม่ใช่ `id`** (ยิงของจริงแล้วเจอ 19 ก.ย. 2569)
     การ์ดนี้เขียนล่วงหน้าจากสัญญาช่องที่ฝั่งท่อส่งมา แต่ของที่ปล่อยจริงใช้อีกชื่อ
     ⇒ เดิมทุกแถวจะขึ้น **undefined** และ `key` ซ้ำกันทั้งตาราง
     🔑 สัญญาที่อ่านจากจดหมาย ≠ สัญญาที่ยิงแล้วได้ — **ต้องยิงก่อนเชื่อ**
     ⇒ รับทั้งสองชื่อ เพราะถ้าท่อเปลี่ยนกลับ จอต้องไม่พังอีกรอบ */
  'งาน'?: string
  id?: string
  cron?: string
  'รอบต่อวันตามตาราง'?: number | null
  'แถวที่มี'?: number
  'รอบที่ควรมีในช่วง'?: number | null
  'ครอบคลุม'?: number | null
  'ค่ากลาง_ms'?: number
  'ช้าสุด_ms'?: number
  'เกินเพดาน'?: number
  'เกือบชนเพดาน'?: number
  'นาทีต่อวัน(จากแถวจริง)'?: number | null
  'ผล'?: { ok?: number; failed?: number; 'ไม่ได้ตัดสิน'?: number }
  'ล่าสุด'?: { at?: string; ms?: number; outcome?: string; note?: string } | null
  /* 🆕 **ผลย่อยของรอบล่าสุด** — ท่อส่งมาตั้งแต่ 20 ก.ย. 2569 แต่ **ไม่มีจอไหนอ่านเลย** จนถึง 28 ก.ย.
     (เจอตอนฝั่งท่อถามว่าจอมีที่ไหนอ่าน `checked` ของ beam-sweep ไหม — คำตอบคือไม่มี)
     🔒 สัญญาที่ตกลงกับฝั่งท่อ: `null` = **งานนี้ไม่ได้นับชิ้น** ไม่ใช่ "สำเร็จ 0 ชิ้น"
        ⇒ null ⇒ ไม่โชว์ช่องนั้นเลย · ห้ามเรนเดอร์เป็น 0 */
  'ผลย่อยรอบล่าสุด'?: { 'สำเร็จ'?: number; 'ล้ม'?: number } | null
}
type Resp = {
  ok?: boolean
  inconclusive?: boolean
  'อ่านสมุดไม่ได้'?: string
  'ชั่วโมงย้อนหลัง'?: number
  'ชั่วโมงที่สมุดเปิดรับจริง'?: number
  'สมุดเพิ่งเริ่มจดกลางช่วงที่ถาม'?: boolean
  'เพดานเวลาฟังก์ชัน_ms'?: number
  'เกือบชนเพดานที่_ms'?: number
  'งานที่จดเวลาแล้ว'?: งาน[] | null
  '⚠️ ขอบเขต'?: string
}

/** ชื่อที่เอาไว้โชว์ — ท่อใช้ `งาน` · รุ่นเก่าใช้ `id` · ไม่มีเลย = บอกตรง ๆ ว่าไม่รู้ */
const ชื่องาน = (x: งาน) => x['งาน'] ?? x.id ?? '(ท่อไม่ได้บอกชื่องาน)'
/** นาที/วัน **ตามตาราง** = รอบต่อวัน × ค่ากลาง — คนละเลขกับผลรวมของแถวที่จดได้จริง */
const นาทีตามตาราง = (x: งาน) => {
  const รอบ = x['รอบต่อวันตามตาราง']; const ms = x['ค่ากลาง_ms']
  return typeof รอบ === 'number' && typeof ms === 'number' ? (รอบ * ms) / 60000 : null
}
const วิ = (ms?: number) => (typeof ms === 'number' ? (ms / 1000).toFixed(1) : '—')
const นาที = (n?: number | null) => (typeof n === 'number' ? n.toFixed(2) : '—')

export default function JobTiming() {
  const [d, setD] = useState<Resp | null>(null)
  const [ท่อรุ่นเก่า, setท่อรุ่นเก่า] = useState(false)
  const [err, setErr] = useState('')

  const load = useCallback(async () => {
    setErr(''); setท่อรุ่นเก่า(false)
    try {
      const r = await fetch('/api/web/core?jobtiming=1&hours=24')
      const j: Resp = await r.json()
      /* 🔴 ไม่มีคีย์เลย = ท่อรุ่นเก่า · คนละเรื่องกับ "มีคีย์แต่เป็น null" (= อ่านสมุดไม่ได้) */
      if (!('งานที่จดเวลาแล้ว' in (j ?? {}))) { setท่อรุ่นเก่า(true); setD(null); return }
      setD(j)
    } catch (e) {
      setErr(String(e instanceof Error ? e.message : e)); setD(null)
    }
  }, [])
  useEffect(() => { load() }, [load])

  /* 🚫 ท่อรุ่นเก่า ⇒ **ไม่แสดงอะไรเลย** — การ์ดว่างดีกว่าการ์ดที่ขึ้น 0 */
  if (ท่อรุ่นเก่า) return null
  if (err) {
    return (
      <p className="text-[12px] text-amber-900 bg-amber-50 border border-amber-300 rounded px-3 py-2 mb-3">
        ⚠️ อ่านเวลางานตามเวลาไม่ได้ — <b>ยังไม่รู้</b> ไม่ใช่ว่าไม่มีปัญหา ({err})
      </p>
    )
  }
  if (!d) return null

  /* 🔴 `inconclusive` มาก่อน `ok` เสมอ — ตอนอ่านสมุดไม่ได้จะไม่มีคีย์ ok เลย */
  if (d.inconclusive) {
    return (
      <div className="text-[12px] text-amber-900 bg-amber-50 border border-amber-300 rounded px-3 py-2 mb-3">
        ⚠️ <b>อ่านสมุดเวลางานไม่ได้รอบนี้</b> — {d['อ่านสมุดไม่ได้'] ?? 'ท่อไม่ได้บอกเหตุ'}
        <span className="block text-amber-800">⇒ ตัวเลขข้างล่างไม่มี ไม่ใช่เพราะทุกอย่างปกติ</span>
      </div>
    )
  }

  const งานทั้งหมด = d['งานที่จดเวลาแล้ว'] ?? []
  if (!งานทั้งหมด.length) return null

  const เพดาน = d['เพดานเวลาฟังก์ชัน_ms']
  /* เรียงด้วยเลขที่ใช้ตัดสินเรื่องต้นทุน = นาที/วัน (ไม่ใช่วินาทีต่อรอบ) */
  /* 🔴 เดิมเรียงด้วย "แถวที่จด" ซึ่ง **ไม่ใช่เลขที่ใช้ตัดสินต้นทุน** (แก้ 19 ก.ย. 2569)
     สมุดที่จดงาน A ไว้ 5 รอบ กับงาน B 2 รอบ จะดันงาน A ขึ้นบน ทั้งที่อาจถูกกว่าต่อวัน
     ⇒ เรียงด้วย ตาราง×ค่ากลาง · ตกกลับไปใช้แถวจริงเฉพาะตอนท่อไม่ส่ง cron มา */
  const เรียง = [...งานทั้งหมด].sort(
    (a, b) => (นาทีตามตาราง(b) ?? b['นาทีต่อวัน(จากแถวจริง)'] ?? 0) - (นาทีตามตาราง(a) ?? a['นาทีต่อวัน(จากแถวจริง)'] ?? 0),
  )
  const รวมนาที = เรียง.reduce((s, x) => s + (x['นาทีต่อวัน(จากแถวจริง)'] ?? 0), 0)
  /* ยอดที่เอาไปคิดต้นทุนได้ · null เมื่อมีงานที่ท่อไม่ส่ง cron มา ⇒ **บวกไม่ครบ ห้ามโชว์เป็นยอดรวม** */
  const รวมนาทีตามตาราง = เรียง.every((x) => นาทีตามตาราง(x) !== null)
    ? เรียง.reduce((s, x) => s + (นาทีตามตาราง(x) ?? 0), 0)
    : null
  const ใกล้เพดาน = เรียง.filter((x) => (x['เกินเพดาน'] ?? 0) > 0 || (x['เกือบชนเพดาน'] ?? 0) > 0)
  /* 🔑 ตรรกะสามสถานะอยู่ที่ `lib/job-subresult.ts` (ทดสอบพฤติกรรมได้โดยไม่ต้องเรนเดอร์)
     ⚠️ อย่าย้ายกลับมาเขียนในนี้ — ตอนอยู่ใน JSX เทสตรวจได้แค่ "มีข้อความนี้ในไฟล์ไหม"
        ซึ่งปลูกบั๊กแล้วยังเขียว (วัดจริง 28 ก.ย. 2569) */
  const ผลย่อย = (x: งาน) => อ่านผลย่อย(x)
  const รอบล่าสุดไม่ครบ = งานที่รอบล่าสุดไม่ครบ(เรียง)

  const จดได้น้อยกว่าตาราง = เรียง.filter((x) => typeof x['ครอบคลุม'] === 'number' && x['ครอบคลุม']! < 1)
  /* ตัวหารของ `ครอบคลุม` เชื่อได้เฉพาะตอนท่อบอกมาว่าสมุดเปิดรับจริงกี่ชั่วโมง */
  const ตัวหารเชื่อได้ = typeof d['ชั่วโมงที่สมุดเปิดรับจริง'] === 'number'
  const ตัดสินไม่ได้ = เรียง.reduce((s, x) => s + (x['ผล']?.['ไม่ได้ตัดสิน'] ?? 0), 0)

  return (
    <div className="bg-white border border-gray-200 rounded-md p-4 mb-3">
      <p className="text-[14.5px] font-semibold text-gray-900 mb-1">
        เวลาที่งานตามเวลาใช้จริง
        <span className="font-normal text-gray-500 text-[12.5px]">
          {' · จากสมุดที่ท่อจด ย้อน '}{d['ชั่วโมงย้อนหลัง'] ?? 24}{' ชม. — ไม่ได้ยิงอะไรใหม่'}
        </span>
      </p>

      {/* 🔴 ของที่จะพังต้องอยู่บนสุด */}
      {ใกล้เพดาน.length > 0 && (
        <p className="text-[12px] text-amber-900 bg-amber-50 border border-amber-300 rounded px-3 py-2 mb-2">
          ⚠️ <b>มีงานที่ชนหรือเกือบชนเพดานเวลาแล้ว</b> —{' '}
          {ใกล้เพดาน.map((x) => `${ชื่องาน(x)} (ช้าสุด ${วิ(x['ช้าสุด_ms'])} วิ${(x['เกินเพดาน'] ?? 0) > 0 ? ` · เกินเพดาน ${x['เกินเพดาน']} รอบ` : ` · เกือบชน ${x['เกือบชนเพดาน']} รอบ`})`).join(' · ')}
          {typeof เพดาน === 'number' && (
            <span className="block">ฟังก์ชันถูกตัดกลางทางเมื่อเกิน <b>{(เพดาน / 1000).toFixed(0)} วินาที</b> ⇒ รอบนั้นไม่จบ และ<b>จะไม่นับเป็น error</b></span>
          )}
        </p>
      )}

      {/* 🔴 **รอบล่าสุดของงานที่ทำหลายชิ้น — ต้องบอกว่าชิ้นไหนล้ม ไม่ใช่แค่ว่างานวิ่ง**
           งานวิ่งสำเร็จ (outcome ok) กับ งานทำงานครบทุกชิ้น เป็นคนละเรื่องกัน
           ของจริงที่ทำให้ต้องมี: beam-sweep ถาม ZORT ไม่สำเร็จ = ลูกค้าไม่ได้รับแจ้งว่าพัสดุออกแล้ว
           แต่ตัวงานยังตอบ 200 และสมุดยังจดว่า ok ⇒ ไม่มีอะไรฟ้องเลย */}
      {รอบล่าสุดไม่ครบ.length > 0 && (
        <p className="text-[12px] text-red-900 bg-red-50 border border-red-200 rounded px-3 py-2 mb-2">
          🔴 <b>รอบล่าสุดทำไม่ครบ {รอบล่าสุดไม่ครบ.length} งาน</b> —{' '}
          {รอบล่าสุดไม่ครบ.map((x) => `${ชื่องาน(x)} (สำเร็จ ${ผลย่อย(x)!.ok} · ล้ม ${ผลย่อย(x)!.fail})`).join(' · ')}
          <span className="block text-red-800">
            ตัวงานอาจ &quot;วิ่งสำเร็จ&quot; ในสมุด (outcome ok) ได้พร้อมกัน — สองอย่างนี้คนละคำถาม:
            <b> งานวิ่งไหม</b> กับ <b>งานทำครบทุกชิ้นไหม</b>
          </span>
          {รอบล่าสุดไม่ครบ.some((x) => x['ล่าสุด']?.note) && (
            <span className="block text-red-800">
              เหตุที่ท่อจดไว้: {รอบล่าสุดไม่ครบ.map((x) => x['ล่าสุด']?.note).filter(Boolean).join(' · ')}
            </span>
          )}
        </p>
      )}

      {/* 🔴 **"จดได้น้อยกว่าตาราง" ตัดสินได้ก็ต่อเมื่อรู้ตัวหาร** — ยิงของจริง 19 ก.ย. 2569 แล้วเจอว่า
           ท่อที่ปล่อยอยู่ **ไม่ส่ง `ชั่วโมงที่สมุดเปิดรับจริง` มาเลย** ⇒ มันหารด้วยทั้ง 24 ชม.
           ⇒ สมุดที่เพิ่งเริ่มจด 5 ชม. จะขึ้น 21% ⇒ การ์ดจะร้องว่า **จดได้น้อยกว่าตาราง 79%** ทั้งที่ไม่หายสักรอบ
           🔑 **แดงลวงพาคนไปรื้อของที่ทำงานดี** ⇒ ไม่มีตัวหาร = ตัดสินไม่ได้ **ห้ามร้อง** */}
      {จดได้น้อยกว่าตาราง.length > 0 && (
        ตัวหารเชื่อได้ ? (
          <p className="text-[12px] text-amber-900 bg-amber-50 border border-amber-200 rounded px-3 py-2 mb-2">
            ⚠️ <b>รอบที่จดได้น้อยกว่าที่ตารางบอก</b> — {จดได้น้อยกว่าตาราง.map((x) => `${ชื่องาน(x)} (${Math.round((x['ครอบคลุม'] ?? 0) * 100)}%)`).join(' · ')}
            <span className="block text-amber-800">
              อาจถูกตัดตายที่เพดาน หรือ deploy ทับกลางช่วง
              {d['สมุดเพิ่งเริ่มจดกลางช่วงที่ถาม'] && <> · <b>สมุดเพิ่งเริ่มจดกลางช่วงที่ถาม</b> ⇒ อ่านเลขนี้อย่างระวัง</>}
            </span>
            {/* 🔴 **สองข้างของเลขนี้มาจากโค้ดคนละชุดได้** (ฝั่งท่อชี้ 20 ก.ย. 2569)
                 ตัวเศษ = แถวที่ท่อ **ที่ปล่อยอยู่** จดไว้ · ตัวหาร = cron ที่สแกนจาก **ซอร์สตอน build**
                 ⇒ ถ้าสองอย่างนั้นไม่ใช่โค้ดชุดเดียวกัน (deploy ตามไม่ทัน / ตารางเพิ่งแก้)
                    เลขจะเพี้ยนโดยไม่มีอะไรฟ้อง — คลาสเดียวกับ `x-core-build`
                 ⇒ ⇒ ด้วยเหตุนี้หัวข้อความจึงเปลี่ยนจาก "มีรอบที่ไม่ได้ถูกจดเลย" (คำตัดสิน)
                      เป็น "จดได้น้อยกว่าที่ตารางบอก" (สิ่งที่วัดได้จริง) */}
            <span className="block text-amber-800">
              📌 ตัวเลขนี้เทียบของสองที่: <b>จำนวนแถว</b>มาจากท่อที่ปล่อยอยู่ ·
              {' '}<b>รอบตามตาราง</b>มาจากซอร์สตอน build ⇒ <b>ยังไม่ใช่คำตัดสินว่าจดได้น้อยกว่าตาราง</b>
            </span>
          </p>
        ) : (
          <p className="text-[12px] text-gray-700 bg-gray-50 border border-gray-300 rounded px-3 py-2 mb-2">
            ℹ️ <b>ยังบอกไม่ได้ว่ามีจดได้น้อยกว่าตารางไหม</b> — ท่อไม่ได้ส่ง <code>ชั่วโมงที่สมุดเปิดรับจริง</code> มา
            <span className="block text-gray-600">
              ความครอบคลุมที่ท่อส่งมา ({จดได้น้อยกว่าตาราง.map((x) => `${ชื่องาน(x)} ${Math.round((x['ครอบคลุม'] ?? 0) * 100)}%`).join(' · ')})
              {' '}หารด้วยทั้ง {d['ชั่วโมงย้อนหลัง'] ?? 24} ชม. ⇒ <b>สมุดที่เพิ่งเริ่มจดจะดูเหมือนจดได้น้อยกว่าตารางเกือบหมด</b>
              {' '}⇒ ตัวเลขนี้ <b>ไม่ใช่ข้อบกพร่อง</b> จนกว่าท่อจะบอกว่าสมุดเปิดรับมากี่ชั่วโมง
            </span>
          </p>
        )
      )}

      <table className="w-full text-[12.5px]">
        <thead>
          <tr className="text-gray-500 text-left border-b border-gray-200">
            <th className="py-1">งาน</th>
            <th className="py-1 text-right">รอบที่จด</th>
            <th className="py-1 text-right">ค่ากลาง</th>
            <th className="py-1 text-right">ช้าสุด</th>
            <th className="py-1 text-right">นาที/วัน<span className="block font-normal text-gray-400">จากแถวที่จด</span></th>
            <th className="py-1 text-right">นาที/วัน<span className="block font-normal text-gray-400">ตาราง×ค่ากลาง</span></th>
            <th className="py-1">ผลล่าสุด</th>
            <th className="py-1 text-right">รอบล่าสุด<span className="block font-normal text-gray-400">สำเร็จ / ล้ม</span></th>
          </tr>
        </thead>
        <tbody>
          {เรียง.map((x) => (
            <tr key={ชื่องาน(x)} className="border-b border-gray-100">
              <td className="py-1">{ชื่องาน(x)}</td>
              <td className="py-1 text-right">
                {x['แถวที่มี'] ?? '—'}
                {typeof x['รอบที่ควรมีในช่วง'] === 'number' && (
                  <span className="text-gray-400">/{x['รอบที่ควรมีในช่วง']}</span>
                )}
              </td>
              <td className="py-1 text-right">{วิ(x['ค่ากลาง_ms'])} วิ</td>
              <td className="py-1 text-right">{วิ(x['ช้าสุด_ms'])} วิ</td>
              <td className="py-1 text-right">{นาที(x['นาทีต่อวัน(จากแถวจริง)'])}</td>
              <td className="py-1 text-right font-medium">{นาที(นาทีตามตาราง(x))}</td>
              <td className="py-1 text-gray-600">
                {x['ล่าสุด']?.outcome ?? '—'}
                {/* 🔑 **โชว์บันทึกของรอบล่าสุดทุกแถว ไม่ใช่เฉพาะแถวที่ล้ม** (28 ก.ย. 2569)
                    เหตุ: ฝั่งท่อใส่เหตุที่รอบจบ (`stoppedBecause` เช่น "หมดงบเวลาของรอบ (18 วินาที)")
                    ต่อท้าย HTTP status ในบันทึกนี้ ⇒ รอบที่ **ถูกตัดกลางทางแต่ไม่มีใบไหนล้ม**
                    จะดูสุขภาพดีทุกประการถ้าเราโชว์เฉพาะตอนล้ม
                    ⚠️ โชว์ข้อความของท่อตรงตัว **ห้ามจอแปลหรือจับคำเพื่อตัดสิน** — ถ้าเริ่มอ่านคำ
                       เพื่อตัดสินว่า "ถูกตัดไหม" เท่ากับจอเดาถ้อยคำของท่อ ซึ่งเปลี่ยนได้ทุกเมื่อ */}
                {x['ล่าสุด']?.note && (
                  <span className="block text-[11px] text-gray-400 max-w-[18rem] truncate"
                    title={x['ล่าสุด']!.note}>{x['ล่าสุด']!.note}</span>
                )}
              </td>
              {/* ⚠️ ไม่ได้นับชิ้น ⇒ ขีด ไม่ใช่ 0 (0 อ่านว่า "ทำไม่สำเร็จสักชิ้น" ซึ่งคนละเรื่อง) */}
              <td className="py-1 text-right whitespace-nowrap">
                {(() => {
                  const v = ผลย่อย(x)
                  if (!v) return <span className="text-gray-300" title="งานนี้ไม่ได้นับชิ้น — ไม่ใช่สำเร็จ 0 ชิ้น">—</span>
                  return (
                    <>
                      <b>{v.ok}</b>
                      <span className="text-gray-400"> / </span>
                      <b className={v.fail > 0 ? 'text-red-700' : 'text-gray-500'}>{v.fail}</b>
                    </>
                  )
                })()}
              </td>
            </tr>
          ))}
        </tbody>
      </table>
      {/* 🔑 **สองช่องนี้ตอบคนละคำถาม — วางคู่กันเฉย ๆ ไม่ได้** (กติกาเดิมของโปรเจกต์)
           · "จากแถวที่จด" = บวกเฉพาะรอบที่สมุดจดไว้ ⇒ สมุดจดไม่ครบ ⇒ **ต่ำกว่าความจริง**
           · "ตาราง×ค่ากลาง" = รอบต่อวันตาม cron × ค่ากลาง ⇒ ประมาณค่าที่ควรเป็นเมื่อสมุดครบ
           ⇒ ตัวที่เอาไปคิดต้นทุนคือตัวหลัง · ตัวแรกมีไว้ดูว่าสมุดจดครบแค่ไหน */}
      <p className="text-[11.5px] text-gray-500 mt-2">
        <b>ทำไมสองช่องไม่เท่ากัน</b> — ช่องซ้ายบวกเฉพาะรอบที่สมุดจดไว้จริง (สมุดจดไม่ครบ ⇒ ต่ำกว่าความจริง) ·
        ช่องขวาคือ <i>รอบต่อวันตามตาราง × ค่ากลาง</i> ⇒ <b>ใช้ช่องขวาคิดต้นทุน</b>
        {typeof เพดาน === 'number' && <> · ⚠️ ค่ากลางนี้ <b>ไม่รวม cold start</b> ⇒ ต่ำกว่าที่ถูกคิดเงินเสมอ</>}
      </p>

      <p className="text-[12px] text-gray-600 mt-2 leading-relaxed">
        {รวมนาทีตามตาราง !== null
          ? <>รวม <b>{รวมนาทีตามตาราง.toFixed(2)}</b> นาที/วัน (ตาราง×ค่ากลาง) จาก <b>{เรียง.length}</b> งานที่มีสมุดเวลา · จากแถวที่จดได้จริง {รวมนาที.toFixed(2)} นาที</>
          : <>รวมจากแถวที่จดได้จริง <b>{รวมนาที.toFixed(2)}</b> นาที/วัน จาก <b>{เรียง.length}</b> งานที่มีสมุดเวลา · <b>ยอดตามตารางบวกไม่ครบ</b> (มีงานที่ท่อไม่ได้ส่ง cron มา)</>}
        {typeof d['ชั่วโมงที่สมุดเปิดรับจริง'] === 'number' && (
          <> · สมุดเปิดรับจริง <b>{d['ชั่วโมงที่สมุดเปิดรับจริง']!.toFixed(2)}</b> ชม.</>
        )}
        {/* 🔴 ข้อที่ผมพลาดเองในรายงานเมื่อบ่าย — เลขรวมต้องมาคู่กับขอบเขตเสมอ */}
        <span className="block text-gray-500">
          ⚠️ นี่คือยอดของ<b>งานที่มีสมุดเวลาเท่านั้น</b> ไม่ใช่ยอดของงานตามเวลาทั้งหมด
        </span>
        {ตัดสินไม่ได้ > 0 && (
          <span className="block text-gray-500">
            📌 มี <b>{ตัดสินไม่ได้}</b> รอบที่ <b>ตัดสินผลไม่ได้</b> (ตัวครอบตอบ 200 ได้แม้ข้างในมี error)
            {' '}⇒ <b>ไม่นับเป็นสำเร็จ และไม่นับเป็นล้มเหลว</b>
          </span>
        )}
        <span className="block text-gray-500">
          📌 เวลาที่จดไม่รวม cold start ⇒ <b>ต่ำกว่าที่ถูกคิดเงินเล็กน้อยเสมอ</b> — ห้ามเอาไปเทียบตรง ๆ กับบิล
        </span>
        {d['⚠️ ขอบเขต'] && <span className="block text-gray-400">{d['⚠️ ขอบเขต']}</span>}
      </p>
    </div>
  )
}
