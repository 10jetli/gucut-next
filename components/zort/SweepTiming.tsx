'use client'
// เวลาที่ตัวกวาดดันสต็อกใช้จริง — อ่านจากสมุดที่ท่อจดไว้อยู่แล้ว (19 ก.ย. 2569 · ใบ S1)
//
// 🔑 **ที่มา: ค้านวิธีวัดแล้วได้ทางที่ถูกกว่า**
//    ใบสั่งให้ "ยิงงานตามเวลาแล้วจับเวลา 3 รอบ" ⇒ เป็นการ **เขียนข้อมูลจริง** และ
//    **สร้างค่าใช้จ่ายที่กำลังจะวัด** แล้วได้แค่ 3 ตัวอย่างที่เราสร้างเอง
//    ⇒ ฝั่งท่อจด `ms` ลง `push_sweep_log` ทุกรอบอยู่แล้ว · เปิดเส้นอ่านอย่างเดียวให้ (`efeec6a`)
//    ⇒ ได้การกระจายจริง 24 ชม. โดยไม่ยิงเพิ่มสักรอบ
//    **เกณฑ์ที่ทีมรับไปใช้: ก่อนยิงวัด ให้ถามก่อนว่าระบบจดค่านั้นไว้แล้วหรือยัง**
//
// ⚠️ **สองข้อที่ฝั่งท่อขอให้จอเคารพ — ห้ามแก้ให้ "ดูสะอาดขึ้น"**
//  ① **ห้ามยุบ `mode` เข้าด้วยกัน** — `fast-skip` เร็วกว่ารอบเต็มราว 27 เท่า (518 ms ต่อ 14,307 ms)
//     ยุบแล้วค่ากลางจะต่ำกว่าความจริงของรอบเต็ม ⇒ **ประเมินต้นทุนต่ำเกิน**
//  ② **เลขที่ใช้ตัดสินเรื่องเครดิตคือ `นาทีต่อวันประมาณ` ไม่ใช่ วินาที/รอบ**
//     Netlify คิดตามเวลาที่ฟังก์ชันทำงาน ⇒ รอบถี่ที่เร็ว อาจแพงกว่ารอบช้าที่นานทีครั้ง
//
// 🔴 **ช้าสุดสำคัญกว่าค่ากลาง** — ค่ากลาง 14 วิดูสบาย แต่ช้าสุด 28.5 วิคือตัวที่จะพัง
//    เพดานฟังก์ชันตามเวลาอยู่ราว 30 วิ ⇒ เหลือที่ว่างไม่ถึง 2 วิ
//    ⇒ จอนี้ขึ้น **ช้าสุดคู่กับค่ากลางเสมอ** ไม่ใช่ซ่อนไว้หลังปุ่ม
import { useCallback, useEffect, useState } from 'react'
import PipeNote from '@/components/ui/PipeNote'

interface แถว {
  channel?: string; mode?: string
  'รอบ'?: number
  'msค่ากลาง'?: number; 'msเร็วสุด'?: number; 'msช้าสุด'?: number
  'วินาทีต่อรอบเฉลี่ย'?: number
  'นาทีต่อวันประมาณ'?: number
  /** ท่อนับให้แล้วว่ากี่รอบที่เข้าใกล้เพดาน — จอไม่ต้องตัดสินเองจากค่ากลาง */
  'รอบที่เกือบชนเพดาน'?: number
}
interface Resp {
  ok?: boolean
  'ชั่วโมงย้อนหลัง'?: number
  /** ✅ ท่อส่งมาแล้ว 19 ก.ย. 2569 (`fda062e`) — **ช่วงที่สมุดมีข้อมูลจริง** ไม่ใช่หน้าต่างที่จอขอ
   *  เกิดจากบั๊กที่จอจับได้: `at` เก็บเป็น ISO (มี `T`) แต่เทียบกับ `datetime('now')` ที่ใช้เว้นวรรค
   *  ⇒ `T` > ช่องว่างเสมอ ⇒ แถววันเดียวกันผ่านหมด ⇒ **ตัวกรองชั่วโมงกลายเป็นรายวัน**
   *  ⇒ อัตราต่อวันเพี้ยน 52 เท่าตามหน้าต่างที่ขอ · ตอนนี้ท่อหารด้วยช่วงจริงแล้ว */
  'แถวแรกสุด'?: string | null
  'แถวล่าสุด'?: string | null
  'ชั่วโมงที่มีข้อมูลจริง'?: number | null
  '🔴 สมุดครอบไม่ถึงหน้าต่างที่ขอ'?: string | null
  /** 🔑 **เพดานมาจากท่อแล้ว — จอเลิกเดาเอง** (เดิมจอฝังไว้ 30 วิ เป็นค่าสำรอง) */
  'เพดานเวลาฟังก์ชัน_ms'?: number | null
  'เกือบชนเพดานที่_ms'?: number | null
  /** นาทีของชั่วโมงที่มีรอบถูกเขียนลงสมุด — ใช้เทียบกับ cron ว่ามีรอบนอกตารางไหม */
  'นาทีที่เจอ'?: Record<string, Record<string, number>>
  '🔎 อ่านนาทีที่เจอยังไง'?: string
  /** ✅ ท่อนับรอบนอกตารางให้เองแล้ว — **จอเลิกตัดด้วยเกณฑ์ของตัวเอง** */
  'รอบนอกตารางทั้งหมด'?: number
  'รอบนอกตาราง'?: Array<{ channel?: string; 'นาที'?: string; ms?: number }>
  /** การกระจาย ไม่ใช่ผลของการตัดที่เกณฑ์ ⇒ คนอ่านตีความเองได้โดยไม่ต้องรับเกณฑ์ของใคร */
  'msรอบก่อนหน้าของรอบนอกตาราง'?: { 'ค่ากลาง'?: number; 'เร็วสุด'?: number; 'ช้าสุด'?: number; 'จำนวน'?: number }
  'msทุกรอบค่ากลาง'?: number
  '🔎 อ่านรอบนอกตารางยังไง'?: string
  'แถว'?: แถว[]
  'รวมนาทีต่อวันประมาณ'?: number
  '⚠️ ขอบเขต'?: string
  error?: string
  fallthrough?: boolean
}

/** 🔴 **ค่าสำรองของเพดานเวลา — ใช้ได้เฉพาะตอนท่อไม่ส่งมาเลย และต้องประกาศบนจอ**
 *  ✅ ท่อประกาศ `เพดานเวลาฟังก์ชัน_ms` มาแล้ว 19 ก.ย. 2569 ⇒ **ปกติจะไม่ได้ใช้ตัวนี้**
 *  เก็บไว้เผื่อเจอท่อรุ่นเก่าตอน deploy เหลื่อม · ท่าเดียวกับ `RECIPE_STALE_HOURS_ทางถอย`
 *  🚫 ห้ามเอามาใช้แทนค่าจากท่อ และห้ามเงียบเมื่อใช้ — เลขเกณฑ์ต้องมีที่เดียว */
const เพดานMs_ทางถอย = 30000

const MODE_TH: Record<string, string> = {
  live: 'ยิงจริง',
  dry: 'ซ้อม (ไม่เขียนอะไรกลับแพลตฟอร์ม)',
  'fast-skip': 'ทางออกเร็ว (ไม่มีอะไรต้องทำ)',
}

const วิ = (ms?: number) => (typeof ms === 'number' ? (ms / 1000).toFixed(1) : '—')

export default function SweepTiming() {
  const [d, setD] = useState<Resp | null>(null)
  const [loading, setLoading] = useState(true)
  const [err, setErr] = useState('')
  const [ยังไม่มีเส้น, setยังไม่มีเส้น] = useState(false)

  const load = useCallback(async () => {
    setLoading(true); setErr(''); setยังไม่มีเส้น(false)
    try {
      const r = await fetch('/api/web/core?sweeptiming=1&hours=24')
      const j: Resp = await r.json()
      /* 🔴 ท่อรุ่นเก่าตอบ 200 พร้อม `fallthrough` ⇒ เช็คแค่ res.ok จะอ่านว่า
         "สำเร็จแต่ไม่มีข้อมูล" ซึ่งกลับหัวความจริง (เจอคลาสนี้มาแล้วหลายรอบ) */
      if (j?.fallthrough || !Array.isArray(j?.['แถว'])) { setยังไม่มีเส้น(true); setD(null); return }
      if (j.error) throw new Error(j.error)
      setD(j)
    } catch (e) {
      setErr(String(e instanceof Error ? e.message : e)); setD(null)
    } finally { setLoading(false) }
  }, [])
  useEffect(() => { load() }, [load])

  const แถวทั้งหมด = d?.['แถว'] ?? []
  /* เรียงตามเลขที่ใช้ตัดสินจริง (นาที/วัน) ไม่ใช่ตามวินาทีต่อรอบ */
  const เรียง = [...แถวทั้งหมด].sort((a, b) => (b['นาทีต่อวันประมาณ'] ?? 0) - (a['นาทีต่อวันประมาณ'] ?? 0))
  /* 🔑 เพดานมาจากท่อ · ค่าสำรองใช้เฉพาะตอนท่อไม่ส่งมา **และต้องบอกบนจอ** */
  const เพดานMs = typeof d?.['เพดานเวลาฟังก์ชัน_ms'] === 'number' ? d['เพดานเวลาฟังก์ชัน_ms']! : เพดานMs_ทางถอย
  const ใช้เพดานสำรอง = typeof d?.['เพดานเวลาฟังก์ชัน_ms'] !== 'number'
  /* เส้น "เกือบชน" ก็มาจากท่อ — จอไม่คิดเปอร์เซ็นต์เอง (เลขเกณฑ์ต้องมีที่เดียว) */
  const เกือบชนMs = typeof d?.['เกือบชนเพดานที่_ms'] === 'number' ? d['เกือบชนเพดานที่_ms']! : เพดานMs * 0.8
  const ใกล้เพดาน = เรียง.filter((r) => (r['msช้าสุด'] ?? 0) >= เกือบชนMs)
  /* ช่วงที่สมุด **มีข้อมูลจริง** — มาจากท่อเท่านั้น ห้ามเดาจากหน้าต่างที่ขอ */
  const ช่วงจริง = d?.['แถวแรกสุด'] && d?.['แถวล่าสุด']
    ? `${new Date(d['แถวแรกสุด']!).toLocaleString('th-TH')} – ${new Date(d['แถวล่าสุด']!).toLocaleString('th-TH')}`
    : null
  const ครอบไม่ถึง = d?.['🔴 สมุดครอบไม่ถึงหน้าต่างที่ขอ'] || null

  /* 🔴 **รอบนอกตาราง — อ่านจำนวนจากท่อ ห้ามตัดด้วยเกณฑ์ของจอเอง**
     เดิมจอนับเองโดยเทียบกับ "นาทีที่มีรอบมากสุดของเจ้านั้น หารสอง" ซึ่งบังเอิญได้ 13 ตรงกับท่อ
     🔑 แต่บทเรียนที่ฝั่งท่อเพิ่งเจอกับตัวเอง (19 ก.ย. 2569) ใช้กับจอเท่ากัน:
        **ตัวเลขที่ผูกกับเกณฑ์ที่เราตั้งเอง จะยืนยันสมมติฐานของเราเสมอ ไม่ว่าจะจริงหรือไม่**
        (เขาตั้งเกณฑ์ "เกือบชนเพดาน 80%" แล้วตัวนับก็ตอบคำถามของเกณฑ์นั้น ไม่ใช่ของข้อมูล
         ⇒ สมมติฐาน "ถูกสั่งซ้ำเพราะรอบก่อนเกือบชนเพดาน" ยิงจริงแล้วตก 4 จาก 13)
     ⇒ จอจึงอ่าน `รอบนอกตารางทั้งหมด` ตรง ๆ · ไม่มีคีย์ = ไม่แสดง (ไม่ใช่คำนวณเอง)
     🚫 และยังคงห้ามเขียนสาเหตุ — ท่อยืนยันว่ามีอย่างน้อยสองเหตุที่ต่างกัน */
  const นอกตาราง = typeof d?.['รอบนอกตารางทั้งหมด'] === 'number' ? d['รอบนอกตารางทั้งหมด']! : null
  const ก่อนหน้า = d?.['msรอบก่อนหน้าของรอบนอกตาราง']
  const ทุกรอบกลาง = d?.['msทุกรอบค่ากลาง']

  return (
    <div className="bg-white border border-gray-200 rounded-md p-4 mb-3">
      <div className="flex flex-wrap items-baseline justify-between gap-2 mb-1">
        <p className="text-[14.5px] font-semibold text-gray-900">
          เวลาที่ตัวกวาดดันสต็อกใช้จริง
          <span className="font-normal text-gray-500 text-[12.5px]">
            {' · วัดจากสมุดที่ท่อจดไว้ ย้อน '}{d?.['ชั่วโมงย้อนหลัง'] ?? 24}{' ชม. — ไม่ได้ยิงอะไรใหม่'}
          </span>
        </p>
        {typeof d?.['รวมนาทีต่อวันประมาณ'] === 'number' && (
          <span className="text-[12.5px] text-gray-700 bg-gray-100 rounded px-2 py-0.5">
            รวม <b>{d['รวมนาทีต่อวันประมาณ']!.toFixed(1)}</b> นาที/วัน
          </span>
        )}
      </div>

      {loading && <p className="text-[12.5px] text-gray-400">กำลังอ่านสมุดรอบกวาด…</p>}
      {err && <p className="text-[12.5px] text-red-700">อ่านไม่ได้: {err} <b>(อ่านไม่ได้ ≠ ไม่มีรอบ)</b></p>}
      {ยังไม่มีเส้น && (
        <p className="text-[12.5px] text-gray-500">
          ท่อรุ่นที่เสิร์ฟอยู่ยังไม่มีเส้นนี้ — <b>ไม่ได้แปลว่าตัวกวาดไม่ทำงาน</b>
        </p>
      )}

      {!loading && !err && !ยังไม่มีเส้น && (
        <>
          {/* 🔴 **"นาที/วัน" คือผลหาร ไม่ใช่ค่าที่วัดได้ — ต้องบอกก่อนที่คนจะอ่านตัวเลข**
              วัดจริง 19 ก.ย. 2569: ข้อมูลชุดเดียวกันเป๊ะ (300 แถว) ให้คำตอบต่างกัน 52 เท่า
              เพียงเพราะเปลี่ยนหน้าต่างที่ขอ — 273.3 ที่ hours=3 · 34.0 ที่ 24 · 5.2 ที่ 336
              เพราะสูตรคือ (เวลารวมในหน้าต่าง ÷ hours × 24) ⇒ หารด้วยเลขที่ **คนขอ**
              ไม่ใช่ด้วยช่วงที่สมุดมีข้อมูลจริง
              ⚠️ ผลที่กลับหัว: ขอหน้าต่างกว้างขึ้นเพื่อให้ได้ข้อมูลเยอะขึ้น **จะได้ค่าใช้จ่ายที่ต่ำลง**
              🚫 นี่คือเลขคณิตของสูตร ไม่ใช่การเดาว่าทำไมข้อมูลถึงกระจุก — เหตุนั้นยังไม่รู้
                 และ **ห้ามเขียนสาเหตุที่เดาเองลงตรงนี้** */}
          {/* 🔑 **ใช้ประโยคของท่อ ไม่เขียนคำของจอคู่ขนาน** — ท่อหารด้วยช่วงจริงแล้ว (fda062e)
              จอเคยเขียนคำเตือนเองตอนที่ท่อยังหารผิด · พอท่อแก้แล้วยังเก็บไว้ = คำเท็จค้างบนจอ */}
          {ครอบไม่ถึง && (
            <div className="text-[12px] text-amber-900 bg-amber-50 border border-amber-200 rounded px-3 py-2 mb-2 leading-relaxed">
              ⚠️ <PipeNote>{ครอบไม่ถึง}</PipeNote>
            </div>
          )}
          {(ช่วงจริง || typeof d?.['ชั่วโมงที่มีข้อมูลจริง'] === 'number') && (
            <p className="text-[11.5px] text-gray-600 mb-2">
              📐 สมุดมีข้อมูลจริง
              {typeof d?.['ชั่วโมงที่มีข้อมูลจริง'] === 'number' && <> <b>{d['ชั่วโมงที่มีข้อมูลจริง']!.toFixed(2)}</b> ชม.</>}
              {ช่วงจริง && <span className="text-gray-400"> ({ช่วงจริง})</span>}
            </p>
          )}

          {/* 🔴 ของที่จะพังต้องอยู่บนสุด ไม่ใช่ต่อท้ายตาราง */}
          {ใกล้เพดาน.length > 0 && (
            <div className="text-[12px] text-amber-900 bg-amber-50 border border-amber-200 rounded px-3 py-2 mb-2 leading-relaxed">
              ⚠️ <b>มีรอบที่เข้าใกล้เพดานเวลาแล้ว</b> —{' '}
              {ใกล้เพดาน.map((r) => {
                const n = r['รอบที่เกือบชนเพดาน']
                return `${r.channel} (${MODE_TH[r.mode ?? ''] ?? r.mode}) ช้าสุด ${วิ(r['msช้าสุด'])} วิ${typeof n === 'number' ? ` · เกือบชน ${n} รอบ` : ''}`
              }).join(' · ')}
              <span className="block">
                ฟังก์ชันตามเวลาถูกตัดกลางทางเมื่อเกิน <b>{(เพดานMs / 1000).toFixed(0)} วินาที</b>
                {' '}⇒ วันที่ของเยอะกว่านี้หน่อย รอบนั้นจะไม่จบ และ<b>จะไม่นับเป็น error</b>
              </span>
              {/* 🔑 เพดานมาจากท่อแล้ว ⇒ ปกติบรรทัดนี้จะไม่ขึ้น · ขึ้นเมื่อไหร่แปลว่าเจอท่อรุ่นเก่า */}
              {ใช้เพดานสำรอง && (
                <span className="block text-amber-800">
                  📌 ท่อรุ่นที่เสิร์ฟอยู่ยังไม่ส่งเพดานมา ⇒ จอใช้<b>ค่าสำรอง</b> {(เพดานMs_ทางถอย / 1000).toFixed(0)} วินาที
                  {' '}— ถือเป็นสัญญาณให้ไปดู ไม่ใช่เส้นตัดสิน
                </span>
              )}
            </div>
          )}

          <div className="overflow-x-auto border border-gray-200 rounded">
            <table className="w-full text-[12px]">
              <thead className="bg-gray-50">
                <tr>
                  {['ช่องทาง', 'โหมด', 'รอบ (24 ชม.)', 'ค่ากลาง', 'ช้าสุด', 'นาที/วัน'].map((h, i) => (
                    <th key={h} className={`px-2 py-1.5 font-semibold text-gray-700 whitespace-nowrap ${i >= 2 ? 'text-right' : 'text-left'}`}>
                      {h}
                    </th>
                  ))}
                </tr>
              </thead>
              <tbody>
                {เรียง.map((r, i) => {
                  /* เส้นเน้นสีมาจากเกณฑ์ของท่อ ไม่ใช่เปอร์เซ็นต์ที่จอคิดเอง */
                  const เกือบชน = (r['msช้าสุด'] ?? 0) >= เกือบชนMs
                  return (
                    <tr key={`${r.channel}-${r.mode}-${i}`} className="border-t border-gray-100">
                      <td className="px-2 py-1 whitespace-nowrap">{r.channel ?? '—'}</td>
                      {/* ⚠️ โหมดห้ามยุบ — fast-skip เร็วกว่ารอบเต็มหลายเท่าโดยตั้งใจ */}
                      <td className="px-2 py-1 text-gray-600">{MODE_TH[r.mode ?? ''] ?? r.mode ?? '—'}</td>
                      <td className="px-2 py-1 text-right tabular-nums">{r['รอบ'] ?? '—'}</td>
                      <td className="px-2 py-1 text-right tabular-nums">{วิ(r['msค่ากลาง'])} วิ</td>
                      <td className={`px-2 py-1 text-right tabular-nums ${เกือบชน ? 'text-amber-800 font-semibold' : ''}`}>
                        {วิ(r['msช้าสุด'])} วิ
                      </td>
                      {/* 🔑 คอลัมน์นี้คือเลขที่ใช้ตัดสินเรื่องเครดิต ⇒ เน้นกว่าวินาที/รอบ */}
                      <td className="px-2 py-1 text-right tabular-nums font-semibold">
                        {typeof r['นาทีต่อวันประมาณ'] === 'number' ? r['นาทีต่อวันประมาณ']!.toFixed(2) : '—'}
                      </td>
                    </tr>
                  )
                })}
              </tbody>
            </table>
          </div>

          {/* 🚫 **ห้ามเขียนสาเหตุตรงนี้** — ฝั่งท่อมีสมมติฐานแล้วแต่ยังพิสูจน์ไม่ได้
              และกำชับเองว่าอย่าเอาขึ้นจอจนกว่าจะพิสูจน์ (ใบ t_mu7qyolx)
              ⇒ จอบอกแค่จำนวนที่นับได้ และบอกตรง ๆ ว่ายังไม่ทราบเหตุ
              🔑 "ยังไม่ทราบเหตุ" ที่เขียนออกมา ดีกว่าสาเหตุที่เดาแล้วดูน่าเชื่อ */}
          {นอกตาราง !== null && นอกตาราง > 0 && (
            <p className="text-[11.5px] text-amber-800 mt-1.5 leading-relaxed">
              ⚠️ <b>มีรอบที่เกิดนอกนาทีของตารางเวลา {นอกตาราง} รอบ</b> ⇒ <b>ยังไม่ทราบเหตุ</b>
              {/* การกระจาย ไม่ใช่ผลของการตัดที่เกณฑ์ ⇒ คนอ่านชั่งเองได้ */}
              {typeof ก่อนหน้า?.['ค่ากลาง'] === 'number' && typeof ทุกรอบกลาง === 'number' && (
                <span className="block text-gray-600">
                  รอบที่มาก่อนหน้ามันใช้เวลาค่ากลาง <b>{(ก่อนหน้า['ค่ากลาง']! / 1000).toFixed(1)} วิ</b>
                  {' '}เทียบกับทุกรอบค่ากลาง <b>{(ทุกรอบกลาง / 1000).toFixed(1)} วิ</b>
                  {typeof ก่อนหน้า['เร็วสุด'] === 'number' && typeof ก่อนหน้า['ช้าสุด'] === 'number' && (
                    <> (กระจายตั้งแต่ {(ก่อนหน้า['เร็วสุด']! / 1000).toFixed(1)} ถึง {(ก่อนหน้า['ช้าสุด']! / 1000).toFixed(1)} วิ)</>
                  )}
                  {' '}— ตัวเลขให้ดูเอง <b>จอไม่สรุปสาเหตุให้</b>
                </span>
              )}
            </p>
          )}
          <p className="text-[11.5px] text-gray-500 mt-1.5 leading-relaxed">
            {/* 🔴 เดิมเขียนว่า "นาที/วัน คือเลขที่ใช้ตัดสินเรื่องค่าใช้จ่าย" ซึ่ง **ขัดกับแถบบนสุด**
                ของการ์ดเดียวกันที่เพิ่งบอกว่าเลขนี้เป็นการประมาณ ใช้เทียบทิศ ไม่ใช่เลขตัดสิน
                (เห็นตอนเปิดดูด้วยตา ไม่เห็นตอนอ่านโค้ด — build ผ่าน ≠ จอถูก)
                ⇒ ประโยคนี้เป็นการเทียบ **ระหว่างคอลัมน์** ว่าคอลัมน์ไหนเกี่ยวกับเงิน
                   ไม่ใช่การรับรองว่าเลขนั้นแม่นพอจะตัดสิน ⇒ เขียนให้ตรงกับที่มันหมายถึงจริง */}
            🔑 ในบรรดาเลขบนตารางนี้ <b>คอลัมน์ที่เกี่ยวกับค่าใช้จ่ายคือ “นาที/วัน”</b> ไม่ใช่วินาทีต่อรอบ —
            Netlify คิดตามเวลาที่ฟังก์ชันทำงาน ⇒ รอบถี่ที่เร็ว อาจแพงกว่ารอบช้าที่นานทีครั้ง
            {' '}(ความแม่นของตัวเลขนั้นดูที่คำเตือนด้านบน)
          </p>
          {d?.['⚠️ ขอบเขต'] && (
            <p className="text-[11.5px] text-gray-500 mt-1 leading-relaxed">
              📖 <PipeNote>{d['⚠️ ขอบเขต']}</PipeNote>
            </p>
          )}
        </>
      )}
    </div>
  )
}
