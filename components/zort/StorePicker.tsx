export type StoreId = '' | 'z1' | 'z2'

/** ป้ายชื่อร้านสำหรับหัวไฟล์ส่งออก/ข้อความอธิบาย — ที่เดียวกับปุ่ม */
export function storeLabel(s: StoreId): string {
  return s === 'z2' ? 'หน้าร้าน (z2)'
    : s === 'z1' ? 'ร้านออนไลน์ (z1)'
      : 'ไม่ได้เลือก (ท่อคืนร้านออนไลน์ z1)'
}

export default function StorePicker({ value, onChange, disabled, note }: {
  value: StoreId
  onChange: (s: 'z1' | 'z2') => void
  disabled?: boolean
  /** ข้อความต่อท้ายของจอนั้น ๆ · ไม่ใส่ = ใช้ประโยคกลาง */
  note?: string
}) {
  return (
    <div className="flex flex-wrap items-center gap-2 mb-2">
      <span className="text-[12.5px] text-gray-500">ร้าน:</span>
      {(['z1', 'z2'] as const).map((v) => {
        const on = value === v || (value === '' && v === 'z1')
        return (
          <button
            key={v}
            type="button"
            disabled={disabled}
            onClick={() => { if (value !== v) onChange(v) }}
            className={`text-[12.5px] rounded-full px-3 py-1 border disabled:opacity-50 ${
              on ? 'bg-[#eef1fa] border-[#4669e5] text-[#2b3f9e] font-medium'
                : 'bg-white border-gray-300 text-gray-700 hover:bg-gray-50'}`}
          >
            {storeLabel(v)}
          </button>
        )
      })}
      <span className="text-[11.5px] text-gray-400">
        {note ?? 'เส้นนี้ตอบทีละร้าน — ยอดและตัวนับทั้งหมดเป็นของร้านที่เลือกเท่านั้น'}
      </span>
    </div>
  )
}
