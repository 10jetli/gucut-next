'use client'
/* ข้อความชั่วคราว: "สินค้าซ้ำสองแถวจากรอบซิงก์" — **ผูกกับเงื่อนไข ⇒ หายเองเมื่อฝั่งท่อลบแถวเก่า**
 *
 * 🔴 **ที่มา 18 ก.ย. 2569** — ฝั่งท่อเจอว่าตัวซิงก์ทะเบียนสินค้า **ตัด `sku` ที่ 60 ตัวอักษร**
 *    รหัสจริงตัวหนึ่งยาว 88 ⇒ แถวในกระจกมี sku สั้นกว่าของจริง · ชื่อว่าง · ราคาว่าง
 *    (จอสินค้าเห็นเป็นแถวไม่มีชื่อที่โผล่บนสุดของการเรียงตามชื่อ)
 *    ⇒ หลังท่อ deploy ตัวแก้ รอบซิงก์ถัดไปจะเขียน **แถวใหม่ด้วย sku เต็ม**
 *      แต่ **แถวสั้นยังอยู่** ⇒ มีสองแถวของสินค้าตัวเดียวกัน จนกว่าฝั่งท่อจะลบแถวเก่า
 *    ⇒ ระหว่างนั้น "จำนวน N รายการ" บนหัวจอจะขยับขึ้นโดยไม่มีใครรู้ว่าทำไม
 *
 * 🔑 **ทำไมต้องผูกเงื่อนไข ไม่ใช่เขียนข้อความไว้เฉย ๆ**
 *    ข้อความชั่วคราวที่ต้องรอคนมาถอด คือข้อความที่จะค้างเป็นคำเท็จ
 *    (บทเรียน `new-capability-falsifies-old-copy`) ⇒ วันที่ท่อลบแถวเก่า บรรทัดนี้ต้องหายเอง
 *
 * ⚠️ **ชื่อช่องในคำตอบ มาจากจดหมายฝั่งท่อ ยังไม่ได้ยิงเห็นของจริง** (เส้นนี้อยู่ในคอมมิตที่ยังไม่ push)
 *    ⇒ อ่านแบบเข้มงวด: ไม่เจอช่อง/ไม่ใช่ตัวเลข ⇒ **เงียบ** ไม่เดา ไม่เดาว่าเป็น 0
 *    ⇒ ยิงจริงเมื่อไหร่ ถ้าชื่อไม่ตรง จะไม่มีอะไรขึ้นจอ (ปลอดภัยกว่าขึ้นข้อความผิด)
 *    📌 ก่อน deploy ยิงเส้นนี้จะได้ 0 เสมอ **เพราะยังไม่มีแถวยาวให้จับคู่** — ไม่ใช่ว่าเส้นพัง
 */
import { useEffect, useState } from 'react'
import { fmtNum } from '@/lib/format'

/** ช่องที่ฝั่งท่อบอกว่าจะส่งมา — เก็บชื่อไว้ที่เดียว จะได้แก้จุดเดียวถ้าชื่อไม่ตรงตอนยิงจริง */
const ช่องจำนวนคู่ = 'ที่มีคู่ยาวกว่าขึ้นต้นเหมือนกัน'

export default function DupSkuNote() {
  const [จำนวนคู่, setจำนวนคู่] = useState<number | null>(null)

  useEffect(() => {
    let ทิ้งแล้ว = false
    ;(async () => {
      try {
        const r = await fetch('/api/web/core?dupsku=1')
        const j = (await r.json()) as Record<string, unknown>
        if (ทิ้งแล้ว || !r.ok || j?.error) return
        const n = j[ช่องจำนวนคู่]
        /* ไม่ใช่ตัวเลข = ยังไม่รู้ ⇒ เงียบ (ไม่ใช่ 0 · ไม่ใช่ "ไม่มีปัญหา") */
        if (typeof n === 'number' && Number.isFinite(n)) { setจำนวนคู่(n); return }
        /* 🔑 **แยกสองเหตุของความเงียบออกจากกัน** (กติกา: 200 + fallthrough = ท่อรุ่นเก่า ไม่ใช่ท่อล้ม)
           · `fallthrough: true` ⇒ เส้นยังไม่ deploy ⇒ เงียบถูกแล้ว ไม่ต้องบ่น
           · ไม่มี fallthrough แต่ **ไม่มีช่องที่รอ** ⇒ เส้นขึ้นแล้วแต่ **ชื่อช่องไม่ตรงกับที่เราอ่าน**
             ⇒ การ์ดนี้จะเงียบตลอดกาลโดยไม่มีใครรู้ ⇒ ต้องส่งเสียงอย่างน้อยที่คอนโซล
           (ชื่อช่องมาจากจดหมายฝั่งท่อ ยังไม่เคยยิงเห็นของจริง — ดูหมายเหตุหัวไฟล์) */
        if (j?.fallthrough !== true) {
          console.warn(
            `[DupSkuNote] เส้น ?dupsku=1 ตอบมาแล้วแต่ไม่มีช่อง "${ช่องจำนวนคู่}" ⇒ การ์ดนี้จะไม่มีวันขึ้น · ` +
              `ช่องที่ได้จริง: ${Object.keys(j ?? {}).join(', ')}`
          )
        }
      } catch { /* เส้นยังไม่ขึ้น/ยิงไม่ได้ ⇒ เงียบ — การ์ดนี้เป็นของเสริม ห้ามทำให้จอหลักดูพัง */ }
    })()
    return () => { ทิ้งแล้ว = true }
  }, [])

  if (จำนวนคู่ === null || จำนวนคู่ <= 0) return null

  return (
    <p className="text-[12px] text-amber-900 bg-amber-50 border border-amber-200 rounded px-3 py-2 mb-2 leading-relaxed">
      ⚠️ ตอนนี้มีสินค้า <b>{fmtNum(จำนวนคู่)} รหัส</b> ที่อยู่ในทะเบียน <b>สองแถว</b> —
      แถวเก่าที่รหัสถูกตัดสั้น กับแถวใหม่ที่รหัสเต็ม (เกิดจากรอบซิงก์ก่อนหน้าตัดรหัสที่ 60 ตัวอักษร)
      <br />
      ⇒ <b>จำนวนรายการบนหัวจอจึงสูงกว่าของจริงเท่าจำนวนนี้</b> · ฝั่งท่อกำลังลบแถวเก่า
      {' '}<span className="text-amber-700/80">บรรทัดนี้จะหายเองเมื่อลบเสร็จ</span>
    </p>
  )
}
