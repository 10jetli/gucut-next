'use client'
/* ตรวจว่า "ร้านที่จอขอ" กับ "ร้านที่ท่อตอบมา" เป็นร้านเดียวกันจริง (17 ก.ย. 2569 · ใบ t_mu2u9mym)
 *
 * 🔴 **รูปร่างของบั๊กที่ตัวนี้เกิดมากัน** — จอเลือกร้านส่ง `store=` ไปทุกครั้ง
 *    แต่ **ไม่มีจอไหนอ่านคำตอบว่าท่อใช้ร้านไหนจริง** (ไล่ดูครบ 5 จอ 17 ก.ย. 2569)
 *    ⇒ วันที่ท่อเมิน `store` เงียบ ๆ ปุ่มจะค้างที่ "หน้าร้าน" แต่ตัวเลขเป็นของ "ร้านออนไลน์"
 *      คนอ่านไม่มีทางรู้เลย เพราะหน้าตาเหมือนกันทุกประการ — และนี่คือตัวเลขที่เอาไปปิดบัญชี
 *
 * 🔑 **ท่อบอกกลับมาอยู่แล้ว ทั้งสองช่อง ที่ชั้นบน (ไม่ได้อยู่ใน `applied`)**
 *    ยิงยืนยันครบ 4 เส้น 17 ก.ย. 2569 (purchases · returnorders · quotations · transfers):
 *    · ไม่ส่ง `store` ⇒ `store:"z1"` + `storeDefaulted:true`
 *    · ส่ง `store=z2` ⇒ `store:"z2"` + `storeDefaulted:false` และยอดต่างกันจริงทุกเส้น
 *    · ส่งค่ามั่ว ⇒ **400** พร้อมข้อความบอกว่ารับแค่ z1/z2
 *    ⇒ รูปแบบคงที่พอจะเทียบตรง ๆ ได้ โดยไม่มีทางเตือนหลอก
 *
 * ⚠️ **ท่อไม่ส่งช่องนี้มา ≠ ตรงกันดี** — เป็น "ยืนยันไม่ได้" ซึ่งเป็นสถานะที่สาม
 *    จึงขึ้นบรรทัดสีเทาบอกตรง ๆ ไม่ใช่เงียบ (กฎประจำโปรเจกต์: ไม่รู้ ≠ 0 ≠ ไม่มี)
 */
import { storeLabel, type StoreId } from './StorePicker'

export default function StoreEcho({ ขอ, ได้, ท่อเลือกให้, ว่างคือ = 'z1' }: {
  /** ร้านที่ผู้ใช้เลือกบนจอ — ค่าว่าง = ไม่ได้เลือก */
  ขอ: StoreId
  /** ช่อง `store` ที่ท่อตอบกลับมา */
  ได้?: string | null
  /** ช่อง `storeDefaulted` ที่ท่อตอบกลับมา */
  ท่อเลือกให้?: boolean
  /** 🔴 **เส้นของท่อสองแบบ ตีความค่าว่างคนละอย่าง — ใส่ผิดคือเตือนหลอก**
   *  ยิงยืนยัน 17 ก.ย. 2569:
   *  · `'z1'` (ค่าเริ่มต้น) — เส้นที่ตอบทีละร้าน (ใบซื้อ · ใบคืนของ · ใบเสนอราคา · ใบโอน)
   *    ไม่ส่ง `store` ⇒ ท่อคืน **z1** พร้อม `storeDefaulted:true`
   *  · `'ทุกร้าน'` — เส้นรายการขาย (`list=orders`) รวมสองร้านได้จริง
   *    ไม่ส่ง หรือส่ง `store=all` ⇒ ท่อคืน **`store: null`** (= ทุกร้าน) และไม่มี `storeDefaulted`
   *    ⇒ ที่นี่ `null` **คือคำตอบ** ไม่ใช่ "ท่อไม่บอก" */
  ว่างคือ?: 'z1' | 'ทุกร้าน'
}) {
  /* 🔑 แยก "ท่อไม่ส่งช่องนี้มาเลย" (undefined) ออกจาก "ท่อบอกว่าไม่เจาะจงร้าน" (null)
     สองอย่างนี้หน้าตาเกือบเหมือนกันในโค้ด แต่ความหมายตรงข้ามกัน */
  if (ได้ === null && ว่างคือ === 'ทุกร้าน') {
    return (ขอ === '' || ขอ === ('all' as StoreId)) ? null : (
      <p className="text-[12.5px] mb-3 bg-red-50 border border-red-200 text-red-800 rounded-lg px-3 py-2">
        ⚠️ <b>ข้อมูลที่เห็นไม่ใช่ของร้านที่เลือก</b> — จอขอ <b>{storeLabel(ขอ)}</b>{' '}
        แต่ท่อตอบเป็นข้อมูล<b>รวมทุกร้าน</b>
        <br />⇒ <b>อย่าเอาตัวเลขชุดนี้ไปใช้</b> จนกว่าจะแจ้งฝั่งท่อและยิงตรวจซ้ำ
      </p>
    )
  }
  if (ได้ === undefined || ได้ === null || ได้ === '') {
    return (
      <p className="text-[12px] text-gray-500 mb-2">
        ⏳ ท่อไม่ได้บอกว่าข้อมูลชุดนี้เป็นของร้านไหน — <b>ยืนยันไม่ได้</b>ว่าตรงกับร้านที่เลือก
      </p>
    )
  }
  const ตรงกัน = ขอ === '' ? ได้ === 'z1' : ได้ === ขอ
  /* เลือกร้านไว้แล้วแต่ท่อบอกว่า "ฉันเลือกให้เอง" = ท่อไม่ได้ใช้ค่าที่เราส่ง */
  const ถูกเมิน = ขอ !== '' && ท่อเลือกให้ === true
  if (ตรงกัน && !ถูกเมิน) return null
  return (
    <p className="text-[12.5px] mb-3 bg-red-50 border border-red-200 text-red-800 rounded-lg px-3 py-2">
      ⚠️ <b>ข้อมูลที่เห็นไม่ใช่ของร้านที่เลือก</b> — จอขอ <b>{storeLabel(ขอ || 'z1')}</b>{' '}
      แต่ท่อตอบเป็นข้อมูลของ <b>{storeLabel(ได้ === 'z2' ? 'z2' : 'z1')}</b>
      {ถูกเมิน && <> (ท่อแจ้งว่าเลือกร้านให้เอง = ไม่ได้ใช้ร้านที่จอส่งไป)</>}
      <br />⇒ <b>อย่าเอาตัวเลขชุดนี้ไปใช้</b> จนกว่าจะแจ้งฝั่งท่อและยิงตรวจซ้ำ
    </p>
  )
}
