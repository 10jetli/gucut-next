//
// 🔴 **ทำไมต้องมีเส้นนี้ ไม่ให้จอยิงตรง** — ของจริงที่วัดได้ 12 ต.ค. 2569:
//    เบราว์เซอร์ยิง `https://gucut.com/parts/f440.json` จาก `test2.gucut.com` ⇒ **ถูก CORS บล็อก**
//    `No 'Access-Control-Allow-Origin' header is present` ⇒ จอว่างเปล่าทั้งหน้า
//    ⚠️ และ **tsc ผ่าน · ด่าน 8 ตัวผ่านหมด** — ไม่มีด่านไหนเห็นข้อนี้ได้
//       ⇒ เจอเพราะเปิดดูด้วยตาเท่านั้น (กฎร้าน: build ผ่าน ≠ จอถูก)
//
// ℹ️ ใช้พร็อกซี `/api/web/[...path]` ไม่ได้ เพราะตัวนั้นฝัง `/api/` ไว้ในพาธปลายทาง
//    (`${base}/api/${path}`) แต่ไฟล์อะไหล่อยู่ที่ `/parts/<รุ่น>.json` ไม่ได้อยู่ใต้ `/api`
import { NextRequest, NextResponse } from 'next/server'

/* 🔴 **สองบรรทัดนี้คือตัวกันบั๊กที่ร้ายที่สุดเท่าที่เจอในหน้าจับคู่อะไหล่** (17 ต.ค. 2569)
   อาการ: เลือกรุ่นไหนก็ได้รายการอะไหล่ของ **f250** เหมือนกันหมดทั้ง 17 รุ่น
   ⇒ คนกรอกจะจับคู่รหัสร้านเข้ากับอะไหล่ **ผิดรุ่นทั้งหน้า** โดยจอไม่ฟ้องอะไรเลย
      และจอดู "สมเหตุสมผล" เป็นพิเศษ เพราะตัวนับกับตารางจับคู่มาคนละท่อ จึงถูกรุ่นอยู่

   เหตุ: ตอบ `cache-control: public, max-age=300` แต่ **ขอบเครือข่ายจำคำตอบตามพาธ
         ไม่รวมพารามิเตอร์** ⇒ คำตอบของรุ่นที่ถูกขอเป็นรุ่นแรก ถูกจ่ายให้ทุกรุ่นต่อจากนั้น
   พิสูจน์: ยิง 4 รุ่นด้วย URL ต่างกัน (มีตัวกันแคชสุ่มท้าย) ได้ `age: 76` **เท่ากันเป๊ะทั้งสี่**
           และ `รหัสรุ่น` ในคำตอบเป็น f250 ทั้งสี่

   ⚠️ **ตัวกันแคชที่ขา URL แก้ไม่ได้** — ผมลองแล้วและเคยสรุปผิดว่าแก้ได้
      ของที่คุมได้จริงคือ **หัวที่ท่อนี้ตอบ**
   🔑 กฎ: **คำตอบที่ขึ้นกับพารามิเตอร์ ห้ามตอบ `cache-control: public`**
      เว้นแต่พิสูจน์ได้ว่าชั้นที่เก็บแยกคำตอบตามพารามิเตอร์จริง — ที่นี่ไม่แยก */
/** ที่อยู่หน้าร้านที่จะไปดึงข้อมูล — ตั้งทับได้ด้วย `GUCUT_SHOP_URL`
 *  🔑 **ห้ามฝัง gucut.com ตายตัว** — เว็บทดสอบ (`test2.gucut.com`) จะยิงไปกินเครดิต
 *     ของจริงโดยไม่มีใครรู้ ทั้งที่ตั้งใจซ้อมเพื่อ **ไม่** ให้เสียเครดิต
 *     (ท่านประธานถามเรื่องนี้ตรง ๆ 17 ต.ค. 2569 — ตอนนั้นของยังฝังตายตัวอยู่)
 *  🔑 "รันที่ไหน" ไม่ได้แปลว่า "ยิงไปที่ไหน" */
const หน้าร้าน = (process.env.GUCUT_SHOP_URL || 'https://gucut.com').replace(/\/+$/, '')

export const dynamic = 'force-dynamic'
export const revalidate = 0

/** ล้างชื่อรุ่น — ตรงกับ `ล้างรุ่น` ของฝั่งท่อ (`parts-map.mjs`): ตัวเล็ก · a-z0-9 · ≤12
 *  🔑 กันคนยิงพาธแปลก ๆ เข้ามา (`../`) และกันชื่อรุ่นที่ไม่มีวันมีไฟล์ */
const ล้างรุ่น = (v: string | null) =>
  String(v || '').toLowerCase().replace(/[^a-z0-9]/g, '').slice(0, 12)

export async function GET(req: NextRequest) {
  const รุ่น = ล้างรุ่น(req.nextUrl.searchParams.get('model'))
  if (!รุ่น) return NextResponse.json({ error: 'ต้องระบุ model' }, { status: 400 })
  try {
    const r = await fetch(`${หน้าร้าน}/parts/${รุ่น}.json`, { cache: 'no-store' })
    if (!r.ok) {
      /* 🔑 อ่านไม่ได้ ≠ ไม่มีอะไหล่ — ต้องตอบเป็นข้อผิดพลาด ไม่ใช่ก้อนว่าง
         ไม่งั้นจอจะขึ้นว่า "รุ่นนี้ยังไม่มีรายการอะไหล่" ทั้งที่ของมีอยู่ */
      return NextResponse.json(
        { error: `อ่านรายการอะไหล่ของรุ่น ${รุ่น} ไม่ได้ (HTTP ${r.status})` },
        { status: 502 })
    }
    return NextResponse.json(await r.json(), {
      /* ⚠️ `no-store` ไม่ได้เสียประสิทธิภาพที่เคยมี — ไฟล์ต้นทางที่ gucut.com ยังแคชตามปกติ
         ที่ห้ามแคชคือ **คำตอบของท่อนี้** ซึ่งเปลี่ยนตามพารามิเตอร์ `model` */
      headers: { 'cache-control': 'no-store' },
    })
  } catch (e) {
    return NextResponse.json(
      { error: `อ่านรายการอะไหล่ไม่ได้: ${e instanceof Error ? e.message : 'เรียกไม่สำเร็จ'}` },
      { status: 502 })
  }
}
