import { NextResponse } from 'next/server'

/* อ่าน "ไฟล์ประกาศสถานะหัวสมอง" ที่ g1 อัปขึ้น R2 แล้วส่งต่อให้หน้า /core/brain
 *
 * 🔑 ทำไมต้องผ่านเส้นนี้ ไม่ให้เบราว์เซอร์ยิงตรง
 *    ① ยิงข้ามโดเมน (1.gucut.com → video.gucut.com) ต้องพึ่ง CORS ของอีกฝั่ง
 *       ซึ่ง **เราไม่ได้คุมและเปลี่ยนได้โดยไม่มีใครบอก** ⇒ จอจะว่างโดยไม่รู้สาเหตุ
 *    ② ฝั่งเซิร์ฟเวอร์แยก "ไม่มีไฟล์ (404)" ออกจาก "ยิงไม่ถึง" ได้ ซึ่งเป็นคนละสถานะกัน
 *       — และหน้าต้องแยกสามสถานะตามที่ท่านสั่ง
 *
 * ⚠️ route นี้ทำหน้าที่ **รับ-ส่งอย่างเดียว ไม่ตัดสินอะไร** — การตัดสินสถานะอยู่ที่
 *    `lib/brain-status.ts` ที่เดียว (และมีเทสเรียกตัวจริงตัวนั้น)
 */
export const dynamic = 'force-dynamic'

const ที่อยู่ประกาศ = 'https://video.gucut.com/brain/status.json'

/* 🔴 **ต้องมี query กันแคชเสมอ** — ของจริงที่เจอ 9 ต.ค. 2569
 *    ตอนยังไม่มีไฟล์ เรายิงไปครั้งหนึ่งแล้วได้ 404 · Cloudflare **เก็บ 404 นั้นไว้ 7 วัน**
 *    (`cf-cache-status: HIT`, `max-age=604800`) ⇒ อัปไฟล์ขึ้นไปแล้วก็ยังได้ 404 อยู่ดี
 *    ⇒ หน้าจะขึ้นว่า "ยังไม่ได้ติดตั้ง" ทั้งที่ติดตั้งเสร็จแล้ว **นานเป็นสัปดาห์**
 *    ⇒ แบ่งเป็นช่องละ 1 นาที: ยังได้ประโยชน์จากแคชภายในนาทีเดียวกัน แต่ไม่ค้างข้ามนาที
 *    ⚠️ `cache: 'no-store'` ของ fetch คุมแคชฝั่งเราเท่านั้น **คุม CDN ของคนอื่นไม่ได้** */
export async function GET() {
  try {
    const ช่องนาที = Math.floor(Date.now() / 60_000)
    const r = await fetch(`${ที่อยู่ประกาศ}?t=${ช่องนาที}`, { cache: 'no-store' })
    if (r.status === 404) {
      /* 404 = ยังไม่เคยมีใครประกาศ ⇒ ยังไม่ได้ติดตั้ง (ไม่ใช่ "พัง") */
      return NextResponse.json({ ok: true, ประกาศ: null, เหตุ: 'ยังไม่มีไฟล์ประกาศ' })
    }
    if (!r.ok) {
      return NextResponse.json(
        { ok: false, ประกาศ: null, เหตุ: `อ่านไฟล์ประกาศไม่ได้ (HTTP ${r.status})` },
        { status: 200 },
      )
    }
    return NextResponse.json({ ok: true, ประกาศ: await r.json() })
  } catch (e: unknown) {
    /* 🔴 ยิงไม่ถึง ≠ ยังไม่ได้ติดตั้ง — ส่ง ok:false ไปให้จอเขียนว่า "ไม่รู้" */
    return NextResponse.json(
      { ok: false, ประกาศ: null, เหตุ: `ยิงไปอ่านไฟล์ประกาศไม่ได้: ${String((e as Error)?.message ?? e).slice(0, 120)}` },
      { status: 200 },
    )
  }
}
