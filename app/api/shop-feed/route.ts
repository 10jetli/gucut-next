/* ท่อดึงข้อมูลหน้าร้านมาให้หลังร้านใช้ — เลี่ยง CORS (17 ต.ค. 2569)
   GET /api/shop-feed?ชนิด=รุ่น | สินค้า

   🔴 **เหตุที่ต้องมีท่อนี้ — บทเรียนที่เจ็บที่สุดของงานวันนี้**
   หน้า /core/parts-map เรียก `fetch('https://gucut.com/...')` ตรงจากเบราว์เซอร์
   แต่ **gucut.com ไม่ส่งหัว `access-control-allow-origin`** ⇒ เบราว์เซอร์บล็อกทุกคำขอ
   แล้ว `catch { return ค่าสำรอง }` ที่เขียนไว้ "เพื่อความปลอดภัย" ก็กลืนมันเงียบสนิท
   ⇒ จอโชว์ 6 รุ่นเหมือนเดิม · ไม่มีรูป · ไม่มีข้อเสนอ · **ไม่มีอะไรบอกว่าพัง**
      ทุกอย่าง deploy ผ่าน · tsc เขียว · วัดความแม่นได้ 98% บน g1 — แต่ของจริงตายสนิท
   🔑 กฎที่ได้: **ทางถอยที่เงียบ จะกลายเป็นทางหลักโดยไม่มีใครรู้**
      ⇒ หน้าจอต้องบอกเมื่อใช้ทางถอย (ดู `โหลดพลาด` ใน page.tsx)

   ⚠️ ทำไมเลือกท่อฝั่งเซิร์ฟเวอร์ แทนการไปใส่หัว CORS ที่ gucut.com
      • แก้ repo เดียว deploy เดียว (ข้ามไปแก้หน้าร้านคือเสี่ยงกับของที่ลูกค้าใช้)
      • หน้าร้านไม่ต้องรู้จักหลังร้าน — ความสัมพันธ์เดินทางเดียว
      • แคชได้ที่นี่ ไม่ต้องให้ทุกเบราว์เซอร์ยิงออกไปเอง */
import { NextResponse } from 'next/server'

export const runtime = 'nodejs'
export const dynamic = 'force-dynamic'

/** ที่อยู่หน้าร้านที่จะไปดึงข้อมูล — ตั้งทับได้ด้วย `GUCUT_SHOP_URL`
 *  🔑 **ห้ามฝัง gucut.com ตายตัว** — เว็บทดสอบ (`test2.gucut.com`) จะยิงไปกินเครดิต
 *     ของจริงโดยไม่มีใครรู้ ทั้งที่ตั้งใจซ้อมเพื่อ **ไม่** ให้เสียเครดิต
 *     (ท่านประธานถามเรื่องนี้ตรง ๆ 17 ต.ค. 2569 — ตอนนั้นของยังฝังตายตัวอยู่)
 *  🔑 "รันที่ไหน" ไม่ได้แปลว่า "ยิงไปที่ไหน" */
const หน้าร้าน = (process.env.GUCUT_SHOP_URL || 'https://gucut.com').replace(/\/+$/, '')


const แหล่ง: Record<string, string> = {
  รุ่น: `${หน้าร้าน}/parts/models.json`,
  /* ⚠️ `products.json` เป็น **ฟังก์ชันของ Netlify** ⇒ เว็บทดสอบไม่มี (404)
     ไม่เป็นไร — หน้าจับคู่ใช้คลังอะไหล่ (โดเมนเดียวกัน) เป็นแหล่งหลักอยู่แล้ว
     ฟีดนี้เป็นแค่ตัวเสริมราคา/ลิงก์สินค้า */
  สินค้า: `${หน้าร้าน}/products.json`,
}

export async function GET(req: Request) {
  const ชนิด = new URL(req.url).searchParams.get('ชนิด') || ''
  /* 🏠 บอก "หน้าร้านอยู่ที่ไหน" ให้ฝั่งเบราว์เซอร์รู้ — ใช้ประกอบ url รูปผังอะไหล่
     เบราว์เซอร์อ่าน env ฝั่งเซิร์ฟเวอร์ไม่ได้ และเราไม่อยากมี NEXT_PUBLIC_* ตัวที่สอง
     เพราะค่าสองที่จะเพี้ยนกันเสมอ ⇒ ถามผ่านท่อนี้ให้เหลือแหล่งความจริงเดียว
     (ของจริง 19 ต.ค. 2569: รายชื่อรุ่นมาจาก GUCUT_SHOP_URL แต่รูปฝัง gucut.com
      ⇒ รุ่นใหม่ที่ยังไม่ขึ้นของจริง รูปหายเงียบ ๆ ทั้งที่รายการมาครบ) */
  if (ชนิด === 'ที่อยู่') {
    return NextResponse.json({ ที่อยู่: หน้าร้าน }, {
      headers: { 'cache-control': 'no-store' },
    })
  }

  const url = แหล่ง[ชนิด]
  /* ⚠️ ชนิดที่ไม่รู้จักต้องตอบ 400 **ห้ามตกไปที่ค่าปริยาย**
     ท่อที่เดาให้เวลาถามผิด ทำให้ฝั่งจอเรียกผิดชื่อแล้วยังได้ของ — แล้วไม่มีใครรู้ว่าเรียกผิด
     (กติกาเดียวกับ fallthrough ของ /api/core ในหน้าร้าน) */
  if (!url) {
    return NextResponse.json(
      { error: `ไม่รู้จักชนิด "${ชนิด}" — รับเฉพาะ: ${Object.keys(แหล่ง).join(' · ')}` },
      { status: 400 },
    )
  }
  try {
    const r = await fetch(url, {
      /* แคช 5 นาที — ข้อมูลสินค้าไม่ได้เปลี่ยนทุกวินาที และหน้านี้เปิดค้างทั้งวัน
         ⚠️ อย่าตั้งยาวกว่านี้: เพิ่มสินค้าใหม่แล้วตัวแนะนำต้องเห็นภายในรอบงานเดียวกัน */
      next: { revalidate: 300 },
    })
    if (!r.ok) {
      return NextResponse.json({ error: `หน้าร้านตอบ HTTP ${r.status}` }, { status: 502 })
    }
    return NextResponse.json(await r.json())
  } catch (e) {
    /* 🔴 ตอบ error จริง ห้ามคืนก้อนว่างแบบ 200
       ก้อนว่าง 200 = ฝั่งจอแยกไม่ออกระหว่าง "ไม่มีข้อมูล" กับ "ดึงไม่ได้"
       ซึ่งเป็นต้นเหตุของบั๊กที่ทำให้ต้องสร้างไฟล์นี้ตั้งแต่แรก */
    return NextResponse.json(
      { error: e instanceof Error ? e.message : 'ดึงข้อมูลหน้าร้านไม่สำเร็จ' },
      { status: 502 },
    )
  }
}
