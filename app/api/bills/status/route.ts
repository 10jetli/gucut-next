import { NextResponse } from 'next/server'
import { BILL_VENDORS } from '@/lib/vendors'
import { สรุปทุกเจ้า } from '@/lib/billreport'
import { อ่านสถานะบิลบนg1, สถานะจากg1 } from '@/lib/bills-g1'

export const dynamic = 'force-dynamic'
export const maxDuration = 30

// GET /api/bills/status — สถานะการเก็บบิลของทุกเจ้า สำหรับหน้า /bills
//
// 🔑 ท่านประธานสั่ง 15 ก.ย. 2569: "ไปดึงบิลวันไหนล่าสุด อับเดตด้วย บอกสเตตัส"
//    และ "ไปเก็บด้วยบอทตัวไหน เช่น g1 ด้วยการเขียนสคริปต์หรือ api หรือดึงเมล ต้องบอกด้วย"
//
// ⚠️ **ไม่อยู่ใน PUBLIC_PATHS โดยตั้งใจ** — ต้องล็อกอินถึงเรียกได้ (middleware กันให้)
//    ต่างจาก /api/bills/report ที่ใช้รหัส DRIVESYNC_SECRET สำหรับทีม AI
// ⚠️ อ่านจากดัชนีที่แคชไว้ ไม่แตะ Gmail ⇒ เปิดหน้า /bills กี่ครั้งก็ไม่กินโควตา
export async function GET() {
  /* 🔑 อ่านสองแหล่งพร้อมกัน: ดัชนีบิล (ทางเมล) + ไฟล์สถานะบน g1 (ทางสคริปต์) */
  const [สรุป, g1] = await Promise.all([สรุปทุกเจ้า(), อ่านสถานะบิลบนg1()])
  const ข้อมูลเก็บ = Object.fromEntries(BILL_VENDORS.map(v => [v.id, v.collect ?? null]))

  const now = Date.now()
  const out = สรุป.map(v => {
    const ล่าสุด = v.สแกนล่าสุด ? new Date(v.สแกนล่าสุด).getTime() : null
    const ชม = ล่าสุด ? (now - ล่าสุด) / 3600e3 : null
    const เก็บ = ข้อมูลเก็บ[v.id]

    /* สถานะ — แยกให้ชัด อย่ายุบ "ไม่รู้" กับ "ไม่มี" เข้าด้วยกัน
       · อ่านไม่ได้        → เราไม่รู้ ไม่ใช่ว่าไม่มีบิล
       · อัปมือ            → ไม่มีตัวเก็บอัตโนมัติ ต้องมีคนทำ (เสี่ยงขาดเงียบ)
       · เงียบเกิน 3 วัน   → ตัวเก็บน่าจะไม่ได้ทำงาน
       · ปกติ              → เพิ่งสแกนมา */
    let สถานะ: 'ปกติ' | 'ควรมาดู' | 'อัปมือ' | 'ต้องล็อกอิน' | 'ไม่รู้' = 'ปกติ'
    let เหตุ = ''
    let สแกนล่าสุด = v.สแกนล่าสุด
    /* 🔴 **เจ้าที่เก็บด้วยสคริปต์บน g1 ต้องอ่านสถานะจาก g1 ไม่ใช่จาก lastScan** (15 ต.ค. 2569)
       lastScan มีแต่ทางเมลที่เขียน ⇒ เจ้าพวกนี้เคยขึ้น "ไม่ได้สแกน 13 วัน" ทั้งที่รันปกติทุกคืน
       ⇒ เหตุผลเต็มอยู่หัวไฟล์ lib/bills-g1.ts (ทำไมไม่ให้ upload เขียน lastScan แทน) */
    const จากg1 = เก็บ?.วิธี === 'สคริปต์บน g1' ? สถานะจากg1(v.id, g1, now) : null
    // 🔑 ท่านประธานสั่ง: "เขียนบอกปัญหาด้วยว่าโหลดไม่ได้เพราะอะไร ตัวไหนโหลดได้เขียนว่า ปกติ"
    //    ⇒ เจ้าที่มีข้อความใน `ปัญหา` ต้องโชว์เหตุผลจริง ไม่ใช่คำว่า "ไม่ได้" ลอย ๆ
    if (จากg1) { สถานะ = จากg1.สถานะ; เหตุ = จากg1.เหตุ; สแกนล่าสุด = จากg1.สแกนล่าสุด }
    else if (v.อ่านไม่ได้) { สถานะ = 'ไม่รู้'; เหตุ = 'อ่านคลังไม่ได้: ' + v.อ่านไม่ได้ }
    else if (เก็บ?.ปัญหา) { สถานะ = เก็บ.วิธี === 'อัปมือ' ? 'อัปมือ' : 'ควรมาดู'; เหตุ = เก็บ.ปัญหา }
    else if (เก็บ?.วิธี === 'อัปมือ') { สถานะ = 'อัปมือ'; เหตุ = 'ไม่มีตัวเก็บอัตโนมัติ' }
    else if (ชม === null) { สถานะ = 'ไม่รู้'; เหตุ = 'ยังไม่เคยสแกน' }
    // ⚠️ ใช้ 'สแกนล่าสุด' ตัดสิน ไม่ใช่ 'เจอบิลใหม่ล่าสุด'
    //    เจ้าที่ไม่มีบิลใหม่มานานไม่ได้แปลว่าระบบพัง — บางเจ้าออกบิลไม่ทุกเดือน
    else if (ชม > 72) { สถานะ = 'ควรมาดู'; เหตุ = `ไม่ได้สแกนมา ${Math.floor(ชม / 24)} วัน` }

    return {
      id: v.id, ชื่อ: v.ชื่อ, สถานะ, เหตุ,
      เก็บโดย: เก็บ,
      สแกนล่าสุด,
      /* บอกว่าเลข "สแกนล่าสุด" มาจากไหน — สองแหล่งนับคนละอย่าง ห้ามวางคู่กันเฉย ๆ (กฎข้อ 4) */
      ที่มาของเวลาสแกน: จากg1 ? 'ไฟล์สถานะบน g1' : 'ดัชนีบิล (ทางเมล)',
      เจอบิลใหม่ล่าสุด: v.เจอบิลใหม่ล่าสุด,
      ชั่วโมงที่แล้ว: ชม === null ? null : Math.round(ชม * 10) / 10,
      รวมทุกเดือน: v.รวมทุกเดือน,
      เดือนล่าสุดที่มีบิล: Object.keys(v.เดือน)[0] ?? null,
      จำนวนเดือนล่าสุด: Object.values(v.เดือน)[0]?.จำนวน ?? 0,
    }
  })

  return NextResponse.json({ เจ้า: out, เวลาที่ตรวจ: new Date().toISOString() })
}
