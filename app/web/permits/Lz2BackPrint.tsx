      {err && <p className="mt-3 text-[12.5px] font-semibold text-red-600">{err}</p>}

      {/* ── ปุ่มปริ้นต์ ล่างสุดของบล็อกนี้ (ท่านประธานสั่งตำแหน่งนี้เอง) ── */}
