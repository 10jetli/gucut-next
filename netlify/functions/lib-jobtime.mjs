/* จับเวลางานตามเวลาฝั่งจอ แล้วส่งลงสมุดเล่มเดียวกับฝั่งท่อ
 * (19 ก.ย. 2569 · ใบ S1 — ฝั่งท่อเปิดช่อง `POST /api/core?joblog=1` ให้ตามที่ขอ)
 *
 * 🔴 ที่มา: งานตามเวลาฝั่งจอมี 4 ตัว (bills-netlify · bills-watch · bills-daily · shelf-report)
 *    และ **ไม่มีตัวไหนจดเวลาเลยสักตัว** ⇒ ต้นทุนฟังก์ชันฝั่งจอ **ไม่มีใครเห็นตลอดไป**
 *    (Netlify คิดเงินตามเวลารันฟังก์ชัน ไม่ใช่จำนวนครั้ง)
 *    และวัดจากเครื่องเราไม่ได้ — ไม่มี Netlify token ⇒ ทางเดียวคือให้มันจดเอง
 *
 * 🔑 **กติกาข้อแรกและสำคัญที่สุด: การจดเวลาต้องไม่ทำให้งานจริงพัง**
 *    ถ้าส่งสมุดไม่สำเร็จ ⇒ **กลืนไว้** แล้วคืนผลของงานจริงเหมือนเดิมทุกประการ
 *    ถ้างานจริงโยน error ⇒ **จดว่า failed แล้วโยนต่อ** ไม่ใช่กลืน
 *    ⇒ ตัวที่มาเฝ้า ห้ามกลายเป็นตัวที่ทำให้ล้ม (บทเรียนของทีม: ตัวตรวจต้องไม่ก่อผลข้างเคียง)
 *
 * ⚠️ กติกาของช่องที่ฝั่งท่อกำหนด (และเหตุผลของเขา — เขียนไว้กันมีคนแก้ให้ "สะดวกขึ้น"):
 *    · ชื่อต้องขึ้นต้น `จอ/` ⇒ กันชนกับงานฝั่งท่อ และให้ตัวอ่านแยกที่มาได้
 *    · `ms` ต้องเป็นเลข ≥ 0
 *    · 🔑 **ผลที่ไม่อยู่ในสามค่า ⇒ ท่อจดเป็น `ไม่ได้ตัดสิน`** ⇒ เราส่ง `ok` เองไม่ได้ถ้ายังไม่รู้ผล
 *      และคำตอบของท่อ **บอกกลับว่าผลถูกลดชั้นไหม** ⇒ เราจะรู้ว่าสมุดจดอะไรลงไปจริง
 *      ไม่ใช่เดาจาก HTTP 200
 */
const PIPE = "https://gucut.com/api/core";

/** ส่งแถวลงสมุด — คืนสิ่งที่ท่อตอบ (หรือเหตุที่ส่งไม่ได้) · **ไม่โยน error ออกไปไม่ว่ากรณีใด** */
async function จดลงสมุด(แถว) {
  const key = process.env.GUCUT_WEB_ADMIN_KEY;
  if (!key) return { จด: false, เหตุ: "ไม่มี GUCUT_WEB_ADMIN_KEY" };
  try {
    const r = await fetch(`${PIPE}?joblog=1`, {
      method: "POST",
      headers: { "x-admin-key": key, "content-type": "application/json" },
      body: JSON.stringify(แถว),
      signal: AbortSignal.timeout(8000),
    });
    const j = await r.json().catch(() => null);
    if (!r.ok) return { จด: false, เหตุ: `ท่อตอบ ${r.status}`, ตอบ: j };
    /* 🔑 อ่านคำตอบ ไม่ใช่แค่ดู 200 — ท่อบอกเองว่าผลถูกลดชั้นเป็น "ไม่ได้ตัดสิน" ไหม */
    return { จด: true, ตอบ: j };
  } catch (e) {
    return { จด: false, เหตุ: String(e?.message ?? e) };
  }
}

/**
 * @param {string} ชื่อ ชื่องานแบบไม่ใส่คำนำหน้า (ฟังก์ชันนี้เติม `จอ/` ให้เอง)
 * @param {() => Promise<any>} งาน งานจริง
 * @param {{อ่านผล?: (x:any)=>Promise<{ผล:('ok'|'failed'|null),note:(string|null)}>, ตัดสินผล?: (x:any)=>('ok'|'failed'|null), อธิบาย?: (x:any)=>(string|null)}} opt
 *   `ตัดสินผล` คืน null = **ยังตัดสินไม่ได้** ⇒ ปล่อยให้ท่อจดเป็น "ไม่ได้ตัดสิน"
 *   🚫 อย่าเขียน `ตัดสินผล: () => 'ok'` — นั่นคือคำรับรอง ไม่ใช่การวัด
 */
export async function วัดเวลางาน(ชื่อ, งาน, opt = {}) {
  const t0 = Date.now();
  let ผลลัพธ์, พัง = null;
  try {
    ผลลัพธ์ = await งาน();
  } catch (e) {
    พัง = e;
  }
  const ms = Date.now() - t0;
  /* 🔑 `อ่านผล` เป็น async ได้ เพราะฝั่งจอคืน `Response` ⇒ ต้อง await ถึงจะอ่านเนื้อได้
     และมันต้อง **ไม่ทำให้พัง** ถ้าอ่านไม่ออก ⇒ ห่อ try/catch ไว้อีกชั้น */
  let ผล = null, note = null;
  if (พัง) {
    ผล = "failed";
    note = String(พัง?.message ?? พัง).slice(0, 200);
  } else {
    try {
      if (opt.อ่านผล) { const x = await opt.อ่านผล(ผลลัพธ์); ผล = x?.ผล ?? null; note = x?.note ?? null; }
      else {
        ผล = opt.ตัดสินผล ? opt.ตัดสินผล(ผลลัพธ์) : null;
        note = opt.อธิบาย ? opt.อธิบาย(ผลลัพธ์) : null;
      }
    } catch (e) {
      /* อ่านผลไม่ได้ ≠ งานล้ม ⇒ ปล่อยเป็น "ยังตัดสินไม่ได้" แล้วบอกเหตุไว้ในโน้ต */
      note = `อ่านผลไม่ได้: ${String(e?.message ?? e)}`.slice(0, 160);
    }
  }
  const ผลการจด = await จดลงสมุด({ "งาน": `จอ/${ชื่อ}`, ms, "ผล": ผล ?? undefined, note: note ?? undefined });
  /* พิมพ์ลง log ของ Netlify ด้วย — เผื่อวันที่สมุดส่งไม่ถึง จะได้ยังมีร่องรอย */
  console.log(`⏱️ จอ/${ชื่อ}: ${ms} ms · ผล=${ผล ?? "(ยังตัดสินไม่ได้)"} · จดลงสมุด=${ผลการจด.จด}${ผลการจด.เหตุ ? ` (${ผลการจด.เหตุ})` : ""}`);
  if (พัง) throw พัง;          // 🔑 งานจริงล้ม ⇒ ต้องล้มต่อ ไม่ใช่ถูกกลืนโดยตัวจับเวลา
  return { ผลลัพธ์, ms, ผล, จดเวลา: ผลการจด.จด, ตอบจากสมุด: ผลการจด.ตอบ ?? null };
}

/* ── ตัวช่วยสำหรับฟังก์ชันที่คืน `Response` (ฝั่งจอเป็นแบบนี้ทั้ง 4 ตัว) ──
   🔑 อ่าน **เนื้อคำตอบ** ไม่ใช่แค่ HTTP status — สัญญาของโปรเจกต์คือ
      `{skip}` = ทำต่อไม่ได้ (ห้ามมีคีย์ ok) · `{ok:false,error}` = ล้ม · `{ok:true}` = สำเร็จ
   ⇒ `skip` ⇒ คืน null = **ยังตัดสินไม่ได้** ให้ท่อจดเป็น "ไม่ได้ตัดสิน"
      (skip ไม่ใช่ความสำเร็จ และไม่ใช่ความล้ม — มันคือ "ไม่ได้ทำ") */
export async function อ่านผลจาก(res) {
  if (!(res instanceof Response)) return { ผล: null, note: null }
  /* 🔑 **อ่านเนื้อเป็นข้อความก่อนเสมอ แล้วค่อยลองแปลงเป็น JSON**
     (แก้ 20 ก.ย. 2569 · ใบ S1 กำชับว่าตัววัดต้องพิสูจน์ว่าแตะงานจริง ด้วย **HTTP code + ขนาด body**)
     🔴 รูเดิม: ถ้าคำตอบไม่ใช่ JSON (เช่น **200 พร้อมหน้า error ของปลายทาง** ซึ่งเป็นอาการจริง
        ที่ทีมเจอกับ ZORT) ⇒ `b = null` ⇒ ผล null และ note null
        ⇒ **ไม่มีหลักฐานสักชิ้น และหน้าตาเหมือนกับ "ยังตัดสินไม่ได้" เฉย ๆ**
     ⇒ ตอนนี้บันทึก **ขนาดไบต์เสมอ** ⇒ 200 ที่ตัวเปล่ากับ 200 ที่มีของ แยกออกจากกันได้ */
  let ข้อความ = ""
  try { ข้อความ = await res.clone().text() } catch (e) { return { ผล: null, note: `อ่านเนื้อไม่ได้: ${String(e?.message ?? e)}`.slice(0, 160) } }
  const ไบต์ = Buffer.byteLength(ข้อความ, "utf8")
  let b = null, เป็นJson = true
  try { b = JSON.parse(ข้อความ) } catch { เป็นJson = false }

  if (b && typeof b.skip === "string") return { ผล: null, note: `skip: ${b.skip} · ${ไบต์} ไบต์`.slice(0, 160) }
  const ผล = res.status >= 400 || b?.ok === false ? "failed" : b?.ok === true ? "ok" : null

  /* 🔑 หลักฐานว่าแตะงานจริง — เก็บ **ช่องที่เป็นตัวเลข** จากคำตอบ
     (ใบ S1 กำชับ: `ok` ที่ไม่มีเลขประกอบ = คำรับรอง ไม่ใช่หลักฐาน)
     ⚠️ ตัดรายการเพื่อให้โน้ตสั้น **ต้องบอกจำนวนเต็มคู่กันเสมอ** — คลาสเดียวกับที่ทีมไล่กันคืนนี้
        (ของเดิมที่นี่เขียน `.slice(0, 6)` เฉย ๆ ⇒ คนอ่านโน้ตจะเชื่อว่าเห็นครบ) */
  const ย่อ = (คู่, เอา) => {
    const หัว = คู่.slice(0, เอา).map(([k, v]) => `${k} ${v}`).join(" · ")
    return คู่.length > เอา ? `${หัว} (อีก ${คู่.length - เอา} · รวม ${คู่.length})` : หัว
  }
  const ช่อง = b && typeof b === "object" && !Array.isArray(b) ? Object.entries(b) : []
  const เลข = ย่อ(ช่อง.filter(([, v]) => typeof v === "number"), 6)
  const arr = ย่อ(ช่อง.filter(([, v]) => Array.isArray(v)).map(([k, v]) => [k, v.length]), 3)

  /* 🔑 **ความเงียบต้องไม่อ่านเป็นหลักฐาน** — ไม่มีเลขในคำตอบ ต้องเขียนว่าไม่มี ไม่ใช่ปล่อยว่าง
     (บทเรียนของทีม: ช่องที่เว้นว่างคือคำกล่าวอ้างที่ไม่มีใครพูด) */
  const หลักฐาน = [เลข, arr].filter(Boolean).join(" · ")
    || (เป็นJson ? "ไม่มีตัวเลขในคำตอบ" : "คำตอบไม่ใช่ JSON")
  return { ผล, note: `HTTP ${res.status} · ${ไบต์} ไบต์ · ${หลักฐาน}`.slice(0, 200) }
}
