export const PICK = 3;   // สั่งนับได้จริงวันละไม่เกิน 3 รหัส (50 รหัสวันเดียว = ไม่มีใครนับสักรหัส)

const TH_MONTH = ["ม.ค.", "ก.พ.", "มี.ค.", "เม.ย.", "พ.ค.", "มิ.ย.", "ก.ค.", "ส.ค.", "ก.ย.", "ต.ค.", "พ.ย.", "ธ.ค."];
export function thaiDate(ymd) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(String(ymd ?? ""))) return String(ymd ?? "—");
  const [y, m, d] = ymd.split("-").map(Number);
  return `${d} ${TH_MONTH[m - 1]} ${y + 543}`;
}
const n = (v) => Number(v ?? 0).toLocaleString("th-TH");

/** ชื่อสินค้าที่ขึ้นต้นด้วยรหัสตัวเอง ("00449 น๊อตยึด…") — ตัดรหัสซ้ำออก **ตอนแสดงเท่านั้น**
 *  🚫 ห้ามไปแก้ชื่อในฐาน — ในบริบทอื่นชื่อแบบนั้นอาจถูกอยู่แล้ว (CEO กำกับ 12 ก.ย. 2569)
 *  ⚠️ ตัดเฉพาะเมื่อขึ้นต้นด้วยรหัส **ตัวเดียวกัน** เท่านั้น ห้ามตัดเลขนำหน้าพล่อย ๆ
 *     (ชื่อจริงหลายตัวขึ้นต้นด้วยเลขที่เป็นส่วนของชื่อ เช่น "3/8 โซ่…") */
export function cleanName(sku, name) {
  const s = String(name ?? "").trim();
  const code = String(sku ?? "").trim();
  if (!s || !code) return s;
  const re = new RegExp(`^${code.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s:\\-–]+`);
  return s.replace(re, "").trim() || s;
}

/** เรียงลำดับรหัสที่ควรให้คนไปนับก่อน
 *  🔑 **เกณฑ์ต้องเขียนลงในข้อความด้วย** ไม่ใช่เรียงเงียบ ๆ — คนอ่านต้องรู้ว่าทำไมสามตัวนี้ถูกเลือก
 *     หลัก: ค้างหลายใบที่สุด (ลูกค้ารออยู่หลายคน = เสียหายมากกว่า)
 *     ตัวตัดสินเสมอ: ใบเก่าสุดของรหัสนั้น
 *  ⚠️ CEO ให้เกณฑ์มาสองแบบในคำสั่งเดียว ("เรียงจากค้างหลายใบที่สุด" กับ "เอาอายุมากสุดก่อน")
 *     ⇒ ใช้แบบแรกเป็นหลัก แบบที่สองเป็นตัวตัดสินเสมอ **แล้วเขียนเกณฑ์ไว้บนข้อความให้เห็น**
 *     ถ้าท่านประธานอยากให้อายุมาก่อน สลับสองบรรทัดนี้ได้จุดเดียว */
export function rankForReport(groups) {
  return [...groups].sort((a, b) => (b.orders?.length ?? 0) - (a.orders?.length ?? 0) || b.maxAge - a.maxAge);
}

/** ประกอบข้อความรายงาน — คืน { text, state, counts }
 *  state: 'error' ดึงไม่สำเร็จ · 'empty' ไม่มีใบค้าง · 'ok' มีใบค้าง (อาจอ่านได้บางส่วน)
 *  ⚠️ ฟังก์ชันนี้ **ไม่ยิงอะไรออกไป** — ผู้เรียกเป็นคนตัดสินใจส่ง (แยกคิดกับส่งออกจากกัน) */
export function buildShelfReport({
  today, scope = {}, groups = [], stuckOrders = 0,
  rowsRead = null, rowsTotal = null, itemsFailed = 0, ordersBeyondCap = 0,
  tooOld = 0, tooNew = 0, byStore = null, byChannel = null,
  olderTail = null, olderTailFrom = null, tailByChannel = null,
  yearWaiting = null, yearDone = null, yearFrom = null,
  error = null, pick = PICK, statusUnverified = true,
}) {
  const head = `📦 <b>ใบที่ยังไม่ได้ส่ง</b> — เช้า ${thaiDate(today)}`;

  /* ① ดึงไม่สำเร็จ = บอกตรง ๆ **ห้ามมีตัวเลขสักตัวในข้อความ**
     ตัวเลขในข้อความที่อ่านไม่ครบ จะถูกเอาไปสั่งงานต่อ แล้วไม่มีใครรู้ว่ามันไม่ครบ */
  if (error) {
    return {
      state: "error",
      counts: { orders: null, skus: null },
      text: [
        head,
        `🔴 <b>ดึงข้อมูลไม่สำเร็จ — วันนี้ยังสรุปไม่ได้</b>`,
        `เหตุผล: ${error}`,
        `⚠️ <b>ไม่ได้แปลว่าไม่มีใบค้างส่ง</b> แปลว่ายังอ่านไม่ได้เท่านั้น — อย่าสั่งนับของจากรายงานใบนี้`,
      ].join("\n"),
    };
  }

  /* ① ขอบเขตต้องครบทุกมิติที่ทำให้เลขเปลี่ยนความหมาย: ร้าน · ช่วงวัน · เกณฑ์อายุ · อ่านได้กี่ใบ
     ขาดข้อใดข้อหนึ่ง ท่านประธานจะสั่งคนไปนับของในขอบเขตที่ไม่ตรงกับเลขที่อ่าน */
  /* 🔴 **ห้ามเขียนชื่อร้านที่ไม่ได้กรองจริง** (แก้ 12 ก.ย. 2569 — CEO จับได้)
     ของเดิมเขียน "ร้าน z1" ตายตัว ทั้งที่คำขอไม่ได้ส่ง store= ไปเลย ⇒ ข้อมูลเป็น **ทุกร้าน**
     ⇒ เลขของผม 909 ใบ กับของ CEO 584 ใบ (z1) ต่างกันเพราะขอบเขตคนละอย่าง ไม่ใช่ข้อมูลผิด
     ⇒ ป้ายต้องบอกตามที่ยิงจริง และแยกให้เห็นว่าแต่ละร้านมีกี่ใบ */
  const storeLine = byStore
    ? Object.entries(byStore).map(([s, c]) => `${s} ${n(c)} ใบ`).join(" · ")
    : null;
  const scopeLine = [
    `ขอบเขต: ${storeLine ? `ทุกร้าน (${storeLine})` : "ทุกร้าน"}`,
    `ใบวันที่ ${thaiDate(scope.from)} – ${thaiDate(scope.to)}${scope.days ? ` (${scope.days} วัน)` : ""}`,
    scope.minAge ? `เฉพาะใบที่ค้างเกิน ${scope.minAge} วัน` : null,
    rowsRead !== null && rowsTotal !== null ? `อ่านใบในช่วงนี้ ${n(rowsRead)} จาก ${n(rowsTotal)} ใบ` : null,
  ].filter(Boolean).join(" · ");

  /* ② ไม่มีใบค้าง = **ต้องส่ง** ห้ามเงียบ (เงียบแยกไม่ออกจาก "งานตามเวลาไม่เคยรัน") */
  if (!groups.length) {
    return {
      state: "empty",
      counts: { orders: stuckOrders, skus: 0 },
      text: [
        head,
        `✅ <b>ไม่มีใบค้างส่งในช่วงที่ตรวจ</b>`,
        scopeLine,
        /* ⚠️ "ไม่มีใบค้าง" จะกลายเป็นคำโกหกถ้าเงียบเรื่องของที่ถูกกรองออก */
        tooNew > 0 ? `(มี ${n(tooNew)} ใบเพิ่งค้างไม่ถึง ${scope.minAge ?? 2} วัน — ยังไม่นับ)` : null,
        (olderTail ?? 0) > 0 || tooOld > 0
          ? `📌 แต่มีใบเก่ากว่าช่วงตรวจ ${n((olderTail ?? 0) + tooOld)} ใบ — ยังยืนยันไม่ได้ว่าค้างจริงหรือสถานะไม่ขยับ`
          : null,
        statusUnverified ? `หมายเหตุ: ดูจากสถานะที่ ZORT บอก — ยังไม่ได้ยืนยันกับแพลตฟอร์มโดยตรง` : null,
      ].filter(Boolean).join("\n"),
    };
  }

  const ranked = rankForReport(groups);
  const top = ranked.slice(0, Math.max(1, pick));
  const lines = [
    head,
    `ค้างอยู่ <b>${n(stuckOrders)} ใบ</b> · <b>${n(groups.length)} รหัสสินค้า</b>`,
    scopeLine,
  ];

  /* ③ อ่านได้บางส่วน — ต้องอยู่ **ก่อน** รายการ ไม่ใช่เชิงอรรถท้ายข้อความ
     (กติกา: ป้ายขอบเขตมาถึงตาก่อนตัวเลข) */
  const gaps = [];
  if (rowsRead !== null && rowsTotal !== null && rowsRead < rowsTotal) gaps.push(`อ่านใบไม่ครบ (ขาด ${n(rowsTotal - rowsRead)} ใบ)`);
  if (itemsFailed > 0) gaps.push(`อ่านรายการสินค้าไม่ได้ ${n(itemsFailed)} ใบ`);
  if (ordersBeyondCap > 0) gaps.push(`ยังไม่ได้เปิดดูรายการสินค้าอีก ${n(ordersBeyondCap)} ใบ (เกินโควตาเวลาต่อรอบ)`);
  if (gaps.length) {
    lines.push(`⚠️ <b>ตัวเลขนี้ยังไม่ครบ</b> — ${gaps.join(" · ")} ⇒ ของจริงอาจมากกว่านี้`);
  }

  /* ② **ตัวกรองที่มองไม่เห็น คือตัวกรองที่ไม่มีใครตั้งคำถาม** (CEO 12 ก.ย. 2569)
     ต้องบอกว่าเกณฑ์ "ค้างเกิน 2 วัน" กรองออกไปกี่ใบ ไม่งั้นคนอ่านคิดว่า 65 คือทั้งหมด */
  if (tooNew > 0) {
    lines.push(`อีก ${n(tooNew)} ใบเพิ่งค้างไม่ถึง ${scope.minAge ?? 2} วัน — ยังไม่นับในรายงานนี้`);
  }

  if (byChannel && Object.keys(byChannel).length) {
    const ch = Object.entries(byChannel).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} ${n(v)}`).join(" · ");
    lines.push(`ช่องทางที่พบใบค้าง: ${ch}`);
  }
  if (statusUnverified) {
    lines.push(`หมายเหตุ: สถานะ "รอจัดส่ง" มาจากที่ ZORT บอก — <b>ยังไม่ได้ยืนยันกับแพลตฟอร์มโดยตรง</b>`);
    lines.push(`ใบจากเว็บ/หน้าร้าน (POS) ไม่มีสถานะจากแพลตฟอร์ม จึงไม่เคยอยู่ในกองนี้`);
  }

  lines.push("");
  lines.push(`<b>รหัสที่ควรให้พนักงานนับของก่อน ${top.length} รหัส</b> (เกณฑ์: ค้างหลายใบที่สุด → ใบเก่าสุด)`);
  /* 🔴 **ถ้าเปิดดูใบไม่ครบ อันดับนี้เชื่อทั้งหมดไม่ได้ — ต้องเขียนกำกับ ห้ามปล่อยให้ดูเหมือนอันดับจริง**
     ของจริง 12 ก.ย. 2569: อ่าน 25 จาก 65 ใบ ⇒ อันดับออกมาคนละชุดกับตอนอ่านครบ
     และรหัสที่ค้างมากที่สุดหลุดหายไปเลย ⇒ คนอ่านจะสั่งนับผิดตัวโดยไม่มีอะไรฟ้อง */
  if (ordersBeyondCap > 0) {
    lines.push(`⚠️ อันดับนี้คิดจากใบที่เปิดดูทันเท่านั้น (${n(Math.max(0, stuckOrders - ordersBeyondCap))} จาก ${n(stuckOrders)} ใบ) — <b>ยังไม่ใช่อันดับของทั้งกอง</b>`);
  }
  top.forEach((g, i) => {
    const nm = cleanName(g.sku, g.name);
    lines.push(`${i + 1}. <b>${g.sku}</b>${nm ? ` ${nm}` : ""} — ค้าง ${n(g.orders?.length ?? 0)} ใบ · ใบเก่าสุด ${n(g.maxAge)} วัน`);
  });

  if (ranked.length > top.length) {
    lines.push(`อีก ${n(ranked.length - top.length)} รหัสก็ค้างอยู่เหมือนกัน — คัดมา ${top.length} เพื่อให้สั่งนับได้จริงในวันเดียว`);
  }

  /* ① **ใบที่เก่ากว่าช่วงตรวจ ห้ามทิ้ง** — CEO ตีกลับข้อนี้แรงที่สุด
     ของเดิมผมตัดออกแล้วเขียนว่า "ไม่ใช่งานแพ็กวันนี้" ซึ่งเป็นการ **ตัดสินแทนท่านประธาน**
     และซ่อนหลักฐานที่แรงที่สุด (ค้าง 3 วันอาจแพ็กไม่ทัน · ค้าง 40 วันคือไม่มีของแน่นอน)
     ⚠️ แต่พอยิงนับจริงกลับได้ **หลายร้อยใบ** ⇒ ตัวเลขนี้ใหญ่เกินกว่าจะเป็นของค้างจริงทั้งหมด
        ⇒ ต้องโชว์ตัวเลข **พร้อมบอกว่ายังไม่ยืนยัน** ห้ามเงียบ และห้ามสรุปแทนคนอ่าน */
  /* 🔴 **ย้ายมาไว้ท้ายข้อความ (12 ก.ย. 2569)** — ของเดิมอยู่บน แล้วดัน "รหัสที่ต้องไปนับ"
     ลงไปบรรทัดที่ 12 ⇒ คนอ่านบนมือถือเห็นคำอธิบายก่อนเห็นสิ่งที่ต้องลงมือ
     กติกาที่ CEO ตั้งเอง: **ป้ายขอบเขต**ขึ้นก่อนตัวเลข · **รายละเอียดวิธีคิด**ไว้ท้ายได้
     ⇒ บรรทัดขอบเขต/ตัวกรอง/ช่องทาง ยังอยู่บน (มันกำกับความหมายของ 65 ใบ)
        ส่วนบล็อกนี้เป็นหลักฐานประกอบ ⇒ ลงท้าย แต่ **ห้ามตัดออก** */
  const tailLines = [];
  if (tooOld > 0 || (olderTail ?? 0) > 0) {
    const parts = [];
    if (tooOld > 0) parts.push(`${n(tooOld)} ใบในช่วงที่อ่าน`);
    if ((olderTail ?? 0) > 0) parts.push(`${n(olderTail)} ใบย้อนไปถึง ${thaiDate(olderTailFrom)}`);
    tailLines.push(`📌 <b>ใบเก่ากว่าช่วงตรวจ (ค้างเกิน ${scope.days ?? 30} วัน): ${parts.join(" + ")}</b>`);
    tailLines.push(`   ใบยิ่งเก่ายิ่งเป็นสัญญาณว่าของหมดจริง — แต่กลุ่มนี้ <b>ยังยืนยันไม่ได้</b>`);
    /* 🔑 เหตุผลที่เทียบกันในบ้านเราเอง — ไม่ต้องอ้างพฤติกรรมของแพลตฟอร์มที่ยังพิสูจน์ไม่ได้ */
    /* แยกหางตามช่องทาง — ท่านประธานแจ้งว่าร้าน ZAMA ปิดไปแล้ว ⇒ ใบของร้านที่ปิด
       **จะไม่มีวันถูกส่ง** และมันไปพองอยู่ในกองนี้ ⇒ ต้องแยกให้เห็นว่าเป็นของช่องทางไหน
       🚫 **ห้ามกรองทิ้งเงียบ ๆ** — ถ้าวันหนึ่งมีใบของร้านที่ปิดแล้วโผล่ใหม่ แปลว่ามีอะไรผิดปกติหนัก
          กรองทิ้งไปแล้วจะไม่มีใครเห็น (กฎเดิม: แถวที่กันออกต้องโชว์) */
    if (tailByChannel?.parts && Object.keys(tailByChannel.parts).length) {
      const ch = Object.entries(tailByChannel.parts).sort((a, b) => b[1] - a[1])
        .map(([k, v]) => `${k} ${n(v)}`).join(" · ");
      tailLines.push(`   แยกตามช่องทาง: ${ch}`);
      if (tailByChannel.complete === false) {
        tailLines.push(`   ⚠️ ผลบวกรายช่องทาง (${n(tailByChannel.sum)}) ไม่เท่ายอดหาง — ยังมีช่องทางที่ยังไม่ได้ถาม`);
      }
    }
    if (yearWaiting !== null && yearDone !== null) {
      tailLines.push(`   ย้อน 1 ปี (ตั้งแต่ ${thaiDate(yearFrom)}): รอจัดส่ง <b>${n(yearWaiting)}</b> ใบ · สำเร็จ <b>${n(yearDone)}</b> ใบ`);
      if (yearWaiting > yearDone) {
        tailLines.push(`   ⇒ <b>กองรอจัดส่งมากกว่ากองสำเร็จทั้งปี</b> ซึ่งเป็นไปไม่ได้ถ้าร้านส่งของทุกวัน`);
        tailLines.push(`   ⇒ สถานะนี้น่าจะไม่ขยับหลังส่ง ⇒ <b>ยังไม่เอาใบกลุ่มเก่ามาจัดอันดับ</b>`);
      }
    } else {
      tailLines.push(`   ว่าค้างจริงทั้งหมด หรือเป็นสถานะที่ไม่ขยับหลังส่ง ⇒ ยังไม่เอามาจัดอันดับ`);
    }
  }


  if (tailLines.length) { lines.push(""); lines.push(...tailLines); }

  /* ② ย้ำท้ายข้อความด้วย เพราะคนอ่านบนมือถืออาจอ่านแค่หัวกับท้าย */
  lines.push("");
  lines.push(`⚠️ <b>นี่ไม่ใช่การยืนยันว่าของหมด</b> — ที่เห็นคือ "ยังไม่ได้ส่ง" เท่านั้น ต้องให้คนนับของจริงเป็นคนตอบ`);

  return { state: "ok", counts: { orders: stuckOrders, skus: groups.length }, text: lines.join("\n") };
}
